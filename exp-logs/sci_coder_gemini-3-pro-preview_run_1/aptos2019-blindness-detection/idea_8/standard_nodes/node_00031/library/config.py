import os
import torch


class Config:
    """
    Configuration class for Diabetic Retinopathy Detection.
    Centralizes all hyperparameters, paths, and system settings.
    """

    # =======================
    # General Configuration
    # =======================
    seed = 42
    debug = False  # Set to True to run on a small subset for debugging
    exp_name = "idea_8"
    working_dir = os.path.join("./working", exp_name)

    # =======================
    # Data Paths
    # =======================
    input_root = "./input"
    metadata_dir = "./metadata"

    # Metadata files generated by the provided script
    train_metadata_path = os.path.join(metadata_dir, "train.csv")
    val_metadata_path = os.path.join(metadata_dir, "val.csv")
    test_metadata_path = os.path.join(metadata_dir, "test.csv")

    # =======================
    # Dataset Configuration
    # =======================
    image_size = 512
    num_classes = 5  # 0, 1, 2, 3, 4
    # For Ordinal Regression, we predict K-1 binary outcomes (P(y>=1), P(y>=2)...)
    num_ordinal_heads = 4

    # Preprocessing & Augmentation
    use_graham_norm = True  # Apply Graham's Color Normalization
    aug_hflip = True
    aug_vflip = True
    aug_rotate90 = True
    aug_color_jitter = False  # Disabled to preserve color-specific lesions

    # Dataloader
    num_workers = 8
    pin_memory = True

    # =======================
    # Model Configuration
    # =======================
    backbone = "convnext_small"
    pretrained = True
    in_chans = 3

    # Architecture specifics
    use_gem_pooling = True  # Generalized Mean Pooling
    use_multi_sample_dropout = True
    dropout_rate = 0.2  # Dropout for the linear head
    backbone_drop_path_rate = 0.1  # Stochastic depth for ConvNeXt

    # =======================
    # Training Configuration
    # =======================
    epochs = 15
    train_batch_size = 24  # Optimized for A100 40GB with 512x512 ConvNeXt
    val_batch_size = 32

    # Optimizer (AdamW)
    learning_rate = 1e-4
    weight_decay = 0.05
    max_grad_norm = 10.0

    # Scheduler (Cosine Annealing)
    scheduler_type = "cosine"
    min_lr = 1e-6
    warmup_epochs = 1

    # Loss
    loss_type = "bce_with_logits"  # Summed across ordinal units

    # Advanced Training Dynamics
    use_ema = True  # Model Exponential Moving Average
    ema_decay = 0.999

    # =======================
    # Inference Configuration
    # =======================
    tta_steps = 4  # 4-view TTA (Original, HFlip, VFlip, Rotate180)

    # =======================
    # Hardware
    # =======================
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    @classmethod
    def setup(cls):
        """
        Initialize the working directory and perform any necessary setup.
        """
        os.makedirs(cls.working_dir, exist_ok=True)


# Automatically setup directories on import
Config.setup()
