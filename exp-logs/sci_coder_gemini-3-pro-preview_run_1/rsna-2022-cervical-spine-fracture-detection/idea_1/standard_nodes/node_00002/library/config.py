import os
import torch


class Config:
    """
    Configuration class for the Fracture Detection Task.
    Holds all hyperparameters, file paths, and constants.
    """

    # ---------------------------------------------------------
    # General Configuration
    # ---------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to use a subset of data for debugging
    DEBUG_DATASET_SIZE = 100  # Number of samples if DEBUG is True

    # ---------------------------------------------------------
    # File Paths
    # ---------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_1"
    SUBMISSION_DIR = "./submission"

    # Metadata files generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Raw Data
    TRAIN_IMAGES_DIR = os.path.join(INPUT_DIR, "train_images")
    TEST_IMAGES_DIR = os.path.join(INPUT_DIR, "test_images")
    BBOX_PATH = os.path.join(INPUT_DIR, "train_bounding_boxes.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ---------------------------------------------------------
    # Image Preprocessing (Bone Windowing)
    # ---------------------------------------------------------
    # Standard bone window settings
    WINDOW_CENTER = 400
    WINDOW_WIDTH = 1800

    # Input dimensions
    IMG_SIZE = (256, 256)
    IN_CHANNELS = 3  # 2.5D: Slice i-1, Slice i, Slice i+1

    # ---------------------------------------------------------
    # Model Architecture
    # ---------------------------------------------------------
    BACKBONE = "resnet18"  # Lightweight backbone for slice classification
    PRETRAINED = True

    # Targets
    TARGET_COLS = ["C1", "C2", "C3", "C4", "C5", "C6", "C7", "patient_overall"]
    NUM_CLASSES = len(TARGET_COLS)

    # ---------------------------------------------------------
    # Training Hyperparameters
    # ---------------------------------------------------------
    BATCH_SIZE = 64
    EPOCHS = 10
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2
    NUM_WORKERS = 4

    # Sampling strategy for training (balance positive/negative slices)
    POSITIVE_RATIO = 0.5

    # ---------------------------------------------------------
    # Inference
    # ---------------------------------------------------------
    # Stride for inference to speed up processing (process every Nth slice)
    INFERENCE_STRIDE = 2

    # ---------------------------------------------------------
    # Hardware
    # ---------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Creates necessary output directories.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories on import
Config.setup()
