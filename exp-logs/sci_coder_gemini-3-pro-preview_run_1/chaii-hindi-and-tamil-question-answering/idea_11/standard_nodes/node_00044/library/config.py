import os
import torch


class Config:
    """
    Configuration class for the Hindi/Tamil Question Answering Task.
    Implements settings for Adversarial Multi-Task XLM-R Large Ensemble.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    # Seeds for the ensemble members. We train one model per seed on the full dataset.
    SEEDS = [42, 43, 44]

    # Set to True to run on a small subset of data for debugging purposes
    DEBUG = False

    # Hardware settings
    NUM_WORKERS = 4
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # =========================================================================
    # File Paths
    # =========================================================================
    # Metadata paths (generated by metadata script)
    TRAIN_META = "./metadata/train.csv"
    VAL_META = "./metadata/val.csv"
    TEST_META = "./metadata/test.csv"

    # Raw input paths
    SAMPLE_SUBMISSION = "./input/sample_submission.csv"

    # Working Directories
    # Main working directory for this specific idea/experiment
    WORKING_DIR = "./working/idea_11"

    # Directory to store cached processed features (parquet/npy)
    # Used to ensure deterministic data processing and speed up restarts
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")

    # Directory to save model checkpoints
    OUTPUT_DIR = os.path.join(WORKING_DIR, "output")

    # Directory for final submission file
    SUBMISSION_DIR = "./submission"
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure all necessary directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # =========================================================================
    # Model Architecture
    # =========================================================================
    # Backbone model
    MODEL_NAME = "xlm-roberta-large"

    # =========================================================================
    # Data Processing & Sampling
    # =========================================================================
    # Tokenizer windowing parameters
    MAX_LENGTH = 384
    DOC_STRIDE = 128

    # Negative Sampling Strategy
    # We retain 100% of positive windows and downsample negatives to maintain this ratio.
    # Ratio of Negative Windows to Positive Windows (e.g., 2.0 means 2 negatives for every 1 positive)
    NEGATIVE_RATIO = 2.0

    # Training Data Strategy
    # If True, concatenates train.csv and val.csv for training (no validation split used during training)
    # This is crucial for low-resource tasks to maximize data usage.
    MERGE_TRAIN_VAL = True

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    EPOCHS = 8
    BATCH_SIZE = 4

    # Optimization
    # Base learning rate for the task heads and top layers
    LEARNING_RATE = 1.5e-5

    # Weight decay applied to ALL parameters (including bias/LayerNorm)
    WEIGHT_DECAY = 0.01

    # Warmup steps ratio
    WARMUP_RATIO = 0.1

    # Gradient Clipping
    MAX_GRAD_NORM = 1.0

    # Layer-Wise Learning Rate Decay (LLRD)
    # The learning rate is decayed by this factor for each layer moving downwards from the head.
    # LR_layer_i = LR_base * (LLRD_DECAY ^ (num_layers - i))
    LLRD_DECAY = 0.9

    # Adversarial Training (Fast Gradient Method - FGM)
    # Disabled to allow for more training epochs within compute budget (Cite solution_lesson_node_00034)
    USE_FGM = False
    ADV_EPSILON = 1.0

    # Loss Function Weighting
    # The model predicts span (start/end) and relevance (binary classification).
    # Total Loss = SpanLoss + (RELEVANCE_LOSS_WEIGHT * RelevanceLoss)
    RELEVANCE_LOSS_WEIGHT = 0.5

    # =========================================================================
    # Inference
    # =========================================================================
    INFERENCE_BATCH_SIZE = 4
