def seed_everything(seed=42):
    """
    Sets the random seed for reproducibility across Python, NumPy, and PyTorch.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def jaccard(str1, str2):
    """
    Calculates the Jaccard similarity score between two strings.
    Defined by the competition metric.
    """
    a = set(str1.lower().split())
    b = set(str2.lower().split())
    c = a.intersection(b)
    if (len(a) + len(b) - len(c)) == 0:
        return 0.0
    return float(len(c)) / (len(a) + len(b) - len(c))


def find_best_substring(context, generated_text):
    """
    Finds the substring in the context that maximizes the Jaccard score
    with the generated text. This ensures the prediction is a valid
    quoted string from the context.

    Args:
        context (str): The original context text.
        generated_text (str): The answer generated by the model.

    Returns:
        str: The best matching substring from the context.
    """
    if not generated_text or not context:
        return ""

    # If exact match exists, return it immediately to save computation
    if generated_text in context:
        return generated_text

    # Tokenize context with character offsets to reconstruct substrings
    # Using regex to mimic .split() behavior (split by whitespace) but keep indices
    context_tokens = []
    for match in re.finditer(r"\S+", context):
        context_tokens.append(
            {"text": match.group(), "start": match.start(), "end": match.end()}
        )

    if not context_tokens:
        return ""

    # Tokenize generated text for comparison
    gen_tokens = set(generated_text.lower().split())
    if not gen_tokens:
        return ""

    n_tokens = len(context_tokens)
    gen_len = len(gen_tokens)

    # Heuristic: Limit search window size to optimize performance.
    # We search for spans with length roughly proportional to the generated answer.
    # We allow a multiplier and a constant buffer to account for tokenization differences.
    max_window_size = min(n_tokens, gen_len * 3 + 5)

    best_score = -1.0
    best_span = ""

    # Pre-calculate lower case text for context tokens to avoid repeated ops in loop
    context_tokens_lower = [t["text"].lower() for t in context_tokens]

    # Sliding window over token indices
    for length in range(1, max_window_size + 1):
        for i in range(n_tokens - length + 1):
            # Define the window range
            j = i + length

            # Get the set of words in this window
            window_words = set(context_tokens_lower[i:j])

            # Calculate Jaccard
            intersection = len(gen_tokens.intersection(window_words))
            union = len(gen_tokens) + len(window_words) - intersection

            if union > 0:
                score = intersection / union
            else:
                score = 0.0

            # Update best found
            if score > best_score:
                best_score = score
                # Reconstruct the exact substring from original context using offsets
                start_char = context_tokens[i]["start"]
                end_char = context_tokens[j - 1]["end"]
                best_span = context[start_char:end_char]

                # Optimization: If perfect match found, return immediately
                if best_score >= 0.999:
                    return best_span

    # If no valid span is found (unlikely), return the generated text as fallback
    if best_span == "":
        return generated_text

    return best_span
