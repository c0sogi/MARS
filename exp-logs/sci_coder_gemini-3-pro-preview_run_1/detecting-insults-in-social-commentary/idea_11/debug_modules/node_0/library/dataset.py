import pandas as pd
import torch
from torch.utils.data import Dataset
from sklearn.model_selection import StratifiedKFold
from library.config import Config
from library.features import get_fold_features


class InsultDataset(Dataset):
    """
    PyTorch Dataset for Insult Detection.
    Combines tokenized text features with dense SVD structural features.
    """

    def __init__(self, texts, svd_features, tokenizer, labels=None):
        """
        Args:
            texts (list): List of text comments.
            svd_features (np.ndarray): Pre-computed SVD features aligned with texts.
            tokenizer: Hugging Face tokenizer instance.
            labels (list/np.ndarray, optional): Target labels. Defaults to None.
        """
        self.texts = texts
        self.svd_features = svd_features
        self.tokenizer = tokenizer
        self.labels = labels
        self.max_len = Config.max_len

    def __len__(self):
        return len(self.texts)

    def __getitem__(self, idx):
        text = str(self.texts[idx])

        # Tokenize text
        inputs = self.tokenizer.encode_plus(
            text,
            None,
            add_special_tokens=True,
            max_length=self.max_len,
            padding="max_length",
            truncation=True,
            return_token_type_ids=True,
        )

        input_ids = inputs["input_ids"]
        attention_mask = inputs["attention_mask"]

        # Retrieve SVD features
        svd_feat = self.svd_features[idx]

        # Construct output dictionary
        item = {
            "input_ids": torch.tensor(input_ids, dtype=torch.long),
            "attention_mask": torch.tensor(attention_mask, dtype=torch.long),
            "svd_features": torch.tensor(svd_feat, dtype=torch.float),
        }

        # Include token_type_ids if generated by tokenizer (e.g., DeBERTa/BERT)
        if "token_type_ids" in inputs:
            item["token_type_ids"] = torch.tensor(
                inputs["token_type_ids"], dtype=torch.long
            )

        # Include target label if available
        if self.labels is not None:
            item["target"] = torch.tensor(self.labels[idx], dtype=torch.float)

        return item


def prepare_fold_data(fold, tokenizer, load_cached_data=True):
    """
    Prepares the datasets for a specific fold of Cross-Validation.

    Args:
        fold (int): The current fold index (0 to n_folds-1).
        tokenizer: The tokenizer instance to be used in the Dataset.
        load_cached_data (bool): Whether to load SVD features from cache.

    Returns:
        tuple: (train_dataset, val_dataset, test_dataset)
    """
    # 1. Load Metadata
    df_train = pd.read_csv(Config.train_path)
    df_test = pd.read_csv(Config.test_path)

    # 2. Handle Debug Mode
    if Config.debug:
        df_train = df_train.sample(
            n=min(len(df_train), Config.debug_sample_size), random_state=Config.seed
        ).reset_index(drop=True)

        df_test = df_test.sample(
            n=min(len(df_test), Config.debug_sample_size), random_state=Config.seed
        ).reset_index(drop=True)

    # 3. Perform Stratified K-Fold Split
    # We split the training metadata into Train/Val for this specific fold
    skf = StratifiedKFold(
        n_splits=Config.n_folds, shuffle=True, random_state=Config.seed
    )

    X = df_train.index
    y = df_train["Insult"].values

    # Get indices for the requested fold
    splits = list(skf.split(X, y))
    if fold >= len(splits):
        raise ValueError(f"Fold {fold} out of range for {Config.n_folds} splits.")

    train_idx, val_idx = splits[fold]

    # Create Dataframes for this fold
    train_fold = df_train.iloc[train_idx].reset_index(drop=True)
    val_fold = df_train.iloc[val_idx].reset_index(drop=True)

    # 4. Extract Raw Texts and Labels
    # Fill NaNs with empty string to prevent tokenization errors
    train_texts = train_fold["Comment"].fillna("").tolist()
    val_texts = val_fold["Comment"].fillna("").tolist()
    test_texts = df_test["Comment"].fillna("").tolist()

    train_labels = train_fold["Insult"].values
    val_labels = val_fold["Insult"].values

    # 5. Generate or Load SVD Features
    # This function handles the fitting on train_texts and transforming others
    train_svd, val_svd, test_svd = get_fold_features(
        fold_idx=fold,
        train_texts=train_texts,
        val_texts=val_texts,
        test_texts=test_texts,
        load_cached_data=load_cached_data,
    )

    # 6. Instantiate Datasets
    train_dataset = InsultDataset(train_texts, train_svd, tokenizer, train_labels)
    val_dataset = InsultDataset(val_texts, val_svd, tokenizer, val_labels)
    test_dataset = InsultDataset(test_texts, test_svd, tokenizer, labels=None)

    return train_dataset, val_dataset, test_dataset
