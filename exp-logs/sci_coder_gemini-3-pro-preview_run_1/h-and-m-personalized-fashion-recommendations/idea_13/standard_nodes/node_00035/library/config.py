import os
import numpy as np


class Config:
    """
    Configuration for Multi-Scale Stratified Graph Cascade (MSG-Cascade).
    Defines hyperparameters, file paths, and constants for the recommendation system.
    """

    # --------------------------------------------------------------------------
    # Global Settings
    # --------------------------------------------------------------------------
    SEED = 42
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 50000  # Number of users to sample when DEBUG is True

    # --------------------------------------------------------------------------
    # Directory Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_13"
    SUBMISSION_DIR = "./submission"

    # --------------------------------------------------------------------------
    # Input File Paths
    # --------------------------------------------------------------------------
    # Metadata splits (Generated by previous steps)
    TRAIN_DATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_DATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_DATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Raw input files
    ARTICLES_PATH = os.path.join(INPUT_DIR, "articles.csv")
    CUSTOMERS_PATH = os.path.join(INPUT_DIR, "customers.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # --------------------------------------------------------------------------
    # Output File Paths
    # --------------------------------------------------------------------------
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache paths for intermediate artifacts to support deterministic caching
    CACHE_PROCESSED_DATA = os.path.join(WORKING_DIR, "processed_data.parquet")
    CACHE_MATRICES = os.path.join(WORKING_DIR, "similarity_matrices.npz")
    CACHE_MAPPINGS = os.path.join(WORKING_DIR, "id_mappings.npz")
    CACHE_USER_HISTORY = os.path.join(WORKING_DIR, "user_history.parquet")

    # --------------------------------------------------------------------------
    # Model Hyperparameters
    # --------------------------------------------------------------------------
    # Temporal Windowing
    # We use a 24-week history window for training the graphs
    HISTORY_WEEKS = 24

    # Decay Parameters (Half-life in days)
    # Fast Graph: Aggressive decay to capture high-velocity trends (e.g., 1 week)
    HALF_LIFE_FAST = 7.0
    # Slow Graph: Gentle decay to capture stable style affinities (e.g., 8 weeks)
    HALF_LIFE_SLOW = 60.0

    # Stratification Score Offsets
    # Enforces strict priority: Habit > Fast Trends > Stable Style > Global Fallback
    # Scores will be normalized to [0, 1000) before adding these offsets.
    SCORE_OFFSET_HABIT = 3000.0
    SCORE_OFFSET_FAST = 2000.0
    SCORE_OFFSET_SLOW = 1000.0
    SCORE_OFFSET_TREND = 0.0

    # Graph Construction Parameters
    TOP_K_NEIGHBORS = 100  # Number of neighbors to keep in sparse similarity matrices
    TOP_K_PREDICT = 12  # Number of items to predict per user

    # Active Inventory Filter
    # Only recommend items sold within the last N days (avoids out-of-stock/obsolete items)
    ACTIVE_INVENTORY_DAYS = 7

    def __init__(self):
        """
        Initialize configuration and ensure necessary directories exist.
        """
        os.makedirs(self.WORKING_DIR, exist_ok=True)
        os.makedirs(self.SUBMISSION_DIR, exist_ok=True)

    @staticmethod
    def get_decay_rate(half_life_days):
        """
        Calculate the exponential decay rate (lambda) from half-life.
        Formula: lambda = ln(2) / half_life
        """
        if half_life_days <= 0:
            return 0.0
        return np.log(2) / half_life_days
