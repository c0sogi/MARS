import os
import torch


class Config:
    """
    Configuration class for the Sentiment Extraction task.
    Centralizes all file paths, model parameters, and training hyperparameters.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to use a small subset of data for debugging
    NUM_WORKERS = 4
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # =========================================================================
    # File Paths
    # =========================================================================
    # Input Metadata (generated by previous steps)
    METADATA_DIR = "./metadata"
    TRAIN_FILE = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_FILE = os.path.join(METADATA_DIR, "validation_metadata.csv")
    TEST_FILE = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Working Directory for Artifacts and Caching
    # Using 'idea_10' as specified to isolate this iteration's outputs
    ARTIFACT_DIR = "./working/idea_10"
    os.makedirs(ARTIFACT_DIR, exist_ok=True)

    # Model Checkpoint Output
    BEST_MODEL_PATH = os.path.join(ARTIFACT_DIR, "best_model.bin")

    # Submission Output
    SUBMISSION_DIR = "./submission"
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Model Architecture
    # =========================================================================
    MODEL_PATH = "microsoft/deberta-v3-base"
    TOKENIZER_PATH = "microsoft/deberta-v3-base"
    MAX_LEN = 128  # Sufficient for max char length of ~141
    HIDDEN_SIZE = 768  # Hidden size for DeBERTa-v3-base

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    TRAIN_BATCH_SIZE = 32
    VALID_BATCH_SIZE = 32
    EPOCHS = 5
    LEARNING_RATE = 2e-5
    WEIGHT_DECAY = 0.01
    MAX_GRAD_NORM = 1.0

    # Scheduler Settings
    WARMUP_RATIO = 0.1

    # =========================================================================
    # Strategy Specific Parameters
    # =========================================================================
    # Target Processing: Sigma for Gaussian smoothing of start/end targets
    TARGET_SMOOTHING = 1.0

    # Data Filtering: Whether to include 'neutral' sentiment tweets in training
    # Strategy dictates excluding them as they are trivial identity mappings
    TRAIN_ON_NEUTRAL = False

    # Optimization: Early stopping patience to prevent overfitting
    EARLY_STOPPING_PATIENCE = 3
