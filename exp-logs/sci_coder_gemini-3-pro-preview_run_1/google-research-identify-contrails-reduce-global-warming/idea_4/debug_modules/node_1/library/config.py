import os


class Config:
    """
    Configuration for HRNet-Ash Semantic Segmenter (Idea 4).
    Defines file paths, normalization constants, and training hyperparameters.
    """

    # -------------------------------------------------------------------------
    # General Setup
    # -------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4
    DEVICE = "cuda"

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata indices generated by the helper script
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VALIDATION_CSV = os.path.join(METADATA_DIR, "validation.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Working Directory for this specific idea
    WORKING_DIR = "./working/idea_4"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    PREDICTION_DIR = os.path.join(WORKING_DIR, "predictions")

    # Final Submission Path
    SUBMISSION_PATH = "./submission/submission.csv"

    # Ensure output directories exist
    for d in [
        WORKING_DIR,
        CACHE_DIR,
        CHECKPOINT_DIR,
        PREDICTION_DIR,
        os.path.dirname(SUBMISSION_PATH),
    ]:
        os.makedirs(d, exist_ok=True)

    # -------------------------------------------------------------------------
    # Data Preprocessing (Ash Composite)
    # -------------------------------------------------------------------------
    IMAGE_SIZE = 256

    # Input Band Indices (0-based index for bands 08-16)
    # Band 11 -> Index 3, Band 14 -> Index 6, Band 15 -> Index 7
    BAND_11_IDX = 3
    BAND_14_IDX = 6
    BAND_15_IDX = 7

    # Wide Normalization Bounds
    # Derived from successful baseline analysis to preserve signal tails

    # Red Channel: Optical Depth (Band 15 - Band 14)
    ASH_RED_MIN = -6.7
    ASH_RED_MAX = 2.6

    # Green Channel: Particle Phase (Band 14 - Band 11)
    # Wide bounds to capture full variation
    ASH_GREEN_MIN = -6.0
    ASH_GREEN_MAX = 5.0

    # Blue Channel: Temperature (Band 14)
    # Brightness Temperature in Kelvin
    ASH_BLUE_MIN = 200.0
    ASH_BLUE_MAX = 300.0

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    MODEL_NAME = "hrnet_w18"
    PRETRAINED = True

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 32
    EPOCHS = 35
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-5

    # Loss Function Configuration (Balanced Focal Loss)
    FOCAL_ALPHA = 0.5
    FOCAL_GAMMA = 2.0

    # Scheduler Configuration (ReduceLROnPlateau)
    SCHEDULER_PATIENCE = 3
    SCHEDULER_FACTOR = 0.5
    MIN_LR = 1e-7

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 8

    # -------------------------------------------------------------------------
    # Debugging
    # -------------------------------------------------------------------------
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 200


def get_config(debug=False):
    """
    Retrieves the configuration class.

    Args:
        debug (bool): If True, overrides settings for a quick debug run
                      (fewer epochs, smaller batch size, enabled debug flag).

    Returns:
        type(Config): The configuration class with potentially modified attributes.
    """
    conf = Config
    if debug:
        conf.DEBUG = True
        conf.EPOCHS = 2
        conf.BATCH_SIZE = 8
        # Ensure directories exist even in debug mode (already handled in class body)
    return conf
