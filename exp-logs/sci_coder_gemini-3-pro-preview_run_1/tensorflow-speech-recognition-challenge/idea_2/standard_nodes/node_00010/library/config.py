import os
import torch


class Config:
    """
    Configuration class for the Speech Command Recognition task.
    Centralizes all hyperparameters, file paths, and model settings.
    """

    # -------------------------------------------------------------------------
    # General Settings
    # -------------------------------------------------------------------------
    seed = 42
    num_workers = 4
    device = "cuda" if torch.cuda.is_available() else "cpu"

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    input_root = "./input"

    # Metadata files (generated by the provided script)
    train_metadata_path = "./metadata/train.csv"
    val_metadata_path = "./metadata/val.csv"
    test_metadata_path = "./metadata/test.csv"

    # Background noise folder for dynamic silence generation
    noise_dir = os.path.join(input_root, "train", "audio", "_background_noise_")

    # Output directories
    working_dir = "./working/idea_2/"
    submission_dir = "./submission"

    # Specific output files
    model_save_path = os.path.join(working_dir, "best_model.pth")
    submission_path = os.path.join(submission_dir, "submission.csv")

    # Cache paths for processed datasets (if needed)
    train_cache_path = os.path.join(working_dir, "train_cache.parquet")
    val_cache_path = os.path.join(working_dir, "val_cache.parquet")
    test_cache_path = os.path.join(working_dir, "test_cache.parquet")

    # -------------------------------------------------------------------------
    # Audio Processing Parameters
    # -------------------------------------------------------------------------
    sample_rate = 16000
    duration = 1.0  # seconds
    target_length = int(sample_rate * duration)

    # Spectrogram extraction
    n_mels = 128
    n_fft = 1024
    hop_length = 512

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    model_name = "convnext_tiny"
    in_channels = 1  # Log-Mel Spectrogram is 1 channel
    num_classes = 12
    pretrained = True

    # Label definition (Order matters for prediction)
    labels = [
        "yes",
        "no",
        "up",
        "down",
        "left",
        "right",
        "on",
        "off",
        "stop",
        "go",
        "silence",
        "unknown",
    ]
    label2id = {label: i for i, label in enumerate(labels)}
    id2label = {i: label for i, label in enumerate(labels)}

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    epochs = 35
    batch_size = 128

    # Optimization
    learning_rate = 1e-3
    weight_decay = 0.05  # AdamW usually requires higher weight decay

    # Scheduler (Cosine Annealing)
    T_max = epochs
    min_lr = 1e-6

    # Regularization
    mixup_alpha = 0.4

    # SpecAugment parameters
    freq_mask_param = 30
    time_mask_param = 100

    # -------------------------------------------------------------------------
    # Debug / Development
    # -------------------------------------------------------------------------
    # If subset_size is set to an integer (e.g., 1000), the dataloader will
    # only use that many samples for quick debugging.
    subset_size = None

    @classmethod
    def setup(cls):
        """
        Create necessary output directories.
        """
        os.makedirs(cls.working_dir, exist_ok=True)
        os.makedirs(cls.submission_dir, exist_ok=True)
