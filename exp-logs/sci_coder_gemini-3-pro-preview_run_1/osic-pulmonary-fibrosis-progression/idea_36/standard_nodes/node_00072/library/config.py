import os
import torch
import random
import numpy as np


class Config:
    """
    Centralized configuration for the SCVR-Net (Scaled Contextualized Visual-Residual Network) solution.
    Defines hyperparameters for the Fixed Overlapping Orthogonal Tri-Slabs data strategy and
    the modified Laplace Log Likelihood metric.
    """

    # ==========================================
    # 1. Experiment & Reproducibility
    # ==========================================
    EXP_ID = "idea_36"
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_DATA_LIMIT = 50  # Number of patients to use when DEBUG is True

    # ==========================================
    # 2. File Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Cache directory for deterministic data processing (Tri-Slab generation)
    # Using a specific subdirectory for this idea to avoid conflicts
    CACHE_DIR = os.path.join(WORKING_DIR, EXP_ID)

    # Submission paths
    SUBMISSION_DIR = "./submission"
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Metadata CSVs (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # ==========================================
    # 3. Data Processing (Tri-Slab Strategy)
    # ==========================================
    IMG_SIZE = 240  # Native resolution for EfficientNet-B1
    NUM_SLABS = 3  # Number of slabs per view (Axial/Coronal)
    SLAB_OVERLAP = 0.15  # 15% overlap between adjacent slabs

    # Augmentation Settings
    USE_AUGMENTATION = True  # Enable spatial augmentations (flips, shifts)

    # ==========================================
    # 4. Model Architecture (SCVR-Net)
    # ==========================================
    BACKBONE = "efficientnet_b1"
    PRETRAINED = True
    BACKBONE_DIM = 1280  # Output dimension of EfficientNet-B1 (GAP)

    # Tabular Context
    # Features used: Age, Sex, SmokingStatus, Percent
    TABULAR_HIDDEN_DIM = 1280  # Projected dimension to match visual tokens

    # Attention Mechanism
    NUM_ATTENTION_HEADS = 4
    DROPOUT = 0.1

    # ==========================================
    # 5. Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 16  # Safe for B1 @ 240x240 on provided hardware
    EPOCHS = 50
    LR = 1e-4  # Learning rate
    WEIGHT_DECAY = 1e-2
    PATIENCE = 7  # Strict early stopping (6-8 epochs)
    NUM_WORKERS = 4

    # Metric / Loss Configuration
    SIGMA_CLIP = 70.0  # Minimum confidence value (ml)
    MAX_ERROR = 1000.0  # Error threshold for metric calculation (ml)

    # Compute
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Initializes the experiment environment.
        - Creates necessary directories for caching and submission.
        - Sets random seeds for full reproducibility.
        """
        # Create directories
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set Random Seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.cuda.manual_seed_all(cls.SEED)
            # Ensure deterministic behavior
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
