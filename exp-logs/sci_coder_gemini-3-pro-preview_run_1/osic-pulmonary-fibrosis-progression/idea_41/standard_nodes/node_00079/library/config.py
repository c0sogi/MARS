import os
import torch


class Config:
    """
    Global configuration for the H2-DAN (Holistic High-Fidelity Dual-Axis Network) pipeline.
    """

    # ==========================================
    # 1. Environment & Reproducibility
    # ==========================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4

    # ==========================================
    # 2. File Paths & Directories
    # ==========================================
    # Input directories (Read-Only)
    INPUT_ROOT = "./input"
    TRAIN_IMG_DIR = os.path.join(INPUT_ROOT, "train")
    TEST_IMG_DIR = os.path.join(INPUT_ROOT, "test")

    # Metadata paths (Generated by previous steps)
    METADATA_DIR = "./metadata"
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_ROOT, "sample_submission.csv")

    # Output & Caching Directories
    # Specific cache directory for this idea iteration
    CACHE_DIR = "./working/idea_41/"
    SUBMISSION_DIR = "./submission"
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure writable directories exist
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================================
    # 3. Data Processing & Augmentation
    # ==========================================
    # Image parameters
    IMG_SIZE = 240  # Native resolution for EfficientNet-B1
    NUM_SLABS = 3  # Tri-slab generation
    SLAB_OVERLAP = 0.15  # 15% overlap between slabs

    # Caching behavior
    LOAD_CACHED_DATA = True  # If True, tries to load .npy files from CACHE_DIR

    # Debugging / Development
    DEBUG = False  # Set to True to run on a small subset
    DEBUG_SAMPLE_SIZE = 50  # Number of samples to use in debug mode

    # ==========================================
    # 4. Model Architecture (H2-DAN)
    # ==========================================
    MODEL_NAME = "H2-DAN"
    BACKBONE = "efficientnet_b1"
    PRETRAINED = True

    # Dimensions
    # We maintain native backbone dimensionality to preserve texture details
    FEATURE_DIM = 1280
    TABULAR_HIDDEN_DIM = 1280

    # Attention & Fusion
    ATTENTION_HEADS = 4
    DROPOUT_RATE = 0.2

    # ==========================================
    # 5. Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 16  # Adjusted for A100 (40GB) with dual backbones
    EPOCHS = 50
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2  # For AdamW

    # Optimization
    PATIENCE = 7  # Early stopping patience
    GRAD_CLIP = 1.0

    # Scheduler (Cosine Annealing)
    T_MAX = 50
    ETA_MIN = 1e-6

    # ==========================================
    # 6. Metric & Loss Configuration
    # ==========================================
    # Modified Laplace Log Likelihood constraints
    MAX_ERROR_CLIP = 1000  # Clip absolute error at 1000 ml
    SIGMA_CLIP = 70  # Clip confidence (sigma) at 70 ml

    @classmethod
    def get_summary(cls):
        """Returns a dictionary summary of the configuration."""
        return {
            k: v
            for k, v in cls.__dict__.items()
            if not k.startswith("__") and not callable(v)
        }
