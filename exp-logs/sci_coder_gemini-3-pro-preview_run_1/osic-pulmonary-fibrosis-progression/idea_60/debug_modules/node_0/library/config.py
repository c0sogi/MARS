import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration module for the Decoupled-Context Shared-Latent Network (DCSL-Net) pipeline.
    Acts as the single source of truth for hyperparameters and paths.
    """

    # ==========================================
    # 1. General & Reproducibility
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to train on a small subset for debugging
    EXPERIMENT_NAME = "idea_60"

    # ==========================================
    # 2. File System Paths
    # ==========================================
    ROOT_DIR = "."

    # Input Directories (Read-Only)
    INPUT_DIR = os.path.join(ROOT_DIR, "input")
    METADATA_DIR = os.path.join(ROOT_DIR, "metadata")

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Directories (Writable)
    WORKING_DIR = os.path.join(ROOT_DIR, "working")

    # Cache directory for deterministic data processing (Tri-Slab generation)
    CACHE_DIR = os.path.join(WORKING_DIR, EXPERIMENT_NAME)

    # Directory for saving model weights
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")

    # Directory for final submission
    SUBMISSION_DIR = os.path.join(ROOT_DIR, "submission")
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure all writable directories exist
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================================
    # 3. Data Processing & Augmentation
    # ==========================================
    # Image dimensions for EfficientNet-B0
    IMG_SIZE = 224
    IN_CHANNELS = 3  # RGB (MIPs of slabs)

    # Tri-Slab Generation Parameters
    NUM_SLABS = 3
    SLAB_OVERLAP = 0.15  # 15% overlap between slabs

    # DataLoader
    NUM_WORKERS = 4

    # Normalization (ImageNet stats)
    MEAN = [0.485, 0.456, 0.406]
    STD = [0.229, 0.224, 0.225]

    # ==========================================
    # 4. Model Architecture (DCSL-Net)
    # ==========================================
    BACKBONE = "efficientnet_b0"
    PRETRAINED = True

    # Latent Dimensions
    SHARED_LATENT_DIM = 128  # T_lat (Clinical Prior)
    VISUAL_DIM = 1280  # Native output of EfficientNet-B0 GAP
    CONTEXT_STREAM_DIM = 64  # Dimension for H_vis and H_ctx streams

    # ==========================================
    # 5. Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 32
    EPOCHS = 50
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2

    # Early Stopping
    PATIENCE = 8

    # Scheduler (Cosine Annealing)
    ETA_MIN = 1e-6

    # Hardware
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================
    # 6. Metric & Loss Constraints
    # ==========================================
    # Modified Laplace Log Likelihood constants
    MAX_ERROR_CLIP = 1000.0
    MIN_CONFIDENCE_CLIP = 70.0

    @staticmethod
    def set_seed(seed=42):
        """
        Sets fixed random seeds for reproducibility across Python, NumPy, and PyTorch.
        """
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
        os.environ["PYTHONHASHSEED"] = str(seed)


# Automatically set seed on import
Config.set_seed(Config.SEED)
