import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration class for the Tri-Stream Balanced-Context Network (TSBC-Net).
    """

    # ==========================================
    # General Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data
    DEBUG_SAMPLES = 50  # Number of samples to use if DEBUG is True
    EXPERIMENT_ID = "idea_64"

    # ==========================================
    # Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Input Data
    TRAIN_DIR = os.path.join(INPUT_DIR, "train")
    TEST_DIR = os.path.join(INPUT_DIR, "test")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Working Directories
    WORKING_DIR = "./working"
    CACHE_DIR = os.path.join(WORKING_DIR, EXPERIMENT_ID)
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = os.path.join(WORKING_DIR, "submission")

    # ==========================================
    # Data Preprocessing
    # ==========================================
    IMG_SIZE = 224  # Matches EfficientNet-B0 native resolution
    NUM_SLABS = 3  # Tri-Slab approach
    SLAB_OVERLAP = 0.15  # 15% overlap between slabs
    USE_AUGMENTATION = True  # Spatial augmentations enabled

    # ==========================================
    # Model Architecture (TSBC-Net)
    # ==========================================
    BACKBONE = "efficientnet-b0"
    BACKBONE_OUT_DIM = 1280  # Native output dim of EfficientNet-B0

    LATENT_DIM = 128  # Dimension for Shared Latent Vector (T_lat)
    PROJ_DIM = 1280  # Dimension for Tabular Alignment (matches backbone)
    HIDDEN_DIM = 64  # Dimension for Visual/Tabular Context streams (H_vis, H_ctx)

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 32
    EPOCHS = 50
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-5
    PATIENCE = 8  # Strict patience for Early Stopping
    NUM_WORKERS = 4  # Number of dataloader workers

    # Device configuration
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================
    # Metric / Loss Constants
    # ==========================================
    MAX_ERROR = 1000  # Clipping threshold for metric calculation (Delta)
    MIN_CONFIDENCE = 70  # Clipping threshold for confidence (Sigma)

    @classmethod
    def setup(cls):
        """Creates necessary working directories."""
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


def seed_everything(seed=42):
    """
    Sets the random seed for reproducibility across Python, NumPy, and PyTorch.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False
