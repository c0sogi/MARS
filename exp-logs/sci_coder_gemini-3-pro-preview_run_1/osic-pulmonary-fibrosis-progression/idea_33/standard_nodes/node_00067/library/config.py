import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration for Gated-Tabular Visual-Residual Network (GTVR-Net).
    Defines paths, hyperparameters, and model settings.
    """

    # ==========================================
    # 1. File Paths and Directories
    # ==========================================
    # Root directories
    INPUT_ROOT = "./input"
    METADATA_ROOT = "./metadata"
    WORKING_ROOT = "./working"

    # Cache directory for deterministic data processing (e.g., Tri-Slab generation)
    # Using idea_33 as the specific iteration identifier
    CACHE_DIR = os.path.join(WORKING_ROOT, "idea_33")
    MODEL_SAVE_DIR = os.path.join(WORKING_ROOT, "checkpoints")
    SUBMISSION_FILE = os.path.join(WORKING_ROOT, "submission.csv")

    # Metadata CSV paths (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_ROOT, "train.csv")
    VAL_CSV = os.path.join(METADATA_ROOT, "val.csv")
    TEST_CSV = os.path.join(METADATA_ROOT, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_ROOT, "sample_submission.csv")

    # DICOM Image directories
    TRAIN_DICOM_DIR = os.path.join(INPUT_ROOT, "train")
    TEST_DICOM_DIR = os.path.join(INPUT_ROOT, "test")

    # ==========================================
    # 2. Reproducibility
    # ==========================================
    SEED = 42

    # ==========================================
    # 3. Image Processing (Tri-Slab)
    # ==========================================
    # Native resolution to avoid upscaling artifacts
    IMG_SIZE = 224

    # Tri-Slab settings
    NUM_SLABS = 3
    SLAB_OVERLAP = 0.15  # 15% overlap between slabs

    # Input channels: 3 (RGB) - Mapped from MIP of slabs
    IN_CHANNELS = 3

    # ==========================================
    # 4. Model Architecture (GTVR-Net)
    # ==========================================
    # Backbone
    BACKBONE = "efficientnet_b0"
    PRETRAINED = True

    # Dimensionality
    # EfficientNet-B0 output is 1280. We keep this native.
    FEATURE_DIM = 1280

    # Tabular Projection
    # Dimension for projecting clinical features via GLU
    TABULAR_HIDDEN_DIM = 1280

    # Dropout rate for regularization
    DROPOUT = 0.2

    # ==========================================
    # 5. Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 16
    EPOCHS = 50
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2  # For AdamW

    # Early Stopping
    PATIENCE = 8

    # Scheduler (Cosine Annealing)
    T_MAX = EPOCHS
    ETA_MIN = 1e-6

    # Hardware
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================
    # 6. Metric and Loss Constraints
    # ==========================================
    # Modified Laplace Log Likelihood constants
    MAX_ERROR = 1000.0  # Clip absolute error at 1000 ml
    MIN_CONFIDENCE = 70.0  # Clip confidence at 70 ml

    # ==========================================
    # 7. Debugging / Development
    # ==========================================
    # Set to a small integer (e.g., 50) to limit dataset size for quick testing
    # Set to None for full training
    DEBUG_SAMPLE_SIZE = None

    @staticmethod
    def setup_reproducibility(seed=42):
        """
        Sets the random seed for python, numpy, and torch to ensure reproducibility.
        """
        random.seed(seed)
        os.environ["PYTHONHASHSEED"] = str(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        torch.cuda.manual_seed(seed)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False
        # print(f"Random seed set to {seed}")

    @staticmethod
    def make_dirs():
        """
        Creates necessary working directories.
        """
        os.makedirs(Config.CACHE_DIR, exist_ok=True)
        os.makedirs(Config.MODEL_SAVE_DIR, exist_ok=True)
