import os
import torch
import random
import numpy as np


def seed_everything(seed=42):
    """
    Sets the random seed for all relevant libraries to ensure reproducibility.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


class Config:
    """
    Central configuration for the Siamese Dual-Axis Tri-Slab Network.
    """

    # ==========================
    # File Paths & Directories
    # ==========================
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata CSVs (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Raw DICOM Directories
    TRAIN_DICOM_DIR = os.path.join(INPUT_ROOT, "train")
    TEST_DICOM_DIR = os.path.join(INPUT_ROOT, "test")

    # Working Directories
    # CACHE_DIR: Stores processed 2.5D Tri-Slab numpy arrays to speed up training
    CACHE_DIR = "./working/idea_4"
    SUBMISSION_DIR = "./submission"

    # Output Files
    MODEL_SAVE_PATH = "./working/best_model.pth"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure writable directories exist
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================
    # Data Configuration
    # ==========================
    IMG_SIZE = 224
    NUM_SLABS = 3  # Tri-slab (R, G, B channels correspond to 3 depth slabs)

    # Categorical Mappings for Tabular Data
    SEX_MAP = {"Male": 0, "Female": 1}
    SMOKING_MAP = {"Ex-smoker": 0, "Never smoked": 1, "Currently smokes": 2}

    # Feature Definitions
    # 'Percent' in the context of input features refers to the Baseline Percent
    NUM_FEATURES = ["Age", "Percent"]
    CAT_FEATURES = ["Sex", "SmokingStatus"]

    # ==========================
    # Model Hyperparameters
    # ==========================
    BACKBONE = "efficientnet_b0"
    PRETRAINED = True
    DROP_RATE = 0.3
    FUSION_DIM = 512  # Dimension after concatenating visual and tabular features

    # ==========================
    # Training Hyperparameters
    # ==========================
    SEED = 42

    # Debugging flags to run on a subset of data
    DEBUG = False
    DEBUG_SIZE = 50

    BATCH_SIZE = 16  # Optimized for GPU memory with dual-image input
    NUM_WORKERS = 4
    EPOCHS = 30  # Dataset is small; typically converges/overfits early

    LR = 3e-4
    WEIGHT_DECAY = 1e-2

    # Cosine Annealing Scheduler Settings
    T_MAX = 30
    MIN_LR = 1e-6

    # Early Stopping
    PATIENCE = 8

    # ==========================
    # Loss & Metrics
    # ==========================
    # Weight for the auxiliary task (MSE of Baseline Percent prediction)
    # L_total = L_metric + lambda * L_aux
    AUX_LOSS_WEIGHT = 0.2

    # Metric Constants (Modified Laplace Log Likelihood)
    MAX_ERROR = 1000  # Clip error at 1000 ml
    MIN_CONFIDENCE = 70  # Clip confidence (sigma) at 70 ml

    # Device configuration
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")


# Apply seeding immediately upon import
seed_everything(Config.SEED)
