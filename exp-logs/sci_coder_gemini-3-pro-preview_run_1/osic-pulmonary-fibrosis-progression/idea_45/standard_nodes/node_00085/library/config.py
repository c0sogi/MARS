import os
import torch


class Config:
    """
    Configuration class for the Shared-Latent Holistic Dual-Axis Network (SLH-DAN).
    Centralizes all file paths, hyperparameters, and model settings.
    """

    # ==========================================
    # 1. Environment & Reproducibility
    # ==========================================
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4

    # ==========================================
    # 2. File Paths & Directories
    # ==========================================
    # Root directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_45"

    # Ensure working directory exists
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Metadata files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Checkpoint paths
    BEST_MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join("submission", "submission.csv")

    # Cache directory for processed images
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    os.makedirs(CACHE_DIR, exist_ok=True)

    # ==========================================
    # 3. Data Processing (Tri-Slab)
    # ==========================================
    IMG_SIZE = 224  # Native resolution for EfficientNet-B0
    SLAB_OVERLAP = 0.15  # 15% overlap for tri-slab generation
    NUM_SLABS = 3  # 3 slabs per view (Axial/Coronal)

    # Normalization constants (ImageNet defaults)
    MEAN = [0.485, 0.456, 0.406]
    STD = [0.229, 0.224, 0.225]

    # ==========================================
    # 4. Model Architecture (SLH-DAN)
    # ==========================================
    BACKBONE_NAME = "efficientnet_b0"
    VISUAL_DIM = 1280  # Native output dim of EfficientNet-B0 (No projection)
    LATENT_DIM = 128  # Shared latent vector dimension for tabular data

    # Tabular features used for the shared latent encoder
    TABULAR_FEATURES = ["Weeks", "Percent", "Age", "Sex", "SmokingStatus"]

    # ==========================================
    # 5. Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 16  # Conservative batch size for dual-path B0
    EPOCHS = 50  # Max epochs
    LEARNING_RATE = 1e-4  # Initial learning rate
    WEIGHT_DECAY = 1e-2  # For AdamW
    PATIENCE = 8  # Early stopping patience

    # Scheduler settings (Cosine Annealing)
    T_MAX = 50
    ETA_MIN = 1e-6

    # Metric constraints
    MAX_ERROR = 1000  # Error clipping threshold
    MIN_CONFIDENCE = 70  # Confidence clipping threshold

    def __init__(self):
        # Create submission directory if it doesn't exist
        os.makedirs(os.path.dirname(self.SUBMISSION_PATH), exist_ok=True)

    @staticmethod
    def get_dicom_path(rel_path):
        """Helper to construct full DICOM path from metadata relative path."""
        return os.path.join(Config.INPUT_DIR, rel_path)
