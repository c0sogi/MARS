import os
import torch


class Config:
    """
    Configuration for Deep-Aligned Visual-Residual Dual-Axis Network (DAVR-Net).
    Centralizes all hyperparameters, file paths, and model settings.
    """

    # ==========================================
    # General Settings
    # ==========================================
    seed = 42
    debug = False  # Set to True to run on a small subset for debugging
    debug_sample_size = 20  # Number of samples to use in debug mode

    # ==========================================
    # Directory Paths
    # ==========================================
    input_root = "./input"
    metadata_dir = "./metadata"
    working_dir = "./working"

    # Cache directory for deterministic data processing (Tri-Slab generation)
    # Strategy: idea_38 (DAVR-Net)
    cache_dir = os.path.join(working_dir, "idea_38")

    # Submission directory
    submission_dir = "./submission"

    # Create directories if they don't exist
    os.makedirs(cache_dir, exist_ok=True)
    os.makedirs(submission_dir, exist_ok=True)

    # ==========================================
    # File Paths
    # ==========================================
    # Metadata files generated by the metadata script
    train_file = os.path.join(metadata_dir, "train.csv")
    val_file = os.path.join(metadata_dir, "val.csv")
    test_file = os.path.join(metadata_dir, "test.csv")

    # Raw DICOM directories (relative to input_root)
    train_dcm_dir = "train"
    test_dcm_dir = "test"

    # Output paths
    model_save_name = "best_model_idea_38.pth"
    model_path = os.path.join(working_dir, model_save_name)
    submission_path = os.path.join(submission_dir, "submission.csv")

    # ==========================================
    # Data Hyperparameters
    # ==========================================
    img_size = 224  # Native resolution for EfficientNet-B0
    slice_count = 3  # Tri-slab inputs (3 channels per view)

    # Caching
    load_cached_data = (
        True  # If True, tries to load pre-processed arrays from cache_dir
    )

    # Normalization (ImageNet stats)
    mean = [0.485, 0.456, 0.406]
    std = [0.229, 0.224, 0.225]

    # ==========================================
    # Model Hyperparameters (DAVR-Net)
    # ==========================================
    # Visual Backbone
    backbone_name = "efficientnet_b0"
    backbone_pretrained = True
    backbone_out_dim = 1280  # EfficientNet-B0 output features

    # Tabular Alignment
    tabular_input_dim = 7  # Age, Sex, Smoking (3), Percent, Baseline_Week
    tabular_hidden_dim = 1280  # Projected to match visual dim

    # Attention & Fusion
    num_attention_heads = 4
    dropout_rate = 0.3

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    batch_size = 32  # A100 allows larger batch size for B0
    epochs = 50
    lr = 1e-4
    weight_decay = 1e-2

    # Scheduler
    T_max = 50  # For CosineAnnealingLR
    eta_min = 1e-6

    # Early Stopping
    patience = 8  # Strict patience to prevent overfitting

    # Hardware
    num_workers = 4
    device = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================
    # Metric / Loss Constants
    # ==========================================
    # Modified Laplace Log Likelihood constants
    sigma_clip = 70.0
    max_fvc_error = 1000.0
