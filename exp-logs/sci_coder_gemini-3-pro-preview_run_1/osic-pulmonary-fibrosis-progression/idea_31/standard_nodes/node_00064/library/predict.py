import os
import torch
import pandas as pd
from torch.utils.data import DataLoader
from library.config import Config
from library.utils import seed_everything
from library.data import OSICDataset
from library.model import AVRDAN


def run_inference(model, dataloader, device):
    """
    Runs inference on the provided dataloader using the given model.

    Args:
        model (nn.Module): The trained AVRDAN model.
        dataloader (DataLoader): DataLoader for the test set.
        device (torch.device): Device to run inference on.

    Returns:
        pd.DataFrame: DataFrame containing Patient_Week, FVC, and Confidence.
    """
    model.eval()
    results = []

    with torch.no_grad():
        for batch in dataloader:
            # Move inputs to device
            img_ax = batch["img_ax"].to(device)
            img_cor = batch["img_cor"].to(device)
            tab_glu = batch["tab_glu"].to(device)
            tab_skip = batch["tab_skip"].to(device)
            delta_week = batch["delta_week"].to(device)
            baseline_fvc = batch["baseline_fvc"].to(device)

            # Metadata
            patient_weeks = batch["patient_week"]

            # Predict
            # The model forward pass calculates:
            # FVC = Baseline + alpha * delta_week
            # Confidence = sigma_base + sigma_growth * |delta_week|
            fvc_pred, conf_pred = model(
                img_ax, img_cor, tab_glu, tab_skip, delta_week, baseline_fvc
            )

            # Move to CPU and convert to numpy
            fvc_pred = fvc_pred.cpu().numpy()
            conf_pred = conf_pred.cpu().numpy()

            # Aggregate results
            for pw, fvc, conf in zip(patient_weeks, fvc_pred, conf_pred):
                results.append({"Patient_Week": pw, "FVC": fvc, "Confidence": conf})

    return pd.DataFrame(results)


def generate_submission_file():
    """
    Main function to load data, load model, run inference, and save the submission file.
    """
    # 1. Setup
    seed_everything(Config.SEED)
    device = Config.DEVICE
    print(f"Running inference on device: {device}")

    # 2. Data Loading
    # We use the test csv generated by the metadata script
    print(f"Loading test data from {Config.TEST_CSV}...")
    test_dataset = OSICDataset(csv_path=Config.TEST_CSV, mode="test")

    test_loader = DataLoader(
        test_dataset,
        batch_size=Config.BATCH_SIZE,
        shuffle=False,
        num_workers=Config.NUM_WORKERS,
        pin_memory=True,
    )

    # 3. Model Loading
    print("Initializing model...")
    model = AVRDAN()
    model.to(device)

    # Load weights
    if os.path.exists(Config.MODEL_SAVE_PATH):
        print(f"Loading weights from {Config.MODEL_SAVE_PATH}...")
        state_dict = torch.load(Config.MODEL_SAVE_PATH, map_location=device)
        model.load_state_dict(state_dict)
    else:
        print(
            f"WARNING: Model weights not found at {Config.MODEL_SAVE_PATH}. Using random initialization."
        )

    # 4. Inference
    print("Generating predictions...")
    df_results = run_inference(model, test_loader, device)

    # 5. Formatting and Saving
    # Ensure correct column order
    submission_cols = ["Patient_Week", "FVC", "Confidence"]
    df_results = df_results[submission_cols]

    # Define output paths
    # 1. Required submission path from guidelines
    submission_dir = "./submission"
    os.makedirs(submission_dir, exist_ok=True)
    submission_path_required = os.path.join(submission_dir, "submission.csv")

    # 2. Config path (working directory)
    submission_path_config = Config.SUBMISSION_PATH

    # Save
    print(f"Saving submission to {submission_path_required}...")
    df_results.to_csv(submission_path_required, index=False)

    if submission_path_required != submission_path_config:
        print(f"Saving copy to {submission_path_config}...")
        df_results.to_csv(submission_path_config, index=False)

    print("Submission generation complete.")
    print(df_results.head())
