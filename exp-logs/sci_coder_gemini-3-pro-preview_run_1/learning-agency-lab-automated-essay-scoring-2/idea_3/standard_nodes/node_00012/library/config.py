import os
import torch


class Config:
    """
    Configuration class for the Essay Scoring task.
    Centralizes hyperparameters, file paths, and model settings.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    seed = 42
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    num_workers = 4  # Optimized for 12 vCPUs

    # =========================================================================
    # Data Paths
    # =========================================================================
    # Input metadata (CSV files generated by the metadata script)
    train_path = "./metadata/train.csv"
    val_path = "./metadata/val.csv"
    test_path = "./metadata/test.csv"

    # Sample submission for format reference
    sample_submission_path = "./input/sample_submission.csv"

    # Output / Working Directory for artifacts (cache, models)
    output_dir = "./working/idea_3"

    # Submission Directory
    submission_dir = "./submission"
    submission_path = os.path.join(submission_dir, "submission.csv")

    # Cache Files (Parquet format for efficiency)
    train_processed_path = os.path.join(output_dir, "train_processed.parquet")
    val_processed_path = os.path.join(output_dir, "val_processed.parquet")
    test_processed_path = os.path.join(output_dir, "test_processed.parquet")

    # Model Checkpoint Path
    model_save_path = os.path.join(output_dir, "deberta_model.pth")

    # =========================================================================
    # Model Hyperparameters
    # =========================================================================
    model_name = "microsoft/deberta-v3-small"

    # Sequence Length: 1024 to capture full argumentation flow
    max_length = 1024

    # Ordinal Classification Settings:
    # We use 5 binary classifiers for the thresholds: >1, >2, >3, >4, >5
    num_labels = 5

    # Dropout rates
    hidden_dropout_prob = 0.1
    attention_probs_dropout_prob = 0.1

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    # Batch sizes (Adjusted for A100 40GB and 1024 sequence length)
    train_batch_size = 8
    valid_batch_size = 16

    # Optimization
    epochs = 4
    learning_rate = 2e-5
    weight_decay = 0.01
    max_grad_norm = 10.0  # Gradient clipping
    warmup_ratio = 0.1

    # Layer-wise Learning Rate Decay (LLRD)
    # Decay rate for learning rates as we go from top layers to bottom layers
    llrd_decay = 0.9

    # =========================================================================
    # Debugging / Development
    # =========================================================================
    # If True, processes only a small subset of data for rapid iteration
    debug = False


# Ensure necessary directories exist
os.makedirs(Config.output_dir, exist_ok=True)
os.makedirs(Config.submission_dir, exist_ok=True)
