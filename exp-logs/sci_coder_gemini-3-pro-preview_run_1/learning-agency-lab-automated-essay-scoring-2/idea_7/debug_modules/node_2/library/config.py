import os
import torch


class Config:
    """
    Global configuration for the Essay Scoring Pipeline.
    Encapsulates settings for paths, model architecture, training hyperparameters,
    and ensemble strategies.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    seed = 42
    debug = False  # Set to True to run on a small subset for debugging
    num_workers = 4
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # =========================================================================
    # File Paths & Directories
    # =========================================================================
    # Input Directories (Read-Only)
    input_dir = "./input"
    metadata_dir = "./metadata"

    # Metadata Files (Generated by previous steps)
    # These files contain the stratified splits and processed text
    train_path = os.path.join(metadata_dir, "train.csv")
    val_path = os.path.join(metadata_dir, "val.csv")
    test_path = os.path.join(metadata_dir, "test.csv")

    # Working Directory (For Artifacts, Checkpoints, Logs)
    working_dir = "./working/idea_7"
    os.makedirs(working_dir, exist_ok=True)

    # Cache Directory (For deterministic data processing)
    # Logic: Check this dir for processed .parquet files before computing
    cache_dir = os.path.join(working_dir, "cache")
    os.makedirs(cache_dir, exist_ok=True)

    # Submission Directory
    submission_dir = "./submission"
    os.makedirs(submission_dir, exist_ok=True)
    submission_path = os.path.join(submission_dir, "submission.csv")

    # Sample Submission (for format reference)
    sample_submission_path = os.path.join(input_dir, "sample_submission.csv")

    # =========================================================================
    # Model Architecture
    # =========================================================================
    model_name = "microsoft/deberta-v3-large"
    max_length = 1024
    num_labels = 1  # Regression task (predicting score 1-6)

    # =========================================================================
    # Stage 1: MLM Pre-training Hyperparameters (Domain Adaptation)
    # =========================================================================
    mlm_epochs = 3
    mlm_batch_size = 4
    mlm_learning_rate = 5e-5
    mlm_probability = 0.15
    mlm_model_dir = os.path.join(working_dir, "mlm_checkpoints")
    os.makedirs(mlm_model_dir, exist_ok=True)

    # =========================================================================
    # Stage 2: Fine-Tuning Hyperparameters (Level 1)
    # =========================================================================
    num_folds = 5
    epochs = 4
    train_batch_size = 4  # Adjusted for 40GB GPU VRAM
    eval_batch_size = 8
    gradient_accumulation_steps = 4  # Effective batch size = 16

    learning_rate = 1e-5
    weight_decay = 0.01
    max_grad_norm = 10.0

    scheduler = "cosine"
    warmup_ratio = 0.1

    # Optimization Strategies
    use_llrd = True  # Layer-wise Learning Rate Decay
    llrd_decay = 0.9

    use_awp = True  # Adversarial Weight Perturbation
    awp_start_epoch = 2
    awp_eps = 1e-4
    awp_lr = 1e-4

    # Checkpointing
    model_dir = os.path.join(working_dir, "checkpoints")
    os.makedirs(model_dir, exist_ok=True)

    # =========================================================================
    # Stage 3: Stacking / Meta-Learner (Level 2)
    # =========================================================================
    # Meta-features to be extracted for the stacking model
    meta_features = [
        "char_count",
        "word_count",
        "sentence_count",
        "avg_word_length",
        "unique_word_count",
    ]

    # LightGBM Hyperparameters
    stacking_model = "lgbm"
    lgbm_params = {
        "n_estimators": 1000,
        "learning_rate": 0.01,
        "metric": "rmse",
        "random_state": seed,
        "verbosity": -1,
        "n_jobs": -1,
        "reg_alpha": 0.1,
        "reg_lambda": 0.1,
        "subsample": 0.8,
        "colsample_bytree": 0.8,
    }
