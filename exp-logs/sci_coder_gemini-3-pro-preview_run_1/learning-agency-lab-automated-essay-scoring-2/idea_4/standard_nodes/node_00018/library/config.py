import os
import torch


class Config:
    """
    Configuration class for Essay Scoring with DeBERTa-v3-Large.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    seed = 42
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    num_workers = 4
    debug = False  # Set to True for fast debugging on a subset

    # =========================================================================
    # Data Paths
    # =========================================================================
    # Metadata generated by the provided script
    train_path = "./metadata/train.csv"
    val_path = "./metadata/val.csv"
    test_path = "./metadata/test.csv"
    sample_submission_path = "./input/sample_submission.csv"

    # Output directories
    working_dir = "./working/idea_4"
    output_dir = working_dir  # Alias
    model_save_path = os.path.join(working_dir, "deberta_large_model.pth")
    submission_path = "./submission/submission.csv"

    # Cache paths for processed datasets
    train_cache_path = os.path.join(working_dir, "train_processed.parquet")
    val_cache_path = os.path.join(working_dir, "val_processed.parquet")
    test_cache_path = os.path.join(working_dir, "test_processed.parquet")

    # Ensure directories exist
    os.makedirs(working_dir, exist_ok=True)
    os.makedirs(os.path.dirname(submission_path), exist_ok=True)

    # =========================================================================
    # Model Architecture
    # =========================================================================
    model_name = "microsoft/deberta-v3-large"
    max_length = 1024
    target_size = 1  # Regression output (scalar)

    # Pooling Strategy
    pooling_type = "attention"  # Options: 'mean', 'attention', 'cls'

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    epochs = 4

    # Batch size considerations for A100 40GB + DeBERTa-Large + 1024 seq len
    # Using a small batch size per step with gradient accumulation (logic in train loop)
    train_batch_size = 2
    valid_batch_size = 4
    gradient_accumulation_steps = 4

    # Optimization
    lr = 1e-5  # Base learning rate for the backbone
    head_lr = 5e-5  # Learning rate for the regressor head
    weight_decay = 0.01
    max_grad_norm = 1.0

    # Scheduler
    scheduler_type = "cosine"
    warmup_ratio = 0.1

    # Layer-wise Learning Rate Decay (LLRD)
    use_llrd = True
    llrd_decay = 0.9  # Decay factor for layers (closer to input = lower LR)

    # =========================================================================
    # Inference & Validation
    # =========================================================================
    use_fp16 = True  # Use mixed precision
    patience = 3  # Early stopping patience
    val_check_interval = 0.5  # Check validation twice per epoch if possible
