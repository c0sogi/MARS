import os
import torch


class Config:
    """
    Configuration for the Deformable Attention-Gated Siamese Network.
    Defines hyperparameters, file paths, and training settings.
    """

    # -------------------------------------------------------------------------
    # General & Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Toggle to True for quick debugging runs

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    # Base Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Metadata Files (Generated by the provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Image Directories
    TRAIN_IMAGES_DIR = os.path.join(INPUT_DIR, "train_images")
    TEST_IMAGES_DIR = os.path.join(INPUT_DIR, "test_images")

    # Caching Directory (for deterministic data processing)
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_22")

    # Submission Output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Configuration
    # -------------------------------------------------------------------------
    # Resolution: 768x768 as specified for the Siamese input
    IMG_SIZE = (768, 768)

    # Channels: 3 -> Image (1) + Spatially Broadcasted Age (1) + Implant (1)
    NUM_CHANNELS = 3

    # -------------------------------------------------------------------------
    # Model Configuration
    # -------------------------------------------------------------------------
    # Backbone: EfficientNet-B2
    BACKBONE = "tf_efficientnet_b2_ns"
    PRETRAINED = True

    # Regularization
    DROP_RATE = 0.3
    DROP_PATH_RATE = 0.2

    # -------------------------------------------------------------------------
    # Training Configuration
    # -------------------------------------------------------------------------
    # Batch Size: Adjusted for 768x768 Siamese input on A100
    BATCH_SIZE = 8

    # Duration
    NUM_EPOCHS = 10

    # Optimization
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2

    # Class Imbalance Handling
    # Aggressive positive weighting to approximate inverse class frequency
    POS_WEIGHT = 47.0

    # Gradient Handling
    # Explicitly disabled to allow large updates for minority class errors
    MAX_GRAD_NORM = None

    # Scheduler: Cosine Annealing
    T_MAX = 10
    ETA_MIN = 1e-6

    # Early Stopping
    PATIENCE = 3

    # -------------------------------------------------------------------------
    # Hardware Configuration
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Optimized for 12 vCPUs

    @classmethod
    def setup(cls):
        """
        Creates necessary writable directories if they do not exist.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize environment setup on import
Config.setup()
