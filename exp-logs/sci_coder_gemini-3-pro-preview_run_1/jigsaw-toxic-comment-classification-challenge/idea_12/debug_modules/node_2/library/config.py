    # Using 'idea_12' to isolate this solution's artifacts
    working_dir = "./working/idea_12"
    output_dir = os.path.join(working_dir, "output")
    cache_dir = os.path.join(working_dir, "cache")

    # Model storage paths
    dapt_model_path = os.path.join(working_dir, "dapt_backbone")
    teacher_model_dir = os.path.join(working_dir, "teacher_models")
    student_model_dir = os.path.join(working_dir, "student_models")

    # Final Submission
    submission_dir = "./submission"
    submission_path = os.path.join(submission_dir, "submission.csv")

    # Create necessary directories
    os.makedirs(working_dir, exist_ok=True)
    os.makedirs(output_dir, exist_ok=True)
    os.makedirs(cache_dir, exist_ok=True)
    os.makedirs(submission_dir, exist_ok=True)
    os.makedirs(teacher_model_dir, exist_ok=True)
    os.makedirs(student_model_dir, exist_ok=True)

    # ====================================================
    # Data & Tokenizer Settings
    # ====================================================
    target_cols = [
        "toxic",
        "severe_toxic",
        "obscene",
        "threat",
        "insult",
        "identity_hate",
    ]
    num_labels = 6
    max_len = 512

    # ====================================================
    # Model Architecture Settings
    # ====================================================
