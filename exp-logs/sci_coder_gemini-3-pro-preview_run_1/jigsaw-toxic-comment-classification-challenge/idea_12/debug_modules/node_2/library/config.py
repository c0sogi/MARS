    # Stage 2: Teacher Training (Supervised + AWP)
    # ====================================================
    run_teacher = True
    teacher_epochs = 5
    teacher_lr = 2e-5

    # Adversarial Weight Perturbation (AWP)
    use_awp = True
    awp_start_epoch = 2
    awp_lr = 1e-4
    awp_eps = 1e-2

    # ====================================================
    # Stage 3: Student Training (Self-Distillation + R-Drop)
    # ====================================================
    run_student = True
    student_epochs = 5
    student_lr = 2e-5

    # R-Drop (Consistency Regularization)
    use_rdrop = True
    rdrop_alpha = 4.0

    # Pseudo-labeling
