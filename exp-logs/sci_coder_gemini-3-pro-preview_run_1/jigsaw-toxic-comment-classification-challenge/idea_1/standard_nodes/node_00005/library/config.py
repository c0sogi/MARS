import os
import torch


class Config:
    # ==========================================
    # System & Environment
    # ==========================================
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4  # Number of dataloader workers

    # ==========================================
    # File Paths
    # ==========================================
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"
    SUBMISSION_DIR = "./submission"

    # Metadata paths (generated by the metadata script)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Raw data paths (for text content)
    RAW_TRAIN_PATH = os.path.join(INPUT_DIR, "train.csv")
    RAW_TEST_PATH = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output paths
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache directory for processed data
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_1")

    # ==========================================
    # Data Hyperparameters
    # ==========================================
    MAX_LEN = 200  # Sequence length for padding/truncating
    MAX_FEATURES = 100000  # Vocabulary size (top N frequent words)

    # Target Labels
    LABEL_COLS = [
        "toxic",
        "severe_toxic",
        "obscene",
        "threat",
        "insult",
        "identity_hate",
    ]
    NUM_CLASSES = len(LABEL_COLS)

    # ==========================================
    # Model Hyperparameters
    # ==========================================
    EMBED_DIM = 300  # Dimension of word embeddings
    HIDDEN_DIM = 128  # Hidden dimension for GRU
    NUM_LAYERS = 2  # Number of GRU layers
    DROPOUT = 0.3  # Dropout rate (spatial and dense)

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 256  # Optimized for A100 GPU
    EPOCHS = 6  # Number of training epochs
    LEARNING_RATE = 1e-3  # Adam optimizer learning rate
    PATIENCE = 2  # Early stopping patience

    # ==========================================
    # Debug / Development
    # ==========================================
    DEBUG = False  # Set to True to run on a small subset
    DEBUG_SAMPLE_SIZE = 1000  # Number of samples to use in debug mode

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print("=" * 40)
        print("CONFIG")
        print("=" * 40)
        for k, v in cls.__dict__.items():
            if not k.startswith("__") and not callable(v):
                print(f"{k:<20}: {v}")
        print("=" * 40)


# Create necessary directories
os.makedirs(Config.WORKING_DIR, exist_ok=True)
os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
os.makedirs(Config.CACHE_DIR, exist_ok=True)
