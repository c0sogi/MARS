import os
import torch


class Config:
    """
    Configuration class for the Attribute-Augmented Attention Network (Idea 5).
    Stores hyperparameters, file paths, and model constants.
    """

    # --------------------------------------------------------------------------
    # System & Device Settings
    # --------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4  # Optimized for 12 vCPUs
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # --------------------------------------------------------------------------
    # Directory & File Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_5"
    SUBMISSION_DIR = "./submission"

    # Input Metadata (Generated by previous steps)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Files
    TOKENIZER_PATH = os.path.join(WORKING_DIR, "tokenizer.json")
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Caching paths for deterministic data processing
    # Stores precomputed attribute targets and normalization stats
    TRAIN_ATTR_CACHE = os.path.join(WORKING_DIR, "train_attributes.npy")
    VAL_ATTR_CACHE = os.path.join(WORKING_DIR, "val_attributes.npy")
    ATTR_STATS_CACHE = os.path.join(WORKING_DIR, "attr_stats.npy")

    # --------------------------------------------------------------------------
    # Data & Image Preprocessing
    # --------------------------------------------------------------------------
    IMAGE_SIZE = 256  # Resizing target for Encoder
    IN_CHANNELS = 3  # RGB channels for EfficientNet backbone

    # ImageNet Normalization Statistics
    MEAN = [0.485, 0.456, 0.406]
    STD = [0.229, 0.224, 0.225]

    # --------------------------------------------------------------------------
    # Text & Tokenizer Constants
    # --------------------------------------------------------------------------
    MAX_LEN = 450  # Safe upper bound (Max observed in EDA was ~403)
    SOS_TOKEN = "<sos>"
    EOS_TOKEN = "<eos>"
    PAD_TOKEN = "<pad>"
    UNK_TOKEN = "<unk>"

    # --------------------------------------------------------------------------
    # Attribute Branch Configuration
    # --------------------------------------------------------------------------
    # Specific atoms to track for the auxiliary regression task
    TRACKED_ATOMS = ["C", "H", "O", "N", "S", "F", "Cl", "Br", "I"]

    # Total size of the attribute vector: Count of each atom + 1 for Sequence Length
    NUM_ATTRIBUTES = len(TRACKED_ATOMS) + 1

    # --------------------------------------------------------------------------
    # Model Architecture
    # --------------------------------------------------------------------------
    ENCODER_NAME = "efficientnet_b0"  # Stronger backbone than MobileNet
    EMBED_DIM = 256  # Dimension for character embeddings
    DECODER_DIM = 512  # Hidden state size of the LSTM Decoder
    ATTENTION_DIM = 256  # Dimension for Bahdanau Attention
    DROPOUT = 0.5

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    DEBUG = False  # Set to True to run on a small subset
    DEBUG_SAMPLE_SIZE = 1000  # Number of samples if DEBUG is True

    BATCH_SIZE = 64
    EPOCHS = 15
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-6
    CLIP_GRAD = 5.0  # Gradient clipping threshold
    TEACHER_FORCING_RATIO = 0.5

    # Multi-Task Loss Weighting
    # Total Loss = CrossEntropy + (LOSS_LAMBDA * MSE)
    # Targets are Z-normalized, so scales are comparable; lambda=1.0 is effective.
    LOSS_LAMBDA = 1.0

    def __init__(self):
        """
        Initialize the configuration.
        Ensures that necessary working directories exist.
        """
        os.makedirs(self.WORKING_DIR, exist_ok=True)
        os.makedirs(self.SUBMISSION_DIR, exist_ok=True)
