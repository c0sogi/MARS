import os
import torch


class Config:
    """
    Configuration module for Idea 8: Coordinate Attention Time-Preserving ResNet-18 CRNN.
    Centralizes all hyperparameters, file paths, and hardware settings.
    """

    # --------------------------------------------------------------------------
    # General & Reproducibility
    # --------------------------------------------------------------------------
    PROJECT_NAME = "idea_8"
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLES = 200  # Number of samples to use when DEBUG is True

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Audio Directories (Read-Only)
    TRAIN_AUDIO_DIR = os.path.join(INPUT_ROOT, "train2")
    TEST_AUDIO_DIR = os.path.join(INPUT_ROOT, "test2")

    # Metadata CSVs (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Working Directory (Write Allowed)
    # Used for caching processed data (npy/parquet) and saving model checkpoints
    WORK_DIR = os.path.join("./working", PROJECT_NAME)

    # Submission Directory
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Model Checkpoint Path
    BEST_MODEL_PATH = os.path.join(WORK_DIR, "best_model.pth")

    # --------------------------------------------------------------------------
    # Audio Preprocessing Parameters
    # --------------------------------------------------------------------------
    SAMPLE_RATE = 2000
    DURATION = 2.0  # Seconds (Full clip duration)
    N_MELS = 128  # Number of Mel frequency bins
    N_FFT = 1024  # FFT window size
    HOP_LENGTH = 32  # Stride for STFT (results in ~125 time frames for 2s)
    F_MIN = 20  # Minimum frequency
    F_MAX = 1000  # Maximum frequency (Nyquist limit for 2kHz SR)

    # --------------------------------------------------------------------------
    # Data Augmentation
    # --------------------------------------------------------------------------
    MIXUP_ALPHA = 0.4

    # SpecAugment Constraints
    # Time Masking: Max 200ms constraint.
    # Calculation: 200ms = 0.2s. Samples = 0.2 * 2000 = 400.
    # Frames = 400 samples / 32 hop_length = 12.5 frames.
    TIME_MASK_PARAM = 12
    FREQ_MASK_PARAM = 20

    # --------------------------------------------------------------------------
    # Model Architecture
    # --------------------------------------------------------------------------
    IN_CHANNELS = 1  # Input channels (1 for mono spectrogram)
    NUM_CLASSES = 1  # Binary classification (Whale vs Noise)

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    BATCH_SIZE = 64
    EPOCHS = 30
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Class Imbalance Handling
    # Approx 1:9 ratio (1813 pos / 16340 neg)
    POS_WEIGHT = 9.0

    # Scheduler (ReduceLROnPlateau)
    SCHEDULER_PATIENCE = 3
    SCHEDULER_FACTOR = 0.5

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 7

    # --------------------------------------------------------------------------
    # Hardware / Compute
    # --------------------------------------------------------------------------
    NUM_WORKERS = 4
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    @classmethod
    def setup(cls):
        """
        Ensures necessary working and submission directories exist.
        Should be called implicitly on import or explicitly before operations.
        """
        os.makedirs(cls.WORK_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Automatically setup directories when config is imported
Config.setup()
