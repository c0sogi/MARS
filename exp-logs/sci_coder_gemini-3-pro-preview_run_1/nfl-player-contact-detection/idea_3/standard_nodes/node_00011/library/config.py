import os
import torch
import numpy as np
import random


def set_seed(seed=42):
    """Sets the seed for reproducibility across all libraries."""
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


class Config:
    # -------------------------------------------------------------------------
    # Global Configuration
    # -------------------------------------------------------------------------
    SEED = 42
    WINDOW_SIZE = 10  # +/- 10 frames (total 21 frames, ~2.1s context)

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_3"
    SUBMISSION_DIR = "./submission"

    # Metadata Paths (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Raw Tracking Data
    TRAIN_TRACKING_PATH = os.path.join(INPUT_DIR, "train_player_tracking.csv")
    TEST_TRACKING_PATH = os.path.join(INPUT_DIR, "test_player_tracking.csv")

    # Submission Paths
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Feature Engineering
    # -------------------------------------------------------------------------
    # Base columns to extract from raw tracking data
    TRACKING_COLS = [
        "x_position",
        "y_position",
        "speed",
        "direction",
        "orientation",
        "acceleration",
        "sa",
    ]

    # Stream B Features (Impact Model)
    STREAM_B_FEATURES = TRACKING_COLS + ["jerk"]

    # Unified Model Features (Player-Player + Player-Ground)
    # Features will be flattened: [feat_t-10, ..., feat_t+10]
    STREAM_A_FEATURES = [
        "distance",
        "speed_diff",
        "acc_diff",
        "orientation_diff",
        "direction_diff",
        "is_ground",  # Indicator for interaction type (Cite Lesson 00007)
    ]

    # -------------------------------------------------------------------------
    # Model Hyperparameters
    # -------------------------------------------------------------------------

    # Unified LightGBM
    LGBM_PARAMS = {
        "objective": "binary",
        "metric": "binary_logloss",
        "boosting_type": "gbdt",
        "learning_rate": 0.02,
        "num_leaves": 63,  # Adjusted for info density (Cite Lesson 00003)
        "max_depth": -1,
        "feature_fraction": 0.8,
        "bagging_fraction": 0.8,
        "bagging_freq": 5,
        "min_child_samples": 50,
        "verbosity": -1,
        "n_jobs": -1,
        "seed": SEED,
        "is_unbalance": True,  # Auto-handle imbalance (Cite Lesson 00007)
    }

    LGBM_TRAIN_PARAMS = {
        "num_boost_round": 5000,
        "early_stopping_rounds": 100,
        "verbose_eval": 100,
    }

    # Stream B: 1D-ResNet (Impact)
    CNN_PARAMS = {
        "input_channels": len(STREAM_B_FEATURES),
        "seq_length": WINDOW_SIZE * 2 + 1,  # 21 frames
        "hidden_dim": 64,
        "kernel_size": 3,
        "dropout": 0.3,
        "num_classes": 1,
    }

    CNN_TRAIN_PARAMS = {
        "batch_size": 1024,
        "epochs": 20,
        "learning_rate": 1e-3,
        "weight_decay": 1e-4,
        "device": "cuda" if torch.cuda.is_available() else "cpu",
        "num_workers": 4,
    }

    @staticmethod
    def setup():
        """Initializes directories and sets random seeds."""
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
        set_seed(Config.SEED)


# Initialize environment on module import
Config.setup()
