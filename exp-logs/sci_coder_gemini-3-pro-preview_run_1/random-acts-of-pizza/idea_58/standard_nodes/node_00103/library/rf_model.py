import os
import joblib
import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import roc_auc_score
from library.config import Config


class MultiInteractionRF:
    """
    Stream A: Multi-Interaction Top-K Random Forest.

    This model consumes the feature vector generated by library.features.py,
    which includes:
    1. High-Fidelity TF-IDF
    2. Full-Spectrum Metadata
    3. Top-K Binary Community Indicators
    4. Global Consistency Scalars
    5. Sentiment Scores
    6. Multi-Axis Interaction Block (Consistency x Credibility, etc.)
    """

    def __init__(self):
        self.model_path = Config.MODEL_RF_PATH
        self.model = None

        # Hyperparameters from Config
        self.n_estimators = Config.RF_N_ESTIMATORS
        self.max_depth = Config.RF_MAX_DEPTH
        self.min_samples_leaf = Config.RF_MIN_SAMPLES_LEAF
        self.class_weight = Config.RF_CLASS_WEIGHT
        self.n_jobs = Config.RF_N_JOBS
        self.random_state = Config.RANDOM_SEED

    def train(self, X_train, y_train, X_val=None, y_val=None):
        """
        Trains the Random Forest classifier and saves the artifact.

        Args:
            X_train (np.ndarray): Training features.
            y_train (np.ndarray): Training labels.
            X_val (np.ndarray, optional): Validation features.
            y_val (np.ndarray, optional): Validation labels.
        """
        print(
            f"Initializing Random Forest with n_estimators={self.n_estimators}, "
            f"max_depth={self.max_depth}, min_samples_leaf={self.min_samples_leaf}..."
        )

        self.model = RandomForestClassifier(
            n_estimators=self.n_estimators,
            max_depth=self.max_depth,
            min_samples_leaf=self.min_samples_leaf,
            class_weight=self.class_weight,
            n_jobs=self.n_jobs,
            random_state=self.random_state,
            verbose=0,
        )

        print("Fitting Random Forest model...")
        self.model.fit(X_train, y_train)

        # Validation
        if X_val is not None and y_val is not None:
            print("Validating Random Forest model...")
            # Predict probabilities for the positive class (column 1)
            y_pred_proba = self.model.predict_proba(X_val)[:, 1]
            auc = roc_auc_score(y_val, y_pred_proba)
            print(f"Random Forest Validation ROC AUC: {auc}")

        # Save model
        self._save_model()

    def predict(self, X):
        """
        Generates probability predictions for the positive class.

        Args:
            X (np.ndarray): Feature matrix.

        Returns:
            np.ndarray: Probabilities of receiving pizza.
        """
        if self.model is None:
            self._load_model()

        if self.model is None:
            raise RuntimeError("Model not trained or loaded.")

        # Return probabilities for class 1 (True)
        return self.model.predict_proba(X)[:, 1]

    def _save_model(self):
        """Saves the trained model to disk."""
        os.makedirs(os.path.dirname(self.model_path), exist_ok=True)
        joblib.dump(self.model, self.model_path)
        print(f"Random Forest model saved to {self.model_path}")

    def _load_model(self):
        """Loads the model from disk if available."""
        if os.path.exists(self.model_path):
            print(f"Loading Random Forest model from {self.model_path}...")
            self.model = joblib.load(self.model_path)
        else:
            print(f"No trained model found at {self.model_path}")
