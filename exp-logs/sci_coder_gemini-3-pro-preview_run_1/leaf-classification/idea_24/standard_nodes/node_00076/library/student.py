import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import log_loss
from library import config, utils


class SyntheticStudent:
    """
    The Student model: A Multinomial Logistic Regression classifier.

    It is designed to be trained on synthetic data generated by the Teacher to
    optimize the decision boundaries for Log Loss, utilizing the robust
    covariance structure learned by OAS-LDA.
    """

    def __init__(self):
        """
        Initializes the Logistic Regression model with configurations for
        high-precision optimization.
        """
        # Initialize the sklearn LogisticRegression model
        # We use warm_start=True to allow manual weight initialization
        self.model = LogisticRegression(
            penalty="l2",
            C=config.C_STUDENT,
            solver=config.SOLVER,
            multi_class="multinomial",
            max_iter=config.MAX_ITER,
            tol=config.TOL,
            fit_intercept=True,
            warm_start=True,
            n_jobs=-1,
            random_state=config.RANDOM_SEED,
        )
        self.classes_ = None

    def fit(self, X_train, y_train, X_val=None, y_val=None, teacher=None):
        """
        Fits the student model to the provided training data (typically synthetic).

        Args:
            X_train (np.ndarray): Training features (synthetic or real).
            y_train (np.ndarray): Training labels.
            X_val (np.ndarray, optional): Validation features for monitoring.
            y_val (np.ndarray, optional): Validation labels.
            teacher (OASTeacher, optional): The trained teacher instance.
                                            If provided, analytic weights are used
                                            to initialize the student.
        """
        # Enforce float64 precision for training data
        X_train = utils.enforce_float64(X_train)

        # Identify unique classes
        self.classes_ = np.unique(y_train)

        # Analytic Initialization (Transfer Learning from Teacher)
        # If a teacher is provided, we inject its analytic solution as the starting point.
        # This helps the optimization start from a robust location on the manifold.
        if teacher is not None:
            print("Initializing Student weights with Teacher's analytic solution...")
            try:
                # Get analytic weights from the teacher
                coef_init, intercept_init = teacher.get_analytic_weights()

                # Manually set the attributes on the sklearn estimator
                # warm_start=True in __init__ allows fit() to respect these if shapes match
                self.model.classes_ = self.classes_
                self.model.coef_ = coef_init
                self.model.intercept_ = intercept_init

                # Note: We do not check for shape mismatch here; we assume the teacher
                # was trained on the same feature set (192 dims) and class set (99 classes).
            except Exception as e:
                print(
                    f"Warning: Failed to initialize weights from Teacher. Proceeding with random init. Error: {e}"
                )

        # Fit the model
        # If weights were injected, lbfgs will use them as the starting point.
        print(f"Training Student on {len(X_train)} samples...")
        self.model.fit(X_train, y_train)

        # Validation Evaluation
        if X_val is not None and y_val is not None:
            print("Evaluating Student on Validation Set...")
            self.evaluate(X_val, y_val)

        return self

    def predict_proba(self, X):
        """
        Predicts class probabilities for the input samples.

        Args:
            X (np.ndarray): Input features.

        Returns:
            np.ndarray: Predicted probabilities (n_samples, n_classes).
        """
        # Enforce float64 precision
        X = utils.enforce_float64(X)

        # Predict probabilities
        probs = self.model.predict_proba(X)

        # Enforce float64 on output
        probs = utils.enforce_float64(probs)

        # Clip probabilities to avoid log(0) and ensure compliance with metric
        # Although utils.calculate_log_loss does this, we do it here to ensure
        # all outputs from the student are safe.
        probs = np.clip(probs, config.PROB_CLIP_MIN, config.PROB_CLIP_MAX)

        return probs

    def evaluate(self, X, y):
        """
        Evaluates the model on a dataset using the competition metric.

        Args:
            X (np.ndarray): Features.
            y (np.ndarray): True labels.

        Returns:
            float: Multi-class Log Loss.
        """
        # Generate predictions
        probs = self.predict_proba(X)

        # Calculate metric using the utility function which handles rescaling/clipping
        # We pass self.model.classes_ to ensure correct column mapping
        loss = utils.calculate_log_loss(y, probs, self.model.classes_)

        return loss


def train_student_on_synthetic(teacher, X_syn, y_syn, X_val=None, y_val=None):
    """
    Orchestrates the training of the Student model on synthetic data.

    Args:
        teacher (OASTeacher): The trained teacher instance (for initialization).
        X_syn (np.ndarray): Synthetic training features.
        y_syn (np.ndarray): Synthetic training labels.
        X_val (np.ndarray, optional): Real validation features.
        y_val (np.ndarray, optional): Real validation labels.

    Returns:
        SyntheticStudent: The trained student model.
    """
    student = SyntheticStudent()

    # Train the student
    # We pass the teacher to allow for analytic weight initialization
    student.fit(X_syn, y_syn, X_val=X_val, y_val=y_val, teacher=teacher)

    return student
