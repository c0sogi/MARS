import os
import numpy as np

# =============================================================================
# GLOBAL PATHS & DIRECTORIES
# =============================================================================
INPUT_DIR = "./input"
METADATA_DIR = "./metadata"
IMAGES_DIR = os.path.join(INPUT_DIR, "images")

# Working directory for this specific idea/experiment
# We use idea_45 to denote the "Moment-Completed High-Precision OAS Discriminant"
# This directory is used for caching extracted features and intermediate artifacts.
WORKING_DIR = "./working/idea_45"
os.makedirs(WORKING_DIR, exist_ok=True)

# =============================================================================
# REPRODUCIBILITY & PRECISION
# =============================================================================
RANDOM_SEED = 42

# Enforce float64 for high-precision linear algebra.
# This is critical for the OAS estimator and matrix inversions to avoid
# spectral truncation issues observed in lower precision.
FLOAT_PRECISION = np.float64

# =============================================================================
# DATASET CONFIGURATION
# =============================================================================
# Metadata file paths generated by the metadata script
TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

# Column names
TARGET_COL = "species"
ID_COL = "id"
FILE_PATH_COL = "file_path"

# =============================================================================
# FEATURE CONFIGURATION
# =============================================================================
# 1. Pre-extracted Tabular Features (64 attributes each)
# These are provided in the dataset and used as part of the feature vector.
MARGIN_COLS = [f"margin{i}" for i in range(1, 65)]
SHAPE_COLS = [f"shape{i}" for i in range(1, 65)]
TEXTURE_COLS = [f"texture{i}" for i in range(1, 65)]

TABULAR_FEATURE_COLS = MARGIN_COLS + SHAPE_COLS + TEXTURE_COLS

# 2. Extracted Image Features (Moment-Completed Geometric Fusion)
# We define specific keys for features to be extracted from the binary images.

# Absolute Moments (Scale/Inertia) - Preserving biological size signal
FEAT_IMG_AREA = "img_area"
FEAT_IMG_MAJOR_AXIS = "img_major_axis_length"
FEAT_IMG_MINOR_AXIS = "img_minor_axis_length"

# Relative Moments (Shape)
FEAT_IMG_ECCENTRICITY = "img_eccentricity"

# Invariant Moments (Structure) - Hu Moments 1-7
# These capture orthogonal asymmetry and kurtosis.
# They will be log-modulus transformed during preprocessing.
FEAT_IMG_HU_MOMENTS = [f"img_hu_moment_{i}" for i in range(1, 8)]

# Boundary/Hull Integrals - Robust shape descriptors
FEAT_IMG_PERIMETER = "img_perimeter"
FEAT_IMG_CONVEX_PERIMETER = "img_convex_perimeter"
FEAT_IMG_SOLIDITY = "img_solidity"
FEAT_IMG_ROUNDNESS = "img_roundness"

# Stable Extrema (Axis-Aligned) - Retained from previous successful iterations
FEAT_IMG_ASPECT_RATIO = "img_aspect_ratio"
FEAT_IMG_EXTENT = "img_extent"

# Combined list of image features to extract
IMAGE_FEATURE_COLS = [
    FEAT_IMG_AREA,
    FEAT_IMG_MAJOR_AXIS,
    FEAT_IMG_MINOR_AXIS,
    FEAT_IMG_ECCENTRICITY,
    FEAT_IMG_PERIMETER,
    FEAT_IMG_CONVEX_PERIMETER,
    FEAT_IMG_SOLIDITY,
    FEAT_IMG_ROUNDNESS,
    FEAT_IMG_ASPECT_RATIO,
    FEAT_IMG_EXTENT,
] + FEAT_IMG_HU_MOMENTS

# =============================================================================
# CACHING CONFIGURATION
# =============================================================================
# Cache file paths (Parquet for tabular data, ensuring float64 preservation).
# We append a version suffix to ensure we don't load stale data from previous experiments.
CACHE_VERSION = "v_moment_completed_01"
CACHE_TRAIN_PATH = os.path.join(WORKING_DIR, f"train_features_{CACHE_VERSION}.parquet")
CACHE_VAL_PATH = os.path.join(WORKING_DIR, f"val_features_{CACHE_VERSION}.parquet")
CACHE_TEST_PATH = os.path.join(WORKING_DIR, f"test_features_{CACHE_VERSION}.parquet")

# =============================================================================
# MODEL HYPERPARAMETERS
# =============================================================================
# Oracle Approximating Shrinkage (OAS) parameters
OAS_PARAMS = {
    "assume_centered": True,  # We manually center data using class means for precision
}

# Preprocessing parameters
# Yeo-Johnson transformation is crucial for stabilizing the variance of geometric features
PREPROCESS_POWER_METHOD = "yeo-johnson"

# Debugging
DEBUG_SAMPLE_SIZE = None  # Set to None for full run, or int (e.g., 50) for debugging

