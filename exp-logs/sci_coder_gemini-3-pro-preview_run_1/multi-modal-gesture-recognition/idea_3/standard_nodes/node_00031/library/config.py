import os
import random
import numpy as np
import torch


class Config:
    """
    Configuration for the Multi-Scale Decoupled Inception-GRU (MS-DIG) solution.
    Defines global constants, paths, and hyperparameters.
    """

    # =========================================================================
    # 1. File System & Paths
    # =========================================================================
    ROOT_DIR = "."
    INPUT_DIR = os.path.join(ROOT_DIR, "input")
    METADATA_DIR = os.path.join(ROOT_DIR, "metadata")
    WORKING_DIR = os.path.join(ROOT_DIR, "working", "idea_3")
    SUBMISSION_DIR = os.path.join(ROOT_DIR, "submission")

    # Metadata Inputs (Generated by metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Outputs
    BEST_MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    STATS_PATH = os.path.join(WORKING_DIR, "stats.npz")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Caching Directories (for deterministic data processing)
    CACHE_TRAIN_DIR = os.path.join(WORKING_DIR, "cache_train")
    CACHE_VAL_DIR = os.path.join(WORKING_DIR, "cache_val")
    CACHE_TEST_DIR = os.path.join(WORKING_DIR, "cache_test")

    # =========================================================================
    # 2. Data Parameters
    # =========================================================================
    SEED = 42

    # Skeleton: 20 joints, 3 coords (x,y,z) per joint
    NUM_JOINTS = 20
    COORDS_PER_JOINT = 3
    SKELETON_INPUT_SIZE = NUM_JOINTS * COORDS_PER_JOINT  # 60 features

    # Audio: MFCC features
    AUDIO_SAMPLE_RATE = 16000
    N_MFCC = 13
    AUDIO_INPUT_SIZE = N_MFCC

    # Temporal Resolution
    VIDEO_FPS = 20

    # Labels: 20 Gestures (1-20) + 1 Background (0)
    NUM_CLASSES = 21
    BACKGROUND_CLASS_IDX = 0

    # =========================================================================
    # 3. Model Architecture (MS-DIG)
    # =========================================================================
    # Multi-Scale Inception Block Kernels
    INCEPTION_KERNELS = [3, 7, 11]
    STEM_KERNEL_SIZE = 7

    # Recurrent Core
    HIDDEN_SIZE = 256
    NUM_GRU_LAYERS = 2
    BIDIRECTIONAL = True
    DROPOUT = 0.5

    # =========================================================================
    # 4. Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 8
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    NUM_EPOCHS = 50
    EARLY_STOPPING_PATIENCE = 10

    # Loss Function Configuration
    LABEL_SMOOTHING = 0.1
    BACKGROUND_LOSS_WEIGHT = 0.5  # Down-weight the dominant background class

    # =========================================================================
    # 5. Augmentation & Preprocessing
    # =========================================================================
    # Random Channel Masking
    AUG_MASK_PROB = 0.5
    AUG_MASK_RATIO = 0.1

    # Additive Gaussian Noise (Skeleton)
    AUG_NOISE_SIGMA = 0.01

    # =========================================================================
    # 6. Inference & Post-Processing
    # =========================================================================
    MEDIAN_FILTER_KERNEL = 7
    MIN_GESTURE_LENGTH = 5  # Filter out gestures shorter than this

    # =========================================================================
    # 7. Hardware & Optimization
    # =========================================================================
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @staticmethod
    def setup_environment():
        """
        Initializes the working environment:
        1. Creates necessary directories.
        2. Sets random seeds for full reproducibility.
        """
        # Create Directories
        dirs = [
            Config.WORKING_DIR,
            Config.SUBMISSION_DIR,
            Config.CACHE_TRAIN_DIR,
            Config.CACHE_VAL_DIR,
            Config.CACHE_TEST_DIR,
        ]
        for d in dirs:
            os.makedirs(d, exist_ok=True)

        # Set Random Seeds
        random.seed(Config.SEED)
        np.random.seed(Config.SEED)
        torch.manual_seed(Config.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(Config.SEED)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
