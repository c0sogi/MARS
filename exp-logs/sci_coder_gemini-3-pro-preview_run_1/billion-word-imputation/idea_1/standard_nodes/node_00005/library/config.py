import os
import random
import numpy as np
import torch


class Config:
    """
    Configuration class for the Sentence Infilling Task.
    Centralizes hyperparameters, paths, and constants for the Gated Convolutional Sequence Labeler.
    """

    # --------------------------------------------------------------------------
    # Reproducibility
    # --------------------------------------------------------------------------
    SEED = 42

    # --------------------------------------------------------------------------
    # File Systems & Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata paths (generated by the provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Working directory for artifacts (vocab, model checkpoints)
    # Using 'idea_2' as the experiment identifier to ensure fresh cache generation
    WORKING_DIR = "./working/idea_2"

    # Submission directory
    SUBMISSION_DIR = "./submission"
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Model and Vocab Artifacts
    VOCAB_FILE = os.path.join(WORKING_DIR, "vocab.npy")
    MODEL_FILE = os.path.join(WORKING_DIR, "best_model.pth")

    # --------------------------------------------------------------------------
    # Data Processing & Vocabulary
    # --------------------------------------------------------------------------
    VOCAB_SIZE = 60000
    MAX_SEQ_LEN = 128  # Covers the vast majority of sentences based on analysis

    # Special Tokens
    # [NO_INSERT]: Represents a gap where no word is missing (majority class)
    # [PAD]: Padding for batching
    # [UNK]: Unknown words
    TOKEN_PAD = "[PAD]"
    TOKEN_UNK = "[UNK]"
    TOKEN_NO_INSERT = "[NO_INSERT]"
    SPECIAL_TOKENS = [TOKEN_PAD, TOKEN_UNK, TOKEN_NO_INSERT]

    # Debugging / Development
    # Set to an integer (e.g., 50000) to limit dataset size for fast iteration/debugging.
    # Set to None to use the full dataset.
    DEBUG_SAMPLE_SIZE = None

    # --------------------------------------------------------------------------
    # Model Architecture (Gated CNN)
    # --------------------------------------------------------------------------
    EMBED_DIM = 512
    HIDDEN_DIM = 512
    KERNEL_SIZE = 3
    NUM_LAYERS = 8
    DROPOUT = 0.1

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    BATCH_SIZE = 2048  # Increased for A100 utilization
    NUM_EPOCHS = 20  # Upper bound, controlled by Early Stopping
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2
    GRAD_CLIP = 1.0

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 3

    # Loss Weighting
    # The [NO_INSERT] class dominates the targets (approx 95%+).
    # We apply a low scalar weight to this class in the CrossEntropyLoss.
    NO_INSERT_WEIGHT = 0.05

    # --------------------------------------------------------------------------
    # Hardware & Runtime
    # --------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 12  # Matches the 12 vCPUs provided

    @classmethod
    def setup(cls):
        """
        Ensures that the working and submission directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


def set_seed(seed=Config.SEED):
    """
    Sets the random seed for Python, NumPy, and PyTorch to ensure reproducibility.

    Args:
        seed (int): The seed value to use. Defaults to Config.SEED.
    """
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    # Enforce deterministic behavior for cuDNN
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False
