import os
import torch


class Config:
    """
    Configuration class for the Catheter Detection task.
    Centralizes all hyperparameters, file paths, and model settings.
    """

    # ==========================
    # General Settings
    # ==========================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 100  # Number of samples to use in debug mode

    # ==========================
    # Compute
    # ==========================
    NUM_WORKERS = 12
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    USE_AMP = True  # Automatic Mixed Precision

    # ==========================
    # Data Paths
    # ==========================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the provided script
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output directories
    WORKING_DIR = "./working/idea_2"
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================
    # Data Configuration
    # ==========================
    IMAGE_SIZE = 768  # High resolution as per idea
    NUM_CLASSES = 11

    # Target columns in specific order
    TARGET_COLS = [
        "ETT - Abnormal",
        "ETT - Borderline",
        "ETT - Normal",
        "NGT - Abnormal",
        "NGT - Borderline",
        "NGT - Incompletely Imaged",
        "NGT - Normal",
        "CVC - Abnormal",
        "CVC - Borderline",
        "CVC - Normal",
        "Swan Ganz Catheter Present",
    ]

    # ==========================
    # Model Configuration
    # ==========================
    MODEL_NAME = "tf_efficientnet_b4"
    USE_GEM_POOLING = True
    PRETRAINED = True
    DROPOUT_RATE = 0.2  # Default head dropout

    # ==========================
    # Training Hyperparameters
    # ==========================
    EPOCHS = 12
    TRAIN_BATCH_SIZE = 8  # Conservative batch size for 768x768 on A100
    VALID_BATCH_SIZE = 16

    # Optimizer & Scheduler
    LEARNING_RATE = 1e-4  # Constant LR
    OPTIMIZER = "AdamW"
    WEIGHT_DECAY = 1e-2
    MAX_GRAD_NORM = 1000
    SCHEDULER = "Constant"  # Explicitly requested constant LR

    # Loss
    LOSS_FN = "BCEWithLogitsLoss"
    USE_POS_WEIGHT = True  # Weighted loss for class imbalance

    # ==========================
    # Augmentation
    # ==========================
    USE_COARSE_DROPOUT = True
    HORIZONTAL_FLIP = True  # Used for TTA and training

    def __init__(self, epochs=None, debug=None):
        """
        Initialize configuration and ensure necessary directories exist.
        Allows overriding epochs and debug mode for flexibility.
        """
        if epochs is not None:
            self.EPOCHS = epochs
        if debug is not None:
            self.DEBUG = debug

        os.makedirs(self.WORKING_DIR, exist_ok=True)
        os.makedirs(self.SUBMISSION_DIR, exist_ok=True)
