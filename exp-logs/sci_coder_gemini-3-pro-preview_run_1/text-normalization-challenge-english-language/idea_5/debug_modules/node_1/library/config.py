import os
import torch
import random
import numpy as np


class Config:
    """
    Central configuration for the Text Normalization task.
    Implements the 'Morphologically-Aware Bi-LSTM Tagger with Neural Fallback' strategy.
    """

    # --------------------------------------------------------------------------
    # General Configuration
    # --------------------------------------------------------------------------
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4  # Number of workers for DataLoaders

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_5"
    SUBMISSION_DIR = "./submission"

    # Input Metadata (Generated by metadata script)
    TRAIN_DATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_DATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_DATA_PATH = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "en_sample_submission_2.csv")

    # Ensure working and submission directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Cache Files (Parquet for dataframes, NPY/Parquet for vocabs)
    # These store processed artifacts to speed up subsequent runs
    VOCAB_WORDS_PATH = os.path.join(WORKING_DIR, "vocab_words.parquet")
    VOCAB_CHARS_PATH = os.path.join(WORKING_DIR, "vocab_chars.parquet")
    VOCAB_CLASSES_PATH = os.path.join(WORKING_DIR, "vocab_classes.parquet")
    KNOWLEDGE_BASE_PATH = os.path.join(WORKING_DIR, "knowledge_base.parquet")

    # Grouped Dataframes (Sentence-level grouping)
    TRAIN_GROUPED_PATH = os.path.join(WORKING_DIR, "train_grouped.parquet")
    VAL_GROUPED_PATH = os.path.join(WORKING_DIR, "val_grouped.parquet")
    TEST_GROUPED_PATH = os.path.join(WORKING_DIR, "test_grouped.parquet")

    # Model Checkpoints
    TAGGER_MODEL_PATH = os.path.join(WORKING_DIR, "tagger_best_model.pth")
    SEQ2SEQ_MODEL_PATH = os.path.join(WORKING_DIR, "seq2seq_best_model.pth")

    # Final Submission Output
    SUBMISSION_OUTPUT_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Data Processing Parameters
    # --------------------------------------------------------------------------
    # Vocabulary Limits
    MAX_VOCAB_SIZE = 60000  # Max words to keep in vocabulary
    MIN_FREQ = 2  # Minimum frequency for a word to be included

    # Sequence Lengths
    MAX_SEQ_LEN = 128  # Maximum tokens per sentence for Tagger
    MAX_CHAR_LEN = 20  # Maximum characters per token for CNN

    # Seq2Seq Specific Data Params
    SEQ2SEQ_MAX_LEN = 64  # Maximum length of generated normalized text

    # Special Tokens
    PAD_TOKEN = "<PAD>"
    UNK_TOKEN = "<UNK>"
    SOS_TOKEN = "<SOS>"
    EOS_TOKEN = "<EOS>"

    # --------------------------------------------------------------------------
    # Model Hyperparameters: Morphologically-Aware Tagger
    # --------------------------------------------------------------------------
    # Embedding Layers
    TAGGER_EMBED_DIM = 256
    TAGGER_CHAR_EMBED_DIM = 50

    # Character CNN
    TAGGER_CHAR_CNN_FILTERS = 50
    TAGGER_CHAR_CNN_KERNEL_SIZE = 3

    # Bi-LSTM Encoder
    TAGGER_HIDDEN_DIM = 512
    TAGGER_NUM_LAYERS = 2
    TAGGER_DROPOUT = 0.3
    TAGGER_BIDIRECTIONAL = True

    # Loss Function Configuration
    CLASS_WEIGHT_SMOOTHING_ALPHA = 0.5  # Power for sqrt smoothing of class weights

    # --------------------------------------------------------------------------
    # Model Hyperparameters: Seq2Seq Fallback
    # --------------------------------------------------------------------------
    SEQ2SEQ_EMBED_DIM = 128
    SEQ2SEQ_HIDDEN_DIM = 256
    SEQ2SEQ_DROPOUT = 0.2
    SEQ2SEQ_TEACHER_FORCING_RATIO = 0.5

    # --------------------------------------------------------------------------
    # Training Configuration
    # --------------------------------------------------------------------------
    # General Training
    BATCH_SIZE = 128  # Batch size for Tagger (A100 can handle this)
    NUM_EPOCHS = 15  # Maximum training epochs
    LEARNING_RATE = 1e-3  # Initial learning rate
    WEIGHT_DECAY = 1e-5  # L2 Regularization
    CLIP_GRAD = 1.0  # Gradient clipping threshold

    # Learning Rate Scheduler
    SCHEDULER_FACTOR = 0.5  # Factor to reduce LR by
    SCHEDULER_PATIENCE = 1  # Epochs with no improvement before reducing LR

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 3  # Epochs with no improvement before stopping

    # Seq2Seq Specific Training
    SEQ2SEQ_BATCH_SIZE = 128
    SEQ2SEQ_EPOCHS = 20  # Seq2Seq might need more epochs to converge on characters

    @staticmethod
    def set_seed(seed=42):
        """
        Sets the random seed for reproducibility across Python, NumPy, and PyTorch.
        """
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
        os.environ["PYTHONHASHSEED"] = str(seed)


# Automatically set seed on import
Config.set_seed(Config.SEED)
