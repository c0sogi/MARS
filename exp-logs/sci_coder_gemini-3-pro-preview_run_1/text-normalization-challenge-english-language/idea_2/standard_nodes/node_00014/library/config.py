import os
import torch


class Config:
    """
    Central configuration for the Context-Aware Transformer Tagger project.
    """

    # --------------------------------------------------------------------------
    # Reproducibility
    # --------------------------------------------------------------------------
    SEED = 42

    # --------------------------------------------------------------------------
    # File Paths & Directories
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_2"
    SUBMISSION_DIR = "./submission"

    # Input Data Files (Generated by metadata script)
    TRAIN_FILE = os.path.join(METADATA_DIR, "train.csv")
    VAL_FILE = os.path.join(METADATA_DIR, "val.csv")
    TEST_FILE = os.path.join(METADATA_DIR, "test.csv")

    # Cache Files (Parquet format for speed/efficiency)
    # These paths are used by the preprocessing module to save/load processed data
    CACHE_DIR = WORKING_DIR
    VOCAB_TOKENS_PATH = os.path.join(CACHE_DIR, "vocab_tokens.parquet")
    VOCAB_CLASSES_PATH = os.path.join(CACHE_DIR, "vocab_classes.parquet")
    TRAIN_GROUPED_PATH = os.path.join(CACHE_DIR, "train_grouped.parquet")
    VAL_GROUPED_PATH = os.path.join(CACHE_DIR, "val_grouped.parquet")
    TEST_GROUPED_PATH = os.path.join(CACHE_DIR, "test_grouped.parquet")
    KNOWLEDGE_BASE_PATH = os.path.join(CACHE_DIR, "knowledge_base.parquet")

    # Model & Submission Outputs
    MODEL_SAVE_PATH = os.path.join(CACHE_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Data Processing Parameters
    # --------------------------------------------------------------------------
    # Max tokens per sentence. EDA shows max length is 233, so 256 is safe.
    MAX_LEN = 256

    # Vocabulary settings
    MIN_FREQ = 2  # Minimum frequency for a token to be included in vocab
    UNK_TOKEN = "<UNK>"
    PAD_TOKEN = "<PAD>"

    # --------------------------------------------------------------------------
    # Model Architecture (Transformer Encoder)
    # --------------------------------------------------------------------------
    EMBED_DIM = 256
    N_HEADS = 4
    N_LAYERS = 3
    FF_DIM = 512
    DROPOUT = 0.1

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    BATCH_SIZE = 64
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-5
    NUM_EPOCHS = 10
    PATIENCE = 3  # For Early Stopping

    # --------------------------------------------------------------------------
    # Debugging & Runtime
    # --------------------------------------------------------------------------
    # Set DEBUG to True to run on a small subset of data for quick testing
    DEBUG = False
    DEBUG_SIZE = 5000  # Number of sentences to use in debug mode

    # --------------------------------------------------------------------------
    # Hardware
    # --------------------------------------------------------------------------
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4

    @classmethod
    def setup(cls):
        """
        Ensures that necessary working and submission directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Automatically setup directories when config is imported
Config.setup()
