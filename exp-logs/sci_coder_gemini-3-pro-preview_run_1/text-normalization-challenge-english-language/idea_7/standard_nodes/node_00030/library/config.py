import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration for the Text Normalization Task using:
    1. Attention-Augmented Bi-LSTM Tagger (Classification)
    2. Transformer-Based Seq2Seq (Fallback Generation)
    """

    # =========================================================================
    # EXPERIMENT SETUP
    # =========================================================================
    IDEA_ID = "idea_7"
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Number of subprocesses for data loading

    # =========================================================================
    # PATHS
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = f"./working/{IDEA_ID}"
    SUBMISSION_DIR = f"{WORKING_DIR}/submission"

    # Input Metadata Files (Generated by previous steps)
    TRAIN_FILE = os.path.join(METADATA_DIR, "train.csv")
    VAL_FILE = os.path.join(METADATA_DIR, "val.csv")
    TEST_FILE = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "en_sample_submission_2.csv")

    # Cache Files (Parquet/NPY for fast loading)
    TRAIN_GROUPED_PATH = os.path.join(WORKING_DIR, "train_grouped.parquet")
    VAL_GROUPED_PATH = os.path.join(WORKING_DIR, "val_grouped.parquet")
    TEST_GROUPED_PATH = os.path.join(WORKING_DIR, "test_grouped.parquet")

    # Artifacts
    KNOWLEDGE_BASE_PATH = os.path.join(WORKING_DIR, "knowledge_base.parquet")
    VOCAB_TOKENS_PATH = os.path.join(WORKING_DIR, "vocab_tokens.parquet")
    VOCAB_CHARS_PATH = os.path.join(WORKING_DIR, "vocab_chars.parquet")
    VOCAB_CLASSES_PATH = os.path.join(WORKING_DIR, "vocab_classes.parquet")

    # Model Checkpoints
    TAGGER_MODEL_PATH = os.path.join(WORKING_DIR, "tagger_best_model.pth")
    SEQ2SEQ_MODEL_PATH = os.path.join(WORKING_DIR, "seq2seq_best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # DATA PARAMETERS
    # =========================================================================
    # Tagger Limits
    MAX_SEQ_LEN = 128  # Maximum tokens per sentence for the Tagger
    MAX_VOCAB_SIZE = 60000  # Max size for word embedding vocabulary
    MIN_FREQ = 2  # Minimum frequency for a token to be included in vocab

    # Seq2Seq Limits
    MAX_CHAR_LEN = 128  # Maximum characters per token for Seq2Seq generation

    # Special Tokens
    PAD_TOKEN = "<PAD>"
    UNK_TOKEN = "<UNK>"
    SOS_TOKEN = "<SOS>"
    EOS_TOKEN = "<EOS>"

    # =========================================================================
    # MODEL HYPERPARAMETERS
    # =========================================================================

    # 1. Attention-Augmented Bi-LSTM Tagger
    # -------------------------------------
    TAGGER_EMBEDDING_DIM = 256
    TAGGER_CHAR_EMBEDDING_DIM = 64
    TAGGER_CNN_FILTERS = 64
    TAGGER_CNN_KERNEL_SIZE = 3
    TAGGER_HIDDEN_DIM = 512  # LSTM Hidden Size
    TAGGER_RNN_LAYERS = 2
    TAGGER_ATTENTION_HEADS = 8  # Multi-Head Attention on top of LSTM
    TAGGER_DROPOUT = 0.3
    TAGGER_USE_BIDIRECTIONAL = True

    # 2. Transformer Seq2Seq Fallback
    # -------------------------------
    SEQ2SEQ_EMBEDDING_DIM = 256
    SEQ2SEQ_HIDDEN_DIM = 512  # Feedforward dimension
    SEQ2SEQ_LAYERS = 3  # Number of Encoder/Decoder layers
    SEQ2SEQ_HEADS = 8  # Number of Attention Heads
    SEQ2SEQ_DROPOUT = 0.2

    # =========================================================================
    # TRAINING HYPERPARAMETERS
    # =========================================================================
    BATCH_SIZE = 256  # Large batch size for A100
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-5
    EPOCHS = 15
    EARLY_STOPPING_PATIENCE = 3

    # Loss Configuration
    # Smoothing factor alpha for Class Weights: w_c = (N / N_c)^alpha
    CLASS_WEIGHT_SMOOTHING = 0.5

    @classmethod
    def setup(cls):
        """
        Initializes the environment:
        1. Creates working directories.
        2. Sets random seeds for reproducibility.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        cls.set_seed(cls.SEED)

    @staticmethod
    def set_seed(seed):
        """Sets fixed seeds for random, numpy, and torch."""
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
            # Ensure deterministic behavior where possible
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
