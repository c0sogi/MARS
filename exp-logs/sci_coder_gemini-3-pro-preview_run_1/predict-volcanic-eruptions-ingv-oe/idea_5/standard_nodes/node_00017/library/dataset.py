import numpy as np
import torch
from torch.utils.data import Dataset


class VolcanoSpectrogramDataset(Dataset):
    """
    PyTorch Dataset for the Vision Branch (Branch B).

    This dataset wraps the pre-computed Log-Mel Spectrograms (generated by DataManager)
    and handles the necessary target scaling (Log-Scaling) to ensure stable training
    of the 2D-CNN model.
    """

    def __init__(self, spectrograms, targets=None, log_target=False, transform=None):
        """
        Initialize the dataset.

        Args:
            spectrograms (np.ndarray): Input spectrogram tensor of shape (N, 10, Freq, Time).
                                       Represents the stacked Log-Mel Spectrograms for N samples.
            targets (np.ndarray, optional): Target values (time_to_eruption) of shape (N,).
                                            Can be None for inference/test sets.
            log_target (bool): If True, applies np.log1p to the target variable.
                               This is crucial for training the CNN to prevent gradient explosion
                               due to the large magnitude of the raw targets.
            transform (callable, optional): A function/transform that takes in a sample tensor
                                            and returns a transformed version (e.g., for augmentation).
        """
        self.spectrograms = spectrograms
        self.targets = targets
        self.log_target = log_target
        self.transform = transform

    def __len__(self):
        """
        Returns the total number of samples in the dataset.
        """
        return len(self.spectrograms)

    def __getitem__(self, idx):
        """
        Retrieves a single sample and its target (if available).

        Args:
            idx (int): Index of the sample to retrieve.

        Returns:
            tuple: (spectrogram_tensor, target_tensor) if targets exist.
            torch.Tensor: spectrogram_tensor if targets do not exist.
        """
        # Retrieve the spectrogram: Shape (10, Freq, Time)
        # DataManager provides float32 arrays, but we ensure conversion to torch.float32
        spec = self.spectrograms[idx]
        spec_tensor = torch.from_numpy(spec).float()

        # Apply any provided transforms (e.g., SpecAugment, masking)
        if self.transform:
            spec_tensor = self.transform(spec_tensor)

        # Handle Target
        if self.targets is not None:
            target_val = self.targets[idx]

            # Apply Log Scaling if enabled (Training Mode)
            if self.log_target:
                target_val = np.log1p(target_val)

            # Convert to tensor with shape (1,) to match model output (Batch, 1)
            # This ensures compatibility with loss functions like L1Loss
            target_tensor = torch.tensor([target_val], dtype=torch.float32)

            return spec_tensor, target_tensor

        # Inference Mode (No Target)
        return spec_tensor
