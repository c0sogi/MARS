import os
import numpy as np
import pandas as pd
import torch
from torch.utils.data import Dataset
from library.config import Config


class VolcanoDataset(Dataset):
    """
    PyTorch Dataset for loading pre-computed Log-Mel Spectrograms and seismic targets.

    This dataset loads .npy files generated by the SpectrogramProcessor.
    For training/validation, it applies log-scaling (np.log1p) to the target variable.
    """

    def __init__(self, metadata_path, is_test=False, transform=None, debug_sample=None):
        """
        Args:
            metadata_path (str): Path to the metadata CSV file (train.csv, val.csv, or test.csv).
            is_test (bool): If True, returns (image, segment_id). If False, returns (image, target).
            transform (callable, optional): Optional transform to be applied on the image tensor.
            debug_sample (int, optional): If provided, limits the dataset to the first N samples for debugging.
        """
        self.config = Config
        self.spectrogram_dir = self.config.SPECTROGRAM_CACHE_DIR
        self.is_test = is_test
        self.transform = transform

        if not os.path.exists(metadata_path):
            raise FileNotFoundError(f"Metadata file not found at {metadata_path}")

        self.metadata = pd.read_csv(metadata_path)

        if debug_sample is not None:
            self.metadata = self.metadata.head(debug_sample)

    def __len__(self):
        return len(self.metadata)

    def __getitem__(self, idx):
        row = self.metadata.iloc[idx]
        segment_id = int(row[self.config.SEGMENT_ID_COL])

        # Construct path to the cached .npy file
        # The SpectrogramProcessor saves files as "{segment_id}.npy"
        file_path = os.path.join(self.spectrogram_dir, f"{segment_id}.npy")

        # Load Spectrogram
        # Expected shape from SpectrogramProcessor: (10, 224, 224)
        if os.path.exists(file_path):
            try:
                data = np.load(file_path)
                image = torch.from_numpy(data).float()
            except Exception:
                # Fallback for corrupt files: return zero tensor
                image = torch.zeros(
                    (
                        self.config.N_SENSORS,
                        self.config.IMG_SIZE[0],
                        self.config.IMG_SIZE[1],
                    ),
                    dtype=torch.float32,
                )
        else:
            # Fallback for missing files: return zero tensor
            image = torch.zeros(
                (
                    self.config.N_SENSORS,
                    self.config.IMG_SIZE[0],
                    self.config.IMG_SIZE[1],
                ),
                dtype=torch.float32,
            )

        # Apply optional transforms (e.g., augmentations)
        if self.transform:
            image = self.transform(image)

        if self.is_test:
            # For test set, return segment_id to map predictions later
            return image, segment_id
        else:
            # For train/val, return transformed target
            raw_target = row[self.config.TARGET_COL]

            # Apply Log-Scaling to target: log(y + 1)
            # This compresses the large range of time_to_eruption
            target = np.log1p(raw_target)

            return image, torch.tensor(target, dtype=torch.float32)
