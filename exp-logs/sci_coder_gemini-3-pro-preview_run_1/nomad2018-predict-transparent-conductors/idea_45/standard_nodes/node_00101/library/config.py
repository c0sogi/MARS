import os
import torch
import numpy as np
import random


class Config:
    """
    Configuration for Chemically-Explicit Anisotropic Multi-Scale Deep Sets (CEA-MS-DS).
    Defines hyperparameters, file paths, and physical constants for the pipeline.
    """

    # -------------------------------------------------------------------------
    # Directories and Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_45"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    SUBMISSION_DIR = "./submission"

    # Ensure working directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Artifacts
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pt")
    SCALER_PATH = os.path.join(WORKING_DIR, "scalers.npz")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42

    @staticmethod
    def seed_everything(seed=42):
        """Sets the random seed for reproducibility across libraries."""
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

    # -------------------------------------------------------------------------
    # Data Processing & Feature Engineering Constants
    # -------------------------------------------------------------------------
    # Mapping of atomic symbols to integers
    ATOM_MAP = {"Al": 0, "Ga": 1, "In": 2, "O": 3}

    # Physical Properties for Physics Injection
    # Format: Symbol: [Atomic Mass (u), Covalent Radius (Ang), Electronegativity (Pauling)]
    ATOMIC_PROPS = {
        "Al": [26.981539, 1.21, 1.61],
        "Ga": [69.723, 1.22, 1.81],
        "In": [114.818, 1.42, 1.78],
        "O": [15.999, 0.66, 3.44],
    }

    # Neighbor Search Parameters
    # K=1: Nearest Neighbor Identity & Distance
    # K=6, 24: Multi-Scale Chemical Contexts (Inverse distance weighted)
    # K=12: Local Packing Ratio denominator (d_min / d_mean_12)
    K_NEIGHBORS_MAX = 24
    K_LIST = [1, 6, 12, 24]

    # -------------------------------------------------------------------------
    # Model Architecture Hyperparameters
    # -------------------------------------------------------------------------
    # Atomic Stream Input Dimension: 21
    #   0-3:   Atomic Identity (One-Hot) -> 4 dims
    #   4-7:   Nearest Neighbor Identity (One-Hot) -> 4 dims
    #   8-10:  Centered XYZ Coordinates -> 3 dims
    #   11:    Nearest Neighbor Distance (d_min) -> 1 dim
    #   12:    Local Packing Ratio -> 1 dim
    #   13-16: Chemical Context (K=6) -> 4 dims
    #   17-20: Chemical Context (K=24) -> 4 dims
    ATOMIC_INPUT_DIM = 21

    # Global Stream Input Dimension: 21
    #   0-2:   Lattice Vector Lengths -> 3 dims
    #   3-5:   Lattice Angles -> 3 dims
    #   6:     Unit Cell Volume -> 1 dim
    #   7-9:   Lattice Aspect Ratios -> 3 dims
    #   10:    Atomic Density -> 1 dim
    #   11:    Total Number of Atoms -> 1 dim
    #   12-14: Stoichiometry (Al, Ga, In %) -> 3 dims
    #   15-17: Mean Physical Props (Mass, Rad, EN) -> 3 dims
    #   18-20: Std Dev Physical Props (Mass, Rad, EN) -> 3 dims
    GLOBAL_INPUT_DIM = 21

    # Encoder Dimensions
    ATOMIC_HIDDEN_DIM = 512
    GLOBAL_HIDDEN_DIM = 256

    # Fusion Head Dimensions (MLP after concatenation)
    FUSION_HIDDEN_DIMS = [512, 256, 128]

    # Regularization
    DROPOUT = 0.1

    # -------------------------------------------------------------------------
    # Scaling Configuration (Selective Scaling)
    # -------------------------------------------------------------------------
    # Only scale continuous features. Do NOT scale One-Hot encoded features.
    # Atomic features to scale: Indices 8 through 20 (XYZ, d_min, Ratio, Contexts)
    ATOMIC_SCALE_INDICES = list(range(8, 21))

    # Global features to scale: All 21 are continuous/ordinal
    GLOBAL_SCALE_INDICES = list(range(21))

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 32
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    NUM_EPOCHS = 200
    PATIENCE = 20

    # Compute
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Target Variables
    TARGET_COLS = ["formation_energy_ev_natom", "bandgap_energy_ev"]
