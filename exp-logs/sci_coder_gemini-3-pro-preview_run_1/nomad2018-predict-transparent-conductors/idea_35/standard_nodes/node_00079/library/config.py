import os


class Config:
    """
    Configuration class for the Multi-Neighbor Packing-Aware Deep Sets (MNPA-DS) strategy.
    """

    # -------------------------------------------------------------------------
    # Random Seed for Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42

    # -------------------------------------------------------------------------
    # Directory Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_35"
    SUBMISSION_DIR = "./submission"

    # Ensure working and submission directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    # Metadata files generated by the previous step
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Sample submission for formatting reference
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Cached data files (using .npz for efficient storage of numpy arrays)
    TRAIN_CACHE_PATH = os.path.join(WORKING_DIR, "train_data.npz")
    VAL_CACHE_PATH = os.path.join(WORKING_DIR, "val_data.npz")
    TEST_CACHE_PATH = os.path.join(WORKING_DIR, "test_data.npz")

    # Scalers cache
    SCALERS_CACHE_PATH = os.path.join(WORKING_DIR, "scalers.npz")

    # Model checkpoint path
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pt")

    # Final submission file
    SUBMISSION_OUTPUT_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Physics Constants
    # -------------------------------------------------------------------------
    # Covalent Radii in Angstroms for Atomic Packing Factor (APF) calculation
    # Al: 1.21, Ga: 1.22, In: 1.42, O: 0.66
    COVALENT_RADII = {"Al": 1.21, "Ga": 1.22, "In": 1.42, "O": 0.66}

    # -------------------------------------------------------------------------
    # Data Processing Parameters
    # -------------------------------------------------------------------------
    # Atomic Stream Features:
    # 1. One-hot encoding (4 dims: Al, Ga, In, O)
    # 2. Centered Cartesian coordinates (3 dims: x, y, z)
    # 3. Multi-Order Nearest Neighbor Distances (3 dims: d1, d2, d3)
    ATOMIC_FEATURE_DIM = 10

    # Global Stream Features:
    # 1. Lattice lengths (3 dims: a, b, c)
    # 2. Lattice angles (3 dims: alpha, beta, gamma)
    # 3. Unit Cell Volume (1 dim)
    # 4. Atomic Density (1 dim)
    # 5. Stoichiometry (3 dims: Al, Ga, In fractions)
    # 6. Total Number of Atoms (1 dim)
    # 7. Atomic Packing Factor (APF) (1 dim)
    GLOBAL_FEATURE_DIM = 13

    # Targets
    TARGET_COLS = ["formation_energy_ev_natom", "bandgap_energy_ev"]

    # -------------------------------------------------------------------------
    # Model Architecture Hyperparameters
    # -------------------------------------------------------------------------
    # Atomic Stream (Wide MLP)
    ATOMIC_HIDDEN_DIM = 512

    # Global Stream (High-Capacity MLP)
    GLOBAL_HIDDEN_DIM = 256

    # Fusion Head
    FUSION_HIDDEN_DIM = 256

    # Regularization
    DROPOUT_RATE = 0.1

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 64
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    EPOCHS = 200
    PATIENCE = 20  # Early stopping patience

    # Scheduler settings (ReduceLROnPlateau)
    SCHEDULER_FACTOR = 0.5
    SCHEDULER_PATIENCE = 5
    MIN_LR = 1e-6

    # -------------------------------------------------------------------------
    # Debugging
    # -------------------------------------------------------------------------
    # Set to True to run on a small subset of data for quick testing
    DEBUG = False
    DEBUG_SIZE = 100
