import os
import random
import numpy as np
import torch


class Config:
    """
    Configuration for the Local-Anisotropy Enhanced Wide Deep Sets (LA-WDS) strategy.
    """

    # -------------------------------------------------------------------------
    # Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Cache directory for Idea 20 (LA-WDS)
    # Stores processed tensors (e.g., .pt or .npz files) to speed up subsequent runs
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_20")

    # Metadata CSVs generated by the metadata script
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Submission
    SUBMISSION_DIR = "./submission"
    SUBMISSION_FILE = "submission.csv"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, SUBMISSION_FILE)
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # -------------------------------------------------------------------------
    # Data Processing
    # -------------------------------------------------------------------------
    # Number of nearest neighbors to consider for Local Anisotropy Eigenvalues
    K_NEIGHBORS = 12

    # Atomic Identity Encoding
    ATOM_TYPES = ["Al", "Ga", "In", "O"]
    NUM_ATOM_TYPES = len(ATOM_TYPES)

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    # Atomic Stream (Point Processor)
    # Features: One-hot (4) + Centered Coords (3) + NN Dist (1) + Anisotropy Eigenvalues (3)
    ATOMIC_INPUT_DIM = NUM_ATOM_TYPES + 3 + 1 + 3
    ATOMIC_HIDDEN_DIM = 512
    ATOMIC_LAYERS = 3  # Number of layers in the atomic encoder MLP

    # Global Stream (Thermodynamic Context)
    # Features: Lattice lengths (3) + Angles (3) + Volume (1) + Density (1) + Stoichiometry (4) + Total Atoms (1)
    GLOBAL_INPUT_DIM = 13
    GLOBAL_HIDDEN_DIM = 256
    GLOBAL_LAYERS = 3

    # Fusion Head
    # Input dim will be: 2 * ATOMIC_HIDDEN_DIM (Mean + Max pooling) + GLOBAL_HIDDEN_DIM
    FUSION_HIDDEN_DIM = 256
    FUSION_LAYERS = 3
    OUTPUT_DIM = 2  # formation_energy_ev_natom, bandgap_energy_ev

    # Regularization
    DROPOUT_RATE = 0.1
    USE_BATCH_NORM = True

    # -------------------------------------------------------------------------
    # Training
    # -------------------------------------------------------------------------
    BATCH_SIZE = 128
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    MAX_EPOCHS = 200

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 20

    # Scheduler (ReduceLROnPlateau)
    SCHEDULER_FACTOR = 0.5
    SCHEDULER_PATIENCE = 5
    SCHEDULER_MIN_LR = 1e-6

    # -------------------------------------------------------------------------
    # Hardware / Misc
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4

    @staticmethod
    def set_seed(seed=42):
        """Sets the random seed for reproducibility across numpy, random, and torch."""
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

    @classmethod
    def prepare_directories(cls):
        """Creates necessary working directories for cache and submission."""
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
