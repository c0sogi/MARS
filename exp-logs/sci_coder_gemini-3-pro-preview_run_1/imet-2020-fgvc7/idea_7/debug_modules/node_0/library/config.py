import os
import torch


class Config:
    """
    Central configuration for the Artwork Attribute Labeling experiment.
    Implements the 'idea_7' strategy: ConvNeXt-Small, 320px, EMA, Mixup/CutMix.
    """

    # -------------------------------------------------------------------------
    # General Configuration
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 2000  # Number of samples to use when DEBUG is True

    # Compute
    NUM_WORKERS = 4
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # -------------------------------------------------------------------------
    # Directories & Paths
    # -------------------------------------------------------------------------
    # Input Directories (Read-Only)
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata Paths (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Labels Information
    LABELS_PATH = os.path.join(INPUT_DIR, "labels.csv")

    # Output Directories
    EXP_NAME = "idea_7"
    WORKING_DIR = os.path.join("./working", EXP_NAME)
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # -------------------------------------------------------------------------
    # Model Configuration
    # -------------------------------------------------------------------------
    # Architecture: ConvNeXt-Small (Pretrained on ImageNet-22k, FT on 1k)
    # Provides higher capacity than Tiny/ResNet34 for fine-grained details
    MODEL_NAME = "convnext_small.fb_in22k_ft_in1k"
    PRETRAINED = True

    # Input Resolution: 320x320 (Balance between detail and compute)
    IMG_SIZE = 320

    # Dataset Specifics
    NUM_CLASSES = 3474

    # Model EMA (Exponential Moving Average)
    # Critical for robustness against noisy labels
    USE_EMA = True
    EMA_DECAY = 0.9999

    # Pooling Layer
    POOLING = "gem"  # Generalized Mean Pooling

    # -------------------------------------------------------------------------
    # Training Configuration
    # -------------------------------------------------------------------------
    # Extended training duration for heavier model
    EPOCHS = 20

    # Batch Size: Tuned for A100-40GB with 320px images
    BATCH_SIZE = 48

    # Optimizer: AdamW
    LR = 1e-4
    WEIGHT_DECAY = 1e-2

    # Scheduler: Cosine Annealing
    MIN_LR = 1e-6

    # Loss Function: BCEWithLogitsLoss
    # Pos weight 12.0 to handle class imbalance (sparse labels)
    POS_WEIGHT = 12.0
    # Label smoothing to mitigate overfitting to noisy annotations
    LABEL_SMOOTHING = 0.05

    # Gradient Clipping
    MAX_GRAD_NORM = 10.0

    # -------------------------------------------------------------------------
    # Augmentation Configuration (Mixup / CutMix)
    # -------------------------------------------------------------------------
    # Strong regularization to prevent overfitting with high-capacity model
    MIXUP_ALPHA = 0.8
    CUTMIX_ALPHA = 1.0
    MIXUP_PROB = 0.5  # Probability of applying Mixup/CutMix per batch

    # -------------------------------------------------------------------------
    # Inference Configuration
    # -------------------------------------------------------------------------
    # Grid search parameters for optimal threshold tuning on Validation set
    THRESHOLD_START = 0.01
    THRESHOLD_END = 0.99
    THRESHOLD_STEP = 0.01
