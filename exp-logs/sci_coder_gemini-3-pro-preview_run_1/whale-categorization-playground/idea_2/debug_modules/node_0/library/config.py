import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration class for the Whale Species Prediction project.
    Centralizes all hyperparameters, paths, and settings.
    """

    # ---------------------------------------------------------
    # General Settings
    # ---------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data
    DEBUG_SAMPLE_SIZE = 100  # Number of samples to use when DEBUG is True

    # ---------------------------------------------------------
    # Compute
    # ---------------------------------------------------------
    # Automatically detect GPU
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4  # Number of data loading workers

    # ---------------------------------------------------------
    # Data Paths
    # ---------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the metadata script
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # ---------------------------------------------------------
    # Output Paths
    # ---------------------------------------------------------
    WORKING_DIR = "./working/idea_2"
    SUBMISSION_DIR = "./submission"

