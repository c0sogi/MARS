import os
import torch


class Config:
    """
    Configuration for Whale Species Prediction (Idea 4: ConvNeXt + ArcFace).
    Centralizes all hyperparameters, file paths, and constants.
    """

    # =========================================================================
    # General & Reproducibility
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data
    DEBUG_SUBSET_SIZE = 200  # Number of samples to use in debug mode

    # =========================================================================
