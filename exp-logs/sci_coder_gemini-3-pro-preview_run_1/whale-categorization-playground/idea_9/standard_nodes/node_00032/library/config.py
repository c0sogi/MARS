import os
import torch


class Config:
    """
    Configuration module for the Whale Identification Task.
    Implements the settings for a Validation-Optimized Homogeneous Ensemble
    of DenseNet121 models with ArcFace heads.
    """

    # --------------------------------------------------------------------------
    # Directory & File Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_9"

    # Ensure working directory exists for caching and checkpoints
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Metadata Paths (Generated by the metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Submission Output
    SUBMISSION_DIR = os.path.join(WORKING_DIR, "submission")
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Model Architecture
    # --------------------------------------------------------------------------
    BACKBONE = "densenet121"
    # Dimension of the embedding vector before the ArcFace head
    EMBEDDING_DIM = 512
    # Total unique classes including 'new_whale' (derived from metadata analysis)
    NUM_CLASSES = 4029

    # --------------------------------------------------------------------------
    # Input Data Specifications
    # --------------------------------------------------------------------------
    IMG_SIZE = 320
    CHANNELS = 3

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    # Seeds for the homogeneous ensemble (3 independent models)
    SEEDS = [42, 43, 44]

    # Batch size compatible with A100 40GB RAM
    BATCH_SIZE = 32

    # Max epochs (Early stopping will likely intervene earlier)
    EPOCHS = 30

    # Optimization
    LEARNING_RATE = 3e-4
    WEIGHT_DECAY = 1e-4

    # Early Stopping
    PATIENCE = 5

    # --------------------------------------------------------------------------
    # ArcFace Hyperparameters
    # --------------------------------------------------------------------------
    # Angular margin penalty
    ARC_MARGIN = 0.50
    # Feature scaling factor
    ARC_SCALE = 30.0

    # --------------------------------------------------------------------------
    # Regularization
    # --------------------------------------------------------------------------
    # Label smoothing to handle singleton classes and prevent overfitting
    LABEL_SMOOTHING = 0.1
    # Dropout rate for the projection head
    DROPOUT = 0.5

    # --------------------------------------------------------------------------
    # Augmentation (Configuration values)
    # --------------------------------------------------------------------------
    # Rotation in degrees (+/-)
    AUG_ROTATION = 20
    # Scaling factor range
    AUG_SCALE_MIN = 0.9
    AUG_SCALE_MAX = 1.1
    # Horizontal flip probability
    AUG_HFLIP_PROB = 0.5
    # Probability for geometric augmentations
    AUG_GEO_PROB = 0.5

    # --------------------------------------------------------------------------
    # Compute Resources
    # --------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Optimized for 12 vCPUs

    # --------------------------------------------------------------------------
    # Debugging & Development
    # --------------------------------------------------------------------------
    # Set to True to run on a small subset of data for pipeline verification
    DEBUG = False
    # Number of samples to use when DEBUG is True
    DEBUG_SAMPLES = 500
