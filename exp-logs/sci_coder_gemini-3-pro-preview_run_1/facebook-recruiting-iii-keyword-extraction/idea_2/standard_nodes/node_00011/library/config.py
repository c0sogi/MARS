import os
import torch


class Config:
    """
    Global configuration for the Stack Exchange Tag Prediction task.
    """

    # ---------------------------------------------------------
    # 1. Paths
    # ---------------------------------------------------------
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_2"
    SUBMISSION_DIR = "./submission"

    # Input files
    TRAIN_CSV = os.path.join(INPUT_DIR, "train.csv")
    TEST_CSV = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata files (Generated by the metadata script)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output files (Cache and Artifacts)
    # We use .parquet for dataframes and .pth for torch models
    TOKENIZER_PATH = os.path.join(WORKING_DIR, "tokenizer.json")
    LABEL_ENCODER_PATH = os.path.join(WORKING_DIR, "label_encoder.npy")
    BEST_MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ---------------------------------------------------------
    # 2. Data Parameters
    # ---------------------------------------------------------
    # Text processing
    VOCAB_SIZE = 80000  # Size of the vocabulary (most frequent words)
    MAX_LEN = 300  # Maximum sequence length (Body)
    MAX_LEN_TITLE = 60  # Maximum sequence length (Title)
    MIN_FREQ = 2  # Minimum frequency for a token to be included

    # Target processing
    NUM_TAGS = 5000  # Number of top frequent tags to predict
    TAG_THRESHOLD = 0.3  # Probability threshold for predicting a tag (inference)

    # ---------------------------------------------------------
    # 3. Model Parameters (FastText / Averaged Embedding)
    # ---------------------------------------------------------
    EMBEDDING_DIM = 256  # Dimension of the embedding layer
    HIDDEN_DIM = 1024  # Dimension of the hidden linear layer (if used)
    DROPOUT = 0.3  # Dropout rate

    # ---------------------------------------------------------
    # 4. Training Parameters
    # ---------------------------------------------------------
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Hyperparameters
    BATCH_SIZE = 1024  # Large batch size for efficiency on A100
    LEARNING_RATE = 2e-3  # Learning rate for Adam
    EPOCHS = 15  # Maximum number of epochs
    PATIENCE = 4  # Early stopping patience
    NUM_WORKERS = 12  # Number of data loading workers

    # ---------------------------------------------------------
    # 5. Setup Logic
    # ---------------------------------------------------------
    @classmethod
    def setup(cls):
        """
        Ensures necessary directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Run setup immediately upon import to ensure directories exist
Config.setup()
