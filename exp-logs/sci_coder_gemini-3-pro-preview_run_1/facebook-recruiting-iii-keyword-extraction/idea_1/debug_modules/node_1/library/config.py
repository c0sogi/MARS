import os
import torch


class Config:
    """
    Configuration class for Stack Exchange Tag Prediction.
    Stores file paths, hyperparameters, and global settings.
    """

    # =========================================================================
    # File Systems & Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"
    IDEA_DIR = os.path.join(WORKING_DIR, "idea_1")
    SUBMISSION_DIR = "./submission"

    # Create necessary writable directories
    os.makedirs(IDEA_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Source Data Paths
    TRAIN_CSV = os.path.join(INPUT_DIR, "train.csv")
    TEST_CSV = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Paths (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output & Cache Paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Caching paths for reproducible data processing
    # We use .npy for numpy arrays and .json for simple mappings
    VOCAB_PATH = os.path.join(IDEA_DIR, "vocab.npy")
    TAG_MAP_PATH = os.path.join(IDEA_DIR, "tag_map.npy")
    TOKENIZER_PATH = os.path.join(IDEA_DIR, "tokenizer.json")

    # Model Checkpoint
    MODEL_SAVE_PATH = os.path.join(IDEA_DIR, "best_model.pth")

    # =========================================================================
    # Data Parameters
    # =========================================================================
    # Text Processing
    MAX_LEN = 300  # Max sequence length (Title + Body)
    VOCAB_SIZE = 50000  # Maximum vocabulary size (top frequent words)
    MIN_WORD_FREQ = 5  # Minimum frequency for a word to be in vocab

    # Target (Tag) Processing
    # Strategy: Predict top N most frequent tags to handle high cardinality
    NUM_TAGS = 5000  # Number of target classes (Top-K tags)

    # =========================================================================
    # Model Architecture (Bi-GRU + Global Pooling)
    # =========================================================================
    EMBED_DIM = 300  # Word embedding dimension
    HIDDEN_DIM = 512  # GRU hidden state dimension
    NUM_LAYERS = 2  # Number of stacked GRU layers
    DROPOUT = 0.3  # Dropout rate for regularization
    BIDIRECTIONAL = True  # Use Bi-Directional GRU

    # =========================================================================
    # Training Configuration
    # =========================================================================
    SEED = 42  # Random seed for reproducibility
    BATCH_SIZE = 512  # Batch size (A100 40GB allows large batches)
    LEARNING_RATE = 1e-3  # Initial learning rate
    NUM_EPOCHS = 10  # Maximum number of training epochs
    EARLY_STOPPING_PATIENCE = 3  # Epochs to wait before stopping if Val F1 stagnates

    # Inference Threshold
    PREDICTION_THRESHOLD = 0.4  # Probability threshold for assigning a tag

    # Hardware
    NUM_WORKERS = 12  # Number of CPU workers (matches vCPUs)
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # =========================================================================
    # Debugging & Development
    # =========================================================================
    DEBUG = False  # Set to True to use a small subset of data
    DEBUG_SIZE = 50000  # Number of samples for debugging

    @staticmethod
    def set_seed():
        """
        Sets random seeds for reproducibility across Python, NumPy, and PyTorch.
        """
        import random
        import numpy as np
        import torch

        seed = Config.SEED
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
        os.environ["PYTHONHASHSEED"] = str(seed)
