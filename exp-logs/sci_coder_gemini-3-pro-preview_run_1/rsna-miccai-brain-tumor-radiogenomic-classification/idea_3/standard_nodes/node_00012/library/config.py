import os
import torch


class Config:
    """
    Configuration class for the 2.5D Volumetric Sequence Transformer pipeline.
    Centralizes all hyperparameters, paths, and constants.
    """

    # ==========================================
    # Global Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 32  # Number of samples to use if DEBUG is True

    # ==========================================
    # Paths & Directories
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for this specific idea (Idea 3)
    WORKING_DIR = "./working/idea_3"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Metadata Paths (Generated by the metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Paths
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = "./submission/submission.csv"

    # Ensure submission directory exists
    os.makedirs(os.path.dirname(SUBMISSION_PATH), exist_ok=True)

    # ==========================================
    # Data Preprocessing & Loading
    # ==========================================
    # Input Dimensions
    IMG_SIZE = 224
    NUM_SLICES = 24  # Sequence length (N) for the transformer

    # Modalities to use (forming the 3 channels of the input)
    # As per idea: FLAIR, T1wCE, T2w
    SELECTED_MODALITIES = ["FLAIR", "T1wCE", "T2w"]
    NUM_CHANNELS = len(SELECTED_MODALITIES)

    # Geometric Sampling
    # Percentage of top/bottom slices to discard before sampling
    SLICE_DISCARD_PCT = 0.15

    # ==========================================
    # Model Architecture
    # ==========================================
    BACKBONE_NAME = "efficientnet_b0"
    PRETRAINED_BACKBONE = True

    # Transformer Encoder settings
    HIDDEN_DIM = 256  # Projection dimension after backbone
    TRANSFORMER_LAYERS = 2
    TRANSFORMER_HEADS = 4
    DROPOUT_RATE = 0.3  # Heavy dropout as per idea

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 16  # Adjusted for A100 40GB (Sequence data is memory intensive)
    NUM_EPOCHS = 15
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2
    EARLY_STOPPING_PATIENCE = 4

    # ==========================================
    # Hardware & Performance
    # ==========================================
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4  # Number of subprocesses for data loading
    PIN_MEMORY = True  # Pin memory for faster host-to-device transfer
