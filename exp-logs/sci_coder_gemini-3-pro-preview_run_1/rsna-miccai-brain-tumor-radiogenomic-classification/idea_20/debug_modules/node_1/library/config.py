import os
import torch


class Config:
    """
    Global configuration for the WIVS-Net (Weight-Inflated 9-Channel Volumetric Stack) pipeline.
    Acts as the single source of truth for hyperparameters and file paths.
    """

    # ==========================================
    # General Setup
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Number of data loading workers

    # ==========================================
    # Data / Preprocessing
    # ==========================================
    IMG_SIZE = 224
    NUM_CHANNELS = 9  # 3 modalities (FLAIR, T1wCE, T2w) * 3 depths
    STRIDE = 5  # Slice gap for volumetric stacking: M-5, M, M+5

    # Normalization
    # We use min-max scaling to [0, 1] per channel, so we don't use ImageNet mean/std here.
    # The model initialization handles the weight inflation.

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    MODEL_NAME = "efficientnet_b0"
    BATCH_SIZE = 32
    EPOCHS = 15

    # Optimization
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2  # Aggressive regularization
    DROPOUT = 0.3  # Classifier dropout rate

    # Cross-Validation
    NUM_FOLDS = 5

    # ==========================================
    # Paths & Directories
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (generated by external script)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Working Directory for this specific idea/experiment
    WORKING_DIR = "./working/idea_20"

    # Cache directory for processed numpy arrays/tensors
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")

    # Directory to save model checkpoints
    MODEL_DIR = os.path.join(WORKING_DIR, "models")

    # Submission output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    @classmethod
    def setup(cls):
        """
        Ensures all necessary working directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.MODEL_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Automatically setup directories when config is imported
Config.setup()
