import os


class Config:
    # -------------------------------------------------------------------------
    # Directory & File Path Configuration
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Cache directory for storing processed features (parquet/npy)
    CACHE_DIR = "./working/idea_8"
    SUBMISSION_DIR = "./submission"

    # Create writable directories if they don't exist
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata file paths (generated by the provided metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # -------------------------------------------------------------------------
    # Reproducibility & Debugging
    # -------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4

    # Set DEBUG to True to train on a small subset of data for quick testing
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 1000

    # -------------------------------------------------------------------------
    # Data Processing Hyperparameters (Signal Profile Aggregation)
    # -------------------------------------------------------------------------
    # Length of the time-series sequence fed into the model
    SEQUENCE_LENGTH = 128

    # Histogram Bin Edges for Feature Engineering
    # Cn0DbHz (Signal Strength): Buckets for signal quality distribution
    CN0_BINS = [0, 15, 25, 35, 45, 100]

    # SvElevationDegrees: Buckets for satellite position distribution
    ELEVATION_BINS = [0, 15, 30, 45, 60, 90]

    # Feature Dimension Calculation:
    # 1. Aggregated Stats (Min, Max, Mean) for Cn0 and Elevation -> 3 + 3 = 6
    # 2. Mean RawPseudorangeUncertaintyMeters -> 1
    # 3. Satellite Count -> 1
    # 4. Histogram counts for Cn0 -> len(CN0_BINS) - 1
    # 5. Histogram counts for Elevation -> len(ELEVATION_BINS) - 1
    NUM_CN0_BINS = len(CN0_BINS) - 1
    NUM_ELEV_BINS = len(ELEVATION_BINS) - 1
    INPUT_CHANNELS = 6 + 1 + 1 + NUM_CN0_BINS + NUM_ELEV_BINS  # Total: 18

    # -------------------------------------------------------------------------
    # Model Architecture Hyperparameters (Cascaded 1D ResUNet)
    # -------------------------------------------------------------------------
    HIDDEN_DIM = 64
    KERNEL_SIZE = 3
    DEPTH = 4  # Depth of the U-Net encoder/decoder
    DROPOUT = 0.1

    # -------------------------------------------------------------------------
    # Training Configuration
    # -------------------------------------------------------------------------
    BATCH_SIZE = 32
    EPOCHS = 30
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    EARLY_STOPPING_PATIENCE = 6

    # Deep Supervision Loss Weights
    # Loss = W1 * MAE(Stage1_Output, GT) + W2 * MAE(Final_Output, GT)
    LOSS_WEIGHT_STAGE1 = 0.5
    LOSS_WEIGHT_FINAL = 1.0

    # -------------------------------------------------------------------------
    # Physical Constants (WGS84 Ellipsoid)
    # -------------------------------------------------------------------------
