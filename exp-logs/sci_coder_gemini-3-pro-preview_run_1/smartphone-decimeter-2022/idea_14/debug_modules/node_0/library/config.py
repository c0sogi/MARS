import os
import torch


class Config:
    """
    Central configuration for the Smartphone Decimeter Challenge solution.
    Handles paths, model hyperparameters, training settings, and feature definitions.
    """

    # -------------------------------------------------------------------------
    # Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORK_DIR = "./working/idea_14"
    SUBMISSION_DIR = "./submission"

    # Ensure working and submission directories exist
    os.makedirs(WORK_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    # Metadata files generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Cache files for storing preprocessed tensors/dataframes
    # Using parquet for efficient storage of tabular features before tensor conversion
    TRAIN_CACHE = os.path.join(WORK_DIR, "train_processed.parquet")
    VAL_CACHE = os.path.join(WORK_DIR, "val_processed.parquet")
    TEST_CACHE = os.path.join(WORK_DIR, "test_processed.parquet")

    # Model checkpoint path
    MODEL_CHECKPOINT = os.path.join(WORK_DIR, "best_model.pth")

    # Final submission output path
    SUBMISSION_OUTPUT = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Global Settings
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to use a small subset of data for debugging
    DEBUG_SAMPLE_SIZE = 50  # Number of trips to use in debug mode
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Number of dataloader workers

    # -------------------------------------------------------------------------
    # Data Preprocessing
    # -------------------------------------------------------------------------
    # Time binning for aggregation (aligning raw GNSS to 1Hz ground truth)
    TIME_BIN_SEC = 1.0

    # Features to be computed during aggregation from raw GNSS logs
    # Keys are raw column names, Values are lists of aggregation functions
    # Note: Azimuth is handled specially (sin/cos components) in the processor
    FEATURE_STATS = {
        "Cn0DbHz": ["mean", "std", "min", "max"],
        "SvElevationDegrees": ["mean", "std", "min", "max"],
        "RawPseudorangeUncertaintyMeters": ["mean"],
    }

    # Ordered list of input feature names expected by the model
    # Total Features: 4 (Cn0) + 4 (Elev) + 1 (Uncertainty) + 2 (Azimuth) + 1 (Count) = 12
    INPUT_FEATURES = [
        "Cn0DbHz_mean",
        "Cn0DbHz_std",
        "Cn0DbHz_min",
        "Cn0DbHz_max",
        "SvElevationDegrees_mean",
        "SvElevationDegrees_std",
        "SvElevationDegrees_min",
        "SvElevationDegrees_max",
        "RawPseudorangeUncertaintyMeters_mean",
        "SvAzimuthDegrees_sin_mean",
        "SvAzimuthDegrees_cos_mean",
        "SatCount",
    ]

    # -------------------------------------------------------------------------
    # Model Hyperparameters (1D ResUNet + ASPP)
    # -------------------------------------------------------------------------
    IN_CHANNELS = len(INPUT_FEATURES)
    OUT_CHANNELS = 2  # Delta East (meters), Delta North (meters)
    BASE_CHANNELS = 64
    ENCODER_DEPTH = 4
    ASPP_DILATIONS = [1, 6, 12, 24]  # Dilation rates for Atrous Spatial Pyramid Pooling

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 32  # Number of trips (sequences) per batch
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    EPOCHS = 50
    EARLY_STOPPING_PATIENCE = 10

    # Loss function weights for Deep Supervision
    # [Main Output, Aux Output 1 (Deepest), Aux Output 2 (Shallower)]
    LOSS_WEIGHTS = [1.0, 0.4, 0.1]

    # -------------------------------------------------------------------------
    # Physical Constants
    # -------------------------------------------------------------------------
    # WGS84 Ellipsoid constants for Lat/Lon <-> Meter conversion
    WGS84_A = 6378137.0  # Semi-major axis
    WGS84_F = 1 / 298.257223563  # Flattening
    WGS84_B = WGS84_A * (1 - WGS84_F)  # Semi-minor axis
    # Squared eccentricity
    WGS84_E2 = (WGS84_A**2 - WGS84_B**2) / (WGS84_A**2)
