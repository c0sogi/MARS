import torch
import torch.nn as nn
from library.config import Config


class DecimatedMAELoss(nn.Module):
    """
    Computes the weighted Mean Absolute Error (MAE) loss with Decimated Deep Supervision.

    The total loss is the sum of the MAE of the final output and the weighted sum of
    MAEs of the auxiliary outputs. Auxiliary targets are generated by decimating
    (subsampling) the ground truth to match the temporal resolution of the auxiliary heads.
    """

    def __init__(self):
        super(DecimatedMAELoss, self).__init__()
        self.aux_weight = Config.AUX_LOSS_WEIGHT
        self.l1_loss = nn.L1Loss(reduction="none")

    def forward(self, outputs, targets, mask):
        """
        Args:
            outputs (list): List of model outputs [final, aux3, aux2].
                            final shape: (B, 2, L)
                            aux3 shape:  (B, 2, L/2)
                            aux2 shape:  (B, 2, L/4)
            targets (torch.Tensor): Ground truth targets (B, L, 2).
            mask (torch.Tensor): Boolean mask for valid sequence lengths (B, L).

        Returns:
            torch.Tensor: Scalar loss value.
        """
        # Unpack outputs
        # Based on model.py: return [final, aux3, aux2]
        # final corresponds to stride 1
        # aux3 corresponds to stride 2 (L/2)
        # aux2 corresponds to stride 4 (L/4)

        final_pred = outputs[0].permute(0, 2, 1)  # (B, L, 2)
        aux3_pred = outputs[1].permute(0, 2, 1)  # (B, L/2, 2)
        aux2_pred = outputs[2].permute(0, 2, 1)  # (B, L/4, 2)

        # 1. Compute Main Loss (Stride 1)
        loss_final = self.compute_masked_mae(final_pred, targets, mask)

        # 2. Compute Auxiliary Losses
        loss_aux = 0.0

        # Aux 3 (Stride 2)
        loss_aux += self.compute_decimated_loss(aux3_pred, targets, mask, stride=2)

        # Aux 2 (Stride 4)
        loss_aux += self.compute_decimated_loss(aux2_pred, targets, mask, stride=4)

        # Total Loss
        total_loss = loss_final + self.aux_weight * loss_aux

        return total_loss

    def compute_decimated_loss(self, pred, target, mask, stride):
        """
        Computes loss for a lower resolution prediction by decimating the target.

        Args:
            pred (torch.Tensor): Prediction tensor (B, L_out, 2).
            target (torch.Tensor): Full resolution target (B, L_in, 2).
            mask (torch.Tensor): Full resolution mask (B, L_in).
            stride (int): Decimation factor.

        Returns:
            torch.Tensor: Scalar loss.
        """
        # Decimate target and mask
        # We take every 'stride'-th element starting from 0
        target_dec = target[:, ::stride, :]
        mask_dec = mask[:, ::stride]

        # Align lengths
        # Due to padding or odd lengths, shapes might differ slightly.
        # We truncate to the minimum length between prediction and decimated target.
        min_len = min(pred.shape[1], target_dec.shape[1])

        pred_aligned = pred[:, :min_len, :]
        target_aligned = target_dec[:, :min_len, :]
        mask_aligned = mask_dec[:, :min_len]

        return self.compute_masked_mae(pred_aligned, target_aligned, mask_aligned)

    def compute_masked_mae(self, pred, target, mask):
        """
        Computes MAE ignoring masked (padded) values.

        Args:
            pred (torch.Tensor): (B, T, 2)
            target (torch.Tensor): (B, T, 2)
            mask (torch.Tensor): (B, T)

        Returns:
            torch.Tensor: Scalar MAE.
        """
        # Compute element-wise L1 loss
        loss = self.l1_loss(pred, target)  # (B, T, 2)

        # Expand mask to (B, T, 2)
        mask_expanded = mask.unsqueeze(-1).expand_as(loss)

        # Apply mask
        loss = loss * mask_expanded.float()

        # Compute mean over valid elements
        # Sum of valid elements (multiply by 2 because mask is expanded to 2 coordinates)
        num_valid = mask_expanded.sum()

        if num_valid == 0:
            return torch.tensor(0.0, device=pred.device, requires_grad=True)

        return loss.sum() / num_valid
