import os
import numpy as np
import pandas as pd
import torch
import cv2
import albumentations as A
from torch.utils.data import Dataset
from library.config import Config
from library.utils import generate_coordinate_map

# Define standard EEG channels to ensure consistent ordering
EEG_CHANNELS = [
    "Fp1",
    "F3",
    "C3",
    "P3",
    "F7",
    "T3",
    "T5",
    "O1",
    "Fz",
    "Cz",
    "Pz",
    "Fp2",
    "F4",
    "C4",
    "P4",
    "F8",
    "T4",
    "T6",
    "O2",
    "EKG",
]

# Define Spectrogram regions
SPEC_REGIONS = ["LL", "RL", "LP", "RP"]


class HMSDataset(Dataset):
    def __init__(
        self,
        metadata: pd.DataFrame,
        config: Config = Config,
        mode: str = "train",
        augment: bool = False,
    ):
        """
        Dataset class for Harmful Brain Activity Detection.

        Args:
            metadata: DataFrame containing dataset metadata.
            config: Configuration class.
            mode: 'train', 'val', or 'test'.
            augment: Whether to apply data augmentation.
        """
        self.metadata = metadata.copy()
        self.config = config
        self.mode = mode
        self.augment = augment

        # Ensure cache directory exists
        os.makedirs(self.config.CACHE_DIR, exist_ok=True)

        # Pre-compute absolute file paths
        # If metadata was generated by the provided script, it has relative paths in 'eeg_path' and 'spectrogram_path'
        # We prepend INPUT_DIR to make them absolute.
        if "eeg_path" in self.metadata.columns:
            self.metadata["eeg_path"] = self.metadata["eeg_path"].apply(
                lambda x: (
                    os.path.join(self.config.INPUT_DIR, x)
                    if not os.path.isabs(x)
                    else x
                )
            )
        else:
            # Fallback for test set if paths are missing
            folder = self.config.TEST_EEGS_DIR
            self.metadata["eeg_path"] = self.metadata["eeg_id"].apply(
                lambda x: os.path.join(folder, f"{x}.parquet")
            )

        if "spectrogram_path" in self.metadata.columns:
            self.metadata["spectrogram_path"] = self.metadata["spectrogram_path"].apply(
                lambda x: (
                    os.path.join(self.config.INPUT_DIR, x)
                    if not os.path.isabs(x)
                    else x
                )
            )
        else:
            # Fallback for test set
            folder = self.config.TEST_SPECTROGRAMS_DIR
            self.metadata["spectrogram_path"] = self.metadata["spectrogram_id"].apply(
                lambda x: os.path.join(folder, f"{x}.parquet")
            )

        # Define Augmentations for Spectrogram
        self.transform = None
        if self.augment:
            self.transform = A.Compose(
                [
                    A.HorizontalFlip(p=0.5),
                    A.CoarseDropout(
                        max_holes=8,
                        max_height=self.config.SPEC_SIZE[0] // 8,
                        max_width=self.config.SPEC_SIZE[1] // 8,
                        fill_value=0,
                        p=0.5,
                    ),
                ]
            )

    def __len__(self):
        return len(self.metadata)

    def __getitem__(self, idx):
        row = self.metadata.iloc[idx]

        # Identifiers
        eeg_id = row["eeg_id"]
        spec_id = row["spectrogram_id"]

        # Offsets (Handle Test Case where they might be missing or 0)
        eeg_offset = row.get("eeg_label_offset_seconds", 0.0)
        spec_offset = row.get("spectrogram_label_offset_seconds", 0.0)

        if pd.isna(eeg_offset):
            eeg_offset = 0.0
        if pd.isna(spec_offset):
            spec_offset = 0.0

        # Cache Key: Unique combination of IDs and offsets
        cache_filename = f"{eeg_id}_{spec_id}_{int(eeg_offset)}_{int(spec_offset)}.npz"
        cache_path = os.path.join(self.config.CACHE_DIR, cache_filename)

        # ---------------------------------------------------------------------
        # 1. Load Data (Cache or Compute)
        # ---------------------------------------------------------------------
        data_loaded = False

        # Try loading from cache
        if os.path.exists(cache_path):
            try:
                cached = np.load(cache_path)
                eeg_data = cached["eeg"]
                spec_data = cached["spec"]
                data_loaded = True
            except Exception:
                # Corrupt cache, recompute
                pass

        if not data_loaded:
            # Compute from scratch
            eeg_data = self.process_eeg(row["eeg_path"], eeg_offset)
            spec_data = self.process_spec(row["spectrogram_path"], spec_offset)

            # Save to cache (compressed to save space)
            np.savez_compressed(cache_path, eeg=eeg_data, spec=spec_data)

        # ---------------------------------------------------------------------
        # 2. Prepare Tensors & Augmentations
        # ---------------------------------------------------------------------

        # --- Spectrogram Augmentation & Coordinate Injection ---
        # spec_data shape: (H, W, 4)

        if self.augment and self.transform:
            # Albumentations expects HWC
            augmented = self.transform(image=spec_data)
            spec_data = augmented["image"]

        # Convert to Tensor (H, W, C) -> (C, H, W)
        spec_tensor = torch.tensor(spec_data, dtype=torch.float32).permute(2, 0, 1)

        # Generate Coordinate Map
        # Shape: (1, H, W)
        coord_map = generate_coordinate_map(
            height=self.config.SPEC_SIZE[0],
            width=self.config.SPEC_SIZE[1],
            device="cpu",
        )

        # Concatenate: 4 channels + 1 coord channel = 5 channels
        spec_input = torch.cat([spec_tensor, coord_map], dim=0)

        # --- EEG Augmentation ---
        # eeg_data shape: (Seq_Len, Channels)

        # Simple Channel Dropout for EEG (if augment)
        if self.augment and np.random.random() < 0.5:
            # Drop 1 channel by zeroing it out
            ch_idx = np.random.randint(0, self.config.EEG_CHANNELS)
            eeg_data[:, ch_idx] = 0.0

        eeg_tensor = torch.tensor(eeg_data, dtype=torch.float32)

        # ---------------------------------------------------------------------
        # 3. Targets
        # ---------------------------------------------------------------------
        if self.mode != "test":
            # Extract probability columns
            target = row[
                [
                    "seizure_prob",
                    "lpd_prob",
                    "gpd_prob",
                    "lrda_prob",
                    "grda_prob",
                    "other_prob",
                ]
            ].values.astype(np.float32)
            target = torch.tensor(target)
        else:
            target = torch.zeros(self.config.NUM_CLASSES, dtype=torch.float32)

        return eeg_tensor, spec_input, target

    def process_eeg(self, path, offset):
        """
        Reads, crops, downsamples, and normalizes EEG data.
        """
        try:
            # Read Parquet
            df = pd.read_parquet(path, columns=EEG_CHANNELS)
        except Exception:
            # Fallback for missing columns or file errors
            return np.zeros(
                (self.config.EEG_SEQ_LEN, self.config.EEG_CHANNELS), dtype=np.float32
            )

        # Calculate indices
        # Original SR = 200Hz
        start_idx = int(offset * self.config.EEG_RAW_SR)
        end_idx = start_idx + int(self.config.EEG_DURATION * self.config.EEG_RAW_SR)

        # Handle bounds
        rows = len(df)
        if start_idx < 0:
            start_idx = 0
        if end_idx > rows:
            end_idx = rows

        # Crop
        crop = df.iloc[start_idx:end_idx].values

        # Pad if shorter than expected
        expected_len = int(self.config.EEG_DURATION * self.config.EEG_RAW_SR)
        if len(crop) < expected_len:
            pad_len = expected_len - len(crop)
            crop = np.pad(crop, ((0, pad_len), (0, 0)), mode="constant")

        # Handle NaNs
        crop = np.nan_to_num(crop, nan=0.0)

        # Downsample (200Hz -> 100Hz)
        downsampled = crop[::2, :]

        # Ensure exact length
        if len(downsampled) > self.config.EEG_SEQ_LEN:
            downsampled = downsampled[: self.config.EEG_SEQ_LEN]
        elif len(downsampled) < self.config.EEG_SEQ_LEN:
            pad = self.config.EEG_SEQ_LEN - len(downsampled)
            downsampled = np.pad(downsampled, ((0, pad), (0, 0)), mode="constant")

        # Normalize
        # Clip outliers first to avoid skewing mean/std
        downsampled = np.clip(downsampled, -1024, 1024)

        # Instance Normalization: (x - mean) / (std + eps) per channel
        mean = np.mean(downsampled, axis=0, keepdims=True)
        std = np.std(downsampled, axis=0, keepdims=True)
        downsampled = (downsampled - mean) / (std + 1e-6)

        # Replace any remaining NaNs
        downsampled = np.nan_to_num(downsampled, nan=0.0)

        return downsampled.astype(np.float32)

    def process_spec(self, path, offset):
        """
        Reads, crops, resizes, and log-transforms Spectrogram data.
        Returns shape (H, W, 4).
        """
        try:
            df = pd.read_parquet(path)
        except Exception:
            return np.zeros((*self.config.SPEC_SIZE, 4), dtype=np.float32)

        # Temporal Crop
        start_time = offset
        end_time = offset + self.config.SPEC_DURATION  # 600s

        if "time" in df.columns:
            mask = (df["time"] >= start_time) & (df["time"] < end_time)
            crop_df = df.loc[mask]
        else:
            # Fallback if no time column, assume rows correspond to time or take all
            crop_df = df

        if crop_df.empty:
            return np.zeros((*self.config.SPEC_SIZE, 4), dtype=np.float32)

        # Extract 4 regions
        img_layers = []
        for region in SPEC_REGIONS:
            # Filter columns for this region
            cols = [c for c in crop_df.columns if c.startswith(f"{region}_")]

            # Sort by frequency
            try:
                cols = sorted(cols, key=lambda x: float(x.split("_")[1]))
            except:
                pass

            if not cols:
                layer = np.zeros(
                    (self.config.SPEC_SIZE[0], self.config.SPEC_SIZE[1]),
                    dtype=np.float32,
                )
            else:
                vals = crop_df[cols].values
                vals = np.nan_to_num(vals, nan=0.0)

                # Log transform
                vals = np.log1p(vals)

                # Resize to target (H, W)
                # Input (Time, Freq). Output (H, W).
                # cv2.resize expects (W, H)
                layer = cv2.resize(
                    vals,
                    (self.config.SPEC_SIZE[1], self.config.SPEC_SIZE[0]),
                    interpolation=cv2.INTER_LINEAR,
                )

            img_layers.append(layer)

        # Stack: (H, W, 4)
        spec_img = np.stack(img_layers, axis=-1)

        # Standardize
        mean = spec_img.mean(axis=(0, 1), keepdims=True)
        std = spec_img.std(axis=(0, 1), keepdims=True)
        spec_img = (spec_img - mean) / (std + 1e-6)

        return spec_img.astype(np.float32)
