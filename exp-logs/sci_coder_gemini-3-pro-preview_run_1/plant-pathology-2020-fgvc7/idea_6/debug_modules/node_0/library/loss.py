import torch
import torch.nn as nn
import torch.nn.functional as F
import pandas as pd
import numpy as np
from library.config import Config
from library.utils import get_logger

logger = get_logger("loss")


def calculate_class_weights(metadata_path=Config.TRAIN_METADATA_PATH):
    """
    Calculates class weights based on the frequency in the training metadata.
    Uses Inverse Class Frequency: w_c = N_total / (N_classes * N_c)

    Args:
        metadata_path (str): Path to the training metadata CSV.

    Returns:
        torch.Tensor: Tensor of shape (Num_Classes,) containing weights.
    """
    try:
        logger.info(
            f"Loading metadata for class weight calculation from {metadata_path}"
        )
        df = pd.read_csv(metadata_path)

        # Ensure class columns exist
        missing_cols = [c for c in Config.CLASS_LABELS if c not in df.columns]
        if missing_cols:
            raise ValueError(f"Metadata missing class columns: {missing_cols}")

        # Count occurrences of each class (summing one-hot encoded columns)
        class_counts = df[Config.CLASS_LABELS].sum().values
        total_samples = len(df)
        n_classes = len(Config.CLASS_LABELS)

        # Handle potential zero counts to avoid division by zero
        class_counts = np.maximum(class_counts, 1)

        # Calculate weights
        weights = total_samples / (n_classes * class_counts)

        # Convert to tensor
        weight_tensor = torch.tensor(weights, dtype=torch.float32)

        logger.info(f"Class counts: {dict(zip(Config.CLASS_LABELS, class_counts))}")
        logger.info(f"Calculated weights: {dict(zip(Config.CLASS_LABELS, weights))}")

        return weight_tensor

    except Exception as e:
        logger.error(f"Failed to calculate class weights: {e}")
        # Fallback to uniform weights
        return torch.ones(len(Config.CLASS_LABELS), dtype=torch.float32)


class WeightedSoftCrossEntropy(nn.Module):
    """
    Custom Cross Entropy Loss that supports:
    1. Soft Targets (Probabilities) generated by Mixup/CutMix.
    2. Class Imbalance Weighting.
    """

    def __init__(self, weights=None, reduction="mean"):
        """
        Args:
            weights (torch.Tensor, optional): Pre-defined class weights.
                                              If None and Config.USE_CLASS_WEIGHTS is True,
                                              weights are calculated from metadata.
            reduction (str): Specifies the reduction to apply to the output: 'none' | 'mean' | 'sum'.
        """
        super(WeightedSoftCrossEntropy, self).__init__()
        self.reduction = reduction

        # Determine weights
        if weights is not None:
            self.weights = weights
        elif Config.USE_CLASS_WEIGHTS:
            self.weights = calculate_class_weights()
        else:
            self.weights = None

        # Move weights to configured device immediately if available
        if self.weights is not None:
            self.weights = self.weights.to(Config.DEVICE)

    def forward(self, logits, targets):
        """
        Computes the weighted soft cross entropy loss.

        Args:
            logits (torch.Tensor): Model predictions (logits) of shape (Batch, Num_Classes).
            targets (torch.Tensor): Soft targets of shape (Batch, Num_Classes).

        Returns:
            torch.Tensor: The calculated loss.
        """
        # Ensure inputs are on the same device
        device = logits.device

        # If targets are indices (Batch,), convert to One-Hot (Batch, Num_Classes)
        # This handles cases where Mixup/CutMix might be disabled or validation phase
        if targets.dim() == 1:
            targets = F.one_hot(targets.long(), num_classes=logits.size(1)).float()

        targets = targets.to(device)

        # Compute Log Softmax
        # log_probs shape: (Batch, Num_Classes)
        log_probs = F.log_softmax(logits, dim=1)

        # Apply Weights
        if self.weights is not None:
            # Ensure weights are on the correct device
            if self.weights.device != device:
                self.weights = self.weights.to(device)

            # Weighted Cross Entropy Formula: - sum( weight_c * target_c * log_prob_c )
            # We broadcast weights across the batch
            loss = -(targets * log_probs * self.weights).sum(dim=1)
        else:
            # Standard Soft Cross Entropy
            loss = -(targets * log_probs).sum(dim=1)

        # Apply Reduction
        if self.reduction == "mean":
            return loss.mean()
        elif self.reduction == "sum":
            return loss.sum()
        else:
            return loss
