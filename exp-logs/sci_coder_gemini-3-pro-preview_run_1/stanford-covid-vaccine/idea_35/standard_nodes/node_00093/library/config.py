    CACHE_TEST_PATH = os.path.join(WORKING_DIR, "test_data.npz")
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # --------------------------------------------------------------------------
    # Model Hyperparameters (Wide-Stream Residual BiGRU)
    # --------------------------------------------------------------------------
