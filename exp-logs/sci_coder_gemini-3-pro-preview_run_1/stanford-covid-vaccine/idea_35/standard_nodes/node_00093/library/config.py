    EMBEDDING_DIM = 128
    # Wide residual stream (256 per direction for BiGRU)
    HIDDEN_DIM = 512
    # Shallow and Wide backbone
    N_LAYERS = 6
    # Inter-Layer Dropout rate
    DROPOUT = 0.2

    # --------------------------------------------------------------------------
    # Data Parameters
    # --------------------------------------------------------------------------
    SEQ_LENGTH = 107
    PRED_LENGTH = 68

    # Column Definitions
    SEQUENCE_COL = "sequence"
    STRUCTURE_COL = "structure"
    LOOP_TYPE_COL = "predicted_loop_type"

