    TARGET_COLS = ["reactivity", "deg_Mg_pH10", "deg_Mg_50C"]

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    BATCH_SIZE = 64
    LEARNING_RATE = 1e-3
    # Low weight decay to allow recurrent signals to propagate
    WEIGHT_DECAY = 1e-4
    EPOCHS = 20
