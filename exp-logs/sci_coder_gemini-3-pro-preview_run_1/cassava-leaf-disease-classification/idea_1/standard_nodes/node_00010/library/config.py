import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration class for the Cassava Leaf Disease Classification task.
    Defines global hyperparameters, file paths, and utility methods.
    """

    # --- Random Seed ---
    SEED = 42

    # --- Data Hyperparameters ---
    IMG_SIZE = 300
    NUM_CLASSES = 5

    # --- Training Hyperparameters ---
    BATCH_SIZE = 32
    EPOCHS = 12
    LEARNING_RATE = 1e-4
    LABEL_SMOOTHING = 0.1

    # --- Compute ---
    # Use CUDA if available, otherwise CPU
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Number of workers for data loading (adjust based on vCPUs)
    NUM_WORKERS = 4

    # --- Paths ---
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata paths (generated by the metadata script)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Output paths
    WORKING_DIR = "./working/idea_1"
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --- Debugging / Development ---
    # Set DEBUG to True to run on a small subset of data for quick testing
    DEBUG = False
    DEBUG_SUBSET_SIZE = 100

    @staticmethod
    def setup_directories():
        """
        Ensures that the working and submission directories exist.
        """
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)

    @staticmethod
    def seed_everything(seed=42):
        """
        Sets the random seed for Python, NumPy, and PyTorch to ensure reproducibility.
        """
        random.seed(seed)
        os.environ["PYTHONHASHSEED"] = str(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            # Ensure deterministic behavior for cuDNN
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
