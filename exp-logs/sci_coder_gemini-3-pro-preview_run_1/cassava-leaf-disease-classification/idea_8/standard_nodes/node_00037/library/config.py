import os
import torch


class Config:
    """
    Configuration for Heterogeneous Cross-Validation Ensemble (HCVE)
    for Cassava Leaf Disease Classification.
    """

    # --- General Configuration ---
    seed = 42
    debug = False  # Set to True to run on a small subset for debugging
    num_classes = 5
    n_folds = 5  # 5-Fold Stratified Cross-Validation
    num_workers = 8  # Optimized for the available 12 vCPUs
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # --- Paths ---
    input_root = "./input"
    metadata_dir = "./metadata"

    # Metadata files generated by the provided script
    train_metadata_path = os.path.join(metadata_dir, "train.csv")
    val_metadata_path = os.path.join(metadata_dir, "val.csv")
    test_metadata_path = os.path.join(metadata_dir, "test.csv")

    # Output directory for checkpoints, logs, and predictions
    output_dir = "./working/idea_8"
    os.makedirs(output_dir, exist_ok=True)

    # --- Model Architecture ---
    # Heterogeneous Ensemble: ConvNeXt V2 (CNN) + Swin V2 (Transformer)
    model_names = [
        "convnextv2_base.fcmae_ft_in22k_in1k",
        "swinv2_tiny_window16_256.ms_in1k",
    ]

    # Custom Head & Pooling
    use_gem_pooling = True  # Generalized Mean Pooling
    use_multi_sample_dropout = True  # Multi-Sample Dropout Head
    msd_num_samples = 8
    msd_dropout_rate = 0.5

    # Regularization
    drop_path_rate = 0.0  # Disabled to avoid over-regularization

    # --- Training Strategy (Progressive Resizing & SWA) ---

    # Phase 1: Base Training
    p1_image_size = 384
    p1_batch_size = 32
    p1_accum_steps = 1  # Effective batch size = 32
    p1_epochs = 8
    p1_lr = 2e-4
    p1_warmup_epochs = 1

    # Phase 2: High-Resolution Fine-Tuning
    p2_image_size = 512
    p2_batch_size = 16  # Reduced due to memory constraints
    p2_accum_steps = 2  # Accumulate to maintain effective batch size = 32
    p2_epochs = 4
    p2_lr = 2e-5

    # Phase 3: Stochastic Weight Averaging (SWA)
    swa_epochs = 4
    swa_lr_start = 1e-5
    swa_lr_end = 1e-6
    swa_batch_size = 16
    swa_accum_steps = 2

    # --- Optimization ---
    optimizer_name = "AdamW"
    weight_decay = 0.01
    max_grad_norm = 1000.0

    # Layer-wise Learning Rate Decay (LLRD)
    llrd_decay = 0.8

    # --- Augmentation ---
    # MixUp & CutMix
    mixup_alpha = 0.8
    cutmix_alpha = 1.0
    mixup_prob = 0.5  # Probability of selecting MixUp vs CutMix
    enable_mixup_cutmix = True

    # Geometric
    random_crop_scale = (0.3, 1.0)  # Contextual cropping

    # --- Inference ---
    use_tta = True  # Test Time Augmentation (Horizontal & Vertical Flips)

    # --- Logging ---
    print_freq = 50
