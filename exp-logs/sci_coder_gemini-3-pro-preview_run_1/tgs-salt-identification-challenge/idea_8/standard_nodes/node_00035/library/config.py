import os
import torch
import numpy as np
import random


class Config:
    """
    Configuration for the Salt Segmentation Task.
    Implements the settings for Context-Aware Deep Residual U-Net with Lovasz-Cycle training.
    """

    # -------------------------------------------------------------------------
    # 1. General & Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 12  # Utilizing available vCPUs

    # -------------------------------------------------------------------------
    # 2. File Paths
    # -------------------------------------------------------------------------
    # Input Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    DEPTHS_CSV = os.path.join(INPUT_DIR, "depths.csv")

    # Output Directories
    WORKING_DIR = "./working/idea_8"
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    PREDICTIONS_DIR = os.path.join(WORKING_DIR, "predictions")
    SUBMISSION_PATH = "./submission/submission.csv"

    # -------------------------------------------------------------------------
    # 3. Data & Image Parameters
    # -------------------------------------------------------------------------
    ORIG_SIZE = 101
    IMAGE_SIZE = 128  # Padded size (Reflection padding)

    # Channels
    # Input: 1 channel (Grayscale Image) + 1 channel (Depth Map) = 2 Channels
    IN_CHANNELS = 2
    OUT_CHANNELS = 1  # Binary segmentation mask

    # -------------------------------------------------------------------------
    # 4. Model Hyperparameters
    # -------------------------------------------------------------------------
    # Backbone settings
    ENCODER_FILTERS = 64

    # -------------------------------------------------------------------------
    # 5. Training Hyperparameters (Lovasz-Cycle)
    # -------------------------------------------------------------------------
    BATCH_SIZE = 64
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Cycle Schedule
    # Total 150 epochs: 3 cycles of 50 epochs each
    NUM_EPOCHS = 150
    CYCLE_LENGTH = 50

    # -------------------------------------------------------------------------
    # 6. Debugging & Flexibility
    # -------------------------------------------------------------------------
    # Set DEBUG to True to run on a small subset of data for testing pipeline
    DEBUG = False
    DEBUG_SIZE = 100

    @staticmethod
    def set_seed(seed=42):
        """Sets the random seed for reproducibility."""
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        torch.cuda.manual_seed(seed)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False

    @classmethod
    def setup(cls):
        """Creates necessary working directories."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.PREDICTIONS_DIR, exist_ok=True)
        os.makedirs(os.path.dirname(cls.SUBMISSION_PATH), exist_ok=True)

        # Set seed immediately upon setup
        cls.set_seed(cls.SEED)
