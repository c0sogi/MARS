import os
import random
import numpy as np
import torch
from sklearn.metrics import mean_squared_error
from library.config import SEED


def seed_everything(seed=SEED):
    """
    Sets the random seed for Python, NumPy, and PyTorch to ensure
    full reproducibility of results.

    Args:
        seed (int): The random seed value.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)

    # Ensure deterministic behavior in CuDNN
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def worker_init_fn(worker_id):
    """
    Initialization function for PyTorch DataLoader workers to ensure
    deterministic data augmentation and loading.

    Args:
        worker_id (int): The ID of the worker process.
    """
    # Use the initial seed generated by PyTorch for this worker
    worker_seed = torch.initial_seed() % 2**32
    np.random.seed(worker_seed)
    random.seed(worker_seed)


def rmse_score(y_true, y_pred):
    """
    Computes the Root Mean Squared Error (RMSE) between the true and
    predicted pixel intensities.

    Args:
        y_true (np.array or torch.Tensor): The ground truth values.
        y_pred (np.array or torch.Tensor): The predicted values.

    Returns:
        float: The RMSE score.
    """
    # Convert PyTorch tensors to NumPy arrays if necessary
    if isinstance(y_true, torch.Tensor):
        y_true = y_true.detach().cpu().numpy()
    if isinstance(y_pred, torch.Tensor):
        y_pred = y_pred.detach().cpu().numpy()

    # Flatten the arrays to ensure element-wise comparison regardless of shape
    y_true_flat = y_true.flatten()
    y_pred_flat = y_pred.flatten()

    # Calculate MSE and then RMSE
    mse = mean_squared_error(y_true_flat, y_pred_flat)
    return np.sqrt(mse)
