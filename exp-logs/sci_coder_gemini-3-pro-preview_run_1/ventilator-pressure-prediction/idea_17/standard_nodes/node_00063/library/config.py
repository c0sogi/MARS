import os
import torch


class Config:
    """
    Configuration for the Wide-State Weight-Normalized Physics-Injected Composite Network.
    Centralizes all hyperparameters, file paths, and system settings.
    """

    # --------------------------------------------------------------------------
    # General & Reproducibility
    # --------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True for quick debugging (reduces data/epochs)
    EXPERIMENT_NAME = "idea_18"

    # --------------------------------------------------------------------------
    # Directories & File Paths
    # --------------------------------------------------------------------------
    # Metadata paths (generated by the provided metadata script)
    INPUT_DIR = "./metadata"
    TRAIN_PATH = os.path.join(INPUT_DIR, "train.csv")
    VAL_PATH = os.path.join(INPUT_DIR, "val.csv")
    TEST_PATH = os.path.join(INPUT_DIR, "test.csv")

    # Original input for sample submission format
    SAMPLE_SUBMISSION_PATH = "./input/sample_submission.csv"

    # Working directory for caching processed data (.parquet/.npy) and saving models
    WORKING_DIR = os.path.join("./working", EXPERIMENT_NAME)

    # Output directory for final submission file
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Model Architecture
    # --------------------------------------------------------------------------
    # Wide-State Composite Block settings
    HIDDEN_DIM = 512  # Base hidden dimension
    LSTM_LAYERS = 4  # Number of Composite Blocks (Depth)
    FFN_EXPANSION_FACTOR = (
        2  # Reduced expansion for stability (Cite solution_lesson_node_00052)
    )
    DROPOUT = 0.1

    # Deep Supervision
    USE_AUXILIARY_HEAD = True
    AUXILIARY_WEIGHT = 0.3  # Weight for the auxiliary loss (attached to Block 2)

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    # Optimization
    EPOCHS = 25 if not DEBUG else 2
    BATCH_SIZE = 512
    LEARNING_RATE = 1e-3  # Max LR for OneCycleLR
    WEIGHT_DECAY = 1e-2  # Standard AdamW weight decay
    PCT_START = 0.3  # Warmup percentage for OneCycleLR

    # Stability
    GRADIENT_CLIPPING = 1.0  # Strict clipping to stabilize Wide-State LSTM

    # --------------------------------------------------------------------------
    # Feature Engineering & Preprocessing
    # --------------------------------------------------------------------------
    USE_CACHE = True  # Enable caching of processed datasets
    NUM_WORKERS = 4  # DataLoader workers

    # Feature Flags
    N_LAGS = 4  # Number of lag steps (1 to 4)
    USE_DIFFERENCES = True  # Include 1st and 2nd derivatives of u_in
    PHYSICS_FEATURES = True  # Include Volume, u_in*R, Vol/C

    # --------------------------------------------------------------------------
    # Hardware
    # --------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Ensures necessary working and output directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories on import
Config.setup()
