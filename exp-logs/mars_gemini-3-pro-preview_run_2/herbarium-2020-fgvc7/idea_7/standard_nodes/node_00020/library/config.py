import os
import torch


class Config:
    """
    Configuration class for the Plant Species Classification task.
    Centralizes all hyperparameters, file paths, and compute settings.
    """

    def __init__(
        self, debug: bool = False, epochs_p1: int = None, epochs_p2: int = None
    ):
        """
        Initialize configuration with optional overrides for debugging and training duration.

        Args:
            debug (bool): If True, enables debug mode (smaller dataset, fewer epochs).
            epochs_p1 (int): Override number of epochs for Phase 1.
            epochs_p2 (int): Override number of epochs for Phase 2.
        """
        # --- General Settings ---
        self.SEED = 42
        self.DEBUG = debug

        # --- Directories ---
        self.INPUT_DIR = "./input"
        self.METADATA_DIR = "./metadata"
        self.WORK_DIR = "./working/idea_7"
        self.SUBMISSION_DIR = "./submission"

        # Create directories if they don't exist
        os.makedirs(self.WORK_DIR, exist_ok=True)
        os.makedirs(self.SUBMISSION_DIR, exist_ok=True)

        # --- Data Paths ---
        # Metadata CSVs generated by the separate metadata script
        self.TRAIN_CSV = os.path.join(self.METADATA_DIR, "train.csv")
        self.VAL_CSV = os.path.join(self.METADATA_DIR, "val.csv")
        self.TEST_CSV = os.path.join(self.METADATA_DIR, "test.csv")

        # Original JSON metadata for extracting taxonomy (Family/Genus)
        self.TRAIN_METADATA_JSON = os.path.join(
            self.INPUT_DIR, "nybg2020/train/metadata.json"
        )
        self.TEST_METADATA_JSON = os.path.join(
            self.INPUT_DIR, "nybg2020/test/metadata.json"
        )

        # --- Caching Paths ---
        # Path to store/load the processed taxonomy mapping (Category ID -> Genus/Family ID)
        self.TAXONOMY_MAP_PATH = os.path.join(self.WORK_DIR, "taxonomy_mapping.parquet")

        # --- Output Paths ---
        self.MODEL_SAVE_PATH = os.path.join(self.WORK_DIR, "best_model.pth")
        self.CHECKPOINT_PATH = os.path.join(self.WORK_DIR, "checkpoint.pth")
        self.SUBMISSION_PATH = os.path.join(self.SUBMISSION_DIR, "submission.csv")

        # --- Compute ---
        self.NUM_WORKERS = 12
        self.DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

        # --- Model Architecture ---
        self.BACKBONE = "tf_efficientnet_b3_ns"
        self.NUM_CLASSES = 32093  # Total species categories
        self.EMBEDDING_DIM = 1536  # EfficientNet-B3 output features

        # --- Training Hyperparameters ---

        # Phase 1: Coarse learning (Resize 224x224)
        # Faster training to learn high-level features (Family/Genus) and initialize backbone
        self.IMG_SIZE_P1 = 224
        self.BATCH_SIZE_P1 = 32  # Reduced to fit 16GB GPU
        self.LR_P1 = 1e-3
        self.EPOCHS_P1 = 4

        # Phase 2: Fine-grained refinement (Resize 300x300)
        # Higher resolution for species-specific details
        self.IMG_SIZE_P2 = 300
        self.BATCH_SIZE_P2 = 16  # Reduced to fit 16GB GPU
        self.LR_P2 = 1e-4
        self.EPOCHS_P2 = 6

        # Loss parameters
        self.FOCAL_LOSS_GAMMA = 2.0

        # --- Debug Overrides ---
        if self.DEBUG:
            self.BATCH_SIZE_P1 = 32
            self.BATCH_SIZE_P2 = 16
            self.EPOCHS_P1 = 1
            self.EPOCHS_P2 = 1
            self.DEBUG_SAMPLES = 5000  # Subset size for debugging

        # --- Manual Overrides ---
        if epochs_p1 is not None:
            self.EPOCHS_P1 = epochs_p1
        if epochs_p2 is not None:
            self.EPOCHS_P2 = epochs_p2

    def print_config(self):
        """Prints the current configuration."""
        print("=" * 30)
        print("CONFIG")
        print("=" * 30)
        for k, v in self.__dict__.items():
            print(f"{k}: {v}")
        print("=" * 30)
