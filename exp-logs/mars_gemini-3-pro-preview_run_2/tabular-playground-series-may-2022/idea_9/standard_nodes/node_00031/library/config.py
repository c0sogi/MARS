import os
import torch


class Config:
    # --------------------------------------------------------------------------
    # Directory & File Paths
    # --------------------------------------------------------------------------
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_9"

    # Ensure working directory exists
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Raw Data Paths
    TRAIN_PATH = os.path.join(INPUT_DIR, "train.csv")
    TEST_PATH = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Paths (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Paths
    PROCESSED_DATA_PATH = os.path.join(WORKING_DIR, "processed_data.npz")
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = "./submission/submission.csv"

    # --------------------------------------------------------------------------
    # Data Configuration
    # --------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4

    # Feature specifics
    NUM_CONT_FEATURES = 30  # f_00 to f_30 (excluding f_27)
    F_27_SEQ_LEN = 10  # Length of the string feature decomposition
    VOCAB_SIZE = 26 + 1  # A-Z + 1 for padding/unknown if needed (though data is clean)

    # --------------------------------------------------------------------------
    # Model Architecture (Hybrid Attention-ResFunnel-GLU)
    # --------------------------------------------------------------------------
    # Stream 1: Categorical / Sequence
    EMBED_DIM = 32
    TRANSFORMER_LAYERS = 1
    TRANSFORMER_HEADS = 4
    TRANSFORMER_FF_DIM = 128

    # Stream 2: Continuous
    # (Processed via BatchNorm in model)

    # Backbone: ResFunnel
    # Fusion dimension will be EMBED_DIM * F_27_SEQ_LEN + NUM_CONT_FEATURES
    # 32 * 10 + 30 = 350 -> Projected to 512
    HIDDEN_SIZES = [512, 256, 128]

    # Regularization
    DROPOUT_RATE = 0.35  # Aggressive dropout as per strategy

    # Activation
    USE_GLU = True

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    BATCH_SIZE = 2048  # Large batch size for stable gradients
    EPOCHS = 50  # Max epochs, controlled by early stopping

    # Optimizer settings (AdamW)
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2  # Aggressive weight decay as per strategy

    # Scheduler
    # Using simple step decay or constant, avoiding complex cycles
    LR_SCHEDULER_STEP_SIZE = 10
    LR_SCHEDULER_GAMMA = 0.5

    # Early Stopping
    PATIENCE = 10  # Stop if Val AUC doesn't improve for 10 epochs

    def __str__(self):
        """Helper to print configuration."""
        attributes = [
            a
            for a in dir(self)
            if not a.startswith("__") and not callable(getattr(self, a))
        ]
        config_str = "Config:\n"
        for attr in attributes:
            config_str += f"\t{attr}: {getattr(self, attr)}\n"
        return config_str
