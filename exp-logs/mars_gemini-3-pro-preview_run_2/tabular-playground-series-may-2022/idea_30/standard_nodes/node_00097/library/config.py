import os
import torch


class Config:
    """
    Global configuration for the RoPE-Enhanced SwiGLU-RMS Network project.
    Contains file paths, data parameters, model architecture specifications,
    and training hyperparameters.
    """

    # --------------------------------------------------------------------------
    # File System & Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Specific directory for this experimental idea (Idea 30)
    IDEA_DIR = os.path.join(WORKING_DIR, "idea_30")

    # Raw Data Paths
    TRAIN_PATH = os.path.join(INPUT_DIR, "train.csv")
    TEST_PATH = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Paths (Generated by metadata script)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Paths
    SUBMISSION_PATH = os.path.join(WORKING_DIR, "submission.csv")
    MODEL_PATH = os.path.join(IDEA_DIR, "best_model.pth")
    PROCESSED_DATA_PATH = os.path.join(IDEA_DIR, "processed_data.npz")

    # --------------------------------------------------------------------------
    # Data Configuration
    # --------------------------------------------------------------------------
    # Feature f_27 is a string of length 10
    SEQUENCE_LENGTH = 10
    # Vocabulary size for uppercase English letters (A-Z)
    VOCAB_SIZE = 26
    # Number of continuous numerical features (f_00 to f_30, excluding f_27)
    NUM_CONT_FEATURES = 30

    # --------------------------------------------------------------------------
    # Model Architecture: RoPE-Enhanced SwiGLU-RMS Network
    # --------------------------------------------------------------------------
    # Stream 1: Categorical Sequence (RoPE-Transformer)
    EMBED_DIM = 32
    TRANSFORMER_LAYERS = 2
    TRANSFORMER_HEADS = 4
    TRANSFORMER_DROPOUT = 0.1
    TRANSFORMER_ACTIVATION = "gelu"
    TRANSFORMER_NORM_FIRST = False  # Post-Normalization for shallow encoder
    USE_ROPE = True  # Rotary Positional Embeddings

    # Stream 2 & Fusion
    # Linear Stem maps concatenated features to this dimension
    BACKBONE_INPUT_DIM = 512

    # Backbone: RMSNorm-SwiGLU Funnel
    # Stages: 512 -> 256 -> 128
    BACKBONE_STAGES = [512, 256, 128]
    BLOCKS_PER_STAGE = 3

    # Backbone Regularization
    BACKBONE_DROPOUT = 0.35
    STOCHASTIC_DEPTH_MIN = 0.0
    STOCHASTIC_DEPTH_MAX = 0.2

    # Backbone Components
    ACTIVATION = "swiglu"
    NORM_TYPE = "rmsnorm"

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    SEED = 42

    # Optimization
    BATCH_SIZE = 1024
    EPOCHS = 40
    LEARNING_RATE = 1e-3

    # Weight Decay Groups
    # Group 1: Weights (Linear, Embeddings)
    WEIGHT_DECAY_WEIGHTS = 1e-2
    # Group 2: Biases, Norm parameters (Critical for Pre-Norm/RMSNorm stability)
    WEIGHT_DECAY_BIASES = 0.0

    # Scheduler: Aggressive Step Decay
    SCHEDULER_STEP_SIZE = 10
    SCHEDULER_GAMMA = 0.1

    # --------------------------------------------------------------------------
    # System & Debugging
    # --------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4

    # Debugging flags to control dataset size for rapid prototyping
    DEBUG = False
    DEBUG_SAMPLES = 10000

    @classmethod
    def setup(cls):
        """
        Ensures necessary directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.IDEA_DIR, exist_ok=True)
