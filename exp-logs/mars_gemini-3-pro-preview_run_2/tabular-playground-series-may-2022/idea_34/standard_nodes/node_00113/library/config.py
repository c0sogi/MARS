import os
import torch


class Config:
    """
    Global configuration for the Dual-View Post-Norm SwiGLU-ResFunnel Network strategy.
    Contains file paths, model architecture parameters, and training hyperparameters.
    """

    # --------------------------------------------------------------------------
    # General Configuration
    # --------------------------------------------------------------------------
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Utilizing available vCPUs as per environment description
    NUM_WORKERS = 12

    # --------------------------------------------------------------------------
    # File System Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_34"
    SUBMISSION_DIR = "./submission"

    # Metadata Paths (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Raw Data Paths
    TRAIN_DATA_PATH = os.path.join(INPUT_DIR, "train.csv")
    TEST_DATA_PATH = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Paths
    # The final submission must be saved here
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    # Cache path for processed data (numpy format)
    PROCESSED_DATA_PATH = os.path.join(WORKING_DIR, "processed_data.npz")
    # Path to save the best model checkpoint
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # --------------------------------------------------------------------------
    # Data Processing Hyperparameters
    # --------------------------------------------------------------------------
    SEQUENCE_LENGTH = 10  # Length of the f_27 string feature
    NUM_CONT_FEATURES = 30  # Number of continuous features (f_00 to f_30)
    VOCAB_SIZE = 26  # Cardinality for character embeddings (A-Z)

    # --------------------------------------------------------------------------
    # Model Architecture: Dual-View Post-Norm SwiGLU-ResFunnel
    # --------------------------------------------------------------------------
    # Common
    EMBEDDING_DIM = 32

    # Stream 1: Categorical (View A - Transformer)
    TRANSFORMER_LAYERS = 2
    TRANSFORMER_HEADS = 4
    TRANSFORMER_DROPOUT = 0.1
    TRANSFORMER_ACTIVATION = "gelu"

    # Backbone: SwiGLU ResFunnel
    # Stages: 512 -> 256 -> 128
    BACKBONE_STAGES = [512, 256, 128]
    # 2 Residual Blocks per stage (Cite solution_lesson_node_00075)
    BACKBONE_BLOCKS = [2, 2, 2]
    BACKBONE_DROPOUT = 0.35
    STOCHASTIC_DEPTH_MAX = 0.2

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    BATCH_SIZE = 1024
    EPOCHS = 40
    LEARNING_RATE = 1e-3

    # Optimizer & Regularization
    WEIGHT_DECAY = 1e-2

    # Scheduler: Step Decay
    SCHEDULER_STEP_SIZE = 10
    SCHEDULER_GAMMA = 0.1

    # --------------------------------------------------------------------------
    # Runtime / Debugging
    # --------------------------------------------------------------------------
    # These flags can be used by the training script to limit dataset size for testing
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 10000

    @classmethod
    def setup(cls):
        """
        Ensures that necessary working and submission directories exist.
        Should be called at the start of execution.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
