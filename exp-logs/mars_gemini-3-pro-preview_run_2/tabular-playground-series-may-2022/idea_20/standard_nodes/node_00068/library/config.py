import os
import torch


class Config:
    """
    Configuration for the Autoencoding Hybrid ResFunnel Network.
    Stores file paths, model architecture parameters, and training settings.
    """

    # --------------------------------------------------------------------------
    # 1. Directory & File Paths
    # --------------------------------------------------------------------------
    # Base Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_20"
    SUBMISSION_DIR = "./submission"

    # Ensure necessary output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Raw Data Files
    TRAIN_PATH = os.path.join(INPUT_DIR, "train.csv")
