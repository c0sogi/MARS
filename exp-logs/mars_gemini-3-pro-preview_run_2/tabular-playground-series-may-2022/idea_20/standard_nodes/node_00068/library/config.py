    # Backbone: Pre-Activation ResFunnel
    # Stages with decreasing width
    BACKBONE_STAGES = [512, 256, 128]
    BACKBONE_DROPOUT = 0.35

    # --------------------------------------------------------------------------
    # 4. Training Hyperparameters
    # --------------------------------------------------------------------------
    SEED = 42

    # Optimization
    BATCH_SIZE = 1024
    EPOCHS = 35  # Optimized for convergence (Cite solution_lesson_node_00045)
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2

    # Loss Function Weights
    # Standard Binary Classification
    # AUX_LOSS_LAMBDA removed (Cite solution_lesson_node_00065)

    # Scheduler (Standard Step Decay)
    SCHEDULER_STEP_SIZE = 10
    SCHEDULER_GAMMA = 0.1

    # --------------------------------------------------------------------------
    # 5. Runtime & Hardware
