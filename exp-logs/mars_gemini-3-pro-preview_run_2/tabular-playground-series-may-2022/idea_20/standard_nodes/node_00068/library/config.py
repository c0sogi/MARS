    # The dataset typically contains uppercase letters (A-Z).
    # We allocate 30 to cover A-Z (26) + padding/unknown tokens safely.
    VOCAB_SIZE = 30

    # Number of continuous features (f_00 to f_30, excluding f_27)
    NUM_CONTINUOUS_FEATURES = 30

