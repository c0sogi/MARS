import os
import torch


class Config:
    """
    Central configuration for the Global-Context Transformer-ResFunnel Hybrid project.
    """

    # --------------------------------------------------------------------------
    # Directory & File Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_12"

    # Create working directory if it doesn't exist
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Source Data
    TRAIN_CSV = os.path.join(INPUT_DIR, "train.csv")
    TEST_CSV = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata (Generated by separate script)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output & Caching
    PROCESSED_DATA_PATH = os.path.join(WORKING_DIR, "processed_data.npz")
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(WORKING_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Data Parameters
    # --------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4

    # Feature Specs
    # Continuous features: f_00-f_26 (27) + f_28-f_30 (3) = 30 total
    NUM_CONTINUOUS_FEATURES = 30

    # Sequence Specs (f_27)
    CHAR_SEQ_LEN = 10  # Length of the string in f_27
    VOCAB_SIZE = 30  # A-Z (26) + Special tokens. Safe upper bound.

    # Debugging / Development Flags
    DEBUG = False
    DEBUG_SAMPLES = 5000  # Subset size for rapid prototyping

    # --------------------------------------------------------------------------
    # Model Hyperparameters (Global-Context Transformer-ResFunnel Hybrid)
    # --------------------------------------------------------------------------
    EMBED_DIM = 32

    # Transformer Encoder (Stream 1 & 2 Fusion)
    TRANSFORMER_LAYERS = 2
    TRANSFORMER_HEADS = 4  # 32 dim / 4 heads = 8 dim per head
    TRANSFORMER_FF_DIM = 128

    # ResFunnel Backbone (Stream 3 Fusion & Exploitation)
    BACKBONE_WIDTHS = [512, 256, 128]
    DROPOUT_RATE = 0.35

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    EPOCHS = 40
    BATCH_SIZE = 1024

    # Optimization
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2  # High weight decay as per Idea

    # Scheduler (StepLR)
    SCHEDULER_STEP_SIZE = 10  # Decay every 10 epochs
    SCHEDULER_GAMMA = 0.1  # Decay factor

    # Validation
    EARLY_STOPPING_PATIENCE = 10  # Stop if Val AUC doesn't improve for 10 epochs

    @classmethod
    def print_config(cls):
        """Prints the current configuration setup."""
        print("\n" + "=" * 40)
        print(f"{'CONFIGURATION':^40}")
        print("=" * 40)
        for k, v in cls.__dict__.items():
            if not k.startswith("__") and not callable(v):
                print(f"{k:<30} {v}")
        print("=" * 40 + "\n")
