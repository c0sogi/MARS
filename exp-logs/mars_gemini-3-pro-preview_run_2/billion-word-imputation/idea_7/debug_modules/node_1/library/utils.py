import os
import torch
import nltk
from library.config import Config


def seed_everything(seed=Config.SEED):
    """
    Sets the random seed for reproducibility across Python, NumPy, and PyTorch
    by invoking the centralized configuration method.

    Args:
        seed (int): The seed value to set. Defaults to Config.SEED.
    """
    Config.set_seed(seed)


def save_model(model, path):
    """
    Saves the PyTorch model's state dictionary to the specified file path.
    Creates the parent directory if it does not exist.

    Args:
        model (torch.nn.Module): The model to save.
        path (str): The file path where the state dict should be saved.
    """
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    torch.save(model.state_dict(), path)


def load_model(model, path, device=Config.DEVICE):
    """
    Loads a state dictionary into a PyTorch model from the specified file path.

    Args:
        model (torch.nn.Module): The model instance to load weights into.
        path (str): The file path of the saved state dict.
        device (torch.device): The device to map the loaded weights to. Defaults to Config.DEVICE.

    Returns:
        torch.nn.Module: The model with loaded weights.

    Raises:
        FileNotFoundError: If the checkpoint file does not exist.
    """
    if not os.path.exists(path):
        raise FileNotFoundError(f"Checkpoint not found at {path}")

    state_dict = torch.load(path, map_location=device)
    model.load_state_dict(state_dict)
    return model


def compute_levenshtein_distance(predicted_sentences, target_sentences):
    """
    Computes the average Levenshtein distance between a list of predicted sentences
    and a list of target sentences.

    Args:
        predicted_sentences (list of str): The sentences generated by the model.
        target_sentences (list of str): The ground truth sentences.

    Returns:
        float: The average Levenshtein distance over the batch.
    """
    if len(predicted_sentences) != len(target_sentences):
        raise ValueError(
            f"Batch size mismatch: {len(predicted_sentences)} predictions vs {len(target_sentences)} targets."
        )

    total_distance = 0
    count = len(predicted_sentences)

    if count == 0:
        return 0.0

    for pred, target in zip(predicted_sentences, target_sentences):
        # nltk.edit_distance calculates the number of edits (insertions, deletions, substitutions)
        # required to change one string into the other.
        dist = nltk.edit_distance(pred, target)
        total_distance += dist

    return total_distance / count
