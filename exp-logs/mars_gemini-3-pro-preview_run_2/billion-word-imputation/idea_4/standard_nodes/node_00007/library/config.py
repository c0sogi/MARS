import os
import torch
from dataclasses import dataclass


@dataclass
class Config:
    """
    Global configuration for the Two-Stage Cascade (Locator + In-Filler) model.
    """

    # -------------------------------------------------------------------------
    # Paths & Directories
    # -------------------------------------------------------------------------
    PROJECT_NAME: str = "idea_4"
    WORKING_DIR: str = f"./working/{PROJECT_NAME}/"
    SUBMISSION_DIR: str = "./submission/"
    SUBMISSION_PATH: str = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Metadata Inputs (Generated by metadata script)
    TRAIN_METADATA: str = "./metadata/train.parquet"
    VAL_METADATA: str = "./metadata/val.parquet"
    TEST_METADATA: str = "./metadata/test.parquet"

    # -------------------------------------------------------------------------
    # Model Architectures
    # -------------------------------------------------------------------------
    # Stage 1: Locator (Structural Encoder)
    # Lightweight model to predict the position of the missing word.
    LOCATOR_MODEL: str = "distilroberta-base"

    # Stage 2: In-Filler (Semantic Decoder)
    # High-capacity model to predict the missing word via Masked Language Modeling.
    INFILLER_MODEL: str = "roberta-base"

    # -------------------------------------------------------------------------
    # Data Processing
    # -------------------------------------------------------------------------
    # Max sequence length. Mean sentence length is ~25 words.
    # 128 covers >99.9% of cases while keeping training fast.
    MAX_LEN: int = 128

    # -------------------------------------------------------------------------
    # Compute & Hardware
    # -------------------------------------------------------------------------
    SEED: int = 42
    DEVICE: str = "cuda" if torch.cuda.is_available() else "cpu"
    # Using 12 vCPUs for data loading
    NUM_WORKERS: int = 12
    PIN_MEMORY: bool = True

    # -------------------------------------------------------------------------
    # Training / Debugging
    # -------------------------------------------------------------------------
    # Set to True to run on a small subset for code verification
    DEBUG: bool = False
    DEBUG_SIZE: int = 20000

    # -------------------------------------------------------------------------
    # Hyperparameters: Stage 1 (Locator)
    # -------------------------------------------------------------------------
    # A100 40GB can handle large batches for DistilRoberta
    LOCATOR_BATCH_SIZE: int = 256
    LOCATOR_LR: float = 3e-5
    LOCATOR_EPOCHS: int = 2
    LOCATOR_WEIGHT_DECAY: float = 0.01
    LOCATOR_WARMUP_RATIO: float = 0.06

    # -------------------------------------------------------------------------
    # Hyperparameters: Stage 2 (In-Filler)
    # -------------------------------------------------------------------------
    # Smaller batch size for the larger Roberta Base model
    INFILLER_BATCH_SIZE: int = 128
    INFILLER_LR: float = 2e-5
    INFILLER_EPOCHS: int = 1  # MLM fine-tuning converges quickly
    INFILLER_WEIGHT_DECAY: float = 0.01
    INFILLER_WARMUP_RATIO: float = 0.06
    INFILLER_MASK_PROB: float = 0.15

    def __post_init__(self):
        """
        Setup directories and adjust config based on flags.
        """
        # Ensure working and submission directories exist
        os.makedirs(self.WORKING_DIR, exist_ok=True)
        os.makedirs(self.SUBMISSION_DIR, exist_ok=True)

        if self.DEBUG:
            print(f"[{self.__class__.__name__}] DEBUG mode enabled.")
            print(
                f"[{self.__class__.__name__}] Training on subset of {self.DEBUG_SIZE} samples."
            )
            # Reduce epochs for rapid debugging
            self.LOCATOR_EPOCHS = 1
            self.INFILLER_EPOCHS = 1
