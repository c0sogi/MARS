import os
import torch


class Config:
    """
    Global configuration for the Ventilator Pressure Prediction task.
    Implements the settings for the Deep Front-Loaded Gated-Injection BiLSTM (DFL-GI-BiLSTM).
    """

    # ==========================================
    # 1. Hardware & Environment
    # ==========================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # 12 vCPUs available, leaving some overhead
    NUM_WORKERS = 8

    # ==========================================
    # 2. Directories & File Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_14"

    # Ensure working directory exists for caching and outputs
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Raw Data Files
    TRAIN_CSV = os.path.join(INPUT_DIR, "train.csv")
    TEST_CSV = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Files (Generated by previous steps)
    TRAIN_META = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Caching Artifacts (Deterministic Processing)
    # Using Parquet for efficient I/O of processed dataframes
    TRAIN_CACHE = os.path.join(WORKING_DIR, "train_processed.parquet")
    VAL_CACHE = os.path.join(WORKING_DIR, "val_processed.parquet")
    TEST_CACHE = os.path.join(WORKING_DIR, "test_processed.parquet")

    # Scaler Parameters (RobustScaler statistics: median, IQR)
    SCALER_PARAMS_PATH = os.path.join(WORKING_DIR, "scaler_params.npz")

    # Model Checkpoints & Output
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(WORKING_DIR, "submission.csv")

    # ==========================================
    # 3. Data Processing Hyperparameters
    # ==========================================
    SEQ_LEN = 80  # Fixed breath length in this dataset

    # Debugging / Development
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 2000  # Number of breaths to use if DEBUG is True

    # Feature Engineering Configuration
    # Raw columns to load
    RAW_COLS = ["id", "breath_id", "R", "C", "time_step", "u_in", "u_out", "pressure"]
    TEST_RAW_COLS = ["id", "breath_id", "R", "C", "time_step", "u_in", "u_out"]

    # Final Feature List for Model Input
    # Includes raw controls, lung attributes, and physics-based engineered features
    INPUT_FEATURES = [
        "time_step",
        "u_in",
        "u_out",
        "R",
        "C",
        # Engineered Physics Features
        "dt",  # Time delta
        "u_in_cumsum",  # Time-weighted volume integration
        "R_u_in",  # Resistive pressure interaction
        "u_in_cumsum_C",  # Elastic pressure interaction
        # Dynamics
        "u_in_lag1",
        "u_in_lag2",
        "u_in_diff1",
        "u_in_diff2",
    ]

    INPUT_DIM = len(INPUT_FEATURES)

    # ==========================================
    # 4. Model Architecture (DFL-GI-BiLSTM)
    # ==========================================
    # Deep Front-End
    FRONT_END_LAYERS = 3  # Depth of the Gated Residual MLP before LSTM

    # Recurrent Backbone
    LSTM_HIDDEN_DIM = 512
    LSTM_LAYERS = 4

    # Injection & Bottleneck
    BOTTLENECK_DIM = 128  # Dimension of the "Physics Context" injection

    # Regularization
    DROPOUT = 0.1

    # ==========================================
    # 5. Training Protocol
    # ==========================================
    # Stretched-Horizon Convergence
    EPOCHS = 200
    BATCH_SIZE = 256  # Optimized for A100 GPU

    # Optimizer (AdamW)
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2

    # Scheduler (Cosine Annealing)
    T_MAX = 200  # Matches EPOCHS for full cosine cycle
    ETA_MIN = 1e-6

    # Weighted L1 Loss
    INSPIRATORY_WEIGHT = 1.0
    EXPIRATORY_WEIGHT = 0.1  # Lower weight for expiratory phase (not scored)
