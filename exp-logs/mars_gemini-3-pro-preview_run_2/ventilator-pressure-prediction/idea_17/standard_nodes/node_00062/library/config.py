import os
import torch


class Config:
    """
    Central configuration for the Ventilator Pressure Prediction task.
    Implements the settings for the Parallel-Context Gated-Injection BiLSTM (PC-GI-BiLSTM)
    and the Robust Physics-Fidelity Engineering pipeline.
    """

    # ==========================================
    # Global Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for testing
    DEBUG_BREATHS = 2000  # Number of breaths to use in debug mode
    NUM_WORKERS = 12  # Utilizing available vCPUs
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================
    # Directory & File Paths
    # ==========================================
    # Read-only inputs
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Experiment-specific working directory
    WORKING_DIR = "./working/idea_18"

    # Sub-directories for artifacts
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = "./submission"

    # Input Data Files
    TRAIN_CSV = os.path.join(INPUT_DIR, "train.csv")
    TEST_CSV = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Files (Generated by previous steps)
    TRAIN_META = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Files
    BEST_MODEL_PATH = os.path.join(CHECKPOINT_DIR, "best_model.pth")
    SCALER_PATH = os.path.join(CACHE_DIR, "scaler_params.npz")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Feature Engineering
    # ==========================================
    # Scaling
    USE_ROBUST_SCALER = True
    ROBUST_Q_MIN = 25.0
    ROBUST_Q_MAX = 75.0

    # Physics & Dynamics
    # Time-weighted integration for volume: cumsum(u_in * dt)
    USE_TIME_WEIGHTED_INTEGRATION = True

    # Explicit Dynamics
    # Past lags and finite differences (derivatives)
    # Note: Future lags are strictly excluded to prevent leakage/overfitting
    LAGS = [1, 2, 3, 4]
    DIFFS = [1, 2]

    # Column Definitions
    ID_COL = "id"
    BREATH_COL = "breath_id"
    TIME_COL = "time_step"
    TARGET_COL = "pressure"

    # Raw features available in dataset
    COLS_CONT = ["time_step", "u_in", "R", "C"]
    COLS_CAT = ["u_out"]

    # ==========================================
    # Model Architecture (PC-GI-BiLSTM)
    # ==========================================
    # Backbone
    LSTM_HIDDEN_DIM = 512
    LSTM_LAYERS = 4
    USE_BIDIRECTIONAL = True

    # Context & Injection
    # "Mild Bottleneck" for fusion of parallel context branches
    BOTTLENECK_DIM = 128

    # Regularization
    DROPOUT = 0.1

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    # Stretched-Horizon Protocol
    EPOCHS = 200
    BATCH_SIZE = 256  # A100 40GB allows large batches

    # Optimizer (AdamW)
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2

    # Scheduler (Cosine Annealing)
    SCHEDULER_T_MAX = 200  # Matches epochs for full stretch
    SCHEDULER_ETA_MIN = 1e-6

    # Loss Function (Weighted L1)
    # Higher weight for inspiratory phase (scored), lower for expiratory
    LOSS_INSPIRATORY_WEIGHT = 1.0
    LOSS_EXPIRATORY_WEIGHT = 0.1

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 30  # Allow fluctuation for convergence

    @classmethod
    def setup(cls):
        """
        Ensures all necessary working directories exist.
        Should be called at the start of the pipeline.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        print(f"Directories initialized at {cls.WORKING_DIR}")
