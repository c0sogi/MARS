import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration class for the AG-CAC-ResUNet denoising task.
    Centralizes all file paths, hyperparameters, and global settings.
    """

    # --- Reproducibility ---
    SEED = 42

    # --- Directories ---
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Specific working directory for Idea 6
    WORKING_DIR = "./working/idea_6"
    SUBMISSION_DIR = "./submission"

    # Create necessary directories
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # --- File Paths ---
    # Metadata files generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Model checkpoints and outputs
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "ag_cac_resunet_best.pth")
    SUBMISSION_FILE_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sampleSubmission.csv")

    # --- Data Parameters ---
    PATCH_SIZE = 128
    # High-density sampling: number of random patches to extract per image per epoch
    PATCHES_PER_IMAGE = 100
    NUM_WORKERS = 8

    # --- Model Architecture ---
    IN_CHANNELS = 1
    OUT_CHANNELS = 1
    BASE_FILTERS = 64

    # Architectural Toggles
    USE_COORDINATE_ATTENTION = True
    USE_ASPP = True
    USE_ATTENTION_GATES = True

    # --- Training Hyperparameters ---
    NUM_EPOCHS = 100
    BATCH_SIZE = 64  # A100 allows for larger batch sizes
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2  # Strong regularization as per idea
    EARLY_STOPPING_PATIENCE = 15

    # --- Inference ---
    # Overlap for tiled inference to reduce boundary artifacts
    INFERENCE_OVERLAP = 0.5

    # --- Compute ---
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @staticmethod
    def set_seed(seed=42):
        """
        Sets the random seed for reproducibility across Python, NumPy, and PyTorch.
        """
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            # Ensure deterministic behavior
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
