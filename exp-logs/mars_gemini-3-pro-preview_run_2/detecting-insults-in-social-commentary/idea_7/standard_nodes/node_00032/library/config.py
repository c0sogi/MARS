import os
import torch


class Config:
    # =========================================================================
    # General Settings
    # =========================================================================
    seed = 42
    num_workers = 4
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print_freq = 50

    # =========================================================================
    # File Paths
    # =========================================================================
    input_dir = "./input"
    metadata_dir = "./metadata"
    working_dir = "./working/idea_7"
    submission_dir = "./submission"

    # Input Files (Generated by metadata script)
    train_path = os.path.join(metadata_dir, "train.csv")
    val_path = os.path.join(metadata_dir, "val.csv")
    test_path = os.path.join(metadata_dir, "test.csv")

    # Output Files
    submission_path = os.path.join(submission_dir, "submission.csv")

    # Artifact Directories
    tapt_output_dir = os.path.join(working_dir, "tapt_output")
    teacher_output_dir = os.path.join(working_dir, "teacher_output")
    student_output_dir = os.path.join(working_dir, "student_output")

    # =========================================================================
    # Model Architecture
    # =========================================================================
    model_name = "microsoft/deberta-v3-large"
    max_len = 128
    target_col = "Insult"
    input_col = "Comment"
    num_classes = 1

    # Head Settings
    fc_dropout = 0.2
    use_multi_sample_dropout = True

    # =========================================================================
    # Stage 1: Task-Adaptive Pre-Training (TAPT)
    # =========================================================================
    tapt_epochs = 3
    tapt_batch_size = 8
    tapt_lr = 2e-5
    tapt_weight_decay = 0.01
    mlm_probability = 0.15

    # =========================================================================
    # Stage 2: Teacher Training (Standard Fine-Tuning)
    # =========================================================================
    n_folds = 5
    teacher_epochs = 4
    teacher_batch_size = 8
    teacher_lr = 1e-5
    teacher_weight_decay = 0.01
    teacher_patience = 3  # Early stopping patience

    # Optimization
    scheduler_type = "cosine"
    warmup_ratio = 0.1
    max_grad_norm = 1.0

    # =========================================================================
    # Pseudo-Labeling
    # =========================================================================
    # Samples with prob > high or prob < low are added to student train set
    conf_thresh_high = 0.9
    conf_thresh_low = 0.1

    # =========================================================================
    # Stage 3: Student Training (Adversarial Self-Training)
    # =========================================================================
    student_epochs = 6
    student_batch_size = 8
    student_lr = 1e-5
    student_weight_decay = 0.01

    # Adversarial Weight Perturbation (AWP)
    use_awp = True
    awp_start_epoch = 1  # Start AWP after the first epoch
    awp_eps = 1e-4  # Perturbation size
    awp_lr = 1e-4  # Learning rate for AWP

    @classmethod
    def setup(cls):
        """Creates necessary directories."""
        os.makedirs(cls.working_dir, exist_ok=True)
        os.makedirs(cls.submission_dir, exist_ok=True)
        os.makedirs(cls.tapt_output_dir, exist_ok=True)
        os.makedirs(cls.teacher_output_dir, exist_ok=True)
        os.makedirs(cls.student_output_dir, exist_ok=True)

        # Set environment variables for reproducibility
        os.environ["PYTHONHASHSEED"] = str(cls.seed)
