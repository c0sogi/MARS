import os


class Config:
    """
    Project-wide configuration and hyperparameters.
    """

    # ---------------------------------------------------------
    # Reproducibility
    # ---------------------------------------------------------
    SEED = 42

    # ---------------------------------------------------------
    # Directories
    # ---------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory specific to the current idea (idea_3)
    WORK_DIR = "./working/idea_3"
    SUBMISSION_DIR = "./submission"

    # ---------------------------------------------------------
    # File Paths
    # ---------------------------------------------------------
    # Metadata paths generated by the metadata script
    TRAIN_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Final submission path
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ---------------------------------------------------------
    # Data Processing Hyperparameters
    # ---------------------------------------------------------
    # Vocabulary size for the CountVectorizer (Bag-of-Words)
    VOCAB_SIZE = 50000

    # Number of top frequent tags to predict
    TOP_K_TAGS = 5000

    # N-gram range for vectorization (Unigrams and Bigrams as per Idea)
    NGRAM_RANGE = (1, 2)

    # Minimum document frequency for a term to be included
    MIN_DF = 2

    # ---------------------------------------------------------
    # Model Hyperparameters (Multinomial Naive Bayes)
    # ---------------------------------------------------------
    # Additive (Laplace/Lidstone) smoothing parameter (0 for no smoothing).
    SMOOTHING_ALPHA = 1.0

    # ---------------------------------------------------------
    # Compute / Runtime Parameters
    # ---------------------------------------------------------
    # Number of CPU workers available
    NUM_WORKERS = 12

    # Batch size for processing large datasets in chunks
    BATCH_SIZE = 25000

    @classmethod
    def setup(cls):
        """
        Ensures that the necessary working and submission directories exist.
        This is called automatically when the module is imported.
        """
        os.makedirs(cls.WORK_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories on module import
Config.setup()
