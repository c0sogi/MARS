import os
import torch


class Config:
    """
    Centralized configuration for the Hybrid Wide-and-Deep Tag Prediction Task.
    Includes file paths, data hyperparameters, model architecture settings,
    and training configurations.
    """

    # --------------------------------------------------------------------------
    # 1. System & Reproducibility
    # --------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4  # Number of dataloader workers
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # --------------------------------------------------------------------------
    # 2. File Paths
    # --------------------------------------------------------------------------
    # Base Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_8"
    SUBMISSION_DIR = "./submission"

    # Ensure working and submission directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Input Metadata Paths (Generated by metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output Submission Path
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache File Paths (for deterministic data processing)
    # We use .npy/.npz for numerical arrays and .parquet for dataframes
    # Wide features (TF-IDF) are sparse, so .npz is appropriate
    # Deep features (Token IDs) are dense integers, so .npy is appropriate

    # Encoders/Vectorizers
    TAG_ENCODER_PATH = os.path.join(WORKING_DIR, "tag_encoder.json")  # Mapping for tags
    TFIDF_VECTORIZER_PATH = os.path.join(
        WORKING_DIR, "tfidf_vectorizer.joblib"
    )  # Sklearn vectorizer
    VOCAB_PATH = os.path.join(WORKING_DIR, "vocab.json")  # Tokenizer vocabulary

    # Processed Data - Training
    TRAIN_WIDE_PATH = os.path.join(WORKING_DIR, "train_wide.npz")
    TRAIN_DEEP_PATH = os.path.join(WORKING_DIR, "train_deep.npy")
    TRAIN_LABELS_PATH = os.path.join(
        WORKING_DIR, "train_labels.npz"
    )  # Sparse matrix for multi-hot

    # Processed Data - Validation
    VAL_WIDE_PATH = os.path.join(WORKING_DIR, "val_wide.npz")
    VAL_DEEP_PATH = os.path.join(WORKING_DIR, "val_deep.npy")
    VAL_LABELS_PATH = os.path.join(WORKING_DIR, "val_labels.npz")

    # Processed Data - Test
    TEST_WIDE_PATH = os.path.join(WORKING_DIR, "test_wide.npz")
    TEST_DEEP_PATH = os.path.join(WORKING_DIR, "test_deep.npy")
    TEST_IDS_PATH = os.path.join(WORKING_DIR, "test_ids.npy")

    # Model Checkpoint
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # --------------------------------------------------------------------------
    # 3. Data Hyperparameters
    # --------------------------------------------------------------------------
    # Text Processing
    VOCAB_SIZE = 50000  # Top N words for Deep component
    MAX_LEN = 200  # Max sequence length for Deep component
    TFIDF_MAX_FEATURES = 150000  # Top N n-grams for Wide component

    # Target Processing
    NUM_CLASSES = 5000  # Top N most frequent tags to predict

    # --------------------------------------------------------------------------
    # 4. Model Architecture
    # --------------------------------------------------------------------------
    # Deep Component (TextCNN + Attention)
    EMBEDDING_DIM = 300  # Dimension of word embeddings
    FILTER_SIZES = [3, 4, 5]  # Kernel sizes for 1D Convolutions
    NUM_FILTERS = 128  # Number of filters per kernel size
    ATTENTION_DIM = 256  # Dimension for Attention Pooling projection

    # Wide Component
    # (Input dimension is determined by TFIDF_MAX_FEATURES)

    # Regularization
    DROPOUT = 0.3  # Dropout rate

    # --------------------------------------------------------------------------
    # 5. Training Settings
    # --------------------------------------------------------------------------
    BATCH_SIZE = 512  # Large batch size for A100
    LEARNING_RATE = 1e-3  # AdamW default
    WEIGHT_DECAY = 1e-5  # AdamW weight decay
    EPOCHS = 10  # Maximum epochs (with early stopping)

    # Loss Function (Focal Loss)
    FOCAL_LOSS_GAMMA = 2.0  # Focusing parameter

    # Mixed Precision
    USE_AMP = True  # Use Automatic Mixed Precision (FP16)

    # --------------------------------------------------------------------------
    # 6. Debugging / Development
    # --------------------------------------------------------------------------
    DEBUG = False  # Set to True to run on a small subset
    DEBUG_SIZE = 50000  # Number of samples if DEBUG is True

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print(f"{'='*20} CONFIGURATION {'='*20}")
        for k, v in cls.__dict__.items():
            if not k.startswith("__") and not callable(v):
                print(f"{k}: {v}")
        print("=" * 55)
