import os
import torch


class Config:
    """
    Configuration for the Multi-Contrast Single-Instance Network (MC-SIN) pipeline.
    Centralizes all hyperparameters, paths, and constants.
    """

    # -------------------------------------------------------------------------
    # Directories & Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_11"
    SUBMISSION_DIR = "./submission"

    # Ensure output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata File Paths (Generated by the provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output File Paths
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache Directory for processed data
    CACHE_DIR = WORKING_DIR

    # -------------------------------------------------------------------------
    # Data Configuration
    # -------------------------------------------------------------------------
    # Image Resolution: Balanced for performance and detail
    IMG_SIZE = (640, 640)

    # Input Channels: 3 (1: Standard, 2: CLAHE, 3: Gamma Corrected)
    IN_CHANNELS = 3

    # Batch Size: Tuned for A100 40GB with 640x640 resolution
    BATCH_SIZE = 24

    # Number of DataLoader workers (12 vCPUs available)
    NUM_WORKERS = 8

    # Pin memory for faster host-to-device transfer
    PIN_MEMORY = True

    # Debugging: If True, limits dataset size for rapid testing
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 2000

    # -------------------------------------------------------------------------
    # Model Configuration
    # -------------------------------------------------------------------------
    # Architecture: EfficientNetV2-Small (timm)
    # Selected for balance of speed and accuracy on grayscale textures
    MODEL_NAME = "tf_efficientnetv2_s.in1k"

    # Use ImageNet pretrained weights
    PRETRAINED = True

    # Number of output classes (Binary: Cancer vs Normal)
    NUM_CLASSES = 1

    # Regularization
    DROP_RATE = 0.2
    DROP_PATH_RATE = 0.1

    # -------------------------------------------------------------------------
    # Training Configuration
    # -------------------------------------------------------------------------
    # Random Seed for full reproducibility
    SEED = 42

    # Training Duration
    EPOCHS = 5

    # Optimization (AdamW + OneCycleLR)
    LEARNING_RATE = 5e-4
    WEIGHT_DECAY = 1e-2
    MAX_GRAD_NORM = 10.0

    # Loss Function: BCEWithLogitsLoss
    # High positive weight to aggressively target the minority class (~2% prevalence)
    # Note: Must be used with float32 context in training loop
    POS_WEIGHT = 20.0

    # Mixed Precision Training
    USE_AMP = True

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 3

    # -------------------------------------------------------------------------
    # Preprocessing / Multi-Contrast Configuration
    # -------------------------------------------------------------------------
    # CLAHE (Contrast Limited Adaptive Histogram Equalization)
    CLAHE_CLIP_LIMIT = 2.0
    CLAHE_TILE_GRID_SIZE = (8, 8)

    # Gamma Correction (Values > 1 darken image, suppressing background noise)
    GAMMA_VALUE = 2.0

    # -------------------------------------------------------------------------
    # Hardware
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
