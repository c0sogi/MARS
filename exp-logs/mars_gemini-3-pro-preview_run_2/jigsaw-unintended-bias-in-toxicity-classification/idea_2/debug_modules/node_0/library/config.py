import os
import torch


class Config:
    # --------------------------------------------------------------------------
    # General Setup
    # --------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to use a small subset of data for debugging
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # --------------------------------------------------------------------------
    # Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_2"
    SUBMISSION_DIR = "./submission"

    # Metadata Files (Generated by the provided script)
    # These define the stratified splits and contain labels/attributes
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VALIDATION_METADATA_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Raw Data Files (Source of text content)
    # Downstream modules will merge metadata with these files on 'id'
    TRAIN_TEXT_PATH = os.path.join(INPUT_DIR, "train.csv")
    TEST_TEXT_PATH = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Artifacts
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    PREDICTION_SAVE_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    TOKENIZER_SAVE_DIR = os.path.join(WORKING_DIR, "tokenizer")

    # --------------------------------------------------------------------------
    # Model Architecture & LoRA Settings
    # --------------------------------------------------------------------------
    MODEL_NAME = "roberta-base"
    MAX_LEN = 256  # Max sequence length (EDA indicates mean char len ~300, so 256 tokens is ample)

    # Low-Rank Adaptation (LoRA) Hyperparameters
    USE_LORA = True
    LORA_R = 8
    LORA_ALPHA = 16
    LORA_DROPOUT = 0.05
    LORA_TARGET_MODULES = [
        "query",
        "value",
    ]  # Apply LoRA to attention projection layers

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    EPOCHS = 3
    TRAIN_BATCH_SIZE = 64
    VALID_BATCH_SIZE = 128

    # Optimizer & Scheduler
    LEARNING_RATE = 2e-4  # Higher LR is generally safe and effective for LoRA
    WEIGHT_DECAY = 0.01
    WARMUP_RATIO = 0.1
    MAX_GRAD_NORM = 1.0

    # Aggressive Multi-Task Loss Weights
    # Total Loss = TOXICITY_WEIGHT * BCE(Toxicity) + IDENTITY_WEIGHT * BCE(Identities)
    TOXICITY_LOSS_WEIGHT = 1.0
    IDENTITY_LOSS_WEIGHT = 0.8

    # --------------------------------------------------------------------------
    # Data Columns
    # --------------------------------------------------------------------------
    TARGET_COL = "target"

    # Identity Columns: Used for the secondary loss task and Bias AUC metrics
    IDENTITY_COLS = [
        "male",
        "female",
        "homosexual_gay_or_lesbian",
        "christian",
        "jewish",
        "muslim",
        "black",
        "white",
        "psychiatric_or_mental_illness",
    ]

    # Auxiliary Toxicity Subtypes: Available in data for potential extra supervision
    AUX_TOXICITY_COLS = [
        "severe_toxicity",
        "obscene",
        "threat",
        "insult",
        "identity_attack",
        "sexual_explicit",
    ]

    @classmethod
    def setup(cls):
        """Creates necessary working and submission directories."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        os.makedirs(cls.TOKENIZER_SAVE_DIR, exist_ok=True)
