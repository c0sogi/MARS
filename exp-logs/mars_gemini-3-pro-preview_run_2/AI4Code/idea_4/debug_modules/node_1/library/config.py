import os
import torch


class Config:
    """
    Configuration class for the Notebook Cell Ordering task.
    Centralizes file paths, hyperparameters, and model settings.
    """

    # --------------------------------------------------------------------------
    # Global Settings
    # --------------------------------------------------------------------------
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Number of workers for data loading

    # --------------------------------------------------------------------------
    # Directory Setup
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_4"
    SUBMISSION_DIR = "./submission"

    # Ensure necessary directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # --------------------------------------------------------------------------
    # Data Paths
    # --------------------------------------------------------------------------
    # Metadata files (generated by the provided metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Cache files for processed data (Parquet format)
    # Used to store intermediate dataframes after feature extraction
    TRAIN_CACHE_PATH = os.path.join(WORKING_DIR, "train_processed.parquet")
    VAL_CACHE_PATH = os.path.join(WORKING_DIR, "val_processed.parquet")
    TEST_CACHE_PATH = os.path.join(WORKING_DIR, "test_processed.parquet")

    # --------------------------------------------------------------------------
    # Model Artifact Paths
    # --------------------------------------------------------------------------
    # Sparse Stream (Global Lexical Model)
    TFIDF_VECTORIZER_PATH = os.path.join(WORKING_DIR, "tfidf_vectorizer.joblib")
    RIDGE_MODEL_PATH = os.path.join(WORKING_DIR, "ridge_model.joblib")

    # Dense Stream (Contextual Model)
    # Vectorizer for extracting code context keywords
    CODE_TFIDF_VECTORIZER_PATH = os.path.join(
        WORKING_DIR, "code_tfidf_vectorizer.joblib"
    )
    # Saved Transformer model weights
    TRANSFORMER_MODEL_PATH = os.path.join(WORKING_DIR, "transformer_model.pth")

    # Final Submission
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Hyperparameters
    # --------------------------------------------------------------------------

    # --- Sparse Model Settings (TF-IDF + Ridge) ---
    VOCAB_SIZE = 60000  # Vocabulary size for markdown TF-IDF
    TFIDF_NGRAM_RANGE = (1, 2)  # Use Bigrams

    # --- Dense Model Settings (Transformer) ---
    MODEL_NAME = "distilroberta-base"
    MAX_LEN = 128  # Max sequence length for Transformer input

    # Context Extraction
    # Number of top TF-IDF keywords extracted from code cells to append to markdown
    MAX_CODE_TOKENS_CONTEXT = 20

    # --- Training Settings ---
    TRAIN_BATCH_SIZE = 32  # Adjusted for 40GB VRAM
    VAL_BATCH_SIZE = 64
    EPOCHS = 3  # Number of training epochs
    LEARNING_RATE = 2e-5  # Learning rate for fine-tuning
    WEIGHT_DECAY = 0.01  # Weight decay for optimizer
    WARMUP_RATIO = 0.1  # Ratio of steps for learning rate warmup

    # --- Ensemble Settings ---
    # Weight for Ridge model in the final ensemble (0.0 to 1.0)
    # Final Rank = Alpha * Ridge_Rank + (1 - Alpha) * Transformer_Rank
    ENSEMBLE_ALPHA = 0.5
