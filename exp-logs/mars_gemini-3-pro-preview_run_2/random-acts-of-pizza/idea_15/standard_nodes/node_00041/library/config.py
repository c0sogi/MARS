import os


class Config:
    """
    Configuration for the Supervised Semantic Projection Ensemble (SSPE) pipeline.
    Defines paths, model parameters, and hyperparameter grids for the pizza success prediction task.
    """

    # ==========================================
    # Directories and Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_15"
    OUTPUT_DIR = "./submission"

    # Raw Data Paths
    TRAIN_JSON_PATH = os.path.join(INPUT_DIR, "train.json")
    TEST_JSON_PATH = os.path.join(INPUT_DIR, "test.json")

    # Metadata Paths (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Submission Output Path
    SUBMISSION_PATH = os.path.join(OUTPUT_DIR, "submission.csv")

    # Cache Paths for Deterministic Processing (Parquet for DataFrames, NPY for Embeddings)
    TRAIN_FEATURES_PATH = os.path.join(WORKING_DIR, "train_features.parquet")
    VAL_FEATURES_PATH = os.path.join(WORKING_DIR, "val_features.parquet")
    TEST_FEATURES_PATH = os.path.join(WORKING_DIR, "test_features.parquet")

    TRAIN_EMBEDDINGS_PATH = os.path.join(WORKING_DIR, "train_embeddings.npy")
    VAL_EMBEDDINGS_PATH = os.path.join(WORKING_DIR, "val_embeddings.npy")
    TEST_EMBEDDINGS_PATH = os.path.join(WORKING_DIR, "test_embeddings.npy")

    # ==========================================
    # Model & Feature Configuration
    # ==========================================
    # Text Backbone: Larger model for better semantic resolution
    MODEL_NAME = "sentence-transformers/all-mpnet-base-v2"

    # Text Columns to concatenate for embedding generation
    TEXT_COLS = ["request_title", "request_text_edit_aware"]

    # Numerical Metadata Columns to be processed with RankGauss (QuantileTransformer)
    NUMERIC_COLS = [
        "requester_account_age_in_days_at_request",
        "requester_days_since_first_post_on_raop_at_request",
        "requester_number_of_comments_at_request",
        "requester_number_of_comments_in_raop_at_request",
        "requester_number_of_posts_at_request",
        "requester_number_of_posts_on_raop_at_request",
        "requester_number_of_subreddits_at_request",
        "requester_upvotes_minus_downvotes_at_request",
        "requester_upvotes_plus_downvotes_at_request",
        "unix_timestamp_of_request",
    ]

    # ==========================================
    # Hyperparameters
    # ==========================================
    SEED = 42
    N_SPLITS = 5  # Stratified K-Fold splits

    # Grid Search Space for PLS (Partial Least Squares) Projection
    # Tuning the number of latent components to maximize covariance with target
    PLS_N_COMPONENTS_GRID = [20, 30, 40, 50]

    # Grid Search Space for Logistic Regression
    # Exploring high-regularization regimes and class weighting
    LR_C_GRID = [0.0001, 0.001, 0.01, 0.1, 1.0, 10.0]
    LR_CLASS_WEIGHT_GRID = ["balanced", None]

    # Bagging Ensemble Settings
    N_BAGGING_ESTIMATORS = 10

    # ==========================================
    # Compute Settings
    # ==========================================
    N_JOBS = 12  # Number of vCPUs available

    @classmethod
    def setup(cls):
        """Ensure necessary working and output directories exist."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.OUTPUT_DIR, exist_ok=True)


# Initialize directories on import
Config.setup()
