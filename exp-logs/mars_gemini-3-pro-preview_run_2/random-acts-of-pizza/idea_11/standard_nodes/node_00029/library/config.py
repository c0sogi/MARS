import os


class Config:
    """
    Configuration class for the Random Acts of Pizza success prediction task.
    Implements the 'Dimensionality-Controlled Hybrid Early Fusion Strategy'.
    """

    # ==========================================
    # Global Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data for testing
    MAX_SAMPLES = 100 if DEBUG else None  # Control dataset size for debugging

    # ==========================================
    # Directory & File Paths
    # ==========================================
    # Base Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_11"
    SUBMISSION_DIR = "./submission"

    # Input Data Files
    TRAIN_DATA_PATH = os.path.join(INPUT_DIR, "train.json")
    TEST_DATA_PATH = os.path.join(INPUT_DIR, "test.json")

    # Metadata Split Files (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output Paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Model Architecture
    # ==========================================
    # Sentence Transformer Backbone (Compact 384d model to avoid overfitting)
    TRANSFORMER_MODEL_NAME = "sentence-transformers/all-MiniLM-L6-v2"

    # ==========================================
    # Feature Engineering Hyperparameters
    # ==========================================
    # Sparse Lexical View: Number of top terms to keep via Chi-Squared
    TOP_K_LEXICAL = 50

    # Community View: Number of top subreddits to keep via Chi-Squared
    TOP_K_COMMUNITY = 20

    # Metadata View: Degree for polynomial interaction features
    POLY_DEGREE = 2

    # ==========================================
    # Training & Cross-Validation
    # ==========================================
    N_FOLDS = 5

    # Bagging Ensemble Settings
    N_BAGGING_ESTIMATORS = 10  # Number of base estimators in the bagging ensemble

    # Logistic Regression Hyperparameter Search Space
    # Focus on High-Regularization Regime to handle noise
    C_GRID = [1e-4, 1e-3, 0.01, 0.1, 1.0, 10.0]
    CLASS_WEIGHT_GRID = ["balanced", None]

    @classmethod
    def setup(cls):
        """
        Ensures necessary working and submission directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
