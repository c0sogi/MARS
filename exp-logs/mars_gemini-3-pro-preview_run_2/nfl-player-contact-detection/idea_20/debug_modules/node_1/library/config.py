# =============================================================================
# FEATURE DEFINITIONS
# =============================================================================

# Window Size: t-5 to t+5 (11 frames total)
WINDOW_SIZE = 5

# Kinematic Features (Base features to be windowed)
# These are calculated for both Player 1 and Player 2 (or Ground proxy)
# and relative metrics are computed.
KINEMATIC_FEATURES = [
    # Player 1 Raw
    "x_position_1",
    "y_position_1",
    "speed_1",
    "acceleration_1",
    "orientation_1",
    "direction_1",
    "sa_1",  # Signed acceleration
    # Player 2 Raw (or Ground Proxy)
    "x_position_2",
    "y_position_2",
    "speed_2",
    "acceleration_2",
    "orientation_2",
    "direction_2",
    "sa_2",
    # Relative / Interaction Features
    "distance",  # Euclidean distance
    "log_distance",  # np.log1p(distance)
    "relative_speed",  # Difference in speed magnitude
    "closing_speed",  # Speed projected onto the vector connecting players
    "relative_orientation",  # Diff in orientation
    "relative_direction",  # Diff in direction
    "is_ground",  # Binary flag: 1 if P2 is Ground
]

# Visual Features (Base features to be windowed or used as current frame context)
# Derived from Max-Pooling strategy on helmet boxes
VISUAL_FEATURES = [
    "view_iou",  # IoU between P1 and P2 boxes (0 if ground)
    "box_distance",  # Distance between box centers
    "p1_area",  # Area of P1 box
    "p2_area",  # Area of P2 box
    "p1_top",  # Top coordinate of P1 (useful for falling detection)
    "p2_top",  # Top coordinate of P2
    "p1_left",
    "p2_left",
    "p1_width",
    "p2_width",
    "p1_height",
    "p2_height",
]

# Total Input Dimensions
# Kinematic: len(features) * (2*WINDOW_SIZE + 1)
# Visual: len(features) * (2*WINDOW_SIZE + 1) -> Assuming we window visual features too for consistency
NUM_KINEMATIC_FEATURES = len(KINEMATIC_FEATURES) * (2 * WINDOW_SIZE + 1)
NUM_VISUAL_FEATURES = len(VISUAL_FEATURES) * (2 * WINDOW_SIZE + 1)

# =============================================================================
# MODEL HYPERPARAMETERS
# =============================================================================

MODEL_PARAMS = {
    "input_dim_kinematic": NUM_KINEMATIC_FEATURES,
    "input_dim_visual": NUM_VISUAL_FEATURES,
    "hidden_dim": 256,  # Capacity for Gated Residual Blocks
    "num_blocks": 3,  # Number of Gated Residual Blocks
    "dropout": 0.2,  # Dropout rate
    "visual_hidden_dim": 64,  # Smaller capacity for visual correction branch
    "fusion_lambda": 1.0,  # Initial weight for visual correction (can be learned or fixed)
}

# =============================================================================
# TRAINING HYPERPARAMETERS
# =============================================================================

TRAIN_PARAMS = {
    "batch_size": 2048,  # Large batch size for tabular efficiency
    "learning_rate": 1e-3,  # AdamW learning rate
    "weight_decay": 1e-4,  # AdamW weight decay
    "epochs": 15,  # Max epochs
    "early_stopping_patience": 3,  # Stop if Val MCC doesn't improve
    "num_workers": 4,  # DataLoader workers
    # Focal Loss Parameters
    "focal_alpha": 0.75,  # Balance for class imbalance (favors minority class 1)
    "focal_gamma": 2.0,  # Focusing parameter for hard examples
    # Debugging / Development
    "debug_sample_size": None,  # Set to integer (e.g., 10000) for quick checks, None for full run
}
