import torch
import numpy as np
from torch.utils.data import Dataset
from library import feature_engineering


class NFLContactDataset(Dataset):
    """
    PyTorch Dataset for NFL Contact Detection.

    This dataset handles the loading of processed kinematic features and targets
    generated by the feature_engineering library. It converts the tabular data
    into PyTorch tensors suitable for the K-MLP model.
    """

    def __init__(
        self, split: str = "train", load_cached_data: bool = True, debug: bool = False
    ):
        """
        Initialize the dataset.

        Args:
            split (str): The data split to load ('train', 'validation', or 'test').
            load_cached_data (bool): If True, attempts to load pre-computed features from cache.
                                     If False or cache missing, regenerates features.
            debug (bool): If True, loads a small subset of the data for debugging purposes.
        """
        super().__init__()

        # Load processed data using the provided library function
        # X_df is a pandas DataFrame of features
        # y_series is a pandas Series of binary targets
        # ids_series is a pandas Series of contact_ids
        X_df, y_series, ids_series = feature_engineering.generate_features(
            split=split, load_cached_data=load_cached_data, debug=debug
        )

        # Convert pandas structures to numpy arrays for efficient memory usage and indexing.
        # We use float32 for features and targets as expected by PyTorch.
        self.features = X_df.values.astype(np.float32)
        self.targets = y_series.values.astype(np.float32)

        # Contact IDs are strings, kept as a numpy object array
        self.contact_ids = ids_series.values

    def __len__(self):
        """
        Return the total number of samples in the dataset.
        """
        return len(self.features)

    def __getitem__(self, idx):
        """
        Retrieve a single sample from the dataset.

        Args:
            idx (int): Index of the sample to retrieve.

        Returns:
            dict: A dictionary containing:
                - 'features': torch.Tensor (float32) of shape (num_features,)
                - 'target': torch.Tensor (float32) scalar
                - 'contact_id': str, the unique identifier for this contact event
        """
        # Convert the numpy array row to a PyTorch tensor
        feature_tensor = torch.tensor(self.features[idx], dtype=torch.float32)
        target_tensor = torch.tensor(self.targets[idx], dtype=torch.float32)
        contact_id = self.contact_ids[idx]

        return {
            "features": feature_tensor,
            "target": target_tensor,
            "contact_id": contact_id,
        }
