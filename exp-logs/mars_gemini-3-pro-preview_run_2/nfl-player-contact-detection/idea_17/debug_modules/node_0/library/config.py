import os


class Config:
    """
    Configuration class for the Multi-Modal Wide-Input Network (MM-WIN) solution.
    Defines file paths, hyperparameters, and feature sets.
    """

    # =========================================================================
    # Directories
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Cache directory for deterministic data processing (Idea 17 specific)
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_17")
    SUBMISSION_DIR = "./submission"

    # Ensure writable directories exist
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # =========================================================================
    # File Paths
    # =========================================================================
    # Raw Data
    TRAIN_TRACKING_PATH = os.path.join(INPUT_DIR, "train_player_tracking.csv")
    TEST_TRACKING_PATH = os.path.join(INPUT_DIR, "test_player_tracking.csv")

    TRAIN_HELMETS_PATH = os.path.join(INPUT_DIR, "train_baseline_helmets.csv")
    TEST_HELMETS_PATH = os.path.join(INPUT_DIR, "test_baseline_helmets.csv")

    TRAIN_VIDEO_META_PATH = os.path.join(INPUT_DIR, "train_video_metadata.csv")
    TEST_VIDEO_META_PATH = os.path.join(INPUT_DIR, "test_video_metadata.csv")

    # Metadata Splits (Generated by previous steps)
    METADATA_TRAIN = os.path.join(METADATA_DIR, "train.csv")
    METADATA_VAL = os.path.join(METADATA_DIR, "validation.csv")
    METADATA_TEST = os.path.join(METADATA_DIR, "test.csv")

    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Processing Hyperparameters
    # =========================================================================
    SEED = 42

    # Temporal Window: +/- 5 steps (0.5 seconds) -> Total 11 frames context
    WINDOW_SIZE = 5

    # Debugging / Development
    USE_ALL_DATA = True  # Set to False to use a small subset for debugging
    DEBUG_SAMPLE_SIZE = 50000

    # =========================================================================
    # Model Hyperparameters
    # =========================================================================
    # Deep Residual MLP Architecture
    HIDDEN_DIM = 512
    NUM_LAYERS = 3  # Number of Residual Blocks
    DROPOUT = 0.2

    # Training
    BATCH_SIZE = 512  # Large batch size for tabular efficiency
    LEARNING_RATE = 1e-3
    EPOCHS = 15
    EARLY_STOPPING_PATIENCE = 3

    # Loss
    POS_WEIGHT = (
        10.0  # Weight for positive class in BCEWithLogitsLoss (due to imbalance)
    )

    # =========================================================================
    # Feature Definitions
    # =========================================================================
    # Kinematic Features (from tracking data)
    TRACKING_FEATS = [
        "x_position",
        "y_position",
        "speed",
        "direction",
        "orientation",
        "acceleration",
        "sa",
    ]

    # Visual Features (from baseline helmets)
    # We will derive centroids and areas from these
    HELMET_FEATS = ["left", "width", "top", "height"]

    # Derived Visual Features to be used in the model
    VISUAL_DERIVED_FEATS = [
        "helmet_area",
        "helmet_aspect_ratio",
        "helmet_centroid_x",
        "helmet_centroid_y",
    ]

    # Interaction Features (computed between pair)
    INTERACTION_FEATS = [
        "distance",
        "log_distance",
        "speed_diff",
        "accel_diff",
        "visual_iou",  # Intersection over Union of helmet boxes
        "visual_dist_pixel",  # Pixel distance between helmet centroids
    ]

    # Ground Imputation
    GROUND_ID = "G"
