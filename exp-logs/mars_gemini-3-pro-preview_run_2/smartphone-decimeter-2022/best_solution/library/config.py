import os
import torch


class Config:
    """
    Global configuration for the Smartphone Location Prediction task.
    Includes file paths, data processing parameters, and model hyperparameters.
    """

    # -------------------------------------------------------------------------
    # 1. File Paths & Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_1"
    SUBMISSION_DIR = "./submission"

    # Ensure working and submission directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata Files (Generated by the provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "validation_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Cache Files (Parquet format for dataframes)
    CACHE_TRAIN_PATH = os.path.join(WORKING_DIR, "train_data.parquet")
    CACHE_VAL_PATH = os.path.join(WORKING_DIR, "val_data.parquet")
    CACHE_TEST_PATH = os.path.join(WORKING_DIR, "test_data.parquet")

    # Artifacts
    # Storing scaler statistics in JSON to avoid pickle
    SCALER_STATS_PATH = os.path.join(WORKING_DIR, "scaler_stats.json")
    MODEL_CHECKPOINT_PATH = os.path.join(WORKING_DIR, "mlp_model.pth")
    SUBMISSION_FILE_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # 2. Data Processing & Features
    # -------------------------------------------------------------------------
    RANDOM_STATE = 42

    # Windowing
    # Size of the sliding window in seconds. Should be an odd number to have a center.
    WINDOW_SIZE = 5

    # Debugging
    # Set to a small integer (e.g., 5) to limit the number of trips processed
    # during development. Set to None for full training.
    DEBUG_TRIP_COUNT = None

    # Column Names
    COL_TRIP_ID = "tripId"
    COL_UNIX_TIME = "UnixTimeMillis"
    COL_UTC_TIME = "utcTimeMillis"
    COL_LATITUDE = "LatitudeDegrees"
    COL_LONGITUDE = "LongitudeDegrees"

    # Processed Feature Names
    FEAT_WLS_LAT = "WlsLat"
    FEAT_WLS_LON = "WlsLon"
    FEAT_WLS_ALT = "WlsAlt"
    FEAT_DELTA_LAT = "DeltaWlsLat"
    FEAT_DELTA_LON = "DeltaWlsLon"
    FEAT_DELTA_ALT = "DeltaWlsAlt"
    FEAT_CN0 = "MeanCn0"
    FEAT_UNC = "MeanUncertainty"
    FEAT_SAT_COUNT = "SatelliteCount"

    # List of features to be used as input (per timestamp in the window)
    INPUT_FEATURES = [
        FEAT_WLS_LAT,
        FEAT_WLS_LON,
        FEAT_WLS_ALT,
        FEAT_DELTA_LAT,
        FEAT_DELTA_LON,
        FEAT_DELTA_ALT,
        FEAT_CN0,
        FEAT_UNC,
        FEAT_SAT_COUNT,
    ]

    # Target Columns (Residuals: GroundTruth - WLS)
    TARGET_LAT_RES = "LatResidual"
    TARGET_LON_RES = "LonResidual"
    TARGETS = [TARGET_LAT_RES, TARGET_LON_RES]

    # Scaling factor for targets (degrees -> ~meters magnitude)
    # 1 degree approx 111km. Residuals are ~5m = 0.00005 deg.
    # Scale by 100,000 to bring to ~5.0 range.
    TARGET_SCALE_FACTOR = 100000.0

    # -------------------------------------------------------------------------
    # 3. Model Architecture & Training
    # -------------------------------------------------------------------------
    # Input dimension = Number of features * Window Size
    INPUT_DIM = len(INPUT_FEATURES) * WINDOW_SIZE

    # MLP Architecture
    HIDDEN_LAYERS = [256, 128, 64]
    DROPOUT_RATE = 0.2
    OUTPUT_DIM = 2  # Predicting Latitude and Longitude residuals

    # Training Hyperparameters
    BATCH_SIZE = 512
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    EPOCHS = 50
    EARLY_STOPPING_PATIENCE = 10

    # Hardware Configuration
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4
