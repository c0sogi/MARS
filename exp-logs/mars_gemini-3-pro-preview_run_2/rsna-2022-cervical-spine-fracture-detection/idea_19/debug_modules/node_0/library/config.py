import os
import torch


class Config:
    # =========================================================================
    # File System & Paths
    # =========================================================================
    # Root directories
    ROOT_DIR = "."
    INPUT_DIR = os.path.join(ROOT_DIR, "input")
    WORKING_DIR = os.path.join(ROOT_DIR, "working", "idea_19")
    METADATA_DIR = os.path.join(ROOT_DIR, "metadata")

    # Input Data Paths
    TRAIN_IMAGES_DIR = os.path.join(INPUT_DIR, "train_images")
    TEST_IMAGES_DIR = os.path.join(INPUT_DIR, "test_images")

    # Metadata Paths (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Paths (Checkpoints, Logs, Submission)
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    BEST_MODEL_PATH = os.path.join(CHECKPOINT_DIR, "best_model.pth")
    LAST_MODEL_PATH = os.path.join(CHECKPOINT_DIR, "last_checkpoint.pth")
    LOG_FILE = os.path.join(WORKING_DIR, "train.log")
    SUBMISSION_DIR = os.path.join(ROOT_DIR, "submission")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Caching Paths (For deterministic data processing)
    # Using Parquet for efficient storage of processed metadata/paths
    TRAIN_CACHE_PATH = os.path.join(WORKING_DIR, "train_paths_cache.parquet")
    VAL_CACHE_PATH = os.path.join(WORKING_DIR, "val_paths_cache.parquet")
    TEST_CACHE_PATH = os.path.join(WORKING_DIR, "test_paths_cache.parquet")

    # Ensure necessary writeable directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # =========================================================================
    # Data Configuration
    # =========================================================================
    # 2.5D Stacking: Input is a stack of (z-1, z, z+1) slices
    IN_CHANNELS = 3

    # Image Resolution: EfficientNet-B4 native is 380, using 384 for alignment
    IMAGE_SIZE = (384, 384)

    # Sequence Modeling: Number of slices sampled per study
    # High density sampling (96) to capture small fractures
    SEQ_LENGTH = 96

    # Data Loading
    NUM_WORKERS = 4

    # =========================================================================
    # Model Architecture
    # =========================================================================
    BACKBONE = "tf_efficientnet_b4_ns"  # Timm implementation

    # LSTM Head Configuration
    LSTM_HIDDEN_SIZE = 256
    LSTM_LAYERS = 2
    LSTM_DROPOUT = 0.2

    # Output Configuration
    # 7 Cervical Levels + 1 Patient Overall
    NUM_CLASSES = 8

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    SEED = 42

    # Batch Size & Optimization
    # Effective Batch Size = BATCH_SIZE * ACCUMULATION_STEPS
    # 4 * 4 = 16 studies per optimization step
    BATCH_SIZE = 4
    ACCUMULATION_STEPS = 4

    EPOCHS = 10
    LEARNING_RATE = 3e-4
    WEIGHT_DECAY = 1e-4
    MAX_GRAD_NORM = 5.0  # Gradient clipping for LSTM stability

    # Early Stopping
    PATIENCE = 3

    # =========================================================================
    # Loss & Metric Configuration
    # =========================================================================
    # Target Columns in order
    TARGET_COLS = ["C1", "C2", "C3", "C4", "C5", "C6", "C7", "patient_overall"]

    # Competition Metric Weights
    # "The any label is weighted more highly than specific fracture level sub-types."
    # Standard weighting: 1/14 for each vertebrae, 7/14 for overall.
    # This ensures the overall label contributes 50% of the total loss.
    CLASS_WEIGHTS = [
        1 / 14,
        1 / 14,
        1 / 14,
        1 / 14,
        1 / 14,
        1 / 14,
        1 / 14,  # C1-C7
        7 / 14,  # patient_overall
    ]

    # Calibration Requirement:
    # Strictly 1.0 to avoid probability drift. Do not use weighted BCE.
    POS_WEIGHT = 1.0

    # =========================================================================
    # Hardware & Debugging
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Debug Mode: Set to True to run on a tiny subset of data for pipeline verification
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 20
