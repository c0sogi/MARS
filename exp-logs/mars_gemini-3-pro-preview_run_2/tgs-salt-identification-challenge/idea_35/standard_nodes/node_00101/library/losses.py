import torch
import torch.nn as nn
import torch.nn.functional as F


def lovasz_grad(gt_sorted):
    """
    Computes gradient of the Lovasz extension w.r.t sorted errors.
    See Alg. 1 in paper: https://arxiv.org/abs/1705.08790
    """
    p = len(gt_sorted)
    gts = gt_sorted.sum()
    intersection = gts - gt_sorted.float().cumsum(0)
    union = gts + (1 - gt_sorted).float().cumsum(0)
    jaccard = 1.0 - intersection / union
    if p > 1:  # cover 1-pixel case
        jaccard[1:p] = jaccard[1:p] - jaccard[0:-1]
    return jaccard


def lovasz_hinge_flat(logits, labels):
    """
    Binary Lovasz hinge loss for a flat vector.

    Args:
        logits: [P] Logits at each pixel (between -infinity and +infinity)
        labels: [P] Binary ground truth labels (0 or 1)

    Returns:
        torch.Tensor: Scalar loss
    """
    if len(labels) == 0:
        # Only void pixels, the gradients should be 0
        return logits.sum() * 0.0

    signs = 2.0 * labels.float() - 1.0
    errors = 1.0 - logits * signs
    errors_sorted, perm = torch.sort(errors, dim=0, descending=True)
    gt_sorted = labels[perm]
    grad = lovasz_grad(gt_sorted)
    loss = torch.dot(F.relu(errors_sorted), grad)
    return loss


class LovaszHingeLoss(nn.Module):
    """
    Lovasz Hinge Loss for Binary Segmentation.
    Optimizes the Jaccard index (IoU) directly.
    Calculates loss per image and averages over the batch.
    """

    def __init__(self):
        super().__init__()

    def forward(self, logits, labels):
        """
        Args:
            logits: (B, 1, H, W) or (B, H, W)
            labels: (B, 1, H, W) or (B, H, W)
        """
        # Ensure correct shape
        if logits.dim() > 2:
            batch_size = logits.size(0)
        else:
            batch_size = 1
            logits = logits.unsqueeze(0)
            labels = labels.unsqueeze(0)

        loss = 0
        for i in range(batch_size):
            l_flat = logits[i].reshape(-1)
            t_flat = labels[i].reshape(-1)
            loss += lovasz_hinge_flat(l_flat, t_flat)

        return loss / batch_size


class StudentLoss(nn.Module):
    """
    Composite loss function for the Generalist Student model.
    Handles both Supervised (Labeled) and Distillation (Unlabeled) modes.

    Modes:
    1. Supervised: Lovasz + BCE (Mask) + MSE (Aux Depth)
    2. Distillation: BCE (Mask vs Soft Targets)
    """

    def __init__(self):
        super().__init__()
        self.bce = nn.BCEWithLogitsLoss()
        self.mse = nn.MSELoss()
        self.lovasz = LovaszHingeLoss()

    def forward(
        self,
        mask_logits,
        aux_depth_pred,
        mask_targets,
        depth_targets=None,
        is_pseudo=False,
    ):
        """
        Args:
            mask_logits (torch.Tensor): (B, 1, H, W) Predicted mask logits.
            aux_depth_pred (torch.Tensor): (B, 1) Predicted depth from aux head.
            mask_targets (torch.Tensor): (B, 1, H, W)
                - If is_pseudo=False: Binary Ground Truth (0 or 1).
                - If is_pseudo=True: Soft Probabilities (0.0 to 1.0).
            depth_targets (torch.Tensor, optional): (B, 1) True depth values. Required if is_pseudo=False.
            is_pseudo (bool): Flag to switch between Supervised and Distillation modes.

        Returns:
            torch.Tensor: Combined scalar loss.
        """
        if is_pseudo:
            # Distillation Mode (Unlabeled Data)
            # We use BCE against soft targets generated by the Teacher Ensemble.
            # Lovasz is skipped because it requires binary targets.
            # Aux depth is skipped because we lack ground truth depth for test set.
            return self.bce(mask_logits, mask_targets)
        else:
            # Supervised Mode (Labeled Data)
            # 1. Mask Loss: Combination of BCE (pixel-wise) and Lovasz (IoU-wise)
            loss_mask_bce = self.bce(mask_logits, mask_targets)
            loss_mask_lovasz = self.lovasz(mask_logits, mask_targets)

            # 2. Depth Loss: MSE on the auxiliary head to force texture feature extraction
            if depth_targets is not None:
                loss_depth = self.mse(aux_depth_pred.view(-1), depth_targets.view(-1))
            else:
                # Fallback if depth targets missing in supervised mode (should not happen in this pipeline)
                loss_depth = 0.0

            # Combine losses (Sum)
            return loss_mask_bce + loss_mask_lovasz + loss_depth
