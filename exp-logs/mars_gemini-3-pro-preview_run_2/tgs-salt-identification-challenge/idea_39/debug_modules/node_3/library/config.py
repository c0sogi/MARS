import os
import torch


class Config:
    """
    Central configuration for the Salt Segmentation Task.
    Implements parameters for the FP32-Stabilized Multi-Task Specialist strategy.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    PROJECT_NAME = "SaltSegmentation_Idea39"

    # =========================================================================
    # Data Paths
    # =========================================================================
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the provided script
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Working directory for artifacts
    WORKING_DIR = "./working/idea_39"
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure working directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # =========================================================================
    # Image & Dataset Parameters
    # =========================================================================
    ORIG_SIZE = 101  # Original image dimension
    IMG_SIZE = 128  # Padded dimension for U-Net divisibility (32x)
    CHANNELS = 1  # Grayscale input

    # =========================================================================
    # Model Architecture Parameters
    # =========================================================================
    MODEL_NAME = "resnet34"
    ENCODER_WEIGHTS = "imagenet"

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 32
    EPOCHS = 50
    LR = 1e-4
    WEIGHT_DECAY = 1e-2
    T_MAX = 50  # Cosine Annealing T_max
    NUM_WORKERS = 4  # Optimized for 12 vCPUs

    # Loss Weights
    BCE_WEIGHT = 1.0
    LOVASZ_WEIGHT = 1.0
    AUX_WEIGHT = 0.1  # Weight for auxiliary depth regression head

    # =========================================================================
    # Inference Strategy: Marginalized Depth Scan
    # =========================================================================
    # Since test depths are missing, we scan across standardized depth values (z-scores)
    # and average the predictions to marginalize out the depth variable.
    SCAN_DEPTHS = [-1.5, -0.75, 0.0, 0.75, 1.5]

    # Quality Gate: Minimum validation mAP required to include a fold in the ensemble
    FOLD_SCORE_THRESHOLD = 0.75

    # =========================================================================
    # Hardware & Compute
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # =========================================================================
    # Debugging & Development
    # =========================================================================
    DEBUG = False

    @classmethod
    def set_debug_mode(cls, debug=True):
        """
        Toggles debug mode.
        If True, reduces epochs to minimize runtime for testing pipeline integration.
        """
        cls.DEBUG = debug
        if debug:
            cls.EPOCHS = 2
            print(f"Debug mode enabled. Epochs set to {cls.EPOCHS}.")
