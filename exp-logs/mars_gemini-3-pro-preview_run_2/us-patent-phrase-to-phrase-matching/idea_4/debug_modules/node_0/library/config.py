import os
import torch


class Config:
    # =========================================================================
    # General Settings
    # =========================================================================
    seed = 42
    debug = False  # Toggle for debugging mode (subsampling data)
    debug_sample_size = 500  # Number of samples to use in debug mode
    exp_name = "idea_4_deberta_v3_large_awp"

    # =========================================================================
    # Paths
    # =========================================================================
    # Input paths (generated by the metadata script)
    train_path = "./metadata/train.csv"
    val_path = "./metadata/val.csv"
    test_path = "./metadata/test.csv"

    # Output paths
    working_dir = "./working/idea_4"
    output_dir = os.path.join(working_dir, "models")
    submission_dir = "./submission"
    submission_path = os.path.join(submission_dir, "submission.csv")

    # Ensure directories exist
    os.makedirs(working_dir, exist_ok=True)
    os.makedirs(output_dir, exist_ok=True)
    os.makedirs(submission_dir, exist_ok=True)

    # =========================================================================
    # Model Configuration
    # =========================================================================
    model_name = "microsoft/deberta-v3-large"
    max_length = 130  # Sufficient for Anchor + Target + Context
    fc_dropout = 0.2
    num_classes = 5  # Classes: 0.0, 0.25, 0.5, 0.75, 1.0

    # Hybrid Feature Fusion
    use_handcrafted_features = True
    handcrafted_features_dim = 3  # Jaccard, Levenshtein, Length Diff

    # =========================================================================
    # Training Configuration
    # =========================================================================
    n_folds = 5
    epochs = 4
    train_batch_size = 8  # Tuned for A100 40GB with Large model
    valid_batch_size = 16
    gradient_accumulation_steps = 1
    max_grad_norm = 1000
    print_freq = 50
    num_workers = 4
    pin_memory = True

    # Optimizer & Scheduler
    learning_rate = 2e-5
    min_lr = 1e-6
    weight_decay = 0.01
    scheduler_type = "cosine"
    warmup_ratio = 0.1

    # Loss
    label_smoothing = 0.1

    # =========================================================================
    # Adversarial Weight Perturbation (AWP)
    # =========================================================================
    use_awp = True
    awp_eps = 1e-4
    awp_lr = 1e-4
    awp_start_epoch = 1  # Start AWP after the 1st epoch

    # =========================================================================
    # System
    # =========================================================================
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    @classmethod
    def set_debug(cls, debug_mode: bool):
        """
        Adjusts configuration for debugging purposes.
        """
        cls.debug = debug_mode
        if debug_mode:
            cls.epochs = 2
            cls.n_folds = 2
            cls.train_batch_size = 4
            cls.valid_batch_size = 4
            cls.print_freq = 10
