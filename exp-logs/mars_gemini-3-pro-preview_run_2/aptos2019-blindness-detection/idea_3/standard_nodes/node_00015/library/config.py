import os
import torch


class Config:
    """
    Configuration class for Diabetic Retinopathy Severity Prediction.
    Centralizes all hyperparameters, file paths, and system settings.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    seed = 42
    debug = False  # Set to True to run on a small subset of data for debugging
    debug_samples = 100  # Number of samples to use in debug mode

    # =========================================================================
    # Compute Environment
    # =========================================================================
    # Utilizing available vCPUs (12 available)
    num_workers = 8
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # =========================================================================
    # File Paths & Directories
    # =========================================================================
    input_dir = "./input"
    metadata_dir = "./metadata"
    working_dir = "./working/idea_3"

    # Ensure the working directory exists for checkpoints and cache
    os.makedirs(working_dir, exist_ok=True)

    # Metadata paths (generated by the metadata script)
    train_csv_path = os.path.join(metadata_dir, "train.csv")
    val_csv_path = os.path.join(metadata_dir, "val.csv")
    test_csv_path = os.path.join(metadata_dir, "test.csv")

    # Raw data paths
    train_images_dir = os.path.join(input_dir, "train_images")
    test_images_dir = os.path.join(input_dir, "test_images")
    sample_submission_path = os.path.join(input_dir, "sample_submission.csv")

    # Output paths
    submission_path = os.path.join(working_dir, "submission.csv")

    # =========================================================================
    # Data Preprocessing & Augmentation
    # =========================================================================
    image_size = 456  # Resolution for EfficientNet-B5 and ConvNeXt
    use_circle_crop = True

    # Augmentation Hyperparameters
    clahe_prob = 0.5
    flip_prob = 0.5
    rotation_degrees = 30

    # =========================================================================
    # Model Architecture
    # =========================================================================
    # Heterogeneous Ensemble: EfficientNet-B5 (CNN) + ConvNeXt (Transformer-style CNN)
    model_archs = ["tf_efficientnet_b5_ns", "convnext_base"]

    # Regression formulation: 1 output neuron
    num_classes = 1

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    n_folds = 5
    epochs = 10  # Sufficient for fine-tuning pre-trained models
    batch_size = 16  # Fits on A100 40GB with B5/ConvNeXt-Base

    # Optimization
    learning_rate = 1e-4
    min_lr = 1e-6
    weight_decay = 1e-6
    max_grad_norm = 10.0

    # Scheduler (Cosine Annealing)
    T_max = epochs

    # =========================================================================
    # Inference
    # =========================================================================
    tta_steps = 2  # Test Time Augmentation: Original + Horizontal Flip
