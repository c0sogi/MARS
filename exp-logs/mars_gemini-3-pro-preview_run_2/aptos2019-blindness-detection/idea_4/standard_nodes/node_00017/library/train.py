import os
import pandas as pd
import torch
import torch.nn as nn
from torch.utils.data import DataLoader
from sklearn.model_selection import StratifiedKFold
import shutil

from library.config import Config
from library.dataset import RetinopathyDataset, get_transforms
from library.models import RetinopathyModel
from library.engine import train_one_epoch, validate
from library.utils import seed_everything


def run_fold(
    fold, train_csv_path, val_csv_path, model_name, image_size, device, debug=False
):
    """
    Trains a single model on a specific fold.
    """
    print(f"\n=== Training Fold {fold} | Model: {model_name} | Size: {image_size} ===")

    # 1. Data Loaders
    # We use the temporary CSV paths generated by the main loop
    train_dataset = RetinopathyDataset(
        csv_path=train_csv_path,
        transform=get_transforms(image_size, mode="train"),
        mode="train",
    )

    val_dataset = RetinopathyDataset(
        csv_path=val_csv_path,
        transform=get_transforms(image_size, mode="val"),
        mode="val",
    )

    train_loader = DataLoader(
        train_dataset,
        batch_size=Config.BATCH_SIZE,
        shuffle=True,
        num_workers=Config.NUM_WORKERS,
        pin_memory=True,
        drop_last=True,
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=Config.BATCH_SIZE,
        shuffle=False,
        num_workers=Config.NUM_WORKERS,
        pin_memory=True,
    )

    # 2. Model Setup
    model = RetinopathyModel(model_name=model_name, pretrained=True)
    model = model.to(device)

    # 3. Optimization
    optimizer = torch.optim.AdamW(
        model.parameters(), lr=Config.LR, weight_decay=Config.WEIGHT_DECAY
    )

    # Regression task: Mean Squared Error
    criterion = nn.MSELoss()

    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=Config.T_MAX, eta_min=Config.MIN_LR
    )

    # 4. Training Loop
    best_kappa = -float("inf")
    best_loss = float("inf")
    patience_counter = 0

    # Define save path
    save_name = f"{model_name}_fold_{fold}.pth"
    save_path = os.path.join(Config.OUTPUT_DIR, save_name)

    epochs = Config.EPOCHS if not debug else 2

    for epoch in range(1, epochs + 1):
        # Train
        train_loss = train_one_epoch(
            model, train_loader, criterion, optimizer, device, epoch
        )

        # Validate
        val_loss, val_kappa = validate(model, val_loader, criterion, device, epoch)

        # Step Scheduler
        scheduler.step()

        # Checkpointing based on Kappa (Maximize)
        if val_kappa > best_kappa:
            print(f"Kappa Improved ({best_kappa} -> {val_kappa}). Saving model...")
            best_kappa = val_kappa
            torch.save(model.state_dict(), save_path)
            patience_counter = 0
        else:
            patience_counter += 1
            print(
                f"No improvement in Kappa. Patience: {patience_counter}/{Config.PATIENCE}"
            )

        # Early Stopping
        if patience_counter >= Config.PATIENCE:
            print("Early stopping triggered.")
            break

    print(f"Fold {fold} finished. Best Kappa: {best_kappa}")

    # Clean up to free memory
    del model, optimizer, scheduler, train_loader, val_loader
    torch.cuda.empty_cache()


def train_models(debug=False):
    """
    Main orchestration function for 5-Fold CV on multiple architectures.
    """
    seed_everything(Config.SEED)

    # Ensure output directory exists
    os.makedirs(Config.OUTPUT_DIR, exist_ok=True)

    # Temporary directory for fold CSVs
    temp_fold_dir = os.path.join(Config.OUTPUT_DIR, "folds")
    os.makedirs(temp_fold_dir, exist_ok=True)

    # 1. Prepare Data
    # Load metadata provided by the system
    df_train_meta = pd.read_csv(Config.TRAIN_CSV)
    df_val_meta = pd.read_csv(Config.VAL_CSV)

    # Combine for Cross-Validation
    df_full = pd.concat([df_train_meta, df_val_meta], ignore_index=True)

    if debug:
        print("DEBUG MODE: Using subset of data.")
        df_full = df_full.sample(n=100, random_state=Config.SEED).reset_index(drop=True)

    # 2. Iterate Architectures
    # Config.MODEL_SPECS = {"tf_efficientnet_b5_ns": 512, "convnext_base": 384}
    for model_name, image_size in Config.MODEL_SPECS.items():
        print(f"\n\n{'='*40}")
        print(
            f"Starting Training for Architecture: {model_name} @ {image_size}x{image_size}"
        )
        print(f"{'='*40}")

        # 3. Stratified K-Fold
        skf = StratifiedKFold(
            n_splits=Config.NUM_FOLDS, shuffle=True, random_state=Config.SEED
        )

        # We stratify based on the 'diagnosis' column
        for fold, (train_idx, val_idx) in enumerate(
            skf.split(df_full, df_full["diagnosis"])
        ):

            # Split Data
            df_fold_train = df_full.iloc[train_idx].reset_index(drop=True)
            df_fold_val = df_full.iloc[val_idx].reset_index(drop=True)

            # Save temporary CSVs for the Dataset class to consume
            # We use unique names to avoid collisions/confusion
            train_csv_path = os.path.join(
                temp_fold_dir, f"train_{model_name}_fold_{fold}.csv"
            )
            val_csv_path = os.path.join(
                temp_fold_dir, f"val_{model_name}_fold_{fold}.csv"
            )

            df_fold_train.to_csv(train_csv_path, index=False)
            df_fold_val.to_csv(val_csv_path, index=False)

            # Run Training
            run_fold(
                fold=fold,
                train_csv_path=train_csv_path,
                val_csv_path=val_csv_path,
                model_name=model_name,
                image_size=image_size,
                device=Config.DEVICE,
                debug=debug,
            )

            # Clean up temp files for this fold
            if os.path.exists(train_csv_path):
                os.remove(train_csv_path)
            if os.path.exists(val_csv_path):
                os.remove(val_csv_path)

    # Cleanup temp dir
    if os.path.exists(temp_fold_dir):
        shutil.rmtree(temp_fold_dir)

    print("\nAll training tasks completed successfully.")


if __name__ == "__main__":
    # Allow controlling debug mode via Config if desired, or default to False
    train_models(debug=Config.DEBUG)
