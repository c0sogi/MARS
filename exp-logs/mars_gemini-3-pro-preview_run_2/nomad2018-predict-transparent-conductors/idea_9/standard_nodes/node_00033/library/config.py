import os
import torch


class Config:
    """
    Configuration for the Dual-Stream Late-Fusion CGCNN pipeline.
    Defines hyperparameters, file paths, and constants used across the project.
    """

    # -------------------------------------------------------------------------
    # Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42

    # -------------------------------------------------------------------------
    # Debugging / Development
    # -------------------------------------------------------------------------
    # Set to True to run on a small subset of data for quick testing/debugging
    DEBUG = False
    # Number of samples to use when DEBUG is True
    DEBUG_SAMPLE_SIZE = 100

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for this specific experiment (Idea 9)
    WORKING_DIR = "./working/idea_9"

    # Sub-directories for artifacts
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = "./submission"

    # Metadata File Paths (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Cache File Paths (For deterministic data processing)
    TRAIN_GRAPHS_CACHE = os.path.join(CACHE_DIR, "train_graphs.npz")
    VAL_GRAPHS_CACHE = os.path.join(CACHE_DIR, "val_graphs.npz")
    TEST_GRAPHS_CACHE = os.path.join(CACHE_DIR, "test_graphs.npz")
    SCALER_CACHE = os.path.join(CACHE_DIR, "scalers.npz")

    # Model Checkpoint Path
    BEST_MODEL_PATH = os.path.join(CHECKPOINT_DIR, "best_model.pth")

    # Final Submission Path
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data / Graph Construction Hyperparameters
    # -------------------------------------------------------------------------
    # Radius for neighbor search in Angstroms
    CUTOFF_RADIUS = 5.0
    # Maximum number of neighbors to consider per atom (for tensor sizing)
    MAX_NEIGHBORS = 50

    # Atom Type Mapping: Maps element symbols to integer indices
    # Dataset contains Al, Ga, In, O
    ATOM_MAP = {"O": 0, "Al": 1, "Ga": 2, "In": 3}
    NUM_ATOM_TYPES = len(ATOM_MAP)

    # -------------------------------------------------------------------------
    # Model Architecture Hyperparameters
    # -------------------------------------------------------------------------
    # Local Graph Stream
    ATOM_EMBEDDING_DIM = 128
    HIDDEN_DIM = 128
    N_INTERACTION_LAYERS = 4
    N_RBF = 60  # Number of Gaussian RBF bins for edge distance expansion

    # Global Feature Stream
    # Features: Lattice Vectors (3 lengths, 3 angles) + Composition (4 fractions)
    N_GLOBAL_FEATURES = 10

    # Regularization
    DROPOUT_RATE = 0.2

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 64
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    MAX_EPOCHS = 150
    PATIENCE = 20  # Early stopping patience (epochs without improvement)

    # Hardware
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Number of subprocesses for data loading

    # Targets
    TARGET_COLS = ["formation_energy_ev_natom", "bandgap_energy_ev"]

    @classmethod
    def setup(cls):
        """
        Ensures that all necessary working directories exist.
        This is called automatically when the module is imported.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories upon import
Config.setup()
