import os
import torch


class Config:
    """
    Centralized configuration for the Melanoma Detection task.
    Implements the settings for the Hybrid Linear Probe (MobileNetV3-Small + Metadata).
    """

    # -------------------------------------------------------------------------
    # General & Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Debugging / Development
    # Set DEBUG to True to run on a small subset of the data
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 2000

    # -------------------------------------------------------------------------
    # File Paths & Directories
    # -------------------------------------------------------------------------
    # Root Input Directory
    INPUT_ROOT = "./input"

    # Metadata Files (Generated by the provided metadata script)
    METADATA_DIR = "./metadata"
    TRAIN_CSV_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Image Directories
    # Note: 'file_path' in metadata is relative to INPUT_ROOT (e.g., "jpeg/train/...")

    # Working Directory for Caching and Intermediates
    WORKING_DIR = "./working/idea_1"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Cache Paths for Deterministic Data Processing
    # Used to store processed metadata arrays/tensors to avoid re-computation
    CACHED_DATA_PATH = os.path.join(WORKING_DIR, "processed_data.parquet")
    METADATA_PREPROCESSOR_PATH = os.path.join(WORKING_DIR, "meta_preprocessor.pkl")

    # Submission Directory
    SUBMISSION_DIR = "./submission"
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    # Backbone: MobileNetV3-Small (Lightweight, Fast)
    BACKBONE_NAME = "mobilenet_v3_small"
    PRETRAINED = True

    # Input Resolution
    # Resizing to 224x224 for speed and compatibility with standard pre-trained models
    IMG_SIZE = 224

    # -------------------------------------------------------------------------
    # Feature Engineering / Metadata
    # -------------------------------------------------------------------------
    # Numerical columns to be standardized (Mean=0, Std=1)
    META_NUM_COLS = ["age_approx"]

    # Categorical columns to be One-Hot Encoded
    META_CAT_COLS = ["sex", "anatom_site_general_challenge"]

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    # Batch Size: 64 is safe for MobileNetV3-Small on A100
    BATCH_SIZE = 64

    # Epochs: Increased for fine-tuning, controlled by Early Stopping
    EPOCHS = 15

    # Learning Rate: Standard starting point for Adam
    LEARNING_RATE = 1e-3

    # Class Imbalance Handling
    # The dataset has approx 1:55 malignant:benign ratio.
    # We use a positive class weight in BCEWithLogitsLoss to penalize missing malignant cases.
    POS_WEIGHT = 50.0

    # -------------------------------------------------------------------------
    # Inference
    # -------------------------------------------------------------------------
    # Threshold is not strictly needed for AUC metric (probabilities required),
    # but useful if hard predictions were needed.
    PROB_THRESHOLD = 0.5
