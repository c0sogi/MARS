import os
import torch
import pandas as pd
import numpy as np
from torch.utils.data import DataLoader
from tqdm import tqdm

from library.config import Config
from library.utils import seed_everything
from library.dataset import CatheterDataset, get_transforms
from library.model import CatheterModel


def inference(
    model_path: str = os.path.join(Config.working_dir, "best_model.pth"),
    output_path: str = "./submission/submission.csv",
    batch_size: int = Config.batch_size,
    device: str = Config.device,
    num_workers: int = Config.num_workers,
):
    """
    Runs inference on the test set and generates a submission file.

    Args:
        model_path (str): Path to the trained model weights.
        output_path (str): Path where the submission CSV will be saved.
        batch_size (int): Batch size for inference.
        device (str): Device to run inference on ('cuda' or 'cpu').
        num_workers (int): Number of worker threads for data loading.
    """
    # 1. Setup
    seed_everything(Config.seed)
    device = torch.device(device)

    # Ensure output directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    print(f"Starting inference using model at: {model_path}")
    print(f"Output will be saved to: {output_path}")

    # 2. Data Loading
    # Load test metadata generated by the metadata script
    if not os.path.exists(Config.test_metadata_path):
        raise FileNotFoundError(
            f"Test metadata not found at {Config.test_metadata_path}"
        )

    df_test = pd.read_csv(Config.test_metadata_path)
    print(f"Loaded test metadata. Shape: {df_test.shape}")

    # Initialize Dataset with validation transforms (Resize -> CLAHE -> Pad)
    test_dataset = CatheterDataset(
        df_test, transform=get_transforms("valid"), is_test=True
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
    )

    # 3. Model Initialization
    model = CatheterModel(
        model_name=Config.model_name,
        pretrained=False,  # No need to download pretrained weights, we load our own
        num_classes=Config.num_classes,
        drop_rate=Config.drop_rate,
        drop_path_rate=Config.drop_path_rate,
    )
    model.to(device)

    # 4. Load Weights
    if os.path.exists(model_path):
        state_dict = torch.load(model_path, map_location=device)
        model.load_state_dict(state_dict)
        print("Model weights loaded successfully.")
    else:
        print(
            f"WARNING: Model path {model_path} does not exist. Using random initialization (for debugging only)."
        )

    # 5. Inference Loop
    model.eval()
    preds = []

    # Disable gradient calculation for inference
    with torch.no_grad():
        for images, _ in test_loader:
            images = images.to(device, dtype=torch.float)

            # Forward pass
            logits = model(images)

            # Apply Sigmoid to get probabilities
            probs = torch.sigmoid(logits)

            preds.append(probs.cpu().numpy())

    # Concatenate all batches
    preds = np.concatenate(preds, axis=0)

    # 6. Submission Generation
    # Create DataFrame with StudyInstanceUID and predicted probabilities
    submission_df = pd.DataFrame(preds, columns=Config.target_cols)
    submission_df.insert(0, "StudyInstanceUID", df_test["StudyInstanceUID"])

    # Save to CSV
    submission_df.to_csv(output_path, index=False)
    print(f"Submission saved successfully to {output_path}")
    print(f"Submission shape: {submission_df.shape}")
