import os
import pandas as pd
import numpy as np
from library.config import (
    TRAIN_PATH,
    VAL_PATH,
    TEST_PATH,
    CACHE_TRAIN_PATH,
    CACHE_TEST_PATH,
    INTERACTION_PAIRS,
    TARGET_COL,
    ID_COL,
)


def engineer_interaction_features(df):
    """
    Generates multiplicative interaction features between binary and continuous columns
    as defined in the configuration.

    Args:
        df (pd.DataFrame): Input dataframe.

    Returns:
        pd.DataFrame: Dataframe with added interaction features.
    """
    # Operate on a copy to prevent SettingWithCopy warnings
    df_eng = df.copy()

    for binary_col, continuous_col in INTERACTION_PAIRS:
        # Verify columns exist before computing
        if binary_col in df_eng.columns and continuous_col in df_eng.columns:
            new_col_name = f"{binary_col}_x_{continuous_col}"
            # Multiplicative interaction
            df_eng[new_col_name] = df_eng[binary_col] * df_eng[continuous_col]

    return df_eng


def process_data(load_cached_data=True):
    """
    Loads raw metadata, merges training and validation splits, performs feature engineering,
    and caches the results.

    Args:
        load_cached_data (bool): If True, attempts to load pre-processed parquet files
                                 from the cache directory.

    Returns:
        tuple: (train_df, test_df)
            train_df (pd.DataFrame): Combined training and validation data with features and target.
            test_df (pd.DataFrame): Test data with features.
    """
    # --- Caching Logic ---
    if load_cached_data:
        if os.path.exists(CACHE_TRAIN_PATH) and os.path.exists(CACHE_TEST_PATH):
            print(f"Loading cached data from {CACHE_TRAIN_PATH}...")
            try:
                train_df = pd.read_parquet(CACHE_TRAIN_PATH)
                test_df = pd.read_parquet(CACHE_TEST_PATH)
                return train_df, test_df
            except Exception as e:
                print(f"Error loading cache: {e}. Proceeding to re-process data.")
        else:
            print("Cache files not found. Processing data from scratch.")
    else:
        print("Skipping cache load. Processing data from scratch.")

    # --- Data Loading ---
    print("Loading raw datasets from metadata...")
    # Load the stratified splits generated by the metadata script
    df_train_split = pd.read_parquet(TRAIN_PATH)
    df_val_split = pd.read_parquet(VAL_PATH)
    df_test = pd.read_parquet(TEST_PATH)

    # --- Merge Train and Val ---
    # We combine them to utilize the full dataset for Stratified K-Fold CV
    print("Combining training and validation splits...")
    df_train = pd.concat([df_train_split, df_val_split], axis=0, ignore_index=True)

    # --- Feature Engineering ---
    print("Engineering interaction features...")
    df_train = engineer_interaction_features(df_train)
    df_test = engineer_interaction_features(df_test)

    # --- Save to Cache ---
    # Ensure the working directory exists (defensive programming)
    os.makedirs(os.path.dirname(CACHE_TRAIN_PATH), exist_ok=True)

    print(f"Saving processed data to {CACHE_TRAIN_PATH} and {CACHE_TEST_PATH}...")
    df_train.to_parquet(CACHE_TRAIN_PATH, index=False)
    df_test.to_parquet(CACHE_TEST_PATH, index=False)

    return df_train, df_test
