import os
import random
import numpy as np
import torch


class Config:
    """
    Configuration module for the Contracted Spatial Pyramid Hybrid Network (CSP-HN).
    """

    # ==========================================
    # 1. REPRODUCIBILITY
    # ==========================================
    SEED = 42

    # ==========================================
    # 2. PATHS & DIRECTORIES
    # ==========================================
    # Base Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORK_DIR = "./working/idea_9"
    SUBMISSION_DIR = "./submission"

    # Raw Data Files
    TRAIN_JSON = os.path.join(INPUT_DIR, "train.json")
    TEST_JSON = os.path.join(INPUT_DIR, "test.json")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Files (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Caching
    PROCESSED_DATA_PATH = os.path.join(WORK_DIR, "processed_data.npz")

    # Output
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # 3. DATA SPECIFICATIONS
    # ==========================================
    IMG_HEIGHT = 75
    IMG_WIDTH = 75
    # 3 Channels: Band 1 (HH), Band 2 (HV), Average (HH+HV)/2
    IMG_CHANNELS = 3
    NUM_CLASSES = 1  # Binary classification (Sigmoid output)

    # ==========================================
    # 4. MODEL HYPERPARAMETERS
    # ==========================================
    # CSP-HN Specifics
    BOTTLENECK_CHANNELS = 32
    DROPOUT_RATE = 0.2

    # ==========================================
    # 5. TRAINING HYPERPARAMETERS
    # ==========================================
    N_FOLDS = 5
    BATCH_SIZE = 32
    LEARNING_RATE = 3e-4  # Cite solution_lesson_node_00023
    NUM_EPOCHS = 100
    PATIENCE = 20  # Cite solution_lesson_node_00023
    WEIGHT_DECAY = 1e-4  # Applied conditionally in training loop if needed

    # ==========================================
    # 6. SYSTEM / HARDWARE
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 2

    @classmethod
    def setup(cls):
        """
        Initialize the environment:
        1. Create necessary working directories.
        2. Set random seeds for reproducibility.
        """
        # 1. Ensure directories exist
        os.makedirs(cls.WORK_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # 2. Set strict reproducibility
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)

        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.cuda.manual_seed_all(cls.SEED)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
