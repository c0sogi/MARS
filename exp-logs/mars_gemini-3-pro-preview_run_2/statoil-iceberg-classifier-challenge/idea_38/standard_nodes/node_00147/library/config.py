import os


class Config:
    """
    Configuration for the Channel-Recalibrated Wide-Body Network (CR-WBN) pipeline.
    Defines all hyperparameters, paths, and constants.
    """

    # ==========================================
    # 1. PATHS & DIRECTORIES
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for artifacts (models, cache)
    # Using 'idea_38' as the designated workspace for this experiment
    WORKING_DIR = "./working/idea_38"

    # Ensure working directory exists
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Input Files
    TRAIN_JSON = os.path.join(INPUT_DIR, "train.json")
    TEST_JSON = os.path.join(INPUT_DIR, "test.json")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Files (Generated by previous steps)
    TRAIN_META = os.path.join(METADATA_DIR, "train.csv")
    VAL_META = os.path.join(METADATA_DIR, "val.csv")
    TEST_META = os.path.join(METADATA_DIR, "test.csv")

    # Submission Output
    SUBMISSION_DIR = "./submission"
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Model Artifacts
    # Template for saving/loading model weights per fold
    MODEL_PATH_TEMPLATE = os.path.join(WORKING_DIR, "model_fold_{}.pth")
    # Path for caching processed numpy arrays to speed up subsequent runs
    CACHE_PATH = os.path.join(WORKING_DIR, "processed_data.npz")

    # ==========================================
    # 2. REPRODUCIBILITY
    # ==========================================
    SEED = 42

    # ==========================================
    # 3. DATA PARAMETERS
    # ==========================================
    IMAGE_SIZE = 75
    # Input constructed from Band 1, Band 2, and Mean(B1, B2)
    INPUT_CHANNELS = 3

    # Normalization Strategy
    # "Independent Per-Channel Min-Max Scaling using statistics derived from the entire training dataset"
    USE_GLOBAL_SCALING = True

    # Augmentation Strategy
    # Rotational Invariance (0, 90, 180, 270) + Horizontal Flip
    AUG_ROTATION = True
    AUG_HFLIP = True
    # Vertical Flips excluded per Idea instructions
    AUG_VFLIP = False

    # ==========================================
    # 4. MODEL ARCHITECTURE (CR-WBN)
    # ==========================================
    # "Sustained Width Strategy": Maintain 128 filters across backbone
    BACKBONE_FILTERS = 128

    # "Channel-Recalibrated Dual-Path Readout"
    # Dimension for the spatial context path
    READOUT_SPATIAL_DIM = 64

    # Regularization
    # High dropout to regularize the wide backbone
    DROPOUT_RATE = 0.5

    # ==========================================
    # 5. TRAINING HYPERPARAMETERS
    # ==========================================
    # Stratified 5-Fold Cross-Validation
    NUM_FOLDS = 5

    BATCH_SIZE = 32
    EPOCHS = 100
    PATIENCE = 10  # Early Stopping patience

    # Optimizer (Adam)
    LEARNING_RATE = 1e-4

    # Scheduler (ReduceLROnPlateau)
    SCHEDULER_FACTOR = 0.5
    SCHEDULER_PATIENCE = 3

    # ==========================================
    # 6. DEBUGGING
    # ==========================================
    # Flags to control dataset size for rapid debugging
    DEBUG = False
    DEBUG_SIZE = 100
