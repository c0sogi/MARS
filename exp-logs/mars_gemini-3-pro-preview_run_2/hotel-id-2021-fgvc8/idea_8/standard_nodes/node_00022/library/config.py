import os
import torch


class Config:
    """
    Configuration for Hotel ID task using Dual-Backbone Ensemble
    with Progressive Resolution Training.
    """

    # --- System & Reproducibility ---
    SEED = 42
    NUM_WORKERS = 12  # Utilizing all available vCPUs
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # --- Directories ---
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for this specific strategy (Idea 8)
    # Stores checkpoints, cached embeddings, and submission files
    WORKING_DIR = "./working/idea_8"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # --- Data Paths ---
    # Metadata files generated by the analysis script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # --- Model Architecture ---
    # Ensemble of CNN (local features) and Transformer-style (global context)
    BACKBONES = ["efficientnet_b4", "convnext_small"]
    EMBEDDING_DIM = 512
    NUM_CLASSES = 7770  # Derived from data analysis

    # --- Head Configuration (Sub-Center ArcFace) ---
    # K=3 centers per class to handle intra-class variance (e.g., room vs facade)
    SUB_CENTER_K = 3
    ARCFACE_MARGIN = 0.2
    ARCFACE_SCALE = 30.0

    # --- Training Strategy: Progressive Resolution ---
    # Phase 1: Initial convergence with lower resolution
    PHASE1_CONFIG = {"img_size": 256, "batch_size": 64, "epochs": 10, "lr": 1e-3}

    # Phase 2: Fine-tuning with higher resolution for details
    PHASE2_CONFIG = {"img_size": 384, "batch_size": 32, "epochs": 8, "lr": 1e-4}

    # Optimizer settings
    WEIGHT_DECAY = 1e-2

    # --- Inference & Post-Processing ---
    # Feature Fusion: Concatenation of embeddings from both backbones
    # DBA: Database Augmentation (Weighted average of neighbors in gallery)
    # QE: Query Expansion (Weighted average of retrieved neighbors for query)
    KNN_DBA = 5
    KNN_QE = 5
    TOP_K = 5  # For MAP@5 submission

    # --- Caching ---
    # Paths for caching intermediate embeddings to speed up inference/debugging
    CACHE_GALLERY_EMBS = os.path.join(WORKING_DIR, "gallery_embeddings.npy")
    CACHE_GALLERY_IDS = os.path.join(WORKING_DIR, "gallery_ids.npy")
    CACHE_QUERY_EMBS = os.path.join(WORKING_DIR, "query_embeddings.npy")
    SUBMISSION_PATH = os.path.join(WORKING_DIR, "submission.csv")

    @staticmethod
    def get_checkpoint_path(backbone_name):
        """Returns the path to save/load the best model for a specific backbone."""
        return os.path.join(Config.WORKING_DIR, f"best_model_{backbone_name}.pth")
