import os
import torch


class Config:
    """
    Configuration class for the Semi-Supervised Heterogeneous Stacking pipeline (Idea 11).
    """

    # =========================================================================
    # General Configuration
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 500  # Number of samples to use when DEBUG is True

    # =========================================================================
    # Compute Configuration
    # =========================================================================
    # 12 vCPUs and 1 NVIDIA A100 GPU available
    NUM_WORKERS = 12
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # =========================================================================
    # Data Configuration
    # =========================================================================
    IMG_SIZE = 224
    BATCH_SIZE = 64  # A100 40GB can handle larger batches for 'small' models

    # =========================================================================
    # Model Configuration
    # =========================================================================
    # Heterogeneous Stacking: CNN + Vision Transformer
    # Using 'Small' variants to ensure convergence within 24h budget
    MODEL_NAMES = ["convnext_small.fb_in22k", "swin_small_patch4_window7_224"]

    # Output dimension: 1 for Binary Classification (Dog probability)
    NUM_CLASSES = 1

    # =========================================================================
    # Training Configuration
    # =========================================================================
    N_FOLDS = 5
    EPOCHS = 20  # Extended training for convergence
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 0.01

    # Scheduler parameters (Cosine Annealing)
    T_MAX = EPOCHS
    MIN_LR = 1e-6

    # Semi-Supervised Learning / Pseudo-Labeling
    USE_PSEUDO_LABELING = True

    # =========================================================================
    # Path Configuration
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata Files (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Working Directory for Idea 11
    WORKING_DIR = "./working/idea_11"

    # Sub-directories for artifacts
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    OOF_DIR = os.path.join(WORKING_DIR, "oof")

    # Submission Directory (Required by competition)
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    @classmethod
    def create_directories(cls):
        """
        Creates the necessary directory structure for the experiment.
        Should be called at the start of the pipeline.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.OOF_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        print(f"Directories initialized at: {cls.WORKING_DIR}")
