import os
import cv2
import torch
import numpy as np
import pandas as pd
import albumentations as A
from albumentations.pytorch import ToTensorV2
from torch.utils.data import Dataset
from library.config import Config


def get_transforms(mode="train"):
    """
    Returns the Albumentations transformations for the specified mode.

    Args:
        mode (str): One of 'train', 'val', or 'test'.

    Returns:
        A.Compose: Composed albumentations transforms.
    """
    if mode == "train":
        return A.Compose(
            [
                A.RandomResizedCrop(
                    size=(Config.IMG_SIZE, Config.IMG_SIZE),
                    scale=Config.CROP_SCALE,
                    p=1.0,
                ),
                A.HorizontalFlip(p=0.5),
                A.Normalize(
                    mean=(0.485, 0.456, 0.406),
                    std=(0.229, 0.224, 0.225),
                    max_pixel_value=255.0,
                    p=1.0,
                ),
                ToTensorV2(),
            ]
        )
    else:
        # Validation and Test
        return A.Compose(
            [
                A.Resize(height=Config.IMG_SIZE, width=Config.IMG_SIZE),
                A.Normalize(
                    mean=(0.485, 0.456, 0.406),
                    std=(0.229, 0.224, 0.225),
                    max_pixel_value=255.0,
                    p=1.0,
                ),
                ToTensorV2(),
            ]
        )


class DogCatDataset(Dataset):
    """
    Dataset class for loading Dog vs Cat images.
    """

    def __init__(self, df, transforms=None, mode="train"):
        """
        Args:
            df (pd.DataFrame): DataFrame containing metadata (filepath, label/id).
            transforms (A.Compose, optional): Albumentations transforms to apply.
            mode (str): 'train', 'val', or 'test'. Determines return values.
        """
        self.df = df
        self.transforms = transforms
        self.mode = mode
        self.input_dir = Config.INPUT_DIR

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]

        # Construct full path from relative path in metadata
        image_path = os.path.join(self.input_dir, row["filepath"])

        # Load image using OpenCV
        image = cv2.imread(image_path)
        if image is None:
            raise FileNotFoundError(f"Image not found or corrupt at {image_path}")

        # Convert BGR to RGB
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

        # Apply transforms
        if self.transforms:
            augmented = self.transforms(image=image)
            image = augmented["image"]

        # Return data based on mode
        if self.mode == "test":
            # For test, we need the ID to map predictions to the submission file
            return image, row["id"]
        else:
            # For train/val, we need the label
            label = row["label"]
            # Return label as float tensor for BCEWithLogitsLoss
            return image, torch.tensor(label, dtype=torch.float32)


def get_datasets(debug=Config.DEBUG, debug_sample_size=Config.DEBUG_SAMPLE_SIZE):
    """
    Loads metadata and creates Dataset objects for train, val, and test splits.

    Args:
        debug (bool): If True, subsets the data for debugging.
        debug_sample_size (int): Number of samples to use if debug is True.

    Returns:
        tuple: (train_dataset, val_dataset, test_dataset)
    """
    # Load metadata CSVs generated by the metadata script
    train_df = pd.read_csv(Config.TRAIN_METADATA_PATH)
    val_df = pd.read_csv(Config.VAL_METADATA_PATH)
    test_df = pd.read_csv(Config.TEST_METADATA_PATH)

    # Apply debug sampling if requested
    if debug:
        train_df = train_df.head(debug_sample_size)
        val_df = val_df.head(debug_sample_size)
        test_df = test_df.head(debug_sample_size)

    # Instantiate Datasets
    train_dataset = DogCatDataset(
        train_df, transforms=get_transforms(mode="train"), mode="train"
    )

    val_dataset = DogCatDataset(
        val_df, transforms=get_transforms(mode="val"), mode="val"
    )

    test_dataset = DogCatDataset(
        test_df, transforms=get_transforms(mode="test"), mode="test"
    )

    return train_dataset, val_dataset, test_dataset
