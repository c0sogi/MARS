import os
import torch


class Config:
    """
    Configuration for the Dog vs Cat classification task.
    Implements settings for a Heterogeneous High-Capacity Ensemble (ConvNeXt + Swin).
    """

    # -------------------------------------------------------------------------
    # Reproducibility & System
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Toggle for debugging on smaller subsets

    # Compute environment
    # 12 vCPUs available, 4 workers is a safe balance to avoid overhead
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata inputs (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Outputs
    # Specific working directory for Idea 6 (Heterogeneous Ensemble)
    WORKING_DIR = "./working/idea_6"

    # Final submission directory
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data & Augmentation
    # -------------------------------------------------------------------------
    IMG_SIZE = 224

    # Mixup alpha for probability calibration and soft decision boundaries
    MIXUP_ALPHA = 0.2

    # -------------------------------------------------------------------------
    # Model Architectures
    # -------------------------------------------------------------------------
    # Heterogeneous ensemble:
    # 1. ConvNeXt-Small (Convolutional bias)
    # 2. Swin-Small (Transformer bias, shifted windows)
    MODEL_ARCHS = ["convnext_small.fb_in1k", "swin_small_patch4_window7_224.ms_in1k"]

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    N_FOLDS = 5
    EPOCHS = 15

    # Batch size of 64 fits comfortably on A100-40GB for these model sizes
    BATCH_SIZE = 64

    # Optimization
    LR = 1e-4
    MIN_LR = 1e-6
    WEIGHT_DECAY = 0.01  # Standard for AdamW

    @classmethod
    def setup(cls):
        """
        Creates necessary output directories for checkpoints and submissions.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

    @classmethod
    def get_checkpoint_path(cls, model_arch, fold):
        """
        Generates a standardized path for saving model checkpoints.

        Args:
            model_arch (str): The name of the model architecture.
            fold (int): The fold index (0-4).

        Returns:
            str: Full path to the checkpoint file.
        """
        # Sanitize model name for filesystem safety
        safe_arch_name = model_arch.replace(".", "_")
        filename = f"{safe_arch_name}_fold_{fold}.pth"
        return os.path.join(cls.WORKING_DIR, filename)
