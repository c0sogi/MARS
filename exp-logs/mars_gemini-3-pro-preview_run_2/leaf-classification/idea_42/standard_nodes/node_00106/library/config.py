import os
import numpy as np


class Config:
    """
    Configuration for the Iterative-Gaussianized Corrected-Morphology Ensemble (IGCME).
    """

    # ==========================================
    # System & Reproducibility
    # ==========================================
    RANDOM_SEED = 42
    N_JOBS = 12
    FLOAT_PRECISION = np.float64

    # ==========================================
    # File Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    IMAGES_DIR = os.path.join(INPUT_DIR, "images")

    # Metadata generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output Directories
    WORKING_DIR = "./working/idea_42"
    CACHE_DIR = WORKING_DIR
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Data Processing Parameters
    # ==========================================
    # Polarity Correction: Threshold to decide if a corner pixel is "white" (background)
    # If mean corner intensity > threshold, image is inverted.
    POLARITY_CHECK_THRESHOLD = 0.90

    # Image loading
    IMG_SIZE = None  # None implies using original size, or specify tuple (H, W)

    # ==========================================
    # Expert Library Hyperparameters
    # ==========================================
    # Topologies define the Gaussianization pipeline:
    # 1. 'marginal': Yeo-Johnson
    # 2. 'iterative': Yeo-Johnson -> PCA(whiten=False) -> Yeo-Johnson
    # 3. 'constrained': QuantileTransformer(n_quantiles=50)
    TOPOLOGIES = ["marginal", "iterative", "constrained"]

    # Shrinkage values for Linear Discriminant Analysis (LDA)
    # 'auto' maps to OAS (Oracle Approximating Shrinkage)
    SHRINKAGE_VALUES = ["auto", 0.001, 0.01, 0.1]

    # Feature Views:
    # 'global': The provided 192 texture/shape/margin features
    # 'combined': Global features + Extracted Morphometric features (Hu Moments + Geometry)
    VIEWS = ["global", "combined"]

    # ==========================================
    # Transformer Specifics
    # ==========================================
    # Constrained Rank Normalization
    QUANTILE_N_QUANTILES = 50
    QUANTILE_OUTPUT_DIST = "normal"

    # Iterative Manifold Engineering
    PCA_WHITEN = False  # Whitening is disabled to prevent noise amplification

    # ==========================================
    # Evaluation & Submission
    # ==========================================
    PROB_CLIP_EPS = 1e-15
    SELECTION_METRIC = "log_loss"

    # Debugging: Set to an integer (e.g., 100) to subsample data for rapid testing
    DEBUG_SAMPLE_SIZE = None

    @staticmethod
    def setup():
        """Ensures all necessary output directories exist."""
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)


# Initialize directories on import
Config.setup()
