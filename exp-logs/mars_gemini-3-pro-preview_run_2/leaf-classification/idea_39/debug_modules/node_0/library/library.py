import numpy as np
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis
from library import config


class LDAExpert:
    """
    Wrapper for Linear Discriminant Analysis expert model.

    Implements the probabilistic expert component of the DSPGL architecture.
    Supports both analytical shrinkage (Ledoit-Wolf, approximating OAS) and
    fixed shrinkage values to capture empirical optima.

    Strictly enforces float64 precision to minimize numerical noise at the metric floor.
    """

    def __init__(self, shrinkage, view_name):
        """
        Initialize the LDA Expert.

        Args:
            shrinkage (str or float): The shrinkage parameter.
                                      'auto' for analytical shrinkage (Ledoit-Wolf).
                                      Float between 0 and 1 for fixed shrinkage.
            view_name (str): The specific feature view this expert consumes
                             (e.g., 'global_a', 'macro_b').
        """
        self.shrinkage = shrinkage
        self.view_name = view_name

        # solver='lsqr' is required to use shrinkage in sklearn's LDA
        self.model = LinearDiscriminantAnalysis(solver="lsqr", shrinkage=self.shrinkage)

    def fit(self, X, y):
        """
        Fit the LDA model to the training data.

        Args:
            X (np.ndarray): Feature matrix.
            y (np.ndarray): Target labels.

        Returns:
            self
        """
        # Strictly enforce float64 precision as per Lesson 73
        X_f64 = X.astype(config.FLOAT_PRECISION)
        self.model.fit(X_f64, y)
        return self

    def predict_proba(self, X):
        """
        Predict class probabilities.

        Args:
            X (np.ndarray): Feature matrix.

        Returns:
            np.ndarray: Matrix of class probabilities (n_samples, n_classes).
        """
        # Strictly enforce float64 precision
        X_f64 = X.astype(config.FLOAT_PRECISION)
        return self.model.predict_proba(X_f64)

    def __repr__(self):
        return f"LDAExpert(view={self.view_name}, shrinkage={self.shrinkage})"


def generate_expert_configs():
    """
    Generates the comprehensive list of expert configurations for the ensemble.

    Constructs the library by iterating over:
    1. Feature Views:
       - global_a (Global Features + PowerTransformer)
       - global_b (Global Features + QuantileTransformer n=50)
       - macro_a  (Macro Features + PowerTransformer)
       - macro_b  (Macro Features + QuantileTransformer n=50)

    2. Shrinkage Strategies:
       - 'auto' (Analytical Baseline)
       - Fixed values defined in config.FIXED_SHRINKAGE_VALUES (e.g., 0.001, 0.01, 0.1)

    Returns:
        list[dict]: A list of configuration dictionaries, each containing:
                    - 'name': Unique identifier string.
                    - 'view': The feature view key.
                    - 'shrinkage': The shrinkage parameter.
    """
    configs = []

    # The four views generated by the DualStreamPipeline
    views = ["global_a", "global_b", "macro_a", "macro_b"]

    # Shrinkage options: Analytical ('auto') + Empirical Fixed Grid
    shrinkage_options = ["auto"] + config.FIXED_SHRINKAGE_VALUES

    for view in views:
        for shrinkage in shrinkage_options:
            # Create a unique name for the expert
            # e.g., "global_a_shrinkage_auto" or "macro_b_shrinkage_0.01"
            s_str = str(shrinkage)
            expert_name = f"{view}_shrinkage_{s_str}"

            config_dict = {"name": expert_name, "view": view, "shrinkage": shrinkage}
            configs.append(config_dict)

    return configs
