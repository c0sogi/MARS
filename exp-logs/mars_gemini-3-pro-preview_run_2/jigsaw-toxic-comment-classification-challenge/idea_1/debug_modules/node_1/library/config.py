import os


class Config:
    """
    Configuration class for the Toxic Comment Classification task.
    Centralizes file paths, model hyperparameters, and feature extraction settings.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    N_JOBS = 12  # Utilize available 12 vCPUs

    # =========================================================================
    # File Paths & Directories
    # =========================================================================
    # Input Metadata Paths (generated by the metadata script)
    METADATA_DIR = "./metadata"
    TRAIN_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Working Directory for Caching Intermediate Artifacts
    WORKING_DIR = "./working"
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_1")

    # Output Directory for Submission
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure necessary directories exist
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # =========================================================================
    # Data Information
    # =========================================================================
    TARGET_COLS = [
        "toxic",
        "severe_toxic",
        "obscene",
        "threat",
        "insult",
        "identity_hate",
    ]

    # =========================================================================
    # Feature Extraction (TF-IDF)
    # =========================================================================
    # Word-level TF-IDF parameters
    WORD_NGRAM_RANGE = (1, 2)
    WORD_MAX_FEATURES = 50000  # High enough to capture semantic meaning
    WORD_MIN_DF = 2  # Filter out extremely rare tokens

    # Character-level TF-IDF parameters
    # Captures subword information, misspellings, and obfuscation
    CHAR_NGRAM_RANGE = (2, 6)
    CHAR_MAX_FEATURES = 50000
    CHAR_MIN_DF = 2

    # =========================================================================
    # Model Hyperparameters (Logistic Regression)
    # =========================================================================
    # C: Inverse of regularization strength; smaller values specify stronger regularization.
    # 4.0 is a common starting point for text classification with TF-IDF.
    LR_C = 4.0

    # Solver: 'sag' (Stochastic Average Gradient) is efficient for large datasets.
    LR_SOLVER = "sag"

    # Max Iterations: Ensure convergence for the solver.
    LR_MAX_ITER = 1000

    # =========================================================================
    # Debugging
    # =========================================================================
    # Set to True to run on a small subset of data for quick pipeline verification
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 2000
