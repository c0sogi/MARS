def load_raw_data(debug: bool = Config.DEBUG):
    """
    Loads the train, validation, and test datasets from the metadata directory.

    Args:
        debug (bool): If True, subsamples the datasets for debugging purposes.

    Returns:
        tuple: (train_df, val_df, test_df)
    """
    train_df = pd.read_csv(Config.TRAIN_CSV)
    val_df = pd.read_csv(Config.VAL_CSV)
    test_df = pd.read_csv(Config.TEST_CSV)

    # Fill missing text values
    train_df["comment_text"] = train_df["comment_text"].fillna("none")
    val_df["comment_text"] = val_df["comment_text"].fillna("none")
    test_df["comment_text"] = test_df["comment_text"].fillna("none")

    if debug:
        print(f"Debug mode enabled. Subsampling {Config.DEBUG_SAMPLES} samples.")
        train_df = train_df.head(Config.DEBUG_SAMPLES).reset_index(drop=True)
        val_df = val_df.head(Config.DEBUG_SAMPLES).reset_index(drop=True)
        test_df = test_df.head(Config.DEBUG_SAMPLES).reset_index(drop=True)

    return train_df, val_df, test_df


class ToxicityDataset(Dataset):
    """
    PyTorch Dataset for the toxicity classification task.
    Handles tokenization and label formatting.
    """

    def __init__(
        self,
        texts: list,
        tokenizer: PreTrainedTokenizer,
        labels: np.ndarray = None,
        max_length: int = Config.MAX_LENGTH,
    ):
        """
        Args:
            texts (list): List of input text strings.
            tokenizer (PreTrainedTokenizer): HuggingFace tokenizer.
            labels (np.ndarray, optional): Binary labels matrix (N, num_classes).
            max_length (int): Maximum sequence length for tokenization.
        """
        self.texts = texts
        self.tokenizer = tokenizer
        self.labels = labels
        self.max_length = max_length

    def __len__(self):
        return len(self.texts)

    def __getitem__(self, idx):
        text = str(self.texts[idx])

        encoding = self.tokenizer(
            text,
            add_special_tokens=True,
            max_length=self.max_length,
            padding="max_length",
            truncation=True,
            return_tensors="pt",
        )

        item = {
            "input_ids": encoding["input_ids"].flatten(),
            "attention_mask": encoding["attention_mask"].flatten(),
        }

        if self.labels is not None:
            # Labels should be float for BCEWithLogitsLoss
            item["labels"] = torch.tensor(self.labels[idx], dtype=torch.float)

        return item


class MLMDataset(Dataset):
    """
    Dataset for Masked Language Modeling (TAPT).
    Returns input_ids and attention_mask without labels (labels are generated by DataCollator).
    """

    def __init__(
        self,
        texts: list,
        tokenizer: PreTrainedTokenizer,
        max_length: int = Config.MAX_LENGTH,
    ):
        self.texts = texts
        self.tokenizer = tokenizer
        self.max_length = max_length

    def __len__(self):
        return len(self.texts)

    def __getitem__(self, idx):
        text = str(self.texts[idx])
        encoding = self.tokenizer(
            text,
            add_special_tokens=True,
            max_length=self.max_length,
            padding="max_length",
            truncation=True,
            return_tensors="pt",
        )
        return {
            "input_ids": encoding["input_ids"].flatten(),
            "attention_mask": encoding["attention_mask"].flatten(),
        }


def get_mlm_dataset(tokenizer: PreTrainedTokenizer, debug: bool = Config.DEBUG):
    """
    Prepares the dataset for Task-Adaptive Pretraining (TAPT).
    Combines Train and Test text to create a domain-specific corpus.

    Args:
        tokenizer: HuggingFace tokenizer.
        debug: If True, uses a subset of data.

    Returns:
        MLMDataset: Dataset object for MLM training.
    """
    train_df, val_df, test_df = load_raw_data(debug=debug)

    # Combine all available text for domain adaptation
    all_texts = (
        pd.concat(
            [train_df["comment_text"], val_df["comment_text"], test_df["comment_text"]]
        )
        .astype(str)
        .tolist()
    )

    if debug:
        print(f"Creating MLM dataset with {len(all_texts)} samples (Debug Mode)")
    else:
        print(f"Creating MLM dataset with {len(all_texts)} samples")

    return MLMDataset(all_texts, tokenizer)


def get_tfidf_features(train_text, val_text, test_text, load_cached_data: bool = True):
    """
    Generates or loads TF-IDF features for the linear baseline model.
    Implements caching using scipy.sparse.save_npz/load_npz.

    Args:
        train_text: Series or list of training texts.
        val_text: Series or list of validation texts.
        test_text: Series or list of test texts.
        load_cached_data: Whether to attempt loading from disk.

    Returns:
        tuple: (X_train, X_val, X_test) as sparse matrices.
    """
    # Define cache paths
    cache_dir = Config.TFIDF_CACHE_DIR
    os.makedirs(cache_dir, exist_ok=True)

    paths = {
        "train": os.path.join(cache_dir, "tfidf_train.npz"),
        "val": os.path.join(cache_dir, "tfidf_val.npz"),
        "test": os.path.join(cache_dir, "tfidf_test.npz"),
    }

    # Check if all files exist
    all_exist = all(os.path.exists(p) for p in paths.values())

    if load_cached_data and all_exist:
        print("Loading cached TF-IDF features...")
        try:
            X_train = sparse.load_npz(paths["train"])
            X_val = sparse.load_npz(paths["val"])
            X_test = sparse.load_npz(paths["test"])
            return X_train, X_val, X_test
        except Exception as e:
            print(f"Failed to load cache: {e}. Recomputing...")

    print("Computing TF-IDF features...")

    # Combine texts to fit vectorizers (standard competition practice for unsupervised features)
    all_text = pd.concat(
        [pd.Series(train_text), pd.Series(val_text), pd.Series(test_text)]
    ).astype(str)

    # Word Vectorizer
    word_vectorizer = TfidfVectorizer(
        sublinear_tf=True,
        strip_accents="unicode",
        analyzer="word",
        token_pattern=r"\w{1,}",
        stop_words="english",
        ngram_range=Config.LINEAR_PARAMS["word_ngram_range"],
        max_features=Config.LINEAR_PARAMS["max_features_word"],
    )

    # Char Vectorizer
    char_vectorizer = TfidfVectorizer(
        sublinear_tf=True,
        strip_accents="unicode",
        analyzer="char",
        stop_words="english",
        ngram_range=Config.LINEAR_PARAMS["char_ngram_range"],
        max_features=Config.LINEAR_PARAMS["max_features_char"],
    )

    print("Fitting Word Vectorizer...")
    word_vectorizer.fit(all_text)
    print("Fitting Char Vectorizer...")
    char_vectorizer.fit(all_text)

    def transform_and_stack(text_series):
        word_feats = word_vectorizer.transform(text_series.astype(str))
        char_feats = char_vectorizer.transform(text_series.astype(str))
        return sparse.hstack([word_feats, char_feats])

    print("Transforming Train...")
    X_train = transform_and_stack(train_text)
    print("Transforming Val...")
    X_val = transform_and_stack(val_text)
    print("Transforming Test...")
    X_test = transform_and_stack(test_text)

    # Save to cache
    print("Saving TF-IDF features to cache...")
    sparse.save_npz(paths["train"], X_train)
    sparse.save_npz(paths["val"], X_val)
    sparse.save_npz(paths["test"], X_test)

    return X_train, X_val, X_test
