import os


class Config:
    """
    Centralized configuration for the Single-Stream Dilated Residual Network.
    Contains hyperparameters for data processing, model architecture, training, and inference.
    """

    # --- Reproducibility ---
    SEED = 42

    # --- File Paths ---
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_9"
    SUBMISSION_DIR = "./submission"

    # Raw Data
    TRAIN_DATA_PATH = os.path.join(INPUT_DIR, "simplified-nq-train.jsonl")
    TEST_DATA_PATH = os.path.join(INPUT_DIR, "simplified-nq-test.jsonl")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "validation_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # --- Caching ---
    # Paths for caching deterministic data processing artifacts
    CACHE_DIR = WORKING_DIR
    VOCAB_CACHE_PATH = os.path.join(CACHE_DIR, "vocab.npy")
    EMBEDDING_MATRIX_CACHE_PATH = os.path.join(CACHE_DIR, "embedding_matrix.npy")
    PROCESSED_TRAIN_DATA_PATH = os.path.join(CACHE_DIR, "train_data.parquet")
    PROCESSED_VAL_DATA_PATH = os.path.join(CACHE_DIR, "val_data.parquet")
    PROCESSED_TEST_DATA_PATH = os.path.join(CACHE_DIR, "test_data.parquet")

    # --- Data Preprocessing ---
    # Max length for the concatenated [Question + Candidate] sequence
    MAX_SEQ_LEN = 350
    # Maximum size of the vocabulary
    VOCAB_SIZE = 50000
    # Dimension of the token embeddings
    EMBEDDING_DIM = 128
    # Special tokens
    PAD_TOKEN = "<PAD>"
    UNK_TOKEN = "<UNK>"
    SEP_TOKEN = "<SEP>"

    # --- Model Architecture ---
    # Dimension of the convolutional channels
    HIDDEN_DIM = 256
    # Kernel size for 1D convolutions
    KERNEL_SIZE = 3
    # Dilation rates for the stacked blocks (exponential expansion)
    DILATION_RATES = [1, 2, 4, 8]
    # Dropout probability
    DROPOUT_RATE = 0.2
    # Number of classes for Yes/No head (YES, NO, NONE)
    NUM_YES_NO_CLASSES = 3

    # --- Training Hyperparameters ---
    # Batch size for training and evaluation
    BATCH_SIZE = 64
    # Initial learning rate for Adam optimizer
    LEARNING_RATE = 1e-3
    # Number of training epochs
    NUM_EPOCHS = 5
    # Patience for early stopping
    EARLY_STOPPING_PATIENCE = 2
    # Ratio of negative samples (non-answers) to positive samples in training batches
    NEGATIVE_SAMPLING_RATIO = 2.0
    # Fraction of dataset to use for debugging (set to 1.0 for full run)
    DATASET_FRACTION = 1.0

    # --- Loss Weights (Multi-Task Learning) ---
    # Weight for the binary ranking loss (Long Answer)
    LOSS_WEIGHT_RANKING = 1.0
    # Weight for the span extraction loss (Short Answer Start/End)
    LOSS_WEIGHT_SPAN = 1.0
    # Weight for the classification loss (Yes/No)
    LOSS_WEIGHT_YESNO = 0.5

    # --- Inference ---
    # Minimum score required to predict a long answer (vs BLANK)
    LONG_ANSWER_THRESHOLD = 0.5
    # Minimum score required to predict a short answer span
    SHORT_ANSWER_THRESHOLD = 0.1

    @classmethod
    def setup(cls):
        """
        Ensures that the necessary working and submission directories exist.
        This should be called at the start of execution.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories immediately upon module import
Config.setup()
