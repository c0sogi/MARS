import os
import torch


class Config:
    """
    Configuration class for the Tweet Sentiment Extraction task.
    Centralizes all hyperparameters, file paths, and model settings.
    """

    # ====================================================
    # General Settings
    # ====================================================
    SEED = 42
    NUM_FOLDS = 5
    NUM_WORKERS = 4
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # Debugging: Set to True to train on a small subset for quick verification
    DEBUG = False

    # ====================================================
    # Data Paths
    # ====================================================
    # Input metadata paths (generated by the metadata script)
    TRAIN_META_PATH = "./metadata/train.csv"
    VAL_META_PATH = "./metadata/val.csv"
    TEST_META_PATH = "./metadata/test.csv"

    # Output paths
    WORKING_DIR = "./working/idea_8/"
    SUBMISSION_PATH = "./submission/submission.csv"

    # Ensure working directory exists
    os.makedirs(WORKING_DIR, exist_ok=True)

    # ====================================================
    # Model Settings
    # ====================================================
    MODEL_NAME = "microsoft/deberta-v3-large"

    # Max length for tokenization.
    # EDA shows max char length ~141. 128 tokens is generally safe for tweets with special tokens.
    MAX_LEN = 128

    # ====================================================
    # Training Hyperparameters
    # ====================================================
    # Batch size: Adjusted for A100 40GB.
    # DeBERTa-Large is memory intensive; 8-16 is typical.
    # Using 12 to be safe with gradients, can be increased if using aggressive gradient checkpointing.
    TRAIN_BATCH_SIZE = 12
    VALID_BATCH_SIZE = 16

    # Training duration
    EPOCHS = 4

    # Optimizer settings
    LEARNING_RATE = 1e-5
    WEIGHT_DECAY = 0.01
    EPS = 1e-6
    MAX_GRAD_NORM = 1.0

    # Scheduler settings
    SCHEDULER_TYPE = "linear"
    WARMUP_RATIO = 0.1

    # Loss function settings
    LABEL_SMOOTHING = 0.1

    # Inference settings
    # Post-processing heuristic for neutral tweets
    NEUTRAL_SENTIMENT_THRESHOLD = 0.98  # Jaccard correlation is high for neutral
