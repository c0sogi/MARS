import os
import random
import numpy as np
import torch


class Config:
    """
    Configuration class for the Bird Species Classification task.
    Encapsulates file paths, hyperparameters, and model settings.
    """

    def __init__(self, debug=False, epochs=50, batch_size=16, image_size=(224, 224)):
        # --- General Settings ---
        self.seed = 42
        self.debug = debug
        self.device = "cuda" if torch.cuda.is_available() else "cpu"

        # --- File Paths ---
        # Base directories
        self.input_dir = "./input"
        self.metadata_dir = "./metadata"
        self.working_dir = "./working/idea_4"
        self.submission_dir = "./submission"

        # Input Data Paths
        # Using filtered spectrograms as per the robustness strategy
        self.spectrogram_dir = os.path.join(
            self.input_dir, "supplemental_data", "filtered_spectrograms"
        )

        # Metadata CSVs (Generated by the metadata script)
        # Note: Ideally, train and val are combined for K-Fold CV
        self.train_csv_path = os.path.join(self.metadata_dir, "train.csv")
        self.val_csv_path = os.path.join(self.metadata_dir, "val.csv")
        self.test_csv_path = os.path.join(self.metadata_dir, "test.csv")

        # Output Paths
        self.model_output_dir = os.path.join(self.working_dir, "models")
        self.predictions_dir = os.path.join(self.working_dir, "preds")
        self.submission_path = os.path.join(self.submission_dir, "submission.csv")

        # --- Data Parameters ---
        self.num_classes = 19
        self.image_size = image_size
        self.n_folds = 5  # For Stratified K-Fold Ensemble
        self.num_workers = 2

        # --- Training Hyperparameters ---
        self.epochs = epochs
        self.batch_size = batch_size
        self.learning_rate = 1e-3
        self.weight_decay = 1e-4

        # Mixup Augmentation
        self.mixup_alpha = 0.4

        # --- Model Architecture ---
        self.backbone = "resnet18"
        self.pretrained = True
        self.use_dual_pooling = True  # Custom head config (Concat(Avg, Max))

        # --- Debugging Overrides ---
        if self.debug:
            self.epochs = 2
            self.n_folds = 2

        # --- Directory Setup ---
        self._create_directories()

    def _create_directories(self):
        """Creates necessary output directories if they don't exist."""
        os.makedirs(self.working_dir, exist_ok=True)
        os.makedirs(self.model_output_dir, exist_ok=True)
        os.makedirs(self.predictions_dir, exist_ok=True)
        os.makedirs(self.submission_dir, exist_ok=True)

    def set_seed(self):
        """Sets fixed random seeds for reproducibility."""
        random.seed(self.seed)
        np.random.seed(self.seed)
        torch.manual_seed(self.seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(self.seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
