import os
import torch


class Config:
    """
    Global configuration for the Bird Species Classification Task.
    Implements the Tri-Architecture Multi-Resolution Ensemble strategy.
    """

    # -------------------------------------------------------------------------
    # General Configuration
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    NUM_WORKERS = 2
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # -------------------------------------------------------------------------
    # File System Paths
    # -------------------------------------------------------------------------
    # Base input directory (Read-Only)
    INPUT_DIR = "./input"

    # Metadata directory (Generated by previous steps)
    METADATA_DIR = "./metadata"
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Source of Spectrograms
    # Using 'filtered_spectrograms' as per the strategy to reduce noise
    SPECTROGRAM_DIR = os.path.join(
        INPUT_DIR, "supplemental_data", "filtered_spectrograms"
    )

    # Working Directory (Read/Write)
    # Used for caching processed data and saving model checkpoints
    WORKING_DIR = "./working/idea_13"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Submission Output
    SUBMISSION_DIR = "./submission"
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Dataset Specifications
    # -------------------------------------------------------------------------
    NUM_SPECIES = 19
    NUM_FOLDS = 5

    # Input Channels: 3 (Pseudo-RGB)
    # The single-channel spectrogram is replicated 3 times to fit ImageNet-pretrained models
    IN_CHANNELS = 3

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    # Strategy: Aggressive Adaptation with Weighted Loss
    # Target: ~1000 total update steps per fold.
    # With ~165 training samples and Batch Size 32, we have ~5 steps per epoch.
    # 200 Epochs * 5 steps = 1000 steps.
    BATCH_SIZE = 32
    NUM_EPOCHS = 200

    # Optimizer settings
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4  # Regularization

    # Mixup Regularization (Mild)
    MIXUP_ALPHA = 0.4

    # -------------------------------------------------------------------------
    # Model Architecture Specifications
    # -------------------------------------------------------------------------
    # Defines the heterogeneous ensemble with multi-resolution inputs.
    # Resolution Format: (Height/Frequency, Width/Time)
    #
    # 1. ResNet18: Rectangular aspect ratio to capture temporal transients.
    # 2. EfficientNet-B0: Adds MBConv inductive bias.
    # 3. DenseNet121: Deepest model gets lower resolution to prevent overfitting to noise.

    MODEL_SPECS = {
        "resnet18": {
            "backbone": "resnet18",
            "resolution": (224, 448),
            "pretrained": True,
        },
        "efficientnet_b0": {
            "backbone": "efficientnet_b0",
            "resolution": (224, 448),
            "pretrained": True,
        },
        "densenet121": {
            "backbone": "densenet121",
            "resolution": (160, 320),
            "pretrained": True,
        },
    }

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print("\n" + "=" * 40)
        print(f"{'CONFIG':^40}")
        print("=" * 40)
        for k, v in cls.__dict__.items():
            if not k.startswith("__") and not callable(v):
                print(f"{k:<20}: {v}")
        print("=" * 40 + "\n")
