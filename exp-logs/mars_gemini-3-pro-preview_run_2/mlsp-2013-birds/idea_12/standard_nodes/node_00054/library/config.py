import os
import torch


class Config:
    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    NUM_CLASSES = 19
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # =========================================================================
    # Paths
    # =========================================================================
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Output directory for this specific idea/experiment
    WORK_DIR = "./working/idea_13"
    os.makedirs(WORK_DIR, exist_ok=True)

    # Metadata files generated by the metadata script
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Submission output
    SUBMISSION_PATH = "./submission/submission.csv"
    os.makedirs(os.path.dirname(SUBMISSION_PATH), exist_ok=True)

    # Spectrogram Data
    # The idea requires using Filtered Spectrograms
    USE_FILTERED_SPECTROGRAMS = True
    FILTERED_SPECTROGRAMS_DIR = os.path.join(
        INPUT_ROOT, "supplemental_data", "filtered_spectrograms"
    )

    # =========================================================================
    # Data Processing & Augmentation
    # =========================================================================
    NUM_FOLDS = 5

    # Mixup
    USE_MIXUP = True
    MIXUP_ALPHA = 0.4

    # =========================================================================
    # Model Architecture & Input Dimensions
    # =========================================================================
    # Branch A: ResNet18 (High-Fidelity Temporal)
    MODEL_A_NAME = "resnet18"
    # Format: (Height/Freq, Width/Time)
    RESNET_INPUT_SIZE = (224, 448)

    # Branch B: DenseNet121 (Structural Regularization)
    MODEL_B_NAME = "densenet121"
    # Format: (Height/Freq, Width/Time)
    DENSENET_INPUT_SIZE = (160, 320)

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 16

    # Optimization
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Training Duration
    # Target is ~1000 update steps per fold.
    # With ~165 samples per fold and batch size 16, steps/epoch is ~11.
    # 1000 / 11 ~= 90 epochs. Setting to 100 for safety.
    NUM_EPOCHS = 100

    # Stochastic Weight Averaging (SWA)
    # Start SWA in the final 25% of training
    SWA_START_EPOCH_RATIO = 0.75
    SWA_START_EPOCH = int(NUM_EPOCHS * SWA_START_EPOCH_RATIO)

    # Loss Configuration
    # Positive weights are handled dynamically in the training loop based on class frequencies,
    # but the loss function type is defined here.
    LOSS_FUNCTION = "BCEWithLogitsLoss"

    @classmethod
    def get_spectrogram_path(cls, filename):
        """
        Helper to get the correct path for a spectrogram file.
        If USE_FILTERED_SPECTROGRAMS is True, returns path in filtered_spectrograms directory.
        """
        base_name = os.path.basename(filename)
        # Ensure extension is .bmp (metadata might have .wav or .bmp depending on column)
        if base_name.lower().endswith(".wav"):
            base_name = os.path.splitext(base_name)[0] + ".bmp"

        if cls.USE_FILTERED_SPECTROGRAMS:
            return os.path.join(cls.FILTERED_SPECTROGRAMS_DIR, base_name)
        else:
            # Fallback to standard spectrograms if ever needed
            return os.path.join(
                cls.INPUT_ROOT, "supplemental_data", "spectrograms", base_name
            )
