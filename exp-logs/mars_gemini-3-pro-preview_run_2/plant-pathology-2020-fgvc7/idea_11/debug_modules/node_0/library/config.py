import os
import torch


class Config:
    # -------------------------------------------------------------------------
    # General Configuration
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run with a small subset of data
    NUM_FOLDS = 5
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # -------------------------------------------------------------------------
    # Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the provided script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    IMAGES_DIR = os.path.join(INPUT_DIR, "images")

    # Output directories
    WORKING_DIR = "./working"
    IDEA_DIR = os.path.join(WORKING_DIR, "idea_11")
    SUBMISSION_PATH = os.path.join(WORKING_DIR, "submission.csv")

    # Create the output directory immediately
    os.makedirs(IDEA_DIR, exist_ok=True)

    # -------------------------------------------------------------------------
    # Model Architecture & Ensemble
    # -------------------------------------------------------------------------
    # Heterogeneous Ensemble: EfficientNetV2-L and ConvNeXt-Base
    MODELS = [
        {
            "model_name": "tf_efficientnetv2_l.in21k_ft_in1k",
            "img_size": 480,
            "batch_size": 16,
            "fold_indices": [0, 1, 2, 3, 4],  # Train all folds
        },
        {
            "model_name": "convnext_base.fb_in22k_ft_in1k_384",
            "img_size": 384,
            "batch_size": 16,
            "fold_indices": [0, 1, 2, 3, 4],  # Train all folds
        },
    ]

    # -------------------------------------------------------------------------
    # Head Design & Loss
    # -------------------------------------------------------------------------
    # Multi-Label Decomposition: We predict Rust and Scab independently.
    # Healthy = (1-Rust)*(1-Scab), Multiple = Rust*Scab
    TARGET_COLUMNS = ["rust", "scab"]
    NUM_CLASSES = 2

    # Structural Innovations
    USE_GEM_POOLING = True
    GEM_P_INIT = 3.0

    USE_MULTI_SAMPLE_DROPOUT = True
    DROPOUT_RATES = [0.0, 0.1, 0.2, 0.3, 0.4]

    # Loss Settings
    USE_POS_WEIGHTS = True  # Use inverse frequency for positive class weights
    LABEL_SMOOTHING = 0.0

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    EPOCHS = 20
    LR = 1e-4
    MIN_LR = 1e-6
    WEIGHT_DECAY = 1e-5

    # Stochastic Weight Averaging (SWA)
    USE_SWA = True
    SWA_START_EPOCH = 15
    SWA_LR = 1e-5

    # -------------------------------------------------------------------------
    # Augmentation
    # -------------------------------------------------------------------------
    # CoarseDropout parameters to force distributed feature learning
    USE_COARSE_DROPOUT = True
    COARSE_DROPOUT_PARAMS = {
        "max_holes": 8,
        "max_height": 100,
        "max_width": 100,
        "min_holes": 1,
        "min_height": 16,
        "min_width": 16,
        "fill_value": 0,
        "p": 0.5,
    }

    # Exclude CutMix as per strategy
    USE_CUTMIX = False
    USE_MIXUP = False

    # -------------------------------------------------------------------------
    # Inference & Post-Processing
    # -------------------------------------------------------------------------
    USE_TTA = True  # Test Time Augmentation (Horizontal Flip)
    USE_RANK_AVERAGING = True  # Rank-Calibrated Averaging

    # -------------------------------------------------------------------------
    # Utility Methods
    # -------------------------------------------------------------------------
    @classmethod
    def get_model_path(cls, model_name, fold):
        """Generates a standardized path for saving/loading model checkpoints."""
        # Sanitize model name for filename
        safe_name = model_name.replace(".", "_")
        filename = f"best_model_{safe_name}_fold_{fold}.pth"
        return os.path.join(cls.IDEA_DIR, filename)

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print("=" * 30)
        print("CONFIG")
        print("=" * 30)
        for k, v in cls.__dict__.items():
            if not k.startswith("__") and not callable(v):
                print(f"{k}: {v}")
        print("=" * 30)
