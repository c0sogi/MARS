import os
import torch


class Config:
    """
    Configuration class for Apple Disease Detection task.
    Centralizes file paths, hyperparameters, and device settings.
    """

    # ==========================================
    # Random Seed for Reproducibility
    # ==========================================
    SEED = 42

    # ==========================================
    # File Paths
    # ==========================================
    # Root directory for input data (read-only)
    INPUT_ROOT = "./input"

    # Directory containing images
    # Note: Metadata file_path column contains relative paths like 'images/Test_0.jpg'
    IMAGES_DIR = os.path.join(INPUT_ROOT, "images")

    # Metadata Directory (Generated by previous steps)
    METADATA_DIR = "./metadata"

    # Metadata File Paths
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Working Directory for intermediate files and model checkpoints
    WORKING_DIR = "./working"
    # Specific directory for this solution idea
    IDEA_DIR = os.path.join(WORKING_DIR, "idea_1")

    # Submission Directory and File
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Best Model Checkpoint Path
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # ==========================================
    # Data Configuration
    # ==========================================
    # Input image size (ResNet standard)
    IMG_SIZE = 224

    # Target Columns (Class Labels)
    # Matching the sample_submission.csv format and alphabetical order
    TARGET_COLS = ["healthy", "multiple_diseases", "rust", "scab"]
    NUM_CLASSES = len(TARGET_COLS)

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 32
    EPOCHS = 15
    LEARNING_RATE = 1e-4

    # Number of workers for data loading
    # 12 vCPUs available, 4 is a safe and efficient choice
    NUM_WORKERS = 4

    # ==========================================
    # Compute Device
    # ==========================================
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # ==========================================
    # Debugging / Development
    # ==========================================
    # Flag to enable debug mode (e.g., use subset of data)
    DEBUG = False
    DEBUG_SUBSET_SIZE = 100
