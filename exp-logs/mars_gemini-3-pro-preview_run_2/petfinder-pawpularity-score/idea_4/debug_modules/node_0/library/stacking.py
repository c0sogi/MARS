import os
import pandas as pd
import numpy as np
from sklearn.linear_model import Ridge
from library.config import Config
from library.utils import scale_target, unscale_target, get_rmse


class StackingTrainer:
    """
    Manages the Level 2 Meta-Learner (Ridge Regression) for the stacking ensemble.
    Aggregates predictions from diverse base learners (Swin, ConvNeXt, BEiT)
    to produce a final robust prediction.
    """

    def __init__(self):
        """
        Initialize the StackingTrainer with configuration and model.
        Instantiates Config to ensure output directories exist.
        """
        self.config = Config()
        self.model = Ridge(alpha=Config.meta_alpha, random_state=Config.seed)
        # Sort keys to ensure consistent column order between training and inference
        self.model_keys = sorted(list(Config.models.keys()))

    def load_oof_data(self, load_cached_data: bool = True):
        """
        Loads and prepares the Out-Of-Fold (OOF) predictions from base models.
        Implements caching to avoid re-processing on subsequent runs.

        Args:
            load_cached_data (bool): Whether to attempt loading from cache.

        Returns:
            tuple: (X, y) where X is the feature matrix (N_samples, N_models)
                   and y is the scaled target vector (N_samples,).
        """
        cache_path = os.path.join(
            self.config.output_dir, "stacked_oof_features.parquet"
        )

        # 1. Try to load from cache
        if load_cached_data and os.path.exists(cache_path):
            print(f"Loading cached OOF features from {cache_path}")
            df = pd.read_parquet(cache_path)
        else:
            # 2. Compute from scratch
            print("Constructing OOF features from base model outputs...")

            # Load Ground Truth Metadata
            if not os.path.exists(Config.train_metadata_path):
                raise FileNotFoundError(
                    f"Metadata not found at {Config.train_metadata_path}"
                )

            meta_df = pd.read_csv(Config.train_metadata_path)
            # Keep only Id and Target
            df = meta_df[["Id", Config.target_col]].copy()
            # Rename target to avoid collision and clarify it's the ground truth
            df = df.rename(columns={Config.target_col: "target_ground_truth"})

            # Merge OOF predictions for each base model
            for model_key in self.model_keys:
                oof_path = self.config.get_oof_path(model_key)

                if not os.path.exists(oof_path):
                    raise FileNotFoundError(
                        f"OOF file for '{model_key}' not found at {oof_path}"
                    )

                # Read OOF CSV (Expected format: Id, Pawpularity)
                oof_df = pd.read_csv(oof_path)

                # Rename prediction column to model key
                # We assume the prediction column is named Config.target_col ("Pawpularity")
                # as generated by the base trainer.
                if Config.target_col in oof_df.columns:
                    oof_df = oof_df.rename(columns={Config.target_col: model_key})
                else:
                    # Fallback: assume the second column is the prediction if names don't match
                    cols = oof_df.columns.tolist()
                    pred_col = [c for c in cols if c != "Id"][0]
                    oof_df = oof_df.rename(columns={pred_col: model_key})

                # Merge predictions into the main dataframe
                df = df.merge(oof_df[["Id", model_key]], on="Id", how="left")

            # Check for NaNs (e.g., if OOF predictions are incomplete)
            if df[self.model_keys].isnull().any().any():
                print(
                    "Warning: Missing OOF predictions for some samples. Filling with mean."
                )
                df[self.model_keys] = df[self.model_keys].fillna(
                    df[self.model_keys].mean()
                )

            # 3. Save to cache
            os.makedirs(self.config.output_dir, exist_ok=True)
            df.to_parquet(cache_path)
            print(f"OOF features cached to {cache_path}")

        # Prepare X (Features) and y (Target)
        # Base model predictions are already scaled [0, 1] (Sigmoid output from base models)
        X = df[self.model_keys].values

        # Target needs scaling to [0, 1] to match the regression range
        y_raw = df["target_ground_truth"].values
        y = scale_target(y_raw)

        return X, y

    def train(self, X, y):
        """
        Trains the Ridge Meta-Learner on the OOF data.

        Args:
            X (np.ndarray): Feature matrix (OOF predictions).
            y (np.ndarray): Scaled target vector.

        Returns:
            float: RMSE score on the training (OOF) set.
        """
        print(f"Training Meta-Learner (Ridge, alpha={Config.meta_alpha})...")

        self.model.fit(X, y)

        # Evaluate on OOF data (This represents the Ensemble's CV score)
        preds_scaled = self.model.predict(X)

        # Unscale for interpretable RMSE calculation [1, 100]
        y_true_orig = unscale_target(y)
        y_pred_orig = unscale_target(preds_scaled)

        rmse = get_rmse(y_true_orig, y_pred_orig)
        print(f"Meta-Learner OOF RMSE: {rmse}")

        # Print coefficients for inspection
        print("Meta-Learner Coefficients:")
        for key, coef in zip(self.model_keys, self.model.coef_):
            print(f"  {key}: {coef}")
        print(f"  Intercept: {self.model.intercept_}")

        return rmse

    def predict(self, test_preds_map):
        """
        Generates final predictions using the trained meta-learner.

        Args:
            test_preds_map (dict): Dictionary mapping model keys (e.g., 'swin')
                                   to numpy arrays of scaled predictions [0, 1].

        Returns:
            np.ndarray: Final unscaled predictions [1, 100].
        """
        # Construct X_test ensuring correct column order matches training
        X_test_list = []
        for key in self.model_keys:
            if key not in test_preds_map:
                raise ValueError(f"Missing test predictions for model '{key}'")

            preds = test_preds_map[key]
            # Ensure shape is flat
            preds = preds.ravel()
            X_test_list.append(preds)

        # Stack columns: Shape (N_samples, N_models)
        X_test = np.column_stack(X_test_list)

        # Predict (Output is scaled [0, 1])
        final_preds_scaled = self.model.predict(X_test)

        # Unscale to original range [1, 100]
        final_preds = unscale_target(final_preds_scaled)

        # Clip to valid range to handle any slight regression overshoot
        final_preds = np.clip(final_preds, 1.0, 100.0)

        return final_preds
