import os
import torch


class Config:
    """
    Configuration class for the Hindi/Tamil Question Answering task.
    Centralizes hyperparameters, paths, and model settings.
    """

    def __init__(self, **kwargs):
        """
        Initialize configuration with optional overrides.
        """
        for k, v in kwargs.items():
            if hasattr(self, k):
                setattr(self, k, v)

    # =========================================================================
    # General Settings & Reproducibility
    # =========================================================================
    seed = 42
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # Debugging: If True, runs on a small subset of data to verify pipeline
    debug = False
    debug_sample_size = 50

    # =========================================================================
    # Data Paths
    # =========================================================================
    # Metadata paths (generated by the provided script)
    train_meta_path = "./metadata/train.csv"
    val_meta_path = "./metadata/val.csv"
    test_meta_path = "./metadata/test.csv"
    sample_submission_path = "./input/sample_submission.csv"

    # Output Directory (for checkpoints, cache, and submission)
    output_dir = "./working/idea_2"
    os.makedirs(output_dir, exist_ok=True)

    # Path to store the best cross-validated score for regression gating
    score_tracking_path = os.path.join(output_dir, "best_cv_score.txt")

    # =========================================================================
    # Model Architecture
    # =========================================================================
    # MuRIL: Multilingual Representations for Indian Languages
    model_checkpoint = "google/muril-base-cased"

    # =========================================================================
    # Tokenizer & Sliding Window Strategy
    # =========================================================================
    # Handling long contexts by splitting into chunks with overlap
    max_length = 384  # Maximum sequence length (tokens)
    doc_stride = 128  # Overlap between consecutive chunks (tokens)

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    n_folds = 5  # Number of folds for Group K-Fold Cross-Validation
    epochs = 3  # Number of training epochs per fold

    # Batch sizes (tuned for A100 40GB)
    train_batch_size = 16
    eval_batch_size = 32

    # Optimizer settings
    learning_rate = 3e-5
    weight_decay = 0.01
    warmup_ratio = 0.1
    max_grad_norm = 1.0

    # =========================================================================
    # Inference & Post-processing
    # =========================================================================
    n_best_size = 20  # Number of best logits to consider for span selection
    max_answer_length = 30  # Maximum allowed length for a predicted answer

    # =========================================================================
    # Caching
    # =========================================================================
    # Locations to store processed features to speed up re-runs
    cached_train_features_path = os.path.join(
        output_dir, "cached_train_features.parquet"
    )
    cached_test_features_path = os.path.join(output_dir, "cached_test_features.parquet")
