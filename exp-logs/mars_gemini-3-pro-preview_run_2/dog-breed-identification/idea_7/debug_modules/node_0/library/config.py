import os
import torch


class Config:
    """
    Configuration class for the Dog Breed Prediction Task.
    Implements settings for the Multi-Scale Deep Feature Pyramid with Robust Local Aggregation.
    """

    # ==========================================
    # Global Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 100

    # ==========================================
    # Directory Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory for Idea 7 (Multi-Scale Deep Feature Pyramid)
    WORKING_DIR = "./working/idea_7"
    SUBMISSION_DIR = "./submission"

    # Ensure writable directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================================
    # File Paths
    # ==========================================
    # Metadata CSVs (Generated by metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Sample Submission (for header/format reference)
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Submission File
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Caching Paths (for Feature Extraction)
    # ==========================================
    # We cache numpy arrays to avoid re-running the heavy backbone
    CACHE_TRAIN_FEATURES = os.path.join(WORKING_DIR, "train_features.npy")
    CACHE_TRAIN_LABELS = os.path.join(WORKING_DIR, "train_labels.npy")

    CACHE_VAL_FEATURES = os.path.join(WORKING_DIR, "val_features.npy")
    CACHE_VAL_LABELS = os.path.join(WORKING_DIR, "val_labels.npy")

    CACHE_TEST_FEATURES = os.path.join(WORKING_DIR, "test_features.npy")
    CACHE_TEST_IDS = os.path.join(WORKING_DIR, "test_ids.npy")

    # Saved Model Path
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "logreg_model.joblib")

    # ==========================================
    # Model Architecture & Compute
    # ==========================================
    MODEL_NAME = "convnext_large"  # torchvision model name
    WEIGHTS = "IMAGENET1K_V1"  # specific weights version
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================
    # Data Processing / Multi-View Strategy
    # ==========================================
    INPUT_SIZE = 224
    BATCH_SIZE = 32
    NUM_WORKERS = 4

    # View 1: Global (Squish)
    # Resizes image directly to (224, 224) ignoring aspect ratio
    GLOBAL_VIEW_SIZE = (224, 224)

    # View 2: Standard (Context)
    # Resize to slightly larger, then Center Crop
    STANDARD_RESIZE = 232
    STANDARD_CROP = 224

    # View 3: Robust Local (Texture)
    # Resize to larger, then FiveCrop (Corners + Center)
    LOCAL_RESIZE = 288
    LOCAL_CROP = 224

    # ==========================================
    # Classifier Hyperparameters
    # ==========================================
    # Logistic Regression CV settings
    LOGREG_SOLVER = "lbfgs"
    LOGREG_MAX_ITER = 2000  # Increased for convergence on high-dim features
    CV_FOLDS = 5
    n_jobs = -1  # Use all cores for sklearn
