import os
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import log_loss

from library import config
from library import utils
from library import dataset


def train_classifier(
    train_embeddings_path=config.CNN_TRAIN_EMBEDDINGS.replace(
        "cnn_", ""
    ),  # Assuming generic naming or handled by caller
    train_labels_path=config.LABELS_TRAIN_PATH,
    val_embeddings_path=config.CNN_VAL_EMBEDDINGS.replace("cnn_", ""),
    val_labels_path=config.LABELS_VAL_PATH,
    C=config.LOGREG_C,
    max_iter=config.LOGREG_MAX_ITER,
    solver=config.LOGREG_SOLVER,
    seed=config.SEED,
):
    """
    Loads embeddings and labels, trains a Logistic Regression classifier,
    and evaluates it on the validation set.

    Note: The embedding paths in the default arguments are placeholders.
    The caller should provide the specific paths to the fused embeddings
    (e.g., generated by feature_engine.py).

    Args:
        train_embeddings_path (str): Path to training embeddings .npy file.
        train_labels_path (str): Path to training labels .npy file.
        val_embeddings_path (str): Path to validation embeddings .npy file.
        val_labels_path (str): Path to validation labels .npy file.
        C (float): Inverse of regularization strength.
        max_iter (int): Maximum number of iterations.
        solver (str): Algorithm to use in the optimization problem.
        seed (int): Random seed.

    Returns:
        sklearn.linear_model.LogisticRegression: The trained model.
    """
    print("Loading training and validation data for classifier training...")

    # Load data
    X_train = utils.load_array(train_embeddings_path)
    y_train = utils.load_array(train_labels_path)
    X_val = utils.load_array(val_embeddings_path)
    y_val = utils.load_array(val_labels_path)

    print(f"Training data shape: {X_train.shape}")
    print(f"Validation data shape: {X_val.shape}")

    # Initialize model
    # multi_class='multinomial' is standard for Log Loss optimization
    clf = LogisticRegression(
        C=C,
        max_iter=max_iter,
        solver=solver,
        multi_class="multinomial",
        random_state=seed,
        verbose=0,  # Keep silent as requested
        n_jobs=-1,  # Use all available cores
    )

    print(f"Training Logistic Regression (C={C}, solver={solver})...")
    clf.fit(X_train, y_train)

    # Validate
    print("Evaluating on validation set...")
    val_probs = clf.predict_proba(X_val)

    # Calculate Log Loss
    # labels in y_val are integers 0..119
    metric = log_loss(y_val, val_probs)

    print(f"Validation Multi Class Log Loss: {metric}")

    return clf


def predict_probabilities(model, test_embeddings_path):
    """
    Loads test embeddings and predicts probabilities using the trained model.

    Args:
        model: Trained LogisticRegression model.
        test_embeddings_path (str): Path to test embeddings .npy file.

    Returns:
        np.ndarray: Probability matrix of shape (n_samples, n_classes).
    """
    print(f"Loading test embeddings from {test_embeddings_path}...")
    X_test = utils.load_array(test_embeddings_path)

    print("Predicting probabilities on test set...")
    probs = model.predict_proba(X_test)

    return probs


def generate_submission(
    test_ids_path,
    probabilities,
    output_path,
    train_metadata_path=config.TRAIN_METADATA_PATH,
):
    """
    Generates the submission CSV file.

    Args:
        test_ids_path (str): Path to test IDs .npy file.
        probabilities (np.ndarray): Predicted probabilities.
        output_path (str): Path to save the submission CSV.
        train_metadata_path (str): Path to training metadata to retrieve class names.
    """
    print("Generating submission file...")

    # Load Test IDs
    test_ids = utils.load_array(test_ids_path)

    # Get Class Names (Breeds)
    # We use the training metadata to ensure we have the correct mapping
    # The dataset class sorts breeds alphabetically to assign indices.
    # LogisticRegression also sorts classes by value (indices 0..N).
    # Therefore, model.classes_[i] corresponds to idx_to_class[i].
    _, idx_to_class = dataset.get_class_mappings(train_metadata_path)

    # Verify consistency
    num_classes = len(idx_to_class)
    if probabilities.shape[1] != num_classes:
        raise ValueError(
            f"Number of predicted classes ({probabilities.shape[1]}) "
            f"does not match number of breeds in metadata ({num_classes})."
        )

    # Create list of column names: ['id', 'breed1', 'breed2', ...]
    # Ensure the order of breed columns matches the model's output indices
    breed_columns = [idx_to_class[i] for i in range(num_classes)]

    # Create DataFrame
    df = pd.DataFrame(probabilities, columns=breed_columns)

    # Insert ID column at the beginning
    df.insert(0, "id", test_ids)

    # Save to CSV
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    df.to_csv(output_path, index=False)

    print(f"Submission saved to {output_path}")
