import os
import numpy as np
import library.config as config


def load_and_fuse_features(
    embedding_dir: str, cache_name: str, load_cached_data: bool = True
):
    """
    Loads raw embeddings (Global, Standard, Local) from the specified directory,
    performs Intra-Stream Early Fusion (concatenation), and returns the fused
    features and labels. Implements caching of the fused result to the working directory.

    Args:
        embedding_dir (str): Directory containing the raw 'embeddings_*.npy' files
                             generated by extraction.py.
        cache_name (str): Unique identifier for this dataset split (e.g., 'stream_a_train')
                          used to name the cached fused files.
        load_cached_data (bool): Whether to attempt loading fused data from cache.

    Returns:
        tuple: (X, y, ids)
            - X (np.ndarray): Fused feature matrix of shape (N, D_global + D_standard + D_local).
            - y (np.ndarray): Labels array of shape (N,).
            - ids (np.ndarray): IDs array of shape (N,).
    """
    # Define paths for cached fused data
    # Fused data is stored in the main working directory defined in config
    fused_dir = config.WORKING_DIR
    os.makedirs(fused_dir, exist_ok=True)

    fused_X_path = os.path.join(fused_dir, f"{cache_name}_fused_X.npy")
    fused_y_path = os.path.join(fused_dir, f"{cache_name}_fused_y.npy")
    fused_ids_path = os.path.join(fused_dir, f"{cache_name}_fused_ids.npy")

    # 1. Try to load from cache
    if load_cached_data:
        if (
            os.path.exists(fused_X_path)
            and os.path.exists(fused_y_path)
            and os.path.exists(fused_ids_path)
        ):
            # print(f"Loading fused features from cache: {fused_X_path}")
            X = np.load(fused_X_path)
            y = np.load(fused_y_path)
            ids = np.load(fused_ids_path, allow_pickle=True)
            return X, y, ids

    # 2. Load raw embeddings from embedding_dir
    # Files expected: embeddings_global.npy, embeddings_standard.npy, embeddings_local.npy, ids.npy, labels.npy
    path_global = os.path.join(embedding_dir, "embeddings_global.npy")
    path_standard = os.path.join(embedding_dir, "embeddings_standard.npy")
    path_local = os.path.join(embedding_dir, "embeddings_local.npy")
    path_ids = os.path.join(embedding_dir, "ids.npy")
    path_labels = os.path.join(embedding_dir, "labels.npy")

    # Verify existence of all required files
    required_files = [path_global, path_standard, path_local, path_ids, path_labels]
    for p in required_files:
        if not os.path.exists(p):
            raise FileNotFoundError(
                f"Required raw embedding file not found at {p}. "
                "Ensure extraction.py has been run for this stream/split."
            )

    # Load raw data
    # print(f"Loading raw embeddings from {embedding_dir}...")
    emb_global = np.load(path_global)
    emb_standard = np.load(path_standard)
    emb_local = np.load(path_local)
    ids = np.load(path_ids, allow_pickle=True)
    y = np.load(path_labels)

    # 3. Perform Intra-Stream Early Fusion
    # Concatenate along the feature dimension (axis 1) to create a unified representation
    # Check for dimension consistency
    if not (
        emb_global.shape[0]
        == emb_standard.shape[0]
        == emb_local.shape[0]
        == ids.shape[0]
    ):
        raise ValueError(
            f"Mismatch in number of samples across views: "
            f"Global({emb_global.shape[0]}), Standard({emb_standard.shape[0]}), Local({emb_local.shape[0]})"
        )

    # Concatenate: [Global features | Standard features | Local features]
    X = np.concatenate([emb_global, emb_standard, emb_local], axis=1)

    # 4. Save fused data to cache
    # print(f"Saving fused features to {fused_dir}...")
    np.save(fused_X_path, X)
    np.save(fused_y_path, y)
    np.save(fused_ids_path, ids)

    return X, y, ids
