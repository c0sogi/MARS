import os
import torch

# Ensure necessary directories exist upon import
_WORKING_DIR = "./working/idea_44"
_SUBMISSION_DIR = "./submission"
os.makedirs(_WORKING_DIR, exist_ok=True)
os.makedirs(_SUBMISSION_DIR, exist_ok=True)


class Config:
    """
    Configuration for the Decoupled Dense-Feedback Recurrent Network (DDF-RN).
    """

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = _WORKING_DIR
    SUBMISSION_DIR = _SUBMISSION_DIR

    # Metadata Files (Generated by previous steps)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Cache Files (Specific versioning for DDF-RN)
    TRAIN_CACHE = os.path.join(WORKING_DIR, "train_data_ddf_rn_v1.npz")
    VAL_CACHE = os.path.join(WORKING_DIR, "val_data_ddf_rn_v1.npz")
    TEST_CACHE = os.path.join(WORKING_DIR, "test_data_ddf_rn_v1.npz")

    # Model Checkpoint and Output
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # --------------------------------------------------------------------------
    # Data Specifications
    # --------------------------------------------------------------------------
    SEQ_LEN = 107
    SEQ_SCORED = 68

    # Columns
    # The submission requires these 5 columns
    TARGET_COLS = ["reactivity", "deg_Mg_pH10", "deg_pH10", "deg_Mg_50C", "deg_50C"]

    # The metric is calculated only on these 3 columns
    SCORED_COLS = ["reactivity", "deg_Mg_pH10", "deg_Mg_50C"]

    # Indices of scored columns within TARGET_COLS (for loss masking)
    SCORED_INDICES = [i for i, col in enumerate(TARGET_COLS) if col in SCORED_COLS]

    # --------------------------------------------------------------------------
    # Model Hyperparameters: DDF-RN
    # --------------------------------------------------------------------------
    # Input Representation
    USE_PARTNER_IDENTITY = True  # Explicit injection of partner base identity

    # Main Backbone: Static Dense Dilated TCN
    # "Decoupled Block Structure" with "Dense Connections"
    BACKBONE_GROWTH_RATE = 64
    BACKBONE_KERNEL_SIZE = 3
    BACKBONE_DILATIONS = [1, 2, 4, 8, 16, 32]
    BACKBONE_DROPOUT = 0.1
    LATENT_DIM = 64  # Z dimension

    # Feedback Module: Decoupled Dense Feedback
    # "Lightweight Dense TCN"
    FEEDBACK_GROWTH_RATE = 12  # Low growth rate to limit capacity
    FEEDBACK_KERNEL_SIZE = 3
    FEEDBACK_DILATIONS = [1, 2, 4, 8]  # Slightly shallower/lighter than backbone
    FEEDBACK_EMBED_DIM = 32  # E_fb dimension

    # Aggregation & Head
    RNN_HIDDEN_DIM = 128
    RNN_LAYERS = 1
    RNN_BIDIRECTIONAL = True

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Optimization
    BATCH_SIZE = 32
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    EPOCHS = 50
    PATIENCE = 7  # Early stopping patience

    # Loss Configuration
    # L_total = MCRMSE(Y2) + AUX_WEIGHT * MCRMSE(Y1)
    AUX_LOSS_WEIGHT = 0.5

    # --------------------------------------------------------------------------
    # Runtime / Debugging
    # --------------------------------------------------------------------------
    NUM_WORKERS = 2
    DEBUG = False  # Set to True to train on a small subset
    DEBUG_SUBSET_SIZE = 100
