import os
import torch


class Config:
    def __init__(self, debug=False, output_dir=None):
        """
        Configuration for TAF-RDN (Topology-Aware Feedback Recurrent Network).

        Args:
            debug (bool): If True, sets parameters for a quick debug run (fewer epochs, smaller dataset).
            output_dir (str): Path to the working directory. Defaults to './working/idea_40'.
        """
        self.debug = debug
        self.seed = 42

        # =============================================================================
        # Paths
        # =============================================================================
        self.input_dir = "./input"
        self.metadata_dir = "./metadata"
        self.working_dir = output_dir if output_dir else "./working/idea_40"

        # Ensure working directory exists
        os.makedirs(self.working_dir, exist_ok=True)

        # Metadata Files (Generated by previous steps)
        self.train_csv = os.path.join(self.metadata_dir, "train.csv")
        self.val_csv = os.path.join(self.metadata_dir, "val.csv")
        self.test_csv = os.path.join(self.metadata_dir, "test.csv")
        self.sample_submission = os.path.join(self.input_dir, "sample_submission.csv")

        # Cache Files (For processed tensors)
        # Using a versioned name to ensure cache invalidation if logic changes
        self.train_cache = os.path.join(self.working_dir, "train_data_taf_rdn_v1.npz")
        self.val_cache = os.path.join(self.working_dir, "val_data_taf_rdn_v1.npz")
        self.test_cache = os.path.join(self.working_dir, "test_data_taf_rdn_v1.npz")

        # Model Checkpoint & Output
        self.best_model_path = os.path.join(self.working_dir, "best_model.pth")
        self.submission_path = os.path.join(self.working_dir, "submission.csv")

        # =============================================================================
        # Data Specifications
        # =============================================================================
        self.seq_len = 107
        self.pred_len = 68

        # Vocabularies
        # Sequence: A, G, U, C
        self.vocab_seq = 4
        # Structure: (, ), .
        self.vocab_struct = 3
        # Loop Type: S, M, I, B, H, E, X
        self.vocab_loop = 7

        # Targets
        self.target_cols = [
            "reactivity",
            "deg_Mg_pH10",
            "deg_pH10",
            "deg_Mg_50C",
            "deg_50C",
        ]
        # Only these columns are scored in the competition metric
        self.scored_cols = ["reactivity", "deg_Mg_pH10", "deg_Mg_50C"]
        self.num_targets = len(self.target_cols)

        # =============================================================================
        # Model Architecture
        # =============================================================================
        # Static Backbone (Dense Dilated TCN)
        # Processes the static sequence/structure features once per batch
        self.backbone_channels = 64
        self.backbone_kernel_size = 3
        self.backbone_dilations = [1, 2, 4, 8, 16, 32]

        # Feedback Module (Lightweight Dilated TCN)
        # Processes recycled predictions + raw topology features
        self.feedback_channels = 32
        self.feedback_kernel_size = 3
        self.feedback_dilations = [1, 2, 4]

        # Interaction & Aggregation
        self.latent_dim = (
            64  # Projection dimension for static features before interaction
        )
        self.rnn_hidden_dim = 128
        self.rnn_layers = 1
        self.dropout = 0.1

        # =============================================================================
        # Training Hyperparameters
        # =============================================================================
        self.batch_size = 32
        self.epochs = 25
        self.lr = 1e-3
        self.weight_decay = 1e-4
        self.patience = 5  # Early stopping patience
        self.grad_clip = 1.0

        # Recycling Strategy
        # Steps: 0 (Initial) -> 1 (Pass 1) -> 2 (Pass 2)
        # We perform 2 passes through the RNN, using feedback from the previous pass.
        self.recycling_steps = 2

        # Loss Weights
        self.aux_loss_weight = 0.5  # Weight for the intermediate pass loss (Pass 1)

        # Hardware
        self.device = "cuda" if torch.cuda.is_available() else "cpu"
        self.num_workers = 2

        # =============================================================================
        # Debug Overrides
        # =============================================================================
        if self.debug:
            self.epochs = 2
            self.batch_size = 4
            self.subset_size = 50  # Limit dataset size for quick testing
            self.num_workers = 0  # Avoid multiprocessing overhead in debug
        else:
            self.subset_size = None
