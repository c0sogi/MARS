import os
import torch


class Config:
    """
    Configuration for the Robust Hybrid-Input Dense-Feedback Network (RHI-DFN).
    Defines paths, data specifications, and hyperparameters for the model and training loop.
    """

    # =========================================================================
    # Paths & Directories
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"
    CACHE_DIR = "./working/idea_70"
    SUBMISSION_DIR = "./submission"

    # Ensure working and cache directories exist
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata File Paths (Generated by metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Cache File Paths (Explicit versioning for cache safety)
    CACHE_TRAIN_DATA = os.path.join(CACHE_DIR, "train_data_rhi_dfn_v1.npz")
    CACHE_VAL_DATA = os.path.join(CACHE_DIR, "val_data_rhi_dfn_v1.npz")
    CACHE_TEST_DATA = os.path.join(CACHE_DIR, "test_data_rhi_dfn_v1.npz")

    # =========================================================================
    # Data Specifications
    # =========================================================================
    SEQ_LENGTH = 107
    SEQ_SCORED = 68

    # Target Definitions
    # Full list of targets present in training data
    TARGET_COLS = ["reactivity", "deg_Mg_pH10", "deg_pH10", "deg_Mg_50C", "deg_50C"]

    # Subset of targets used for scoring and loss calculation
    SCORED_COLS = ["reactivity", "deg_Mg_pH10", "deg_Mg_50C"]

    # Indices of the scored columns within the full target vector (Indices: 0, 1, 3)
    SCORED_INDICES = [i for i, col in enumerate(TARGET_COLS) if col in SCORED_COLS]

    NUM_TARGETS = 5

    # =========================================================================
    # Model Hyperparameters (RHI-DFN)
    # =========================================================================
    # Backbone Configuration
    GROWTH_RATE = 64
    LATENT_DIM = 64
    DROPOUT = 0.1
    KERNEL_SIZE = 3
    DILATIONS = [1, 2, 4, 8, 16, 32]

    # RNN / Aggregation Configuration
    RNN_HIDDEN_SIZE = 64

    # Feedback Mechanism Configuration
    FEEDBACK_DIM = 32  # Dimension of feedback embeddings

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 16  # Strictly set to 16 (Small Batch Regime)
    LEARNING_RATE = 1e-3  # AdamW default
    NUM_EPOCHS = 50  # Sufficient for convergence with early stopping
    EARLY_STOPPING_PATIENCE = 10
    NUM_WORKERS = 4  # Number of DataLoader workers
    SEED = 42

    # Loss Weights for Iterative Refinement
    # Total Loss = MCRMSE(Pass2) + 0.5 * MCRMSE(Pass1)
    LOSS_WEIGHT_PASS_1 = 0.5
    LOSS_WEIGHT_PASS_2 = 1.0

    # =========================================================================
    # System & Debugging
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    DEBUG = False  # Set to True to use a small subset of data for debugging
