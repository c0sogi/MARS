import os
import torch
import numpy as np
import random


class Config:
    """
    Configuration for the Raw-Physics ConvNeXt U-Net with Focal-Batch Optimization.
    Defines all hyperparameters, file paths, and normalization constants.
    """

    # =========================================================================
    # Directories and Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for checkpoints, logs, and cached data
    WORKING_DIR = "./working/idea_25"

    # Metadata Files (Generated by the provided metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VALIDATION_METADATA_PATH = os.path.join(METADATA_DIR, "validation_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Submission
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Parameters
    # =========================================================================
    IMG_SIZE = 256

    # Temporal Context
    # The dataset provides a sequence of images. We focus on the labeled frame (T=4).
    N_TIMES_BEFORE = 4
    N_TIMES_AFTER = 3

    # Selected Bands for Raw-Physics Input
    # We use Bands 11, 14, 15 (Infrared) as they are critical for contrail detection.
    BANDS = [11, 14, 15]

    # Normalization Constants (Min, Max) for Min-Max Scaling to [0, 1]
    # Values are derived from EDA (Brightness Temperatures in Kelvin).
    # We use slightly wider bounds than the strict min/max to handle outliers.
    BAND_STATS = {
        11: {"min": 180.0, "max": 325.0},
        14: {"min": 180.0, "max": 330.0},
        15: {"min": 180.0, "max": 325.0},
    }

    # Normalization for Temporal Difference Channels (T_current - T_prev)
    # These channels capture the motion/evolution of contrails.
    # We assume a dynamic range of +/- 50K which covers rapid atmospheric changes.
    DIFF_STATS = {
        11: {"min": -50.0, "max": 50.0},
        14: {"min": -50.0, "max": 50.0},
        15: {"min": -50.0, "max": 50.0},
    }

    # =========================================================================
    # Model Parameters
    # =========================================================================
    MODEL_NAME = "RawPhysics_ConvNeXt_UNet"
    BACKBONE = "convnext_tiny"
    PRETRAINED = True

    # Input Channels:
    # 3 channels (Raw Bands at T=4) + 3 channels (Differences T=4 minus T=3)
    IN_CHANNELS = 6
    NUM_CLASSES = 1

    # =========================================================================
    # Training Parameters
    # =========================================================================
    SEED = 42

    # Optimization
    BATCH_SIZE = 32
    EPOCHS = 30
    LEARNING_RATE = 2e-4
    WEIGHT_DECAY = 1e-5

    # Loss Function (Focal + Batch Dice)
    FOCAL_GAMMA = 2.0

    # Scheduler (Cosine Annealing)
    T_MAX = 30  # Matches EPOCHS
    ETA_MIN = 1e-6

    # Compute
    NUM_WORKERS = 4  # Optimized for 12 vCPUs
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Debugging / Development
    # Set to an integer (e.g., 1000) to train on a subset, or None for full dataset
    DEBUG_SAMPLE_SIZE = None

    # =========================================================================
    # Inference Parameters
    # =========================================================================
    THRESHOLD = 0.5
    USE_TTA = True  # Enable Test-Time Augmentation (flips/rotations)

    @classmethod
    def setup(cls):
        """
        Initializes the environment: creates directories and sets random seeds.
        """
        # Create directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set Reproducibility
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

        print(f"Config Setup Complete. Output Dir: {cls.WORKING_DIR}")
        print(f"Device: {cls.DEVICE}")
