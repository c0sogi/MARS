import os
import torch


class Config:
    """
    Configuration class for the Contrail Identification Task.
    Implements the settings for the Macro-Context ConvNeXt U-Net with Deep Supervision.
    """

    def __init__(self, debug: bool = False, epochs: int = 30, batch_size: int = 32):
        """
        Initialize configuration with flexibility for debugging and resource management.

        Args:
            debug (bool): If True, runs in debug mode with a small dataset subset and fewer epochs.
            epochs (int): Number of training epochs (default 30).
            batch_size (int): Batch size for training (default 32).
        """
        # ==========================================
        # General Settings
        # ==========================================
        self.seed = 42
        self.project_name = "contrails-segmentation"
        self.idea_name = "idea_13"

        # Directory structure
        self.working_dir = "./working"
        self.output_dir = os.path.join(self.working_dir, self.idea_name)
        self.submission_dir = "./submission"
        self.submission_path = os.path.join(self.submission_dir, "submission.csv")

        # Create necessary directories
        os.makedirs(self.output_dir, exist_ok=True)
        os.makedirs(self.submission_dir, exist_ok=True)

        # Compute resources
        self.num_workers = 12
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

        # ==========================================
        # Data Paths & Parameters
        # ==========================================
        self.input_dir = "./input"
        self.metadata_dir = "./metadata"

        # Metadata files generated by the provided script
        self.train_metadata_path = os.path.join(self.metadata_dir, "train_metadata.csv")
        self.valid_metadata_path = os.path.join(
            self.metadata_dir, "validation_metadata.csv"
        )
        self.test_metadata_path = os.path.join(self.metadata_dir, "test_metadata.csv")

        # Input Engineering
        self.image_size = 256
        # 6 Channels: 3 for Ash Color Scheme + 3 for Temporal Difference (T4 - T3)
        self.input_channels = 6
        self.n_times_before = 4  # Frame index 4 is the labeled frame

        # Debugging / Sampling Control
        self.debug = debug
        if self.debug:
            self.train_sample_size = 500
            self.valid_sample_size = 100
            self.epochs = 2
        else:
            self.train_sample_size = None  # None implies full dataset
            self.valid_sample_size = None
            self.epochs = epochs

        # ==========================================
        # Model Architecture
        # ==========================================
        self.backbone = "convnext_tiny"
        self.pretrained = True
        # Deep Supervision: Auxiliary heads at Stride 4 and Stride 8
        self.deep_supervision = True

        # ==========================================
        # Training Hyperparameters
        # ==========================================
        self.batch_size = batch_size

        # Optimization
        self.learning_rate = 1e-4  # Standard start for ConvNeXt
        self.weight_decay = 1e-2
        self.min_lr = 1e-6

        # Loss Function: Hybrid Loss (BCE + BatchDice)
        # Weights correspond to: [Main Output, Aux Head 1, Aux Head 2]
        self.loss_weights = [1.0, 0.4, 0.2]

        # ==========================================
        # Inference & Post-Processing
        # ==========================================
        self.threshold = 0.5
        self.use_tta = True  # Enable Test-Time Augmentation (Flip/Rotate)

    def get_model_save_path(self, filename="best_model.pth"):
        """Returns the full path to save the model weights."""
        return os.path.join(self.output_dir, filename)

    def __repr__(self):
        """Helper to print config state."""
        return (
            f"Config(debug={self.debug}, epochs={self.epochs}, "
            f"batch_size={self.batch_size}, device={self.device}, "
            f"output_dir={self.output_dir})"
        )
