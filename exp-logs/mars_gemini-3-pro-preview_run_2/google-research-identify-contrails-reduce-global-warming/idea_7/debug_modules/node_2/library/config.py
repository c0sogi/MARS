import os
import torch


class Config:
    """
    Centralized configuration for the Deformable ResNet18 U-Net Contrail Detection experiment.
    """

    # ==========================================
    # General & Reproducibility
    # ==========================================
    SEED = 42
    EXPERIMENT_NAME = "idea_7"
    DEBUG = False  # Set to True to run in debug mode (fewer samples, fewer epochs)

    # ==========================================
    # File Systems & Paths
    # ==========================================
    # Input Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata Files (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VALIDATION_METADATA_PATH = os.path.join(METADATA_DIR, "validation_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Directories
    WORKING_DIR = os.path.join("./working", EXPERIMENT_NAME)
    SUBMISSION_DIR = "./submission"

    # Specific Output Files
    BEST_MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure working directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================================
    # Data Configuration
    # ==========================================
    IMG_SIZE = 256
    N_CHANNELS = 6  # 3 channels for Ash Color + 3 channels for Temporal Difference

    # Debugging constraints
    # If DEBUG is True, the data loader will restrict itself to this many samples
    DEBUG_SAMPLE_SIZE = 500

    # ==========================================
    # Model Architecture
    # ==========================================
    ENCODER_NAME = "resnet18"
    ENCODER_WEIGHTS = "imagenet"
    USE_DEFORMABLE_CONV = True  # Key innovation for Idea 7

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 32
    EPOCHS = 30

    # Optimizer (AdamW)
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2

    # Scheduler (CosineAnnealingLR)
    T_MAX = EPOCHS  # For Cosine Annealing
    ETA_MIN = 1e-6

    # Loss Weights
    BCE_WEIGHT = 0.5
    DICE_WEIGHT = 0.5

    # Thresholding
    THRESHOLD = 0.5

    # ==========================================
    # Compute
    # ==========================================
    NUM_WORKERS = 4  # 12 vCPUs available, 4 is a safe number for dataloading
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def get_summary(cls):
        """Returns a dictionary of key configuration parameters for logging."""
        return {
            "Experiment": cls.EXPERIMENT_NAME,
            "Image Size": cls.IMG_SIZE,
            "Channels": cls.N_CHANNELS,
            "Batch Size": cls.BATCH_SIZE,
            "Epochs": cls.EPOCHS,
            "Learning Rate": cls.LEARNING_RATE,
            "Device": cls.DEVICE,
            "Deformable Conv": cls.USE_DEFORMABLE_CONV,
        }
