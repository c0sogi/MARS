import os
import torch


class Config:
    """
    Configuration class for the Hybrid ResNet18-Transformer U-Net Contrail Detection task.
    Centralizes all hyperparameters, file paths, and system settings.
    """

    # ==========================================
    # System & Reproducibility
    # ==========================================
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    # 12 vCPUs available, 8 is a safe balance for data loading
    NUM_WORKERS = 8

    # ==========================================
    # File Paths & Directories
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata CSVs (Generated by previous metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "validation_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Directories
    # Using 'idea_9' as the working directory for this iteration
    WORKING_DIR = "./working/idea_9"
    SUBMISSION_DIR = "./submission"

    # Specific Output Files
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Data Configuration
    # ==========================================
    IMAGE_SIZE = 256
    # Input: 3 channels (Ash Composite) + 3 channels (Temporal Difference) = 6
    INPUT_CHANNELS = 6

    # ==========================================
    # Model Architecture (Hybrid U-Net)
    # ==========================================
    ENCODER_NAME = "resnet18"
    ENCODER_WEIGHTS = "imagenet"

    # Transformer Bottleneck Configuration
    # ResNet18's final feature map (layer4) has 512 channels
    TRANSFORMER_EMBED_DIM = 512
    TRANSFORMER_NUM_HEADS = 8
    TRANSFORMER_NUM_LAYERS = 1
    TRANSFORMER_DROPOUT = 0.1

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 32
    EPOCHS = 30
    LEARNING_RATE = 2e-4
    WEIGHT_DECAY = 1e-2

    # Scheduler: Cosine Annealing
    T_MAX = 30
    ETA_MIN = 1e-6

    # Loss Function: Hybrid (BCE + Batch-Level Dice)
    BCE_WEIGHT = 0.5
    DICE_WEIGHT = 0.5

    # ==========================================
    # Inference & Post-Processing
    # ==========================================
    THRESHOLD = 0.5
    MIN_CONTRAIL_PIXELS = 10  # Minimum size to be considered a valid object

    # Test-Time Augmentation (TTA)
    # We use Horizontal Flip, Vertical Flip, and Rotation
    TTA_ENABLED = True

    # ==========================================
    # Debugging & Constraints
    # ==========================================
    # Set to an integer (e.g., 1000) to restrict dataset size for rapid debugging/testing
    # Set to None to use the full dataset
    MAX_TRAIN_SAMPLES = None
    MAX_VAL_SAMPLES = None

    @classmethod
    def setup(cls):
        """
        Ensures that necessary working directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories immediately upon import
Config.setup()
