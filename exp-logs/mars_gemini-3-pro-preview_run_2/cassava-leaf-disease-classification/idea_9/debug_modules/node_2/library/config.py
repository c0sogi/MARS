import os
import torch


class CFG:
    """
    Configuration class for Cassava Leaf Disease Classification.
    Implements parameters for Progressive Resolution Training with ConvNeXt Small.
    """

    # ====================================================
    # General Setup
    # ====================================================
    seed = 42
    debug = False  # Set to True for fast debugging (reduces epochs and data)
    num_workers = 12
    device = "cuda" if torch.cuda.is_available() else "cpu"

    # ====================================================
    # Directories & Paths
    # ====================================================
    input_dir = "./input"
    metadata_dir = "./metadata"
    working_dir = "./working/idea_9"
    submission_dir = "./submission"

    # Metadata files (generated by previous steps)
    train_metadata_path = os.path.join(metadata_dir, "train.csv")
    val_metadata_path = os.path.join(metadata_dir, "val.csv")
    test_metadata_path = os.path.join(metadata_dir, "test.csv")

    # Model outputs
    output_dir = working_dir

    # ====================================================
    # Model Architecture
    # ====================================================
    # Using ConvNeXt Small pre-trained on ImageNet-22k and fine-tuned on 1k
    model_name = "convnext_small.fb_in22k_ft_in1k"
    num_classes = 5
    pretrained = True

    # Model EMA (Exponential Moving Average)
    # Stabilizes training during resolution transitions
    use_ema = True
    model_ema_decay = 0.9999

    # Regularization
    drop_path_rate = 0.4  # Stochastic Depth rate

    # ====================================================
    # Training Strategy: Progressive Resolution
    # ====================================================
    num_folds = 5

    # Phase 1: Coarse Learning (Global Features)
    # Lower resolution, high augmentation noise
    epochs_coarse = 12 if not debug else 1
    img_size_coarse = 224
    mixup_prob_coarse = 0.5
    cutmix_prob_coarse = 0.5

    # Phase 2: Fine Tuning (Local Details)
    # Higher resolution, no mixing to resolve fine artifacts
    epochs_fine = 8 if not debug else 1
    img_size_fine = 384
    mixup_prob_fine = 0.0
    cutmix_prob_fine = 0.0

    # Total epochs per fold
    epochs = epochs_coarse + epochs_fine

    # ====================================================
    # Optimization
    # ====================================================
    batch_size = 32
    lr = 2e-4
    min_lr = 1e-6
    weight_decay = 0.05
    label_smoothing = 0.1

    # Gradient Accumulation (safeguard for 384px on GPU)
    grad_accum_steps = 1

    # ====================================================
    # Inference
    # ====================================================
    tta_steps = 2  # Original + Horizontal Flip

    # ====================================================
    # Debugging
    # ====================================================
    debug_sample_size = 100  # Subset size if debug=True

    @staticmethod
    def setup():
        """Ensure working directories exist."""
        os.makedirs(CFG.output_dir, exist_ok=True)
        os.makedirs(CFG.submission_dir, exist_ok=True)


# Initialize environment directories upon import
CFG.setup()
