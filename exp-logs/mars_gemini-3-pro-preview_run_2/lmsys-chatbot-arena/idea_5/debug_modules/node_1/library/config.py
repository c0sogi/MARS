import os
import torch
import random
import numpy as np


class Config:
    """
    Centralized configuration for the Siamese DeBERTa-v3-Base model pipeline.
    Handles hyperparameters, file paths, and reproducibility settings.
    """

    # ==========================
    # General Settings
    # ==========================
    SEED = 42
    DEBUG = False  # Set to True to run on a subset of data for debugging
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================
    # Data Paths
    # ==========================
    # Input metadata paths (generated by the metadata script)
    METADATA_DIR = "./metadata"
    TRAIN_DATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_DATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_DATA_PATH = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = "./input/sample_submission.csv"

    # Working directory for artifacts
    WORKING_DIR = "./working/idea_5"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    MODEL_OUTPUT_DIR = os.path.join(WORKING_DIR, "models")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================
    # Model Hyperparameters
    # ==========================
    MODEL_NAME = "microsoft/deberta-v3-base"
    MAX_LENGTH = 512

    # Training
    N_FOLDS = 4
    EPOCHS = 3
    TRAIN_BATCH_SIZE = 8
    VALID_BATCH_SIZE = 16
    GRADIENT_ACCUMULATION_STEPS = 1

    # Optimization
    LEARNING_RATE = 2e-5
    WEIGHT_DECAY = 0.01
    MAX_GRAD_NORM = 10.0
    WARMUP_RATIO = 0.1

    # Layer-wise Learning Rate Decay (LLRD)
    LLRD_DECAY = 0.9

    # Head specific
    DROP_RATE = 0.1
    NUM_DROPOUT_SAMPLES = 5  # For Multi-Sample Dropout

    # Target Columns
    TARGET_COLS = ["winner_model_a", "winner_model_b", "winner_tie"]

    def __init__(self):
        """
        Initialize configuration and ensure necessary directories exist.
        """
        self.create_dirs()
        self.seed_everything()

    def create_dirs(self):
        """
        Create working directories for cache, models, and submissions.
        """
        os.makedirs(self.WORKING_DIR, exist_ok=True)
        os.makedirs(self.CACHE_DIR, exist_ok=True)
        os.makedirs(self.MODEL_OUTPUT_DIR, exist_ok=True)
        os.makedirs(self.SUBMISSION_DIR, exist_ok=True)

    @classmethod
    def seed_everything(cls, seed=None):
        """
        Set random seeds for reproducibility across python, numpy, and torch.
        """
        if seed is None:
            seed = cls.SEED

        random.seed(seed)
        os.environ["PYTHONHASHSEED"] = str(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        torch.cuda.manual_seed(seed)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False
