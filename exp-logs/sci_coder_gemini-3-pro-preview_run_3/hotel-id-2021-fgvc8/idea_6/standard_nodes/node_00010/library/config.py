import os
import torch


class Config:
    # --------------------------------------------------------------------------
    # General Settings
    # --------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data
    DEBUG_SAMPLE_SIZE = 1000  # Number of samples to use in debug mode
    NUM_WORKERS = 4  # Number of data loading workers

    # --------------------------------------------------------------------------
    # Directories & Paths
    # --------------------------------------------------------------------------
    # Input Data
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Image Roots (Metadata file_path columns are relative to INPUT_DIR)
    IMG_ROOT_DIR = INPUT_DIR

    # Working Directory for this specific idea/experiment
    WORKING_DIR = "./working/idea_6"

    # Output Paths
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    LOG_PATH = os.path.join(WORKING_DIR, "training_log.csv")

    # Submission
    SUBMISSION_DIR = "./submission"
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Model Architecture
    # --------------------------------------------------------------------------
    BACKBONE = "convnext_tiny"
    PRETRAINED = True
    IMG_SIZE = 384  # High resolution for fine-grained details

    # Embedding & Head
    EMBEDDING_SIZE = 512
    NUM_CLASSES = 7770  # Based on dataset analysis

    # ArcFace Hyperparameters
    MARGIN = 0.50
    SCALE = 30.0

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    # Optimization
    EPOCHS = 12  # Sufficient for convergence with pre-trained backbone
    BATCH_SIZE = 32  # Adjusted for 384x384 resolution on A100

    # Learning Rate Strategy (Stability Focused)
    LR = 5e-4  # Reduced peak LR to prevent divergence
    MIN_LR = 1e-6
    WARMUP_EPOCHS = 1  # Linear warmup to stabilize early gradients
    WEIGHT_DECAY = 1e-2

    # Regularization & Stability
    CLIP_GRAD_NORM = 1.0  # Gradient clipping to handle numerical instability
    LABEL_SMOOTHING = 0.0

    # Device
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # --------------------------------------------------------------------------
    # Inference
    # --------------------------------------------------------------------------
    KNN_K = 50  # Number of neighbors to retrieve for ranking (before filtering)
    TOP_K = 5  # MAP@5

    @classmethod
    def setup(cls):
        """
        Creates necessary output directories.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set reproducible seeds
        import random
        import numpy as np

        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
