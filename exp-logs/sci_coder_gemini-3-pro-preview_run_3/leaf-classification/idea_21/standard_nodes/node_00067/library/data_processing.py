import os
import numpy as np
import pandas as pd
from sklearn.model_selection import StratifiedKFold
from library.config import Config
from library.utils import setup_logger, load_numpy, save_numpy


class OrthogonalDataManager:
    """
    Manages data loading, orthogonal view-set partitioning (Centroids A, B, C),
    and stratified K-Fold splitting for the OS-LDE pipeline.
    """

    def __init__(self):
        self.logger = setup_logger("OrthogonalDataManager")

    def _get_partition_filenames(self, dataset_type):
        """Generates filenames for cached partitioned centroids."""
        return {
            "A": f"{dataset_type}_centroid_A.npy",
            "B": f"{dataset_type}_centroid_B.npy",
            "C": f"{dataset_type}_centroid_C.npy",
        }

    def _partition_and_aggregate(self, features):
        """
        Splits the 12-view features into 3 orthogonal sets and computes centroids.

        Args:
            features (np.ndarray): Shape (N, 12, F)

        Returns:
            dict: {
                "A": (N, F),
                "B": (N, F),
                "C": (N, F)
            }
        """
        centroids = {}

        # Iterate over sets defined in Config (A, B, C)
        for set_name, indices in Config.ORTHOGONAL_SETS.items():
            # Extract specific views: (N, 4, F)
            subset = features[:, indices, :]
            # Compute centroid (mean) along the view axis: (N, F)
            centroid = np.mean(subset, axis=1)
            centroids[set_name] = centroid.astype(np.float32)

        return centroids

    def get_data(self, dataset_type="train", load_cached_data=True):
        """
        Loads data, performs partitioning if necessary, and returns structured dictionary.

        Args:
            dataset_type (str): 'train' or 'test'
            load_cached_data (bool): Whether to attempt loading cached partitions.

        Returns:
            dict: Contains 'centroids' (dict of A,B,C), 'tabular', 'ids',
                  and 'labels'/'classes' (if train).
        """
        partition_files = self._get_partition_filenames(dataset_type)

        # 1. Attempt to load cached partitions
        if load_cached_data:
            self.logger.info(
                f"Attempting to load cached partitions for {dataset_type}..."
            )
            loaded_centroids = {}
            all_exist = True

            # Check/Load centroids
            for key, filename in partition_files.items():
                data = load_numpy(filename)
                if data is None:
                    all_exist = False
                    break
                loaded_centroids[key] = data

            # Check/Load static data (tabular, ids, labels)
            # These are cached by FeatureExtractor, so we use Config keys
            if dataset_type == "train":
                tabular = load_numpy(Config.CACHE_TRAIN_TABULAR)
                ids = load_numpy(Config.CACHE_TRAIN_IDS)
                labels = load_numpy(Config.CACHE_TRAIN_LABELS)
                classes = load_numpy(Config.CACHE_CLASSES)
                statics_exist = (
                    tabular is not None
                    and ids is not None
                    and labels is not None
                    and classes is not None
                )
            else:
                tabular = load_numpy(Config.CACHE_TEST_TABULAR)
                ids = load_numpy(Config.CACHE_TEST_IDS)
                statics_exist = tabular is not None and ids is not None

            if all_exist and statics_exist:
                self.logger.info("Cache hit. Partitions loaded successfully.")
                result = {"centroids": loaded_centroids, "tabular": tabular, "ids": ids}
                if dataset_type == "train":
                    result["labels"] = labels
                    result["classes"] = classes
                return result
            else:
                self.logger.info(
                    "Cache miss or incomplete. Processing from raw features..."
                )

        # 2. Process from raw features
        # Load raw features generated by FeatureExtractor
        raw_feature_key = (
            Config.CACHE_TRAIN_IMG_FEATURES
            if dataset_type == "train"
            else Config.CACHE_TEST_IMG_FEATURES
        )

        raw_features = load_numpy(raw_feature_key)
        if raw_features is None:
            raise FileNotFoundError(
                f"Raw features not found for {dataset_type}. "
                "Ensure FeatureExtractor has been executed first."
            )

        # Load auxiliary data
        if dataset_type == "train":
            tabular = load_numpy(Config.CACHE_TRAIN_TABULAR)
            ids = load_numpy(Config.CACHE_TRAIN_IDS)
            labels = load_numpy(Config.CACHE_TRAIN_LABELS)
            classes = load_numpy(Config.CACHE_CLASSES)

            if any(x is None for x in [tabular, ids, labels, classes]):
                raise FileNotFoundError(f"Missing auxiliary training data in cache.")
        else:
            tabular = load_numpy(Config.CACHE_TEST_TABULAR)
            ids = load_numpy(Config.CACHE_TEST_IDS)
            if any(x is None for x in [tabular, ids]):
                raise FileNotFoundError(f"Missing auxiliary test data in cache.")

        # Perform Partitioning
        self.logger.info(
            f"Partitioning {dataset_type} features into orthogonal sets..."
        )
        centroids = self._partition_and_aggregate(raw_features)

        # Save Partitions
        self.logger.info(f"Saving partitions to {Config.WORKING_DIR}...")
        for key, data in centroids.items():
            save_numpy(data, partition_files[key])

        result = {"centroids": centroids, "tabular": tabular, "ids": ids}
        if dataset_type == "train":
            result["labels"] = labels
            result["classes"] = classes

        return result

    def get_folds(self, y, n_folds=Config.N_FOLDS, seed=Config.SEED):
        """
        Generates Stratified K-Fold indices.

        Args:
            y (np.ndarray): Labels array.
            n_folds (int): Number of folds.
            seed (int): Random seed.

        Returns:
            list: List of (train_index, val_index) tuples.
        """
        # Safety check for small classes
        class_counts = pd.Series(y).value_counts()
        min_samples = class_counts.min()

        if min_samples < n_folds:
            self.logger.warning(
                f"Min samples per class ({min_samples}) is less than n_folds ({n_folds}). "
                f"Adjusting n_folds to {min_samples} to prevent errors."
            )
            actual_folds = min_samples
        else:
            actual_folds = n_folds

        skf = StratifiedKFold(n_splits=actual_folds, shuffle=True, random_state=seed)
        # StratifiedKFold expects X for length, but only uses y for stratification
        folds = list(skf.split(np.zeros(len(y)), y))

        return folds
