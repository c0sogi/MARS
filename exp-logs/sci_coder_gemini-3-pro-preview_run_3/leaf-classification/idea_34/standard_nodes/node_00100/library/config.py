import os
import torch


class Config:
    """
    Global configuration for the Plant Species Identification task.
    Implements the strategy: Stratified Selective-Topology Orthogonal Manifold-Densified LDA.
    """

    # ==========================================
    # Global Seeding & Hardware
    # ==========================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Use available CPUs for data loading, capping at reasonable limits if needed
    NUM_WORKERS = min(os.cpu_count(), 12)

    # ==========================================
    # Directory & File Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    IMAGES_DIR = os.path.join(INPUT_DIR, "images")

    # Working Directory for Caching Intermediate Features (Parquet/NPY)
    WORKING_DIR = "./working/idea_34"

    # Submission Output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Metadata Files (Generated by previous steps)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # ==========================================
    # Data Processing & Manifold Densification
    # ==========================================
    IMAGE_SIZE = 224
    BATCH_SIZE = 32  # Batch size for feature extraction

    # 12 Equidistant Rotations (0, 30, ..., 330)
    NUM_VIEWS = 12
    ROTATION_ANGLES = [i * 30 for i in range(12)]

    # Orthogonal Centroid Definitions
    # Maps centroid ID to indices of the ROTATION_ANGLES list
    # Centroid A: 0, 90, 180, 270
    # Centroid B: 30, 120, 210, 300
    # Centroid C: 60, 150, 240, 330
    CENTROID_INDICES = {"A": [0, 3, 6, 9], "B": [1, 4, 7, 10], "C": [2, 5, 8, 11]}

    # ==========================================
    # Feature Engineering (Tabular)
    # ==========================================
    # Pre-defined column groups for the 192 handcrafted features
    MARGIN_COLS = [f"margin{i}" for i in range(1, 65)]
    SHAPE_COLS = [f"shape{i}" for i in range(1, 65)]
    TEXTURE_COLS = [f"texture{i}" for i in range(1, 65)]
    TABULAR_COLS = MARGIN_COLS + SHAPE_COLS + TEXTURE_COLS

    # ==========================================
    # Model Architectures (Dual-Stream)
    # ==========================================
    # Global Geometry Stream: DINOv2 ViT-Large
    MODEL_DINO = "vit_large_patch14_dinov2.lvd142m"

    # Local Texture Stream: ConvNeXt Large
    MODEL_CONVNEXT = "convnext_large.fb_in22k_ft_in1k"

    # ==========================================
    # Training & Pipeline Hyperparameters
    # ==========================================
    # Dimensionality Reduction
    PCA_VARIANCE = 0.99  # Retain 99% variance for visual streams

    # Classifier
    N_SPLITS = 10  # 10-Fold Stratified Cross-Validation

    # Debugging / Development Control
    # Set DEBUG_SAMPLE_LIMIT to an integer (e.g., 50) to run on a subset for testing.
    # Set to None for full run.
    DEBUG_SAMPLE_LIMIT = None

    @classmethod
    def setup(cls):
        """
        Initialize the environment by creating necessary directories.
        Should be called at the start of execution.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        print(f"Configured Working Directory: {cls.WORKING_DIR}")
        print(f"Configured Submission Directory: {cls.SUBMISSION_DIR}")
        print(f"Device: {cls.DEVICE}")
