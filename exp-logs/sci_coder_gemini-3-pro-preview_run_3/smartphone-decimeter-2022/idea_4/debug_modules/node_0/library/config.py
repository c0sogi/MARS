import os


class Config:
    # -------------------------------------------------------------------------
    # Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_4"
    SUBMISSION_DIR = "./submission"

    # Ensure working and submission directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    # Metadata files generated by the analysis script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Sample submission for formatting
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Final output file
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache Paths for intermediate data (Parquet format)
    TRAIN_FEATURES_PATH = os.path.join(WORKING_DIR, "train_features.parquet")
    TRAIN_TARGETS_PATH = os.path.join(WORKING_DIR, "train_targets.parquet")
    VAL_FEATURES_PATH = os.path.join(WORKING_DIR, "val_features.parquet")
    VAL_TARGETS_PATH = os.path.join(WORKING_DIR, "val_targets.parquet")
    TEST_FEATURES_PATH = os.path.join(WORKING_DIR, "test_features.parquet")

    # -------------------------------------------------------------------------
    # Global Settings
    # -------------------------------------------------------------------------
    SEED = 42
    # Set to a small integer (e.g., 1000) to run on a subset of data for debugging.
    # Set to None for the full run.
    DEBUG_SAMPLE_SIZE = None

    # -------------------------------------------------------------------------
    # Feature Engineering Parameters
    # -------------------------------------------------------------------------
    # Window size k: The model input at time t will include features from [t-k, ..., t, ..., t+k]
    # Total window width in seconds = 2 * WINDOW_SIZE + 1
    WINDOW_SIZE = 2

    # Raw GNSS columns to load for aggregation
    GNSS_COLS = ["utcTimeMillis", "Cn0DbHz", "SvElevationDegrees", "Svid"]

    # Raw IMU columns to load for aggregation
    IMU_COLS = [
        "utcTimeMillis",
        "MessageType",
        "MeasurementX",
        "MeasurementY",
        "MeasurementZ",
    ]

    # -------------------------------------------------------------------------
    # Model Hyperparameters (LightGBM)
    # -------------------------------------------------------------------------
    # Using L1 loss (MAE) to be robust against GNSS outliers
    LGBM_PARAMS = {
        "objective": "regression_l1",
        "metric": "mae",
        "n_estimators": 5000,
        "learning_rate": 0.05,
        "num_leaves": 64,
        "max_depth": -1,
        "min_child_samples": 20,
        "subsample": 0.7,
        "subsample_freq": 1,
        "colsample_bytree": 0.7,
        "reg_alpha": 0.1,
        "reg_lambda": 0.1,
        "random_state": SEED,
        "n_jobs": -1,
        "verbose": -1,
    }

    # Training loop settings
    EARLY_STOPPING_ROUNDS = 100
    VERBOSE_EVAL = 100

    # -------------------------------------------------------------------------
    # Post-Processing Parameters (Kalman Filter)
    # -------------------------------------------------------------------------
    # Measurement Noise (R): Represents uncertainty in the ML model's predictions.
    # Higher R -> Trust the model less, smooth more.
    KF_R = 5.0

    # Process Noise (Q): Represents uncertainty in the physical motion model (constant velocity).
    # Higher Q -> Trust the physics less, allow more rapid changes.
    KF_Q = 0.5
