import os
import numpy as np
import pandas as pd
from library.data_manager import DataManager


class MultiHypothesisFeaturizer:
    """
    Orchestrates the creation of training and test datasets for the Multi-Hypothesis Newton-Boost strategy.

    This class utilizes the DataManager to load raw GNSS and IMU data, compute physics-based
    correction vectors (Newton steps) under multiple weighting hypotheses, and aggregates them
    into a structured feature set for machine learning models.
    """

    def __init__(
        self,
        input_dir="./input",
        metadata_dir="./metadata",
        cache_dir="./working/idea_15",
    ):
        """
        Initialize the featurizer.

        Args:
            input_dir (str): Path to the input data directory.
            metadata_dir (str): Path to the metadata directory.
            cache_dir (str): Path to store cached parquet files.
        """
        self.cache_dir = cache_dir
        os.makedirs(self.cache_dir, exist_ok=True)

        self.data_manager = DataManager(
            input_dir=input_dir, metadata_dir=metadata_dir, cache_dir=cache_dir
        )

        # Define the feature schema
        # These features are generated by library.gnss_math.process_gnss_data
        self.gnss_features = [
            # Hypothesis A: Signal Strength (Cn0) weighted Newton Step
            "newton_E_sig",
            "newton_N_sig",
            "newton_U_sig",
            "chi2_sig",
            # Hypothesis B: Elevation weighted Newton Step
            "newton_E_el",
            "newton_N_el",
            "newton_U_el",
            "chi2_el",
            # Hypothesis C: Masked (Quality) Newton Step
            "newton_E_mask",
            "newton_N_mask",
            "newton_U_mask",
            "chi2_mask",
            # Geometry / Dilution of Precision
            "GDOP",
            "PDOP",
            "HDOP",
            "VDOP",
            # Satellite Availability
            "sat_count",
        ]

        # Define IMU features schema
        # Pattern: {sensor}_{metric}_{measure}
        # Sensors: UncalAccel, UncalGyro, UncalMag
        # Metrics: mean, std
        # Measures: MeasurementX, MeasurementY, MeasurementZ
        self.imu_features = []
        sensors = ["UncalAccel", "UncalGyro", "UncalMag"]
        metrics = ["mean", "std"]
        measures = ["MeasurementX", "MeasurementY", "MeasurementZ"]

        for sensor in sensors:
            for metric in metrics:
                for measure in measures:
                    self.imu_features.append(f"{sensor}_{metric}_{measure}")

        self.feature_columns = self.gnss_features + self.imu_features

        # Targets: ENU residuals (Ground Truth - WLS Baseline)
        self.target_columns = ["target_E", "target_N", "target_U"]

        # Metadata to retain
        self.meta_columns = [
            "tripId",
            "UnixTimeMillis",
            "drive_id",
            "phone_name",
            "WlsPositionXEcefMeters",
            "WlsPositionYEcefMeters",
            "WlsPositionZEcefMeters",
        ]

    def get_train_data(self, load_cached_data=True, sample_frac=1.0):
        """
        Load and prepare training and validation data.

        Args:
            load_cached_data (bool): If True, tries to load from cache. If False or missing, recomputes.
            sample_frac (float): Fraction of data to return (useful for debugging/testing).

        Returns:
            tuple: (train_df, val_df)
        """
        print(f"Loading training data (cached={load_cached_data})...")
        train_df, val_df = self.data_manager.load_train_val(
            load_cached=load_cached_data, sample_frac=sample_frac
        )

        # Validate and ensure feature columns exist (fill missing with NaN if necessary)
        # This handles cases where some drives might lack IMU data
        train_df = self._ensure_features(train_df)
        val_df = self._ensure_features(val_df)

        print(f"Train data shape: {train_df.shape}")
        print(f"Val data shape: {val_df.shape}")

        return train_df, val_df

    def get_test_data(self, load_cached_data=True):
        """
        Load and prepare test data.

        Args:
            load_cached_data (bool): If True, tries to load from cache. If False or missing, recomputes.

        Returns:
            pd.DataFrame: Test dataframe.
        """
        print(f"Loading test data (cached={load_cached_data})...")
        test_df = self.data_manager.load_test(load_cached=load_cached_data)

        test_df = self._ensure_features(test_df)

        print(f"Test data shape: {test_df.shape}")

        return test_df

    def _ensure_features(self, df):
        """
        Ensures all expected feature columns exist in the dataframe.
        Missing columns are filled with NaN.
        """
        if df.empty:
            return df

        missing_cols = [c for c in self.feature_columns if c not in df.columns]
        if missing_cols:
            # Create missing columns with NaN
            # Using concat for efficiency if many columns are missing, or direct assignment
            df_missing = pd.DataFrame(np.nan, index=df.index, columns=missing_cols)
            df = pd.concat([df, df_missing], axis=1)

        return df

    def get_feature_names(self):
        """Returns the list of feature column names."""
        return self.feature_columns

    def get_target_names(self):
        """Returns the list of target column names."""
        return self.target_columns

    def get_meta_names(self):
        """Returns the list of metadata column names."""
        return self.meta_columns
