import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration for Transformer-Enhanced Multi-View MIL with Auxiliary Multi-Task Learning.
    """

    # --------------------------------------------------------------------------
    # General Setup
    # --------------------------------------------------------------------------
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 12  # Utilizing available vCPUs

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata generated by the provided script
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Working directory for this specific idea/experiment
    WORKING_DIR = "./working/idea_5"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Cache paths for processed data (Parquet format)
    CACHE_DIR = WORKING_DIR
    TRAIN_BAG_CACHE = os.path.join(CACHE_DIR, "train_bag_cache.parquet")
    VAL_BAG_CACHE = os.path.join(CACHE_DIR, "val_bag_cache.parquet")
    TEST_BAG_CACHE = os.path.join(CACHE_DIR, "test_bag_cache.parquet")

    # Model Checkpoint
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # Submission
    SUBMISSION_DIR = "./submission"
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Data Processing
    # --------------------------------------------------------------------------
    # Mammograms are typically tall and narrow.
    # Using (Height, Width) format.
    IMAGE_SIZE = (1024, 512)

    # Normalization constants (ImageNet defaults usually work well for transfer learning)
    NORM_MEAN = [0.485, 0.456, 0.406]
    NORM_STD = [0.229, 0.224, 0.225]

    # --------------------------------------------------------------------------
    # Model Architecture
    # --------------------------------------------------------------------------
    BACKBONE = "efficientnetv2_s"
    PRETRAINED = True

    # Transformer MIL Aggregator settings
    TRANSFORMER_EMBED_DIM = 256  # Dimension to project backbone features to
    TRANSFORMER_NUM_HEADS = 4
    TRANSFORMER_NUM_LAYERS = 2
    DROPOUT = 0.3

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    # Reduced batch size to accommodate smaller GPU memory (T4 vs A100)
    BATCH_SIZE = 2
    NUM_EPOCHS = 10
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-4

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 3

    # Multi-Task Loss Weights
    # These balance the primary cancer loss with auxiliary tasks
    LAMBDA_DENSITY = 0.5
    LAMBDA_BIOPSY = 0.5

    # --------------------------------------------------------------------------
    # Calibration / Post-Processing
    # --------------------------------------------------------------------------
    # Analytical Log-Odds Correction Constants
    # P_train is 0.5 because we use a balanced sampler (50% pos, 50% neg)
    TRAIN_PREVALENCE = 0.5
    # P_test is approx 0.02 based on dataset analysis
    TEST_PREVALENCE = 0.0206

    # --------------------------------------------------------------------------
    # Debugging
    # --------------------------------------------------------------------------
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 200  # Number of samples to use if DEBUG is True

    @staticmethod
    def setup_reproducibility():
        """
        Sets seeds for all random number generators to ensure reproducible results.
        """
        random.seed(Config.SEED)
        np.random.seed(Config.SEED)
        torch.manual_seed(Config.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(Config.SEED)
            torch.cuda.manual_seed_all(Config.SEED)
            # Deterministic operations may be slower, but ensure reproducibility
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
