import os
import time
import numpy as np
import pandas as pd
import torch
import torch.optim as optim
from torch_geometric.loader import DataLoader
from library.config import Config
from library.utils import TargetStandardizer
from library.dataset import MoleculeDataset
from library.model import DualGraphNetwork
from library.loss import PhysicsAwareLoss


class Trainer:
    """
    Manages the training, validation, and prediction lifecycle for the Scalar Coupling Prediction task.
    """

    def __init__(self):
        self.device = Config.DEVICE
        self._set_seed(Config.SEED)

        # Initialize Model
        self.model = DualGraphNetwork().to(self.device)

        # Optimizer
        self.optimizer = optim.AdamW(
            self.model.parameters(),
            lr=Config.LEARNING_RATE,
            weight_decay=Config.WEIGHT_DECAY,
        )

        # Scheduler: Cosine Annealing Warm Restarts
        self.scheduler = optim.lr_scheduler.CosineAnnealingWarmRestarts(
            self.optimizer,
            T_0=Config.SCHEDULER_T0,
            T_mult=Config.SCHEDULER_T_MULT,
            eta_min=Config.SCHEDULER_ETA_MIN,
        )

        # Loss Function (Composite: Coupling MAE + Shielding MSE + Charge MSE)
        self.criterion = PhysicsAwareLoss()

        # Target Standardizer (will be loaded/fitted during dataset init)
        self.standardizer = TargetStandardizer()

    def _set_seed(self, seed):
        """Sets random seeds for reproducibility."""
        torch.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)
        np.random.seed(seed)
        # Deterministic settings can slow down GNNs significantly, so we keep benchmark=True
        torch.backends.cudnn.deterministic = False
        torch.backends.cudnn.benchmark = True

    def train(self):
        """
        Executes the training loop with validation and early stopping.
        """
        print("Initializing Datasets...")
        # Initialize datasets
        # Note: Initializing train_dataset triggers the builder, which fits and saves the standardizer stats.
        train_dataset = MoleculeDataset(split="train")
        val_dataset = MoleculeDataset(split="val")

        # Now we can safely load the standardizer stats generated by the train dataset builder
        self.standardizer.load(Config.WORKING_DIR)

        train_loader = DataLoader(
            train_dataset,
            batch_size=Config.BATCH_SIZE,
            shuffle=True,
            num_workers=Config.NUM_WORKERS,
            pin_memory=True,
        )

        val_loader = DataLoader(
            val_dataset,
            batch_size=Config.BATCH_SIZE,
            shuffle=False,
            num_workers=Config.NUM_WORKERS,
            pin_memory=True,
        )

        print(f"Starting training on {self.device}...")
        best_metric = float("inf")
        patience_counter = 0
        best_model_path = os.path.join(Config.WORKING_DIR, "best_model.pth")

        for epoch in range(Config.EPOCHS):
            start_time = time.time()

            # Training Step
            train_loss_metrics = self._train_epoch(train_loader)

            # Validation Step
            val_metric, val_loss = self._validate(val_loader)

            # Scheduler Step
            self.scheduler.step()
            current_lr = self.scheduler.get_last_lr()[0]

            elapsed = time.time() - start_time

            # Logging
            print(
                f"Epoch {epoch+1}/{Config.EPOCHS} | Time: {elapsed:.1f}s | LR: {current_lr:.2e}"
            )
            print(
                f"  Train Loss: {train_loss_metrics['loss_total']:.5f} "
                f"(Coup: {train_loss_metrics['loss_coupling']:.4f}, "
                f"Shld: {train_loss_metrics['loss_shielding']:.4f}, "
                f"Chrg: {train_loss_metrics['loss_charge']:.4f})"
            )
            print(f"  Val Loss: {val_loss:.5f} | Val LMAE: {val_metric:.9f}")

            # Early Stopping & Checkpointing
            if val_metric < best_metric:
                print(
                    f"  [New Best] LMAE improved from {best_metric:.9f} to {val_metric:.9f}. Saving model."
                )
                best_metric = val_metric
                patience_counter = 0
                torch.save(self.model.state_dict(), best_model_path)
            else:
                patience_counter += 1
                print(
                    f"  [No Improv] Patience: {patience_counter}/{Config.EARLY_STOPPING_PATIENCE}"
                )
                if patience_counter >= Config.EARLY_STOPPING_PATIENCE:
                    print("Early stopping triggered.")
                    break

        print(f"Training complete. Best Validation LMAE: {best_metric:.9f}")

    def _train_epoch(self, loader):
        """Runs one epoch of training."""
        self.model.train()
        total_loss = 0.0
        metrics_accum = {
            "loss_coupling": 0.0,
            "loss_shielding": 0.0,
            "loss_charge": 0.0,
        }
        num_batches = len(loader)

        for batch in loader:
            batch = batch.to(self.device)

            self.optimizer.zero_grad()

            # Forward pass
            preds = self.model(batch)

            # Compute Loss
            loss, metrics = self.criterion(preds, batch)

            # Backward pass
            loss.backward()

            # Clip gradients to prevent explosion in deep GNNs
            torch.nn.utils.clip_grad_norm_(self.model.parameters(), max_norm=1.0)

            self.optimizer.step()

            total_loss += metrics["loss_total"]
            for k in metrics_accum:
                metrics_accum[k] += metrics[k]

        # Average metrics
        avg_metrics = {k: v / num_batches for k, v in metrics_accum.items()}
        avg_metrics["loss_total"] = total_loss / num_batches
        return avg_metrics

    def _validate(self, loader):
        """Runs validation and calculates the competition metric (LMAE)."""
        self.model.eval()
        total_loss = 0.0

        # Containers for metric calculation
        all_preds = []
        all_targets = []
        all_types = []

        with torch.no_grad():
            for batch in loader:
                batch = batch.to(self.device)

                # Forward
                preds = self.model(batch)

                # Loss (for monitoring purposes)
                loss, _ = self.criterion(preds, batch)
                total_loss += loss.item()

                # Collect data for LMAE calculation
                # preds[0] is the coupling constant prediction
                pred_coupling = preds[0].cpu().numpy().flatten()
                target_coupling = batch.y.cpu().numpy().flatten()

                # Map integer types back to string types for standardizer
                # batch.target_type is (N,) int tensor
                type_indices = batch.target_type.cpu().numpy()
                type_strs = [Config.COUPLING_TYPES[i] for i in type_indices]

                all_preds.append(pred_coupling)
                all_targets.append(target_coupling)
                all_types.extend(type_strs)

        avg_loss = total_loss / len(loader)

        # Concatenate all batches
        all_preds = np.concatenate(all_preds)
        all_targets = np.concatenate(all_targets)
        all_types = np.array(all_types)

        # Inverse Transform to original physical scale
        # Note: targets in dataset are standardized, so we must restore them too
        # to calculate MAE in physical units.
        preds_original = self.standardizer.inverse_transform(all_preds, all_types)
        targets_original = self.standardizer.inverse_transform(all_targets, all_types)

        # Calculate Log Mean Absolute Error per type
        # Metric = mean( log( mean( |y - y_pred| ) ) ) over types
        df = pd.DataFrame(
            {"type": all_types, "target": targets_original, "pred": preds_original}
        )

        df["abs_error"] = np.abs(df["target"] - df["pred"])

        # Group by type and calculate MAE
        mae_per_type = df.groupby("type")["abs_error"].mean()

        # Log of MAE (natural log)
        log_mae_per_type = np.log(mae_per_type)

        # Average across types
        final_metric = log_mae_per_type.mean()

        return final_metric, avg_loss

    def predict(self):
        """
        Generates predictions for the test set and saves the submission file.
        """
        print("Loading Test Dataset...")
        test_dataset = MoleculeDataset(split="test")
        test_loader = DataLoader(
            test_dataset,
            batch_size=Config.BATCH_SIZE,
            shuffle=False,
            num_workers=Config.NUM_WORKERS,
            pin_memory=True,
        )

        # Load Best Model
        best_model_path = os.path.join(Config.WORKING_DIR, "best_model.pth")
        if not os.path.exists(best_model_path):
            raise FileNotFoundError("Best model not found. Run train() first.")

        print(f"Loading model from {best_model_path}...")
        self.model.load_state_dict(
            torch.load(best_model_path, map_location=self.device)
        )
        self.model.eval()

        # Ensure standardizer is loaded
        self.standardizer.load(Config.WORKING_DIR)

        all_ids = []
        all_preds = []
        all_types = []

        print("Running Inference...")
        with torch.no_grad():
            for batch in test_loader:
                batch = batch.to(self.device)

                # Forward
                preds = self.model(batch)

                # Extract coupling predictions
                pred_coupling = preds[0].cpu().numpy().flatten()
                ids = batch.id.cpu().numpy().flatten()

                # Types
                type_indices = batch.target_type.cpu().numpy()
                type_strs = [Config.COUPLING_TYPES[i] for i in type_indices]

                all_preds.append(pred_coupling)
                all_ids.append(ids)
                all_types.extend(type_strs)

        # Concatenate
        all_preds = np.concatenate(all_preds)
        all_ids = np.concatenate(all_ids)
        all_types = np.array(all_types)

        # Inverse Transform
        print("Restoring predictions to physical scale...")
        preds_original = self.standardizer.inverse_transform(all_preds, all_types)

        # Create Submission DataFrame
        submission = pd.DataFrame(
            {"id": all_ids, "scalar_coupling_constant": preds_original}
        )

        # Sort by ID to match sample submission format
        submission = submission.sort_values("id")

        # Save
        save_path = os.path.join(Config.SUBMISSION_DIR, "submission.csv")
        print(f"Saving submission to {save_path}...")
        submission.to_csv(save_path, index=False)
        print("Done.")
