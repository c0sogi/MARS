import os
import torch
import numpy as np
import random


class Config:
    """
    Configuration class for the View-Invariant Attentive Refinement Network (VI-ARN).
    Centralizes all hyperparameters, file paths, and global settings.
    """

    # ==========================================
    # Directory & File Paths
    # ==========================================
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_9"
    SUBMISSION_DIR = "./submission"

    # Ensure necessary writeable directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata paths (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Cache paths for deterministic data processing
    # Using .npz for efficient storage of numpy arrays
    CACHE_TRAIN_PATH = os.path.join(WORKING_DIR, "train_features.npz")
    CACHE_VAL_PATH = os.path.join(WORKING_DIR, "val_features.npz")
    CACHE_TEST_PATH = os.path.join(WORKING_DIR, "test_features.npz")

    # Model checkpoint and output paths
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Data Processing Hyperparameters
    # ==========================================
    # Windowing
    WINDOW_SIZE = 64
    STRIDE = 32  # 50% overlap for sliding window

    # Vocabulary
    # 20 gestures + 1 background class (Index 0)
    NUM_CLASSES = 21

    # Skeleton Alignment
    # Indices for Left Hip and Right Hip to calculate alignment angle
    # Based on Kinect skeleton format: HipLeft=12, HipRight=16, HipCenter=0 (approximate, depends on specific map)
    # Using standard indices often found in these datasets, but logic will be in feature extractor.

    # ==========================================
    # Model Architecture Hyperparameters
    # ==========================================
    # Bi-GRU Encoder
    GRU_HIDDEN_SIZE = 128
    GRU_NUM_LAYERS = 2

    # TCN / Refinement Stages
    TCN_KERNEL_SIZE = 3
    TCN_NUM_CHANNELS = [64, 64, 64]  # Channel dimensions for TCN layers
    DROPOUT_RATE = 0.3

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    SEED = 42
    BATCH_SIZE = 32
    LEARNING_RATE = 1e-3
    NUM_EPOCHS = 50

    # Debugging / Development
    # Set to a small integer (e.g., 10) to train on a subset of data for quick checks.
    # Set to None for full training.
    DEBUG_SUBSET_SIZE = None

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 10

    # Loss Function Weights
    # Class weights: 0.2 for Background (index 0), 1.0 for all gesture classes (1-20)
    CLASS_WEIGHTS = [0.2] + [1.0] * 20

    # Cascaded Loss
    # Lambda for the Log-Space Smoothing (Truncated MSE) component
    LAMBDA_SMOOTH = 0.15

    # ==========================================
    # Utilities
    # ==========================================
    @staticmethod
    def set_seed(seed=42):
        """
        Sets the random seed for Python, NumPy, and PyTorch to ensure reproducibility.
        """
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            # Ensure deterministic behavior in CuDNN
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

        # Set environment variable for deterministic algorithms if supported
        os.environ["CUBLAS_WORKSPACE_CONFIG"] = ":4096:8"
