import os
import torch
import random
import numpy as np


class Config:
    """
    Global configuration for the Siamese DeBERTa-v3-Base experiment.
    Includes hyperparameters, file paths, and model settings.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 500  # Number of samples to use if DEBUG is True

    # =========================================================================
    # File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_14"
    SUBMISSION_DIR = "./submission"

    # Metadata paths (generated by previous steps)
    TRAIN_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # Cache paths (for deterministic data processing)
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")

    # =========================================================================
    # Model Architecture
    # =========================================================================
    MODEL_NAME = "microsoft/deberta-v3-base"
    MAX_LENGTH = 512
    NUM_CLASSES = 3  # Winner A, Winner B, Tie

    # Disentangled Hierarchical Pooling Settings
    # Number of final hidden layers to concatenate for the Response stream
    POOLING_NUM_LAYERS = 4

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    EPOCHS = 4
    TRAIN_BATCH_SIZE = 8  # Adjusted for A100 40GB with Siamese (2x input) + 512 seq len
    VALID_BATCH_SIZE = 16

    LEARNING_RATE = 1e-5
    WEIGHT_DECAY = 0.01
    WARMUP_RATIO = 0.1
    MAX_GRAD_NORM = 1.0

    # Optimization flags
    FP16 = True  # Mixed Precision
    GRADIENT_CHECKPOINTING = True
    GRADIENT_ACCUMULATION_STEPS = 1

    # =========================================================================
    # Data Strategy
    # =========================================================================
    # Symmetric Augmentation: Double training data by swapping (A, B) -> (B, A)
    USE_SYMMETRIC_AUGMENTATION = True

    # =========================================================================
    # Inference Strategy
    # =========================================================================
    # Test-Time Augmentation: Average predictions of (A, B) and (B, A)
    USE_TTA = True

    # =========================================================================
    # Hardware / System
    # =========================================================================
    NUM_WORKERS = 4
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")


def setup_environment(config=Config):
    """
    Initializes the environment by creating necessary directories and
    setting random seeds for reproducibility.

    Args:
        config: The Config class containing path and seed information.
    """
    # 1. Create Directories
    os.makedirs(config.WORKING_DIR, exist_ok=True)
    os.makedirs(config.CACHE_DIR, exist_ok=True)
    os.makedirs(config.SUBMISSION_DIR, exist_ok=True)

    # 2. Set Random Seeds
    seed = config.SEED
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)

    # 3. Ensure Deterministic Behavior (cudnn)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False

    # 4. Environment Variables
    os.environ["PYTHONHASHSEED"] = str(seed)
    # Disable tokenizers parallelism to avoid deadlocks in dataloaders
    os.environ["TOKENIZERS_PARALLELISM"] = "false"

    print(f"Environment setup complete. Working directory: {config.WORKING_DIR}")
