import os


class Config:
    """
    Global configuration for the Sequential Cascade Dual-Stream GBDT pipeline.
    Includes file paths, feature engineering parameters, and model hyperparameters.
    """

    # =========================================================================
    # 1. File Paths and Directories
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_14"
    SUBMISSION_DIR = "./submission"

    # Ensure necessary directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata Files (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Raw Data Files
    # Note: Tracking and Helmets files are split by train/test in the input directory
    TRAIN_TRACKING_PATH = os.path.join(INPUT_DIR, "train_player_tracking.csv")
    TRAIN_HELMETS_PATH = os.path.join(INPUT_DIR, "train_baseline_helmets.csv")
    TRAIN_VIDEO_META_PATH = os.path.join(INPUT_DIR, "train_video_metadata.csv")

    TEST_TRACKING_PATH = os.path.join(INPUT_DIR, "test_player_tracking.csv")
    TEST_HELMETS_PATH = os.path.join(INPUT_DIR, "test_baseline_helmets.csv")
    TEST_VIDEO_META_PATH = os.path.join(INPUT_DIR, "test_video_metadata.csv")

    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # 2. Global Settings
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run on a smaller subset of data for debugging

    # =========================================================================
    # 3. Feature Engineering Configuration
    # =========================================================================

    # --- Cross-Modal Temporal Pyramids ---
    # Lags are defined as relative steps from current time t.
    # Negative values are past, positive values are future (acausal).

    # Tracking Lags: Exponentially spaced (t, t±1, t±2, t±4, t±8, t±15)
    # Captures micro-mechanics and macro-trajectory.
    LAGS_TRACKING = [-15, -8, -4, -2, -1, 0, 1, 2, 4, 8, 15]

    # Visual Lags: Sparse (t, t±4, t±8, t±15)
    # Captures visual trajectory (looming/convergence).
    LAGS_VISUAL = [-15, -8, -4, 0, 4, 8, 15]

    # --- Stream B Context ---
    # Rolling window size to compute 'Max_Interaction_Prob' from Stream A predictions.
    # Looking back 10 steps (1 second) to capture recent collision history.
    STREAM_B_ROLLING_WINDOW = 10

    # --- Feature Whitelists (Deterministic Ordering) ---
    # Base columns to be used for lag generation.

    # Tracking features (Sensor data)
    TRACKING_BASE_COLS = [
        "x_position",
        "y_position",
        "speed",
        "distance",
        "direction",
        "orientation",
        "acceleration",
        "sa",
        "sin_direction",
        "cos_direction",
        "sin_orientation",
        "cos_orientation",
    ]

    # Visual features (Computer Vision data)
    # These will be duplicated for each view (Sideline/Endzone)
    VISUAL_BASE_COLS = [
        "left",
        "width",
        "top",
        "height",  # Bounding box geometry
        "iou",
        "dist_centroid",  # Geometric relationships
    ]

    # Stream B specific context feature
    STREAM_B_CONTEXT_COLS = ["max_interaction_prob"]

    # =========================================================================
    # 4. Model Hyperparameters (XGBoost)
    # =========================================================================

    # Training Configuration
    UNDERSAMPLE_RATIO = 10.0  # Ratio of Negative to Positive samples (10:1)
    NUM_BOOST_ROUND = 5000  # Maximum number of boosting rounds
    EARLY_STOPPING_ROUNDS = 50
    VERBOSE_EVAL = 100

    # --- Stream A: Interaction Model (Player-Player) ---
    # Architecture: Conditional Early-Fusion GBDT
    # Focus: High-fidelity contact detection between players.
    XGB_PARAMS_STREAM_A = {
        "objective": "binary:logistic",
        "eval_metric": "logloss",
        "tree_method": "hist",
        "device": "cuda",  # Use NVIDIA A100
        "learning_rate": 0.02,  # Lower LR for robust convergence
        "max_depth": 8,  # Moderate depth for interaction complexity
        "subsample": 0.8,
        "colsample_bytree": 0.8,
        "min_child_weight": 5,
        "seed": SEED,
        "n_jobs": 12,
    }

    # --- Stream B: Impact Model (Player-Ground) ---
    # Architecture: Context-Aware Kinematic GBDT
    # Focus: Detecting ground impact using kinematics + interaction context.
    # Note: Requires higher capacity (depth) to model kinematic non-linearities.
    XGB_PARAMS_STREAM_B = {
        "objective": "binary:logistic",
        "eval_metric": "logloss",
        "tree_method": "hist",
        "device": "cuda",  # Use NVIDIA A100
        "learning_rate": 0.02,
        "max_depth": 10,  # Deeper trees as per "Lessons Learned"
        "subsample": 0.8,
        "colsample_bytree": 0.8,
        "min_child_weight": 3,
        "seed": SEED,
        "n_jobs": 12,
    }

    @staticmethod
    def get_xgb_params(stream="A"):
        """
        Returns the XGBoost parameters for the specified stream.

        Args:
            stream (str): 'A' for Interaction model, 'B' for Impact model.

        Returns:
            dict: XGBoost parameter dictionary.
        """
        if stream == "A":
            return Config.XGB_PARAMS_STREAM_A.copy()
        elif stream == "B":
            return Config.XGB_PARAMS_STREAM_B.copy()
        else:
            raise ValueError("Stream must be 'A' or 'B'")
