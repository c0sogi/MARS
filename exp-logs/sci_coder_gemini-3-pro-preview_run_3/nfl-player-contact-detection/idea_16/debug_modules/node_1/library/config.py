import os


class Config:
    """
    Global configuration for the NFL Player Contact Detection pipeline.
    Implements settings for the Ego-Centric Dual-Stream GBDT architecture.
    """

    # ==========================================
    # 1. Directories and Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_16"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    SUBMISSION_DIR = "./submission"

    # Ensure working directories exist immediately
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata Paths (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Raw Data Paths
    TRAIN_TRACKING_PATH = os.path.join(INPUT_DIR, "train_player_tracking.csv")
    TEST_TRACKING_PATH = os.path.join(INPUT_DIR, "test_player_tracking.csv")
    TRAIN_HELMETS_PATH = os.path.join(INPUT_DIR, "train_baseline_helmets.csv")
    TEST_HELMETS_PATH = os.path.join(INPUT_DIR, "test_baseline_helmets.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")
    SUBMISSION_OUTPUT_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # 2. Global Constants
    # ==========================================
    SEED = 42

    # Exponential Temporal Pyramids
    # Lags to retrieve past/future context.
    # 0 is current frame. 15 is ~1.5 seconds context.
    LAGS = [0, 1, 2, 4, 8, 15]

    # Undersampling Ratio (Negative : Positive)
    # Used to balance the training set.
    NEG_POS_RATIO = 10.0

    # ==========================================
    # 3. Feature Configuration (Dual-Stream)
    # ==========================================

    # --- Stream A: Interaction Model (Player-Player) ---
    # Focus: Relational dynamics and Visual Geometry.
    # Input: Field-Centric Tracking + Visuals.
    STREAM_A_CONFIG = {
        "stream_name": "interaction",
        "use_tracking": True,
        "use_relational": True,
        "use_visual": True,
        "use_ego": False,  # Ego-motion less relevant for external interactions
        # Base columns to expand with lags
        "tracking_cols": [
            "x_position",
            "y_position",
            "speed",
            "direction",
            "orientation",
            "acceleration",
            "sa",
        ],
        "visual_cols": [
            "view_sideline_iou",
            "view_sideline_dist",
            "view_endzone_iou",
            "view_endzone_dist",
        ],
    }

    # --- Stream B: Impact Model (Player-Ground) ---
    # Focus: Loss of control and force transients.
    # Input: Ego-Centric Kinematics ONLY.
    # Innovation: Project motion into body frame (Surge/Sway).
    STREAM_B_CONFIG = {
        "stream_name": "impact",
        "use_tracking": False,  # Raw field coords disabled
        "use_relational": False,  # No second player to relate to
        "use_visual": False,  # Visuals often occluded or noisy for ground
        "use_ego": True,
        # Derived Ego-Centric features
        "ego_cols": ["surge_speed", "sway_speed", "surge_accel", "sway_accel"],
    }

    # ==========================================
    # 4. Model Hyperparameters (XGBoost)
    # ==========================================

    # Common Parameters
    XGB_PARAMS_BASE = {
        "booster": "gbtree",
        "objective": "binary:logistic",
        "eval_metric": "logloss",
        "tree_method": "gpu_hist",  # Leverage A100 GPU
        "learning_rate": 0.05,
        "subsample": 0.8,
        "colsample_bytree": 0.8,
        "n_jobs": -1,
        "random_state": SEED,
        "verbosity": 0,
        "early_stopping_rounds": 50,
    }

    # Stream A Specifics
    # Standard depth for relational features
    XGB_PARAMS_STREAM_A = XGB_PARAMS_BASE.copy()
    XGB_PARAMS_STREAM_A.update(
        {
            "max_depth": 6,
            "n_estimators": 5000,  # Controlled by Early Stopping
        }
    )

    # Stream B Specifics
    # Deeper trees to learn complex kinematic boundaries in Ego space
    XGB_PARAMS_STREAM_B = XGB_PARAMS_BASE.copy()
    XGB_PARAMS_STREAM_B.update(
        {
            "max_depth": 8,
            "n_estimators": 5000,  # Controlled by Early Stopping
        }
    )
