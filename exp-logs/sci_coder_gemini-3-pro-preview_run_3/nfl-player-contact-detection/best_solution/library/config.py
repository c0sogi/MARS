import os


class Config:
    """
    Configuration for Hybrid-Context Dual-Stream GBDT with Cross-Modal Consistency Pyramids.
    Acts as the central source of truth for pipeline parameters and cache hashing.
    """

    # =========================================================================
    # 1. Paths & Directories
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_30"

    # Create working directory immediately upon config load
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Raw Input Files
    TRAIN_TRACKING_PATH = os.path.join(INPUT_DIR, "train_player_tracking.csv")
    TEST_TRACKING_PATH = os.path.join(INPUT_DIR, "test_player_tracking.csv")
    TRAIN_HELMETS_PATH = os.path.join(INPUT_DIR, "train_baseline_helmets.csv")
    TEST_HELMETS_PATH = os.path.join(INPUT_DIR, "test_baseline_helmets.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Files (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output
    SUBMISSION_PATH = "./submission/submission.csv"

    # =========================================================================
    # 2. Global Pipeline Settings
    # =========================================================================
    SEED = 42

    # Temporal Window Flattening Schedule
    # Exponential lags: t, t+/-1, t+/-2, t+/-4, t+/-8, t+/-15
    LAG_SCHEDULE = [-15, -8, -4, -2, -1, 0, 1, 2, 4, 8, 15]

    # Targeted Majority Undersampling Ratio (Negative : Positive)
    # Retain 100% positives, subsample negatives to this ratio.
    NEGATIVE_SAMPLING_RATIO = 10.0

    # =========================================================================
    # 3. Stream A: Interaction Model (Player-Player)
    # =========================================================================
    # Scope: player2 != 'G'
    # Strategy: Consistency & Verification

    STREAM_A_FEATURES = {
        # Robust Proximity
        "relational": [
            "distance",
            "closure_rate",
            "orientation_cos_sim",
            "direction_cos_sim",
        ],
        # Visual Consensus (Flattened Pyramids)
        "visual": ["sideline_iou", "endzone_iou", "max_iou", "min_iou", "iou_diff"],
        # Cross-Modal Consistency (The Innovation)
        "cross_modal": ["visual_looming", "consistency_metric"],
        # System Energy
        "energy": ["speed_p1", "speed_p2", "acceleration_p1", "acceleration_p2"],
    }

    STREAM_A_MODEL_PARAMS = {
        "n_estimators": 5000,
        "learning_rate": 0.02,
        "max_depth": 6,  # Standard depth for complex interactions
        "subsample": 0.8,
        "colsample_bytree": 0.8,
        "objective": "binary:logistic",
        "eval_metric": "logloss",
        "tree_method": "gpu_hist",  # GPU acceleration
        "random_state": SEED,
        "n_jobs": -1,
    }

    # =========================================================================
    # 4. Stream B: Impact Model (Player-Ground)
    # =========================================================================
    # Scope: player2 == 'G'
    # Strategy: Hybrid Context + Ego-Dynamics
    # Constraint: NO Visual Features

    STREAM_B_FEATURES = {
        # Field-Centric Anchors (Environmental Priors)
        "field_centric": [
            # Removed x, y, dir, orient to prevent spatial overfitting (Cite Lesson 00075)
            "speed",
            "acceleration",
        ],
        # Ego-Centric Dynamics (Invariant Fall Signatures)
        "ego_centric": ["v_surge", "v_sway", "a_surge", "a_sway", "j_surge", "j_sway"],
    }

    STREAM_B_MODEL_PARAMS = {
        "n_estimators": 5000,
        "learning_rate": 0.02,
        "max_depth": 8,  # Slightly deeper to capture dynamic shapes without visual aid
        "subsample": 0.8,
        "colsample_bytree": 0.8,
        "objective": "binary:logistic",
        "eval_metric": "logloss",
        "tree_method": "gpu_hist",  # GPU acceleration
        "random_state": SEED,
        "n_jobs": -1,
    }

    # =========================================================================
    # 5. Training & Optimization
    # =========================================================================
    EARLY_STOPPING_ROUNDS = 100
    VERBOSE_EVAL = 100

    # Threshold Optimization Search Space (start, stop, step)
    THRESHOLD_SEARCH = (0.10, 0.90, 0.01)

    @staticmethod
    def get_hashable_config(stream_name):
        """
        Returns a dictionary representation of the configuration for a specific stream.
        Used to generate cache keys for feature engineering.
        """
        if stream_name == "A":
            return {
                "features": Config.STREAM_A_FEATURES,
                "lags": Config.LAG_SCHEDULE,
                "seed": Config.SEED,
            }
        elif stream_name == "B":
            return {
                "features": Config.STREAM_B_FEATURES,
                "lags": Config.LAG_SCHEDULE,
                "seed": Config.SEED,
            }
        else:
            raise ValueError(f"Unknown stream: {stream_name}")
