import os
import hashlib
import json


class ProjectConfig:
    """
    Centralized configuration for the Physically-Consistent Hybrid-Context Dual-Stream GBDT.
    """

    # =========================================================================
    # Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_30"
    SUBMISSION_DIR = "./submission"

    # Raw Data Paths
    TRAIN_TRACKING_PATH = os.path.join(INPUT_DIR, "train_player_tracking.csv")
    TEST_TRACKING_PATH = os.path.join(INPUT_DIR, "test_player_tracking.csv")
    TRAIN_HELMETS_PATH = os.path.join(INPUT_DIR, "train_baseline_helmets.csv")
    TEST_HELMETS_PATH = os.path.join(INPUT_DIR, "test_baseline_helmets.csv")

    # Metadata Paths (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output Paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Global Settings
    # =========================================================================
    SEED = 42
    USE_GPU = True
    NUM_WORKERS = 12  # Available vCPUs
    MISSING_SENTINEL = -999.0

    # =========================================================================
    # Feature Engineering Configuration
    # =========================================================================

    # Sparse Exponential Lags for Temporal Flattening
    # Covers immediate context (0, 1, 2) and wider temporal context (4, 8, 15)
    LAGS = [-15, -8, -4, -2, -1, 0, 1, 2, 4, 8, 15]

    # Stream A: Interaction Model (Player-Player)
    # Focus: Relational Physics, System Energy, Visual Verification
    STREAM_A_FEATURES = [
        # Relational Primitives
        "distance",
        "closure_rate",  # Finite difference of distance
        # System Energy (Player 1)
        "speed_p1",
        "acceleration_p1",  # Scalar acceleration
        # System Energy (Player 2)
        "speed_p2",
        "acceleration_p2",
        # Visual Consensus & Verification
        "iou_sideline",
        "iou_endzone",
        "max_iou",
        "min_iou",
        "iou_diff",
        "visual_looming_mismatch",  # (Normalized Closure Rate - Visual Looming Rate)
    ]

    # Stream B: Impact Model (Player-Ground)
    # Focus: Hybrid Context (Field Position) + Ego-Dynamics
    # Explicitly excludes visual features
    STREAM_B_FEATURES = [
        # Field-Centric Anchor
        "x_position",
        "y_position",
        "speed",
        "acceleration",
        "direction",
        "orientation",
        # Ego-Centric Dynamics (Derived Physics)
        "v_surge",
        "v_sway",
        "a_surge",
        "a_sway",
        "j_surge",  # Jerk
        "j_sway",
    ]

    # =========================================================================
    # Training Configuration
    # =========================================================================

    # Sampling
    NEG_POS_RATIO = 10.0  # Targeted Majority Undersampling

    # Stream A Model Parameters (Deep / Complex Interactions)
    XGB_PARAMS_STREAM_A = {
        "objective": "binary:logistic",
        "eval_metric": "logloss",
        "tree_method": "gpu_hist" if USE_GPU else "hist",
        "max_depth": 6,  # Standard depth for interaction complexity
        "learning_rate": 0.05,
        "n_estimators": 5000,  # High cap, controlled by early stopping
        "subsample": 0.8,
        "colsample_bytree": 0.8,
        "random_state": SEED,
        "n_jobs": NUM_WORKERS,
    }

    # Stream B Model Parameters (Shallow / Robust Dynamics)
    XGB_PARAMS_STREAM_B = {
        "objective": "binary:logistic",
        "eval_metric": "logloss",
        "tree_method": "gpu_hist" if USE_GPU else "hist",
        "max_depth": 6,  # Shallow depth to prevent overfitting sensor noise
        "learning_rate": 0.05,
        "n_estimators": 5000,
        "subsample": 0.8,
        "colsample_bytree": 0.8,
        "random_state": SEED,
        "n_jobs": NUM_WORKERS,
    }

    EARLY_STOPPING_ROUNDS = 50
    VERBOSE_EVAL = 100

    @classmethod
    def init_environment(cls):
        """
        Initialize the environment: create directories and set seeds.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set seeds for reproducibility (generic python/numpy)
        import numpy as np
        import random

        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        try:
            import torch

            torch.manual_seed(cls.SEED)
            if torch.cuda.is_available():
                torch.cuda.manual_seed_all(cls.SEED)
        except ImportError:
            pass

    @classmethod
    def get_config_hash(cls):
        """
        Generate a unique hash based on critical configuration parameters.
        Used for cache invalidation.
        """
        config_dict = {
            "lags": cls.LAGS,
            "stream_a_features": cls.STREAM_A_FEATURES,
            "stream_b_features": cls.STREAM_B_FEATURES,
            "neg_pos_ratio": cls.NEG_POS_RATIO,
            "seed": cls.SEED,
            "xgb_a": cls.XGB_PARAMS_STREAM_A,
            "xgb_b": cls.XGB_PARAMS_STREAM_B,
        }
        # Serialize to JSON string with sorting to ensure determinism
        config_str = json.dumps(config_dict, sort_keys=True)
        return hashlib.md5(config_str.encode("utf-8")).hexdigest()
