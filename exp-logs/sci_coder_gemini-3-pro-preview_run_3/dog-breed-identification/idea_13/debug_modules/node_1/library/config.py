import os
import torch


class Config:
    """
    Configuration class for the Dog Breed Classification Task.
    Implements the strategy: Stratified Ensemble with ImageNet-21k Priors and Greedy Model Soups.
    """

    # ==========================================
    # General Setup
    # ==========================================
    seed = 42
    debug = False  # Set to True to run on a small subset for debugging

    # ==========================================
    # Directories & Paths
    # ==========================================
    input_dir = "./input"
    metadata_dir = "./metadata"
    working_dir = "./working/idea_13"
    submission_dir = "./submission"

    # Metadata Paths (Generated by the provided metadata script)
    train_metadata_path = os.path.join(metadata_dir, "train.csv")
    val_metadata_path = os.path.join(metadata_dir, "val.csv")
    test_metadata_path = os.path.join(metadata_dir, "test.csv")

    # Output Paths
    submission_path = os.path.join(submission_dir, "submission.csv")

    # ==========================================
    # Data Parameters
    # ==========================================
    # Fixed resolution as per solution strategy (no scaling to 384+)
    image_size = 224

    # Batch size optimized for A100 40GB with ConvNeXt-Small
    batch_size = 64
    num_workers = 4

    # Target details
    num_classes = 120

    # ==========================================
    # Model Architecture
    # ==========================================
    # ConvNeXt-Small initialized with ImageNet-22k weights (fine-tuned on 1k)
    model_name = "convnext_small.fb_in22k_ft_in1k"
    pretrained = True

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    n_folds = 5

    # Full 30-epoch schedule required for Greedy Soup convergence
    epochs = 30

    # Conservative learning rate for fine-tuning pre-trained weights
    learning_rate = 1e-5

    # Standard weight decay for AdamW
    weight_decay = 1e-2

    # Scheduler: Cosine Annealing
    T_max = 30
    min_lr = 1e-7

    # ==========================================
    # Optimization & Ensembling Strategies
    # ==========================================
    # Early Stopping: Set to match epochs to enforce full training run (as per strategy)
    patience = 30

    # Greedy Model Soup Configuration
    # We save checkpoints for the final 10 epochs to construct the soup
    soup_start_epoch = 20

    # ==========================================
    # Hardware
    # ==========================================
    device = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Creates necessary working and submission directories.
        """
        os.makedirs(cls.working_dir, exist_ok=True)
        os.makedirs(cls.submission_dir, exist_ok=True)
