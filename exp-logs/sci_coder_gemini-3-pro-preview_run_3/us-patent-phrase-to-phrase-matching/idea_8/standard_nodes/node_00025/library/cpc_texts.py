def get_cpc_text(context_code):
    """
    Constructs the full hierarchical description for a given CPC context code.
    Hierarchy: Section Description > Class Description

    Args:
        context_code (str): The CPC code (e.g., "A47").

    Returns:
        str: The concatenated description string.
    """
    if not context_code:
        return ""

    # Extract Section (first character) and Class (full code)
    section = context_code[0]

    # Get descriptions
    section_desc = CPC_TITLES.get(section, "")
    class_desc = CPC_TITLES.get(context_code, "")

    # Construct hierarchical text
    # If class description is available, append it to section description
    parts = [section_desc]
    if class_desc:
        parts.append(class_desc)

    # Join with separator and clean up
    full_text = "; ".join([p for p in parts if p])
    return full_text


def create_context_map(load_cached_data=True):
    """
    Generates or loads a mapping of CPC context codes to their textual descriptions.

    Args:
        load_cached_data (bool): If True, attempts to load from cache first.

    Returns:
        pd.DataFrame: DataFrame with columns ['context', 'context_text'].
    """
    cache_path = Config.context_map_path

    # 1. Try to load from cache
    if load_cached_data and os.path.exists(cache_path):
        print(f"Loading context map from cache: {cache_path}")
        try:
            return pd.read_parquet(cache_path)
        except Exception as e:
            print(f"Failed to load cache: {e}. Regenerating...")

    # 2. Generate from scratch
    print("Generating context map from metadata...")

    # Load all unique contexts from Train, Val, and Test
    # We use the metadata files defined in Config
    contexts = set()

    for file_path in [Config.train_file, Config.val_file, Config.test_file]:
        if os.path.exists(file_path):
            df = pd.read_csv(file_path)
            if "context" in df.columns:
                contexts.update(df["context"].unique().tolist())

    # Create mapping
    data = []
    for ctx in sorted(list(contexts)):
        text = get_cpc_text(ctx)
        data.append({"context": ctx, "context_text": text})

    df_map = pd.DataFrame(data)

    # 3. Save to cache
    os.makedirs(os.path.dirname(cache_path), exist_ok=True)
    df_map.to_parquet(cache_path, index=False)
    print(f"Context map saved to {cache_path}")

    return df_map
