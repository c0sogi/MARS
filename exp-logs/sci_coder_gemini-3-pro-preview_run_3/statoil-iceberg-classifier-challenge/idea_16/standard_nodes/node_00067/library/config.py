import os
import torch


class Config:
    """
    Configuration for the Spatially-Regularized Selective SE-CNN solution.
    Defines file paths, hyperparameters, and constants.
    """

    # --------------------------------------------------------------------------
    # Reproducibility
    # --------------------------------------------------------------------------
    SEED = 42

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for this specific experiment (Idea 16)
    WORK_DIR = "./working/idea_16"

    # Raw Data Files
    TRAIN_JSON = os.path.join(INPUT_DIR, "train.json")
    TEST_JSON = os.path.join(INPUT_DIR, "test.json")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Files (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output Paths
    SUBMISSION_PATH = os.path.join(WORK_DIR, "submission.csv")
    CHECKPOINT_DIR = os.path.join(WORK_DIR, "checkpoints")
    CACHE_DIR = os.path.join(WORK_DIR, "cache")

    # --------------------------------------------------------------------------
    # Data Parameters
    # --------------------------------------------------------------------------
    IMG_HEIGHT = 75
    IMG_WIDTH = 75
    # Input Channels: Band 1 (HH), Band 2 (HV), Average ((HH+HV)/2)
    IN_CHANNELS = 3

    # --------------------------------------------------------------------------
    # Model Hyperparameters
    # --------------------------------------------------------------------------
    # Architecture: Custom 4-Stage CNN
    # Width Strategy: Early expansion to preserve texture
    CHANNEL_SIZES = [64, 128, 128, 128]

    # Regularization
    # Spatial Dropout applied within convolutional blocks
    SPATIAL_DROPOUT_RATE = 0.1
    # Dropout applied in the classification head
    HEAD_DROPOUT_RATE = 0.5

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    NUM_FOLDS = 5
    BATCH_SIZE = 32
    NUM_EPOCHS = 100  # Max epochs, controlled by Early Stopping
    LEARNING_RATE = 1e-3  # Constant learning rate for Adam
    WEIGHT_DECAY = 1e-4  # L2 Regularization
    PATIENCE = 15  # Early Stopping patience

    # --------------------------------------------------------------------------
    # Compute & Debugging
    # --------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Number of dataloader workers

    # Debugging flags to control dataset size
    DEBUG = False
    DEBUG_SAMPLES = 100  # Number of samples to use if DEBUG is True

    @classmethod
    def create_directories(cls):
        """Creates necessary output directories if they don't exist."""
        os.makedirs(cls.WORK_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)


# Automatically create directories when config is imported
Config.create_directories()
