import os
import random
import numpy as np
import torch


class Config:
    """
    Central configuration for the Ensembled Robust Micro-ResNet (ERM-ResNet) solution.
    Stores all hyperparameters, file paths, and execution settings.
    """

    # -------------------------------------------------------------------------
    # General Settings
    # -------------------------------------------------------------------------
    PROJECT_NAME = "Iceberg_Classifier_Idea_11_SimpleCNN"
    SEED = 42
    DEBUG = False  # Flag to reduce dataset/epochs for testing

    # -------------------------------------------------------------------------
    # Directories & Paths
    # -------------------------------------------------------------------------
    # Input Data (Read-Only)
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working Directory (Write Allowed)
    # Stores checkpoints, logs, and cache
    WORKING_DIR = "./working/idea_11"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Checkpoint Directory
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)

    # Raw Data Files
    TRAIN_JSON = os.path.join(INPUT_DIR, "train.json")
    TEST_JSON = os.path.join(INPUT_DIR, "test.json")

    # Metadata Files (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Submission Output
    SUBMISSION_PATH = os.path.join(WORKING_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Caching Paths (for deterministic data processing)
    # -------------------------------------------------------------------------
    # These paths are used by the Dataset module to store/load processed tensors
    CACHE_TRAIN_X = os.path.join(WORKING_DIR, "X_train_v11.npy")
    CACHE_TRAIN_Y = os.path.join(WORKING_DIR, "y_train_v11.npy")
    CACHE_TRAIN_ANGLE = os.path.join(WORKING_DIR, "angle_train_v11.npy")

    CACHE_VAL_X = os.path.join(WORKING_DIR, "X_val_v11.npy")
    CACHE_VAL_Y = os.path.join(WORKING_DIR, "y_val_v11.npy")
    CACHE_VAL_ANGLE = os.path.join(WORKING_DIR, "angle_val_v11.npy")

    CACHE_TEST_X = os.path.join(WORKING_DIR, "X_test_v11.npy")
    CACHE_TEST_IDS = os.path.join(WORKING_DIR, "ids_test_v11.npy")
    CACHE_TEST_ANGLE = os.path.join(WORKING_DIR, "angle_test_v11.npy")

    # -------------------------------------------------------------------------
    # Data Parameters
    # -------------------------------------------------------------------------
    IMAGE_SIZE = 75
    IN_CHANNELS = 3  # Band 1 (HH), Band 2 (HV), Average ((HH+HV)/2)

    # -------------------------------------------------------------------------
    # Model Architecture: SimpleCNN
    # -------------------------------------------------------------------------
    MODEL_NAME = "SimpleCNN"
    BASE_FILTERS = 64
    MAX_FILTERS = 128  # Strict width constraint to prevent overfitting
    USE_SE = False
    POOLING_TYPE = "max"  # Global Max Pooling to preserve peak signals
    DROPOUT_SPATIAL = 0.2
    DROPOUT_FC = 0.2  # Reduced to 0.2 (Cite solution_lesson_node_00019)

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    NUM_FOLDS = 5
    BATCH_SIZE = 32
    EPOCHS = 50
    LEARNING_RATE = 1e-3  # Constant learning rate
    WEIGHT_DECAY = 1e-4  # L2 Regularization
    PATIENCE = 10  # Early Stopping patience

    # -------------------------------------------------------------------------
    # Compute Configuration
    # -------------------------------------------------------------------------
    NUM_WORKERS = 4
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    @classmethod
    def setup(cls, debug=False, batch_size=None, epochs=None):
        """
        Configure the Config class at runtime.

        Args:
            debug (bool): If True, enables debug mode (fewer epochs, smaller data).
            batch_size (int, optional): Override batch size.
            epochs (int, optional): Override number of epochs.
        """
        if debug:
            cls.DEBUG = True
            cls.EPOCHS = 2
            cls.NUM_FOLDS = 2  # Run fewer folds to save time
            cls.BATCH_SIZE = 16
            print(f"[{cls.PROJECT_NAME}] Debug mode enabled.")

        if batch_size is not None:
            cls.BATCH_SIZE = batch_size

        if epochs is not None:
            cls.EPOCHS = epochs

    @classmethod
    def print_summary(cls):
        """Prints a summary of the current configuration."""
        print(f"\n=== Configuration: {cls.PROJECT_NAME} ===")
        print(f"Device        : {cls.DEVICE}")
        print(f"Working Dir   : {cls.WORKING_DIR}")
        print(
            f"Model         : {cls.MODEL_NAME} (Filters: {cls.BASE_FILTERS}->{cls.MAX_FILTERS})"
        )
        print(
            f"Training      : {cls.EPOCHS} Epochs, BS={cls.BATCH_SIZE}, LR={cls.LEARNING_RATE}"
        )
        print(
            f"Regularization: WD={cls.WEIGHT_DECAY}, Drop={cls.DROPOUT_SPATIAL}/{cls.DROPOUT_FC}"
        )
        print(f"Debug Mode    : {cls.DEBUG}")
        print("============================================\n")


def set_seed(seed=42):
    """
    Sets random seeds for reproducibility across Python, NumPy, and PyTorch.

    Args:
        seed (int): The seed value to use.
    """
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)

    # Ensure deterministic behavior for cuDNN
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False

    os.environ["PYTHONHASHSEED"] = str(seed)
    print(f"Random seed set to {seed}")
