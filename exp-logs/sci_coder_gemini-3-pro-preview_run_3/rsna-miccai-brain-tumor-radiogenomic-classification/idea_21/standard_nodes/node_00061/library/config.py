import os
import torch


class Config:
    """
    Central configuration for the Modality-Grouped Stabilized High-Density (MG-SHD) Network pipeline.
    Defines hyperparameters, file paths, and environment settings.
    """

    # ==========================================
    # Reproducibility & Hardware
    # ==========================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Adjust based on CPU availability (12 vCPUs available)

    # ==========================================
    # File Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata Paths (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.parquet")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.parquet")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.parquet")

    # Output & Cache Paths
    WORKING_DIR = "./working"
    # Specific cache directory for this idea iteration
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_21")

    # Submission Paths
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Data Preprocessing
    # ==========================================
    IMG_SIZE = 224
    NUM_SLICES = 32  # Number of slices to sample per modality
    NUM_MODALITIES = 4  # FLAIR, T1w, T1wCE, T2w

    # Total input channels = 32 slices * 4 modalities = 128
    IN_CHANNELS = NUM_SLICES * NUM_MODALITIES

    # ==========================================
    # Model Architecture
    # ==========================================
    MODEL_NAME = "efficientnet_b0"
    # Stochastic Depth rate for regularization
    DROP_PATH_RATE = 0.2

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 16
    LEARNING_RATE = 1e-4
    EPOCHS = 15

    # ==========================================
    # Debugging / Development
    # ==========================================
    # If True, limits dataset size for rapid prototyping
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 20

    @classmethod
    def setup(cls):
        """
        Ensures that necessary writable directories exist.
        Should be called or run upon module import.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Automatically setup directories when config is imported
Config.setup()
