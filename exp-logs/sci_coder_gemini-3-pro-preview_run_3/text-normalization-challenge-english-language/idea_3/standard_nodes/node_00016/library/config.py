import os
import torch
import random
import numpy as np


class Config:
    """
    Global configuration for the Text Normalization pipeline.
    Supports a Hybrid Neuro-Symbolic architecture with:
    1. Symbolic Memory (N-gram lookup)
    2. Heuristic Routing
    3. Transformer-based Character Transduction
    """

    # ==========================================
    # Global Settings & Reproducibility
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging/testing
    DEBUG_SIZE = 50000  # Number of samples to use when DEBUG is True

    # ==========================================
    # File Paths
    # ==========================================
    # Input Directories (Read-Only)
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata Files (Parquet format, generated by previous steps)
    TRAIN_DATA_PATH = os.path.join(METADATA_DIR, "train.parquet")
    VAL_DATA_PATH = os.path.join(METADATA_DIR, "val.parquet")
    TEST_DATA_PATH = os.path.join(METADATA_DIR, "test.parquet")

    # Working Directory (Read/Write)
    # Used for caching processed data, stats, and model checkpoints
    WORKING_DIR = "./working/idea_3"

    # Submission Output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Model Checkpoint
    MODEL_PATH = os.path.join(WORKING_DIR, "transformer_best.pt")

    # Cache Directories
    # We separate stats (symbolic) and processed tensors (neural)
    STATS_CACHE_DIR = os.path.join(WORKING_DIR, "stats")
    PROCESSED_DATA_DIR = os.path.join(WORKING_DIR, "processed")

    # ==========================================
    # Symbolic Model Configuration (Stage 1)
    # ==========================================
    # Hierarchy of N-grams to check for exact matches
    # Priority: Trigram -> Left Bigram -> Right Bigram -> Unigram
    SYMBOLIC_ORDERS = ["trigram", "bigram_left", "bigram_right", "unigram"]

    # ==========================================
    # Neural Model Data Configuration (Stage 3)
    # ==========================================
    # Filtering criteria for the "Hard" dataset used to train the Transformer
    # We exclude 'easy' tokens to focus the neural model on complex cases.
    # Safe classes are usually handled by identity or simple rules if not found in symbolic memory.
    SAFE_CLASSES = {"PLAIN", "PUNCT"}

    # Input Context Formatting: [prev] <SEP> [target] <SEP> [next]
    CONTEXT_WINDOW = 1  # Number of tokens to the left and right to include

    # Sequence Lengths
    MAX_CHAR_LEN = 128  # Maximum length of character sequence (input/output)

    # Special Tokens for Character Tokenizer
    TOKEN_PAD = "<pad>"
    TOKEN_SOS = "<sos>"
    TOKEN_EOS = "<eos>"
    TOKEN_UNK = "<unk>"
    TOKEN_SEP = "<sep>"  # Separator for context

    SPECIAL_TOKENS = [TOKEN_PAD, TOKEN_SOS, TOKEN_EOS, TOKEN_UNK, TOKEN_SEP]

    # ==========================================
    # Transformer Architecture
    # ==========================================
    # Designed for character-level transduction
    D_MODEL = 256
    NHEAD = 4
    NUM_ENCODER_LAYERS = 6
    NUM_DECODER_LAYERS = 6
    DIM_FEEDFORWARD = 1024
    DROPOUT = 0.1

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    BATCH_SIZE = 128  # Reduced to fit available GPU memory
    NUM_WORKERS = 4

    LEARNING_RATE = 2e-4
    WEIGHT_DECAY = 0.01

    EPOCHS = 15  # Total training epochs
    WARMUP_RATIO = 0.1  # Linear warmup for first 10% of training steps

    LABEL_SMOOTHING = 0.1  # Regularization to prevent overconfidence
    GRAD_CLIP = 1.0  # Gradient clipping norm

    EARLY_STOPPING_PATIENCE = 3  # Stop if validation loss doesn't improve

    # ==========================================
    # Utility Methods
    # ==========================================
    @classmethod
    def setup(cls):
        """
        Initialize the environment:
        1. Create necessary directories.
        2. Set random seeds for full reproducibility.
        """
        # Create directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.STATS_CACHE_DIR, exist_ok=True)
        os.makedirs(cls.PROCESSED_DATA_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)

        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(cls.SEED)
            # Deterministic algorithms
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

        print(f"Configuration initialized.")
        print(f"Device: {cls.DEVICE}")
        print(f"Working Directory: {cls.WORKING_DIR}")
        print(f"Debug Mode: {cls.DEBUG}")
