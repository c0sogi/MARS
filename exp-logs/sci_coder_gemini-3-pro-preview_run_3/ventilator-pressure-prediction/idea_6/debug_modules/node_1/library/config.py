import os
import torch
import numpy as np
import random


def seed_everything(seed=42):
    """
    Sets the random seed for reproducibility across Python, NumPy, and PyTorch.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed(seed)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False


class Config:
    """
    Global configuration for the Pyramidal Context-Aware Hybrid Network (PCA-Net) pipeline.
    """

    # ==========================================
    # File Paths & Directories
    # ==========================================
    # Input Metadata (Pre-split)
    INPUT_DIR = "./metadata"
    TRAIN_CSV = os.path.join(INPUT_DIR, "train.csv")
    VAL_CSV = os.path.join(INPUT_DIR, "validation.csv")
    TEST_CSV = os.path.join(INPUT_DIR, "test.csv")

    # Working Directory (Cache)
    WORKING_DIR = "./working/idea_6"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Submission
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Model Checkpoint
    MODEL_PATH = os.path.join(WORKING_DIR, "model_best.pth")

    # ==========================================
    # Data Configuration
    # ==========================================
    SEED = 42
    NUM_WORKERS = 4

    # Column Definitions
    COL_ID = "id"
    COL_BREATH_ID = "breath_id"
    COL_TARGET = "pressure"

    # Unified Feature List
    # These features must be generated by the dataset class in this exact order.
    FEATURES = [
        "time_step",  # Temporal context
        "u_in",  # Control input (Proportional)
        "u_out",  # Phase indicator
        "R",  # Lung Resistance (Context)
        "C",  # Lung Compliance (Context)
        "u_in_cumsum",  # Integral proxy (Volume)
        "u_in_diff1",  # Derivative proxy (Velocity)
        "u_in_diff2",  # Derivative proxy (Acceleration)
        "R_u_in",  # Physics interaction: Resistive Pressure (Flow * R)
        "vol_C",  # Physics interaction: Elastic Pressure (Volume / C)
    ]

    INPUT_DIM = len(FEATURES)
    SEQ_LEN = 80  # Fixed sequence length for breaths in this dataset

    # ==========================================
    # Model Architecture (PCA-Net)
    # ==========================================
    # Pyramidal TCN Branch
    TCN_CHANNELS = [64, 128, 256, 512]  # Doubling channels with depth
    TCN_KERNEL_SIZE = 3
    TCN_DROPOUT = 0.1

    # Bidirectional LSTM Branch
    LSTM_HIDDEN = 256
    LSTM_LAYERS = 2
    LSTM_DROPOUT = 0.1

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    # Batch size set to 128 to prioritize generalization over throughput
    BATCH_SIZE = 128

    # Optimization
    EPOCHS = 150
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Scheduler
    SCHEDULER_PATIENCE = 5
    SCHEDULER_FACTOR = 0.5
    EARLY_STOPPING_PATIENCE = 15

    # Hardware
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @staticmethod
    def print_config():
        """Prints the current configuration."""
        print("=" * 30)
        print("CONFIG")
        print("=" * 30)
        print(f"Device: {Config.DEVICE}")
        print(f"Batch Size: {Config.BATCH_SIZE}")
        print(f"Input Features: {Config.FEATURES}")
        print(f"Input Dim: {Config.INPUT_DIM}")
        print(f"TCN Channels: {Config.TCN_CHANNELS}")
        print(f"LSTM Hidden: {Config.LSTM_HIDDEN}")
        print("=" * 30)
