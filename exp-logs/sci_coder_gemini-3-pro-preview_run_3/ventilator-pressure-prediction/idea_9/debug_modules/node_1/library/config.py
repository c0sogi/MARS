import os
import torch


class Config:
    """
    Central configuration module for the Robust Pyramidal Context-Aware Network (RPC-Net).
    Synchronizes hyperparameters, file paths, and feature definitions across the pipeline.
    """

    # -------------------------------------------------------------------------
    # General Setup
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    NUM_WORKERS = 4

    # -------------------------------------------------------------------------
    # Directories and Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_9"
    OUTPUT_DIR = "./submission"

    # Input Data (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "validation.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Cache Files (Numpy format for fast loading)
    # These store the preprocessed feature matrices and targets
    TRAIN_X_CACHE = os.path.join(WORKING_DIR, "train_x.npy")
    TRAIN_Y_CACHE = os.path.join(WORKING_DIR, "train_y.npy")
    TRAIN_U_OUT_CACHE = os.path.join(WORKING_DIR, "train_u_out.npy")

    VAL_X_CACHE = os.path.join(WORKING_DIR, "val_x.npy")
    VAL_Y_CACHE = os.path.join(WORKING_DIR, "val_y.npy")
    VAL_U_OUT_CACHE = os.path.join(WORKING_DIR, "val_u_out.npy")

    TEST_X_CACHE = os.path.join(WORKING_DIR, "test_x.npy")
    TEST_U_OUT_CACHE = os.path.join(WORKING_DIR, "test_u_out.npy")

    # Scaler State (RobustScaler statistics)
    SCALER_CACHE = os.path.join(WORKING_DIR, "scaler_stats.npz")

    # Model Artifacts
    MODEL_CHECKPOINT = os.path.join(WORKING_DIR, "model.pth")
    SUBMISSION_FILE = os.path.join(OUTPUT_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Pipeline Configuration
    # -------------------------------------------------------------------------
    SEQ_LEN = 80  # Fixed breath length in the dataset

    # Feature Engineering Strategy:
    # 1. Dynamic PID: u_in (P), u_in_cumsum (I), u_in_diff (D)
    # 2. Physics Interactions: R*u_in (Resistive), V/C (Elastic)
    # 3. Context: Time, Lung Attributes
    FEATURE_LIST = [
        "time_step",
        "u_in",
        "u_out",
        "R",
        "C",
        "u_in_cumsum",  # Integral proxy (Volume)
        "u_in_diff1",  # Derivative proxy (Flow Acceleration)
        "u_in_diff2",  # Second Derivative
        "u_in_lag1",  # Temporal context
        "u_in_lag2",  # Temporal context
        "u_in_lead1",  # Lookahead context (valid in bidirectional offline processing)
        "u_in_lead2",  # Lookahead context
        "R_u_in",  # Interaction: Resistance * Flow
        "vol_C_ratio",  # Interaction: Volume / Compliance
    ]

    NUM_FEATURES = len(FEATURE_LIST)
    USE_ROBUST_SCALER = True  # Uses Median/IQR to handle valve outliers

    # -------------------------------------------------------------------------
    # Model Hyperparameters (RPC-Net)
    # -------------------------------------------------------------------------
    # Training Regime
    BATCH_SIZE = 128  # Strategy: Small batch size for gradient noise/regularization
    EPOCHS = 80  # Strategy: Long training for hybrid convergence
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2
    PATIENCE = 15  # Early stopping patience
    MAX_GRAD_NORM = 1000  # Gradient clipping

    # Branch 1: Pyramidal Wide-Kernel TCN (Resistive Stream)
    TCN_KERNEL_SIZE = 7  # Strategy: Wide kernel for smoothing
    TCN_CHANNELS = [64, 128, 256, 512]  # Strategy: Pyramidal scaling
    TCN_DROPOUT = 0.1

    # Branch 2: High-Capacity LSTM (Elastic Stream)
    LSTM_HIDDEN_SIZE = 512  # Strategy: High capacity for integration
    LSTM_LAYERS = 3
    LSTM_BIDIRECTIONAL = True
    LSTM_DROPOUT = 0.1

    # Fusion Head
    FC_HIDDEN_SIZE = 256

    # -------------------------------------------------------------------------
    # Hardware
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def create_dirs(cls):
        """Ensures that working and output directories exist."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.OUTPUT_DIR, exist_ok=True)
