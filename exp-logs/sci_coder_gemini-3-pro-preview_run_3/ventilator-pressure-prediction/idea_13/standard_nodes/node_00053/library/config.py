import os
import torch


class Config:
    """
    Configuration for the Time-Agnostic Physically-Integrated Non-Causal Network (TAPIN-Net).

    Strategy Reference:
    - Idea 13: TAPIN-Net
    - Lesson 47: Time-Agnostic Learning (Excluding time_step)
    - Lesson 49: Numerical Integration (Area = sum(u_in * dt))
    - Lesson 18: Small Batch Size (128) for Gradient Noise
    - Lesson 49: Wide Kernel TCN (k=9)
    """

    # --------------------------------------------------------------------------
    # Paths & Directories
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Specific working directory for Idea 13
    WORKING_DIR = "./working/idea_13"

    # Input Files (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "validation.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Cache Files (For processed numpy arrays)
    # We use .npy format for efficiency and to avoid pickle security/compatibility issues
    TRAIN_CACHE_X = os.path.join(WORKING_DIR, "train_x.npy")
    TRAIN_CACHE_Y = os.path.join(WORKING_DIR, "train_y.npy")
    VAL_CACHE_X = os.path.join(WORKING_DIR, "val_x.npy")
    VAL_CACHE_Y = os.path.join(WORKING_DIR, "val_y.npy")
    TEST_CACHE_X = os.path.join(WORKING_DIR, "test_x.npy")
    TEST_IDS = os.path.join(WORKING_DIR, "test_ids.npy")

    # Scaler Statistics Path
    SCALER_STATS = os.path.join(WORKING_DIR, "scaler_stats.npz")

    # --------------------------------------------------------------------------
    # Feature Configuration
    # --------------------------------------------------------------------------
    # The model input features.
    # CRITICAL: 'time_step' is EXCLUDED to force learning of intrinsic physics (Lesson 47).
    # 'Area' is the physically accurate integral (Lesson 49).
    # Explicit Lookahead and Derivatives added (Cite Lesson 51, Lesson 52).
    MODEL_FEATURES = [
        "u_in",  # Control input: Valve opening
        "u_out",  # Control input: Expiratory valve state
        "R",  # Lung Attribute: Resistance
        "C",  # Lung Attribute: Compliance
        "dt",  # Numerical Integration: Time delta
        "Area",  # Numerical Integration: Accurate Volume
        "u_in_diff",  # Backward Derivative
        "u_in_next1",  # Lookahead 1 (Cite Lesson 51)
        "u_in_next2",  # Lookahead 2
        "u_in_diff_next1",  # Forward Derivative 1 (Cite Lesson 52)
        "u_in_diff_next2",  # Forward Derivative 2
        "R_u_in",  # Interaction: Resistive pressure proxy
        "Area_C",  # Interaction: Elastic pressure proxy
    ]

    # Input dimension for the model
    INPUT_DIM = len(MODEL_FEATURES)

    # --------------------------------------------------------------------------
    # Model Hyperparameters
    # --------------------------------------------------------------------------
    # Branch 1: Non-Causal Dense TCN (Resistive Stream)
    # Using Dense Convolutions (dilation=1) as per Lesson 52
    TCN_KERNEL_SIZE = 7
    TCN_CHANNELS = [64, 128, 256, 512]  # Pyramidal Scaling (Lesson 24)
    TCN_DROPOUT = 0.1

    # Branch 2: High-Capacity Bidirectional LSTM (Elastic Stream/Integrator)
    LSTM_HIDDEN_SIZE = 512  # High capacity for numerical integration (Lesson 32)
    LSTM_LAYERS = 3
    LSTM_BIDIRECTIONAL = True

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    SEED = 42
    EPOCHS = 80  # Extended training budget for hybrid convergence (Lesson 39)
    BATCH_SIZE = (
        128  # Small batch size for regularization via gradient noise (Lesson 18)
    )
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2
    PATIENCE = 15  # Early stopping patience
    NUM_WORKERS = 4  # DataLoader workers

    # Compute Device
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Initialize the working directory.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
