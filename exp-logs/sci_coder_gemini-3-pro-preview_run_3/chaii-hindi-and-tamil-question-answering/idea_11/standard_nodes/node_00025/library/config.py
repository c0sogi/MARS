import os
import torch


class Config:
    """
    Central configuration for the QA pipeline.
    Includes paths, model parameters, and training hyperparameters.
    """

    # ==========================================
    # General Settings
    # ==========================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    DEBUG = False  # Set to True to run on a small subset for debugging

    # ==========================================
    # Directory Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_11"
    SUBMISSION_DIR = "./submission"

    # Input Metadata Files (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Directories (Created by setup)
    # TAPT (Task-Adaptive Pretraining) Artifacts
    TAPT_CACHE_DIR = os.path.join(WORKING_DIR, "tapt_cache")
    TAPT_MODEL_DIR = os.path.join(WORKING_DIR, "tapt_model_finetuned")

    # QA (Question Answering) Artifacts
    QA_CACHE_DIR = os.path.join(WORKING_DIR, "qa_cache")
    QA_MODEL_DIR = os.path.join(WORKING_DIR, "qa_models")

    # Final Submission
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Model Architecture
    # ==========================================
    MODEL_NAME = "xlm-roberta-base"
    TOKENIZER_NAME = "xlm-roberta-base"

    # ==========================================
    # Data Processing (Sliding Window)
    # ==========================================
    MAX_LEN = 384
    DOC_STRIDE = 128

    # ==========================================
    # Training Hyperparameters (QA Fine-tuning)
    # ==========================================
    BATCH_SIZE = 16
    EPOCHS = 10
    LEARNING_RATE = 2e-5
    WEIGHT_DECAY = 0.01
    N_FOLDS = 3

    # ==========================================
    # TAPT Hyperparameters (Masked Language Modeling)
    # ==========================================
    TAPT_BATCH_SIZE = 8
    TAPT_EPOCHS = 10  # Sufficient epochs for small dataset adaptation
    TAPT_LEARNING_RATE = 2e-5
    MLM_PROBABILITY = 0.15

    @classmethod
    def setup(cls):
        """
        Creates the necessary directory structure for the experiment.
        Should be called at the start of execution.
        """
        dirs = [
            cls.WORKING_DIR,
            cls.SUBMISSION_DIR,
            cls.TAPT_CACHE_DIR,
            cls.TAPT_MODEL_DIR,
            cls.QA_CACHE_DIR,
            cls.QA_MODEL_DIR,
        ]

        for d in dirs:
            os.makedirs(d, exist_ok=True)

        print(f"Directories initialized at {cls.WORKING_DIR}")

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print("\n=== Configuration ===")
        print(f"Device: {cls.DEVICE}")
        print(f"Model: {cls.MODEL_NAME}")
        print(f"Window: Max={cls.MAX_LEN}, Stride={cls.DOC_STRIDE}")
        print(
            f"Training: Batch={cls.BATCH_SIZE}, Epochs={cls.EPOCHS}, Folds={cls.N_FOLDS}"
        )
        print(f"TAPT: Epochs={cls.TAPT_EPOCHS}")
        print("=====================\n")
