import os
import random
import numpy as np
import torch


class Config:
    """
    Global configuration for the Dilated Residual Denoising Network (DRDN) project.
    Contains file paths, model hyperparameters, and training settings.
    """

    # -------------------------------------------------------------------------
    # Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_3"
    SUBMISSION_DIR = "./submission"

    # Metadata files (generated by the metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output paths for artifacts
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "drdn_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Processing Parameters
    # -------------------------------------------------------------------------
    # Patch extraction settings for training
    PATCH_SIZE = 64
    PATCH_STRIDE = 32  # Overlap to increase training samples

    # Data normalization ranges
    INTENSITY_MIN = 0.0
    INTENSITY_MAX = 1.0

    # -------------------------------------------------------------------------
    # Model Architecture Hyperparameters
    # -------------------------------------------------------------------------
    IN_CHANNELS = 1
    OUT_CHANNELS = 1  # The model predicts the noise residual
    HIDDEN_CHANNELS = 64
    KERNEL_SIZE = 3

    # Dilation rates for the central block to expand receptive field
    # Structure: Progressive dilation to capture context, then contracting
    DILATION_RATES = [1, 2, 4, 8, 4, 2, 1]

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 64
    NUM_EPOCHS = 50
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-5
    EARLY_STOPPING_PATIENCE = 8

    # -------------------------------------------------------------------------
    # Compute Environment
    # -------------------------------------------------------------------------
    NUM_WORKERS = 4  # Optimized for 12 vCPUs
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def create_directories(cls):
        """
        Ensures that the working and submission directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


def seed_everything(seed=Config.SEED):
    """
    Sets the random seed for reproducibility across Python, NumPy, and PyTorch.

    Args:
        seed (int): The seed value to use. Defaults to Config.SEED.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)
        # Ensure deterministic behavior for cuDNN
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False
