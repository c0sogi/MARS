import os
import torch


class Config:
    """
    Configuration class for the Multi-View Semantic Alignment with Contextual Smoothing (MVSS) pipeline.
    Stores all constants, paths, and hyperparameters required for data processing,
    model fine-tuning, feature extraction, and regression.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    DEBUG = (
        False  # Set to True to run the pipeline on a small subset of data for testing
    )
    DEBUG_SAMPLE_SIZE = 5000  # Number of notebooks to use when DEBUG is True

    # =========================================================================
    # Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_5"
    SUBMISSION_DIR = "./submission"

    # Ensure necessary output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata Files (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Submission File
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache Files (Parquet format for intermediate features)
    TRAIN_FEATURES_PATH = os.path.join(WORKING_DIR, "train_features.parquet")
    VAL_FEATURES_PATH = os.path.join(WORKING_DIR, "val_features.parquet")
    TEST_FEATURES_PATH = os.path.join(WORKING_DIR, "test_features.parquet")

    # =========================================================================
    # Model Configuration (Dual-Backbone)
    # =========================================================================
    # We use two distinct backbones to capture both code syntax and natural language semantics
    MODEL_NAMES = [
        "microsoft/codebert-base",  # Code-View Backbone
        "sentence-transformers/all-mpnet-base-v2",  # Text-View Backbone
    ]

    # Paths to save/load the fine-tuned versions of the models
    MODEL_SAVE_PATHS = {}
    for name in MODEL_NAMES:
        MODEL_SAVE_PATHS[name] = os.path.join(
            WORKING_DIR, f"{name.replace('/', '_')}_finetuned"
        )
    del name

    # Tokenizer & DataLoader Settings
    MAX_LEN = 128
    TRAIN_BATCH_SIZE = 32
    VALID_BATCH_SIZE = 64
    NUM_WORKERS = 4

    # Hardware Configuration
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # =========================================================================
    # Training Configuration (Contrastive Fine-Tuning)
    # =========================================================================
    EPOCHS = 1
    LEARNING_RATE = 2e-5
    WEIGHT_DECAY = 0.01
    WARMUP_RATIO = 0.1
    SCHEDULER_TYPE = "linear"

    # =========================================================================
    # Feature Engineering Configuration
    # =========================================================================
    # Window size for 1D smoothing convolution on similarity matrices
    # Helps account for markdown cells describing blocks of code rather than single lines
    SMOOTHING_WINDOW = 3

    # =========================================================================
    # Regressor Configuration (LightGBM)
    # =========================================================================
    LGBM_PARAMS = {
        "objective": "regression",
        "metric": "rmse",
        "boosting_type": "gbdt",
        "learning_rate": 0.05,
        "num_leaves": 64,
        "feature_fraction": 0.9,
        "bagging_fraction": 0.8,
        "bagging_freq": 5,
        "n_estimators": 5000,
        "early_stopping_rounds": 100,
        "verbose": -1,
        "n_jobs": -1,
        "random_state": SEED,
        "force_col_wise": True,
    }
