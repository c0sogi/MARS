import os


class Config:
    """
    Global configuration for the Domain-Adaptive Semantic Alignment Regressor (DASAR).
    """

    # --------------------------------------------------------------------------
    # Reproducibility
    # --------------------------------------------------------------------------
    SEED = 42

    # --------------------------------------------------------------------------
    # Directories
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_4"
    SUBMISSION_DIR = "./submission"

    # Create output directories if they don't exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    # Metadata generated by the analysis script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Cache files for processed features (Parquet format)
    TRAIN_FEATURES_PATH = os.path.join(WORKING_DIR, "train_features.parquet")
    VAL_FEATURES_PATH = os.path.join(WORKING_DIR, "val_features.parquet")
    TEST_FEATURES_PATH = os.path.join(WORKING_DIR, "test_features.parquet")

    # Path to save/load the fine-tuned Sentence Transformer
    FINE_TUNED_MODEL_PATH = os.path.join(WORKING_DIR, "fine_tuned_backbone")

    # Submission output
    SUBMISSION_FILE_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Stage 1: Domain-Adaptive Semantic Backbone (Sentence Transformer)
    # --------------------------------------------------------------------------
    PRETRAINED_MODEL_NAME = "all-MiniLM-L6-v2"
    MAX_SEQ_LENGTH = 128

    # Fine-tuning hyperparameters
    BACKBONE_BATCH_SIZE = 32
    BACKBONE_EPOCHS = 1
    BACKBONE_LEARNING_RATE = 2e-5

    # --------------------------------------------------------------------------
    # Stage 2: Explicit Alignment Regressor (LightGBM)
    # --------------------------------------------------------------------------
    # Features to be used for regression
    FEATURES = [
        "best_match_loc",  # Spatial Alignment: Index of code cell with max similarity
        "center_of_mass",  # Spatial Alignment: Weighted average index
        "sim_max",  # Signal Strength: Max similarity score
        "sim_mean",  # Signal Strength: Mean similarity score
        "n_code",  # Global Context: Total number of code cells
        "md_len",  # Global Context: Length of the markdown cell
    ]

    # LightGBM Hyperparameters
    LGBM_PARAMS = {
        "objective": "regression",
        "metric": "rmse",
        "boosting_type": "gbdt",
        "learning_rate": 0.05,
        "num_leaves": 31,
        "feature_fraction": 0.9,
        "bagging_fraction": 0.8,
        "bagging_freq": 5,
        "verbosity": -1,
        "n_jobs": -1,
        "seed": SEED,
        "force_col_wise": True,
    }

    # Training control
    NUM_BOOST_ROUND = 2000
    EARLY_STOPPING_ROUNDS = 50
    VERBOSE_EVAL = 100

    # --------------------------------------------------------------------------
    # Debugging / Development
    # --------------------------------------------------------------------------
    # If True, runs the pipeline on a small subset of data
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 1000
