import os
import torch


class Config:
    """
    Configuration class for the Deep Sequence-Aware Position Regressor pipeline.
    """

    # =========================================================================
    # Directories and Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_2"
    SUBMISSION_DIR = "./submission"

    # Ensure output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata Paths (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output Paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "lgbm_model.txt")

    # Cache Paths for Preprocessed Data (Parquet format)
    TRAIN_CACHE_PATH = os.path.join(WORKING_DIR, "train_features.parquet")
    VAL_CACHE_PATH = os.path.join(WORKING_DIR, "val_features.parquet")
    TEST_CACHE_PATH = os.path.join(WORKING_DIR, "test_features.parquet")

    # Paths for Tabular Regression Features
    TRAIN_TABULAR_PATH = os.path.join(WORKING_DIR, "train_tabular.parquet")
    VAL_TABULAR_PATH = os.path.join(WORKING_DIR, "val_tabular.parquet")
    TEST_TABULAR_PATH = os.path.join(WORKING_DIR, "test_tabular.parquet")

    # =========================================================================
    # Model Hyperparameters
    # =========================================================================
    # Sentence Transformer backbone
    MODEL_NAME = "sentence-transformers/all-MiniLM-L6-v2"
    EMBED_DIM = 384

    # Transformer Encoder settings
    # MAX_SEQ_LEN defines the maximum number of code cells to include in the context.
    # Notebooks with more code cells will be truncated; those with fewer will be padded.
    MAX_SEQ_LEN = 128
    TRANSFORMER_LAYERS = 2
    TRANSFORMER_HEADS = 8
    DROPOUT = 0.1
    FORWARD_EXPANSION = 4  # Multiplier for feed-forward network inside transformer

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    SEED = 42
    BATCH_SIZE = 64
    LEARNING_RATE = 2e-4
    NUM_EPOCHS = 15
    PATIENCE = 3  # Early stopping patience
    WEIGHT_DECAY = 0.01
    WARMUP_RATIO = 0.1
    MAX_GRAD_NORM = 1.0

    # =========================================================================
    # Hardware and Environment
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Number of workers for DataLoader.
    # Set to 0 if debugging or if shared memory issues arise.
    NUM_WORKERS = 4

    @staticmethod
    def set_seed(seed=42):
        """
        Sets the random seed for reproducibility across random, numpy, and torch.

        Args:
            seed (int): The seed value to use. Defaults to 42.
        """
        import random
        import numpy as np

        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
