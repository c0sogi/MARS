import os
import json
import pandas as pd
import numpy as np
import torch
from torch.utils.data import Dataset
from sentence_transformers import InputExample
from library.config import Config


class FineTuningDataset(Dataset):
    """
    PyTorch Dataset for fine-tuning the Sentence Transformer backbone.
    Wraps the pairs generated by create_relaxed_pairs and yields InputExample objects.
    """

    def __init__(self, pairs_df: pd.DataFrame):
        """
        Args:
            pairs_df: DataFrame containing 'markdown' and 'code' columns.
        """
        self.pairs_df = pairs_df.reset_index(drop=True)

    def __len__(self):
        return len(self.pairs_df)

    def __getitem__(self, idx):
        row = self.pairs_df.iloc[idx]
        # InputExample is the expected format for Sentence Transformers
        # We provide the markdown text and the associated code text as a positive pair.
        return InputExample(texts=[str(row["markdown"]), str(row["code"])])


def read_notebook(file_path: str) -> dict:
    """
    Reads a notebook JSON file and returns a dictionary containing cell types and sources.

    Args:
        file_path: Relative path to the notebook JSON file.

    Returns:
        dict: A dictionary with keys 'cell_type' and 'source'.
              Returns empty dicts if file read fails.
    """
    full_path = os.path.join(Config.INPUT_DIR, file_path)
    try:
        with open(full_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        return data
    except Exception as e:
        # In case of read error, return empty structure to prevent pipeline crash
        return {"cell_type": {}, "source": {}}


def get_data_splits():
    """
    Loads the train, validation, and test metadata CSVs.

    Returns:
        tuple: (df_train, df_val, df_test)
    """
    df_train = pd.read_csv(Config.TRAIN_METADATA_PATH)
    df_val = pd.read_csv(Config.VAL_METADATA_PATH)
    df_test = pd.read_csv(Config.TEST_METADATA_PATH)
    return df_train, df_val, df_test


def create_relaxed_pairs(
    df_metadata: pd.DataFrame, load_cached_data: bool = True
) -> pd.DataFrame:
    """
    Generates (Markdown, Code) pairs for contrastive fine-tuning using the
    'Relaxed Proximity' strategy: pairing a markdown cell with its nearest
    subsequent code cell.

    Implements strict caching logic using Parquet.

    Args:
        df_metadata: DataFrame containing training metadata (must include 'id', 'cell_order', 'file_path').
        load_cached_data: If True, attempts to load from disk before computing.

    Returns:
        pd.DataFrame: DataFrame with columns ['markdown', 'code'].
    """
    # Ensure working directory exists
    os.makedirs(Config.WORKING_DIR, exist_ok=True)

    cache_path = os.path.join(Config.WORKING_DIR, "train_pairs_relaxed.parquet")

    # 1. Try to load from cache
    if load_cached_data and os.path.exists(cache_path):
        print(f"Loading cached pairs from {cache_path}")
        return pd.read_parquet(cache_path)

    print(
        f"Generating relaxed pairs from scratch (Target: {Config.NUM_FINE_TUNE_NOTEBOOKS} notebooks)..."
    )

    # 2. Compute from scratch
    # Limit to the configured number of notebooks for fine-tuning
    df_subset = df_metadata.head(Config.NUM_FINE_TUNE_NOTEBOOKS)

    markdown_texts = []
    code_texts = []

    # Iterate over notebooks
    for _, row in df_subset.iterrows():
        notebook_data = read_notebook(row["file_path"])

        # Parse cell order
        if isinstance(row["cell_order"], str):
            cell_order = row["cell_order"].split()
        else:
            continue

        cell_types = notebook_data.get("cell_type", {})
        sources = notebook_data.get("source", {})

        # Filter cells that exist in the JSON
        valid_order = [cid for cid in cell_order if cid in cell_types]

        # Identify code cells and their indices in the ordered list
        code_indices = [
            i for i, cid in enumerate(valid_order) if cell_types[cid] == "code"
        ]

        if not code_indices:
            continue

        # For each cell in the notebook
        for i, cell_id in enumerate(valid_order):
            c_type = cell_types[cell_id]

            if c_type == "markdown":
                # Find the nearest subsequent code cell
                # We look for the smallest code_index j such that j > i
                subsequent_code_indices = [idx for idx in code_indices if idx > i]

                if subsequent_code_indices:
                    # Pair with the immediate next code cell
                    target_idx = subsequent_code_indices[0]
                    target_id = valid_order[target_idx]

                    md_text = sources.get(cell_id, "").strip()
                    code_text = sources.get(target_id, "").strip()

                    # Only add non-empty pairs to improve training quality
                    if md_text and code_text:
                        markdown_texts.append(md_text)
                        code_texts.append(code_text)

    # Create DataFrame
    pairs_df = pd.DataFrame({"markdown": markdown_texts, "code": code_texts})

    # 3. Save to cache
    print(f"Saving {len(pairs_df)} pairs to {cache_path}")
    pairs_df.to_parquet(cache_path, index=False)

    return pairs_df
