    SUBMISSION_PATH = "./submission/submission.csv"

    # ==== Data Parameters ====
    # Image size: 1024x1024 to capture small findings like nodules
    IMAGE_SIZE = 1024

    # Number of workers for data loading
    NUM_WORKERS = 8

    # Dataset control for debugging
    # Set to < 1.0 to train on a subset (e.g., 0.1 for 10% of data)
    DATASET_FRACTION = 1.0

    # ==== Model Parameters ====
    # The dataset has 14 finding classes (0-13) + "No finding" (14).
    # Faster R-CNN requires Class 0 to be Background.
    # We map Dataset Classes 0-13 -> Model Classes 1-14.
    # Dataset Class 14 ("No finding") is treated as Background (no boxes).
    # Total Model Classes = 1 (Background) + 14 (Diseases) = 15.
    NUM_CLASSES = 15

