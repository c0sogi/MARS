import os


class Config:
    """
    Configuration for the Pizza Request Success Prediction Task.
    Implements settings for a Tri-View Stacking Ensemble (Lexical, Semantic, Behavioral).
    """

    # -------------------------------------------------------------------------
    # General Settings
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLES = 100  # Number of samples to use if DEBUG is True

    # -------------------------------------------------------------------------
    # Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_7"
    SUBMISSION_DIR = "./submission"

    # Ensure necessary output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    # Metadata Parquet files (Generated by the provided metadata script)
    TRAIN_PATH = os.path.join(METADATA_DIR, "train.parquet")
    VAL_PATH = os.path.join(METADATA_DIR, "val.parquet")
    TEST_PATH = os.path.join(METADATA_DIR, "test.parquet")

    # Output Submission File
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Columns
    # -------------------------------------------------------------------------
    ID_COL = "request_id"
    TARGET_COL = "requester_received_pizza"

    # Text Input (Using edit-aware text to avoid leakage)
    TEXT_COL = "request_text_edit_aware"

    # Behavioral Input (List of subreddits posted in)
    SUBREDDIT_COL = "requester_subreddits_at_request"

    # Numerical / Metadata Features
    # Strictly excluding '_at_retrieval' columns to prevent data leakage.
    NUMERICAL_COLS = [
        "requester_account_age_in_days_at_request",
        "requester_days_since_first_post_on_raop_at_request",
        "requester_number_of_comments_at_request",
        "requester_number_of_comments_in_raop_at_request",
        "requester_number_of_posts_at_request",
        "requester_number_of_posts_on_raop_at_request",
        "requester_number_of_subreddits_at_request",
        "requester_upvotes_minus_downvotes_at_request",
        "requester_upvotes_plus_downvotes_at_request",
        "unix_timestamp_of_request",  # Included for temporal feature extraction (hour, day)
    ]

    # -------------------------------------------------------------------------
    # Feature Extraction Hyperparameters
    # -------------------------------------------------------------------------
    # View 1: Lexical (Sparse TF-IDF on Request Text)
    LEXICAL_TFIDF_PARAMS = {
        "max_features": 3000,
        "ngram_range": (1, 2),
        "stop_words": "english",
        "sublinear_tf": True,
        "min_df": 2,
        "max_df": 0.95,
    }

    # View 2: Behavioral (Sparse TF-IDF on Subreddit History)
    # Treating the list of subreddits as a "bag of communities" document.
    BEHAVIORAL_TFIDF_PARAMS = {
        "max_features": 1000,
        "ngram_range": (1, 1),
        "stop_words": None,  # Subreddit names are not stopwords
        "binary": True,  # Presence matters more than frequency in this context
        "use_idf": True,
        "norm": "l2",
    }

    # View 3: Semantic (Dense Embeddings via SBERT)
    # Using a small, efficient model for frozen embeddings.
    SBERT_MODEL_NAME = "all-MiniLM-L6-v2"

    # -------------------------------------------------------------------------
    # Model Hyperparameters
    # -------------------------------------------------------------------------
    # Level 1: Base Learners (Random Forests)
    # Applied to Lexical, Semantic, and Behavioral views independently.
    # 'balanced' class_weight is critical for the ~25% positive class imbalance.
    RF_PARAMS = {
        "n_estimators": 300,
        "max_depth": None,
        "min_samples_split": 5,
        "min_samples_leaf": 2,
        "max_features": "sqrt",
        "class_weight": "balanced",
        "n_jobs": -1,
        "random_state": SEED,
        "verbose": 0,
    }

    # Level 2: Meta-Learner (Logistic Regression)
    # Stacking classifier taking probabilities from Level 1 models.
    META_LEARNER_PARAMS = {
        "C": 1.0,
        "penalty": "l2",
        "solver": "lbfgs",
        "random_state": SEED,
        "max_iter": 1000,
    }

    # Stacking Configuration
    N_FOLDS = 5  # Number of folds for Out-Of-Fold (OOF) prediction generation

    # -------------------------------------------------------------------------
    # Cache File Names
    # -------------------------------------------------------------------------
    # Standardized filenames for caching processed features in WORKING_DIR
    CACHE_FILES = {
        # Train
        "train_lexical": "X_train_lexical.npz",
        "train_semantic": "X_train_semantic.npy",
        "train_behavioral": "X_train_behavioral.npz",
        "train_meta": "X_train_meta.npy",
        "train_target": "y_train.npy",
        # Validation
        "val_lexical": "X_val_lexical.npz",
        "val_semantic": "X_val_semantic.npy",
        "val_behavioral": "X_val_behavioral.npz",
        "val_meta": "X_val_meta.npy",
        "val_target": "y_val.npy",
        # Test
        "test_lexical": "X_test_lexical.npz",
        "test_semantic": "X_test_semantic.npy",
        "test_behavioral": "X_test_behavioral.npz",
        "test_meta": "X_test_meta.npy",
        "test_ids": "test_ids.npy",
    }
