import os
import torch


class Config:
    """
    Configuration class for the Residual-Interaction Dual-Stream Network (RIDS-Net).
    Centralizes all hyperparameters, file paths, and settings.
    """

    # -------------------------------------------------------------------------
    # General Settings
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4  # Number of data loading workers

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the provided scripts
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Sample submission for format reference
    SAMPLE_SUBMISSION = os.path.join(INPUT_ROOT, "sample_submission.csv")

    # Output Directories
    # Specific directory for this idea iteration to avoid conflicts
    WORKING_DIR = "./working/idea_17"

    # Cache directory for processed data (e.g., .npy files)
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")

    # Checkpoint directory for saving model weights
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    BEST_MODEL_PATH = os.path.join(CHECKPOINT_DIR, "best_model.pth")

    # Submission directory
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    MODEL_NAME = "tf_efficientnet_b0"  # EfficientNet-B0 (Smaller, less overfitting)
    IMAGE_SIZE = 224  # Native resolution for EfficientNet-B0
    IN_CHANNELS = 1  # DICOM images are grayscale
    NUM_SLICES = 3  # Anchor slice + 2 boundary slices
    EMBED_DIM = 64  # Constrained dimension to prevent overfitting (Cite solution_lesson_node_00065)

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    EPOCHS = 30
    BATCH_SIZE = 32

    # Differential Learning Rates
    LR_BACKBONE = 1e-4  # Slower learning for the pre-trained backbone
    LR_HEAD = 1e-3  # Faster learning for the new MLP heads

    WEIGHT_DECAY = 1e-2
    T_MAX = EPOCHS  # For Cosine Annealing scheduler

    # -------------------------------------------------------------------------
    # Preprocessing & Feature Engineering
    # -------------------------------------------------------------------------
    # Scale relative time (Weeks) by this factor
    TIME_SCALER = 0.01

    # -------------------------------------------------------------------------
    # Metric & Post-processing
    # -------------------------------------------------------------------------
    # Metric constants
    MAX_ERROR_METRIC = 1000
    MIN_CONFIDENCE = 70  # Clipped sigma value

    @staticmethod
    def setup_directories():
        """Creates necessary working directories if they don't exist."""
        os.makedirs(Config.CACHE_DIR, exist_ok=True)
        os.makedirs(Config.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
