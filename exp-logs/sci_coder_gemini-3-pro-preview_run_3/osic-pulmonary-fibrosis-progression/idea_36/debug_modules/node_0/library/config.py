import os
import torch


class Config:
    """
    Configuration for the Unregularized Cascaded Output-Space Residual Network (UCOSR-Net).
    Centralizes all hyperparameters, file paths, and constants.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    IDEA_NAME = "idea_36"
    WORKING_DIR = os.path.join("./working", IDEA_NAME)

    # Debugging
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 50  # Number of samples to use when DEBUG is True

    # Device configuration
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4

    # =========================================================================
    # Data Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SUBMISSION_SAMPLE_CSV = os.path.join(INPUT_DIR, "sample_submission.csv")

    # DICOM Directories
    TRAIN_DICOM_DIR = os.path.join(INPUT_DIR, "train")
    TEST_DICOM_DIR = os.path.join(INPUT_DIR, "test")

    # =========================================================================
    # Preprocessing & Normalization
    # =========================================================================
    # Image Preprocessing (Lung Window)
    IMG_SIZE = 260
    WINDOW_LEVEL = -600
    WINDOW_WIDTH = 1500

    # Slice Selection
    NUM_SLICES = (
        3  # Anchor + 2 boundary slices (though model might use 1 or 3 channels)
    )

    # Tabular Feature Scaling
    # Relative time scaling factor (t_rel = (Weeks - Baseline) * SCALE)
    TIME_SCALE = 0.01

    # Target Normalization (FVC) - Derived from EDA
    # Mean: 2654.6528, Std: 801.7017
    TARGET_MEAN = 2654.6528
    TARGET_STD = 801.7017

    # Metric Constants
    METRIC_CLIP_SIGMA = 70.0
    METRIC_MAX_ERROR = 1000.0

    # =========================================================================
    # Model Architecture (UCOSR-Net)
    # =========================================================================
    BACKBONE_NAME = "tf_efficientnet_b2_ns"
    PRETRAINED = True

    # Dimensions
    # Inputs: Baseline FVC, Relative Time, Age, Sex, SmokingStatus (Ordinal)
    TABULAR_INPUT_DIM = 5
    CLINICAL_HIDDEN_DIM = 128
    CLINICAL_LATENT_DIM = 64

    # Visual Stream
    # EfficientNet B2 output features usually 1408, but we use GAP
    VISUAL_LATENT_DIM = 64  # Dimension to project visual features to before fusion

    # Dropout Settings
    # Explicitly set to 0.0 for the Visual Stream as per design (Unregularized)
    VISUAL_DROPOUT = 0.0

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    EPOCHS = 50
    BATCH_SIZE = 32

    # Optimization
    # Differential Learning Rates
    LR_BACKBONE = 1e-4
    LR_HEAD = 1e-3

    WEIGHT_DECAY = 1e-2

    # Scheduler (Cosine Annealing)
    T_MAX = EPOCHS
    ETA_MIN = 1e-6

    @classmethod
    def setup(cls):
        """
        Ensures necessary directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        print(f"Configuration setup complete. Working directory: {cls.WORKING_DIR}")
