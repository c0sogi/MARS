import os
import torch
import pandas as pd
import numpy as np
from torch.utils.data import DataLoader
from library.config import Config
from library.utils import seed_everything
from library.dataset import CatDogDataset
from library.models import build_model


def predict_with_tta(model, loader, device):
    """
    Generates predictions for a single model using Test Time Augmentation (TTA).
    TTA involves predicting on the original image and a horizontally flipped version,
    then averaging the resulting probabilities.

    Args:
        model (nn.Module): The trained PyTorch model.
        loader (DataLoader): DataLoader for the test set.
        device (torch.device): The computation device (CPU or CUDA).

    Returns:
        pd.DataFrame: A DataFrame containing 'id' and 'prob' columns.
    """
    model.eval()
    ids_all = []
    probs_all = []

    # Sigmoid for converting logits to probabilities
    sigmoid = torch.nn.Sigmoid()

    with torch.no_grad():
        for images, ids in loader:
            images = images.to(device)

            # 1. Forward pass: Original images
            logits_orig = model(images)
            probs_orig = sigmoid(logits_orig)

            # 2. Forward pass: Flipped images (Horizontal Flip)
            # Dims are (Batch, Channel, Height, Width), so we flip dim 3
            images_flipped = torch.flip(images, dims=[3])
            logits_flip = model(images_flipped)
            probs_flip = sigmoid(logits_flip)

            # 3. Average probabilities
            probs_avg = (probs_orig + probs_flip) / 2.0

            # Store results
            # Flatten to 1D array
            probs_all.extend(probs_avg.cpu().view(-1).numpy())
            ids_all.extend(ids.numpy())

    return pd.DataFrame({"id": ids_all, "prob": probs_all})


def run_ensemble():
    """
    Loads all trained models specified in Config.MODELS, generates predictions
    using TTA, and creates a final ensemble submission via simple averaging.
    """
    seed_everything(Config.SEED)
    device = torch.device(Config.DEVICE)

    print(f"Starting inference on device: {device}")

    # Prepare Test Loader
    # We use the test CSV generated by the metadata script
    test_dataset = CatDogDataset(Config.TEST_CSV, phase="test", debug=Config.DEBUG)
    test_loader = DataLoader(
        test_dataset,
        batch_size=Config.BATCH_SIZE,
        shuffle=False,
        num_workers=Config.NUM_WORKERS,
        pin_memory=True,
    )

    model_predictions = []

    # Iterate over each model architecture defined in the ensemble
    for model_name in Config.MODELS:
        print(f"Generating predictions for model: {model_name}")

        # Construct path to the best checkpoint
        checkpoint_path = os.path.join(Config.WORKING_DIR, f"{model_name}_best.pth")

        if not os.path.exists(checkpoint_path):
            print(
                f"Warning: Checkpoint not found at {checkpoint_path}. Skipping this model."
            )
            continue

        # Build model and load weights
        model = build_model(model_name, pretrained=False)
        model.load_state_dict(torch.load(checkpoint_path, map_location=device))
        model = model.to(device)

        # Get TTA predictions
        df_pred = predict_with_tta(model, test_loader, device)

        # Sort by ID to ensure alignment for averaging (though loader is sequential, this is safe)
        df_pred = df_pred.sort_values("id").reset_index(drop=True)

        model_predictions.append(df_pred["prob"].values)

        # Free memory
        del model
        torch.cuda.empty_cache()

    if not model_predictions:
        raise RuntimeError("No models were successfully loaded for inference.")

    # Perform Ensemble Averaging
    print(f"Ensembling predictions from {len(model_predictions)} models...")
    avg_probs = np.mean(model_predictions, axis=0)

    # Prepare Submission DataFrame
    # We take the IDs from the first prediction dataframe (all are sorted same way)
    submission_ids = test_dataset.df["id"].values

    # Ensure lengths match
    if len(submission_ids) != len(avg_probs):
        # Fallback to IDs from the prediction loop if dataset/loader mismatch occurred (unlikely)
        # But strictly, test_dataset.df is the source of truth for IDs.
        pass

    submission_df = pd.DataFrame({"id": submission_ids, "label": avg_probs})

    # Save Submission
    print(f"Saving submission to {Config.SUBMISSION_PATH}")
    submission_df.to_csv(Config.SUBMISSION_PATH, index=False)
    print("Inference completed successfully.")
