import os
import torch


class Config:
    """
    Centralized configuration for the Plant Image Categorization task.
    """

    # =========================================================================
    # System & Reproducibility
    # =========================================================================
    SEED = 42
    NUM_WORKERS = 12  # Utilizing the available 12 vCPUs
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # =========================================================================
    # File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the provided script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output directories
    WORKING_DIR = "./working"
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_1")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Model Hyperparameters
    # =========================================================================
    MODEL_NAME = "mobilenet_v3_large"
    NUM_CLASSES = 15501
    PRETRAINED = True

    # Input dimensions
    IMAGE_SIZE = 224

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    # Batch size of 256 is efficient for MobileNetV3 on A100 40GB
    BATCH_SIZE = 256

    # Training duration
    NUM_EPOCHS = 10

    # Optimization (AdamW + OneCycleLR)
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2

    # =========================================================================
    # Debugging & Development
    # =========================================================================
    # Set DEBUG to True to run on a small subset of data for quick pipeline verification
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 5000  # Number of samples to use when DEBUG is True

    @classmethod
    def setup(cls):
        """
        Creates necessary output directories for the project.
        Should be called at the start of the pipeline.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
