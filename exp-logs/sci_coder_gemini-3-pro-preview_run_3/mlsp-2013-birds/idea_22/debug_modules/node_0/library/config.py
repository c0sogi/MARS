import os
import torch
import random
import numpy as np


class Config:
    """
    Centralized configuration for the Bird Species Classification task.
    Handles hyperparameters, file paths, directory creation, and reproducibility settings.
    """

    def __init__(self, debug: bool = False, num_epochs: int = 30, batch_size: int = 32):
        """
        Initialize configuration with optional overrides.

        Args:
            debug (bool): If True, enables debug mode (e.g., smaller dataset subsets).
            num_epochs (int): Number of training epochs.
            batch_size (int): Batch size for training and inference.
        """
        # Runtime Flags
        self.DEBUG = debug

        # Paths - Input
        self.INPUT_ROOT = "./input"
        self.METADATA_DIR = "./metadata"
        self.SPECTROGRAM_DIR = os.path.join(
            self.INPUT_ROOT, "supplemental_data", "spectrograms"
        )

        # Metadata Files (Generated by previous steps)
        self.TRAIN_METADATA = os.path.join(self.METADATA_DIR, "train.csv")
        self.VAL_METADATA = os.path.join(self.METADATA_DIR, "val.csv")
        self.TEST_METADATA = os.path.join(self.METADATA_DIR, "test.csv")

        # Paths - Output
        # Specific working directory for this strategy (Idea 22)
        self.WORKING_DIR = "./working/idea_22"
        self.CACHE_DIR = os.path.join(self.WORKING_DIR, "cache")
        self.CHECKPOINT_DIR = os.path.join(self.WORKING_DIR, "checkpoints")
        self.SUBMISSION_DIR = "./submission"
        self.SUBMISSION_PATH = os.path.join(self.SUBMISSION_DIR, "submission.csv")

        # Create necessary directories
        os.makedirs(self.WORKING_DIR, exist_ok=True)
        os.makedirs(self.CACHE_DIR, exist_ok=True)
        os.makedirs(self.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(self.SUBMISSION_DIR, exist_ok=True)

        # Data Hyperparameters
        self.IMG_SIZE = 224
        self.NUM_CLASSES = 19
        self.NUM_CHANNELS = 3  # Replicating single-channel spectrogram to 3 channels

        # Training Hyperparameters
        self.BATCH_SIZE = batch_size
        self.NUM_EPOCHS = num_epochs
        self.LEARNING_RATE = 1e-3
        self.WEIGHT_DECAY = 1e-2
        self.NUM_FOLDS = 5

        # Optimization (Lookahead)
        self.LOOKAHEAD_K = 5
        self.LOOKAHEAD_ALPHA = 0.5

        # Model & Ensemble Hyperparameters
        self.ARCHITECTURES = ["resnet18", "efficientnet_b0", "densenet121"]
        self.TOP_K_CHECKPOINTS = 3  # Intra-fold snapshotting

        # System & Reproducibility
        self.SEED = 42
        self.DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
        self.NUM_WORKERS = 4

        # Apply Seeding
        self._set_seed()

    def _set_seed(self):
        """
        Sets fixed random seeds for Python, NumPy, and PyTorch to ensure reproducibility.
        """
        random.seed(self.SEED)
        np.random.seed(self.SEED)
        torch.manual_seed(self.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(self.SEED)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

    def get_checkpoint_path(self, arch_name: str, fold: int, rank: int = 0) -> str:
        """
        Helper to generate standardized checkpoint paths.

        Args:
            arch_name (str): Name of the architecture (e.g., 'resnet18').
            fold (int): Fold index.
            rank (int): Rank of the snapshot (0 for best, 1 for 2nd best, etc.).

        Returns:
            str: Full path to the checkpoint file.
        """
        arch_dir = os.path.join(self.CHECKPOINT_DIR, arch_name)
        os.makedirs(arch_dir, exist_ok=True)
        return os.path.join(arch_dir, f"{arch_name}_fold_{fold}_rank_{rank}.pth")
