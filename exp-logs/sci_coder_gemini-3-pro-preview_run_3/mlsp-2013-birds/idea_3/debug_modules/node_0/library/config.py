import os
import torch


class Config:
    """
    Configuration class for Bird Species Classification.
    Centralizes all hyperparameters and file paths.
    """

    # ==========================================
    # General Configuration
    # ==========================================
    PROJECT_NAME = "bird_species_classification"
    EXPERIMENT_NAME = "idea_3_resnet34_sed"
    SEED = 42

    # Debugging flags
    DEBUG = False  # Set to True to run on a small subset
    DEBUG_SUBSET_SIZE = 50  # Number of samples to use when DEBUG is True

    # Compute
    NUM_WORKERS = 2
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # ==========================================
    # Data Paths
    # ==========================================
    INPUT_ROOT = "./input"
    ESSENTIAL_DATA_ROOT = os.path.join(INPUT_ROOT, "essential_data")
    METADATA_DIR = "./metadata"

    # Metadata CSVs (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Raw Audio Directory
    AUDIO_DIR = os.path.join(ESSENTIAL_DATA_ROOT, "src_wavs")

    # Sample Submission
    SAMPLE_SUBMISSION = os.path.join(INPUT_ROOT, "sample_submission.csv")

    # ==========================================
    # Output Paths
    # ==========================================
    # Main working directory for this experiment
    WORKING_DIR = "./working/idea_3"

    # Sub-directories for artifacts
    OUTPUT_DIR = os.path.join(WORKING_DIR, "outputs")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")

    # Final Submission Path
    SUBMISSION_PATH = "./submission/submission.csv"

    # ==========================================
    # Audio Processing Parameters
    # ==========================================
    SR = 16000  # Sampling Rate (16kHz)
    DURATION = 10  # Duration of clips in seconds

    # Spectrogram Parameters
    N_MELS = 128  # Number of Mel bands
    N_FFT = 1024  # FFT window size
    HOP_LENGTH = 320  # Hop length (results in ~500 time frames for 10s)
    FMIN = 0  # Minimum frequency
    FMAX = 8000  # Maximum frequency (Nyquist)

    # ==========================================
    # Model Architecture Parameters
    # ==========================================
    MODEL_NAME = "resnet34"  # Backbone
    PRETRAINED = True  # Use ImageNet weights
    NUM_CLASSES = 19  # Number of bird species
    IN_CHANNELS = 3  # Replicate mono spectrogram to 3 channels
    POOLING = "attention"  # Use Attention Pooling (SED)

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    N_FOLDS = 5  # Stratified K-Fold
    EPOCHS = 50  # Max training epochs
    BATCH_SIZE = 32  # Batch size

    # Optimization
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Scheduler (Cosine Annealing)
    T_MAX = 10  # Cycle length for scheduler
    ETA_MIN = 1e-6  # Minimum learning rate

    # Early Stopping
    PATIENCE = 10  # Epochs to wait before stopping if no improvement

    # Augmentation
    MIXUP_ALPHA = 0.4  # Alpha for Mixup distribution

    @classmethod
    def setup(cls):
        """
        Creates necessary output directories.
        Should be called at the start of the process.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.OUTPUT_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(os.path.dirname(cls.SUBMISSION_PATH), exist_ok=True)


# Automatically setup directories when config is imported
Config.setup()
