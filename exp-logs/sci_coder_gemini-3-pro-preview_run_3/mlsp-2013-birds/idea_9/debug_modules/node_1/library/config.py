import os
import torch
import random
import numpy as np


class Config:
    """
    Global configuration for the Bird Species Classification Pipeline.
    Implements the strategy: Multi-Instance ResNet-18 on Domain-Curated Spectrograms.
    """

    # ==========================================
    # Reproducibility & System
    # ==========================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Number of dataloader workers

    # ==========================================
    # Data Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_9"

    # Metadata files generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Source of pre-computed spectrograms (BMP files)
    # Note: Metadata points to .wav files, we will map these to .bmp in this dir
    SPECTROGRAM_DIR = os.path.join(INPUT_DIR, "supplemental_data", "spectrograms")

    # Cache directory for processed data (e.g. numpy arrays of images)
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = os.path.join(WORKING_DIR, "submission")

    # ==========================================
    # Model Hyperparameters
    # ==========================================
    MODEL_NAME = "resnet18"
    PRETRAINED = True
    NUM_CLASSES = 19

    # Multi-Instance Learning settings
    # We split the 10s audio (spectrogram) into NUM_TILES overlapping tiles
    NUM_TILES = 3
    IMAGE_SIZE = 224  # Input size for ResNet
    CHANNELS = 3  # Replicate mono spectrogram to 3 channels for ImageNet weights

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    NUM_FOLDS = 5
    BATCH_SIZE = 16  # Effective batch size = BATCH_SIZE * NUM_TILES images
    NUM_EPOCHS = 25
    LEARNING_RATE = 3e-4
    WEIGHT_DECAY = 1e-4

    # Scheduler settings (Cosine Annealing)
    ETA_MIN = 1e-6

    # Early Stopping
    PATIENCE = 8

    # ==========================================
    # Debugging / Development
    # ==========================================
    DEBUG = False  # If True, runs on a small subset of data
    DEBUG_SUBSET_SIZE = 20

    @staticmethod
    def setup_reproducibility(seed=42):
        """
        Sets random seeds for python, numpy, and torch to ensure reproducibility.
        """
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)

        # Ensure deterministic behavior in CuDNN
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False

        # Set python hash seed
        os.environ["PYTHONHASHSEED"] = str(seed)


# Ensure necessary directories exist
os.makedirs(Config.WORKING_DIR, exist_ok=True)
os.makedirs(Config.CACHE_DIR, exist_ok=True)
os.makedirs(Config.CHECKPOINT_DIR, exist_ok=True)
os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
