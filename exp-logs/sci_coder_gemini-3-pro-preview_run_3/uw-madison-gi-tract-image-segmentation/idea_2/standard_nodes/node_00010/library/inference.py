import os
import numpy as np
import pandas as pd
import torch
import cv2
from torch.utils.data import DataLoader
from scipy.ndimage import label
from collections import defaultdict

from library.config import Config
from library.utils import set_seed, rle_encode, post_process_3d
from library.model import UNetEfficientNet
from library.data import UWDataset, get_transforms, prepare_data


def predict(load_cached_data=True, debug=False):
    """
    Main inference function.
    Loads data, runs prediction, applies 3D post-processing, and generates submission file.
    """
    # 1. Setup
    set_seed(Config.SEED)
    device = Config.DEVICE
    Config.setup()

    # 2. Load Metadata
    # We use the test.csv generated by the metadata script
    if not os.path.exists(Config.TEST_CSV):
        raise FileNotFoundError(f"Test metadata not found at {Config.TEST_CSV}")

    df_test = pd.read_csv(Config.TEST_CSV)

    if debug:
        df_test = df_test.iloc[: Config.DEBUG_SAMPLE_SIZE].reset_index(drop=True)

    # 3. Prepare Data (2.5D Context)
    # This generates the necessary prev/next slice paths
    df_test = prepare_data(df_test, load_cached_data=load_cached_data, split="test")

    # 4. Dataset & Loader
    test_dataset = UWDataset(
        df_test, transforms=get_transforms(data="test"), mode="test"
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=Config.BATCH_SIZE,
        shuffle=False,
        num_workers=Config.NUM_WORKERS,
        pin_memory=True,
    )

    # 5. Model Loading
    model = UNetEfficientNet(
        backbone_name=Config.BACKBONE, pretrained=False, classes=Config.NUM_CLASSES
    )

    if os.path.exists(Config.CHECKPOINT_PATH):
        checkpoint = torch.load(Config.CHECKPOINT_PATH, map_location=device)
        model.load_state_dict(checkpoint)
    else:
        print(
            f"Warning: Checkpoint not found at {Config.CHECKPOINT_PATH}. Using random weights."
        )

    model.to(device)
    model.eval()

    # 6. Prediction Loop
    # We need to reconstruct volumes, so we store predictions grouped by case_day
    # structure: volumes[case_day][slice_num] = { 'id': id, 'preds': np_array(H,W,3) }
    volumes = defaultdict(dict)

    with torch.no_grad():
        for images, ids, heights, widths in test_loader:
            images = images.to(device, dtype=torch.float32)

            # Forward pass
            logits = model(images)
            probs = torch.sigmoid(logits)

            # Convert to numpy
            probs = probs.cpu().numpy()

            # Process batch
            for i in range(len(ids)):
                sample_id = ids[i]
                h_orig = int(heights[i])
                w_orig = int(widths[i])
                prob_map = probs[i]  # (C, H_model, W_model)

                # Transpose to (H, W, C) for cv2 resize
                prob_map = np.transpose(prob_map, (1, 2, 0))

                # Resize back to original image dimensions
                # cv2.resize expects (width, height)
                pred_resized = cv2.resize(
                    prob_map, (w_orig, h_orig), interpolation=cv2.INTER_LINEAR
                )

                # Thresholding
                mask = (pred_resized > Config.PRED_THR).astype(np.uint8)

                # Parse ID to get grouping keys
                # ID format: caseXXX_dayYY_slice_ZZZZ
                parts = sample_id.split("_")
                case_day = f"{parts[0]}_{parts[1]}"
                slice_num = int(parts[3])

                volumes[case_day][slice_num] = {
                    "id": sample_id,
                    "mask": mask,  # (H_orig, W_orig, 3)
                }

    # 7. Post-Processing & RLE Encoding
    submission_rows = []

    # Iterate over each scan (case + day)
    for case_day, slices_dict in volumes.items():
        # Sort slices by number to form a proper 3D volume
        sorted_slice_nums = sorted(slices_dict.keys())

        # Check dimensions from the first slice
        first_slice = slices_dict[sorted_slice_nums[0]]["mask"]
        h, w, c = first_slice.shape
        d = len(sorted_slice_nums)

        # Construct 3D volume: (Depth, Height, Width, Classes)
        # Pre-allocate
        volume_3d = np.zeros((d, h, w, c), dtype=np.uint8)

        # Map slice index back to original ID for submission
        slice_idx_to_id = {}

        for idx, s_num in enumerate(sorted_slice_nums):
            volume_3d[idx] = slices_dict[s_num]["mask"]
            slice_idx_to_id[idx] = slices_dict[s_num]["id"]

        # Process each class channel independently
        for class_idx, class_name in enumerate(Config.CLASSES):
            # Extract volume for this class: (Depth, Height, Width)
            class_volume = volume_3d[..., class_idx]

            # Apply 3D Post-Processing (CCA)
            processed_volume = post_process_3d(class_volume)

            # Encode each slice in the processed volume
            for z in range(d):
                slice_mask = processed_volume[z, :, :]
                rle = rle_encode(slice_mask)

                # Append to submission
                submission_rows.append(
                    {"id": slice_idx_to_id[z], "class": class_name, "predicted": rle}
                )

    # 8. Generate Submission File
    df_sub = pd.DataFrame(submission_rows)

    # Ensure columns are in correct order
    df_sub = df_sub[["id", "class", "predicted"]]

    # Save
    df_sub.to_csv(Config.SUBMISSION_PATH, index=False)
