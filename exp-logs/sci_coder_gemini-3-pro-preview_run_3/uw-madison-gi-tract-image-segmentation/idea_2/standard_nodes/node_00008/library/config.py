import os
import torch


class Config:
    """
    Configuration class for the UW-Madison GI Tract Segmentation task.
    Centralizes all hyperparameters, paths, and model settings.
    """

    # ====================================================
    # General & System Settings
    # ====================================================
    PROJECT_NAME = "uw-madison-gi-tract-segmentation"
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    # Use available CPUs, capped to prevent overhead
    NUM_WORKERS = min(12, os.cpu_count() if os.cpu_count() else 4)

    # ====================================================
    # File Paths & Directories
    # ====================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (generated by the provided script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Working directory for caching processed data (parquet/npy) and saving artifacts
    WORKING_DIR = "./working/idea_2"
    OUTPUT_DIR = "./working"

    # Model checkpoint path
    CHECKPOINT_PATH = os.path.join(OUTPUT_DIR, "best_model.pth")

    # Submission paths
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # ====================================================
    # Data Configuration
    # ====================================================
    # Image Dimensions: 320x320 is a good balance for the 360x310 max original size
    IMG_HEIGHT = 320
    IMG_WIDTH = 320
    IMG_SIZE = (IMG_HEIGHT, IMG_WIDTH)

    # Input Channels: 3 channels for 2.5D representation (slices t-1, t, t+1)
    IN_CHANNELS = 3

    # Class Definitions
    CLASSES = ["large_bowel", "small_bowel", "stomach"]
    NUM_CLASSES = len(CLASSES)

    # Normalization Parameters
    # Robust scaling using percentiles to handle MRI intensity outliers
    NORM_MIN_PERCENTILE = 1.0
    NORM_MAX_PERCENTILE = 99.0
    # Threshold to detect empty/noisy background slices (if dynamic range is too low)
    NOISE_THRESHOLD = 0.01

    # ====================================================
    # Model Architecture
    # ====================================================
    MODEL_ARCH = "Unet"
    BACKBONE = "efficientnet_b1"
    ENCODER_WEIGHTS = "imagenet"

    # ====================================================
    # Training Hyperparameters
    # ====================================================
    BATCH_SIZE = 32
    EPOCHS = 20

    # Optimizer settings
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-5

    # Scheduler settings (Cosine Annealing)
    T_MAX = EPOCHS
    MIN_LR = 1e-6

    # Loss Function Weights (Combined BCE + Tversky)
    # Tversky is useful for imbalanced segmentation (small organs)
    LOSS_BCE_WEIGHT = 0.4
    LOSS_TVERSKY_WEIGHT = 0.6
    TVERSKY_ALPHA = 0.3  # False Positive penalty
    TVERSKY_BETA = 0.7  # False Negative penalty (higher to recall small organs)
    TVERSKY_SMOOTH = 1.0

    # ====================================================
    # Inference & Post-processing
    # ====================================================
    PRED_THR = 0.5  # Threshold for converting probability to binary mask

    # 3D Hausdorff Distance Optimization
    USE_3D_CCA = True  # Enable 3D Connected Component Analysis
    MIN_PIXELS = 50  # Minimum volume (in pixels) to keep a 3D object

    # ====================================================
    # Debugging / Development
    # ====================================================
    # Set DEBUG to True to run on a small subset of data for quick pipeline testing
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 200

    @staticmethod
    def setup():
        """
        Creates necessary directories for the project.
        Should be called at the start of the pipeline.
        """
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
        os.makedirs(Config.OUTPUT_DIR, exist_ok=True)

    @staticmethod
    def to_dict():
        """Returns the configuration as a dictionary."""
        return {
            k: v
            for k, v in Config.__dict__.items()
            if not k.startswith("__") and not callable(v)
        }
