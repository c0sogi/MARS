import os
import torch


class Config:
    """
    Configuration class for the Pathology Tumor Detection task.
    Implements settings for Heterogeneous Cross-Validation Ensemble (ResNet18 + ConvNeXt-Tiny).
    """

    # --- General Configuration ---
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data for debugging
    DEBUG_SAMPLES = 1000  # Number of samples to use when DEBUG is True

    # --- Directory Paths ---
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for the current idea (Idea 3: Heterogeneous Ensemble)
    WORKING_DIR = "./working/idea_3"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Submission directory
    SUBMISSION_DIR = "./submission"
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # --- File Paths ---
    TRAIN_LABELS_PATH = os.path.join(INPUT_DIR, "train_labels.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Metadata CSVs (Generated by the provided metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # --- Data Preprocessing ---
    # Input images are 96x96. We crop to 64x64 to focus on the center while keeping context.
    # The label is determined by the center 32x32 region.
    INPUT_SIZE = 96
    CROP_SIZE = 64
    CENTER_REGION_SIZE = 32

    # --- Model Architectures ---
    # We use a single strong architecture to prioritize convergence (Cite solution_lesson_node_00008)
    MODEL_ARCHITECTURES = ["convnext_tiny"]
    NUM_CLASSES = 1  # Binary classification (0: No Tumor, 1: Tumor)

    # --- Training Hyperparameters ---
    NUM_FOLDS = 5
    EPOCHS = 15
    BATCH_SIZE = 512  # Maximized for A100 GPU to ensure stable BN statistics
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-4
    EARLY_STOPPING_PATIENCE = 5

    # --- Hardware Settings ---
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 8  # Optimized for 12 vCPUs

    # --- Inference / TTA ---
    USE_TTA = True
    TTA_VIEWS = 4  # 4 Views: Original, Horizontal Flip, Vertical Flip, Combined Flip
