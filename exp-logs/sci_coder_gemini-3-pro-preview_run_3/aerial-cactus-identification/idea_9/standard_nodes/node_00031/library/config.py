import os
import torch
import random
import numpy as np


class Config:
    """
    Central configuration for the Cactus Identification pipeline.
    Defines hyperparameters, paths, and system settings based on the
    Robust Pretrained Heterogeneous Stacking Strategy.
    """

    # ==========================================
    # General Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 100  # Number of samples if DEBUG is True

    # ==========================================
    # Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (generated by the provided metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Working directory for caching and checkpoints
    WORKING_DIR = "./working/idea_9"

    # Submission output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Data Configuration
    # ==========================================
    IMG_SIZE = (32, 32)
    NUM_CLASSES = 1
    N_FOLDS = 5
    NUM_WORKERS = 4  # Optimized for 12 vCPUs

    # ==========================================
    # Model Architecture
    # ==========================================
    # The "Robust Triad" of architectures
    MODEL_NAMES = ["seresnext50_32x4d", "densenet121", "resnet34"]
    PRETRAINED = True

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 128
    EPOCHS = 100  # High limit, managed by Early Stopping

    # Optimization
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2
    EARLY_STOPPING_PATIENCE = 20  # Relaxed patience for Mixup convergence

    # ==========================================
    # Regularization
    # ==========================================
    USE_MIXUP = True
    MIXUP_ALPHA = 1.0

    # ==========================================
    # Hardware & System
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    CUDNN_BENCHMARK = True

    @classmethod
    def setup(cls):
        """
        Initialize the environment:
        1. Create necessary working and submission directories.
        2. Set random seeds for reproducibility across libraries.
        3. Configure hardware backends.
        """
        # Ensure directories exist
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set reproducible seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(cls.SEED)

        # Optimize cudnn for fixed input sizes
        if cls.CUDNN_BENCHMARK and torch.cuda.is_available():
            torch.backends.cudnn.benchmark = True
