import os
import torch


class Config:
    """
    Configuration module for the Cactus Identification Task.
    Implements settings for the Lightweight Heterogeneous Triad with Stacking strategy.
    """

    # --------------------------------------------------------------------------
    # General & Reproducibility
    # --------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging

    # --------------------------------------------------------------------------
    # Directory & File Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for caching intermediate files and model checkpoints
    WORKING_DIR = "./working/idea_7"

    # Submission directory
    SUBMISSION_DIR = "./submission"

    # Metadata Files (Generated by the provided metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Submission File
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure necessary writeable directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # --------------------------------------------------------------------------
    # Data Configuration
    # --------------------------------------------------------------------------
    IMG_SIZE = 32
    NUM_CLASSES = 1  # Binary classification (has_cactus)
    NUM_FOLDS = 5  # Stratified K-Fold Cross Validation

    # --------------------------------------------------------------------------
    # Model Architectures (The Lightweight Triad)
    # --------------------------------------------------------------------------
    MODELS = [
        "custom_wide_se_resnet",  # Shallow, wide ResNet with SE blocks
        "custom_densenet_bc",  # Compact DenseNet
        "modified_efficientnet_b0",  # EfficientNet with stride-1 stem
    ]

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    EPOCHS = 50
    BATCH_SIZE = 128

    # Optimization
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2  # AdamW typically requires higher weight decay than SGD

    # Regularization & Convergence
    EARLY_STOPPING_PATIENCE = 25  # Relaxed patience for Mixup training
    MIXUP_ALPHA = 1.0  # Beta distribution parameter for Mixup

    # --------------------------------------------------------------------------
    # Hardware & System Settings
    # --------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Number of dataloader workers

    # Enable cuDNN benchmark for fixed-size inputs (32x32) to optimize kernel selection
    CUDNN_BENCHMARK = True

    # --------------------------------------------------------------------------
    # Utility
    # --------------------------------------------------------------------------
    @staticmethod
    def print_config():
        """Prints the current configuration settings."""
        print("=" * 40)
        print("PIPELINE CONFIGURATION")
        print("=" * 40)
        for key, value in Config.__dict__.items():
            if not key.startswith("__") and not isinstance(value, staticmethod):
                print(f"{key}: {value}")
        print("=" * 40)
