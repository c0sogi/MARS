import os
import torch


class Config:
    """
    Configuration class for the Word-Level Wide-and-Deep TextCNN model.
    Serves as the central source of truth for hyperparameters and file paths.
    """

    # ==========================================
    # Reproducibility
    # ==========================================
    SEED = 42

    # ==========================================
    # File Paths
    # ==========================================
    # Base Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_8"
    SUBMISSION_DIR = "./submission"

    # Metadata Files (Generated by metadata script)
    TRAIN_META_FILE = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_FILE = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_FILE = os.path.join(METADATA_DIR, "test.csv")

    # Raw Data Files
    TRAIN_RAW_FILE = os.path.join(INPUT_DIR, "train.csv")
    TEST_RAW_FILE = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION_FILE = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Artifacts
    MODEL_PATH = os.path.join(WORKING_DIR, "wide_deep_model.pth")
    VOCAB_PATH = os.path.join(WORKING_DIR, "vocab.json")
    MLB_PATH = os.path.join(WORKING_DIR, "mlb.joblib")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache Files (for deterministic data processing)
    # We use .npy for efficient loading of preprocessed tensors
    TRAIN_TOKENS_PATH = os.path.join(WORKING_DIR, "train_tokens.npy")
    VAL_TOKENS_PATH = os.path.join(WORKING_DIR, "val_tokens.npy")
    TEST_TOKENS_PATH = os.path.join(WORKING_DIR, "test_tokens.npy")

    TRAIN_LABELS_PATH = os.path.join(WORKING_DIR, "train_labels.npy")
    VAL_LABELS_PATH = os.path.join(WORKING_DIR, "val_labels.npy")

    # ==========================================
    # Data Processing Hyperparameters
    # ==========================================
    VOCAB_SIZE = 50000  # Top N most frequent words
    MAX_LEN = 400  # Fixed sequence length for padding/truncation
    NUM_TAGS = 5000  # Top K most frequent tags to predict

    # ==========================================
    # Model Hyperparameters
    # ==========================================
    EMBED_DIM = 300  # Dimension of word embeddings

    # TextCNN Backbone Configuration
    CNN_FILTERS = 128  # Number of filters per kernel size
    CNN_KERNEL_SIZES = [3, 4, 5]  # N-gram window sizes

    # Regularization
    DROPOUT = 0.5

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 512  # Optimized for A100 (40GB VRAM)
    LEARNING_RATE = 1e-3  # Initial learning rate for AdamW
    NUM_EPOCHS = 10  # Maximum epochs (relies on early stopping)
    PATIENCE = 3  # Early stopping patience
    WEIGHT_DECAY = 1e-4  # Weight decay for optimizer

    # ==========================================
    # Hardware & Execution
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 12  # Number of CPU cores available for data loading
    PIN_MEMORY = True if torch.cuda.is_available() else False

    @staticmethod
    def setup():
        """
        Creates the necessary working and submission directories.
        Should be called at the start of the pipeline.
        """
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
