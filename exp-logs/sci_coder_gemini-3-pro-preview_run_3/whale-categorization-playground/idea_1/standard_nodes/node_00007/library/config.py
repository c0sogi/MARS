import os
import random
import numpy as np
import torch


class Config:
    """
    Configuration class for the Whale Identification Siamese Network.
    """

    # -------------------------------------------------------------------------
    # Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42

    # -------------------------------------------------------------------------
    # File System Paths
    # -------------------------------------------------------------------------
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_1"
    SUBMISSION_DIR = "./submission"

    # Metadata files (generated by the provided script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Output files
    MODEL_PATH = os.path.join(WORKING_DIR, "siamese_resnet18.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache directory for processed data (if needed)
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")

    # -------------------------------------------------------------------------
    # Data Parameters
    # -------------------------------------------------------------------------
    IMG_HEIGHT = 224
    IMG_WIDTH = 224
    CHANNELS = 3

    # Debugging: Set to an integer (e.g., 500) to limit the number of samples
    # used during training/validation for rapid iteration. Set to None for full run.
    DEBUG_SUBSET_SIZE = None

    # -------------------------------------------------------------------------
    # Model Hyperparameters
    # -------------------------------------------------------------------------
    BACKBONE = "densenet121"
    EMBEDDING_DIM = 128
    MARGIN = 0.5  # Margin for Triplet Loss

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 14
    LEARNING_RATE = 0.0003
    WEIGHT_DECAY = 1e-4
    EPOCHS = 20
    PATIENCE = 5  # Early stopping patience (epochs without improvement)

    # Hardware settings
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Adjust based on available vCPUs (12 available)

    # -------------------------------------------------------------------------
    # Inference / Post-processing
    # -------------------------------------------------------------------------
    # Threshold for deciding 'new_whale'.
    # If the distance to the nearest known whale embedding is > THRESHOLD,
    # the primary prediction is 'new_whale'.
    NEW_WHALE_THRESHOLD = 0.7

    # Number of nearest neighbors to retrieve for ranking
    KNN_K = 50

    @classmethod
    def setup(cls):
        """
        Ensures that necessary working and submission directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)


def set_seed(seed=42):
    """
    Sets the random seed for reproducibility across Python, NumPy, and PyTorch.
    """
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed(seed)

    # deterministic algorithms for reproducibility
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False

    os.environ["PYTHONHASHSEED"] = str(seed)
