import os
import torch


class CFG:
    """
    Configuration class for Whale Species Identification Task.
    Implements settings for EfficientNet-B2 backbone, CurricularFace loss,
    and k-Reciprocal Re-ranking.
    """

    # -------------------------------------------------------------------------
    # General Setup
    # -------------------------------------------------------------------------
    seed = 42
    debug = False  # Set to True to run on a small subset for debugging
    num_workers = 4
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print_freq = 100

    # -------------------------------------------------------------------------
    # Paths
    # -------------------------------------------------------------------------
    # Input directories (Read-Only)
    input_dir = "./input"
    metadata_dir = "./metadata"

    # Metadata files generated by the provided script
    train_csv = os.path.join(metadata_dir, "train.csv")
    val_csv = os.path.join(metadata_dir, "val.csv")
    test_csv = os.path.join(metadata_dir, "test.csv")

    # Output directories (Read/Write)
    # Using 'idea_3' directory as specified for this experimental branch
    working_dir = "./working/idea_3"
    output_dir = "./working/idea_3"
    submission_dir = "./submission"

    # Specific file paths for saving/loading
    model_path = os.path.join(working_dir, "efficientnet_curricularface.pth")
    submission_path = os.path.join(submission_dir, "submission.csv")

    # Ensure writeable directories exist
    os.makedirs(working_dir, exist_ok=True)
    os.makedirs(submission_dir, exist_ok=True)

    # -------------------------------------------------------------------------
    # Data Configuration
    # -------------------------------------------------------------------------
    image_size = 448
    batch_size = 32  # Optimized for A100 40GB

    # -------------------------------------------------------------------------
    # Model Configuration
    # -------------------------------------------------------------------------
    model_name = "tf_efficientnet_b2"
    embedding_size = 512
    pretrained = True
    drop_rate = 0.3

    # -------------------------------------------------------------------------
    # Training Configuration
    # -------------------------------------------------------------------------
    epochs = 20
    lr = 3e-4
    weight_decay = 1e-4
    min_lr = 1e-6

    # Scheduler parameters (Cosine Annealing)
    scheduler_T_0 = 20
    scheduler_T_mult = 1

    # -------------------------------------------------------------------------
    # Loss Configuration (CurricularFace)
    # -------------------------------------------------------------------------
    # s: scale factor (inverse temperature)
    # m: margin
    s = 30.0
    m = 0.50

    # -------------------------------------------------------------------------
    # Inference & Re-ranking Configuration
    # -------------------------------------------------------------------------
    # Parameters for k-Reciprocal Encoding Re-ranking
    use_reranking = True
    k1 = 20  # Number of neighbors for k-reciprocal set
    k2 = 6  # Number of neighbors for local query expansion
    lambda_value = 0.3  # Weight for re-ranked distance vs original distance

    # Threshold for 'new_whale' classification
    # If the distance to the nearest neighbor is greater than this, predict 'new_whale'
    # This threshold applies to the final (potentially re-ranked) distances.
    # Distance is usually Cosine Distance (1 - Cosine Similarity) or Jaccard Distance.
    # Range typically [0, 1] or [0, 2] depending on metric.
    # For Cosine Distance (0 to 2), a value around 0.6-0.8 is a reasonable starting point.
    new_whale_threshold = 0.65
