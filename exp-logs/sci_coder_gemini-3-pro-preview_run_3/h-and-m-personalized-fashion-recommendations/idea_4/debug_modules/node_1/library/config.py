import os
from pathlib import Path
from dataclasses import dataclass, field
from typing import Dict, Any, List


@dataclass
class Config:
    """
    Global configuration for the Multi-View Cascade System.
    Defines paths, hyperparameters, and model settings for the pipeline.
    """

    # =========================================================================
    # Directories
    # =========================================================================
    INPUT_DIR: Path = Path("./input")
    METADATA_DIR: Path = Path("./metadata")
    WORKING_DIR: Path = Path("./working/idea_4")
    SUBMISSION_DIR: Path = Path("./submission")

    # =========================================================================
    # Input File Paths
    # =========================================================================
    # Raw CSVs
    ARTICLES_CSV: Path = INPUT_DIR / "articles.csv"
    CUSTOMERS_CSV: Path = INPUT_DIR / "customers.csv"
    TRANSACTIONS_CSV: Path = INPUT_DIR / "transactions_train.csv"
    SAMPLE_SUBMISSION_CSV: Path = INPUT_DIR / "sample_submission.csv"
    IMAGES_DIR: Path = INPUT_DIR / "images"

    # Metadata Parquets (Generated by previous steps)
    TRAIN_METADATA: Path = METADATA_DIR / "train_metadata.parquet"
    VAL_METADATA: Path = METADATA_DIR / "val_metadata.parquet"
    TEST_METADATA: Path = METADATA_DIR / "test_metadata.parquet"

    # =========================================================================
    # Artifact Paths (Caching)
    # =========================================================================
    # Mappings
    ARTICLE_ID_MAP_PATH: Path = (
        WORKING_DIR / "article_id_map.npy"
    )  # Maps article_id (int) -> dense index (int)
    CUSTOMER_ID_MAP_PATH: Path = (
        WORKING_DIR / "customer_id_map.npy"
    )  # Maps customer_id (hash) -> dense index (int)

    # Visual Components
    ARTICLE_EMBEDDINGS_PATH: Path = WORKING_DIR / "article_embeddings.npy"
    VISUAL_KNN_GRAPH_PATH: Path = WORKING_DIR / "visual_knn_graph.npz"

    # Behavioral Components
    TRANSITION_MATRIX_PATH: Path = WORKING_DIR / "transition_matrix.npz"
    GLOBAL_POPULARITY_PATH: Path = WORKING_DIR / "global_popularity.parquet"

    # Ranker Datasets
    RANKER_TRAIN_SET: Path = WORKING_DIR / "ranker_train_set.parquet"
    RANKER_VAL_SET: Path = WORKING_DIR / "ranker_val_set.parquet"
    RANKER_MODEL_PATH: Path = WORKING_DIR / "lgbm_ranker.txt"

    # Output
    SUBMISSION_PATH: Path = SUBMISSION_DIR / "submission.csv"

    # =========================================================================
    # Hyperparameters
    # =========================================================================
    SEED: int = 42

    # --- Visual Encoder (ResNet) ---
    IMG_SIZE: int = 224
    BATCH_SIZE: int = 256
    NUM_WORKERS: int = 8
    EMBEDDING_DIM: int = 512

    # --- Stage 1: Retrieval ---
    RETRIEVAL_TOP_K: int = 100  # Number of candidates to generate per user
    KNN_NEIGHBORS: int = 20  # K for Visual KNN graph

    # Weights for Multi-View Score Aggregation
    # Score = (User * Trans) + lambda * (User * Visual) + alpha * (User_History)
    VISUAL_WEIGHT: float = 0.15  # lambda
    HISTORY_WEIGHT: float = 1.0  # alpha (Repurchase signal)

    # Time Decay for Transition Matrix
    # Weight = exp(-decay * days_diff)
    TIME_DECAY_RATE: float = 0.005

    # --- Stage 2: Ranking (LightGBM) ---
    RANKING_TOP_K: int = 12  # Final submission cutoff

    # Sliding Window for Training Data
    # We use the last N weeks of training data to create (History -> Target) samples
    SLIDING_WINDOW_WEEKS: int = 12
    VAL_WEEKS: int = 1  # Last week for validation

    # LightGBM Parameters
    LGBM_PARAMS = {
        "objective": "lambdarank",
        "metric": "ndcg",
        "eval_at": [12],
        "boosting_type": "gbdt",
        "n_estimators": 2000,
        "learning_rate": 0.05,
        "num_leaves": 64,
        "max_depth": 8,
        "min_data_in_leaf": 50,
        "feature_fraction": 0.8,
        "bagging_fraction": 0.8,
        "bagging_freq": 1,
        "lambda_l1": 0.1,
        "lambda_l2": 0.1,
        "verbose": -1,
        "random_state": 42,
        "n_jobs": 12,
        "early_stopping_round": 50,
    }

    def __post_init__(self):
        """
        Setup directories upon initialization.
        """
        self.WORKING_DIR.mkdir(parents=True, exist_ok=True)
        self.SUBMISSION_DIR.mkdir(parents=True, exist_ok=True)
