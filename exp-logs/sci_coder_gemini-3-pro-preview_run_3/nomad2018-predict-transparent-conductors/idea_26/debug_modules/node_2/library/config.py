import os


class Config:
    """
    Configuration for Distributional Multi-Order Geometric Fingerprinting (DMGF) project.
    This class serves as a centralized definition of all paths, constants, and hyperparameters.
    """

    # -------------------------------------------------------------------------
    # Directories and Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_26"
    SUBMISSION_DIR = "./submission"

    # Ensure working and submission directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata Paths (Generated by the analysis step)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Feature Cache Paths
    # We use parquet for efficient storage of tabular feature data
    TRAIN_FEATURES_PATH = os.path.join(WORKING_DIR, "train_features.parquet")
    VAL_FEATURES_PATH = os.path.join(WORKING_DIR, "val_features.parquet")
    TEST_FEATURES_PATH = os.path.join(WORKING_DIR, "test_features.parquet")

    # Final Submission Path
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Global Settings
    # -------------------------------------------------------------------------
    RANDOM_SEED = 42

    # Debugging: Set to True to run on a small subset of data for rapid testing
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 50

    # -------------------------------------------------------------------------
    # Feature Extraction Hyperparameters
    # -------------------------------------------------------------------------

    # Elements involved in the crystal structures
    ELEMENTS = ["Al", "Ga", "In", "O"]

    # 2-Body: Radial Distribution Function (RDF)
    RDF_CUTOFF = 6.0  # Maximum distance in Angstroms for RDF calculation
    RDF_BINS = 60  # Number of bins for the histogram (resolution ~0.1 A)
    RDF_SIGMA = 0.1  # Width for Gaussian smearing (if continuous RDF is used)

    # 3-Body: Bond Angles
    # Cutoff distance to define neighbors for angle calculation
    # Typically slightly larger than the first coordination shell
    ANGLE_NEIGHBOR_CUTOFF = 3.0

    # Many-Body: Steinhardt Order Parameters & ECoN
    # Cutoff for determining local environment for order parameters
    LOCAL_ENV_CUTOFF = 3.5
    # Spherical harmonic degrees for Steinhardt parameters (Q_l)
    STEINHARDT_L = [4, 6]

    # Distributional Aggregation
    # Percentiles to compute for bond lengths, angles, ECoN, and Q_l distributions
    # This captures the shape of the distribution (min, low-tail, median, high-tail, max)
    PERCENTILES = [0, 10, 25, 50, 75, 90, 100]

    # -------------------------------------------------------------------------
    # Model Hyperparameters (XGBoost)
    # -------------------------------------------------------------------------
    # Separate models are trained for formation energy and bandgap
    TARGET_COLS = ["formation_energy_ev_natom", "bandgap_energy_ev"]

    # Hyperparameters optimized for generalization on geometric descriptors
    XGB_PARAMS = {
        "n_estimators": 3000,
        "learning_rate": 0.01,
        "max_depth": 6,
        "subsample": 0.7,  # Stochastic row subsampling
        "colsample_bytree": 0.6,  # Stochastic column subsampling
        "min_child_weight": 5,
        "gamma": 0.1,
        "n_jobs": -1,
        "random_state": RANDOM_SEED,
        "objective": "reg:squarederror",
        "tree_method": "hist",  # Histogram-based algorithm for speed
        "reg_alpha": 0.1,  # L1 regularization
        "reg_lambda": 1.0,  # L2 regularization
    }

    # Training control
    EARLY_STOPPING_ROUNDS = 100
    VERBOSE_EVAL = 200
