import os


class Config:
    """
    Global configuration for the CR-LEM (Chemically-Resolved Local Environment Moments) strategy.
    Centralizes file paths, physical constants, and model hyperparameters.
    """

    # -------------------------------------------------------------------------
    # Directories and Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Specific working directory for this idea to avoid conflicts
    WORKING_DIR = "./working/idea_14/"
    SUBMISSION_DIR = "./submission"

    # Ensure output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata File Paths (generated by the metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Sample Submission Path
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # -------------------------------------------------------------------------
    # Global Settings
    # -------------------------------------------------------------------------
    RANDOM_SEED = 42

    # Debugging control
    # Set to True to run on a small subset of data for rapid testing
    DEBUG_MODE = False
    # Number of samples to use if DEBUG_MODE is True
    DEBUG_SAMPLE_SIZE = 50

    # -------------------------------------------------------------------------
    # Feature Extraction Hyperparameters
    # -------------------------------------------------------------------------
    # Radial Distribution Function (RDF) settings
    # 6.0 Angstroms captures medium-range order beyond the first shell
    RDF_CUTOFF = 6.0
    # 60 bins gives a resolution of 0.1 Angstrom, sufficient for crystal peaks
    RDF_NUM_BINS = 60

    # Local Environment Moments (LEM) settings
    # Cutoff for defining immediate neighbors (1st coordination shell)
    # ~3.0 A covers typical metal-oxygen bond lengths (Al-O ~1.9, Ga-O ~2.0, In-O ~2.2)
    # and excludes second neighbors.
    NEIGHBOR_CUTOFF = 3.0

    # List of elements expected in the dataset for chemical resolution
    ELEMENTS = ["Al", "Ga", "In", "O"]

    # -------------------------------------------------------------------------
    # Model Hyperparameters (XGBoost)
    # -------------------------------------------------------------------------
    # Optimized for robustness and to prevent overfitting on high-dimensional features
    XGB_PARAMS = {
        "n_estimators": 3000,
        "learning_rate": 0.01,
        "max_depth": 6,
        "subsample": 0.65,  # Row subsampling to force diversity
        "colsample_bytree": 0.65,  # Column subsampling
        "min_child_weight": 1,
        "n_jobs": -1,
        "random_state": RANDOM_SEED,
        "objective": "reg:squarederror",
        "tree_method": "hist",  # Efficient histogram-based algorithm
    }

    # -------------------------------------------------------------------------
    # Caching Filenames
    # -------------------------------------------------------------------------
    # Parquet files for storing processed feature matrices
    TRAIN_FEATURES_FILE = "train_features.parquet"
    VAL_FEATURES_FILE = "val_features.parquet"
    TEST_FEATURES_FILE = "test_features.parquet"

    # Final submission filename
    SUBMISSION_FILE = "submission.csv"
