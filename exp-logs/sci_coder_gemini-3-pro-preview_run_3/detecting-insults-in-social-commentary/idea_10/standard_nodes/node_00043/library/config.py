import os
import torch


class Config:
    """
    Configuration class for the Heterogeneous Ensemble with Adversarial Knowledge Distillation.
    Centralizes all hyperparameters, paths, and model settings.
    """

    def __init__(
        self,
        debug: bool = False,
        epochs: int = 5,
        train_batch_size: int = 4,
        accumulation_steps: int = 8,
        max_len: int = 160,
        seed: int = 42,
    ):

        # ==========================================
        # General Settings
        # ==========================================
        self.debug = debug
        self.seed = seed
        self.num_workers = 4
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

        # ==========================================
        # Paths
        # ==========================================
        # Input metadata paths (generated by previous steps)
        self.input_dir = "./metadata"
        self.train_path = os.path.join(self.input_dir, "train.csv")
        self.val_path = os.path.join(self.input_dir, "val.csv")
        self.test_path = os.path.join(self.input_dir, "test.csv")

        # Output and Working directories
        self.working_dir = "./working/idea_10"
        self.teacher_dir = os.path.join(self.working_dir, "teachers")
        self.student_dir = os.path.join(self.working_dir, "students")
        self.cache_dir = os.path.join(self.working_dir, "cache")
        self.submission_path = "./submission/submission.csv"

        # Ensure necessary directories exist
        os.makedirs(self.working_dir, exist_ok=True)
        os.makedirs(self.teacher_dir, exist_ok=True)
        os.makedirs(self.student_dir, exist_ok=True)
        os.makedirs(self.cache_dir, exist_ok=True)
        os.makedirs(os.path.dirname(self.submission_path), exist_ok=True)

        # ==========================================
        # Model Architectures
        # ==========================================
        # Heterogeneous backbones for ensemble diversity
        self.model_names = ["roberta-large", "microsoft/deberta-v3-large"]

        # ==========================================
        # Model Hyperparameters
        # ==========================================
        self.max_len = max_len
        self.dropout = 0.2
        self.freeze_layers = 6  # Freeze bottom 6 layers to preserve general features
        self.pool_type = "mean"  # Mean pooling of final hidden states

        # ==========================================
        # Training Hyperparameters
        # ==========================================
        self.epochs = epochs
        self.train_batch_size = train_batch_size
        self.valid_batch_size = train_batch_size * 2
        self.accumulation_steps = accumulation_steps
        self.effective_batch_size = train_batch_size * accumulation_steps

        self.learning_rate = 1e-5
        self.weight_decay = 0.01
        self.scheduler_type = "linear"
        self.warmup_ratio = 0.1
        self.max_grad_norm = 1.0

        # ==========================================
        # Adversarial Weight Perturbation (AWP)
        # ==========================================
        self.use_awp = True
        self.awp_lr = 1e-4
        self.awp_eps = 1e-2
        self.awp_start_epoch = (
            1  # Enable AWP after the first epoch to stabilize initial training
        )

        # ==========================================
        # Knowledge Distillation
        # ==========================================
        self.teacher_epochs = (
            3  # Teachers usually converge faster or similar to students
        )
        self.student_epochs = (
            epochs  # Students need time to learn from soft targets and AWP
        )
        self.distillation_alpha = (
            0.5  # Weight for KL Divergence loss (vs Ground Truth BCE)
        )
        self.temperature = 1.0  # Soft target temperature

        # ==========================================
        # Ensemble Strategy
        # ==========================================
        self.seeds = [42, 43, 44]

        # ==========================================
        # Debugging / Development
        # ==========================================
        self.subset_rows = None
        if self.debug:
            # Drastically reduce compute for debugging
            self.epochs = 2
            self.teacher_epochs = 2
            self.student_epochs = 2
            self.train_batch_size = 4
            self.valid_batch_size = 4
            self.accumulation_steps = 1
            self.seeds = [42]  # Run only one seed
            self.model_names = ["roberta-large"]  # Run only one model architecture
            self.subset_rows = 100  # Load only 100 rows for rapid testing

    def to_dict(self):
        """Returns a dictionary representation of the config for logging."""
        return {k: v for k, v in self.__dict__.items() if not k.startswith("__")}
