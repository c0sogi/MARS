import os
import torch


class Config:
    """
    Configuration class for Salt Segmentation Task (Idea 13).
    Encapsulates hyperparameters, file paths, and model settings.
    """

    # -------------------------------------------------------------------------
    # 1. Reproducibility & Compute
    # -------------------------------------------------------------------------
    SEED = 42
    # Detect device: A100 is available
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # 12 vCPUs available
    NUM_WORKERS = 12

    # -------------------------------------------------------------------------
    # 2. File Systems & Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata CSVs (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Working Directory for this specific experiment (Idea 13)
    WORKING_DIR = "./working/idea_13"

    # Checkpoints and Logs
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")

    # Submission Outputs
    SUBMISSION_DIR = os.path.join(WORKING_DIR, "submission")
