    # T_0 is cycle length, T_mult is 1 (constant cycle length)
    T_0 = CYCLE_LEN
    T_MULT = 1
    ETA_MIN = 1e-6

    # Curriculum Learning Strategy
    # Phase 1: BCE + Dice (Epochs 0-100)
    # Phase 2: Lovasz Hinge (Epochs 101-150)
    LOSS_SWITCH_EPOCH = 100

    # Snapshot Ensembling
    # Save best models from these cycles for final inference
    SNAPSHOT_CYCLES = [2, 3]  # 1-indexed cycles (Cycle 2 and Cycle 3)
