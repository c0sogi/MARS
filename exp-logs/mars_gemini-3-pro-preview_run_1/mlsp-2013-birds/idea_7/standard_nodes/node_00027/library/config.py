import os
import torch


class Config:
    """
    Configuration class for the Ensemble-Distilled ResNet-34 Bird Species Classification.
    Centralizes all file paths, hyperparameters, and global settings.
    """

    # =========================================================================
    # Directories and Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    ESSENTIAL_DATA_DIR = os.path.join(INPUT_DIR, "essential_data")
    SUPPLEMENTAL_DATA_DIR = os.path.join(INPUT_DIR, "supplemental_data")

    # Spectrograms are located here
    SPECTROGRAM_DIR = os.path.join(SUPPLEMENTAL_DATA_DIR, "spectrograms")

    # Working directory for caching intermediate files (e.g., processed tensors)
    # Specific to 'idea_7' as per the strategy
    WORKING_DIR = "./working/idea_7"

    # Metadata files (generated by the metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Sample submission file for format reference
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output path for the final submission
    SUBMISSION_PATH = "./submission/submission.csv"

    # =========================================================================
    # Data Parameters
    # =========================================================================
    # Input dimensions: Height x Width
    # Height 256 preserves frequency resolution.
    # Width 512 captures temporal context and densifies features.
    IMG_HEIGHT = 256
    IMG_WIDTH = 512

    # Number of bird species
    NUM_CLASSES = 19

    # Normalization statistics (ImageNet defaults, can be adjusted if computing dataset specific)
    # Using ImageNet stats is standard for transfer learning with RGB replication
    NORM_MEAN = [0.485, 0.456, 0.406]
    NORM_STD = [0.229, 0.224, 0.225]

    # =========================================================================
    # Model Parameters
    # =========================================================================
    MODEL_NAME = "resnet34"
    PRETRAINED = True

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    SEED = 42
    BATCH_SIZE = 32
    EPOCHS = 20
    LEARNING_RATE = 3e-4  # Stable LR to prevent optimization collapse

    # Mixup regularization
    USE_MIXUP = True
    MIXUP_ALPHA = 0.2

    # Hardware
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # =========================================================================
    # Ensemble / Distillation Parameters
    # =========================================================================
    # Number of teacher models to train for the ensemble
    NUM_TEACHERS = 3
    # Seeds for each teacher to ensure diversity
    TEACHER_SEEDS = [42, 43, 44]

    # =========================================================================
    # Debugging / Development
    # =========================================================================
    # Set to True to run on a small subset of data for quick pipeline verification
    DEBUG = False
    DEBUG_SUBSET_SIZE = 32  # Number of samples to use in debug mode

    @classmethod
    def setup_directories(cls):
        """
        Ensures that necessary working directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(os.path.dirname(cls.SUBMISSION_PATH), exist_ok=True)


# Automatically setup directories when config is imported
Config.setup_directories()
