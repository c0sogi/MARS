import os
import torch


class Config:
    """
    Global configuration for the Pulmonary Fibrosis Progression prediction task.
    Implements settings for the Prior-Preserving Symmetric Dual-Axis Network (Idea 12).
    """

    # =========================================================================
    # File Paths & Directories
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Cache directory for deterministic data processing (Idea 12 specific)
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_12")

    # Metadata file paths (generated by the metadata script)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Submission paths
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Configuration
    # =========================================================================
    # Image preprocessing
    IMAGE_SIZE = 224  # Native resolution to avoid upscaling artifacts
    NUM_SLABS = 3  # Tri-slab approach
    SLAB_OVERLAP = 0.15  # 15% overlap between slabs

    # Tabular features
    # Numerical features to be normalized
    TABULAR_NUM_FEATURES = ["Age", "Percent"]
    # Categorical features to be encoded
    TABULAR_CAT_FEATURES = ["Sex", "SmokingStatus"]

    # Debugging / Development
    DEBUG = False  # Set to True to run in fast debug mode
    MAX_TRAIN_SAMPLES = None  # Limit training samples (None for full dataset)
    MAX_VAL_SAMPLES = None  # Limit validation samples (None for full dataset)

    # =========================================================================
    # Model Architecture
    # =========================================================================
    MODEL_NAME = "PriorPreservingSymmetricDualAxisNet"
    BACKBONE = "efficientnet_b0"
    PRETRAINED = True

    # Dimensions
    EMBED_DIM = 512  # Dimension D for projection and fusion
    OUTPUT_DIM = 3  # Outputs: alpha (slope), sigma_base, sigma_growth

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    SEED = 42
    BATCH_SIZE = 32
    EPOCHS = 50
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2  # For AdamW
    PATIENCE = 8  # Strict early stopping (6-8 epochs recommended)
    NUM_WORKERS = 4

    # Scheduler
    T_MAX = EPOCHS  # For Cosine Annealing
    ETA_MIN = 1e-6

    # =========================================================================
    # Metric & Loss Constants
    # =========================================================================
    # Modified Laplace Log Likelihood constants
    MAX_ERROR_THRESHOLD = 1000.0  # Delta clipping
    MIN_CONFIDENCE = 70.0  # Sigma clipping

    # =========================================================================
    # Hardware
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Initialize the environment by creating necessary directories.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Automatically setup directories when config is imported
Config.setup()
