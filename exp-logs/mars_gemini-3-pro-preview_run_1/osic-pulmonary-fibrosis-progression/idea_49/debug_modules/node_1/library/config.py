import os
import torch


class Config:
    """
    Configuration for Shared-Latent Holistic Dual-Axis Network (SLH-DAN).
    Centralizes all hyperparameters, file paths, and model settings.
    """

    # ==========================================
    # 1. General Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 20  # Number of samples to use in debug mode

    # ==========================================
    # 2. File Paths & Directories
    # ==========================================
    # Input Roots
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_ROOT, "sample_submission.csv")

    # DICOM Directories (Relative to INPUT_ROOT)
    TRAIN_DICOM_DIR = "train"
    TEST_DICOM_DIR = "test"

    # Output Directories
    WORKING_DIR = "./working"
    IDEA_DIR = os.path.join(WORKING_DIR, "idea_49")
    CACHE_DIR = os.path.join(IDEA_DIR, "cache")
    CHECKPOINTS_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure output directories exist
    os.makedirs(IDEA_DIR, exist_ok=True)
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(CHECKPOINTS_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================================
    # 3. Data Preprocessing (Tri-Slab)
    # ==========================================
    IMG_SIZE = 224  # Native resolution for EfficientNet-B0
    NUM_SLABS = 3  # Number of slabs per view (Axial/Coronal)
    SLAB_OVERLAP = 0.15  # 15% overlap between slabs

    # Augmentation
    USE_AUGMENTATION = True
    NO_INTENSITY_AUG = True  # Strictly disable brightness/contrast changes

    # ==========================================
    # 4. Model Architecture (SLH-DAN)
    # ==========================================
    BACKBONE_NAME = "efficientnet_b0"
    BACKBONE_PRETRAINED = True

    # Dimensions
    BACKBONE_DIM = 1280  # Output dim of EfficientNet-B0 GAP (no projection)
    LATENT_DIM = 128  # Shared latent vector for tabular data
    ALIGN_DIM = 1280  # Projection dim for latent vector to match visual
    HEAD_HIDDEN_DIM = 128  # Bottleneck dimension in the prediction head

    # Regularization
    DROPOUT_RATE = 0.1

    # ==========================================
    # 5. Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 32
    EPOCHS = 50
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2  # Standard for AdamW

    # Scheduler
    T_MAX = EPOCHS  # For CosineAnnealingLR
    ETA_MIN = 1e-6

    # Early Stopping
    PATIENCE = 8  # Strict patience as per design

    # Compute
    NUM_WORKERS = 4  # 12 vCPUs available, 4 is safe
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================
    # 6. Metric & Loss
    # ==========================================
    MAX_ERROR = 1000  # Clip absolute error at 1000 ml
    MIN_CONFIDENCE = 70  # Clip confidence at 70 ml

    @classmethod
    def get_cache_path(cls, patient_id, view_plane):
        """
        Generates a safe path for caching processed images.
        view_plane: 'axial' or 'coronal'
        """
        filename = f"{patient_id}_{view_plane}.npy"
        return os.path.join(cls.CACHE_DIR, filename)
