import os
import torch


class Config:
    """
    Configuration class for the Visually-Contextualized Residual Network.
    Centralizes all hyperparameters, file paths, and model settings.
    """

    # --------------------
    # General Setup
    # --------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # --------------------
    # File Paths
    # --------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata CSVs (Generated by the metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Original Sample Submission (for reference or headers)
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # DICOM Directories
    # Metadata 'dicom_dir' fields are relative (e.g., "train/ID..."), so we use INPUT_DIR as root.
    DICOM_ROOT = INPUT_DIR

    # Output Directories
    WORKING_DIR = "./working"
    IDEA_DIR = os.path.join(WORKING_DIR, "idea_16")
    CACHE_DIR = IDEA_DIR
    CHECKPOINT_DIR = os.path.join(IDEA_DIR, "checkpoints")

    # Submission Output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure output directories exist
    os.makedirs(IDEA_DIR, exist_ok=True)
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # --------------------
    # Data Configuration
    # --------------------
    IMG_SIZE = 224  # Native resolution to avoid upscaling artifacts
    SLAB_COUNT = 3  # Tri-slab input (3 channels per view)

    # Tabular features to be encoded
    TABULAR_COLS = ["Age", "Sex", "SmokingStatus", "Percent"]

    # --------------------
    # Model Configuration
    # --------------------
    BACKBONE_NAME = "efficientnet_b0"

    # Dimensionality
    VISUAL_DIM = 1280  # EfficientNet-B0 output channels (Global Average Pooling)
    TABULAR_INPUT_DIM = 4  # Number of tabular features
    TABULAR_HIDDEN_DIM = 512
    PROJECTION_DIM = 1280  # Project tabular embedding to match visual dim for attention

    # Attention Mechanism
    ATTENTION_HEADS = 4
    ATTENTION_LAYERS = 1

    # Parametric Head Initialization
    # These values help the model start in a reasonable regime
    INIT_ALPHA = -5.0  # Assume a slight decline in lung function initially
    INIT_SIGMA_BASE = 100.0  # Initial confidence (approx 100ml)
    INIT_SIGMA_GROWTH = 1.0  # Initial uncertainty growth rate per week

    # --------------------
    # Training Configuration
    # --------------------
    BATCH_SIZE = 32
    EPOCHS = 50
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2
    PATIENCE = 8  # Strict early stopping to prevent overfitting on small data

    # Scheduler Settings (Cosine Annealing)
    T_MAX = EPOCHS
    ETA_MIN = 1e-6

    # --------------------
    # Metric / Loss Constants
    # --------------------
    # Used for the Modified Laplace Log Likelihood
    MAX_ERROR = 1000.0  # Error clipping threshold (ml)
    MIN_CONFIDENCE = 70.0  # Minimum confidence clipping (ml)
