import os
import torch


class Config:
    """
    Configuration class for the Shared-Latent Aligned Dual-Axis Network (SLA-DAN).
    Centralizes all hyperparameters, file paths, and constant settings.
    """

    def __init__(self, debug: bool = False, epochs: int = 50, batch_size: int = 32):
        """
        Initialize configuration with flexible overrides.

        Args:
            debug (bool): If True, runs in debug mode (fewer epochs, subset of data).
            epochs (int): Maximum number of training epochs.
            batch_size (int): Batch size for training and inference.
        """
        # ==========================================
        # 1. File Systems & Paths
        # ==========================================
        self.INPUT_ROOT = "./input"
        self.METADATA_DIR = "./metadata"

        # Metadata files (generated by previous pipeline steps)
        self.TRAIN_CSV = os.path.join(self.METADATA_DIR, "train.csv")
        self.VAL_CSV = os.path.join(self.METADATA_DIR, "val.csv")
        self.TEST_CSV = os.path.join(self.METADATA_DIR, "test.csv")

        # Working Directories
        # Using a specific subdirectory for Idea 44 to ensure isolation
        self.WORKING_DIR = "./working/idea_44"
        self.CACHE_DIR = os.path.join(self.WORKING_DIR, "cache")
        self.CHECKPOINT_DIR = os.path.join(self.WORKING_DIR, "checkpoints")
        self.SUBMISSION_DIR = "./submission"
        self.SUBMISSION_PATH = os.path.join(self.SUBMISSION_DIR, "submission.csv")

        # Create necessary directories
        os.makedirs(self.CACHE_DIR, exist_ok=True)
        os.makedirs(self.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(self.SUBMISSION_DIR, exist_ok=True)

        # ==========================================
        # 2. Data Hyperparameters
        # ==========================================
        self.DEBUG = debug
        self.SEED = 42

        # Image Processing: Fixed Overlapping Orthogonal Tri-Slabs
        self.IMG_SIZE = 224  # Native resolution for EfficientNet-B0
        self.NUM_SLABS = 3  # Split volume into 3 slabs
        self.SLAB_OVERLAP = 0.15  # 15% overlap between slabs
        self.IN_CHANNELS = 3  # RGB (MIPs mapped to channels)

        # Caching Logic
        # If True, dataset will attempt to load pre-processed .npy files from CACHE_DIR
        self.LOAD_CACHED_DATA = True

        # Tabular Data
        # Strictly excluding 'Weeks' from the static encoder input
        self.TABULAR_COLS = ["Age", "Sex", "SmokingStatus", "Percent"]
        self.TABULAR_INPUT_DIM = 9  # Estimated dim after encoding (Age:1, Percent:1, Sex:2, Smoking:5 approx)

        # ==========================================
        # 3. Model Architecture (SLA-DAN)
        # ==========================================
        # Independent Low-Capacity Visual Backbones
        self.BACKBONE = "tf_efficientnet_b0_ns"
        self.BACKBONE_DIM = 1280  # Output dimension of EfficientNet-B0 GAP

        # Shared-Latent Tabular Encoder
        self.LATENT_DIM = 128  # Dimension of the Shared Latent Vector (T_lat)

        # Bifurcated Flow
        self.PROJ_DIM = 1280  # Alignment Branch projection dimension (matches backbone)

        # Attention Mechanism (Pre-Norm Symmetric)
        self.NUM_HEADS = 4
        self.ATTN_DROPOUT = 0.1
        self.FFN_DIM = 2048  # Feed-Forward Network hidden dimension

        # ==========================================
        # 4. Training Hyperparameters
        # ==========================================
        self.EPOCHS = 2 if self.DEBUG else epochs
        self.BATCH_SIZE = batch_size
        self.NUM_WORKERS = 4

        # Optimization
        self.LR = 1e-4
        self.WEIGHT_DECAY = 1e-2
        self.PATIENCE = 8  # Strict early stopping patience

        # Metric Constants (Modified Laplace Log Likelihood)
        self.MAX_ERROR = 1000  # Threshold for absolute error
        self.CONFIDENCE_CLIP = 70  # Minimum clipping for confidence (sigma)

        # Device Configuration
        self.DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    def display(self):
        """Prints the configuration."""
        print("\n" + "=" * 30)
        print("CONFIG")
        print("=" * 30)
        for k, v in self.__dict__.items():
            print(f"{k}: {v}")
        print("=" * 30 + "\n")
