import os
import torch


class Config:
    """
    Configuration for Content-Adaptive Symmetric Dual-Axis Network (CAS-DAN).
    Centralizes all hyperparameters, file paths, and model settings.
    """

    # ==========================================
    # 1. General Settings
    # ==========================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    DEBUG = False  # Set to True to run on a small subset for testing
    NUM_WORKERS = 4

    # ==========================================
    # 2. File Paths
    # ==========================================
    # Input Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    DICOM_ROOT = INPUT_DIR  # Metadata 'dicom_dir' is relative to input root

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Working Directories (Cache & Outputs)
    # We use a specific subdirectory for this idea to keep things organized
    WORKING_DIR = "./working/idea_22"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Cache Files (for preprocessed images/features)
    CACHE_DIR = WORKING_DIR
    CACHE_TRAIN_PATH = os.path.join(CACHE_DIR, "train_cache.npy")
    CACHE_VAL_PATH = os.path.join(CACHE_DIR, "val_cache.npy")
    CACHE_TEST_PATH = os.path.join(CACHE_DIR, "test_cache.npy")

    # Model Checkpoints
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # Submission
    SUBMISSION_DIR = "./submission"
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # 3. Data Processing Hyperparameters
    # ==========================================
    # Image
    IMG_SIZE = 224  # Native resolution for EfficientNet-B0
    NUM_SLABS = 3  # Tri-Slab design
    SLAB_OVERLAP = 0.15  # 15% overlap between slabs

    # Normalization (ImageNet stats)
    MEAN = [0.485, 0.456, 0.406]
    STD = [0.229, 0.224, 0.225]

    # ==========================================
    # 4. Model Architecture
    # ==========================================
    BACKBONE_NAME = "tf_efficientnet_b0_ns"  # Noisy Student weights
    VISUAL_DIM = 1280  # Native output dim of B0 (do not project down)

    # Tabular Embedding
    # Inputs: Age(1) + Sex(1) + Smoking(3) + Percent(1) = 6 (approx, depends on encoding)
    TABULAR_HIDDEN_DIM = 512
    PROJECTION_DIM = 1280  # Up-project to match VISUAL_DIM

    # Attention
    NUM_HEADS = 4  # For Symmetric Self-Attention
    DROPOUT = 0.1

    # ==========================================
    # 5. Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 32
    EPOCHS = 50
    PATIENCE = 8  # Strict early stopping
    LEARNING_RATE = 1e-4  # Fine-tuning rate
    WEIGHT_DECAY = 1e-2
    SCHEDULER_T_MAX = 50  # Cosine Annealing cycles
    SCHEDULER_MIN_LR = 1e-6

    # ==========================================
    # 6. Metric / Loss Constants
    # ==========================================
    MAX_ERROR_CLIP = 1000  # Clip absolute error at 1000ml
    CONFIDENCE_CLIP = 70  # Clip confidence at 70ml
