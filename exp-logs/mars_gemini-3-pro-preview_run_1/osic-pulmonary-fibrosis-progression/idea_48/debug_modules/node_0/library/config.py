import os
import torch


class Config:
    """
    Configuration class for the Shared-Latent Holistic Dual-Axis Network (SLH-DAN).
    Centralizes all hyperparameters and constants.
    """

    # ==========================================
    # 1. General & Reproducibility
    # ==========================================
    SEED = 42
    DEBUG = False  # Toggle for debug mode (smaller subset, fewer epochs)

    # Hardware settings
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 8  # Optimized for 12 vCPUs

    # ==========================================
    # 2. File System Paths
    # ==========================================
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Idea-specific directory for caching and artifacts
    IDEA_DIR = os.path.join(WORKING_DIR, "idea_48")
    CACHE_DIR = IDEA_DIR  # Directory to store processed/cached data

    # Metadata files (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # DICOM Source Directories
    # Note: These are relative to INPUT_DIR in the metadata, but we define absolute roots here
    TRAIN_DICOM_ROOT = os.path.join(INPUT_DIR)  # Metadata contains 'train/ID...'
    TEST_DICOM_ROOT = os.path.join(INPUT_DIR)  # Metadata contains 'test/ID...'

    # Output Paths
    CHECKPOINT_DIR = os.path.join(IDEA_DIR, "checkpoints")
    BEST_MODEL_PATH = os.path.join(IDEA_DIR, "best_model.pth")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # 3. Data Preprocessing (Tri-Slab)
    # ==========================================
    IMG_SIZE = 224  # Native resolution for EfficientNet-B0
    SLAB_COUNT = 3  # Number of slabs per view
    SLAB_OVERLAP = 0.15  # 15% overlap between slabs

    # Normalization constants (ImageNet defaults)
    MEAN = [0.485, 0.456, 0.406]
    STD = [0.229, 0.224, 0.225]

    # ==========================================
    # 4. Model Architecture (SLH-DAN)
    # ==========================================
    BACKBONE_NAME = "efficientnet_b0"
    VISUAL_DIM = 1280  # Dimension of EfficientNet-B0 GAP output (do not compress)
    LATENT_DIM = 128  # Dimension of Shared Latent Vector (Tabular/Prior)

    # The model predicts slope, sigma_base, sigma_growth
    NUM_OUTPUTS = 3

    # ==========================================
    # 5. Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 32  # A100 allows larger batch size
    EPOCHS = 50  # Max epochs
    LEARNING_RATE = 1e-4  # Initial learning rate
    WEIGHT_DECAY = 1e-2  # For AdamW

    # Scheduler
    T_MAX = 50  # Cosine Annealing T_max (usually equal to epochs)
    ETA_MIN = 1e-6  # Minimum learning rate

    # Early Stopping
    PATIENCE = 8  # Stop if val score doesn't improve for 8 epochs

    # Metric Constraints
    MAX_ERROR = 1000.0  # Clip absolute error at 1000 ml
    MIN_CONFIDENCE = 70.0  # Clip confidence at 70 ml

    # ==========================================
    # 6. Debugging / Development
    # ==========================================
    # If set to an integer, only use this many samples for training/validation
    DEBUG_SUBSET_SIZE = None

    @classmethod
    def setup(cls):
        """
        Create necessary working directories.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories upon import
Config.setup()
