import os
import torch


class Config:
    """
    Configuration class for the Lung Function Decline Prediction task.
    Implements settings for the Dynamic-Depth GeM-Attention Network.
    """

    # --------------------
    # General Settings
    # --------------------
    PROJECT_NAME = "lung_decline_prediction"
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4
    DEBUG = False  # Set to True to use a small subset of data for debugging

    # --------------------
    # File Paths
    # --------------------
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata CSV Files (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Sample submission for reference
    SAMPLE_SUBMISSION = os.path.join(INPUT_ROOT, "sample_submission.csv")

    # Cache Directory for processed features/images (Idea 10 specific)
    CACHE_DIR = "./working/idea_10"
    os.makedirs(CACHE_DIR, exist_ok=True)

    # Output Submission Path
    SUBMISSION_PATH = "./submission/submission.csv"
    os.makedirs(os.path.dirname(SUBMISSION_PATH), exist_ok=True)

    # Model Checkpoint Path
    MODEL_SAVE_PATH = os.path.join(CACHE_DIR, "best_model.pth")

    # --------------------
    # Data Preprocessing / Augmentation
    # --------------------
    IMG_SIZE = 224
    NUM_SLABS = 3

    # Depth Jitter (Stochastic Tri-Slab) Parameters
    # We split the Z-axis into 3 slabs. The boundaries are jittered during training.
    # Standard boundaries would be 0.33 and 0.66.
    SLAB_BOUND1_RANGE = (0.25, 0.40)  # Range for the first split point
    SLAB_BOUND2_RANGE = (0.60, 0.75)  # Range for the second split point

    # Inference settings
    INFERENCE_OVERLAP = 0.15  # 15% overlap between slabs during inference

    # Normalization (ImageNet stats)
    MEAN = [0.485, 0.456, 0.406]
    STD = [0.229, 0.224, 0.225]

    # --------------------
    # Model Architecture
    # --------------------
    BACKBONE = "efficientnet_b0"
    PRETRAINED = True

    # GeM Pooling Initial Parameter p
    GEM_P_INIT = 3.0

    # Dimensions
    HIDDEN_DIM = 512
    DROPOUT = 0.2

    # Tabular Features
    TABULAR_COLS = ["Weeks", "Percent", "Age", "Sex", "SmokingStatus"]

    # --------------------
    # Training Hyperparameters
    # --------------------
    BATCH_SIZE = 32
    EPOCHS = 30
    LR = 3e-4
    WEIGHT_DECAY = 1e-2

    # Cosine Annealing Scheduler
    T_MAX = 30
    ETA_MIN = 1e-6

    # Early Stopping
    PATIENCE = 8  # Strict patience as per strategy

    # --------------------
    # Metric / Loss Function
    # --------------------
    # Modified Laplace Log Likelihood settings
    CONFIDENCE_CLIP = 70.0
    MAX_ERROR = 1000.0

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print("=" * 30)
        print("CONFIGURATION")
        print("=" * 30)
        for key, val in cls.__dict__.items():
            if not key.startswith("__") and not callable(val):
                print(f"{key}: {val}")
        print("=" * 30)
