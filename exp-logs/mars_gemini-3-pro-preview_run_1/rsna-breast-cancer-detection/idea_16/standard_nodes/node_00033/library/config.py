import os
import torch


class Config:
    """
    Central configuration for the Breast Cancer Detection task.
    Implements settings for the FPN-Enhanced Deformable Siamese network.
    """

    # -------------------------------------------------------------------------
    # General & Reproducibility
    # -------------------------------------------------------------------------
    PROJECT_NAME = "Siamese_FPN_Deformable_Cancer_Detection"
    SEED = 42

    # Debugging flags
    # Set DEBUG to True to train on a small subset of data for verification
    DEBUG = False
    DEBUG_SUBSET_SIZE = 500

    # -------------------------------------------------------------------------
    # Directory Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Cache directory for deterministic data processing (Idea 16)
    # Used to store processed tensors/dataframes to speed up subsequent runs
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_16")

    # Submission directory
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Paths
    # -------------------------------------------------------------------------
    # Metadata CSVs generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Image Source Directories
    TRAIN_IMAGES_DIR = os.path.join(INPUT_DIR, "train_images")
    TEST_IMAGES_DIR = os.path.join(INPUT_DIR, "test_images")

    # -------------------------------------------------------------------------
    # Data Processing Parameters
    # -------------------------------------------------------------------------
    # Input resolution: 768x768 as specified for high-res mammography
    IMG_SIZE = (768, 768)

    # Channels: 3 (1 Grayscale Image + 1 Age Map + 1 Implant Map)
    NUM_CHANNELS = 3

    # -------------------------------------------------------------------------
    # Model Hyperparameters
    # -------------------------------------------------------------------------
    BACKBONE = "efficientnet_b2"
    PRETRAINED = False

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    # Batch Size: 8 fits on A100 (40GB) with Siamese 768x768 + Gradients
    BATCH_SIZE = 8

    # Epochs: 10 is sufficient for convergence with pretraining
    NUM_EPOCHS = 10

    # Learning Rate: 1e-4 as specified
    LEARNING_RATE = 1e-4

    # Weight Decay for AdamW
    WEIGHT_DECAY = 1e-2

    # -------------------------------------------------------------------------
    # Loss & Optimization
    # -------------------------------------------------------------------------
    # Positive Weight: 47.0 to approximate inverse class frequency (Neg/Pos ratio)
    POS_WEIGHT = 47.0

    # Gradient Clipping: Disabled (None) to allow large updates for minority class
    CLIP_GRAD_NORM = None

    # Scheduler: Cosine Annealing
    T_MAX = NUM_EPOCHS
    ETA_MIN = 1e-6

    # -------------------------------------------------------------------------
    # Hardware
    # -------------------------------------------------------------------------
    # 12 vCPUs available, 4 workers is a safe balance
    NUM_WORKERS = 4

    # Device selection
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Ensures that necessary working directories exist.
        Should be called at the start of execution.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        print(f"Configuration loaded. Device: {cls.DEVICE}, Cache: {cls.CACHE_DIR}")
