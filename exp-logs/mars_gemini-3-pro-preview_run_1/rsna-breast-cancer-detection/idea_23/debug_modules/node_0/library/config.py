import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration class for the Breast Cancer Detection Task.
    Centralizes all hyperparameters, file paths, and compute settings.
    """

    # ==========================
    # Path Configuration
    # ==========================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Cache directory for deterministic data processing (Idea 23)
    # Stores processed parquet/npy files to speed up subsequent runs
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_23")

    # Metadata Paths (Generated by the provided metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Submission Path
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================
    # Data Configuration
    # ==========================
    # Input resolution for the Siamese Network
    IMAGE_SIZE = (768, 768)

    # Input channels: Image (1) + Age (1) + Implant (1) = 3
    CHANNELS = 3

    # Debugging flags
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 100  # Number of samples to use when DEBUG is True

    # ==========================
    # Model Configuration
    # ==========================
    # Backbone for the Siamese Network
    BACKBONE = "efficientnet_b2"
    PRETRAINED = True

    # Dropout rates
    DROP_RATE = 0.3
    DROP_PATH_RATE = 0.2

    # ==========================
    # Training Configuration
    # ==========================
    SEED = 42

    # Batch size (Conservative for 768x768 on 40GB GPU with Siamese architecture)
    BATCH_SIZE = 8

    # Training duration
    NUM_EPOCHS = 10

    # Optimizer settings (AdamW)
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2

    # Loss Function Weights
    # Aggressive positive weighting to handle high class imbalance (approx 1:47)
    POS_WEIGHT = 47.0

    # Optimization Strategy
    # Gradient clipping is explicitly disabled to allow large updates for the minority class
    GRADIENT_CLIPPING = None

    # Scheduler Settings (Cosine Annealing)
    T_MAX = NUM_EPOCHS
    ETA_MIN = 1e-6

    # ==========================
    # Compute Configuration
    # ==========================
    NUM_WORKERS = 12
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    USE_AMP = True  # Enable Automatic Mixed Precision for A100

    @classmethod
    def setup(cls):
        """
        Initializes the environment by creating necessary directories
        and setting random seeds for reproducibility.
        """
        # Create directories
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set fixed random seeds
        cls.seed_everything(cls.SEED)

    @staticmethod
    def seed_everything(seed):
        """
        Sets seeds for all random number generators.
        """
        random.seed(seed)
        os.environ["PYTHONHASHSEED"] = str(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
