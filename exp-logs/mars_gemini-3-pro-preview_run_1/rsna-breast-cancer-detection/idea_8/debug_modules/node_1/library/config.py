import os
import torch


class Config:
    """
    Configuration for the Spatial Symmetry-Difference Siamese Network.

    Architecture:
        - Siamese EfficientNet-B2 Backbone
        - Input: 3x768x768 (Image + Spatial Age + Spatial Implant)
        - Strategy: Spatial Difference (Target - Contralateral)
    """

    # =========================================================================
    # Random Seed for Reproducibility
    # =========================================================================
    SEED = 42

    # =========================================================================
    # File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata generated by the provided script
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Working directory for caching processed data and model checkpoints
    # Specific to "Idea 8" as per instructions
    WORKING_DIR = "./working/idea_8"

    # Submission output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data & Image Processing
    # =========================================================================
    # Input dimensions: (Channels, Height, Width)
    # Channels = 3 (1 Grayscale Image + 1 Age Map + 1 Implant Map)
    IMG_SIZE = 768
    IN_CHANNELS = 3

    # =========================================================================
    # Model Architecture
    # =========================================================================
    BACKBONE = "efficientnet_b2"
    PRETRAINED = True

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    # Batch size constrained by 40GB VRAM, Siamese architecture, and 768px resolution
    BATCH_SIZE = 4

    # Optimization
    NUM_EPOCHS = 10
    LR = 1e-4

    # Loss Function Weights
    # Approximating inverse class frequency for imbalance handling
    POS_WEIGHT = 47.0

    # Gradient Handling
    CLIP_GRADIENTS = (
        False  # Disabled as per strategy to allow large updates for minority class
    )

    # =========================================================================
    # Hardware & Compute
    # =========================================================================
    NUM_WORKERS = 12  # Matches available vCPUs
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # =========================================================================
    # Debugging & Development
    # =========================================================================
    # Set DEBUG to True to run on a small subset of data for quick iteration
    DEBUG = False
    DEBUG_SIZE = 500

    @classmethod
    def setup(cls):
        """
        Initializes the environment by creating necessary directories.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Execute setup on import to ensure directories exist
Config.setup()
