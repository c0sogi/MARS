import os
import torch
import random
import numpy as np


class Config:
    """
    Central configuration for the Aligned-Attentive Siamese Network pipeline.
    """

    # ==========================================
    # Reproducibility & Environment
    # ==========================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 12  # Utilizing all available vCPUs
    MAX_RUNTIME_HOURS = 24

    # ==========================================
    # File Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the provided script
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Working directories
    WORKING_DIR = "./working"
    CACHE_DIR = "./working/idea_21"  # Specific directory for this idea

    # Output paths
    MODEL_FILENAME = "siamese_efficientnet_b2.pth"
    MODEL_SAVE_PATH = os.path.join(CACHE_DIR, MODEL_FILENAME)
    SUBMISSION_PATH = "submission.csv"  # Standard submission location

    # ==========================================
    # Model Architecture
    # ==========================================
    BACKBONE = "efficientnet_b2"
    # Input: 3 Channels (1 Image + 1 Age Map + 1 Implant Map)
    IN_CHANNELS = 3
    IMG_SIZE = (768, 768)

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    # Batch size tailored for A100 40GB with Siamese overhead
    BATCH_SIZE = 8
    LEARNING_RATE = 1e-4

    # Loss Function Weights
    # Aggressive positive weighting to handle 1:47 imbalance
    POS_WEIGHT = 47.0

    # Optimization
    GRADIENT_CLIPPING = False  # Disabled to allow large updates for minority class
    WEIGHT_DECAY = 1e-2

    # ==========================================
    # Runtime & Debugging
    # ==========================================
    EPOCHS = 10
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 1000  # Number of samples to use in debug mode
    PIN_MEMORY = False  # Disabled to prevent OOM (Cite debug_lesson_9)

    @classmethod
    def setup(cls, debug=False, epochs=None):
        """
        Initialize the environment, directories, and configuration overrides.

        Args:
            debug (bool): If True, enables debug mode (smaller dataset).
            epochs (int, optional): Override the default number of epochs.
        """
        # 1. Override Configuration
        if debug:
            cls.DEBUG = True
            cls.EPOCHS = 2 if epochs is None else epochs
            print(f"[Config] Debug mode enabled. Epochs set to {cls.EPOCHS}.")
        elif epochs is not None:
            cls.EPOCHS = epochs
            print(f"[Config] Epochs overridden to {cls.EPOCHS}.")

        # 2. Create Directories
        os.makedirs(cls.CACHE_DIR, exist_ok=True)

        # 3. Set Random Seeds for Reproducibility
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(cls.SEED)
            # Ensure deterministic behavior where possible
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

        print(f"[Config] Setup complete. Device: {cls.DEVICE}")
        print(f"[Config] Cache Directory: {cls.CACHE_DIR}")
