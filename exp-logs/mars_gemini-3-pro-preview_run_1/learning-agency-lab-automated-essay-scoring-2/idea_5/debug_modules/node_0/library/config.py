import os
import torch


class Config:
    """
    Configuration class for Essay Scoring with DeBERTa-v3-Large.
    Centralizes settings for Domain Adaptive Pre-training (DAPT),
    Supervised Fine-Tuning with LLRD, and Inference.
    """

    # ==========================
    # General Settings
    # ==========================
    seed = 42
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    num_workers = 4
    debug = False  # Set to True to run on a small subset for debugging

    # ==========================
    # File Paths & Directories
    # ==========================
    # Input Metadata (Generated by previous steps)
    train_path = "./metadata/train.csv"
    val_path = "./metadata/val.csv"
    test_path = "./metadata/test.csv"
    sample_submission_path = "./input/sample_submission.csv"

    # Output Directory (for caching data, saving models, and submissions)
    # Using 'idea_5' as per the working directory structure hint
    output_dir = "./working/idea_5/"
    os.makedirs(output_dir, exist_ok=True)

    # ==========================
    # Model Architecture
    # ==========================
    model_name = "microsoft/deberta-v3-large"
    max_length = 1024
    num_labels = 1  # Regression output (score)

    # Pooling Strategy: 'mean', 'max', 'attention' (WeightedLayerPooling)
    pooling = "attention"

    # Dropout settings - set to 0 for regression stability
    hidden_dropout_prob = 0.0
    attention_probs_dropout_prob = 0.0

    # ==========================
    # Training Hyperparameters (Fine-Tuning)
    # ==========================
    # Batch sizes (tuned for A100 40GB)
    train_batch_size = 4
    valid_batch_size = 8
    gradient_accumulation_steps = 4

    # Optimization
    epochs = 4
    learning_rate = 2e-5  # Backbone Learning Rate
    weight_decay = 0.01
    max_grad_norm = 1.0
    warmup_ratio = 0.1
    scheduler = "cosine"

    # Loss Function
    loss_type = "mse"  # Mean Squared Error for QWK optimization

    # ==========================
    # Layer-wise Learning Rate Decay (LLRD)
    # ==========================
    use_llrd = True
    llrd_decay = 0.9
    head_lr = 1e-4  # Higher LR for the regression head

    # ==========================
    # Masked Language Modeling (DAPT)
    # ==========================
    # Pre-training on combined Train + Test data
    mlm_epochs = 3
    mlm_batch_size = 4
    mlm_learning_rate = 1e-5
    mlm_probability = 0.15

    # ==========================
    # Cross-Validation
    # ==========================
    num_folds = 5

    # ==========================
    # Inference
    # ==========================
    use_fp16 = True
