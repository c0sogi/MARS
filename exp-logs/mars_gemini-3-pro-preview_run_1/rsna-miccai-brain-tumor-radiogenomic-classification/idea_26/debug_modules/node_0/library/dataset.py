import os
import cv2
import torch
import numpy as np
from torch.utils.data import Dataset
from library.data_processing import get_processed_metadata, read_dicom, get_transforms

IMG_SIZE = 224


class SIADSDataset(Dataset):
    """
    Dataset class for Scale-Invariant Anatomically-Anchored Dense-Slab (SIA-DS) Network.
    Loads 9 channels: FLAIR, T1wCE, T2w at 45%, 50%, and 55% relative anatomical depth.
    """

    def __init__(self, df, phase="train"):
        """
        Args:
            df (pd.DataFrame): Dataframe containing file paths for the 9 channels.
            phase (str): 'train', 'val', or 'test'.
        """
        self.df = df
        self.phase = phase
        self.transforms = get_transforms(phase)

        # Define channel order as per the SIA-DS strategy:
        # [FLAIR, T1wCE, T2w] at 45%, then 50%, then 55%
        self.channel_cols = [
            "flair_45",
            "t1wce_45",
            "t2w_45",
            "flair_50",
            "t1wce_50",
            "t2w_50",
            "flair_55",
            "t1wce_55",
            "t2w_55",
        ]

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        images = []

        for col in self.channel_cols:
            path = row[col]
            img = read_dicom(path)

            if img is None:
                # Fallback for corrupt or missing file: black image
                img = np.zeros((IMG_SIZE, IMG_SIZE), dtype=np.float32)
            else:
                # Resize to standard input size
                img = cv2.resize(img, (IMG_SIZE, IMG_SIZE))
                img = img.astype(np.float32)

                # Independent Channel Min-Max Normalization to [0, 1]
                min_val = img.min()
                max_val = img.max()
                if max_val > min_val:
                    img = (img - min_val) / (max_val - min_val)
                else:
                    img = np.zeros_like(img)

            images.append(img)

        # Stack to (H, W, 9)
        # Albumentations expects (H, W, C) input
        vol = np.stack(images, axis=-1)

        # Apply transforms (Augmentations + ToTensorV2)
        if self.transforms:
            augmented = self.transforms(image=vol)
            vol_tensor = augmented["image"]  # Result is (C, H, W) tensor
        else:
            # Fallback if no transforms (should not happen with get_transforms)
            vol_tensor = torch.from_numpy(vol.transpose(2, 0, 1))

        # Return appropriate data based on phase
        if self.phase == "test":
            # Return ID for submission tracking
            return vol_tensor, row["BraTS21ID"]
        else:
            # Return label for training/validation
            label = torch.tensor(row["MGMT_value"], dtype=torch.float32)
            return vol_tensor, label


def get_datasets(metadata_dir="./metadata", load_cached_data=True, limit_size=None):
    """
    Generates and returns the training, validation, and test datasets.

    Args:
        metadata_dir (str): Directory containing the metadata CSV files.
        load_cached_data (bool): If True, attempts to load processed file lists from cache.
        limit_size (int, optional): Limit the number of subjects for debugging.

    Returns:
        tuple: (train_dataset, val_dataset, test_dataset)
    """
    # Define paths to the metadata files generated by the metadata script
    train_meta_path = os.path.join(metadata_dir, "train_metadata.csv")
    val_meta_path = os.path.join(metadata_dir, "val_metadata.csv")
    test_meta_path = os.path.join(metadata_dir, "test_metadata.csv")

    # Process metadata using the library function.
    # This handles ROI detection, slice selection (45%, 50%, 55%), and caching.
    df_train = get_processed_metadata(
        train_meta_path,
        "train",
        load_cached_data=load_cached_data,
        limit_size=limit_size,
    )

    df_val = get_processed_metadata(
        val_meta_path, "val", load_cached_data=load_cached_data, limit_size=limit_size
    )

    df_test = get_processed_metadata(
        test_meta_path, "test", load_cached_data=load_cached_data, limit_size=limit_size
    )

    # Instantiate the datasets
    train_dataset = SIADSDataset(df_train, phase="train")
    val_dataset = SIADSDataset(df_val, phase="val")
    test_dataset = SIADSDataset(df_test, phase="test")

    return train_dataset, val_dataset, test_dataset
