import os
import torch


class Config:
    """
    Configuration class for the MobileNetV3 training pipeline on the iNaturalist dataset.
    Centralizes all file paths, hyperparameters, and compute settings.
    """

    # --------------------------------------------------------------------------
    # Reproducibility
    # --------------------------------------------------------------------------
    SEED = 42

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    # Root directory for read-only input data
    INPUT_ROOT = "./input"

    # Metadata files generated by the analysis script
    METADATA_DIR = "./metadata"
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Output directories for artifacts
    # Using 'idea_1' as the specific working directory for this approach
    WORKING_DIR = "./working/idea_1"
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")

    # Submission directory
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure output directories exist
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # --------------------------------------------------------------------------
    # Data Configuration
    # --------------------------------------------------------------------------
    IMG_SIZE = 224  # Standard resolution for MobileNetV3
    NUM_CLASSES = 1010  # Total number of species in the dataset
    NUM_WORKERS = 4  # Number of subprocesses for data loading (12 vCPUs available)

    # --------------------------------------------------------------------------
    # Model & Training Hyperparameters
    # --------------------------------------------------------------------------
    MODEL_NAME = "efficientnet_b0"
    PRETRAINED = True  # Start with ImageNet weights

    BATCH_SIZE = (
        256  # Increased for EfficientNet-B0 with AMP (Cite solution_lesson_node_00006)
    )
    EPOCHS = 10  # Increased epochs for convergence (Cite solution_lesson_node_00006)
    LEARNING_RATE = 1e-3  # Initial learning rate for AdamW
    WEIGHT_DECAY = 1e-4  # Regularization
    LABEL_SMOOTHING = 0.1  # Label smoothing for fine-grained classification (Cite solution_lesson_node_00006)

    # Early Stopping
    PATIENCE = 3  # Stop if validation loss doesn't improve for 3 epochs

    # --------------------------------------------------------------------------
    # Compute
    # --------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print(f"{'='*20} CONFIGURATION {'='*20}")
        for k, v in cls.__dict__.items():
            if not k.startswith("__") and not callable(v):
                print(f"{k}: {v}")
        print("=" * 55)
