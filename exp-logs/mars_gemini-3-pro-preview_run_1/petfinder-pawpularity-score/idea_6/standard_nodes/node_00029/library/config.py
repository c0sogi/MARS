import os
import numpy as np


class Config:
    """
    Configuration for Tri-Paradigm Stacking with Heterogeneous Interaction Experts.
    Centralizes hyperparameters, file paths, and model definitions.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run on a subset of data for debugging
    N_FOLDS = 5
    NUM_WORKERS = 4
    DEVICE = "cuda"

    # =========================================================================
    # File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for caching intermediate features and models
    # Using 'idea_6' as requested for this iteration
    WORKING_DIR = "./working/idea_6"
    CACHE_DIR = WORKING_DIR

    # Metadata paths (generated by the provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Submission output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Processing
    # =========================================================================
    IMAGE_SIZE = 224
    BATCH_SIZE = 32

    # Feature Extraction
    USE_FLIP_AUGMENTATION = True  # Average features of original and flipped images

    # =========================================================================
    # Model Backbones (Hugging Face IDs)
    # =========================================================================
    # Semantic Expert: CLIP ViT-L/14
    MODEL_CLIP = "openai/clip-vit-large-patch14"

    # Geometric Expert: DINOv2 ViT-Large
    MODEL_DINO = "facebook/dinov2-large"

    # Textural Expert: ConvNeXt Large
    MODEL_CONVNEXT = "facebook/convnext-large-224-22k-1k"

    BACKBONES = [MODEL_CLIP, MODEL_DINO, MODEL_CONVNEXT]

    # =========================================================================
    # Level-0 Expert Hyperparameters
    # =========================================================================

    # 1. Linear Expert: Ridge Regression
    # Search range up to ~50,000 to handle high-dim embeddings
    RIDGE_ALPHAS = np.logspace(-2, 4.7, 50).tolist()

    # 2. Kernel Expert: Support Vector Regression (SVR)
    SVR_KERNEL = "rbf"
    SVR_C = [0.1, 1.0, 10.0, 50.0]
    SVR_EPSILON = 0.1

    # 3. Partitioning Expert: ExtraTrees Regressor
    # Trained on PCA-reduced embeddings + Metadata
    ET_N_ESTIMATORS = 500
    ET_MIN_SAMPLES_SPLIT = 2
    ET_RANDOM_STATE = SEED

    # Dimensionality Reduction for Tree Models
    PCA_COMPONENTS = 64

    # =========================================================================
    # Level-1 Meta-Learner Hyperparameters
    # =========================================================================
    # Ridge Regression for Stacking
    META_RIDGE_ALPHAS = np.logspace(-2, 2, 20).tolist()

    @classmethod
    def setup(cls):
        """
        Ensures necessary directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Execute setup on import
Config.setup()
