import os
import torch
import numpy as np
import random


class Config:
    """
    Global configuration for the Pet Pawpularity Prediction task.
    Implements the settings for Stratified Tri-Paradigm Stacking with Interaction-Aware Meta-Learning.
    """

    # ==========================================
    # General Configuration
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    NUM_WORKERS = 4  # 12 vCPUs available
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================
    # Directory Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_12"
    SUBMISSION_DIR = "./submission"

    # Metadata Files (Generated by the provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Submission Output
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Data Schema
    # ==========================================
    TARGET_COL = "Pawpularity"
    ID_COL = "Id"
    PATH_COL = "file_path"

    # Binary Metadata Features used for Interaction Terms
    META_FEATURES = [
        "Subject Focus",
        "Eyes",
        "Face",
        "Near",
        "Action",
        "Accessory",
        "Group",
        "Collage",
        "Human",
        "Occlusion",
        "Info",
        "Blur",
    ]

    # ==========================================
    # Backbone Models (Tri-Paradigm)
    # ==========================================
    # 1. Semantic Expert: SigLIP So400M (384px)
    # Superior for aesthetic/subjective tasks
    MODEL_SIGLIP = "google/siglip-so400m-patch14-384"

    # 2. Geometric Expert: DINOv2 ViT-Large (518px)
    # Self-supervised understanding of layout and structure
    MODEL_DINOV2 = "facebook/dinov2-large"

    # 3. Textural Expert: ConvNeXt Large (224px)
    # Captures high-frequency textures
    MODEL_CONVNEXT = "facebook/convnext-large-224-22k-1k"

    # ==========================================
    # Feature Extraction Settings
    # ==========================================
    BATCH_SIZE = 32
    # Feature-Space Augmentation: Average embeddings of original and flipped images
    USE_FLIP_AUGMENTATION = True

    # ==========================================
    # Level-0 Expert Hyperparameters
    # ==========================================
    N_FOLDS = 5  # Stratified K-Fold

    # Dimensionality reduction for Tree-based models to prevent overfitting
    PCA_COMPONENTS = 64

    # 1. Ridge Regression (Linear Expert)
    RIDGE_ALPHAS = [0.01, 0.1, 1.0, 10.0, 100.0, 1000.0, 10000.0, 50000.0]

    # 2. Support Vector Regression (Kernel Expert)
    SVR_PARAMS = {
        "kernel": "rbf",
        "C": [1.0, 10.0, 100.0],
        "epsilon": [0.01, 0.1],
        "gamma": "scale",
    }

    # 3. ExtraTrees Regressor (Bagging Expert)
    ET_PARAMS = {
        "n_estimators": 500,
        "max_depth": None,
        "min_samples_split": 2,
        "min_samples_leaf": 1,
        "n_jobs": -1,
        "random_state": SEED,
        "verbose": 0,
    }

    # 4. LightGBM Regressor (Boosting Expert)
    # Note: early_stopping_rounds is typically handled in the fit() call
    LGBM_PARAMS = {
        "objective": "regression",
        "metric": "rmse",
        "boosting_type": "gbdt",
        "learning_rate": 0.01,
        "num_leaves": 31,
        "feature_fraction": 0.8,
        "bagging_fraction": 0.8,
        "bagging_freq": 5,
        "n_estimators": 2000,
        "verbosity": -1,
        "random_state": SEED,
        "n_jobs": -1,
    }
    LGBM_EARLY_STOPPING_ROUNDS = 100

    # ==========================================
    # Level-1 Meta-Learner Hyperparameters
    # ==========================================
    # Interaction-Aware Bayesian Meta-Learner
    # Uses Bayesian Ridge for Automatic Relevance Determination (ARD)
    META_MODEL_PARAMS = {
        "n_iter": 300,
        "tol": 1e-3,
        "alpha_1": 1e-6,
        "alpha_2": 1e-6,
        "lambda_1": 1e-6,
        "lambda_2": 1e-6,
        "fit_intercept": True,
        "verbose": False,
    }

    @classmethod
    def setup(cls):
        """
        Initializes the environment:
        1. Creates working and submission directories.
        2. Sets deterministic seeds for reproducibility.
        """
        # Create directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(cls.SEED)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

    @classmethod
    def get_cache_path(cls, backbone_name, split_name):
        """
        Generates a standardized path for cached features.

        Args:
            backbone_name (str): Name of the backbone (e.g., 'siglip', 'dinov2').
            split_name (str): Dataset split (e.g., 'train', 'val', 'test').

        Returns:
            str: Path to the .npy file in the working directory.
        """
        filename = f"{backbone_name}_{split_name}_features.npy"
        return os.path.join(cls.WORKING_DIR, filename)
