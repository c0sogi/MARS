import os
import torch


class Config:
    """
    Configuration configuration for the Dual-Stream Denoising Network (DSDN) strategy.
    Encapsulates paths, model architecture parameters, and training settings.
    """

    # -------------------------------------------------------------------------
    # General & Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging

    # -------------------------------------------------------------------------
    # File Paths & Directories
    # -------------------------------------------------------------------------
    # Input Metadata (Generated by previous steps)
    METADATA_DIR = "./metadata"
    TRAIN_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Raw Input (Read-Only)
    INPUT_DIR = "./input"
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Working Directory (For Caching and Models)
    # Strategy: Idea 12
    WORK_DIR = "./working/idea_12"
    CACHE_DIR = os.path.join(WORK_DIR, "cache")
    MODEL_PATH = os.path.join(WORK_DIR, "best_model.pth")

    # Output Directory
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Configuration
    # -------------------------------------------------------------------------
    ID_COL = "id"
    TARGET_COL = "target"
    SEQ_COL = "f_27"

    # -------------------------------------------------------------------------
    # Model Architecture: Dual-Stream Denoising Network (DSDN)
    # -------------------------------------------------------------------------
    # General
    EMBED_DIM = 128  # Dimension for linear tokens and sequence embeddings

    # Stream 1: Deep Denoising Expert (Transformer)
    NUM_TRANSFORMER_LAYERS = 3
    NUM_HEADS = 4
    DIM_FEEDFORWARD = 512  # Internal dimension for GEGLU blocks
    DROPOUT = 0.1
    MASK_PROB = 0.15  # Probability of masking tokens for reconstruction

    # Stream 2: Wide Anchoring Expert (MLP)
    MLP_HIDDEN_DIM = 256  # Hidden dimension for the residual MLP branch

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 512  # Explicitly set to 512 as per strategy
    EPOCHS = 35  # Extended duration for optimal convergence
    LEARNING_RATE = 1e-3  # Max Learning Rate for OneCycleLR
    PCT_START = 0.3  # Percentage of training for warm-up
    LABEL_SMOOTHING = 0.01  # Regularization for BCE Loss
    RECON_WEIGHT = 0.5  # Lambda: Weight for auxiliary reconstruction loss

    # -------------------------------------------------------------------------
    # Hardware
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Optimized for available vCPUs

    def __init__(self, make_dirs=True):
        """
        Initialize configuration and create necessary directories.
        """
        if make_dirs:
            os.makedirs(self.WORK_DIR, exist_ok=True)
            os.makedirs(self.CACHE_DIR, exist_ok=True)
            os.makedirs(self.SUBMISSION_DIR, exist_ok=True)

    def display(self):
        """Prints the configuration."""
        print("=" * 40)
        print(f"Config: {self.__class__.__name__}")
        print("=" * 40)
        for attr in dir(self):
            if not attr.startswith("__") and not callable(getattr(self, attr)):
                print(f"{attr:<25} {getattr(self, attr)}")
        print("=" * 40)
