import os
import numpy as np
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from library import config


class DataHandler:
    def __init__(self):
        """
        Initialize the DataHandler.
        Ensures the working directory for caching exists.
        """
        self.working_dir = config.WORKING_DIR
        os.makedirs(self.working_dir, exist_ok=True)

    def split_f27_sequence(self, df):
        """
        Splits the string column 'f_27' into individual character columns based on position.

        Args:
            df (pd.DataFrame): The input DataFrame containing 'f_27'.

        Returns:
            tuple: (pd.DataFrame with new columns, list of new column names)
        """
        # Ensure the column is string type
        s = df[config.CAT_COL].astype(str)

        # Convert strings to list of characters
        # We assume all strings in f_27 have the same length (typically 10 characters for this dataset)
        # Using list comprehension is efficient for this size
        char_data = [list(x) for x in s]

        # Determine sequence length from the first element
        if not char_data:
            return df, []

        seq_len = len(char_data[0])
        pos_cols = [f"p_{i}" for i in range(seq_len)]

        # Create a DataFrame for the characters
        char_df = pd.DataFrame(char_data, columns=pos_cols, index=df.index)

        # Concatenate with original dataframe
        df_out = pd.concat([df, char_df], axis=1)

        return df_out, pos_cols

    def create_preprocessor(self, position_cols):
        """
        Creates a Scikit-Learn ColumnTransformer.
        - Numerical columns (f_00..f_30) are StandardScaled.
        - Position character columns are OneHotEncoded.

        Args:
            position_cols (list): List of column names generated by split_f27_sequence.

        Returns:
            ColumnTransformer: The configured preprocessor.
        """
        # Numerical Transformer
        numerical_transformer = StandardScaler()

        # Categorical Transformer
        # sparse_output=False ensures we get dense arrays suitable for .npy saving
        categorical_transformer = OneHotEncoder(
            handle_unknown="ignore", sparse_output=False
        )

        preprocessor = ColumnTransformer(
            transformers=[
                ("num", numerical_transformer, config.NUM_COLS),
                ("cat", categorical_transformer, position_cols),
            ],
            verbose_feature_names_out=False,
        )

        return preprocessor

    def get_processed_data(self, load_cached_data=True):
        """
        Orchestrates data loading, feature engineering, and preprocessing.
        Implements caching using .npy files.

        Args:
            load_cached_data (bool): If True, attempts to load from cache first.

        Returns:
            tuple: (X_train, y_train, X_val, y_val, X_test, ids_test)
                   All X arrays are dense numpy arrays.
        """
        # Define cache file paths
        cache_files = {
            "X_train": os.path.join(self.working_dir, "X_train.npy"),
            "y_train": os.path.join(self.working_dir, "y_train.npy"),
            "X_val": os.path.join(self.working_dir, "X_val.npy"),
            "y_val": os.path.join(self.working_dir, "y_val.npy"),
            "X_test": os.path.join(self.working_dir, "X_test.npy"),
            "ids_test": os.path.join(self.working_dir, "ids_test.npy"),
        }

        # Check if all cache files exist
        cache_exists = all(os.path.exists(p) for p in cache_files.values())

        if load_cached_data and cache_exists:
            print("Loading cached data from .npy files...")
            try:
                X_train = np.load(cache_files["X_train"])
                y_train = np.load(cache_files["y_train"])
                X_val = np.load(cache_files["X_val"])
                y_val = np.load(cache_files["y_val"])
                X_test = np.load(cache_files["X_test"])
                ids_test = np.load(cache_files["ids_test"])
                return X_train, y_train, X_val, y_val, X_test, ids_test
            except Exception as e:
                print(f"Failed to load cache: {e}. Reprocessing...")

        print("Processing data from scratch...")

        # 1. Load Data
        print("Loading CSV files...")
        train_df = pd.read_csv(config.TRAIN_PATH)
        val_df = pd.read_csv(config.VAL_PATH)
        test_df = pd.read_csv(config.TEST_PATH)

        # 2. Feature Engineering (Split f_27)
        print("Engineering features...")
        train_df, pos_cols = self.split_f27_sequence(train_df)
        val_df, _ = self.split_f27_sequence(val_df)
        test_df, _ = self.split_f27_sequence(test_df)

        # 3. Extract Targets and IDs
        y_train = train_df[config.TARGET_COL].values
        y_val = val_df[config.TARGET_COL].values
        ids_test = test_df[config.ID_COL].values

        # 4. Preprocessing
        print("Fitting and transforming data...")
        preprocessor = self.create_preprocessor(pos_cols)

        # Fit on Train
        X_train = preprocessor.fit_transform(train_df)

        # Transform Val and Test
        X_val = preprocessor.transform(val_df)
        X_test = preprocessor.transform(test_df)

        # 5. Save to Cache
        print("Saving processed data to cache...")
        np.save(cache_files["X_train"], X_train)
        np.save(cache_files["y_train"], y_train)
        np.save(cache_files["X_val"], X_val)
        np.save(cache_files["y_val"], y_val)
        np.save(cache_files["X_test"], X_test)
        np.save(cache_files["ids_test"], ids_test)

        return X_train, y_train, X_val, y_val, X_test, ids_test
