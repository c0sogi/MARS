import os
import torch


class Config:
    """
    Configuration for the Dual-Shell Geometric Wide Deep Sets (DSG-WDS) pipeline.
    Centralizes all file paths, hyperparameters, and constants.
    """

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Specific working directory for this experiment to ensure isolation
    WORKING_DIR = "./working/idea_37"
    SUBMISSION_DIR = "./submission"

    # Input Metadata Files (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Cache Files for Processed Data (using .npz for efficient storage of arrays)
    TRAIN_DATA_PATH = os.path.join(WORKING_DIR, "train_data.npz")
    VAL_DATA_PATH = os.path.join(WORKING_DIR, "val_data.npz")
    TEST_DATA_PATH = os.path.join(WORKING_DIR, "test_data.npz")
    SCALERS_PATH = os.path.join(WORKING_DIR, "scalers.npz")

    # Model Checkpoint
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pt")

    # Final Submission
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Processing Parameters
    # -------------------------------------------------------------------------
    SEED = 42

    # Neighbor definitions for Dual-Shell features
    # Bonding Shell: 1st nearest neighbor (index 0)
    # Coordination Shell: 2nd to 5th nearest neighbors (indices 1 to 4)
    COORD_SHELL_START_IDX = 1
    COORD_SHELL_END_IDX = 5

    # -------------------------------------------------------------------------
    # Model Architecture Hyperparameters
    # -------------------------------------------------------------------------
    # Atomic Stream (Dual-Shell Point Processor)
    # Features:
    #   1. Atomic Identity (One-hot Al, Ga, In, O) -> 4 dims
    #   2. Centered Coordinates (x, y, z) -> 3 dims
    #   3. Bonding Shell Distance -> 1 dim
    #   4. Coordination Shell Distance -> 1 dim
    # Total = 9 dimensions
    ATOMIC_INPUT_DIM = 9
    ATOMIC_HIDDEN_DIM = 512  # Wide MLP for Immediate Expansion
    ATOMIC_LAYERS = 3
    ATOMIC_DROPOUT = 0.1

    # Global Stream (Thermodynamic Context)
    # Features:
    #   1. Lattice Vectors (a, b, c) -> 3 dims
    #   2. Lattice Angles (alpha, beta, gamma) -> 3 dims
    #   3. Unit Cell Volume -> 1 dim
    #   4. Atomic Density -> 1 dim
    #   5. Stoichiometry (Al, Ga, In ratios) -> 3 dims
    #   6. Total Atoms -> 1 dim
    # Total = 12 dimensions
    GLOBAL_INPUT_DIM = 12
    GLOBAL_HIDDEN_DIM = 256
    GLOBAL_DROPOUT = 0.1

    # Fusion Head
    # Input dim is concatenation of:
    #   - Atomic Global Mean Pooling (ATOMIC_HIDDEN_DIM)
    #   - Atomic Global Max Pooling (ATOMIC_HIDDEN_DIM)
    #   - Global Stream Embedding (GLOBAL_HIDDEN_DIM)
    # Total Fusion Input = 512 + 512 + 256 = 1280
    FUSION_HIDDEN_DIMS = [512, 256]
    FUSION_DROPOUT = 0.1
    OUTPUT_DIM = 2  # formation_energy_ev_natom, bandgap_energy_ev

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 64
    NUM_EPOCHS = 200
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4  # Regularization for wide layers

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 20

    # Scheduler (ReduceLROnPlateau)
    SCHEDULER_FACTOR = 0.5
    SCHEDULER_PATIENCE = 10
    SCHEDULER_MIN_LR = 1e-6

    # -------------------------------------------------------------------------
    # System Configuration
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # For DataLoader

    @staticmethod
    def setup_directories():
        """
        Creates the necessary working and submission directories if they do not exist.
        This ensures safe file writing operations later in the pipeline.
        """
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
        print(f"Directories ensured: {Config.WORKING_DIR}, {Config.SUBMISSION_DIR}")
