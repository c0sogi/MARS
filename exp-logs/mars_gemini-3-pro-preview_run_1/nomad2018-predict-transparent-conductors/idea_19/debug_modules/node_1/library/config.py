import os
import torch


class Config:
    """
    Configuration class for the Chemically-Resolved Wide Deep Sets (CR-WDS) strategy.
    Acts as a central repository for paths, hyperparameters, and constants.
    """

    # -------------------------------------------------------------------------
    # 1. Paths & Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory for intermediate files (cache, models)
    WORKING_DIR = "./working/idea_19"
    SUBMISSION_DIR = "./submission"

    # Ensure necessary writeable directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata File Paths (Generated by previous steps)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Raw Data Paths
    TRAIN_CSV = os.path.join(INPUT_DIR, "train.csv")
    TEST_CSV = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pt")

    # Cache File Paths (using .npz for efficient numpy storage)
    TRAIN_DATA_CACHE = os.path.join(WORKING_DIR, "train_data.npz")
    VAL_DATA_CACHE = os.path.join(WORKING_DIR, "val_data.npz")
    TEST_DATA_CACHE = os.path.join(WORKING_DIR, "test_data.npz")
    SCALERS_CACHE = os.path.join(WORKING_DIR, "scalers.npz")

    # -------------------------------------------------------------------------
    # 2. Data & Feature Engineering
    # -------------------------------------------------------------------------
    # Chemical definitions
    ATOM_TYPES = ["Al", "Ga", "In", "O"]
    ATOM_TO_IDX = {atom: i for i, atom in enumerate(ATOM_TYPES)}
    NUM_ATOM_TYPES = len(ATOM_TYPES)

    # Proximity Feature Hyperparameter: Gaussian kernel width gamma
    # Feature = exp(-gamma * distance)
    PROXIMITY_GAMMA = 0.5

    # Feature Dimensions
    # Atomic Stream Input:
    #   - One-hot encoding (4)
    #   - Centered Cartesian coordinates (3)
    #   - Chemically-Resolved Proximity (4)
    ATOMIC_FEATURE_DIM = 4 + 3 + 4  # 11

    # Global Stream Input:
    #   - Lattice lengths (3) + Lattice angles (3) = 6
    #   - Unit Cell Volume (1)
    #   - Atomic Density (1)
    #   - Stoichiometry (Al, Ga, In) = 3
    #   - Total Number of Atoms (1)
    GLOBAL_FEATURE_DIM = 6 + 1 + 1 + 3 + 1  # 12

    # Targets
    TARGET_COLS = ["formation_energy_ev_natom", "bandgap_energy_ev"]
    NUM_TARGETS = len(TARGET_COLS)

    # -------------------------------------------------------------------------
    # 3. Model Architecture
    # -------------------------------------------------------------------------
    # Atomic Stream: Wide MLP for point-cloud processing
    ATOMIC_HIDDEN_DIM = 512

    # Global Stream: High-capacity MLP for thermodynamic context
    GLOBAL_HIDDEN_DIM = 256

    # Fusion Head: Dimension after concatenating aggregated atomic + global
    # (ATOMIC_HIDDEN_DIM * 2 for mean+max pool) + GLOBAL_HIDDEN_DIM
    # 512*2 + 256 = 1280 input to fusion head

    # Regularization
    DROPOUT_RATE = 0.1

    # -------------------------------------------------------------------------
    # 4. Training Hyperparameters
    # -------------------------------------------------------------------------
    SEED = 42
    BATCH_SIZE = 64
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4  # Regularization for wide layers
    NUM_EPOCHS = 200

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 20

    # Learning Rate Scheduler (ReduceLROnPlateau)
    SCHEDULER_FACTOR = 0.5
    SCHEDULER_PATIENCE = 10
    SCHEDULER_MIN_LR = 1e-6

    # -------------------------------------------------------------------------
    # 5. Runtime & Hardware
    # -------------------------------------------------------------------------
    # Set to an integer (e.g., 100) to debug with a small subset of data.
    # Set to None for full training.
    DEBUG_SAMPLE_SIZE = None

    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # For DataLoader
