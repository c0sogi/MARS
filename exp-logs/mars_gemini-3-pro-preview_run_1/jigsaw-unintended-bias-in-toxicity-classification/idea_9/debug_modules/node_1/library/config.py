import os
import torch


class CFG:
    """
    Configuration class for Toxicity Classification with Bias Mitigation.
    Implements settings for Domain-Adaptive DeBERTa-v3-Large with MTL, Ranking Loss, and AWP.
    """

    # ====================================================
    # General Settings
    # ====================================================
    project_name = "toxicity-bias-mitigation"
    idea_name = "idea_9"
    seed = 42
    debug = False  # Set to True to run with a small subset of data for debugging
    debug_sample_size = 5000  # Number of samples to use if debug is True
    print_freq = 100
    num_workers = 4

    # Compute Environment
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # ====================================================
    # Data Paths & Directories
    # ====================================================
    # Input Metadata (Generated by previous steps in ./metadata)
    metadata_dir = "./metadata"
    train_path = os.path.join(metadata_dir, "train.csv")
    val_path = os.path.join(metadata_dir, "val.csv")
    test_path = os.path.join(metadata_dir, "test.csv")

    # Working Directories (Cache & Outputs)
    # Strictly following ./working/idea_9/ requirement
    base_dir = f"./working/{idea_name}"
    output_dir = os.path.join(base_dir, "outputs")
    cache_dir = os.path.join(base_dir, "cache")
    submission_dir = "./submission"
    submission_path = os.path.join(submission_dir, "submission.csv")

    # Ensure directories exist
    os.makedirs(output_dir, exist_ok=True)
    os.makedirs(cache_dir, exist_ok=True)
    os.makedirs(submission_dir, exist_ok=True)

    # ====================================================
    # Model Architecture
    # ====================================================
    model_name = "microsoft/deberta-v3-large"
    gradient_checkpointing = True  # Essential for Large models to save VRAM

    # Tokenizer
    max_len = 256  # Sufficient for 95th percentile of comments (EDA showed ~160 words)

    # Multi-Task Learning (MTL) Heads Configuration
    # 1. Primary Toxicity Head (Target)
    # 2. Auxiliary Identity Head (Predicts presence of 9 identity attributes)
    # 3. Auxiliary Identity Attack Head (Predicts identity_attack subtype)
    num_classes = 1
    identity_cols = [
        "male",
        "female",
        "homosexual_gay_or_lesbian",
        "christian",
        "jewish",
        "muslim",
        "black",
        "white",
        "psychiatric_or_mental_illness",
    ]
    num_identity_classes = len(identity_cols)
    num_identity_attack_classes = 1

    # ====================================================
    # Training Hyperparameters
    # ====================================================
    epochs = 4
    train_batch_size = 8  # Conservative batch size for DeBERTa-Large on 40GB GPU
    valid_batch_size = 32
    accumulate_grad_batches = 4  # Effective batch size = 32

    # Optimization
    learning_rate = 1e-5
    encoder_lr = 1e-5
    decoder_lr = 5e-5  # Higher LR for classification heads
    min_lr = 1e-7
    weight_decay = 0.01
    eps = 1e-6
    betas = (0.9, 0.999)

    # Scheduler
    scheduler_type = "cosine"  # Options: 'linear', 'cosine'
    warmup_ratio = 0.1
    num_cycles = 0.5

    # Gradient Clipping
    # Set high or disable for AWP, as AWP induces large gradients
    max_grad_norm = 1000.0

    # ====================================================
    # Loss & Bias Mitigation Strategies
    # ====================================================
    # Loss Weights
    # L_total = L_BCE_Weighted + lambda_rank * L_Rank + lambda_aux * L_Aux
    rank_weight = 0.5
    aux_weight = 0.3

    # Sample Weighting (Bias-Centric)
    # Weights applied to specific subgroups in the Weighted BCE Loss
    bias_pos_weight = 5.0  # Toxic + Identity Mention
    bias_neg_weight = 5.0  # Non-Toxic + Identity Mention
    normal_weight = 1.0

    # Adversarial Weight Perturbation (AWP)
    use_awp = True
    awp_start_epoch = 2  # Start AWP after model has stabilized
    awp_eps = 1e-2
    awp_lr = 1e-4

    # ====================================================
    # Domain Adaptation (MLM)
    # ====================================================
    mlm_epochs = 1
    mlm_batch_size = 8
    mlm_lr = 2e-5
    mlm_mask_prob = 0.15

    # ====================================================
    # Evaluation Metric
    # ====================================================
    # Generalized Mean p-value for combining Bias AUCs
    metric_p = -5
