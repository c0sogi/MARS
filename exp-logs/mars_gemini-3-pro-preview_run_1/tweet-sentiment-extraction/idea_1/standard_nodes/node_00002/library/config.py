import os
import random
import numpy as np
import torch


class Config:
    """
    Configuration class for the Sentiment Extraction task.
    Centralizes all hyperparameters, file paths, and model settings.
    """

    # ====================================================
    # General & Reproducibility
    # ====================================================
    SEED = 42
    DEBUG = False  # Set to True to train on a small subset for debugging

    # ====================================================
    # File Paths
    # ====================================================
    # Input Metadata (generated by metadata script)
    TRAIN_META_PATH = "./metadata/train_metadata.csv"
    VAL_META_PATH = "./metadata/validation_metadata.csv"
    TEST_META_PATH = "./metadata/test_metadata.csv"

    # Output Paths
    SUBMISSION_PATH = "./submission/submission.csv"

    # Working Directory for Checkpoints and Cache
    WORKING_DIR = "./working/idea_1"
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "distilroberta_model.bin")

    # ====================================================
    # Model & Tokenizer
    # ====================================================
    MODEL_NAME = "distilroberta-base"
    TOKENIZER_PATH = "distilroberta-base"

    # ====================================================
    # Data Processing
    # ====================================================
    MAX_LEN = 96  # Max sequence length (tweets are short)

    # ====================================================
    # Training Hyperparameters
    # ====================================================
    TRAIN_BATCH_SIZE = 32
    VALID_BATCH_SIZE = 32
    EPOCHS = 3
    LEARNING_RATE = 3e-5
    WEIGHT_DECAY = 0.01

    # ====================================================
    # Hardware
    # ====================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Utilizing available vCPUs

    @staticmethod
    def setup_directories():
        """
        Ensures that the working and submission directories exist.
        """
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(os.path.dirname(Config.SUBMISSION_PATH), exist_ok=True)


def seed_everything(seed: int = 42):
    """
    Sets the random seed for reproducibility across Python, NumPy, and PyTorch.

    Args:
        seed (int): The seed value to use.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


# Initialize directories on import
Config.setup_directories()
