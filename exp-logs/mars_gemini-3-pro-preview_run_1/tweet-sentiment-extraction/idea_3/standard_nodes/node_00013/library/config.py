import os
import torch


class TweetConfig:
    """
    Configuration class for the Tweet Sentiment Extraction task.
    Centralizes all hyperparameters, file paths, and model settings.
    """

    # ====================================================
    # General Settings
    # ====================================================
    SEED = 42
    NUM_WORKERS = 4
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # Debugging
    # Set DEBUG to True to run on a small subset of data for testing pipeline
    DEBUG = False
    DEBUG_SIZE = 100  # Number of samples to use when DEBUG is True

    # ====================================================
    # Data Paths
    # ====================================================
    # Metadata paths (generated by the metadata script)
    TRAIN_PATH = "./metadata/train_metadata.csv"
    VAL_PATH = "./metadata/validation_metadata.csv"
    TEST_PATH = "./metadata/test_metadata.csv"

    # Input paths
    SAMPLE_SUBMISSION_PATH = "./input/sample_submission.csv"

    # Output paths
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache Directory for deterministic data processing
    CACHE_DIR = "./working/idea_3/"

    # Ensure necessary directories exist
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ====================================================
    # Model Architecture
    # ====================================================
    MODEL_NAME = "microsoft/deberta-v3-base"
    MAX_LEN = 128
    HIDDEN_SIZE = 768  # Standard for base models
    DROPOUT = 0.1

    # ====================================================
    # Training Hyperparameters
    # ====================================================
    TRAIN_BATCH_SIZE = 32
    VALID_BATCH_SIZE = 64
    EPOCHS = 5

    # Optimizer & Scheduler
    LEARNING_RATE = 2e-5
    WEIGHT_DECAY = 0.01
    WARMUP_RATIO = 0.1
    SCHEDULER_TYPE = "linear"  # 'linear' or 'cosine'
    MAX_GRAD_NORM = 1.0

    # Early Stopping
    ES_PATIENCE = 2  # Stop if validation score doesn't improve for 2 epochs

    # ====================================================
    # Loss & Target Generation
    # ====================================================
    # Sigma for Gaussian smoothing of start/end index targets
    SIGMA = 1.0
    # KL Divergence reduction
    LOSS_REDUCTION = "batchmean"

    # ====================================================
    # Inference / Post-processing
    # ====================================================
    # Sentiment strings to filter/handle
    SENTIMENT_NEUTRAL = "neutral"
    SENTIMENT_POSITIVE = "positive"
    SENTIMENT_NEGATIVE = "negative"
