import os
import torch


class GASEConfig:
    """
    Configuration module for the Graph-Augmented Stratified Ensemble (GASE) solution.
    Centralizes all file paths, hyperparameters, and compute settings for the
    two-stage pipeline (MPNN + XGBoost).
    """

    # =========================================================================
    # 1. Directories and File Paths
    # =========================================================================

    # Root Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_3"
    SUBMISSION_DIR = "./submission"

    # Ensure mutable directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Input Data Files (Read-Only)
    # Metadata generated by the provided script
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Raw Input Files
    STRUCTURES_CSV = os.path.join(INPUT_DIR, "structures.csv")
    DIPOLE_MOMENTS_CSV = os.path.join(INPUT_DIR, "dipole_moments.csv")
    POTENTIAL_ENERGY_CSV = os.path.join(INPUT_DIR, "potential_energy.csv")
    MULLIKEN_CHARGES_CSV = os.path.join(INPUT_DIR, "mulliken_charges.csv")
    SCALAR_COUPLING_CONTRIBUTIONS_CSV = os.path.join(
        INPUT_DIR, "scalar_coupling_contributions.csv"
    )
    SAMPLE_SUBMISSION_CSV = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output / Cache Files (in Working Directory)
    # Parquet files for processed tabular features (Geometric + Meta)
    PROCESSED_TRAIN_PATH = os.path.join(WORKING_DIR, "processed_train.parquet")
    PROCESSED_VAL_PATH = os.path.join(WORKING_DIR, "processed_val.parquet")
    PROCESSED_TEST_PATH = os.path.join(WORKING_DIR, "processed_test.parquet")

    # Graph Data Cache
    # We store processed graph structures to avoid re-computing neighbors
    GRAPH_CACHE_DIR = os.path.join(WORKING_DIR, "graph_cache")
    os.makedirs(GRAPH_CACHE_DIR, exist_ok=True)

    # Learned Embeddings (Numpy format for easy concatenation with tabular data)
    # These are the outputs of Stage 1 (MPNN)
    EMBEDDINGS_TRAIN_PATH = os.path.join(WORKING_DIR, "embeddings_train.npy")
    EMBEDDINGS_VAL_PATH = os.path.join(WORKING_DIR, "embeddings_val.npy")
    EMBEDDINGS_TEST_PATH = os.path.join(WORKING_DIR, "embeddings_test.npy")

    # Model Checkpoints
    MPNN_MODEL_PATH = os.path.join(WORKING_DIR, "mpnn_best_model.pth")
    XGB_MODELS_DIR = os.path.join(WORKING_DIR, "xgb_models")
    os.makedirs(XGB_MODELS_DIR, exist_ok=True)

    # Final Submission
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # 2. General Compute Settings
    # =========================================================================
    RANDOM_SEED = 42
    NUM_WORKERS = 12  # Matches available vCPUs
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # =========================================================================
    # 3. Feature Engineering & Graph Construction
    # =========================================================================
    GRAPH_RADIUS = 5.0  # Angstroms, cutoff for creating edges between atoms
    MAX_NEIGHBORS = 32  # Maximum number of neighbors per atom (for batching efficiency)

    # Atom types mapping (H, C, N, O, F are the elements in this dataset)
    ATOM_TYPES = {"H": 0, "C": 1, "N": 2, "O": 3, "F": 4}
    NUM_ATOM_TYPES = len(ATOM_TYPES)

    # =========================================================================
    # 4. Stage 1: MPNN (Message Passing Neural Network) Configuration
    # =========================================================================
    # Architecture
    MPNN_ATOM_EMBED_DIM = 64  # Embedding size for atom type
    MPNN_HIDDEN_DIM = 128  # Hidden state dimension
    MPNN_OUTPUT_DIM = 128  # Size of the final interaction embedding vector
    MPNN_NUM_LAYERS = 4  # Number of message passing steps
    MPNN_NUM_RBF = 16  # Number of Radial Basis Functions for edge features
    MPNN_RBF_MIN = 0.0  # Min distance for RBF
    MPNN_RBF_MAX = 5.0  # Max distance for RBF

    # Training
    MPNN_EPOCHS = 20  # Sufficient for convergence given dataset size
    MPNN_BATCH_SIZE = 512  # Large batch size for A100 GPU
    MPNN_LEARNING_RATE = 1e-3
    MPNN_WEIGHT_DECAY = 1e-5
    MPNN_PATIENCE = 3  # Early stopping patience

    # =========================================================================
    # 5. Stage 2: Stratified XGBoost Ensemble Configuration
    # =========================================================================
    COUPLING_TYPES = ["1JHC", "1JHN", "2JHC", "2JHH", "2JHN", "3JHC", "3JHH", "3JHN"]

    # Base XGBoost Parameters
    # Optimized for regression on high-dimensional features (Geometric + Embeddings)
    XGB_BASE_PARAMS = {
        "tree_method": "hist",
        "device": DEVICE,
        "objective": "reg:absoluteerror",  # Training on MAE to match metric
        "eval_metric": "mae",
        "n_estimators": 20000,  # High limit, controlled by early stopping
        "learning_rate": 0.01,  # Low LR for better generalization
        "subsample": 0.8,
        "colsample_bytree": 0.4,  # Heavy regularization for high-dim features
        "n_jobs": -1,
        "random_state": RANDOM_SEED,
        "early_stopping_rounds": 100,
        "verbosity": 0,
    }

    # Type-Specific Parameter Overrides
    # 1Jxx couplings are generally stronger and more distinct, benefiting from deeper trees.
    # Long-range couplings (2J, 3J) may require more regularization.
    XGB_TYPE_OVERRIDES = {
        "1JHC": {"max_depth": 10, "colsample_bytree": 0.5},
        "1JHN": {"max_depth": 10, "colsample_bytree": 0.5},
        "2JHC": {"max_depth": 9, "colsample_bytree": 0.4},
        "2JHH": {"max_depth": 9, "colsample_bytree": 0.4},
        "2JHN": {"max_depth": 9, "colsample_bytree": 0.4},
        "3JHC": {"max_depth": 9, "colsample_bytree": 0.4},
        "3JHH": {"max_depth": 9, "colsample_bytree": 0.4},
        "3JHN": {"max_depth": 9, "colsample_bytree": 0.4},
    }

    @classmethod
    def get_xgb_params(cls, coupling_type):
        """
        Returns the specific XGBoost parameters for a given coupling type.
        Merges base params with type-specific overrides.
        """
        params = cls.XGB_BASE_PARAMS.copy()
        if coupling_type in cls.XGB_TYPE_OVERRIDES:
            params.update(cls.XGB_TYPE_OVERRIDES[coupling_type])
        return params
