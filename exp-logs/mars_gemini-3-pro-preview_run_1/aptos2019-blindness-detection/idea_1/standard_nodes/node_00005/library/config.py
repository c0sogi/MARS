import os
import torch
import random
import numpy as np


class Config:
    # =========================================================================
    # System Settings
    # =========================================================================
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    # We have 12 vCPUs, so we can use a reasonable number of workers
    NUM_WORKERS = 4

    # =========================================================================
    # File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the provided script
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Working directories
    WORKING_DIR = "./working"
    # Specific cache directory for this idea/experiment
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_1")

    # Submission
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Model Checkpoint
    MODEL_SAVE_PATH = os.path.join(CACHE_DIR, "best_model.pth")

    # =========================================================================
    # Data Configuration
    # =========================================================================
    IMG_SIZE = 256
    NUM_CLASSES = 5  # 0, 1, 2, 3, 4

    # For Ordinal Regression:
    # We predict P(y > k) for k = 0, 1, 2, 3.
    # So we need 4 output units.
    NUM_ORDINAL_UNITS = 4

    # =========================================================================
    # Hyperparameters
    # =========================================================================
    # Backbone architecture
    BACKBONE = "efficientnet_b0"
    PRETRAINED = True

    # Training
    BATCH_SIZE = 32
    EPOCHS = 12
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Scheduler (Cosine Annealing)
    T_MAX = EPOCHS
    ETA_MIN = 1e-6

    # Early Stopping
    PATIENCE = 4

    # Debugging / Development
    # Set to a small integer (e.g., 100) to limit dataset size for quick testing.
    # Set to None to use the full dataset.
    DEBUG_SAMPLE_SIZE = None

    @classmethod
    def setup(cls):
        """
        Initializes the environment:
        1. Creates necessary directories.
        2. Sets random seeds for reproducibility.
        """
        # Create directories
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)

        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.cuda.manual_seed_all(cls.SEED)
            # Ensure deterministic behavior
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

        print(f"Configuration setup complete. Device: {cls.DEVICE}")
