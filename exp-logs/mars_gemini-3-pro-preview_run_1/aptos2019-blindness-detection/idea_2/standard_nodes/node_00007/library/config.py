import os
import torch


class Config:
    """
    Configuration class for Diabetic Retinopathy Severity Prediction.
    Centralizes all hyperparameters, file paths, and model settings.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    seed = 42
    num_workers = 4  # Optimized for 12 vCPUs
    device = "cuda" if torch.cuda.is_available() else "cpu"

    # =========================================================================
    # Directories & Paths
    # =========================================================================
    input_dir = "./input"
    metadata_dir = "./metadata"
    working_dir = "./working/idea_2"

    # Metadata CSVs generated by the metadata script
    train_csv_path = os.path.join(metadata_dir, "train.csv")
    val_csv_path = os.path.join(metadata_dir, "val.csv")
    test_csv_path = os.path.join(metadata_dir, "test.csv")

    # Submission output
    submission_path = os.path.join(working_dir, "submission.csv")

    # =========================================================================
    # Data Configuration
    # =========================================================================
    image_size = 512  # Increased resolution for fine-grained feature detection
    num_classes = 5  # Diagnosis levels: 0, 1, 2, 3, 4

    # =========================================================================
    # Model Architecture
    # =========================================================================
    backbone = "efficientnet_b4"
    pretrained = True

    # Ordinal Regression Head Settings
    # We use K-1 output units for K classes in Rank-Consistent Ordinal Regression
    # Each unit k predicts Prob(y > k)
    num_ordinal_units = 4

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    # Batch size reduced to accommodate larger model/image size on GPU
    batch_size = 8

    # Learning rate scaled down proportionally to batch size reduction
    learning_rate = 1e-4
    weight_decay = 1e-5

    # Training duration
    epochs = 15

    # Scheduler (Cosine Annealing)
    scheduler_t_max = 15  # Should match epochs
    scheduler_eta_min = 1e-6

    # Early Stopping
    early_stopping_patience = 4
    early_stopping_min_delta = 1e-4

    # =========================================================================
    # Debugging & Development
    # =========================================================================
    # Set debug to True to run on a small subset of data for quick pipeline verification
    debug = False
    debug_sample_size = 100

    @classmethod
    def setup(cls):
        """
        Performs necessary setup operations like creating working directories.
        """
        os.makedirs(cls.working_dir, exist_ok=True)


# Initialize setup immediately upon module import
Config.setup()
