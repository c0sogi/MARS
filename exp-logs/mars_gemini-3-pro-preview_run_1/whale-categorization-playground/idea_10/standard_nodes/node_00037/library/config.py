import os
import torch


class Config:
    """
    Centralized configuration for the Whale Species Prediction task.
    Implements the strategy: DenseNet121 + ArcFace + SWA.
    """

    # -------------------------------------------------------------------------
    # General & Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # Debugging / Development
    # Set DEBUG to True to run on a small subset of data for quick testing
    DEBUG = False
    DEBUG_SUBSET_SIZE = 500

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for this specific idea (Idea 10)
    WORKING_DIR = "./working/idea_10"

    # Input Metadata (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Outputs
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache for processed data (if needed)
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")

    # -------------------------------------------------------------------------
    # Data Configuration
    # -------------------------------------------------------------------------
    IMG_SIZE = 320
    NUM_CLASSES = 4029  # Based on metadata analysis (includes new_whale)

    # Normalization constants (ImageNet defaults)
    MEAN = [0.485, 0.456, 0.406]
    STD = [0.229, 0.224, 0.225]

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    BACKBONE = "densenet121"
    PRETRAINED = True

    # Projection Head (Neck)
    EMBEDDING_SIZE = 512
    DROPOUT = 0.0  # Explicitly disabled as per strategy

    # ArcFace Head Hyperparameters
    ARCFACE_SCALE = 30.0
    ARCFACE_MARGIN = 0.50

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 32

    # Learning Rate Strategy
    LEARNING_RATE = 3e-4
    WEIGHT_DECAY = 1e-2  # For AdamW
    MIN_LR = 1e-6

    # Training Schedule
    TOTAL_EPOCHS = 15

    # Regularization
    LABEL_SMOOTHING = 0.1

    # -------------------------------------------------------------------------
    # Inference
    # -------------------------------------------------------------------------
    TTA_FLIP = True  # Test Time Augmentation (Horizontal Flip)
    TOP_K = 5  # Number of predictions per image

    @classmethod
    def setup(cls):
        """
        Create necessary directories for outputs and checkpoints.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
