import os
import torch


class Config:
    # -------------------------------------------------------------------------
    # General Configuration
    # -------------------------------------------------------------------------
    PROJECT_NAME = "whale_identification_idea_11"

    # Ensemble Strategy: Independent Convergence Ensemble (ICE)
    # We use 3 distinct seeds to train 3 independent models.
    ENSEMBLE_SEEDS = [42, 2023, 999]

    # Default seed for operations that don't vary between ensemble members
    SEED = 42

    # Compute
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # -------------------------------------------------------------------------
    # Directory Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_11"
    SUBMISSION_DIR = "./submission"

    # Metadata Files (Generated by the provided script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Original Sample Submission (for reference/formatting)
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # -------------------------------------------------------------------------
    # Data Parameters
    # -------------------------------------------------------------------------
    IMAGE_SIZE = 320

    # Number of classes in training set (based on metadata analysis)
    # This includes 'new_whale' as a specific class ID.
    NUM_CLASSES = 4029

    # Debugging flags
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 200  # Number of samples to use if DEBUG is True

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    BACKBONE = "densenet121"
    EMBEDDING_DIM = 512

    # Neck Configuration
    # We explicitly remove dropout in the neck to prevent underfitting with margin losses
    DROPOUT = 0.0

    # -------------------------------------------------------------------------
    # Loss Function: ArcFace
    # -------------------------------------------------------------------------
    LOSS_MODULE = "ArcFace"
    S = 30.0  # Scale factor
    M = 0.50  # Margin

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 32
    MAX_EPOCHS = 25
    PATIENCE = 5  # Early stopping patience

    # Optimizer: AdamW
    # Cite solution_lesson_node_00038: Margin-based losses are hypersensitive to LR.
    # Reducing from 1e-3 to 3e-4 to prevent embedding collapse.
    LEARNING_RATE = 3e-4
    WEIGHT_DECAY = 1e-2
    MIN_LR = 1e-6

    # Scheduler: Cosine Annealing
    SCHEDULER_T_MAX = MAX_EPOCHS

    # Regularization
    # Cite solution_lesson_node_00013: Avoid Label Smoothing with ArcFace on singleton-heavy datasets.
    LABEL_SMOOTHING = 0.0

    # -------------------------------------------------------------------------
    # Augmentation Pipeline
    # -------------------------------------------------------------------------
    # Geometric (Conservative)
    # Cite solution_lesson_node_00014: Conservative rotation is critical.
    AUG_ROTATION = 15.0  # +/- degrees
    AUG_SCALE_MIN = 0.9
    AUG_SCALE_MAX = 1.1
    AUG_HFLIP_PROB = 0.5

    # Photometric (Brightness/Contrast only, No Saturation/Hue)
    AUG_BRIGHTNESS = 0.2
    AUG_CONTRAST = 0.2

    # -------------------------------------------------------------------------
    # Inference & Post-Processing
    # -------------------------------------------------------------------------
    TTA_FLIP = True  # Enable Horizontal Flip Test-Time Augmentation
    TOP_K = 5  # Number of predictions per image

    # Label for new whales
    NEW_WHALE_LABEL = "new_whale"

    @classmethod
    def setup_directories(cls):
        """
        Ensures that the working and submission directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
