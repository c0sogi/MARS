import os
import torch


class Config:
    """
    Centralized configuration for the Thoracic Lung Disease Detection task.
    Implements settings for the EfficientNet-B0 + BiFPN + Decoupled Heads strategy.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    PROJECT_NAME = "thoracic-disease-detection-idea-6"
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 500  # Number of samples to use in debug mode

    # =========================================================================
    # Compute Environment
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 12  # Matches available vCPUs

    # =========================================================================
    # File Paths & Directories
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the analysis script
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_meta.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_meta.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_meta.csv")

    # Working directory for artifacts (Idea 6 specific)
    WORKING_DIR = "./working/idea_6"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")

    # Final submission location
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # =========================================================================
    # Dataset Parameters
    # =========================================================================
    IMG_SIZE = 640  # Input resolution (Square)
    IN_CHANNELS = 3  # Model expects RGB

    # Class Definitions
    # 0-13 are findings, 14 is "No finding"
    NUM_CLASSES = 15
    NO_FINDING_CLASS_ID = 14
    CLASS_NAMES = [
        "Aortic enlargement",
        "Atelectasis",
        "Calcification",
        "Cardiomegaly",
        "Consolidation",
        "ILD",
        "Infiltration",
        "Lung Opacity",
        "Nodule/Mass",
        "Other lesion",
        "Pleural effusion",
        "Pleural thickening",
        "Pneumothorax",
        "Pulmonary fibrosis",
        "No finding",
    ]

    # =========================================================================
    # Model Architecture
    # =========================================================================
    BACKBONE = "tf_efficientnet_b0_ns"  # Lightweight, pre-trained backbone
    DOWNSAMPLE_RATIO = 4  # Output stride for CenterNet-style heads

    # Decoupled Coordinate-Aware Heads Settings
    USE_COORD_CONV = True  # Inject (x, y) channels into regression heads
    HEAD_INIT_STD = (
        0.001  # Small std dev init for regression to prevent exploding gradients
    )

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    NUM_EPOCHS = 20  # Long training horizon for robust feature learning
    BATCH_SIZE = 16  # Fits on A100 with 640x640 resolution

    # Optimizer (AdamW)
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-4

    # Scheduler (Cosine Annealing)
    T_MAX = NUM_EPOCHS
    ETA_MIN = 1e-6

    # Gradient Clipping
    CLIP_GRAD_NORM = 1.0

    # =========================================================================
    # Augmentation & Preprocessing
    # =========================================================================
    # Geometric
    MIN_VISIBILITY = 0.3  # BBox must be at least 30% visible after crop

    # Photometric
    # Note: CLAHE is explicitly excluded based on strategy
    BRIGHTNESS_LIMIT = 0.2
    CONTRAST_LIMIT = 0.2

    # =========================================================================
    # Inference & Post-processing
    # =========================================================================
    CONF_THRESHOLD = 0.01  # Low threshold to capture all potential objects for mAP
    NO_FINDING_PROB_THRESHOLD = 0.8  # Global head gating threshold
    IOU_THRESHOLD = 0.4  # For NMS (if applied) or metric evaluation
    MAX_DETECTIONS_PER_IMAGE = 100

    @classmethod
    def setup(cls):
        """
        Ensures necessary directories exist.
        Should be called at the start of the pipeline.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Create subdirectories for cache if needed by dataset logic
        os.makedirs(os.path.join(cls.CACHE_DIR, "train"), exist_ok=True)
        os.makedirs(os.path.join(cls.CACHE_DIR, "val"), exist_ok=True)
        os.makedirs(os.path.join(cls.CACHE_DIR, "test"), exist_ok=True)
