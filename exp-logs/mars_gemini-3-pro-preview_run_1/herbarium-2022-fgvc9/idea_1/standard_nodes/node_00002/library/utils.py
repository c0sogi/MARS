import os
import json
import numpy as np
import pandas as pd
import torch
from sklearn.metrics import f1_score
from sklearn.utils.class_weight import compute_class_weight
from library import config


def get_class_mappings(train_csv_path=config.TRAIN_CSV, load_cached_data=True):
    """
    Generates or loads mappings between category_id and model indices.

    Args:
        train_csv_path (str): Path to the training metadata CSV.
        load_cached_data (bool): Whether to try loading from cache.

    Returns:
        tuple: (label_to_idx, idx_to_label) dictionaries.
               label_to_idx: Maps raw category_id (int) to model index (int).
               idx_to_label: Maps model index (int) to raw category_id (int).
    """
    # Define cache path locally as it's specific to this utility
    mapping_path = os.path.join(config.IDEA_DIR, "class_mappings.json")

    # 1. Try to load from cache
    if load_cached_data and os.path.exists(mapping_path):
        try:
            with open(mapping_path, "r") as f:
                data = json.load(f)

            # JSON keys are always strings. We need to cast them back to integers.
            # label_to_idx: key=category_id (str->int), value=index (int)
            label_to_idx = {int(k): v for k, v in data["label_to_idx"].items()}

            # idx_to_label: key=index (str->int), value=category_id (int)
            idx_to_label = {int(k): v for k, v in data["idx_to_label"].items()}

            return label_to_idx, idx_to_label
        except Exception as e:
            print(f"Failed to load cached mappings: {e}. Recomputing...")

    # 2. Compute from scratch
    if not os.path.exists(train_csv_path):
        raise FileNotFoundError(f"Training metadata not found at {train_csv_path}")

    df = pd.read_csv(train_csv_path)

    # Sort unique IDs to ensure deterministic 0..N-1 mapping
    unique_ids = sorted(df["category_id"].unique())

    if len(unique_ids) != config.NUM_CLASSES:
        print(
            f"Warning: Number of unique classes in train.csv ({len(unique_ids)}) "
            f"does not match config.NUM_CLASSES ({config.NUM_CLASSES})"
        )

    label_to_idx = {int(cat_id): idx for idx, cat_id in enumerate(unique_ids)}
    idx_to_label = {idx: int(cat_id) for idx, cat_id in enumerate(unique_ids)}

    # 3. Save to cache
    # Ensure directory exists (config usually handles this, but being safe)
    os.makedirs(os.path.dirname(mapping_path), exist_ok=True)

    with open(mapping_path, "w") as f:
        json.dump({"label_to_idx": label_to_idx, "idx_to_label": idx_to_label}, f)

    return label_to_idx, idx_to_label


def calculate_class_weights(train_csv_path=config.TRAIN_CSV, load_cached_data=True):
    """
    Computes class weights for weighted cross-entropy loss using inverse frequency (balanced).

    Args:
        train_csv_path (str): Path to training metadata.
        load_cached_data (bool): Whether to use cache.

    Returns:
        torch.FloatTensor: Tensor of weights of shape (NUM_CLASSES,).
    """
    weights_path = config.CLASS_WEIGHTS_PATH

    # 1. Try to load from cache
    if load_cached_data and os.path.exists(weights_path):
        try:
            weights_np = np.load(weights_path)
            return torch.from_numpy(weights_np).float()
        except Exception as e:
            print(f"Failed to load cached weights: {e}. Recomputing...")

    # 2. Compute from scratch
    if not os.path.exists(train_csv_path):
        raise FileNotFoundError(f"Training metadata not found at {train_csv_path}")

    df = pd.read_csv(train_csv_path)
    y = df["category_id"].values

    # Ensure classes are sorted. This aligns with the index mapping (0..N-1)
    # generated by get_class_mappings because both sort the unique IDs.
    classes = np.unique(y)
    classes.sort()

    # Compute balanced weights: n_samples / (n_classes * np.bincount(y))
    weights_np = compute_class_weight(class_weight="balanced", classes=classes, y=y)

    # 3. Save to cache
    os.makedirs(os.path.dirname(weights_path), exist_ok=True)
    np.save(weights_path, weights_np)

    return torch.from_numpy(weights_np).float()


def calculate_macro_f1(y_true, y_pred):
    """
    Calculates Macro F1 score.

    Args:
        y_true (array-like): Ground truth labels (indices or raw IDs).
        y_pred (array-like): Predicted labels (indices or raw IDs).

    Returns:
        float: Macro F1 score.
    """
    return f1_score(y_true, y_pred, average="macro")
