import os
import torch
import numpy as np
import random


class Config:
    def __init__(self, debug=False, epochs=15):
        """
        Configuration for Apple Disease Detection Pipeline.

        Args:
            debug (bool): If True, use a small subset of data for debugging.
            epochs (int): Number of training epochs.
        """
        # ==========================
        # General Settings
        # ==========================
        self.seed = 42
        self.debug = debug
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        self.num_workers = 4  # Optimal for the available vCPUs

        # ==========================
        # Data Paths
        # ==========================
        self.input_dir = "./input"
        self.metadata_dir = "./metadata"
        self.images_dir = os.path.join(self.input_dir, "images")

        # Metadata files generated by the metadata script
        self.train_metadata_path = os.path.join(self.metadata_dir, "train_metadata.csv")
        self.val_metadata_path = os.path.join(self.metadata_dir, "val_metadata.csv")
        self.test_metadata_path = os.path.join(self.metadata_dir, "test_metadata.csv")

        # ==========================
        # Output Directories
        # ==========================
        self.working_dir = "./working/idea_12"
        self.models_dir = os.path.join(self.working_dir, "models")
        self.oof_dir = os.path.join(self.working_dir, "oof")
        self.submission_dir = "./submission"
        self.submission_path = os.path.join(self.submission_dir, "submission.csv")

        # Create necessary directories
        os.makedirs(self.working_dir, exist_ok=True)
        os.makedirs(self.models_dir, exist_ok=True)
        os.makedirs(self.oof_dir, exist_ok=True)
        os.makedirs(self.submission_dir, exist_ok=True)

        # ==========================
        # Dataset Parameters
        # ==========================
        self.img_size = 256
        self.batch_size = 64  # A100 40GB can handle this easily for ResNet34
        # Target columns based on dataset analysis (alphabetical order for consistency)
        self.target_cols = ["healthy", "multiple_diseases", "rust", "scab"]
        self.num_classes = len(self.target_cols)

        # ==========================
        # Model Parameters
        # ==========================
        self.model_name = "resnet34"
        self.pretrained = True

        # ==========================
        # Training Parameters
        # ==========================
        self.n_folds = 5
        self.epochs = epochs
        self.learning_rate = 1e-4
        self.min_lr = 1e-6
        self.weight_decay = 1e-4

        # ==========================
        # Distillation Parameters
        # ==========================
        self.distillation_alpha = 0.5  # Weight for Hard Loss vs Soft Loss
        self.temperature = 4.0  # Temperature for Softmax

        # ==========================
        # Reproducibility
        # ==========================
        self.set_seed()

    def set_seed(self):
        """Sets the random seed for reproducibility."""
        random.seed(self.seed)
        np.random.seed(self.seed)
        torch.manual_seed(self.seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(self.seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

    def get_image_path(self, filename):
        """Helper to get full image path from filename/relative path."""
        # Handles cases where filename might already contain 'images/' or not
        if filename.startswith("images/"):
            return os.path.join(self.input_dir, filename)
        return os.path.join(self.images_dir, filename)
