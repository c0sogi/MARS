import os
import torch


class Config:
    """
    Central configuration for the Apple Disease Detection pipeline.
    """

    # ==========================================
    # General Configuration
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging

    # ==========================================
    # Data Configuration
    # ==========================================
    IMG_SIZE = 256
    NUM_CLASSES = 4
    # Class labels sorted alphabetically as per sample_submission columns
    CLASS_LABELS = ["healthy", "multiple_diseases", "rust", "scab"]

    # ==========================================
    # Paths
    # ==========================================
    INPUT_DIR = "./input"
    IMAGES_DIR = os.path.join(INPUT_DIR, "images")
    METADATA_DIR = "./metadata"

    # Metadata paths generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output directories
    WORKING_DIR = "./working/idea_2"
    MODELS_DIR = os.path.join(WORKING_DIR, "models")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    N_FOLDS = 5
    BATCH_SIZE = 32
    EPOCHS = 30
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-5

    # Hardware
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 8  # Number of data loading workers

    @classmethod
    def setup_directories(cls):
        """
        Creates necessary output directories if they don't exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.MODELS_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

    @classmethod
    def get_class_index(cls, label):
        """
        Returns the index for a given class label.
        """
        return cls.CLASS_LABELS.index(label)

    @classmethod
    def get_class_label(cls, index):
        """
        Returns the label for a given class index.
        """
        return cls.CLASS_LABELS[index]
