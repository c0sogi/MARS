import os
import torch


class Config:
    """
    Configuration class for the Apple Disease Detection pipeline.
    Implements settings for the 'Decoupled Calibration with Full-Data Seed Ensembling' strategy.
    """

    # ==========================================
    # Path Configuration
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for caching and outputs
    # Using 'idea_16' as the designated workspace
    WORKING_DIR = "./working/idea_16"
    OUTPUT_DIR = os.path.join(WORKING_DIR, "output")
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")

    # Ensure working directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    os.makedirs(CACHE_DIR, exist_ok=True)

    # Metadata Paths (Generated by external script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Image Directory (relative to input)
    IMAGES_DIR = os.path.join(INPUT_DIR, "images")

    # Submission Path
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================================
    # Data Configuration
    # ==========================================
    # Target Columns
    TARGET_COLS = ["healthy", "multiple_diseases", "rust", "scab"]
    NUM_CLASSES = len(TARGET_COLS)

    # Image Parameters
    # Resolution strictly 256x256 to ensure pipeline consistency
    IMAGE_SIZE = 256
    CHANNELS = 3

    # Dataloader
    BATCH_SIZE = 32
    NUM_WORKERS = 6

    # ==========================================
    # Model Configuration
    # ==========================================
    MODEL_NAME = "resnet34"
    PRETRAINED = True

    # ==========================================
    # Training Configuration
    # ==========================================
    # Strategy: Decoupled Calibration
    # Stage 1: Calibration (5-Fold CV) to find optimal epoch (E_opt)
    # Stage 2: Production (Full Data) using E_opt

    N_FOLDS = 5
    MAX_EPOCHS = 15  # Sufficient budget for small dataset convergence

    # Optimization
    LEARNING_RATE = 1e-4  # Uniform LR
    WEIGHT_DECAY = 1e-6
    OPTIMIZER_NAME = "Adam"

    # Scheduler
    # Cosine Annealing Warm Restarts, T_0 synced with total epochs
    SCHEDULER_NAME = "CosineAnnealingWarmRestarts"
    T_0 = MAX_EPOCHS
    T_MULT = 1
    MIN_LR = 1e-6

    # Loss
    LOSS_FUNCTION = "CrossEntropyLoss"
    USE_CLASS_WEIGHTS = True  # Weighted CE to handle imbalance

    # ==========================================
    # Ensemble Configuration
    # ==========================================
    # 5 Seeds for Full-Data Seed Ensembling in Stage 2
    SEEDS = [42, 2021, 2022, 2023, 2024]

    # Inference
    USE_TTA = False  # Explicitly disabled to maintain validation-inference parity

    # ==========================================
    # Hardware
    # ==========================================
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    @classmethod
    def print_config(cls):
        print("=" * 30)
        print("Configuration:")
        for key, value in cls.__dict__.items():
            if not key.startswith("__") and not callable(value):
                print(f"{key}: {value}")
        print("=" * 30)
