import os
import torch


class Config:
    """
    Configuration class for Apple Disease Detection task.
    Implements parameters for 'Full-Data Seed Ensembling with Proxy Calibration'.
    """

    # ==========================================
    # General Setup
    # ==========================================
    PROJECT_NAME = "apple_disease_detection"
    IDEA_NAME = "idea_11"
    SEED = 42
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 50  # Number of samples to use when DEBUG is True

    # ==========================================
    # Directories & Paths
    # ==========================================
    # Input (Read-Only)
    INPUT_DIR = "./input"
    IMAGES_DIR = os.path.join(INPUT_DIR, "images")
    METADATA_DIR = "./metadata"

    # Metadata Files (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output (Writable)
    WORKING_DIR = os.path.join("./working", IDEA_NAME)
    OUTPUT_DIR = os.path.join(WORKING_DIR, "output")
    LOG_DIR = os.path.join(WORKING_DIR, "logs")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Create writable directories
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    os.makedirs(LOG_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================================
    # Data Specifications
    # ==========================================
    IMAGE_SIZE = 256
    NUM_CLASSES = 4
    CLASS_LABELS = ["healthy", "multiple_diseases", "rust", "scab"]

    # ==========================================
    # Model Architecture
    # ==========================================
    MODEL_NAME = "resnet34"
    PRETRAINED = True
    DROPOUT_RATE = 0.0  # Simple head, avoiding over-regularization

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 32
    NUM_WORKERS = 4
    PIN_MEMORY = True

    # Optimization
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-4

    # Scheduler (Cosine Annealing Warm Restarts)
    # Cycle length synchronized with total epoch budget
    # Cite solution_lesson_node_00015: Synchronize cycle length with budget
    EPOCHS = 10
    T_0 = 10
    T_MULT = 1
    MIN_LR = 1e-6

    # ==========================================
    # Strategy: Full-Data Seed Ensembling
    # ==========================================
    # Phase 1: Proxy Calibration (5-Fold CV to find optimal epoch)
    N_FOLDS = 5

    # Phase 2: Production Training (Full Data)
    # List of seeds for the final ensemble models
    ENSEMBLE_SEEDS = [42, 2021, 2022, 2023, 2024]

    # Inference
    USE_TTA = True  # Will be conditionally applied based on Phase 1 validation

    # ==========================================
    # Compute
    # ==========================================
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print(f"==== Configuration: {cls.IDEA_NAME} ====")
        print(f"Device: {cls.DEVICE}")
        print(f"Model: {cls.MODEL_NAME}")
        print(f"Image Size: {cls.IMAGE_SIZE}")
        print(f"Batch Size: {cls.BATCH_SIZE}")
        print(f"Epochs: {cls.EPOCHS}")
        print(f"Ensemble Seeds: {cls.ENSEMBLE_SEEDS}")
        print(f"Output Dir: {cls.OUTPUT_DIR}")
        print("==========================================")
