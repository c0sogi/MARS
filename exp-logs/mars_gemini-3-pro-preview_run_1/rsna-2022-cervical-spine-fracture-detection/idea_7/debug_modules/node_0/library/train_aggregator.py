import os
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader
import numpy as np

from library.config import Config
from library.models import DualStreamRNN
from library.data import PatientSequenceDataset
from library.utils import RSNALoss, weighted_log_loss_numpy


def train_one_epoch(model, loader, optimizer, criterion, device):
    """
    Trains the aggregator model for one epoch.
    """
    model.train()
    running_loss = 0.0

    for batch in loader:
        # Unpack batch (collate_fn returns: local_emb, global_ctx, anat_probs, targets, lengths)
        local_emb, global_ctx, anat_probs, targets, _ = batch

        local_emb = local_emb.to(device)
        global_ctx = global_ctx.to(device)
        anat_probs = anat_probs.to(device)
        targets = targets.to(device)

        optimizer.zero_grad()

        # Forward pass
        # Output shape: (Batch, 8) -> [C1...C7, Patient_Overall]
        logits = model(local_emb, global_ctx, anat_probs)

        # Calculate Loss
        loss = criterion(logits, targets)

        # Backward pass
        loss.backward()
        optimizer.step()

        running_loss += loss.item()

    return running_loss / len(loader)


def validate(model, loader, criterion, device):
    """
    Validates the model and calculates the competition metric.
    """
    model.eval()
    running_loss = 0.0

    all_preds = []
    all_targets = []

    with torch.no_grad():
        for batch in loader:
            local_emb, global_ctx, anat_probs, targets, _ = batch

            local_emb = local_emb.to(device)
            global_ctx = global_ctx.to(device)
            anat_probs = anat_probs.to(device)
            targets = targets.to(device)

            logits = model(local_emb, global_ctx, anat_probs)
            loss = criterion(logits, targets)

            running_loss += loss.item()

            # Apply sigmoid to get probabilities for metric calculation
            probs = torch.sigmoid(logits)

            all_preds.append(probs.cpu().numpy())
            all_targets.append(targets.cpu().numpy())

    # Concatenate all batches
    if len(all_preds) > 0:
        all_preds = np.concatenate(all_preds, axis=0)
        all_targets = np.concatenate(all_targets, axis=0)

        # Calculate competition metric
        metric_score = weighted_log_loss_numpy(all_preds, all_targets)
    else:
        metric_score = float("inf")

    return running_loss / len(loader), metric_score


def train_stage3(load_cached_data=True):
    """
    Main function to train the Stage 3 Sequence Aggregator (Bi-GRU).

    Args:
        load_cached_data (bool): Whether to use cached dataset indices/files.
    """
    print("Initializing Stage 3: Sequence Aggregator Training...")

    # 1. Setup Device and Config
    device = torch.device(Config.DEVICE)
    Config.setup()

    # 2. Prepare Datasets and Loaders
    # Note: This dataset relies on features generated by feature_generator.py
    train_dataset = PatientSequenceDataset(
        split="train", load_cached_data=load_cached_data
    )
    val_dataset = PatientSequenceDataset(split="val", load_cached_data=load_cached_data)

    if len(train_dataset) == 0:
        print(
            "No training features found. Please run feature generation first. Exiting Stage 3."
        )
        return

    # Use the custom collate_fn from the dataset class to handle padding
    train_loader = DataLoader(
        train_dataset,
        batch_size=Config.STAGE3_BATCH_SIZE,
        shuffle=True,
        num_workers=Config.NUM_WORKERS,
        collate_fn=PatientSequenceDataset.collate_fn,
        pin_memory=True if device.type == "cuda" else False,
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=Config.STAGE3_BATCH_SIZE,
        shuffle=False,
        num_workers=Config.NUM_WORKERS,
        collate_fn=PatientSequenceDataset.collate_fn,
        pin_memory=True if device.type == "cuda" else False,
    )

    print(f"Training samples: {len(train_dataset)}")
    print(f"Validation samples: {len(val_dataset)}")

    # 3. Model Setup
    # Global context dim is 512 (from ResNet18 bottleneck in Stage 1)
    model = DualStreamRNN(global_context_dim=512).to(device)

    optimizer = optim.AdamW(
        model.parameters(), lr=Config.STAGE3_LR, weight_decay=Config.STAGE3_WEIGHT_DECAY
    )

    # Use the competition weighted loss
    criterion = RSNALoss(use_competition_weights=True)

    # 4. Training Loop
    best_val_metric = float("inf")
    patience = 5
    patience_counter = 0
    checkpoint_path = os.path.join(Config.CHECKPOINT_DIR, "fracture_aggregator.pth")

    print(f"Starting training for {Config.STAGE3_EPOCHS} epochs...")

    for epoch in range(Config.STAGE3_EPOCHS):
        # Train
        train_loss = train_one_epoch(model, train_loader, optimizer, criterion, device)

        # Validate
        val_loss, val_metric = validate(model, val_loader, criterion, device)

        print(
            f"Epoch {epoch+1}/{Config.STAGE3_EPOCHS} | "
            f"Train Loss: {train_loss} | "
            f"Val Loss: {val_loss} | "
            f"Val Metric: {val_metric}"
        )

        # Checkpointing & Early Stopping based on the competition metric
        if val_metric < best_val_metric:
            best_val_metric = val_metric
            patience_counter = 0
            torch.save(model.state_dict(), checkpoint_path)
            print(f"  New best model saved to {checkpoint_path}")
        else:
            patience_counter += 1
            print(f"  No improvement. Patience: {patience_counter}/{patience}")

        if patience_counter >= patience:
            print("Early stopping triggered.")
            break

    print("Stage 3 Training Completed.")
