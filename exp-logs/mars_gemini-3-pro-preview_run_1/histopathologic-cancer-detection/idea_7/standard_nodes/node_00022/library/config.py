import os
import torch


class Config:
    """
    Central Configuration for the Pathology Classification Task.
    Implements the strategy defined in Idea 7:
    - Model: DenseNet121 with GeM Pooling
    - Data: 48x48 Center Crops (Hard Attention)
    - Training: 5-Fold CV, 20 Epochs, Label Smoothing, AdamW
    """

    # ==========================================
    # General & Reproducibility
    # ==========================================
    SEED = 42

    # ==========================================
    # Directories & Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata paths generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output directories
    WORKING_DIR = "./working/idea_7"
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================================
    # Data Configuration
    # ==========================================
    # Original images are typically 96x96.
    # Task is center 32x32. We use 48x48 to include context.
    IMG_SIZE = 48

    # Augmentation Settings
    # Conservative augmentation: Flips, Rotations, Mild Brightness/Contrast
    AUG_PROB = 0.5
    AUG_BRIGHTNESS_LIMIT = 0.1
    AUG_CONTRAST_LIMIT = 0.1

    # ==========================================
    # Model Configuration
    # ==========================================
    MODEL_NAME = "densenet121"
    PRETRAINED = True
    NUM_CLASSES = 1

    # GeM Pooling Parameter
    USE_GEM_POOLING = True
    GEM_P_INIT = 3.0

    # ==========================================
    # Training Configuration
    # ==========================================
    NUM_FOLDS = 5
    EPOCHS = 20
    BATCH_SIZE = 256  # A100 allows large batch size for small images

    # Optimization
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 0.01  # AdamW default
    LABEL_SMOOTHING = 0.05

    # Scheduler (Cosine Annealing)
    T_MAX = EPOCHS
    MIN_LR = 1e-6

    # Early Stopping
    PATIENCE = 6

    # ==========================================
    # Hardware & Performance
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 8  # 12 vCPUs available
    PIN_MEMORY = True

    # ==========================================
    # Debugging & Development
    # ==========================================
    # If set to an integer, limits the dataset size for rapid prototyping
    DEBUG_SAMPLE_SIZE = None

    # ==========================================
    # Inference / TTA
    # ==========================================
    # Test Time Augmentation: Original + HFlip + VFlip + Rot90
    TTA_ENABLED = True
