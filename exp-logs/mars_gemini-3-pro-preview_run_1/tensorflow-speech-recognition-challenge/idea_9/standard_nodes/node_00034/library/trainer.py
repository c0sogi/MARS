import os
import torch
import torch.nn as nn
import torch.nn.functional as F
import pandas as pd
import numpy as np
from library.config import Config, set_seed
from library.utils import get_logger, map_prediction_to_label
from library.dataset import get_dataloaders
from library.model import DilatedEfficientNet


class SoftCrossEntropyLoss(nn.Module):
    """
    Cross Entropy Loss that handles soft targets (probabilities)
    generated by Mixup augmentation.
    """

    def __init__(self):
        super(SoftCrossEntropyLoss, self).__init__()

    def forward(self, logits, targets):
        # logits: (B, C)
        # targets: (B, C) - One-hot or soft labels
        log_probs = F.log_softmax(logits, dim=1)
        # Cross Entropy: - sum(target * log_prob)
        return -(targets * log_probs).sum(dim=1).mean()


class Trainer:
    def __init__(self, load_cached_data=True, debug_subset_size=None):
        self.logger = get_logger("trainer")
        self.device = Config.DEVICE
        self.num_classes = Config.NUM_CLASSES

        # Data Loaders
        self.train_loader, self.val_loader, self.test_loader = get_dataloaders(
            batch_size=Config.BATCH_SIZE,
            num_workers=Config.NUM_WORKERS,
            load_cached_data=load_cached_data,
            debug_subset_size=debug_subset_size,
        )

        # Model
        self.model = DilatedEfficientNet(num_classes=self.num_classes, pretrained=True)
        self.model.to(self.device)

        # Optimization
        self.optimizer = torch.optim.AdamW(
            self.model.parameters(),
            lr=Config.LEARNING_RATE,
            weight_decay=Config.WEIGHT_DECAY,
        )

        self.scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
            self.optimizer, T_max=Config.EPOCHS, eta_min=1e-6
        )

        # Loss Functions
        # Training uses soft targets (Mixup)
        self.train_criterion = SoftCrossEntropyLoss()
        # Validation uses standard indices
        self.val_criterion = nn.CrossEntropyLoss()

        # State
        self.best_acc = 0.0
        self.best_model_path = os.path.join(Config.CACHE_DIR, "best_model.pth")

        # Ensure cache dir exists
        os.makedirs(Config.CACHE_DIR, exist_ok=True)

    def train_one_epoch(self, epoch_idx):
        self.model.train()
        running_loss = 0.0
        count = 0

        for batch_idx, (inputs, targets) in enumerate(self.train_loader):
            inputs = inputs.to(self.device)
            targets = targets.to(self.device)

            self.optimizer.zero_grad()

            outputs = self.model(inputs)
            loss = self.train_criterion(outputs, targets)

            loss.backward()
            self.optimizer.step()

            running_loss += loss.item() * inputs.size(0)
            count += inputs.size(0)

        avg_loss = running_loss / count if count > 0 else 0.0
        return avg_loss

    def validate(self):
        self.model.eval()
        running_loss = 0.0
        count = 0

        # Fine-grained stats
        correct_fine = 0
        total_samples = 0

        # Competition metric stats (12 classes)
        correct_comp = 0

        # Mapping helpers
        id2label = Config.get_id2label()

        with torch.no_grad():
            for inputs, targets in self.val_loader:
                inputs = inputs.to(self.device)
                targets = targets.to(self.device)  # (B,) indices

                outputs = self.model(inputs)
                loss = self.val_criterion(outputs, targets)

                running_loss += loss.item() * inputs.size(0)
                count += inputs.size(0)

                # Predictions
                preds = torch.argmax(outputs, dim=1)

                # Update Fine-Grained Accuracy
                correct_fine += (preds == targets).sum().item()
                total_samples += targets.size(0)

                # Update Competition Accuracy
                # We must map both pred and target to the 12-class format
                preds_cpu = preds.cpu().numpy()
                targets_cpu = targets.cpu().numpy()

                for p_idx, t_idx in zip(preds_cpu, targets_cpu):
                    # Map indices to submission strings
                    pred_str = map_prediction_to_label(p_idx)

                    # For target, we manually do the mapping logic since map_prediction_to_label handles logic
                    # We can reuse map_prediction_to_label because it takes an int ID.
                    # The validation dataset returns IDs consistent with Config.ALL_LABELS
                    target_str = map_prediction_to_label(t_idx)

                    if pred_str == target_str:
                        correct_comp += 1

        avg_loss = running_loss / count if count > 0 else 0.0
        fine_acc = correct_fine / total_samples if total_samples > 0 else 0.0
        comp_acc = correct_comp / total_samples if total_samples > 0 else 0.0

        return avg_loss, fine_acc, comp_acc

    def fit(self, epochs=Config.EPOCHS, patience=10):
        self.logger.info(
            f"Starting training for {epochs} epochs on device {self.device}..."
        )

        no_improve_epochs = 0

        for epoch in range(1, epochs + 1):
            train_loss = self.train_one_epoch(epoch)
            val_loss, val_fine_acc, val_comp_acc = self.validate()

            self.scheduler.step()

            self.logger.info(
                f"Epoch {epoch}/{epochs} | "
                f"Train Loss: {train_loss:.6f} | "
                f"Val Loss: {val_loss:.6f} | "
                f"Val Fine Acc: {val_fine_acc:.6f} | "
                f"Val Comp Acc: {val_comp_acc:.6f}"
            )

            # Model Selection based on Fine-Grained Accuracy
            if val_fine_acc > self.best_acc:
                self.best_acc = val_fine_acc
                torch.save(self.model.state_dict(), self.best_model_path)
                self.logger.info(
                    f"New best model saved with Fine Acc: {self.best_acc:.6f}"
                )
                no_improve_epochs = 0
            else:
                no_improve_epochs += 1

            if no_improve_epochs >= patience:
                self.logger.info(
                    f"Early stopping triggered after {patience} epochs without improvement."
                )
                break

        self.logger.info(f"Training completed. Best Fine Acc: {self.best_acc:.6f}")

    def predict(self):
        """
        Generates predictions for the test set using the best saved model.
        Saves the result to submission/submission.csv.
        """
        self.logger.info("Starting prediction on test set...")

        # Load best model
        if not os.path.exists(self.best_model_path):
            self.logger.warning("Best model not found. Using current model state.")
        else:
            self.logger.info(f"Loading model from {self.best_model_path}")
            self.model.load_state_dict(
                torch.load(self.best_model_path, map_location=self.device)
            )

        self.model.eval()

        predictions = []
        fnames = []

        # Test loader returns (spec, label_id) but label_id is dummy for test
        # We need the filenames. The dataset doesn't return filenames in __getitem__.
        # We must access the dataset's dataframe directly to align filenames.
        # The DataLoader is sequential and not shuffled, so order is preserved.

        test_df = self.test_loader.dataset.df

        with torch.no_grad():
            batch_start_idx = 0
            for inputs, _ in self.test_loader:
                inputs = inputs.to(self.device)
                outputs = self.model(inputs)

                # Get predicted class indices
                batch_preds = torch.argmax(outputs, dim=1).cpu().numpy()

                # Map to submission labels
                for idx, pred_idx in enumerate(batch_preds):
                    label_str = map_prediction_to_label(pred_idx)

                    # Get filename from dataframe
                    # Global index = batch_start_idx + idx
                    global_idx = batch_start_idx + idx
                    if global_idx < len(test_df):
                        # filepath is like "test/audio/clip_xxxx.wav"
                        # Submission format requires just filename "clip_xxxx.wav"
                        full_path = test_df.iloc[global_idx]["filepath"]
                        fname = os.path.basename(full_path)

                        fnames.append(fname)
                        predictions.append(label_str)

                batch_start_idx += inputs.size(0)

        # Create Submission DataFrame
        submission_df = pd.DataFrame({"fname": fnames, "label": predictions})

        # Ensure submission directory exists
        submission_dir = "./submission"
        os.makedirs(submission_dir, exist_ok=True)
        submission_path = os.path.join(submission_dir, "submission.csv")

        submission_df.to_csv(submission_path, index=False)
        self.logger.info(
            f"Submission saved to {submission_path} with {len(submission_df)} rows."
        )
