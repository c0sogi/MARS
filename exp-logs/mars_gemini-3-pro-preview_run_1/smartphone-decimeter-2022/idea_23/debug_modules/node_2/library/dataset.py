import torch
import numpy as np
import pandas as pd
from torch.utils.data import Dataset
from library.config import Config
from library.preprocessing import GNSSPreprocessor


class GNSSSequenceDataset(Dataset):
    """
    PyTorch Dataset for GNSS sequences.
    Groups processed data by drive and phone to form continuous time-series windows.
    Handles feature extraction, target generation, and decimation for deep supervision.
    """

    def __init__(self, processed_df, mode="train", config=None):
        """
        Args:
            processed_df (pd.DataFrame): Dataframe containing processed features and targets (for train/val).
            mode (str): 'train', 'val', or 'test'.
            config (Config): Configuration object.
        """
        self.mode = mode
        self.config = config if config is not None else Config()

        # Group data by unique drive sequences
        # Each group corresponds to one continuous drive log
        self.groups = list(processed_df.groupby(["drive_id", "phone_name"]))

        # Generate the list of feature column names based on Config and Preprocessing logic
        self.feature_cols = self._get_feature_columns()

        # Target columns (East, North residuals)
        self.target_cols = ["target_E", "target_N"]

        # WLS columns for reconstruction
        self.wls_cols = ["WLS_Lat", "WLS_Lon", "WLS_Alt"]

    def _get_feature_columns(self):
        """
        Reconstructs the feature column names generated by the preprocessor.
        """
        cols = [
            "Global_SignalCount",
            "Global_RawPseudorangeUncertaintyMeters_mean",
            "Global_AzimuthCentroid_X",
            "Global_AzimuthCentroid_Y",
        ]

        for stratum in self.config.STRATA:
            # Stats features
            for feat in ["Cn0DbHz", "SvElevationDegrees"]:
                for stat in self.config.STATS_FUNCS:
                    cols.append(f"{stratum}_{feat}_{stat}")
            # Phase validity features
            cols.append(f"{stratum}_PhaseValid_count")
            cols.append(f"{stratum}_PhaseValid_fraction")

        return cols

    def __len__(self):
        return len(self.groups)

    def __getitem__(self, idx):
        (drive_id, phone_name), df_seq = self.groups[idx]

        # Ensure sequence is sorted by time
        df_seq = df_seq.sort_values("UnixTimeMillis")

        # 1. Extract Features
        # Shape: (Sequence_Length, Input_Channels) -> Transpose to (Input_Channels, Sequence_Length)
        features = df_seq[self.feature_cols].values.astype(np.float32)
        features_t = torch.tensor(features).transpose(0, 1)  # (C, L)

        # 2. Extract Metadata
        timestamps = df_seq["UnixTimeMillis"].values

        # WLS Baseline (needed for all modes for reconstruction)
        wls_pos = df_seq[self.wls_cols].values.astype(
            np.float64
        )  # Keep high precision for coords

        result = {
            "features": features_t,
            "drive_id": drive_id,
            "phone_name": phone_name,
            "timestamps": timestamps,
            "wls_pos": wls_pos,
        }

        # 3. Extract Targets (Train/Val only)
        if self.mode in ["train", "val"]:
            targets = df_seq[self.target_cols].values.astype(np.float32)
            targets_t = torch.tensor(targets).transpose(0, 1)  # (Output_Channels, L)

            result["targets"] = targets_t

            # 4. Generate Decimated Targets for Deep Supervision
            # Factors correspond to decoder outputs: 1/8, 1/4, 1/2, 1/1
            # We slice the full resolution target.
            # Note: Exact alignment depends on padding in collate_fn.
            # Here we provide the raw sliced versions; collate_fn will pad them.
            decimated_targets = []

            # Factors: 8, 4, 2, 1 (Full res is handled separately as main target, but added here for consistency if needed)
            # The config AUX_LOSS_WEIGHTS implies 4 heads.
            # Usually: Head 0 (Deepest) -> stride 8, Head 1 -> stride 4, Head 2 -> stride 2, Head 3 -> stride 1
            strides = [8, 4, 2, 1]

            for s in strides:
                # Simple subsampling.
                # Note: For strict correctness with conv arithmetic, center-aligned or average pooling might be better,
                # but subsampling is standard for segmentation-like tasks with dense targets.
                sub_target = targets_t[:, ::s]
                decimated_targets.append(sub_target)

            result["decimated_targets"] = decimated_targets

        return result

    @staticmethod
    def collate_fn(batch):
        """
        Custom collate function to handle variable length sequences.
        Pads sequences to the nearest multiple of 16 (max downsampling factor).
        """
        # separate items
        features_list = [item["features"] for item in batch]
        meta_list = [
            {
                k: v
                for k, v in item.items()
                if k not in ["features", "targets", "decimated_targets"]
            }
            for item in batch
        ]

        # Determine max length in this batch
        max_len = max([f.shape[1] for f in features_list])

        # Round up to nearest multiple of 16 to ensure valid shape through UNet bottleneck
        pad_divisor = 16
        target_len = ((max_len + pad_divisor - 1) // pad_divisor) * pad_divisor

        # Initialize batched tensors
        batch_size = len(batch)
        n_in_channels = features_list[0].shape[0]

        # Features: (B, C, L)
        batched_features = torch.zeros(
            (batch_size, n_in_channels, target_len), dtype=torch.float32
        )

        # Masks: (B, L) - 1 for valid data, 0 for padding
        batched_masks = torch.zeros((batch_size, target_len), dtype=torch.float32)

        has_targets = "targets" in batch[0]
        batched_targets = None
        batched_decimated = []

        if has_targets:
            n_out_channels = batch[0]["targets"].shape[0]
            batched_targets = torch.zeros(
                (batch_size, n_out_channels, target_len), dtype=torch.float32
            )

            # Prepare lists for decimated targets
            # Assuming all items have same number of decimated levels
            num_levels = len(batch[0]["decimated_targets"])
            strides = [8, 4, 2, 1]  # Must match __getitem__ logic

            for i in range(num_levels):
                stride = strides[i]
                level_len = target_len // stride
                batched_decimated.append(
                    torch.zeros(
                        (batch_size, n_out_channels, level_len), dtype=torch.float32
                    )
                )

        # Fill batches
        for i, item in enumerate(batch):
            seq_len = item["features"].shape[1]

            # Fill features
            batched_features[i, :, :seq_len] = item["features"]

            # Fill mask
            batched_masks[i, :seq_len] = 1.0

            if has_targets:
                # Fill full resolution target
                batched_targets[i, :, :seq_len] = item["targets"]

                # Fill decimated targets
                for level_idx, sub_target in enumerate(item["decimated_targets"]):
                    sub_len = sub_target.shape[1]
                    batched_decimated[level_idx][i, :, :sub_len] = sub_target

        output = {
            "features": batched_features,
            "masks": batched_masks,
            "metadata": meta_list,
        }

        if has_targets:
            output["targets"] = batched_targets
            output["decimated_targets"] = batched_decimated

        return output


def get_datasets(config, load_cached_data=True):
    """
    Factory function to load data, process it, and return Dataset objects.

    Args:
        config (Config): Configuration object.
        load_cached_data (bool): Whether to attempt loading from cache.

    Returns:
        tuple: (train_dataset, val_dataset, test_dataset)
    """
    preprocessor = GNSSPreprocessor(config)

    # 1. Train Data
    try:
        df_train = preprocessor.process_dataset(
            config.TRAIN_METADATA_PATH, mode="train", load_cached_data=load_cached_data
        )
        train_dataset = GNSSSequenceDataset(df_train, mode="train", config=config)
    except Exception as e:
        print(f"Error creating train dataset: {e}")
        train_dataset = None

    # 2. Validation Data
    try:
        df_val = preprocessor.process_dataset(
            config.VAL_METADATA_PATH, mode="val", load_cached_data=load_cached_data
        )
        val_dataset = GNSSSequenceDataset(df_val, mode="val", config=config)
    except Exception as e:
        print(f"Error creating val dataset: {e}")
        val_dataset = None

    # 3. Test Data
    try:
        df_test = preprocessor.process_dataset(
            config.TEST_METADATA_PATH, mode="test", load_cached_data=load_cached_data
        )
        test_dataset = GNSSSequenceDataset(df_test, mode="test", config=config)
    except Exception as e:
        print(f"Error creating test dataset: {e}")
        test_dataset = None

    return train_dataset, val_dataset, test_dataset
