import os
import torch


class Config:
    """
    Configuration class for the Cyclic Spatio-Temporal 2D ResUNet project.
    Centralizes hyperparameters, file paths, and data processing settings.
    """

    # -------------------------------------------------------------------------
    # General Settings
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to use a small subset of data for debugging

    # -------------------------------------------------------------------------
    # File Paths and Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory specific to this idea
    WORKING_DIR = "./working/idea_21"

    # Sub-directories for organized storage
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    MODEL_DIR = os.path.join(WORKING_DIR, "models")
    SUBMISSION_DIR = os.path.join(WORKING_DIR, "submission")

    # Ensure necessary directories exist
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(MODEL_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata file paths (generated by the provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # -------------------------------------------------------------------------
    # Data Processing Hyperparameters
    # -------------------------------------------------------------------------
    # Spatio-Temporal Heatmap Construction
    AZIMUTH_BINS = 36  # 360 degrees divided into 10-degree bins

    # Input Features per Bin:
    # 1. Max Cn0DbHz (Signal Quality)
    # 2. Mean Cn0DbHz (Signal Quality)
    # 3. Mean SvElevationDegrees (Geometry)
    # 4. SatCount (Density in bin)
    # 5. Global Total SatCount (Broadcasted)
    # 6. Global Mean RawPseudorangeUncertaintyMeters (Broadcasted)
    INPUT_CHANNELS = 6

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    # Encoder channel progression
    ENCODER_CHANNELS = [32, 64, 128, 256]
    # Decoder channel progression
    DECODER_CHANNELS = [128, 64, 32]

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    # Temporal Windowing for Training
    WINDOW_SIZE = 128  # Number of seconds (timesteps) per training sample
    STRIDE = 64  # Overlap stride for generating windows

    BATCH_SIZE = 32
    EPOCHS = 30
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Optimization
    PATIENCE = 5  # Early stopping patience
    GRAD_CLIP = 1.0  # Gradient clipping value

    # -------------------------------------------------------------------------
    # Hardware
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print("=" * 40)
        print("CYCLIC SPATIO-TEMPORAL 2D RESUNET CONFIG")
        print("=" * 40)
        for k, v in cls.__dict__.items():
            if not k.startswith("__") and not callable(v):
                print(f"{k:<25}: {v}")
        print("=" * 40)
