import os


class Config:
    """
    Configuration parameters for the 1D Atrous Residual U-Net GNSS correction project.
    """

    # ==========================================
    # Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_12"
    SUBMISSION_DIR = "./submission"

    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Ensure working directory exists
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================================
    # Data Preprocessing & Feature Engineering
    # ==========================================
    # Random seed for reproducibility
    SEED = 42

    # Temporal quantization (1Hz)
    TIME_ROUNDING = "1s"

    # Raw GNSS columns to load
    RAW_GNSS_COLS = [
        "utcTimeMillis",
        "Cn0DbHz",
        "SvElevationDegrees",
        "RawPseudorangeUncertaintyMeters",
    ]

    # Feature Aggregations
    # Dictionary mapping raw column names to list of aggregation functions
    FEATURE_AGGREGATIONS = {
        "Cn0DbHz": ["mean", "min", "max"],
        "SvElevationDegrees": ["mean", "min", "max"],
        "RawPseudorangeUncertaintyMeters": ["mean"],
    }

    # Metadata features to generate explicitly
    # 'count' will be generated as 'SatCount' during aggregation
    INCLUDE_SAT_COUNT = True

    # Final Input Feature Names (Order matters for the model input)
    # These must match the columns generated by the preprocessing pipeline
    INPUT_FEATURES = [
        "Cn0DbHz_mean",
        "Cn0DbHz_min",
        "Cn0DbHz_max",
        "SvElevationDegrees_mean",
        "SvElevationDegrees_min",
        "SvElevationDegrees_max",
        "RawPseudorangeUncertaintyMeters_mean",
        "SatCount",
    ]

    # Number of input channels for the model
    IN_CHANNELS = len(INPUT_FEATURES)

    # Target columns (Regression targets in meters)
    TARGET_COLS = ["delta_north", "delta_east"]
    OUT_CHANNELS = 2

    # ==========================================
    # Model Architecture (Atrous ResUNet)
    # ==========================================
    # Base number of filters in the encoder
    HIDDEN_DIM = 64

    # Dilation rates for the ASPP bottleneck
    ASPP_DILATION_RATES = [1, 6, 12, 18]

    # Encoder depth (number of downsampling stages)
    ENCODER_DEPTH = 4

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    BATCH_SIZE = 16  # Batch size refers to number of full drive sequences
    NUM_EPOCHS = 50
    EARLY_STOPPING_PATIENCE = 10

    # Loss weights for deep supervision
    # Weights for [Final Output, Decoder 1, Decoder 2, ...]
    LOSS_WEIGHTS = [1.0, 0.5, 0.25]

    # Debugging / Development
    # Set to a small integer (e.g., 100) to limit the number of drives processed
    # Set to None for full training
    DEBUG_SAMPLE_SIZE = None

    # ==========================================
    # Constants
    # ==========================================
    # WGS84 Ellipsoid constants for coordinate conversion
    WGS84_A = 6378137.0
    WGS84_F = 1 / 298.257223563
    WGS84_B = WGS84_A * (1 - WGS84_F)
