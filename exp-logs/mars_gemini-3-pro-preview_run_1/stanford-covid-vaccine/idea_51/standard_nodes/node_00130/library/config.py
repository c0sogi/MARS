import os
import torch


class Config:
    """
    Configuration class for the LayerDrop-Stabilized High-Capacity Wide-Stream BiGRU model.
    Centralizes all hyperparameters, file paths, and training settings.
    """

    # =========================================================================
    # File Paths & Directories
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Specific working directory for this idea to avoid conflicts
    WORKING_DIR = "./working/idea_51"

    # Ensure working directory exists
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Metadata Parquet Files (Generated by metadata script)
    TRAIN_FILE = os.path.join(METADATA_DIR, "train.parquet")
    VAL_FILE = os.path.join(METADATA_DIR, "val.parquet")
    TEST_FILE = os.path.join(METADATA_DIR, "test.parquet")

    # Submission
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")
    SUBMISSION_PATH = os.path.join(WORKING_DIR, "submission.csv")
    BEST_MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # =========================================================================
    # Data Specifications
    # =========================================================================
    # Target columns to predict and score
    TARGET_COLS = ["reactivity", "deg_Mg_pH10", "deg_Mg_50C"]

    # Sequence dimensions
    SEQ_LEN = 107  # Full sequence length
    PRED_LEN = 68  # Number of scored positions

    # =========================================================================
    # Model Architecture (High-Capacity Wide-Stream BiGRU)
    # =========================================================================
    # Embedding Dimensions
    EMBED_DIM = 128  # Atomic nucleotide embedding (A, G, C, U)
    LOOP_DIM = 64  # Predicted loop type embedding
    PAIR_DIM = 64  # Signed sinusoidal pairing distance embedding
    # Total Input Dim = 128 + 64 + 64 = 256

    # Backbone Dimensions
    HIDDEN_DIM = 512  # Wide stream capacity (Lesson 00022)
    N_LAYERS = 8  # Increased depth

    # Regularization
    DROPOUT = 0.2  # Inter-layer dropout

    # LayerDrop Schedule (Stochastic Depth)
    # Linearly decay survival probability from first to last layer
    LAYERDROP_MAX = 1.0  # Survival probability for the first block
    LAYERDROP_MIN = 0.6  # Survival probability for the last block

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    SEED = 42
    BATCH_SIZE = 64  # Standard batch size for high-capacity model
    EPOCHS = 20  # Fixed budget

    # Optimization
    LR = 1e-3  # AdamW learning rate
    WEIGHT_DECAY = 1e-4  # Low weight decay (Lesson 00070)
    CLIP_GRAD = 1.0  # Critical stabilizer for 512-width (Lesson 00097)

    # Scheduler
    T_MAX = 20  # For CosineAnnealing (matches EPOCHS)

    # Hardware
    NUM_WORKERS = 2
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    def __init__(self, debug: bool = False):
        """
        Initialize configuration, optionally overriding for debug mode.

        Args:
            debug (bool): If True, sets parameters for a quick dry-run
                          (fewer epochs, smaller batch, subset of data).
        """
        self.debug = debug
        if self.debug:
            self.EPOCHS = 2
            self.BATCH_SIZE = 16
            # In debug mode, data loaders should handle subsetting
            print("Config initialized in DEBUG mode: Epochs=2, BatchSize=16")
