import os
import random
import numpy as np
import torch


class Config:
    """
    Centralized configuration for the RNA Degradation Prediction task.
    Implements the 'Input-Normed Wide-Stream Residual BiGRU' strategy.
    """

    # =========================================================================
    # Reproducibility
    # =========================================================================
    SEED = 42

    # =========================================================================
    # Data Paths
    # =========================================================================
    # Metadata files generated by the metadata script
    TRAIN_METADATA = "./metadata/train.parquet"
    VAL_METADATA = "./metadata/val.parquet"
    TEST_METADATA = "./metadata/test.parquet"

    # Cache directory for processed tensors (deterministic data processing)
    CACHE_DIR = "./working/idea_40/"

    # Submission output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Dimensions
    # =========================================================================
    SEQ_LEN = 107  # Full sequence length
    PRED_LEN = 68  # Scored positions
    NUM_CLASSES = 3  # reactivity, deg_Mg_pH10, deg_Mg_50C

    # =========================================================================
    # Model Architecture: Input-Normed Wide-Stream Residual BiGRU
    # =========================================================================
    # Strategy: Unlock high-capacity Width 512 with strict regularization
    HIDDEN_DIM = 512  # Wide stream width (Lesson 00022)

    # Proportional Feature Embeddings (Lesson 00099)
    EMBED_DIM_SEQ = 128  # Atomic sequence embedding
    EMBED_DIM_LOOP = 64  # Predicted loop type embedding
    EMBED_DIM_DIST = 64  # Signed Sinusoidal Pairing Distance

    N_LAYERS = 6  # Shallow and Wide backbone (Lesson 00065)
    DROPOUT = 0.2  # Inter-layer dropout (Lesson 00076)

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 64
    EPOCHS = 20  # Fixed for Cosine Annealing (Lesson 00056)
    LR = 1e-3  # AdamW learning rate
    WEIGHT_DECAY = 1e-4  # Low weight decay to preserve recurrent signal (Lesson 00070)
    CLIP_GRAD_NORM = 1.0  # Gradient clipping for stability (Lesson 00097)

    # =========================================================================
    # Debugging / Development Controls
    # =========================================================================
    DEBUG = False  # Set to True to run on a small subset
    DEBUG_SUBSET_SIZE = 100  # Number of samples to use if DEBUG is True

    @staticmethod
    def setup_reproducibility(seed=42):
        """
        Sets random seeds for Python, NumPy, and PyTorch to ensure reproducibility.
        """
        random.seed(seed)
        os.environ["PYTHONHASHSEED"] = str(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

    @classmethod
    def create_dirs(cls):
        """
        Ensures necessary directories exist.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Automatically setup environment when module is imported
Config.setup_reproducibility(Config.SEED)
Config.create_dirs()
