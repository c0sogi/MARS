import os


class Config:
    """
    Configuration for the Time-Embedded Similarity Stratified Cascade (TESSC) model.

    This architecture resolves the Recency vs. Volume trade-off by using a long
    historical window (16 weeks) weighted by an aggressive temporal decay function,
    and enforces a strict priority hierarchy via score stratification.
    """

    # ==========================================
    # Global Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a smaller subset for debugging

    # ==========================================
    # File Paths
    # ==========================================
    # Base Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_10"  # Caching directory for this specific idea
    SUBMISSION_DIR = "./submission"

    # Input Data Files
    ARTICLES_PATH = os.path.join(INPUT_DIR, "articles.csv")
    CUSTOMERS_PATH = os.path.join(INPUT_DIR, "customers.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Splits (Generated by previous steps)
    TRAIN_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output Files
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # TESSC Architecture Hyperparameters
    # ==========================================

    # 1. Temporal Windowing
    # We extend the window to 16 weeks to capture the "Long Tail" of connectivity
    # while relying on decay to suppress noise.
    HISTORY_WEEKS = 16
    HISTORY_DAYS = HISTORY_WEEKS * 7  # 112 days

    # 2. Time-Embedding Decay Function
    # Formula: w(t) = 1 / (t + 1) ^ DECAY_POWER
    # A power of 0.5 corresponds to 1/sqrt(t+1), balancing recency with stability.
    DECAY_POWER = 0.5

    # 3. Stratification (Score Offsets)
    # Enforces strict hierarchy: Repurchase > CF > Trend
    # Scores are additive, but these offsets separate them into disjoint bands.

    # Stratum 1: Habitual Repurchase (The "Priors" Layer)
    # Range: [2000, inf)
    STRATA_HABIT_OFFSET = 2000.0

    # Stratum 2: Time-Embedded CF (The "Discovery" Layer)
    # Range: [100, 1000]
    # Raw similarity scores (0-1) are scaled and offset.
    STRATA_CF_OFFSET = 100.0
    STRATA_CF_SCALE = 900.0  # Maps normalized [0,1] scores to [0,900]

    # Stratum 3: Global Trend (The "Fallback" Layer)
    # Range: [0, 10]
    STRATA_TREND_SCALE = 10.0

    # ==========================================
    # Graph Construction & Inference
    # ==========================================
    # Collaborative Filtering Settings
    TOP_K_SIMILAR = (
        100  # Number of neighbors to retain per item in the similarity matrix
    )
    IDF_WEIGHTING = True  # Apply Inverse Document Frequency to item columns
    USER_L2_NORM = True  # Apply L2 normalization to user rows

    # Inference Settings
    TOP_K_PREDICT = 12  # Number of items to predict per customer

    # ==========================================
    # Setup Utilities
    # ==========================================
    @classmethod
    def setup(cls):
        """Ensures that working and submission directories exist."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Execute setup on import to guarantee directory structure
Config.setup()
