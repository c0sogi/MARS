import os
import torch
import numpy as np
import random


class Config:
    """
    Configuration class for the Stochastic ResNet34 Multi-Task U-Net.
    Centralizes all hyperparameters, paths, and settings.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run with a small subset of data for debugging
    NUM_WORKERS = 12  # Utilizing available vCPUs

    # =========================================================================
    # Directories & Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Specific working directory for caching processed data for this idea
    WORKING_DIR = "./working/idea_17"
    SUBMISSION_DIR = "./submission"

    # Metadata Paths (Generated by previous steps)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Output Paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    BEST_MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # =========================================================================
    # Data & Augmentation
    # =========================================================================
    IMG_SIZE = 512
    NUM_CLASSES = 4  # Negative, Typical, Indeterminate, Atypical

    # CoarseDropout Augmentation (Label-Consistent)
    # ~10% of image dimension (512 * 0.1 ~= 51)
    CD_MAX_HOLES = 8
    CD_MAX_HEIGHT = 52
    CD_MAX_WIDTH = 52
    CD_MIN_HOLES = 1
    CD_FILL_VALUE = 0
    # Crucial: mask_fill_value=0 ensures removed image regions are also removed from mask
    CD_MASK_FILL_VALUE = 0

    # =========================================================================
    # Model Architecture
    # =========================================================================
    BACKBONE = "resnet34"
    PRETRAINED = True
    DROP_PATH_RATE = 0.2  # Stochastic Depth rate for regularization

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 32
    EPOCHS = 25

    # Optimizer settings
    # Linear Scaling Rule: LR = Base_LR * (Batch_Size / 256)
    # We target an effective LR of ~5e-4 for Batch 32.
    # Therefore, Base_LR (for 256) should be 4e-3.
    # 4e-3 * (32/256) = 4e-3 * 0.125 = 5e-4
    BASE_LR = 4e-3
    LEARNING_RATE = BASE_LR * (BATCH_SIZE / 256.0)

    WEIGHT_DECAY = 1e-2

    # Scheduler (Cosine Annealing)
    T_MAX = EPOCHS
    ETA_MIN = 1e-6

    # Loss Weighting (Prioritizing Segmentation)
    STUDY_LOSS_WEIGHT = 1.0
    IMAGE_LOSS_WEIGHT = 10.0

    # =========================================================================
    # Setup Methods
    # =========================================================================
    @classmethod
    def setup(cls):
        """
        Initializes the environment:
        1. Creates necessary directories.
        2. Sets random seeds for reproducibility.
        3. Determines computation device.
        """
        # Create directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        torch.cuda.manual_seed(cls.SEED)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False

        # Device
        cls.DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

        # Debug adjustments
        if cls.DEBUG:
            cls.EPOCHS = 2
            cls.BATCH_SIZE = 8
            cls.LEARNING_RATE = 1e-4  # Safe default for debug
            print(f"DEBUG MODE ENABLED: Epochs={cls.EPOCHS}, Batch={cls.BATCH_SIZE}")

        print(f"Configuration Setup Complete.")
        print(f"Device: {cls.DEVICE}")
        print(f"Backbone: {cls.BACKBONE} | DropPath: {cls.DROP_PATH_RATE}")
        print(f"Input Size: {cls.IMG_SIZE}x{cls.IMG_SIZE}")
        print(f"Batch Size: {cls.BATCH_SIZE} | LR: {cls.LEARNING_RATE:.2e}")
        print(
            f"Loss Weights -> Study: {cls.STUDY_LOSS_WEIGHT}, Image: {cls.IMAGE_LOSS_WEIGHT}"
        )
