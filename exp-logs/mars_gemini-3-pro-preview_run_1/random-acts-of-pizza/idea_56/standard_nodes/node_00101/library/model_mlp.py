import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import Dataset, DataLoader
from sklearn.metrics import roc_auc_score

from library.config import Config
from library.utils import print_log, seed_everything, get_device
from library.feature_manager import FeatureManager


class PizzaDataset(Dataset):
    """
    PyTorch Dataset for the Pizza Request data.
    Wraps the numpy arrays generated by FeatureManager.
    """

    def __init__(self, data_dict, mode="train"):
        self.mode = mode
        self.title_emb = torch.tensor(data_dict["title_emb"], dtype=torch.float32)
        self.body_emb = torch.tensor(data_dict["body_emb"], dtype=torch.float32)
        self.history_seq = torch.tensor(data_dict["history_seq"], dtype=torch.float32)
        self.centroid_emb = torch.tensor(data_dict["centroid_emb"], dtype=torch.float32)
        self.metadata = torch.tensor(data_dict["metadata"], dtype=torch.float32)

        if mode != "test":
            self.y = torch.tensor(data_dict["y"], dtype=torch.float32)
        else:
            self.y = torch.zeros(len(self.title_emb), dtype=torch.float32)

    def __len__(self):
        return len(self.title_emb)

    def __getitem__(self, idx):
        return {
            "title_emb": self.title_emb[idx],
            "body_emb": self.body_emb[idx],
            "history_seq": self.history_seq[idx],
            "centroid_emb": self.centroid_emb[idx],
            "metadata": self.metadata[idx],
            "y": self.y[idx],
        }


class DualQueryAttention(nn.Module):
    """
    Attention mechanism to query User History using Title and Body.
    Implements Explicit Additive Masking.
    """

    def __init__(self, embed_dim):
        super(DualQueryAttention, self).__init__()
        self.scale = embed_dim**-0.5
        # No learnable parameters for raw dot-product attention as per design,
        # but we can add a projection if needed. Keeping it simple as per idea description.

    def forward(self, query, keys, mask=None):
        """
        Args:
            query: (Batch, Embed_Dim)
            keys: (Batch, Seq_Len, Embed_Dim)
            mask: (Batch, Seq_Len) - Boolean mask where True indicates padding/ignore.
        Returns:
            context: (Batch, Embed_Dim)
        """
        # Expand query to (Batch, 1, Embed_Dim)
        query = query.unsqueeze(1)

        # Dot product scores: (Batch, 1, Seq_Len)
        scores = torch.bmm(query, keys.transpose(1, 2)) * self.scale

        if mask is not None:
            # Expand mask to (Batch, 1, Seq_Len)
            mask = mask.unsqueeze(1)
            # Apply additive masking (-inf)
            scores = scores.masked_fill(mask, -1e9)

        attn_weights = torch.softmax(scores, dim=-1)

        # Context: (Batch, 1, Embed_Dim) -> (Batch, Embed_Dim)
        context = torch.bmm(attn_weights, keys).squeeze(1)
        return context


class NonLinearGate(nn.Module):
    """
    Non-Linear MLP Gate to modulate semantic features based on metadata (credibility).
    Architecture: Dense -> ReLU -> Dense -> Sigmoid
    """

    def __init__(self, input_dim, output_dim):
        super(NonLinearGate, self).__init__()
        # Intermediate dimension can be smaller or larger.
        # Using input_dim // 2 or a fixed size like 64.
        hidden_dim = max(input_dim, 64)

        self.net = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, output_dim),
            nn.Sigmoid(),
        )

    def forward(self, x):
        return self.net(x)


class PizzaNet(nn.Module):
    """
    Hybrid Ensemble Stream B: Non-Linear Orthogonal Skip-Gated MLP.
    """

    def __init__(self, metadata_dim, embed_dim=384, hidden_dim=Config.MLP_HIDDEN_DIM):
        super(PizzaNet, self).__init__()

        # 1. Attention Modules
        self.attn_title = DualQueryAttention(embed_dim)
        self.attn_body = DualQueryAttention(embed_dim)

        # 2. Semantic Vector Construction
        # Components: Title, Body, Context_Title, Context_Body, Centroid
        self.semantic_dim = embed_dim * 5

        # 3. Non-Linear Gate
        # Input: Metadata, Output: Semantic Dim
        self.gate = NonLinearGate(metadata_dim, self.semantic_dim)

        # 4. Fusion Layer
        # Input: Gated Semantic + Metadata (Skip Connection)
        fusion_input_dim = self.semantic_dim + metadata_dim

        # 5. Classifier Head
        self.classifier = nn.Sequential(
            nn.Linear(fusion_input_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(Config.MLP_DROPOUT_DENSE),
            nn.Linear(hidden_dim, hidden_dim // 2),
            nn.ReLU(),
            nn.Dropout(Config.MLP_DROPOUT_DENSE),
            nn.Linear(hidden_dim // 2, 1),
        )

        # Dropout for embeddings
        self.emb_dropout = nn.Dropout(Config.MLP_DROPOUT_EMB)

    def forward(self, title_emb, body_emb, history_seq, centroid_emb, metadata):
        # Create mask for history sequence (Batch, Seq_Len)
        # Assuming zero-padding implies padding. Check norm of embeddings.
        # history_seq shape: (B, S, D)
        # mask: True where vector is all zeros
        mask = history_seq.abs().sum(dim=-1) == 0

        # Apply dropout to embeddings
        title_emb = self.emb_dropout(title_emb)
        body_emb = self.emb_dropout(body_emb)
        history_seq = self.emb_dropout(history_seq)
        centroid_emb = self.emb_dropout(centroid_emb)

        # Branch 3: Dual-Query Attention
        context_title = self.attn_title(title_emb, history_seq, mask)
        context_body = self.attn_body(body_emb, history_seq, mask)

        # Construct Semantic Vector S
        # Concatenate: [Title, Body, Context_Title, Context_Body, Centroid]
        S = torch.cat(
            [title_emb, body_emb, context_title, context_body, centroid_emb], dim=1
        )

        # Branch 5 & Gating: Calculate Gate G from Metadata
        G = self.gate(metadata)

        # Gated Semantic: S * G
        gated_S = S * G

        # Final Fusion: Concat [Gated_S, Metadata] (Skip Connection)
        fusion_vec = torch.cat([gated_S, metadata], dim=1)

        # Classifier
        logits = self.classifier(fusion_vec)
        return logits


def train_mlp(load_cached_data=True):
    """
    Trains the PizzaNet MLP model.
    """
    seed_everything()
    device = get_device()

    # 1. Load Data
    print_log("Initializing FeatureManager and loading MLP dataset...")
    fm = FeatureManager()
    train_data, val_data, test_data = fm.get_mlp_dataset(
        load_cached_data=load_cached_data
    )

    # Create Datasets and DataLoaders
    train_dataset = PizzaDataset(train_data, mode="train")
    val_dataset = PizzaDataset(val_data, mode="val")
    # Test dataset not needed for training loop, but useful to return for consistency
    test_dataset = PizzaDataset(test_data, mode="test")

    train_loader = DataLoader(
        train_dataset,
        batch_size=Config.MLP_BATCH_SIZE,
        shuffle=True,
        num_workers=0,
        drop_last=True,
    )
    val_loader = DataLoader(
        val_dataset, batch_size=Config.MLP_BATCH_SIZE, shuffle=False, num_workers=0
    )

    # 2. Initialize Model
    metadata_dim = train_data["metadata"].shape[1]
    embed_dim = train_data["title_emb"].shape[1]

    print_log(
        f"Initializing PizzaNet (Meta Dim: {metadata_dim}, Embed Dim: {embed_dim})..."
    )
    model = PizzaNet(metadata_dim, embed_dim=embed_dim).to(device)

    # 3. Setup Training
    optimizer = optim.AdamW(
        model.parameters(),
        lr=Config.MLP_LEARNING_RATE,
        weight_decay=Config.MLP_WEIGHT_DECAY,
    )
    criterion = nn.BCEWithLogitsLoss()

    best_val_auc = 0.0
    patience_counter = 0
    best_model_state = None

    print_log(f"Starting training for {Config.MLP_EPOCHS} epochs...")

    for epoch in range(Config.MLP_EPOCHS):
        model.train()
        train_loss = 0.0

        for batch in train_loader:
            # Move to device
            title = batch["title_emb"].to(device)
            body = batch["body_emb"].to(device)
            hist = batch["history_seq"].to(device)
            cent = batch["centroid_emb"].to(device)
            meta = batch["metadata"].to(device)
            y = batch["y"].to(device).unsqueeze(1)

            optimizer.zero_grad()
            logits = model(title, body, hist, cent, meta)
            loss = criterion(logits, y)
            loss.backward()
            optimizer.step()

            train_loss += loss.item()

        avg_train_loss = train_loss / len(train_loader)

        # Validation
        model.eval()
        val_preds = []
        val_targets = []

        with torch.no_grad():
            for batch in val_loader:
                title = batch["title_emb"].to(device)
                body = batch["body_emb"].to(device)
                hist = batch["history_seq"].to(device)
                cent = batch["centroid_emb"].to(device)
                meta = batch["metadata"].to(device)
                y = batch["y"].to(device)

                logits = model(title, body, hist, cent, meta)
                probs = torch.sigmoid(logits).cpu().numpy()

                val_preds.extend(probs)
                val_targets.extend(y.cpu().numpy())

        val_auc = roc_auc_score(val_targets, val_preds)

        print_log(
            f"Epoch {epoch+1}/{Config.MLP_EPOCHS} | Train Loss: {avg_train_loss:.4f} | Val AUC: {val_auc}"
        )

        # Early Stopping
        if val_auc > best_val_auc:
            best_val_auc = val_auc
            best_model_state = model.state_dict()
            patience_counter = 0
        else:
            patience_counter += 1

        if patience_counter >= Config.MLP_PATIENCE:
            print_log(f"Early stopping triggered at epoch {epoch+1}")
            break

    # Load best model
    if best_model_state is not None:
        model.load_state_dict(best_model_state)
        print_log(f"Loaded best model with Val AUC: {best_val_auc}")

    return model, val_data, test_data


def predict_mlp(model, data_dict):
    """
    Generates predictions using the trained MLP model.
    """
    device = get_device()
    model.eval()

    dataset = PizzaDataset(data_dict, mode="test")
    loader = DataLoader(
        dataset, batch_size=Config.MLP_BATCH_SIZE, shuffle=False, num_workers=0
    )

    all_probs = []

    with torch.no_grad():
        for batch in loader:
            title = batch["title_emb"].to(device)
            body = batch["body_emb"].to(device)
            hist = batch["history_seq"].to(device)
            cent = batch["centroid_emb"].to(device)
            meta = batch["metadata"].to(device)

            logits = model(title, body, hist, cent, meta)
            probs = torch.sigmoid(logits).cpu().numpy()
            all_probs.extend(probs.flatten())

    return np.array(all_probs)
