import os
import pandas as pd
import numpy as np
import ast
from library import config


def _parse_list_column(df, col_name):
    """
    Parses a column containing stringified lists (e.g. "['a', 'b']") into actual Python lists.
    Handles NaNs by converting them to empty lists.
    """
    if col_name in df.columns:
        # Fill NaNs with empty list string representation before parsing
        df[col_name] = (
            df[col_name]
            .fillna("[]")
            .apply(lambda x: ast.literal_eval(x) if isinstance(x, str) else x)
        )
    return df


def load_tabular_data(load_cached_data=True):
    """
    Loads the Train, Validation, and Test tabular datasets.
    Implements caching using Parquet files to preserve data types (lists).

    Args:
        load_cached_data (bool): If True, attempts to load from processed Parquet files.

    Returns:
        tuple: (df_train, df_val, df_test)
    """
    # Ensure working directory exists
    os.makedirs(config.WORKING_DIR, exist_ok=True)

    # Define cache paths
    cache_paths = {
        "train": config.CACHE_TRAIN_PROCESSED,
        "val": config.CACHE_VAL_PROCESSED,
        "test": config.CACHE_TEST_PROCESSED,
    }

    # 1. Try Loading from Cache
    if load_cached_data:
        if all(os.path.exists(path) for path in cache_paths.values()):
            print("Loading tabular data from cache...")
            try:
                df_train = pd.read_parquet(cache_paths["train"])
                df_val = pd.read_parquet(cache_paths["val"])
                df_test = pd.read_parquet(cache_paths["test"])
                return df_train, df_val, df_test
            except Exception as e:
                print(f"Failed to load cache: {e}. Reloading from source.")
        else:
            print("Cache not found. Loading from source metadata CSVs...")
    else:
        print("Forcing reload from source metadata CSVs...")

    # 2. Load from Source CSVs
    if not os.path.exists(config.TRAIN_CSV):
        raise FileNotFoundError(f"Metadata file not found: {config.TRAIN_CSV}")

    df_train = pd.read_csv(config.TRAIN_CSV)
    df_val = pd.read_csv(config.VAL_CSV)
    df_test = pd.read_csv(config.TEST_CSV)

    # 3. Process Columns
    # Parse the history column from string to list
    print(f"Parsing list column: {config.HISTORY_COL}")
    df_train = _parse_list_column(df_train, config.HISTORY_COL)
    df_val = _parse_list_column(df_val, config.HISTORY_COL)
    df_test = _parse_list_column(df_test, config.HISTORY_COL)

    # Ensure target is integer (0/1) for Train/Val
    if config.TARGET_COL in df_train.columns:
        df_train[config.TARGET_COL] = df_train[config.TARGET_COL].astype(int)
    if config.TARGET_COL in df_val.columns:
        df_val[config.TARGET_COL] = df_val[config.TARGET_COL].astype(int)

    # 4. Save to Cache
    print("Saving processed data to cache...")
    try:
        df_train.to_parquet(cache_paths["train"])
        df_val.to_parquet(cache_paths["val"])
        df_test.to_parquet(cache_paths["test"])
    except Exception as e:
        print(f"Warning: Could not save to cache: {e}")

    return df_train, df_val, df_test


def load_sbert_embeddings(kind="request"):
    """
    Loads pre-computed SBERT embeddings from .npz files.

    Args:
        kind (str): 'request' or 'history'.

    Returns:
        dict: Dictionary containing 'train', 'val', 'test' arrays.
    """
    if kind == "request":
        path = config.CACHE_SBERT_REQUEST
    elif kind == "history":
        path = config.CACHE_SBERT_HISTORY
    else:
        raise ValueError("kind must be 'request' or 'history'")

    if not os.path.exists(path):
        # This function assumes embeddings are generated by a separate feature engineering step.
        # If missing, return None to indicate they need to be generated.
        print(f"Embedding file not found at {path}. Returning None.")
        return None

    print(f"Loading {kind} embeddings from {path}...")
    data = np.load(path)
    return {"train": data["train"], "val": data["val"], "test": data["test"]}


def get_common_features(df_train, df_test):
    """
    Identifies the intersection of numeric features available in both train and test sets
    to prevent leakage and runtime errors.

    Args:
        df_train (pd.DataFrame): Training data.
        df_test (pd.DataFrame): Test data.

    Returns:
        list: List of valid column names.
    """
    # Start with the candidate list from config
    candidates = config.NUMERIC_COLS

    # Check existence in both dataframes
    train_cols = set(df_train.columns)
    test_cols = set(df_test.columns)

    valid_features = []
    for col in candidates:
        if col in train_cols and col in test_cols:
            valid_features.append(col)
        else:
            # Silent drop or log if needed
            pass

    print(
        f"Selected {len(valid_features)} common numeric features out of {len(candidates)} candidates."
    )
    return valid_features
