import os


class Config:
    # --------------------------------------------------------------------------
    # General Setup
    # --------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 8  # Adjust based on available vCPUs (12 available)

    # Debugging flags
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 200  # Number of samples to use when DEBUG is True

    # --------------------------------------------------------------------------
    # Directory Paths
    # --------------------------------------------------------------------------
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the previous step
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Working directory for Idea 5 (Temporal Ash-Net)
    WORKING_DIR = "./working/idea_5"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    PREDICTION_DIR = os.path.join(WORKING_DIR, "predictions")

    # Final submission path
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Data Parameters
    # --------------------------------------------------------------------------
    IMG_SIZE = 256

    # Temporal sequence details
    # Labeled frame is at index 4 (n_times_before=4)
    # Reverting to Static Frame (t=4) to accelerate convergence (Cite solution_lesson_node_00022)
    TEMPORAL_INDICES = [4]

    # Bands required for Ash Composite
    # Band 11 (8.4um), Band 14 (11.2um), Band 15 (12.3um)
    REQUIRED_BANDS = [11, 14, 15]

    # Ash Composite Normalization Bounds (Wide)
    # Preserving tails as per strategy
    # Red: Band 15 - Band 14
    ASH_RED_MIN = -6.7
    ASH_RED_MAX = 2.6

    # Green: Band 14 - Band 11
    # Using standard wide bounds for split window difference
    ASH_GREEN_MIN = -6.0
    ASH_GREEN_MAX = 6.0

    # Blue: Band 14 (Brightness Temperature)
    # Kelvin range
    ASH_BLUE_MIN = 200.0
    ASH_BLUE_MAX = 300.0

    # --------------------------------------------------------------------------
    # Model Architecture
    # --------------------------------------------------------------------------
    # 1 timestep * 3 color channels (Ash) = 3 input channels
    IN_CHANNELS = 3
    NUM_CLASSES = 1

    # Encoder configuration (Custom Wide)
    # Increasing capacity to 1024 at bottleneck (Cite solution_lesson_node_00016)
    ENCODER_DEPTH = 4
    ENCODER_CHANNELS = [64, 128, 256, 512]

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    # Increased batch size for stability (Cite solution_lesson_node_00006)
    BATCH_SIZE = 48
    EPOCHS = 25
    LEARNING_RATE = 2e-4

    # Loss Function Weights
    # Prioritizing stability (Focal) over overlap (Dice) initially
    WEIGHT_FOCAL = 0.75
    WEIGHT_DICE = 0.25

    # Focal Loss Parameters
    FOCAL_ALPHA = 0.5  # Balanced alpha
    FOCAL_GAMMA = 2.0

    # Scheduler Parameters
    LR_PATIENCE = 3
    LR_FACTOR = 0.5
    LR_MIN = 1e-6

    # Inference Threshold
    THRESHOLD = 0.5

    @classmethod
    def setup(cls):
        """
        Ensures all necessary working directories exist.
        """
        dirs = [
            cls.WORKING_DIR,
            cls.CACHE_DIR,
            cls.CHECKPOINT_DIR,
            cls.PREDICTION_DIR,
            cls.SUBMISSION_DIR,
        ]
        for d in dirs:
            os.makedirs(d, exist_ok=True)
