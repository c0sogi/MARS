import os
import numpy as np
import pandas as pd
import torch
from torch.utils.data import Dataset
from library.config import Config


class VolcanoDataset(Dataset):
    """
    PyTorch Dataset for the Magnitude-Modulated Hybrid Ensemble.
    Loads cached spectrograms and scalar features from disk.
    Handles target transformation (log1p) and scalar normalization.
    """

    def __init__(
        self,
        df: pd.DataFrame,
        spectrogram_dir: str,
        mode: str = "train",
        scalar_stats: dict = None,
    ):
        """
        Args:
            df (pd.DataFrame): Dataframe containing metadata, tabular features, and scalars.
            spectrogram_dir (str): Path to the directory containing .npy spectrogram files.
            mode (str): Mode of operation ('train', 'val', or 'test').
            scalar_stats (dict, optional): Dictionary containing 'mean' and 'std' numpy arrays
                                           for scalar normalization. If None and mode='train',
                                           stats are computed from the provided dataframe.
        """
        self.df = df.reset_index(drop=True)
        self.spectrogram_dir = spectrogram_dir
        self.mode = mode

        # 1. Identify Scalar Columns (for FiLM modulation)
        # These columns are generated by FeatureEngineer.extract_scalars
        self.scalar_cols = [c for c in self.df.columns if c.startswith("scalar_")]

        if not self.scalar_cols:
            print(
                "Warning: No scalar columns found in dataframe starting with 'scalar_'."
            )

        # 2. Prepare and Normalize Scalars
        # Convert to float32 for PyTorch compatibility
        scalars_raw = self.df[self.scalar_cols].values.astype(np.float32)

        if scalar_stats is not None:
            # Use provided statistics (e.g., from training set applied to val/test)
            self.scalar_mean = scalar_stats["mean"]
            self.scalar_std = scalar_stats["std"]
        elif mode == "train":
            # Compute statistics from current data
            self.scalar_mean = np.mean(scalars_raw, axis=0)
            self.scalar_std = np.std(scalars_raw, axis=0)
            # Prevent division by zero
            self.scalar_std[self.scalar_std == 0] = 1.0
        else:
            # Fallback: No stats provided and not training (should be avoided in pipeline)
            # Default to identity scaling
            self.scalar_mean = np.zeros(scalars_raw.shape[1], dtype=np.float32)
            self.scalar_std = np.ones(scalars_raw.shape[1], dtype=np.float32)

        # Apply Standard Scaling: (X - mean) / std
        self.scalars = (scalars_raw - self.scalar_mean) / (self.scalar_std + 1e-8)

        # 3. Prepare Targets
        if self.mode != "test":
            if "time_to_eruption" not in self.df.columns:
                raise ValueError("Column 'time_to_eruption' missing in dataframe.")

            # Apply Log-Scaling to Target: log(y + 1)
            targets_raw = self.df["time_to_eruption"].values.astype(np.float32)
            self.targets = np.log1p(targets_raw)
        else:
            self.targets = None

        self.segment_ids = self.df["segment_id"].values

    def __len__(self):
        """Returns the total number of samples in the dataset."""
        return len(self.df)

    def __getitem__(self, idx):
        """
        Retrieves a single sample from the dataset.

        Returns:
            tuple: (spectrogram_tensor, scalar_tensor, target_tensor)
        """
        segment_id = self.segment_ids[idx]

        # 1. Load Spectrogram
        # Expected shape: (10, 256, 256)
        spec_path = os.path.join(self.spectrogram_dir, f"{segment_id}.npy")
        try:
            spectrogram = np.load(spec_path).astype(np.float32)
        except FileNotFoundError:
            # Fallback: Return zero tensor if file is missing (should be handled by pipeline)
            spectrogram = np.zeros(
                (Config.NUM_SENSORS, Config.IMG_SIZE[0], Config.IMG_SIZE[1]),
                dtype=np.float32,
            )

        # 2. Get Scalars
        scalar_vec = self.scalars[idx]

        # 3. Convert to Tensors
        spec_tensor = torch.from_numpy(spectrogram)
        scalar_tensor = torch.from_numpy(scalar_vec)

        # 4. Return Tuple
        if self.mode != "test":
            target_val = self.targets[idx]
            target_tensor = torch.tensor(target_val, dtype=torch.float32)
            return spec_tensor, scalar_tensor, target_tensor
        else:
            # For test, return dummy target to maintain signature consistency
            dummy_target = torch.tensor(0.0, dtype=torch.float32)
            return spec_tensor, scalar_tensor, dummy_target

    def get_scalar_stats(self):
        """
        Returns the mean and std used for scalar normalization.
        These should be passed to the validation and test datasets to ensure consistent scaling.

        Returns:
            dict: {'mean': np.array, 'std': np.array}
        """
        return {"mean": self.scalar_mean, "std": self.scalar_std}
