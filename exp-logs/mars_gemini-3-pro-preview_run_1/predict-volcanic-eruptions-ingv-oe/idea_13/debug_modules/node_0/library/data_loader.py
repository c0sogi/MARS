import os
import torch
import numpy as np
import pandas as pd
from torch.utils.data import Dataset, DataLoader
from library.config import Config
from library.utils import load_npy, transform_target
from library.feature_engineering import generate_features


class VolcanoDataset(Dataset):
    """
    PyTorch Dataset for the Volcano Eruption Prediction Task.
    Serves the Vision Branch (EfficientNet) by providing:
    1. Log-Mel Spectrograms (loaded from .npy cache)
    2. Global Energy Scalars (extracted from DataFrame)
    3. Log-Transformed Targets (for train/val)
    """

    def __init__(self, df, spectrogram_dir, mode="train"):
        """
        Args:
            df (pd.DataFrame): DataFrame containing metadata, scalar features, and targets.
            spectrogram_dir (str): Path to the directory containing cached .npy spectrograms.
            mode (str): 'train', 'val', or 'test'.
        """
        self.df = df.reset_index(drop=True)
        self.spectrogram_dir = spectrogram_dir
        self.mode = mode

        # Identify scalar injection columns (prefixed with 'scalar_')
        # These are generated by library.feature_engineering.extract_injection_scalars
        self.scalar_cols = [c for c in self.df.columns if c.startswith("scalar_")]

        # Validation of scalar dimensions
        if len(self.scalar_cols) != Config.SCALAR_INPUT_DIM:
            # In a production environment we might raise an error, but here we proceed
            # assuming the pipeline generated the correct features.
            pass

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        segment_id = int(row["segment_id"])

        # ---------------------------------------------------------
        # 1. Load Spectrogram (Vision Input)
        # ---------------------------------------------------------
        # Path format: {cache_dir}/{segment_id}.npy
        spec_path = os.path.join(self.spectrogram_dir, f"{segment_id}.npy")

        try:
            # Load cached numpy array
            spectrogram = load_npy(spec_path)
        except FileNotFoundError:
            # Fallback: return zero tensor if file is missing (should not happen in correct pipeline)
            spectrogram = np.zeros(
                (Config.IN_CHANNELS, Config.IMG_SIZE[0], Config.IMG_SIZE[1]),
                dtype=np.float32,
            )

        # Convert to Tensor (C, H, W)
        spectrogram = torch.from_numpy(spectrogram)

        # ---------------------------------------------------------
        # 2. Load Scalars (Injection Input)
        # ---------------------------------------------------------
        # Extract the pre-computed global energy statistics
        scalars = row[self.scalar_cols].values.astype(np.float32)
        scalars = torch.from_numpy(scalars)

        # ---------------------------------------------------------
        # 3. Load Target (Regression Label)
        # ---------------------------------------------------------
        if self.mode in ["train", "val"]:
            target_val = row["time_to_eruption"]

            # Apply Log1p Transformation to normalize target distribution
            target_val = transform_target(target_val)

            # Return as float32 tensor of shape (1,)
            target = torch.tensor([target_val], dtype=torch.float32)

            return spectrogram, scalars, target
        else:
            # Test mode: Return inputs only
            return spectrogram, scalars


def load_tabular_dataset(load_cached=True):
    """
    Loads the processed DataFrames for the Tabular Branch (LightGBM).
    Triggers the feature engineering pipeline to generate or load features.

    Args:
        load_cached (bool): If True, attempts to load features from parquet cache.

    Returns:
        tuple: (df_train, df_val, df_test) containing engineered features.
    """
    # Delegate to the feature engineering module
    return generate_features(load_cached=load_cached)


def get_data_loaders(
    df_train,
    df_val,
    df_test,
    batch_size=Config.BATCH_SIZE,
    num_workers=Config.NUM_WORKERS,
):
    """
    Constructs PyTorch DataLoaders for the Vision Branch.

    Args:
        df_train (pd.DataFrame): Training data with scalar features.
        df_val (pd.DataFrame): Validation data with scalar features.
        df_test (pd.DataFrame): Test data with scalar features.
        batch_size (int): Batch size for training/inference.
        num_workers (int): Number of subprocesses for data loading.

    Returns:
        tuple: (train_loader, val_loader, test_loader)
    """
    # 1. Instantiate Datasets
    # Each dataset points to its specific spectrogram cache directory
    train_dataset = VolcanoDataset(
        df_train, Config.CACHE_SPECTROGRAMS_TRAIN, mode="train"
    )
    val_dataset = VolcanoDataset(df_val, Config.CACHE_SPECTROGRAMS_VAL, mode="val")
    test_dataset = VolcanoDataset(df_test, Config.CACHE_SPECTROGRAMS_TEST, mode="test")

    # 2. Create DataLoaders
    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=True,
        drop_last=True,  # Drop last incomplete batch for stability
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
        drop_last=False,
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
        drop_last=False,
    )

    return train_loader, val_loader, test_loader
