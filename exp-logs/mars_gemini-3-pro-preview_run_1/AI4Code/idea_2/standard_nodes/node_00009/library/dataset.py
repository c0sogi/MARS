import torch
import numpy as np
import pandas as pd
from torch.utils.data import Dataset
from collections import defaultdict
from library.config import Config


class HAPSDataset(Dataset):
    """
    Dataset class for the Hybrid Anchor-Pairwise Sorting Network.
    Loads pre-computed embeddings and generates labels for:
    1. Anchor Head: Which code cell follows the markdown cell?
    2. Pairwise Head: Relative ordering of markdown cells within the same anchor bin.
    """

    def __init__(self, features_path, mode="train", max_pairs_per_nb=1000):
        """
        Args:
            features_path (str): Path to the parquet file containing features.
            mode (str): 'train', 'val', or 'test'.
            max_pairs_per_nb (int): Maximum number of pairwise constraints to sample per notebook.
        """
        self.mode = mode
        self.max_pairs_per_nb = max_pairs_per_nb

        # Load cached features
        # The features are expected to be in the format generated by feature_extraction.py
        if not pd.io.common.file_exists(features_path):
            raise FileNotFoundError(f"Features file not found at {features_path}")

        # Load dataframe
        # Columns: notebook_id, cell_id, cell_type, rank, rel_rank, embedding
        self.df = pd.read_parquet(features_path)

        # Get unique notebooks
        self.notebooks = self.df["notebook_id"].unique()

        # Group by notebook_id for fast retrieval
        # Note: groupby() is efficient, but get_group() can be slightly slow.
        # For 140k notebooks, this is acceptable given the compute resources.
        self.grouped = self.df.groupby("notebook_id")

    def __len__(self):
        return len(self.notebooks)

    def __getitem__(self, idx):
        nb_id = self.notebooks[idx]
        nb_df = self.grouped.get_group(nb_id)

        # Separate Code and Markdown
        # We assume the dataframe contains the necessary columns
        code_df = nb_df[nb_df["cell_type"] == "code"].copy()
        md_df = nb_df[nb_df["cell_type"] == "markdown"].copy()

        # Sort by rank if available (Train/Val) to ensure correct ground truth processing
        # In Test, ranks are not available (or meaningless), so we rely on input order or just don't sort.
        if self.mode != "test":
            code_df = code_df.sort_values("rank")
            md_df = md_df.sort_values("rank")

        # Extract Embeddings
        # Embeddings are stored as lists/arrays in the parquet column.
        # We stack them into a numpy array (N, 384).
        if len(code_df) > 0:
            code_embeddings = np.stack(code_df["embedding"].values)
        else:
            code_embeddings = np.zeros((0, Config.input_dim), dtype=np.float32)

        if len(md_df) > 0:
            md_embeddings = np.stack(md_df["embedding"].values)
        else:
            md_embeddings = np.zeros((0, Config.input_dim), dtype=np.float32)

        # Convert to Tensors
        code_tensor = torch.tensor(code_embeddings, dtype=torch.float32)
        md_tensor = torch.tensor(md_embeddings, dtype=torch.float32)

        sample = {
            "notebook_id": nb_id,
            "code_embeddings": code_tensor,
            "md_embeddings": md_tensor,
        }

        # Generate Labels for Train/Val
        if self.mode != "test":
            # --- 1. Anchor Labels ---
            # Label = Index of the code cell that immediately follows the markdown cell.
            # Bins: [Before C0, Between C0-C1, ..., After Cn]
            # Since code_df is sorted by rank, we can use searchsorted.

            if len(code_df) > 0:
                code_ranks = code_df["rank"].values
                md_ranks = md_df["rank"].values
                # side='left': indices i such that code_ranks[i-1] < v <= code_ranks[i]
                # Effectively: index i such that code_ranks[i] > md_rank.
                anchor_labels = np.searchsorted(code_ranks, md_ranks, side="left")
            else:
                # If no code cells, all MD cells fall into bin 0 (which is the only bin)
                anchor_labels = np.zeros(len(md_df), dtype=np.int64)

            sample["anchor_labels"] = torch.tensor(anchor_labels, dtype=torch.long)

            # --- 2. Pairwise Labels (Hard Negatives) ---
            # We identify MD cells that fall into the SAME bin (same anchor label).
            # These are the ones the Anchor head cannot distinguish.

            pairs = []
            pair_labels = []

            if len(md_df) > 1:
                # Group indices by anchor label
                bin_to_indices = defaultdict(list)
                for idx, label in enumerate(anchor_labels):
                    bin_to_indices[label].append(idx)

                for label, indices in bin_to_indices.items():
                    if len(indices) < 2:
                        continue

                    # Generate pairs within this bin
                    # Since md_df is sorted by rank, indices[i] < indices[j] implies rank[i] < rank[j]
                    # We generate both (i, j) -> 1 and (j, i) -> 0 for balance

                    local_pairs = []
                    n_indices = len(indices)

                    # Optimization: If n_indices is huge, just sample random pairs directly
                    if n_indices > 20:
                        # Random sampling strategy for dense bins
                        for _ in range(
                            min(n_indices * 5, 100)
                        ):  # heuristic cap per bin
                            i, j = np.random.choice(n_indices, 2, replace=False)
                            # indices are sorted by rank, so min index is earlier
                            idx_a = indices[min(i, j)]
                            idx_b = indices[max(i, j)]

                            local_pairs.append([idx_a, idx_b, 1.0])
                            local_pairs.append([idx_b, idx_a, 0.0])
                    else:
                        # Full pairwise for small bins
                        for i in range(n_indices):
                            for j in range(i + 1, n_indices):
                                idx_a = indices[i]
                                idx_b = indices[j]
                                local_pairs.append([idx_a, idx_b, 1.0])
                                local_pairs.append([idx_b, idx_a, 0.0])

                    for p in local_pairs:
                        pairs.append(p[:2])
                        pair_labels.append(p[2])

            # Global Cap per notebook to prevent memory spikes
            if len(pairs) > self.max_pairs_per_nb:
                # Randomly subsample
                select_indices = np.random.choice(
                    len(pairs), self.max_pairs_per_nb, replace=False
                )
                pairs = [pairs[i] for i in select_indices]
                pair_labels = [pair_labels[i] for i in select_indices]

            if len(pairs) > 0:
                sample["pairwise_indices"] = torch.tensor(pairs, dtype=torch.long)
                sample["pairwise_labels"] = torch.tensor(
                    pair_labels, dtype=torch.float32
                )
            else:
                sample["pairwise_indices"] = torch.empty((0, 2), dtype=torch.long)
                sample["pairwise_labels"] = torch.empty((0,), dtype=torch.float32)

        return sample


def haps_collate_fn(batch):
    """
    Custom collate function to handle variable numbers of code/md cells and pairwise constraints.
    Pads sequences to the maximum length in the batch.
    """
    batch_size = len(batch)

    # Determine max lengths
    max_code = max(b["code_embeddings"].shape[0] for b in batch)
    max_md = max(b["md_embeddings"].shape[0] for b in batch)
    feat_dim = batch[0]["code_embeddings"].shape[1]

    # Initialize tensors
    padded_code = torch.zeros(batch_size, max_code, feat_dim)
    padded_md = torch.zeros(batch_size, max_md, feat_dim)
    code_mask = torch.zeros(batch_size, max_code, dtype=torch.bool)
    md_mask = torch.zeros(batch_size, max_md, dtype=torch.bool)

    padded_anchor_labels = None
    has_labels = "anchor_labels" in batch[0]

    if has_labels:
        # Fill with -100 (standard ignore_index for CrossEntropy)
        padded_anchor_labels = torch.full((batch_size, max_md), -100, dtype=torch.long)

    all_pairwise_indices = []
    all_pairwise_labels = []
    notebook_ids = []

    for i, item in enumerate(batch):
        notebook_ids.append(item["notebook_id"])

        # Code
        n_code = item["code_embeddings"].shape[0]
        if n_code > 0:
            padded_code[i, :n_code] = item["code_embeddings"]
            code_mask[i, :n_code] = True

        # MD
        n_md = item["md_embeddings"].shape[0]
        if n_md > 0:
            padded_md[i, :n_md] = item["md_embeddings"]
            md_mask[i, :n_md] = True

        # Labels
        if has_labels:
            if n_md > 0:
                padded_anchor_labels[i, :n_md] = item["anchor_labels"]

            # Pairwise
            # item['pairwise_indices'] is (K, 2)
            # We need to construct (Total_K, 3) -> [batch_idx, md_idx_1, md_idx_2]
            if "pairwise_indices" in item and item["pairwise_indices"].shape[0] > 0:
                indices = item["pairwise_indices"]
                batch_idx_col = torch.full((indices.shape[0], 1), i, dtype=torch.long)
                triplets = torch.cat([batch_idx_col, indices], dim=1)

                all_pairwise_indices.append(triplets)
                all_pairwise_labels.append(item["pairwise_labels"])

    batch_out = {
        "notebook_ids": notebook_ids,
        "code_embeddings": padded_code,
        "code_mask": code_mask,
        "md_embeddings": padded_md,
        "md_mask": md_mask,
    }

    if has_labels:
        batch_out["anchor_labels"] = padded_anchor_labels

        if all_pairwise_indices:
            batch_out["pairwise_indices"] = torch.cat(all_pairwise_indices, dim=0)
            batch_out["pairwise_labels"] = torch.cat(all_pairwise_labels, dim=0)
        else:
            batch_out["pairwise_indices"] = torch.empty((0, 3), dtype=torch.long)
            batch_out["pairwise_labels"] = torch.empty((0,), dtype=torch.float32)

    return batch_out
