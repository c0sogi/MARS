import os
import torch


class Config:
    """
    Central configuration for the Weighted Layer-Pooling Stacking experiment.
    Defines hyperparameters, file paths, and model settings.
    """

    # -------------------------------------------------------------------------
    # General Configuration
    # -------------------------------------------------------------------------
    SEED = 42
    N_FOLDS = 5
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Debugging / Development
    # Set DEBUG to True to run on a small subset of data for pipeline verification
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 100

    # -------------------------------------------------------------------------
    # Paths & Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (Generated by the provided metadata script)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Working Directories for artifacts
    WORKING_DIR = "./working/idea_8"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")

    # Output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Expert A: Deep Syntactic-Semantic (DeBERTa-v3-Large)
    # -------------------------------------------------------------------------
    MODEL_NAME = "microsoft/deberta-v3-large"

    # Sequence Length: 99th percentile of training data is ~256 tokens.
    # Limiting to 256 avoids context bloat and improves efficiency.
    MAX_LEN = 256

    # Training Hyperparameters
    # A100 40GB allows for moderate batch sizes with large models.
    # Effective Batch Size = TRAIN_BATCH_SIZE * GRAD_ACCUM_STEPS = 4 * 8 = 32
    TRAIN_BATCH_SIZE = 4
    VALID_BATCH_SIZE = 16
    GRAD_ACCUM_STEPS = 8
    EPOCHS = 10
    PATIENCE = 3  # Early stopping patience

    # Optimization
    LEARNING_RATE = 1e-5
    WEIGHT_DECAY = 0.01
    EPS = 1e-6
    BETAS = (0.9, 0.999)
    SCHEDULER_TYPE = "cosine"
    NUM_WARMUP_STEPS_RATIO = 0.1
    MAX_GRAD_NORM = 1.0

    # Advanced Architecture: Weighted Layer Pooling
    # Uses a learnable weighted average of the last N hidden layers
    USE_WEIGHTED_LAYER_POOLING = True
    NUM_POOLING_LAYERS = 4

    # Layer-Wise Learning Rate Decay (LLRD)
    # Stabilizes training of large models by decaying LR for lower layers
    USE_LLRD = True
    LLRD_DECAY = 0.9

    # -------------------------------------------------------------------------
    # Expert B: Surface Stylometric (TF-IDF + Logistic Regression)
    # -------------------------------------------------------------------------
    # TF-IDF Features
    TFIDF_WORD_NGRAM_RANGE = (1, 3)
    TFIDF_CHAR_NGRAM_RANGE = (3, 5)
    # Use sparse matrices to save memory
    TFIDF_USE_SPARSE = True

    # Logistic Regression
    LOGREG_C = 1.0
    LOGREG_MAX_ITER = 1000
    LOGREG_SOLVER = "saga"  # Optimized for large sparse datasets

    # -------------------------------------------------------------------------
    # Meta-Learner (XGBoost)
    # -------------------------------------------------------------------------
    # Features: Probabilities from Expert A & B + Meta-features (len, punct, etc.)
    USE_META_FEATURES = True

    XGB_PARAMS = {
        "n_estimators": 2000,
        "learning_rate": 0.01,
        "max_depth": 4,
        "subsample": 0.7,
        "colsample_bytree": 0.7,
        "objective": "multi:softprob",
        "num_class": 3,
        "n_jobs": -1,
        "random_state": SEED,
        "tree_method": "hist",  # Efficient histogram-based algorithm
        "early_stopping_rounds": 50,
        "verbosity": 0,
    }

    @classmethod
    def create_directories(cls):
        """
        Ensures all necessary working directories exist.
        Should be called at the start of the pipeline.
        """
        dirs = [cls.WORKING_DIR, cls.CACHE_DIR, cls.CHECKPOINT_DIR, cls.SUBMISSION_DIR]
        for path in dirs:
            os.makedirs(path, exist_ok=True)
