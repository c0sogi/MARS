import os
import torch


class Config:
    """
    Configuration class for the artwork attribute labeling task.
    Centralizes all hyperparameters, file paths, and system settings.
    """

    # ==========================================
    # General Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 1000  # Number of samples to use in debug mode

    # ==========================================
    # Compute
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Number of subprocesses for data loading

    # ==========================================
    # Directories
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"
    SUBMISSION_DIR = "./submission"

    # Specific directory for this idea/experiment
    IDEA_DIR = os.path.join(WORKING_DIR, "idea_1")

    # Create necessary directories
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    os.makedirs(IDEA_DIR, exist_ok=True)

    # ==========================================
    # File Paths
    # ==========================================
    # Metadata CSVs generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Label descriptions
    LABELS_PATH = os.path.join(INPUT_DIR, "labels.csv")

    # Output paths
    MODEL_SAVE_PATH = os.path.join(IDEA_DIR, "resnet34_best.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Data Hyperparameters
    # ==========================================
    IMG_SIZE = 224  # Input resolution for ResNet
    NUM_CLASSES = 3474  # Total number of attributes

    # ==========================================
    # Model Hyperparameters
    # ==========================================
    MODEL_NAME = "resnet34"
    PRETRAINED = True
    FREEZE_BACKBONE = False  # Fine-tune end-to-end

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 128  # A100 40GB can handle large batches
    EPOCHS = 10
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-5

    # Loss configuration
    # Positive weight for BCEWithLogitsLoss to handle class imbalance/sparsity
    POS_WEIGHT = 10.0

    # ==========================================
    # Inference / Evaluation
    # ==========================================
    THRESHOLD = 0.4  # Probability threshold for multi-label prediction
    EARLY_STOPPING_PATIENCE = 3  # Stop if validation metric doesn't improve
