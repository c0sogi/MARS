import os
import torch


class Config:
    # ---------------------------------------------------------
    # 1. Global & System
    # ---------------------------------------------------------
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 8  # Optimized for 12 vCPUs
    PIN_MEMORY = True  # Faster data transfer to GPU

    # ---------------------------------------------------------
    # 2. File Paths
    # ---------------------------------------------------------
    # Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_3"
    SUBMISSION_DIR = "./submission"

    # Raw Data
    TRAIN_CSV = os.path.join(INPUT_DIR, "train.csv")
    TEST_CSV = os.path.join(INPUT_DIR, "test.csv")

    # Metadata (Generated by previous steps)
    TRAIN_META = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Artifacts (Saved/Loaded by this pipeline)
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    TOKENIZER_PATH = os.path.join(WORKING_DIR, "tokenizer.json")
    TAG_MAP_PATH = os.path.join(WORKING_DIR, "tag_map.json")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache Files (Parquet for dataframes)
    CACHED_TRAIN = os.path.join(WORKING_DIR, "cached_train.parquet")
    CACHED_VAL = os.path.join(WORKING_DIR, "cached_val.parquet")
    CACHED_TEST = os.path.join(WORKING_DIR, "cached_test.parquet")

    # ---------------------------------------------------------
    # 3. Data Processing Hyperparameters
    # ---------------------------------------------------------
    VOCAB_SIZE = 200000  # Cap vocabulary to top 200k words
    MIN_FREQ = 2  # Minimum word frequency
    MAX_LEN_TITLE = 50  # Max sequence length for Title
    MAX_LEN_BODY = 300  # Max sequence length for Body (truncated)

    # ---------------------------------------------------------
    # 4. Model Architecture (Attention-DAN)
    # ---------------------------------------------------------
