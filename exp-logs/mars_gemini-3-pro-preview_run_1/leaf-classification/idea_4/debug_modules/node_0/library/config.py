import os
import random
import numpy as np
import torch


class Config:
    """
    Central configuration for the Taxonomy-Regularized Hierarchical LDA Ensemble.
    """

    # ==========================================
    # Directories
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Specific working directory for this idea (Idea 4)
    WORKING_DIR = "./working/idea_4"
    SUBMISSION_DIR = "./submission"

    # ==========================================
    # File Paths
    # ==========================================
    # Metadata files generated by the metadata script
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Sample submission for format reference
    SAMPLE_SUBMISSION_CSV = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Final output path
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Data Configuration
    # ==========================================
    ID_COL = "id"
    TARGET_COL = "species"
    GENUS_COL = "genus"  # Name for the derived genus column

    # Image folder (if needed for raw loading, though we use features mostly)
    IMAGES_DIR = os.path.join(INPUT_DIR, "images")

    # ==========================================
    # Reproducibility
    # ==========================================
    SEED = 42

    # ==========================================
    # Model Hyperparameters
    # ==========================================
    # Global LDA Settings
    # 'lsqr' is a solver that supports shrinkage
    GLOBAL_LDA_SOLVER = "lsqr"
    # 'auto' uses the Ledoit-Wolf lemma for shrinkage
    GLOBAL_LDA_SHRINKAGE = "auto"

    # Hierarchical LDA Settings
    # Minimum samples required to train a specific species discriminator for a genus
    # If a genus has fewer samples than this, we fallback to global/prior
    MIN_SAMPLES_FOR_GENUS_MODEL = 5

    # Preprocessing
    # Yeo-Johnson supports positive and negative values (though features are likely positive)
    # and attempts to make data Gaussian-like, which is optimal for LDA.
    POWER_TRANSFORM_METHOD = "yeo-johnson"

    # Scaling
    # Standard scaling (0 mean, 1 var) is crucial after power transform
    SCALER_METHOD = "standard"

    # Probability Clipping
    # To avoid log(0) in metric calculation: max(min(p, 1-1e-15), 1e-15)
    PROB_CLIP = 1e-15

    # ==========================================
    # Runtime / Debugging
    # ==========================================
    # These can be overridden during initialization
    DEBUG = False
    # LDA doesn't use epochs, but this is included per requirements for flexibility
    # Could be used if we switch to an iterative solver or neural component later
    N_EPOCHS = 1

    def __init__(self, debug: bool = False, n_epochs: int = 1):
        """
        Initialize configuration with optional overrides for debugging.

        Args:
            debug (bool): If True, downstream scripts should use a subset of data.
            n_epochs (int): Number of training epochs (placeholder for LDA).
        """
        self.DEBUG = debug
        self.N_EPOCHS = n_epochs

        # Ensure necessary directories exist upon initialization
        self.create_directories()

        # Set random seeds immediately
        self.set_seed()

    def create_directories(self):
        """Creates working and submission directories if they don't exist."""
        os.makedirs(self.WORKING_DIR, exist_ok=True)
        os.makedirs(self.SUBMISSION_DIR, exist_ok=True)

    def set_seed(self):
        """Sets fixed random seeds for reproducibility."""
        random.seed(self.SEED)
        np.random.seed(self.SEED)
        torch.manual_seed(self.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(self.SEED)
        os.environ["PYTHONHASHSEED"] = str(self.SEED)

    @staticmethod
    def get_feature_columns():
        """
        Returns the list of 192 pre-extracted feature column names.
        Features are: margin_1..64, shape_1..64, texture_1..64
        """
        feature_types = ["margin", "shape", "texture"]
        features = []
        for f_type in feature_types:
            for i in range(1, 65):
                features.append(f"{f_type}_{i}")
        return features

