import os
import numpy as np

# =============================================================================
# Directory Configuration
# =============================================================================
INPUT_DIR = "./input"
METADATA_DIR = "./metadata"
WORKING_DIR = "./working/idea_68"
SUBMISSION_DIR = "./submission"

# Ensure working and output directories exist
os.makedirs(WORKING_DIR, exist_ok=True)
os.makedirs(SUBMISSION_DIR, exist_ok=True)

# =============================================================================
# File Paths
# =============================================================================
# Metadata CSVs generated by the metadata script
TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

# Base directory for images (metadata contains relative paths e.g., 'images/1.jpg')
IMAGES_BASE_DIR = INPUT_DIR

# Output Submission File
SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

# =============================================================================
# Data Schema & Column Definitions
# =============================================================================
ID_COL = "id"
TARGET_COL = "species"
FILE_PATH_COL = "file_path"

# =============================================================================
# Feature Engineering Configuration
# =============================================================================
# 1. Pre-extracted Tabular Features (192 total)
MARGIN_FEATURES = [f"margin_{i}" for i in range(1, 65)]
SHAPE_FEATURES = [f"shape_{i}" for i in range(1, 65)]
TEXTURE_FEATURES = [f"texture_{i}" for i in range(1, 65)]

TABULAR_FEATURES = MARGIN_FEATURES + SHAPE_FEATURES + TEXTURE_FEATURES

# 2. 3D-Geometric Fusion Features (6 total)
# These are calculated from the binary images during the pipeline execution
GEOMETRIC_FEATURES = [
    "Area",  # Absolute Mass (2D)
    "Mean_Thickness",  # Absolute Density (3D - via Distance Transform)
    "Eccentricity",  # Elongation
    "Solidity",  # Roughness
    "Extent",  # Rectangularity
    "Aspect_Ratio",  # Orientation
]

# 3. Combined Feature Set
# Sorted to ensure deterministic memory layout and column ordering
ALL_FEATURES = sorted(TABULAR_FEATURES + GEOMETRIC_FEATURES)

# =============================================================================
# Pipeline Hyperparameters
# =============================================================================
SEED = 42
N_JOBS = 12

# Precision: Use float64 for exact analytical inference in OAS/LDA
FLOAT_PRECISION = np.float64

# Sanitization: Variance Threshold to remove constant features (e.g., empty bins)
# Applied before scaling to prevent numerical explosion
VARIANCE_THRESHOLD = 0.0

# Probability Clipping for Log Loss Metric
PROB_CLIP_MIN = 1e-15
PROB_CLIP_MAX = 1.0 - 1e-15

