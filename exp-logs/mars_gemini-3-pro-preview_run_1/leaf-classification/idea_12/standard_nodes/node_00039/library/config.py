import os


class Config:
    """
    Configuration module for the Transductive PCA-LDA Leaf Classification project.

    This class defines:
    1. Deterministic file paths and directory structures.
    2. Model hyperparameters derived from previous analyses (PCA-LDA).
    3. A strictly ordered feature schema to ensure alignment between train and test matrices.
    """

    # -------------------------------------------------------------------------
    # 1. Directories and File Paths
    # -------------------------------------------------------------------------
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_12"
    SUBMISSION_DIR = "./submission"

    # Ensure necessary writeable directories exist immediately
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Specific File Paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Metadata Paths (Generated by metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # -------------------------------------------------------------------------
    # 2. Hyperparameters
    # -------------------------------------------------------------------------
    # Random Seed for reproducibility
    SEED = 42

    # LDA Settings
    # 'eigen': Solves the generalized eigenvalue problem, more stable for high-dim data.
    # 'auto': Applies Ledoit-Wolf shrinkage to the covariance matrix.
    LDA_SOLVER = "eigen"
    LDA_SHRINKAGE = "auto"

    # -------------------------------------------------------------------------
    # 3. Deterministic Feature Schema
    # -------------------------------------------------------------------------
    # We explicitly generate and sort the 192 feature names.
    # This sorted list MUST be used to reindex both Train and Test dataframes
    # to guarantee that columns are in the exact same order before matrix conversion.

    _feature_types = ["margin", "shape", "texture"]
    _feature_indices = range(1, 65)  # 1 to 64 inclusive

    FEATURES = []
    for f_type in _feature_types:
        for idx in _feature_indices:
            FEATURES.append(f"{f_type}{idx}")

    # Sort alphanumerically (lexicographically)
    # e.g., 'margin_1', 'margin_10', 'margin_11', ..., 'margin_2', ...
    FEATURES.sort()
