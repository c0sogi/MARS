SEED = 42

# Numerical Precision
# Using float64 is critical for the stability of the Linearized OAS Discriminant
# and to avoid machine epsilon floors in probability calibration.
NUMERIC_TYPE = np.float64

# ==========================================
# Directory & File Paths
# ==========================================

INPUT_DIR = "./input"
METADATA_DIR = "./metadata"
# Working directory specific to this idea/experiment
WORKING_DIR = "./working/idea_21"
SUBMISSION_DIR = "./submission"

# Ensure output directories exist
os.makedirs(WORKING_DIR, exist_ok=True)
os.makedirs(SUBMISSION_DIR, exist_ok=True)

# Metadata File Paths (Generated by previous steps)
TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

