# ==========================================
# Data Schema & Columns
# ==========================================

ID_COL = "id"
TARGET_COL = "species"

# Feature Columns
# We generate the 192 feature names (margin_1..64, shape_1..64, texture_1..64)
# and enforce strict alphanumeric ordering to prevent implicit column permutation.
_feature_groups = ["margin", "shape", "texture"]
_feature_indices = range(1, 65)  # 1 to 64

_raw_feature_cols = []
for group in _feature_groups:
    for idx in _feature_indices:
        _raw_feature_cols.append(f"{group}{idx}")

# Sort strictly alphanumerically (e.g., margin1, margin10, margin11, ..., margin2)
# This ensures the feature vector matches the order expected by the model
# regardless of how the CSV is read.
FEATURE_COLS = sorted(_raw_feature_cols)
