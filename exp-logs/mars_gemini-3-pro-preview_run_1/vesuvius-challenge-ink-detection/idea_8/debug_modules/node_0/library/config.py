import os
import torch


class Config:
    """
    Configuration class for the Full-Resolution Dilated U-Net (FR-UNet) solution.
    Centralizes all file paths, model hyperparameters, and training settings.
    """

    # --- Directory Paths ---
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Specific working directory for Idea 8
    WORKING_DIR = "./working/idea_8"

    # Metadata File Paths
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Output Sub-directories
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    PREDICTIONS_DIR = os.path.join(WORKING_DIR, "predictions")

    # Final Submission Path
    SUBMISSION_FILE = "./submission.csv"

    # --- Data Configuration ---
    # The input volume depth (z-direction slices)
    Z_DIM = 65
    # Patch dimensions generated by the metadata script
    PATCH_HEIGHT = 512
    PATCH_WIDTH = 512
    # Number of data loading workers
    NUM_WORKERS = 2

    # --- Model Architecture Hyperparameters ---
    # Input channels match the Z-dimension of the volume
    IN_CHANNELS = 65
    # Base channel width for the network (kept moderate to fit batch size 32)
    BASE_CHANNELS = 64
    # Dilation rates for the encoder path (Context Expansion)
    ENCODER_DILATIONS = [1, 2, 4, 8]
    # Dilation rates for the decoder path (Hierarchical Refinement)
    DECODER_DILATIONS = [8, 4, 2, 1]

    # --- Training Hyperparameters ---
    SEED = 42
    # Strictly maintained batch size as per strategy
    BATCH_SIZE = 32
    # Training duration
    NUM_EPOCHS = 20
    # Optimizer settings
    LEARNING_RATE = 1e-4
    # Loss function weight for the positive class (Ink)
    POS_WEIGHT = 2.0

    # --- Hardware ---
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup_directories(cls):
        """
        Creates the necessary directory structure for the experiment.
        Should be called at the start of execution.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.PREDICTIONS_DIR, exist_ok=True)

        print(f"Configuration loaded. Device: {cls.DEVICE}")
        print(f"Working directory: {cls.WORKING_DIR}")
