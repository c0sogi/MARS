import os
import torch
import random
import numpy as np


class Config:
    """
    Centralized configuration for the Steganography Detection Task.
    Implements settings for the Single-Stream HPF-CNN pipeline.
    """

    # ==========================================
    # General Settings
    # ==========================================
    seed = 42
    debug = False  # If True, runs on a small subset of data
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    num_workers = 4  # 12 vCPUs available, 4 is usually a safe sweet spot per GPU

    # ==========================================
    # File Paths
    # ==========================================
    input_root = "./input"
    metadata_dir = "./metadata"

    # Metadata files generated by the provided script
    train_csv = os.path.join(metadata_dir, "train.csv")
    val_csv = os.path.join(metadata_dir, "val.csv")
    test_csv = os.path.join(metadata_dir, "test.csv")

    # Output directories
    working_dir = "./working/idea_1"
    submission_dir = "./submission"
    submission_path = os.path.join(submission_dir, "submission.csv")

    # ==========================================
    # Data Parameters
    # ==========================================
    img_size = 512  # Input size for the model (random crop during train)

    # Debugging/Subset parameters
    # If debug is True, these control how many samples are loaded
    train_subset_size = 2000 if debug else None
    val_subset_size = 500 if debug else None

    # ==========================================
    # Model Parameters
    # ==========================================
    backbone = "efficientnet_b0"
    pretrained = True
    num_classes = 1  # Binary classification (Cover vs Stego)

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    epochs = 5  # Fast convergence expected with HPF + Pretrained backbone
    batch_size = 32  # A100 40GB can handle 32-64 comfortably with 512x512

    # Optimizer settings (AdamW)
    lr = 1e-3
    weight_decay = 1e-4

    # Scheduler settings (OneCycleLR)
    max_lr = 1e-3
    pct_start = 0.3
    div_factor = 25.0
    final_div_factor = 1000.0

    # Early Stopping
    patience = 2

    # ==========================================
    # Metric Parameters
    # ==========================================
    # Weighted AUC parameters
    tpr_thresholds = [0.0, 0.4, 1.0]
    weights = [2, 1]

    @classmethod
    def setup(cls):
        """
        Performs necessary setup:
        1. Creates working and submission directories.
        2. Sets random seeds for reproducibility.
        """
        # Create directories
        os.makedirs(cls.working_dir, exist_ok=True)
        os.makedirs(cls.submission_dir, exist_ok=True)

        # Set seeds
        random.seed(cls.seed)
        np.random.seed(cls.seed)
        torch.manual_seed(cls.seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.seed)
            torch.cuda.manual_seed_all(cls.seed)
            # Ensure deterministic behavior for reproducibility
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print("=" * 30)
        print("CONFIGURATION")
        print("=" * 30)
        print(f"Device: {cls.device}")
        print(f"Debug Mode: {cls.debug}")
        print(f"Backbone: {cls.backbone}")
        print(f"Image Size: {cls.img_size}")
        print(f"Batch Size: {cls.batch_size}")
        print(f"Epochs: {cls.epochs}")
        print(f"Learning Rate: {cls.lr}")
        print("=" * 30)
