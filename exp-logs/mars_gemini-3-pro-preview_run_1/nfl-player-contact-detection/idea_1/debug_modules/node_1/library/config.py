import os


class Config:
    """
    Global configuration for the NFL Contact Detection task.
    Contains file paths, model hyperparameters, and training settings.
    """

    # ---------------------------------------------------------
    # General Settings
    # ---------------------------------------------------------
    SEED = 42

    # ---------------------------------------------------------
    # Directories
    # ---------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Cache directory for storing processed features (Parquet files)
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_1")

    # Output directory for submission
    SUBMISSION_DIR = "./submission"

    # ---------------------------------------------------------
    # File Paths
    # ---------------------------------------------------------
    # Metadata files (generated by the provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Raw tracking data
    TRAIN_TRACKING_PATH = os.path.join(INPUT_DIR, "train_player_tracking.csv")
    TEST_TRACKING_PATH = os.path.join(INPUT_DIR, "test_player_tracking.csv")

    # Final submission file
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ---------------------------------------------------------
    # Data Processing Hyperparameters
    # ---------------------------------------------------------
    # Ratio of negative samples (no contact) to positive samples (contact)
    # used during training to handle class imbalance.
    # Example: 5.0 means 5 negative samples for every 1 positive sample.
    UNDERSAMPLE_RATIO = 5.0

    # ---------------------------------------------------------
    # Feature Engineering
    # ---------------------------------------------------------
    # List of features to be used by the MLP model
    FEATURES = [
        "distance",  # Euclidean distance between players (or player-ground)
        "speed_p1",  # Speed of player 1
        "speed_p2",  # Speed of player 2 (or 0 for ground)
        "speed_diff",  # Absolute difference in speed
        "acc_p1",  # Acceleration of player 1
        "acc_p2",  # Acceleration of player 2
        "acc_diff",  # Absolute difference in acceleration
        "orientation_diff",  # Difference in orientation
        "is_ground",  # Binary flag: 1 if player-ground contact, 0 otherwise
    ]

    # ---------------------------------------------------------
    # Model Architecture (K-FFN)
    # ---------------------------------------------------------
    # Dimensions of hidden layers
    HIDDEN_LAYERS = [64, 32]

    # Dropout rate for regularization
    DROPOUT_RATE = 0.1

    # ---------------------------------------------------------
    # Training Settings
    # ---------------------------------------------------------
    BATCH_SIZE = 2048
    LEARNING_RATE = 0.001
    EPOCHS = 10
    EARLY_STOPPING_PATIENCE = 3

    @staticmethod
    def setup_directories():
        """
        Creates necessary working and submission directories if they do not exist.
        """
        os.makedirs(Config.CACHE_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
