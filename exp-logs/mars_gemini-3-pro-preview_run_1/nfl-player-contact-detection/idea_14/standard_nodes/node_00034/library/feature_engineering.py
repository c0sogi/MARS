class FeatureEngineer:
    """
    Implements the Ordered Neighbor Kinematic Mining feature engineering pipeline.
    Handles tracking data processing, temporal windowing, neighbor finding,
    and geometric gating.
    """

    def __init__(self, config: Optional[FeatureConfig] = None):
        self.config = config if config is not None else FeatureConfig()
        set_seed(SEED)

    def _compute_physics_derivatives(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Computes derivatives like Jerk and Cartesian components of velocity/acceleration.
        """
        # Convert direction to radians (assuming 0 is North/Y-axis, clockwise)
        # Note: Exact coordinate system matters less than consistency for relative features.
        dir_rad = np.radians(df["direction"].fillna(0))

        # Velocity Components
        df["vx"] = df["speed"] * np.sin(dir_rad)
        df["vy"] = df["speed"] * np.cos(dir_rad)

        # Acceleration Components (Approximation assuming accel is in direction of motion)
        df["ax"] = df["acceleration"] * np.sin(dir_rad)
        df["ay"] = df["acceleration"] * np.cos(dir_rad)

        # Jerk (Derivative of Acceleration)
        # We group by game_play and nfl_player_id to ensure continuity
        # fillna(0) for the first frame
        df["jerk"] = (
            df.groupby(["game_play", "nfl_player_id"])["acceleration"].diff().fillna(0)
        )

        # Signed Acceleration (already in data as 'sa', but we ensure it's clean)
        df["sa"] = df["sa"].fillna(0)

        return df

    def _add_temporal_windows(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Adds shifted features for temporal context (History/Future).
        """
        # Identify columns to window. We include x, y to calculate pair-distance history later.
        cols_to_window = self.config.window_target_cols + ["x_position", "y_position"]
        # Filter to only those present in df
        cols_to_window = [c for c in cols_to_window if c in df.columns]

        # We need steps from -WINDOW_OFFSET to +WINDOW_OFFSET, excluding 0
        steps = [i for i in range(-WINDOW_OFFSET, WINDOW_OFFSET + 1) if i != 0]

        # Perform shifts
        # GroupBy is necessary to not shift across different players/plays
        grouper = df.groupby(["game_play", "nfl_player_id"])

        for col in cols_to_window:
            for t in steps:
                col_name = f"{col}_t{t:+d}"
                # Shift: positive t gets future (needs shift(-t)), negative t gets past (needs shift(-t))
                # strictly: shift(1) moves previous row to current. So t=-1 (past) is shift(1).
                # t=1 (future) is shift(-1).
                # So we use shift(-t).
                df[col_name] = grouper[col].shift(-t)

        # Fill NaNs generated by shifting (edges of play)
        # We use forward fill then backward fill to propagate state
        # For derivatives/speed, 0 might be appropriate, but ffill is robust for positions.
        window_cols = [f"{c}_t{t:+d}" for c in cols_to_window for t in steps]
        df[window_cols] = df[window_cols].fillna(0)  # Simple fill for safety

        return df

    def _compute_ordered_neighbors(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Computes K-Nearest Neighbors and their relative kinematics for every player-step.
        Returns a DataFrame with neighbor features appended.
        """
        # We process by (game_play, step) groups.
        # To optimize, we extract numpy arrays.

        # Prepare storage for neighbor features
        # Structure: index -> [n1_dist, n1_speed_rel, ..., nK_accel_rel]
        neighbor_data = {}

        # Columns needed for calculation
        req_cols = ["x_position", "y_position", "vx", "vy", "ax", "ay", "nfl_player_id"]

        # Iterate over groups (Play-Steps)
        # Note: This loop can be slow. ~50k groups.
        # We use a generator to process.
        groups = df.groupby(["game_play", "step"])

        feature_names = self.config.neighbor_features
        num_neighbors = K_NEIGHBORS

        # Pre-allocate output array for speed
        # shape: (len(df), len(feature_names))
        # We'll map back via index.

        # List to collect results
        results = []
        indices = []

        for (play, step), group in groups:
            # Extract arrays
            ids = group["nfl_player_id"].values
            pos = group[["x_position", "y_position"]].values
            vel = group[["vx", "vy"]].values
            acc = group[["ax", "ay"]].values

            n = len(ids)
            if n < 2:
                # No neighbors possible
                zeros = np.zeros((n, len(feature_names)))
                results.append(zeros)
                indices.extend(group.index.tolist())
                continue

            # Distance Matrix
            dists = cdist(pos, pos)  # (n, n)

            # Fill diagonal with infinity to ignore self
            np.fill_diagonal(dists, np.inf)

            # Find K nearest
            # argsort returns indices of neighbors sorted by distance
            sorted_idx = np.argsort(dists, axis=1)[:, :num_neighbors]

            # Calculate features for these neighbors
            # We need to construct a row for each player i

            batch_feats = []

            for i in range(n):
                neighbor_indices = sorted_idx[i]
                # If fewer than K neighbors exist (rare), pad?
                # argsort will return valid indices, but if n-1 < K, we might duplicate?
                # cdist handles n < K by just giving what's available.
                # But we sliced [:num_neighbors]. If n-1 < K, we need to handle it.

                valid_neighbors = neighbor_indices[
                    neighbor_indices < n
                ]  # Should be all valid

                row_feats = []

                for k in range(num_neighbors):
                    if k < len(valid_neighbors):
                        j = valid_neighbors[k]

                        # Primitives
                        # 1. Distance
                        d = dists[i, j]

                        # 2. Relative Speed (Magnitude of velocity difference)
                        v_rel_vec = vel[i] - vel[j]
                        speed_rel = np.linalg.norm(v_rel_vec)

                        # 3. Closing Speed (Projection of v_rel onto r_rel)
                        # r_rel vector from i to j
                        r_rel_vec = pos[j] - pos[i]
                        r_len = np.linalg.norm(r_rel_vec)
                        if r_len > 1e-6:
                            closing_speed = np.dot(v_rel_vec, r_rel_vec) / r_len
                        else:
                            closing_speed = 0.0

                        # 4. Relative Acceleration
                        a_rel_vec = acc[i] - acc[j]
                        accel_rel = np.linalg.norm(a_rel_vec)

                        row_feats.extend([d, speed_rel, closing_speed, accel_rel])
                    else:
                        # Pad with 0 or large distance if neighbor doesn't exist
                        row_feats.extend([999.0, 0.0, 0.0, 0.0])

                batch_feats.append(row_feats)

            results.append(np.array(batch_feats))
            indices.extend(group.index.tolist())

        # Concatenate all results
        all_feats = np.vstack(results)

        # Create DataFrame
        df_neighbors = pd.DataFrame(all_feats, columns=feature_names, index=indices)

        # Join back to original dataframe
        df = df.join(df_neighbors)

        return df

    def process_tracking_data(self, df_tracking: pd.DataFrame) -> pd.DataFrame:
        """
        Master function to process raw tracking data into enriched tracking data.
        """
        # Ensure sorting
        df_tracking = df_tracking.sort_values(
            ["game_play", "nfl_player_id", "step"]
        ).reset_index(drop=True)

        # 1. Physics Derivatives
        df_tracking = self._compute_physics_derivatives(df_tracking)

        # 2. Temporal Windows (Player-centric)
        df_tracking = self._add_temporal_windows(df_tracking)

        # 3. Ordered Neighbors
        # This is the heavy step.
        df_tracking = self._compute_ordered_neighbors(df_tracking)

        return df_tracking

    def generate_features(
        self,
        metadata_input: Union[str, pd.DataFrame],
        tracking_input: Union[str, pd.DataFrame],
        mode: str = "train",
        load_cached_data: bool = True,
    ) -> pd.DataFrame:
        """
        Main entry point to generate the feature matrix (X, y).

        Args:
            metadata_input: Path to metadata csv or DataFrame.
            tracking_input: Path to tracking csv or DataFrame.
            mode: 'train', 'val', or 'test'. Controls gating.
            load_cached_data: Whether to try loading from cache.

        Returns:
            pd.DataFrame: The feature matrix including target 'contact' and identifiers.
        """
        # 1. Construct Cache Key
        # We hash the config + mode to ensure uniqueness
        cache_config = {
            "config": self.config,
            "mode": mode,
            "data_version": "v1",  # Increment if logic changes
        }
        cache_path = get_hashed_filepath(f"features_{mode}", cache_config, "parquet")

        # 2. Try Load Cache
        if load_cached_data and os.path.exists(cache_path):
            print(f"Loading cached features from {cache_path}...")
            return pd.read_parquet(cache_path)

        print(f"Generating features for mode='{mode}' (Cache miss or force reload)...")

        # 3. Load Data
        if isinstance(metadata_input, str):
            df_meta = pd.read_csv(metadata_input)
        else:
            df_meta = metadata_input.copy()

        if isinstance(tracking_input, str):
            df_track = pd.read_csv(tracking_input)
        else:
            df_track = tracking_input.copy()

        # 4. Process Tracking Data (Enrichment)
        print("Processing tracking data (Derivatives, Windows, Neighbors)...")
        df_track_rich = self.process_tracking_data(df_track)

        # 5. Merge Metadata with Tracking
        print("Merging metadata with enriched tracking...")

        # Prepare Metadata
        # Ensure types match
        df_meta["game_play"] = df_meta["game_play"].astype(str)
        df_meta["step"] = df_meta["step"].astype(int)
        df_meta["nfl_player_id_1"] = df_meta["nfl_player_id_1"].astype(int)

        # Handle 'G' in player 2
        df_meta["is_ground"] = (df_meta["nfl_player_id_2"] == "G").astype(int)

        # Temporary column for merge, convert G to -1 or similar to avoid type error,
        # though we will handle P2 merge carefully.
        # We split into P-P and P-G for cleaner merging?
        # Actually, left join works if we handle the key.

        # Create a merge key for P2 that is numeric. 'G' becomes NaN or -999.
        df_meta["p2_merge_id"] = (
            pd.to_numeric(df_meta["nfl_player_id_2"], errors="coerce")
            .fillna(-999)
            .astype(int)
        )

        # Merge Player 1
        # We want all columns from tracking for P1
        track_cols = df_track_rich.columns.tolist()
        # Rename for P1
        p1_rename = {
            c: f"{c}_p1"
            for c in track_cols
            if c not in ["game_play", "step", "nfl_player_id"]
        }

        df_merged = (
            pd.merge(
                df_meta,
                df_track_rich,
                left_on=["game_play", "step", "nfl_player_id_1"],
                right_on=["game_play", "step", "nfl_player_id"],
                how="left",
            )
            .rename(columns=p1_rename)
            .drop(columns=["nfl_player_id"])
        )

        # Merge Player 2
        # Rename for P2
        p2_rename = {
            c: f"{c}_p2"
            for c in track_cols
            if c not in ["game_play", "step", "nfl_player_id"]
        }

        df_merged = (
            pd.merge(
                df_merged,
                df_track_rich,
                left_on=["game_play", "step", "p2_merge_id"],
                right_on=["game_play", "step", "nfl_player_id"],
                how="left",
            )
            .rename(columns=p2_rename)
            .drop(columns=["nfl_player_id"])
        )

        # 6. Post-Merge Feature Engineering
        print("Computing pair kinematics...")

        # Handle P-G (Player-Ground) cases
        # If is_ground == 1, P2 features are NaN. Fill them with 0.
        # Exception: We don't want distance to be NaN, but 0 is technically wrong for "contact".
        # However, for the model, 0 distance usually implies contact.
        # But here, 'contact' with ground is a specific event.
        # We fill NaNs with 0.
        p2_cols = [c for c in df_merged.columns if c.endswith("_p2")]
        df_merged[p2_cols] = df_merged[p2_cols].fillna(0)

        # Calculate Pair Distance
        # If P2 is Ground, x_position_p2 is 0 (from fillna). P1 is at x,y.
        # Distance would be large. This is noisy.
        # We should set distance to 0 for Ground interactions to avoid large outliers,
        # or use a sentinel value.
        # Strategy: Calculate Euclidean dist. If is_ground, set to 0.

        dx = df_merged["x_position_p1"] - df_merged["x_position_p2"]
        dy = df_merged["y_position_p1"] - df_merged["y_position_p2"]
        dist = np.sqrt(dx**2 + dy**2)

        df_merged["distance"] = np.where(df_merged["is_ground"] == 1, 0.0, dist)

        # Calculate Pair Distance Windows
        # We have x_position_t{k}_p1 and x_position_t{k}_p2
        # We can compute distance_t{k}
        steps = [i for i in range(-WINDOW_OFFSET, WINDOW_OFFSET + 1) if i != 0]
        for t in steps:
            x1 = df_merged[f"x_position_t{t:+d}_p1"]
            y1 = df_merged[f"y_position_t{t:+d}_p1"]
            x2 = df_merged[f"x_position_t{t:+d}_p2"]
            y2 = df_merged[f"y_position_t{t:+d}_p2"]

            d_t = np.sqrt((x1 - x2) ** 2 + (y1 - y2) ** 2)
            df_merged[f"distance_t{t:+d}"] = np.where(
                df_merged["is_ground"] == 1, 0.0, d_t
            )

        # Speed Diff
        df_merged["speed_diff"] = np.abs(df_merged["speed_p1"] - df_merged["speed_p2"])

        # Accel Diff
        df_merged["accel_diff"] = np.abs(
            df_merged["acceleration_p1"] - df_merged["acceleration_p2"]
        )

        # Orientation/Direction Diff (Angular difference)
        def ang_diff(a, b):
            diff = np.abs(a - b)
            return np.minimum(diff, 360 - diff)

        df_merged["orientation_diff"] = ang_diff(
            df_merged["orientation_p1"].fillna(0), df_merged["orientation_p2"].fillna(0)
        )
        df_merged["direction_diff"] = ang_diff(
            df_merged["direction_p1"].fillna(0), df_merged["direction_p2"].fillna(0)
        )

        # Rename columns to match config expectations if necessary
        # Config expects 'accel_p1', tracking has 'acceleration_p1'. Rename.
        rename_map = {
            "acceleration_p1": "accel_p1",
            "acceleration_p2": "accel_p2",
            "jerk_p1": "jerk_p1",  # already named jerk in tracking
            "jerk_p2": "jerk_p2",
        }
        df_merged = df_merged.rename(columns=rename_map)

        # 7. Geometric Gating (The Sieve)
        # Only apply in train mode to reduce data size.
        # Validation set must remain complete for accurate metric calculation.
        # Keep ALL Ground interactions.
        # Keep Player-Player interactions ONLY if distance < GATING_DIST.
        if mode == "train":
            print(f"Applying Geometric Gating (Dist < {GATING_DIST} or Ground)...")
            initial_len = len(df_merged)

            # Condition: (is_ground == 1) OR (distance < GATING_DIST)
            # Note: We set distance=0 for ground, so distance < 2.5 covers ground too.
            # But let's be explicit for safety.
            mask = (df_merged["distance"] < GATING_DIST) | (df_merged["is_ground"] == 1)
            df_merged = df_merged[mask].copy()

            print(f"Gating reduced rows from {initial_len} to {len(df_merged)}.")

        # 8. Final Column Selection
        # Ensure 'contact' is present (it is in metadata)
        # Select features defined in config + identifiers

        feature_cols = self.config.all_features
        # Add identifiers and target
        keep_cols = [
            "contact_id",
            "game_play",
            "step",
            "nfl_player_id_1",
            "nfl_player_id_2",
            "contact",
        ] + feature_cols

        # Check for missing columns
        missing = [c for c in keep_cols if c not in df_merged.columns]
        if missing:
            print(f"Warning: Missing columns filled with 0: {missing}")
            for c in missing:
                df_merged[c] = 0

        df_final = df_merged[keep_cols]

        # 9. Save to Cache
        print(f"Saving features to {cache_path}...")
        df_final.to_parquet(cache_path, index=False)

        return df_final
