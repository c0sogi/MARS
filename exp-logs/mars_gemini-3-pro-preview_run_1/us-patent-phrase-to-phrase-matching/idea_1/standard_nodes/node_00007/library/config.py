import os
import torch


class Config:
    # =========================================================================
    # General Settings
    # =========================================================================
    seed = 42
    debug = False  # Set to True to run on a small subset of data for debugging
    debug_subset_size = 100  # Number of samples to use when debug=True
    num_workers = 2  # Number of subprocesses for data loading

    # =========================================================================
    # File Paths
    # =========================================================================
    # Input Metadata Paths (Generated by the provided metadata script)
    train_path = "./metadata/train.csv"
    val_path = "./metadata/val.csv"
    test_path = "./metadata/test.csv"
    sample_submission_path = "./input/sample_submission.csv"

    # Output Directories
    working_dir = "./working/idea_1"
    submission_dir = "./submission"

    # Specific Output Files
    model_save_path = os.path.join(working_dir, "siamese_model.pth")
    predictions_save_path = os.path.join(working_dir, "test_predictions.npy")
    submission_path = os.path.join(submission_dir, "submission.csv")

    # =========================================================================
    # Model Architecture
    # =========================================================================
    model_name = "sentence-transformers/all-MiniLM-L6-v2"
    # Max length for [CLS] <context> [SEP] <phrase> [SEP]
    # Phrases are generally short, context is 3 chars. 64 is usually sufficient.
    max_length = 64

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    epochs = 15
    train_batch_size = 32
    val_batch_size = 64
    learning_rate = 2e-5
    weight_decay = 0.01
    warmup_ratio = 0.1
    early_stopping_patience = 3

    # =========================================================================
    # Caching
    # =========================================================================
    load_cached_data = True  # If True, attempts to load processed tensors from disk

    # =========================================================================
    # Hardware
    # =========================================================================
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    @classmethod
    def setup(cls):
        """
        Creates necessary output directories if they do not exist.
        """
        os.makedirs(cls.working_dir, exist_ok=True)
        os.makedirs(cls.submission_dir, exist_ok=True)
