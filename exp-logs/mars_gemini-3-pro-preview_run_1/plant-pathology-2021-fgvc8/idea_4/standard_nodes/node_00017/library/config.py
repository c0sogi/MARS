import os
import torch


class Config:
    """
    Configuration for Apple Disease Detection Task.
    Implements the strategy defined in Idea 4: ConvNeXt-Small + GeM Pooling + 384px.
    """

    # -------------------------------------------------------------------------
    # General Configuration
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    NUM_WORKERS = 8  # Optimized for 12 vCPUs

    # -------------------------------------------------------------------------
    # Directories & Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_4"
    SUBMISSION_DIR = "./submission"

    # Image Directories
    TRAIN_IMAGES_DIR = os.path.join(INPUT_DIR, "train_images")
    TEST_IMAGES_DIR = os.path.join(INPUT_DIR, "test_images")

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Paths
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    LOG_PATH = os.path.join(WORKING_DIR, "train_log.txt")

    # -------------------------------------------------------------------------
    # Data Configuration
    # -------------------------------------------------------------------------
    IMAGE_SIZE = 384
    NUM_CLASSES = 6
    # Alphabetically sorted class labels for consistent mapping
    CLASSES = [
        "complex",
        "frog_eye_leaf_spot",
        "healthy",
        "powdery_mildew",
        "rust",
        "scab",
    ]

    # -------------------------------------------------------------------------
    # Model Configuration
    # -------------------------------------------------------------------------
    MODEL_NAME = "convnext_small.in12k_ft_in1k"
    PRETRAINED = True

    # Custom Head Parameters
    USE_GEM_POOLING = True
    GEM_P = 3.0  # Initial power for Generalized Mean Pooling
    DROP_RATE = 0.3  # Dropout rate for the classification head
    DROP_PATH_RATE = 0.2  # Stochastic depth rate for the backbone

    # -------------------------------------------------------------------------
    # Training Configuration
    # -------------------------------------------------------------------------
    BATCH_SIZE = 32  # Fits on A100 40GB with 384px images
    EPOCHS = 15  # Short schedule due to pretraining

    # Optimizer (AdamW)
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 0.05
    MAX_GRAD_NORM = 1000

    # Precision
    USE_AMP = True  # Automatic Mixed Precision

    # Loss Function
    LABEL_SMOOTHING = 0.05

    # Scheduler (Cosine Annealing)
    SCHEDULER_T_MAX = 15  # Should match EPOCHS
    SCHEDULER_MIN_LR = 1e-6

    # -------------------------------------------------------------------------
    # Augmentation Configuration (Albumentations)
    # -------------------------------------------------------------------------
    # Geometric - Strict enforcement for rotation invariance
    AUG_ROTATE90_P = 0.5
    AUG_SHIFT_SCALE_ROTATE_P = 0.5

    # Color / Regularization - Stronger augs to prevent overfitting
    AUG_HSV_P = 0.5
    AUG_BRIGHTNESS_CONTRAST_P = 0.5
    AUG_COARSE_DROPOUT_P = 0.5

    # Exclusions - Explicitly disabled based on Lesson 00005
    AUG_MIXUP_PROB = 0.0
    AUG_CUTMIX_PROB = 0.0

    # -------------------------------------------------------------------------
    # Inference Configuration
    # -------------------------------------------------------------------------
    USE_TTA = True  # Enabled for robustness (Cite Lesson 00007)
    THRESHOLD = 0.5  # Probability threshold for multi-label classification

    # -------------------------------------------------------------------------
    # Hardware
    # -------------------------------------------------------------------------
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    @classmethod
    def create_dirs(cls):
        """Creates necessary directories for outputs and working files."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
