    SUBMISSION_DIR = "./submission"
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Processing Strategy
    # =========================================================================
    # Density Sampling:
    # We keep 100% of sentences with at least one "interesting" (non-PLAIN/PUNCT) token.
    # We subsample sentences that are purely PLAIN/PUNCT to this ratio.
    PLAIN_KEEP_RATE = 0.05

    # Vocabulary Limits
    MAX_VOCAB_SIZE_WORD = 60000
    MIN_FREQ_WORD = 2

    # Sequence Limits
    MAX_SEQ_LEN = 128  # Max tokens per sentence (for batching)
    MAX_CHAR_LEN = 30  # Max characters per token (for Char-CNN)

    # =========================================================================
    # Model Architecture: Morphologically-Augmented Tagger
    # =========================================================================
    # Inputs: Word Embeddings + Char CNN + Regex Features -> Bi-LSTM -> Softmax
    EMBED_DIM_WORD = 256
    EMBED_DIM_CHAR = 64

    # Character CNN
    CHAR_CNN_FILTERS = 64
    CHAR_CNN_KERNEL_SIZE = 3

    # Main Recurrent Layer
    HIDDEN_DIM_TAGGER = 512
    NUM_LAYERS_TAGGER = 2
    DROPOUT_TAGGER = 0.3

    # =========================================================================
    # Model Architecture: Seq2Seq Fallback (LSTM)
    # =========================================================================
    # Used for OOV tokens where (token, class) is not in Knowledge Base
    EMBED_DIM_SEQ2SEQ = 128
    HIDDEN_DIM_SEQ2SEQ = 256
    NUM_LAYERS_SEQ2SEQ = 1
    DROPOUT_SEQ2SEQ = 0.2
    MAX_GEN_LEN = 128  # Max length of generated normalized text

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 256  # A100 has 40GB, can handle large batches
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-5

    # Tagger Training
    NUM_EPOCHS_TAGGER = 15
    PATIENCE_TAGGER = 3

    # Seq2Seq Training
    NUM_EPOCHS_SEQ2SEQ = 10
    PATIENCE_SEQ2SEQ = 3

    # =========================================================================
    # Explicit Morphological Features (Regex)
    # =========================================================================
    # These patterns are matched against every token. The binary match results
    # are concatenated with the word embeddings and char-cnn outputs.
    REGEX_PATTERNS = [
        r"^\d+$",  # All digits
        r"\d",  # Contains digit
        r"^[A-Z]+$",  # All caps
        r"^[A-Z]",  # Capitalized
        r"^[a-z]+$",  # All lower
        r"[a-z]",  # Contains lower
        r"\.",  # Contains dot
        r",",  # Contains comma
        r"\d+\.\d+",  # Decimal pattern (e.g., 3.14)
        r"\d+,\d+",  # Comma number pattern (e.g., 1,000)
        r"[$£€¥₹]",  # Currency symbols
        r"%",  # Percent
        r"#",  # Hash
        r"/",  # Slash (dates/fractions)
        r"-",  # Dash
        r":",  # Colon (time)
        r"(st|nd|rd|th)$",  # Ordinal suffixes
        r"^\d{4}$",  # 4 digits (year?)
        r"^\d{1,2}/\d{1,2}/\d{2,4}$",  # Date format 1 (DD/MM/YYYY)
        r"^\d{4}-\d{1,2}-\d{1,2}$",  # Date format 2 (YYYY-MM-DD)
        r"[A-Za-z]+\.$",  # Abbreviation-like (e.g., Dr.)
        r"https?://",  # URL protocol
        r"www\.",  # URL prefix
        r"@",  # Email/Handle
        r"^\W+$",  # All non-alphanumeric (Punctuation)
        r"^[IVXLCDM]+$",  # Roman Numerals
        r"(kg|km|mm|cm|mg|ml|ltr|lb|oz|ft|in)$",  # Common measures
        r"(am|pm|a\.m\.|p\.m\.)$",  # Time indicators
        r"\d+:\d+",  # Time pattern
    ]

    NUM_REGEX_FEATURES = len(REGEX_PATTERNS)
