import os
import torch
import random
import numpy as np


class Config:
    # =========================================================================
    # 1. GENERAL SETUP & REPRODUCIBILITY
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data
    MAX_DEBUG_SAMPLES = 10000  # Number of samples to use in debug mode

    # Device configuration
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4  # For data loading

    # =========================================================================
    # 2. DIRECTORY STRUCTURE & FILE PATHS
    # =========================================================================
    # Input Directories (Read-Only)
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working Directory (Write Allowed) - Idea 3 specific
    WORKING_DIR = "./working/idea_3"
    SUBMISSION_DIR = os.path.join(WORKING_DIR, "submission")

    # Ensure working directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Input Data Files (Generated by metadata script)
    TRAIN_DATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_DATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_DATA_PATH = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "en_sample_submission_2.csv")

    # Output / Cache Files (Parquet format preferred over pickle)
    # Data Caches
    TRAIN_GROUPED_PATH = os.path.join(WORKING_DIR, "train_grouped.parquet")
    VAL_GROUPED_PATH = os.path.join(WORKING_DIR, "val_grouped.parquet")
    TEST_GROUPED_PATH = os.path.join(WORKING_DIR, "test_grouped.parquet")

    # Vocab Caches
    VOCAB_TOKENS_PATH = os.path.join(WORKING_DIR, "vocab_tokens.parquet")
    VOCAB_CHARS_PATH = os.path.join(WORKING_DIR, "vocab_chars.parquet")
    VOCAB_CLASSES_PATH = os.path.join(WORKING_DIR, "vocab_classes.parquet")

    # Knowledge Base Cache
    KNOWLEDGE_BASE_PATH = os.path.join(WORKING_DIR, "knowledge_base.parquet")

    # Seq2Seq Specific Data Cache
    SEQ2SEQ_DATA_PATH = os.path.join(WORKING_DIR, "seq2seq_data.parquet")

    # Model Checkpoints
    TAGGER_MODEL_PATH = os.path.join(WORKING_DIR, "tagger_best_model.pth")
    SEQ2SEQ_MODEL_PATH = os.path.join(WORKING_DIR, "seq2seq_best_model.pth")

    # Final Submission
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # 3. DATA HYPERPARAMETERS
    # =========================================================================
    # Tagger Limits
    MAX_SEQ_LEN = 128  # Maximum tokens per sentence
    MAX_CHAR_LEN = 30  # Maximum characters per token
    MAX_VOCAB_SIZE = 40000  # Max number of words in vocabulary
    MIN_FREQ = 2  # Minimum frequency for a word to be in vocab

    # Seq2Seq Limits
    MAX_OUTPUT_LEN = 64  # Max length of normalized text generation

    # =========================================================================
    # 4. MODEL ARCHITECTURE HYPERPARAMETERS
    # =========================================================================
    # --- Stage 1: Character-Aware Bi-LSTM Tagger ---
    TAGGER_EMBEDDING_DIM = 128
    TAGGER_HIDDEN_DIM = 256
    TAGGER_DROPOUT = 0.3
    TAGGER_LAYERS = 2

    # Character CNN branch
    CHAR_EMBEDDING_DIM = 32
    CNN_FILTERS = 48
    CNN_KERNEL_SIZE = 3

    # --- Stage 3: Seq2Seq Fallback Model ---
    SEQ2SEQ_EMBED_DIM = 64
    SEQ2SEQ_HIDDEN_DIM = 128
    SEQ2SEQ_DROPOUT = 0.2
    SEQ2SEQ_LAYERS = 1
    TEACHER_FORCING_RATIO = 0.5

    # =========================================================================
    # 5. TRAINING HYPERPARAMETERS
    # =========================================================================
    BATCH_SIZE = 64
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-5
    EPOCHS = 10
    EARLY_STOPPING_PATIENCE = 3

    # Class Balancing
    USE_CLASS_WEIGHTS = True
    SMOOTHING_FACTOR = 0.5  # Power for sqrt smoothing (0.5 = sqrt)

    @staticmethod
    def set_seed(seed=None):
        """Sets the random seed for reproducibility."""
        if seed is None:
            seed = Config.SEED
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
