import os
import torch


class Config:
    """
    Configuration class for Domain-Adapted DeBERTa-v3 with Multi-Layer Fusion and AWP.
    Centralizes all hyperparameters, paths, and model settings.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    seed = 42
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    num_workers = 4

    # Debug mode: if True, runs on a small subset of data for quick verification
    debug = False

    # =========================================================================
    # Directory & File Paths
    # =========================================================================
    input_dir = "./input"
    metadata_dir = "./metadata"

    # Working directory for this specific experiment/idea
    working_dir = "./working/idea_10"
    output_dir = os.path.join(working_dir, "output")

    # Ensure writable directories exist
    os.makedirs(working_dir, exist_ok=True)
    os.makedirs(output_dir, exist_ok=True)

    # Metadata Files (Generated by previous preprocessing steps)
    train_metadata_path = os.path.join(metadata_dir, "train.csv")
    val_metadata_path = os.path.join(metadata_dir, "val.csv")
    test_metadata_path = os.path.join(metadata_dir, "test.csv")

    # Raw Data Files (Read-only source of text)
    train_raw_path = os.path.join(input_dir, "train.csv")
    test_raw_path = os.path.join(input_dir, "test.csv")
    sample_submission_path = os.path.join(input_dir, "sample_submission.csv")

    # Artifact Paths
    # Path to save/load the Domain-Adapted backbone
    dapt_model_path = os.path.join(working_dir, "dapt_backbone")
    # Path template for saving fold models
    saved_model_path = os.path.join(output_dir, "model_fold_{}.pth")
    # Final submission file
    submission_path = os.path.join(working_dir, "submission.csv")

    # =========================================================================
    # Data Configuration
    # =========================================================================
    target_cols = [
        "toxic",
        "severe_toxic",
        "obscene",
        "threat",
        "insult",
        "identity_hate",
    ]
    num_labels = 6

    # Tokenizer settings
    max_length = 512

    # =========================================================================
    # Model Architecture
    # =========================================================================
    model_name = "microsoft/deberta-v3-base"
    hidden_size = 768

    # Multi-Layer Fusion: Aggregate hidden states from the last N layers
    use_multi_layer_fusion = True
    fusion_layers = 4

    # Hybrid Pooling: Concatenate Global Max Pooling and Linear Attention Pooling
    use_hybrid_pooling = True

    # Multi-Sample Dropout: Apply dropout multiple times to the final representation
    use_multi_sample_dropout = True
    dropout_samples = 5
    dropout_rate = 0.1

    # =========================================================================
    # Stage 1: Domain-Adaptive Pre-training (DAPT)
    # =========================================================================
    # Whether to run DAPT or skip it (if model already exists)
    train_dapt = True

    dapt_batch_size = 16
    dapt_epochs = 3
    dapt_lr = 2e-5
    dapt_mlm_probability = 0.15
    dapt_weight_decay = 0.01

    # =========================================================================
    # Stage 2: Supervised Fine-Tuning (Cross-Validation)
    # =========================================================================
    n_folds = 5
    epochs = 5
    train_batch_size = 16
    valid_batch_size = 32

    # Optimization
    learning_rate = 2e-5
    weight_decay = 0.01
    max_grad_norm = 1.0

    # Scheduler (OneCycleLR)
    scheduler_type = "OneCycleLR"
    pct_start = 0.1  # Warmup for 10% of training steps

    # Adversarial Weight Perturbation (AWP)
    use_awp = True
    # Start AWP from this epoch (0-indexed). 1 means start at Epoch 2.
    awp_start_epoch = 1
    awp_eps = 1e-4
    awp_lr = 1e-4

    # Logging
    print_freq = 100
