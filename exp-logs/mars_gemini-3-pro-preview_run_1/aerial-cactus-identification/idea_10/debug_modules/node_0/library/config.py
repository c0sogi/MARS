import os
import torch


class Config:
    """
    Configuration class for the Cactus Classification Task.
    Defines paths, hyperparameters, and constants for the Heterogeneous Stacking Ensemble.
    """

    # ==========================================
    # Directories & Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_10"
    SUBMISSION_DIR = "./submission"

    # Ensure necessary writeable directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Input Metadata Paths (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Submission Path
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Caching Configuration (NPY Files)
    # ==========================================
    # Paths for cached numpy arrays to speed up I/O.
    # We will combine train and val metadata for 5-Fold CV, so we define "Full Train" cache paths.
    CACHE_FULL_TRAIN_IMGS = os.path.join(WORKING_DIR, "cache_full_train_imgs.npy")
    CACHE_FULL_TRAIN_LABELS = os.path.join(WORKING_DIR, "cache_full_train_labels.npy")
    CACHE_FULL_TRAIN_FILESIZES = os.path.join(
        WORKING_DIR, "cache_full_train_filesizes.npy"
    )

    # Test set cache paths
    CACHE_TEST_IMGS = os.path.join(WORKING_DIR, "cache_test_imgs.npy")
    CACHE_TEST_IDS = os.path.join(WORKING_DIR, "cache_test_ids.npy")
    CACHE_TEST_FILESIZES = os.path.join(WORKING_DIR, "cache_test_filesizes.npy")

    # ==========================================
    # Model & Data Hyperparameters
    # ==========================================
    # Data Specifications
    IMAGE_SIZE = 32
    NUM_CHANNELS = 3
    NUM_CLASSES = 1

    # Reproducibility
    SEED = 42

    # Training Loop
    N_FOLDS = 5
    EPOCHS = 30
    BATCH_SIZE = 64

    # Optimization
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2

    # Regularization
    MIXUP_ALPHA = 0.2

    # ==========================================
    # Hardware Settings
    # ==========================================
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    # 12 vCPUs available, setting workers to a reasonable number to avoid overhead
    NUM_WORKERS = 4
