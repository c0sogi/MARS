import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration class to centralize all hyperparameters, file paths, and settings.
    """

    # ==========================================
    # System & Reproducibility
    # ==========================================
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4  # Number of dataloader workers

    # ==========================================
    # File Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_2"
    SUBMISSION_DIR = "./submission"

    # Metadata paths (generated by metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output paths
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Data Parameters
    # ==========================================
    IMAGE_SIZE = 32
    NUM_CLASSES = 1

    # Debugging / Development
    DEBUG = False
    DEBUG_SUBSET_SIZE = 1000  # Size of subset if DEBUG is True

    # ==========================================
    # Model Architecture (Custom DenseNet)
    # ==========================================
    GROWTH_RATE = 12  # k in DenseNet paper
    BLOCK_CONFIG = (6, 12, 24)  # Number of layers in each dense block
    COMPRESSION = 0.5  # Reduction factor in transition layers (theta)
    DROP_RATE = 0.0  # Dropout rate inside dense blocks
    USE_SE = True  # Use Squeeze-and-Excitation blocks

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    EPOCHS = 50  # Extended duration for Mixup convergence
    BATCH_SIZE = 128  # Suitable for 32x32 images on A100
    LEARNING_RATE = 1e-3  # Initial LR for AdamW
    WEIGHT_DECAY = 1e-2  # Weight decay for AdamW
    MIN_LR = 1e-6  # Minimum LR for Cosine Annealing

    # Regularization
    MIXUP_ALPHA = 1.0  # Alpha for Beta distribution in Mixup

    # ==========================================
    # Inference
    # ==========================================
    TTA_VIEWS = 4  # 4-view TTA: Original, HFlip, VFlip, Rotate180

    @staticmethod
    def setup():
        """
        Initializes the environment: creates necessary directories and sets random seeds.
        """
        # Create directories
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)

        # Set seeds for reproducibility
        Config.set_seed(Config.SEED)

    @staticmethod
    def set_seed(seed):
        """
        Sets the random seed for Python, NumPy, and PyTorch.
        """
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
