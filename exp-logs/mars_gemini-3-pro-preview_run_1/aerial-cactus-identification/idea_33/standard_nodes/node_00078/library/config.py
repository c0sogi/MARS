import os
import torch


class Config:
    # --------------------------------------------------------------------------
    # General Setup
    # --------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to limit dataset size for debugging

    # Compute Environment
    # Using 12 vCPUs and A100 GPU
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 12

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata Files (Generated by metadata script)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Working Directory (Specific to Idea 33)
    WORK_DIR = "./working/idea_33"

    # Sub-directories for artifacts
    CACHE_DIR = os.path.join(WORK_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORK_DIR, "checkpoints")
    SUBMISSION_DIR = os.path.join(WORK_DIR, "submission")

    # Final Submission File
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Data Parameters
    # --------------------------------------------------------------------------
    IMG_SIZE = 32
    NUM_CLASSES = 1

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    N_FOLDS = 5
    EPOCHS = 30
    BATCH_SIZE = 128
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2

    # Mixup Regularization
    MIXUP_ALPHA = 0.2

    # Loss Configuration
    # L_total = L_main + 0.4 * L_aux
    AUX_WEIGHT = 0.4

    # Stochastic Weight Averaging (SWA)
    USE_SWA = True
    SWA_START_EPOCH = 20
    SWA_LR = 1e-4

    # --------------------------------------------------------------------------
    # Model Configuration
    # --------------------------------------------------------------------------
    # Heterogeneous backbones for stacking
    MODELS = ["CactusRepVGG", "CactusResNet"]

    # --------------------------------------------------------------------------
    # Utility Methods
    # --------------------------------------------------------------------------
    @classmethod
    def setup(cls):
        """
        Creates the necessary directory structure for the current experiment.
        """
        os.makedirs(cls.WORK_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

    @classmethod
    def print_config(cls):
        """
        Prints the current configuration for logging purposes.
        """
        print("=" * 40)
        print(f"Configuration (Idea 33)")
        print("=" * 40)
        for k, v in cls.__dict__.items():
            if not k.startswith("__") and not callable(v):
                print(f"{k:<20}: {v}")
        print("=" * 40)
