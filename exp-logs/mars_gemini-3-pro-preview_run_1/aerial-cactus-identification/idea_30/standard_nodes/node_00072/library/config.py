import os
import torch
import numpy as np
import random


class Config:
    # -------------------------------------------------------------------------
    # Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42

    # -------------------------------------------------------------------------
    # Compute Environment
    # -------------------------------------------------------------------------
    # Use CUDA if available
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    # Number of dataloader workers (12 vCPUs available, leaving some for main process)
    NUM_WORKERS = 4

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    TRAIN_IMG_DIR = os.path.join(INPUT_DIR, "train")
    TEST_IMG_DIR = os.path.join(INPUT_DIR, "test")

    # Metadata paths (generated by the provided script)
    METADATA_DIR = "./metadata"
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Working Directory for Idea 30
    WORKING_DIR = "./working/idea_30"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = os.path.join(WORKING_DIR, "submission")

    # Output file paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache file paths (for numpy memory mapping/loading)
    CACHE_TRAIN_IMGS = os.path.join(CACHE_DIR, "train_imgs.npy")
    CACHE_TRAIN_LABELS = os.path.join(CACHE_DIR, "train_labels.npy")
    CACHE_TRAIN_FSIZES = os.path.join(CACHE_DIR, "train_fsizes.npy")
    CACHE_TRAIN_IDS = os.path.join(CACHE_DIR, "train_ids.npy")

    CACHE_TEST_IMGS = os.path.join(CACHE_DIR, "test_imgs.npy")
    CACHE_TEST_IDS = os.path.join(CACHE_DIR, "test_ids.npy")
    CACHE_TEST_FSIZES = os.path.join(CACHE_DIR, "test_fsizes.npy")

    # -------------------------------------------------------------------------
    # Data Hyperparameters
    # -------------------------------------------------------------------------
    IMG_SIZE = 32
    NUM_CLASSES = 1  # Binary classification (Cactus vs No Cactus)

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    NUM_FOLDS = 5
    BATCH_SIZE = 128
    EPOCHS = 30
    LR = 1e-3
    WEIGHT_DECAY = 1e-2  # Standard for AdamW

    # Stochastic Weight Averaging (SWA)
    # Active for the final 10 epochs (Epochs 20-29)
    SWA_START_EPOCH = 20
    SWA_LR = 1e-4

    # Regularization & Aux Loss
    MIXUP_ALPHA = 0.2
    AUX_LOSS_WEIGHT = 1.0  # Weight for the File Size Regression Head

    # -------------------------------------------------------------------------
    # Utility Functions
    # -------------------------------------------------------------------------
    @staticmethod
    def setup():
        """Creates necessary working directories."""
        os.makedirs(Config.CACHE_DIR, exist_ok=True)
        os.makedirs(Config.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)

    @staticmethod
    def seed_everything(seed=42):
        """Sets fixed random seeds for fully reproducible results."""
        random.seed(seed)
        os.environ["PYTHONHASHSEED"] = str(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        torch.cuda.manual_seed(seed)
        # Deterministic mode slows down training but guarantees reproducibility
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False
