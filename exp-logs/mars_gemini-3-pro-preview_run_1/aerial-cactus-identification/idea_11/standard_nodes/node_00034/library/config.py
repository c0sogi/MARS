import os
import torch


class Config:
    """
    Configuration class for the Metadata-Fused RepVGG experiment.
    """

    # -------------------------------------------------------------------------
    # Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42

    # -------------------------------------------------------------------------
    # Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_11"
    SUBMISSION_DIR = "./submission"

    # Ensure writable directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # -------------------------------------------------------------------------
    # Input File Paths
    # -------------------------------------------------------------------------
    # Raw images
    TRAIN_IMG_DIR = os.path.join(INPUT_DIR, "train")
    TEST_IMG_DIR = os.path.join(INPUT_DIR, "test")

    # Metadata splits (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # -------------------------------------------------------------------------
    # Caching Paths (Numpy format for fast I/O)
    # -------------------------------------------------------------------------
    # Training set
    CACHE_TRAIN_IMGS = os.path.join(WORKING_DIR, "cache_train_imgs.npy")
    CACHE_TRAIN_LABELS = os.path.join(WORKING_DIR, "cache_train_labels.npy")
    CACHE_TRAIN_FILESIZES = os.path.join(WORKING_DIR, "cache_train_filesizes.npy")

    # Validation set
    CACHE_VAL_IMGS = os.path.join(WORKING_DIR, "cache_val_imgs.npy")
    CACHE_VAL_LABELS = os.path.join(WORKING_DIR, "cache_val_labels.npy")
    CACHE_VAL_FILESIZES = os.path.join(WORKING_DIR, "cache_val_filesizes.npy")

    # Test set
    CACHE_TEST_IMGS = os.path.join(WORKING_DIR, "cache_test_imgs.npy")
    CACHE_TEST_IDS = os.path.join(WORKING_DIR, "cache_test_ids.npy")
    CACHE_TEST_FILESIZES = os.path.join(WORKING_DIR, "cache_test_filesizes.npy")

    # -------------------------------------------------------------------------
    # Model Output Paths
    # -------------------------------------------------------------------------
    BEST_MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    FINAL_SWA_MODEL_PATH = os.path.join(WORKING_DIR, "final_swa_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Hyperparameters
    # -------------------------------------------------------------------------
    # Data
    IMAGE_SIZE = 32
    NUM_CLASSES = 1  # Binary classification
    NUM_WORKERS = 4  # Based on 12 vCPUs availability

    # Training
    BATCH_SIZE = 256
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    EPOCHS = 35  # 25 standard + 10 SWA

    # Stochastic Weight Averaging (SWA)
    SWA_START_EPOCH = 25
    SWA_LR = 5e-4

    # Regularization / Augmentation
    MIXUP_ALPHA = 0.2

    # Debugging
    DEBUG = False
    DEBUG_SIZE = 1000  # Subset size when DEBUG is True

    # Compute
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    @classmethod
    def print_config(cls):
        print("=" * 40)
        print("CONFIGURATION")
        print("=" * 40)
        for k, v in cls.__dict__.items():
            if not k.startswith("__") and not callable(v):
                print(f"{k}: {v}")
        print("=" * 40)
