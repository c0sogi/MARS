import torch
from torch.utils.data import Dataset, DataLoader
import numpy as np
from library.config import Config
from library.features import prepare_datasets


class VentilatorDataset(Dataset):
    """
    PyTorch Dataset for Ventilator Pressure Prediction.
    Wraps the numpy arrays generated by the feature engineering pipeline.
    """

    def __init__(self, data_dict, is_test=False):
        """
        Args:
            data_dict (dict): Dictionary containing 'x', 'u_out', and optionally 'y' or 'ids'.
            is_test (bool): Flag indicating if this is the test set (returns ids instead of targets).
        """
        self.x = data_dict["x"]
        self.u_out = data_dict["u_out"]
        self.is_test = is_test

        if self.is_test:
            # Test set has flattened IDs
            self.ids = data_dict["ids"]
        else:
            # Train/Val sets have targets
            self.y = data_dict["y"]

    def __len__(self):
        return len(self.x)

    def __getitem__(self, idx):
        """
        Returns a tuple of tensors for a single breath.

        Returns:
            If train/val: (x, u_out, y)
            If test: (x, u_out, ids)
        """
        # x shape: (80, n_features)
        # The last 2 columns of x are R_cat and C_cat indices
        x = torch.tensor(self.x[idx], dtype=torch.float32)

        # u_out shape: (80,)
        # Used for masking the loss
        u_out = torch.tensor(self.u_out[idx], dtype=torch.float32)

        if self.is_test:
            # Calculate the slice for IDs corresponding to this breath
            # ids array is flattened (N_breaths * 80)
            start = idx * Config.SEQ_LEN
            end = start + Config.SEQ_LEN
            ids = torch.tensor(self.ids[start:end], dtype=torch.long)
            return x, u_out, ids
        else:
            # y shape: (80,)
            y = torch.tensor(self.y[idx], dtype=torch.float32)
            return x, u_out, y


def get_data_loaders(load_cached_data=True, batch_size=None):
    """
    Prepares datasets and returns DataLoaders for train, validation, and test sets.

    Args:
        load_cached_data (bool): Whether to load pre-processed data from cache.
        batch_size (int, optional): Batch size override. Defaults to Config.BATCH_SIZE.

    Returns:
        tuple: (train_loader, val_loader, test_loader)
    """
    if batch_size is None:
        batch_size = Config.BATCH_SIZE

    # Load data using the features library (handles caching and processing)
    train_data, val_data, test_data = prepare_datasets(
        load_cached_data=load_cached_data
    )

    # Initialize Datasets
    train_dataset = VentilatorDataset(train_data, is_test=False)
    val_dataset = VentilatorDataset(val_data, is_test=False)
    test_dataset = VentilatorDataset(test_data, is_test=True)

    # Initialize DataLoaders
    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=Config.NUM_WORKERS,
        pin_memory=(Config.DEVICE == "cuda"),
        drop_last=True,
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=Config.NUM_WORKERS,
        pin_memory=(Config.DEVICE == "cuda"),
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=Config.NUM_WORKERS,
        pin_memory=(Config.DEVICE == "cuda"),
    )

    return train_loader, val_loader, test_loader
