import os
import torch


class Config:
    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    EXP_NAME = "idea_20"
    DEBUG = False  # Toggle for fast debugging (subsamples data)

    # =========================================================================
    # Paths & Directories
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = os.path.join("./working", EXP_NAME)
    SUBMISSION_DIR = "./submission"

    # Input Files (Generated by metadata script)
    TRAIN_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_PATH = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Files
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    MODEL_PATH = os.path.join(WORKING_DIR, "model.pth")

    # Cache Files (Parquet for fast I/O)
    CACHE_TRAIN_PATH = os.path.join(WORKING_DIR, "train_engineered.parquet")
    CACHE_VAL_PATH = os.path.join(WORKING_DIR, "val_engineered.parquet")
    CACHE_TEST_PATH = os.path.join(WORKING_DIR, "test_engineered.parquet")
    SCALER_PATH = os.path.join(WORKING_DIR, "scaler.pkl")

    # =========================================================================
    # Data Configuration
    # =========================================================================
    # Column Definitions
    ID_COL = "id"
    BREATH_ID_COL = "breath_id"
    TIME_COL = "time_step"
    TARGET_COL = "pressure"
    U_IN_COL = "u_in"
    U_OUT_COL = "u_out"
    R_COL = "R"
    C_COL = "C"

    # Sequence Properties
    SEQ_LEN = 80  # Fixed length per breath in this dataset

    # Feature Engineering Parameters
    USE_LAGS = True
    LAG_STEPS = [1, 2, 3, 4]
    USE_DIFFS = True

    # Feature Groups
    # Continuous features to be scaled using RobustScaler
    # Includes raw inputs, physics terms, and time-series derived features
    CONT_FEATURES = [
        "time_step",
        "u_in",
        "R",
        "C",
        # Physics Terms
        "volume",  # Integral of u_in * dt
        "u_in_R",  # Interaction: u_in * R
        "vol_C",  # Interaction: volume / C
        # Lags
        "u_in_lag1",
        "u_in_lag2",
        "u_in_lag3",
        "u_in_lag4",
        # Diffs
        "u_in_diff1",
        "u_in_diff2",
    ]

    # Binary/Categorical features to exclude from scaling
    # u_out is critical for masking and must remain 0/1
    BINARY_FEATURES = ["u_out"]

    # Total input dimension calculated dynamically based on lists above
    INPUT_DIM = len(CONT_FEATURES) + len(BINARY_FEATURES)

    # =========================================================================
    # Model Architecture (Curated-Identity Physics-Composite)
    # =========================================================================
    # Stem
    CNN_KERNELS = [3, 5, 7]  # Multi-scale convolution
    MODEL_DIM = 1024  # D_model (Cite Lesson 00042)

    # Backbone
    NUM_BLOCKS = 4
    LSTM_HIDDEN = 512  # Bidirectional -> 2 * 512 = 1024 output (matches D_model) (Cite Lesson 00055)
    FFN_EXPANSION = 2  # 1024 -> 2048 -> 1024
    DROPOUT = 0.1

    # Deep Supervision
    AUX_BLOCK_INDEX = 1  # Attach aux head after Block 2 (0-indexed index 1)

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    EPOCHS = 35
    BATCH_SIZE = 512

    # Optimization
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2
    MAX_GRAD_NORM = 1.0  # Strict clipping for LSTM stability

    # Loss
    AUX_LOSS_WEIGHT = 0.3  # Weight for auxiliary head

    # Scheduler (OneCycleLR)
    PCT_START = 0.3
    DIV_FACTOR = 25.0
    FINAL_DIV_FACTOR = 1e4

    # Hardware
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Initialize the directory structure.
        Should be called at the start of any execution script.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        if cls.DEBUG:
            print(f"[{cls.__name__}] Debug mode enabled. Parameters may be overridden.")
