import os
import torch


class Config:
    # --------------------------------------------------------------------------
    # System Configuration
    # --------------------------------------------------------------------------
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 12  # Utilizing available vCPUs

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    # Base Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Idea Specific Cache Directory
    # Stores processed data and checkpoints for Idea 19
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_19")

    # Metadata Files (Generated by previous steps)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Raw Data Files
    TRAIN_CSV = os.path.join(INPUT_DIR, "train.csv")
    TEST_CSV = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Files
    PROCESSED_DATA_PATH = os.path.join(CACHE_DIR, "processed_data.npz")
    MODEL_PATH = os.path.join(CACHE_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(WORKING_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Data Hyperparameters
    # --------------------------------------------------------------------------
    # Continuous features: f_00-f_26 (27) + f_28-f_30 (3) = 30 total
    NUM_CONT_FEATURES = 30

    # Sequence feature: f_27
    SEQ_LEN = 10
    # Vocab size: A-Z (26 characters). We use 0-25 indices.
    VOCAB_SIZE = 26

    # --------------------------------------------------------------------------
    # Model Architecture Hyperparameters
    # --------------------------------------------------------------------------
    # Stream 1: Transformer
    EMBED_DIM = 32
    TRANSFORMER_LAYERS = 2
    TRANSFORMER_HEADS = 4
    TRANSFORMER_DROPOUT = 0.1

    # Stream 2 & Fusion
    # Backbone structure: 3 stages of decreasing width
    BACKBONE_STAGES = [512, 256, 128]
    # Blocks per stage
    BLOCKS_PER_STAGE = 3
    # High dropout for backbone regularization
    BACKBONE_DROPOUT = 0.35

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    BATCH_SIZE = 1024
    NUM_EPOCHS = 35

    # Optimizer (AdamW)
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2

    # Scheduler (StepLR)
    SCHEDULER_STEP_SIZE = 10
    SCHEDULER_GAMMA = 0.1

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 10  # Stop if no improvement for 10 epochs

    @classmethod
    def setup(cls):
        """
        Creates necessary directories for caching and outputs.
        Should be called at the start of execution.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        # Ensure submission directory exists (usually ./working is root, but good practice)
        os.makedirs(os.path.dirname(cls.SUBMISSION_PATH), exist_ok=True)
        print(f"Configuration loaded. Cache directory: {cls.CACHE_DIR}")
