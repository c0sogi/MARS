import os
import torch


class Config:
    """
    Configuration class for the Wide & Deeply Supervised ResFunnel-GLU model.
    Serves as the single source of truth for hyperparameters and file paths.
    """

    # --------------------------------------------------------------------------
    # General Setup
    # --------------------------------------------------------------------------
    PROJECT_NAME = "idea_8"
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Use available CPUs for data loading, capping at reasonable number
    NUM_WORKERS = min(8, os.cpu_count() if os.cpu_count() else 4)

    # --------------------------------------------------------------------------
    # Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = os.path.join("./working", PROJECT_NAME)

    # Metadata Paths (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Raw Data Paths
    TRAIN_DATA_PATH = os.path.join(INPUT_DIR, "train.csv")
    TEST_DATA_PATH = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Artifacts
    PROCESSED_DATA_PATH = os.path.join(WORKING_DIR, "processed_data.npz")
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(WORKING_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Data Hyperparameters
    # --------------------------------------------------------------------------
    # There are 30 continuous features (f_00 - f_30, excluding f_27)
    NUM_CONTINUOUS_FEATURES = 30

    # Feature f_27 is a string of length 10
    F_27_SEQ_LEN = 10
    # Vocab size for character embeddings (A-Z).
    # 26 letters + 1 for padding/unknown = 27 minimum. Setting 30 for safety.
    VOCAB_SIZE = 30

    # --------------------------------------------------------------------------
    # Model Architecture (Wide & Deeply Supervised ResFunnel-GLU)
    # --------------------------------------------------------------------------
    # Embedding dimension for the characters in f_27
    EMBEDDING_DIM = 32

    # Dimensions for the 3 stages of the Deep ResFunnel Stream
    FUNNEL_STAGES = [512, 256, 128]

    # Aggressive dropout as per strategy
    DROPOUT_RATE = 0.35

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    BATCH_SIZE = 2048
    LEARNING_RATE = 1e-3

    # High weight decay to constrain the high capacity model
    WEIGHT_DECAY = 1e-2

    # Extended training duration
    EPOCHS = 50
    EARLY_STOPPING_PATIENCE = 10

    # Loss Weights for Deep Supervision
    # Formula: Loss = L_final + lambda1*L_aux1 + lambda2*L_aux2
    AUX_LOSS_WEIGHTS = [0.3, 0.3]

    # --------------------------------------------------------------------------
    # Debugging / Development
    # --------------------------------------------------------------------------
    # Set to True to train on a small subset for rapid testing
    DEBUG = False
    DEBUG_SAMPLES = 5000

    @classmethod
    def setup(cls):
        """Ensures the working directory exists."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)


# Initialize environment setup on import
Config.setup()
