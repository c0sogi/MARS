import os
import torch


class Config:
    """
    Global configuration for the Hotel ID classification task.
    Encapsulates paths, hyperparameters, and system settings.
    """

    # =========================================================================
    # Directory Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"
    SUBMISSION_DIR = "./submission"

    # Experiment specific directory (Idea 1: Parametric Classification)
    IDEA_DIR = os.path.join(WORKING_DIR, "idea_1")

    # =========================================================================
    # File Paths
    # =========================================================================
    # Metadata CSVs generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output files
    MODEL_SAVE_PATH = os.path.join(IDEA_DIR, "model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Parameters
    # =========================================================================
    NUM_CLASSES = 7770  # Total unique hotel IDs (from analysis)
    IMAGE_SIZE = 224  # Standard input size for ResNet
    NUM_WORKERS = 12  # Number of vCPUs available for data loading

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    SEED = 42
    BATCH_SIZE = 256  # Large batch size for A100 GPU
    LEARNING_RATE = 1e-3  # Standard starting LR for Adam
    NUM_EPOCHS = 15  # Max epochs (subject to early stopping)
    LABEL_SMOOTHING = 0.1  # Helps with high cardinality classification
    PATIENCE = 3  # Early stopping patience

    # =========================================================================
    # Model Architecture
    # =========================================================================
    MODEL_NAME = "resnet18"
    PRETRAINED = True
    DROPOUT = 0.2  # Dropout rate for the final layer

    # =========================================================================
    # System Settings
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Ensures that the necessary working and submission directories exist.
        """
        os.makedirs(cls.IDEA_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories upon module import
Config.setup()
