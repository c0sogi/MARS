import os
import torch


class Config:
    # -------------------------------------------------------------------------
    # Project Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"
    SUBMISSION_DIR = "./submission"

    # Idea-specific directory for caching features (Idea 1: Cached Linear Probing)
    IDEA_NAME = "idea_2"
    CACHE_DIR = os.path.join(WORKING_DIR, IDEA_NAME)

    # -------------------------------------------------------------------------
    # Dataset Paths
    # -------------------------------------------------------------------------
    # Metadata files generated by the provided script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Submission output
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Model & Data Configuration
    # -------------------------------------------------------------------------
    SEED = 42
    NUM_CLASSES = 23
    IMAGE_SIZE = 224  # ResNet standard input size

    # Standard ImageNet normalization statistics (RGB)
    IMAGENET_MEAN = [0.485, 0.456, 0.406]
    IMAGENET_STD = [0.229, 0.224, 0.225]

    # -------------------------------------------------------------------------
    # Compute & Optimization
    # -------------------------------------------------------------------------
    # Auto-detect GPU
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Use available vCPUs
    NUM_WORKERS = 12

    # Batch size for feature extraction (inference mode)
    # A100 40GB allows for a large batch size with ResNet50
    BATCH_SIZE = 256

    # Training parameters for the Linear Classifier (L-BFGS)
    EPOCHS = 50
    LEARNING_RATE = 1.0

    # -------------------------------------------------------------------------
    # Feature Caching Configuration
    # -------------------------------------------------------------------------
    # Paths to store/load the extracted features (Numpy format)
    # This enables the "Cached" part of the strategy
    TRAIN_FEATURES = os.path.join(CACHE_DIR, "train_features.npy")
    TRAIN_TARGETS = os.path.join(CACHE_DIR, "train_targets.npy")

    VAL_FEATURES = os.path.join(CACHE_DIR, "val_features.npy")
    VAL_TARGETS = os.path.join(CACHE_DIR, "val_targets.npy")

    TEST_FEATURES = os.path.join(CACHE_DIR, "test_features.npy")
    TEST_IDS = os.path.join(CACHE_DIR, "test_ids.npy")

    @staticmethod
    def initialize():
        """
        Creates the necessary working and submission directories if they do not exist.
        This ensures subsequent file operations do not fail.
        """
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
        os.makedirs(Config.CACHE_DIR, exist_ok=True)


# Execute initialization on import
Config.initialize()
