import os
import torch


class Config:
    """
    Configuration for the Hybrid Geometric-Attention Network (HGA-Net) pipeline.
    Includes paths, model hyperparameters, and training settings.
    """

    # -------------------------------------------------------------------------
    # System & Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42
    # Use GPU if available
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    # Number of workers for data loading (12 vCPUs available)
    NUM_WORKERS = 12

    # -------------------------------------------------------------------------
    # Directory & File Paths
    # -------------------------------------------------------------------------
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory for this specific idea/experiment
    WORKING_DIR = "./working/idea_5"
    SUBMISSION_DIR = "./submission"

    # Create writable directories if they don't exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata paths (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Raw Structure Data
    STRUCTURES_CSV = os.path.join(INPUT_DIR, "structures.csv")
    # Folder containing individual .xyz files
    STRUCTURES_DIR = os.path.join(INPUT_DIR, "structures")

    # Caching Paths (Using .npz for efficient storage of processed graphs)
    # These files will store the pre-computed geometric graphs
    CACHE_TRAIN_PATH = os.path.join(WORKING_DIR, "cached_train.npz")
    CACHE_VAL_PATH = os.path.join(WORKING_DIR, "cached_val.npz")
    CACHE_TEST_PATH = os.path.join(WORKING_DIR, "cached_test.npz")

    # Model Checkpoint
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pt")

    # Submission Output
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Processing Hyperparameters
    # -------------------------------------------------------------------------
    # Geometric Graph Construction
    CUTOFF_RADIUS = 5.0  # Angstroms (Interaction threshold for local graph)
    MAX_NEIGHBORS = 32  # Maximum number of neighbors per atom to maintain efficiency

    # Coupling Types for Stratification/Normalization
    COUPLING_TYPES = ["1JHC", "2JHC", "3JHC", "1JHN", "2JHN", "3JHN", "2JHH", "3JHH"]

    # Debugging / Development
    DEBUG = False  # Set to True to run on a small subset for testing
    DEBUG_SIZE = 5000  # Number of samples if DEBUG is True

    # -------------------------------------------------------------------------
    # Model Architecture: Hybrid Geometric-Attention Network (HGA-Net)
    # -------------------------------------------------------------------------
    # General Capacity
    HIDDEN_DIM = 256  # Scaled up for A100 (prevents underfitting)

    # Backbone: Directional Message Passing (DMPNN)
    NUM_MP_LAYERS = 4  # Number of message passing iterations
    RBF_SIZE = 64  # Number of Radial Basis Functions for distance
    SBF_SIZE = 32  # Number of Spherical Basis Functions for angles

    # Global Interaction: Transformer Encoder
    # Enables long-range information flow beyond local cutoff
    USE_TRANSFORMER = True
    NUM_TRANSFORMER_LAYERS = 2
    NUM_ATTENTION_HEADS = 8
    TRANSFORMER_DIM_FEEDFORWARD = 1024

    # Regularization
    # Deterministic readout requested: Dropout set to 0.0 for regression precision
    DROPOUT = 0.0

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 192  # Optimized for A100 40GB VRAM
    EPOCHS = 50  # Extended training horizon for convergence
    LEARNING_RATE = 2e-4  # Initial Learning Rate
    WEIGHT_DECAY = 1e-5  # L2 Regularization
    MAX_GRAD_NORM = 1.0  # Gradient Clipping threshold

    # Scheduler (Linear Warmup + Cosine Annealing)
    WARMUP_EPOCHS = 5
    MIN_LR = 1e-6
