import os


class Config:
    """
    Central configuration for the Dual-Resolution Semantic Early Fusion (DRSEF) pipeline.
    """

    # -------------------------------------------------------------------------
    # Global Settings
    # -------------------------------------------------------------------------
    RANDOM_SEED = 42
    N_FOLDS = 5

    # -------------------------------------------------------------------------
    # Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory for caching intermediate artifacts (embeddings, features)
    WORKING_DIR = "./working/idea_28"
    SUBMISSION_DIR = "./submission"

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    # Raw Data
    TRAIN_JSON_PATH = os.path.join(INPUT_DIR, "train.json")
    TEST_JSON_PATH = os.path.join(INPUT_DIR, "test.json")

    # Metadata (Generated by metadata script)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Submission Output
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Feature Engineering Configuration
    # -------------------------------------------------------------------------
    # Text Columns to Concatenate for Embedding
    TEXT_COLS = ["request_title", "request_text_edit_aware"]

    # View 1: Primary Backbone (High-Resolution)
    # Rationale: Best sample-to-feature ratio, high performance anchor.
    MODEL_HIGH_RES = "sentence-transformers/all-MiniLM-L6-v2"

    # View 2: Auxiliary Backbone (Low-Resolution)
    # Rationale: Deeper semantic knowledge, compressed to avoid dimensionality curse.
    MODEL_LOW_RES = "sentence-transformers/all-mpnet-base-v2"
    PCA_DIMS = 32

    # View 3: Robust Metadata
    # Explicitly including unix_timestamp_of_request, excluding user history/heuristics
    METADATA_COLS = [
        "unix_timestamp_of_request",
        "requester_account_age_in_days_at_request",
        "requester_days_since_first_post_on_raop_at_request",
        "requester_number_of_comments_at_request",
        "requester_number_of_comments_in_raop_at_request",
        "requester_number_of_posts_at_request",
        "requester_number_of_posts_on_raop_at_request",
        "requester_number_of_subreddits_at_request",
        "requester_upvotes_minus_downvotes_at_request",
        "requester_upvotes_plus_downvotes_at_request",
    ]

    # -------------------------------------------------------------------------
    # Caching Paths (Intermediate Artifacts)
    # -------------------------------------------------------------------------
    # High-Res Embeddings
    TRAIN_EMBEDDINGS_HIGH_RES = os.path.join(
        WORKING_DIR, "train_embeddings_high_res.npy"
    )
    TEST_EMBEDDINGS_HIGH_RES = os.path.join(WORKING_DIR, "test_embeddings_high_res.npy")

    # Low-Res Embeddings (Pre-PCA)
    TRAIN_EMBEDDINGS_LOW_RES = os.path.join(WORKING_DIR, "train_embeddings_low_res.npy")
    TEST_EMBEDDINGS_LOW_RES = os.path.join(WORKING_DIR, "test_embeddings_low_res.npy")

    # Metadata Features
    TRAIN_METADATA_PATH = os.path.join(WORKING_DIR, "train_metadata.parquet")
    TEST_METADATA_PATH = os.path.join(WORKING_DIR, "test_metadata.parquet")

    # -------------------------------------------------------------------------
    # Model Hyperparameters
    # -------------------------------------------------------------------------
    # Bagging Ensemble Settings
    N_ESTIMATORS = 20

    # Logistic Regression Grid Search Space
    # Focusing on high-regularization regime (small C to moderate C)
    PARAM_GRID = {
        "C": [0.0001, 0.001, 0.01, 0.1, 1.0, 5.0, 10.0],
        "class_weight": ["balanced", None],
        "penalty": ["l2"],  # Ridge regression
        "solver": ["lbfgs", "liblinear"],
        "max_iter": [1000],
    }

    @classmethod
    def setup(cls):
        """Creates necessary directories if they don't exist."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
