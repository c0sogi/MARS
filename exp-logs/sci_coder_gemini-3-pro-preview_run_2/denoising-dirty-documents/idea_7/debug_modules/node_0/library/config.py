import os
import torch


class Config:
    """
    Configuration for Deeply Supervised Attention-Gated Coordinate ResUNet (DS-AG-CAC-ResUNet).
    Centralizes all hyperparameters for architecture, data, training, and inference.
    """

    # -------------------------------------------------------------------------
    # Reproducibility & Hardware
    # -------------------------------------------------------------------------
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Utilizing 12 vCPUs for data loading
    NUM_WORKERS = 12

    # -------------------------------------------------------------------------
    # Paths & Directories
    # -------------------------------------------------------------------------
    # Base Directories
    METADATA_DIR = "./metadata"
    INPUT_DIR = "./input"
    WORKING_DIR = "./working/idea_7"
    SUBMISSION_DIR = "./submission"

    # Ensure output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata Files (Generated by provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Model Checkpoint & Output
    MODEL_CHECKPOINT_PATH = os.path.join(WORKING_DIR, "ds_ag_cac_resunet_best.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Configuration
    # -------------------------------------------------------------------------
    # Patch extraction settings
    PATCH_SIZE = 128

    # High-Density Sampling: Number of random patches to extract per image per epoch
    # This ensures the model sees a diverse range of noise/text alignments.
    PATCHES_PER_IMAGE = 100

    # Debugging: Set to an integer (e.g., 10) to train on a small subset of images.
    # Set to None to use the full dataset.
    DEBUG_SUBSET_SIZE = None

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    MODEL_NAME = "DS-AG-CAC-ResUNet"

    # Capacity
    BASE_FILTERS = 64

    # Architectural Components
    USE_DEEP_SUPERVISION = True  # Auxiliary heads at decoder levels
    USE_ATTENTION_GATES = True  # AGs in skip connections
    USE_COORDINATE_ATTENTION = True  # CA blocks in encoder/decoder
    USE_ASPP = True  # Atrous Spatial Pyramid Pooling at bottleneck

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    NUM_EPOCHS = 100
    BATCH_SIZE = 64  # Optimized for A100 40GB with 128x128 patches

    # Optimization
    OPTIMIZER = "AdamW"
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2  # Strong regularization for high-capacity model

    # Learning Rate Scheduler (Cosine Annealing)
    SCHEDULER = "CosineAnnealingLR"
    MIN_LEARNING_RATE = 1e-6

    # Loss Function
    # We predict the noise residual.
    # Loss is weighted sum of final output and deep supervision heads.
    LOSS_FUNCTION = "MultiScaleMSE"

    # -------------------------------------------------------------------------
    # Inference Hyperparameters
    # -------------------------------------------------------------------------
    # Tiled Inference
    TILE_OVERLAP = 0.5  # 50% overlap to eliminate edge artifacts

    # Test-Time Augmentation (TTA)
    USE_TTA = True
    TTA_ROUNDS = 8  # Original + 7 geometric transformations (flips/rotates)

    @classmethod
    def print_config(cls):
        """Prints the current configuration settings."""
        print("\n" + "=" * 40)
        print(f"  CONFIG: {cls.MODEL_NAME}")
        print("=" * 40)
        for key, value in cls.__dict__.items():
            if not key.startswith("__") and not callable(value):
                print(f"  {key:<25} : {value}")
        print("=" * 40 + "\n")
