import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration class for Anatomy-Aware U-Net++ pipeline.
    Centralizes hyperparameters, file paths, and model settings.
    """

    # ==============================
    # General Settings
    # ==============================
    SEED = 42
    DEBUG = False  # Set to True to run with a small subset for debugging

    # ==============================
    # File Paths
    # ==============================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_2"
    SUBMISSION_DIR = "./submission"

    # Metadata generated by the preprocessing script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output paths
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache paths for deterministic data processing
    TRAIN_CACHE_PATH = os.path.join(WORKING_DIR, "train_tiles.npy")
    VAL_CACHE_PATH = os.path.join(WORKING_DIR, "val_tiles.npy")

    # Create necessary directories
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==============================
    # Data Hyperparameters
    # ==============================
    TILE_SIZE = 1024
    # Stride for inference (50% overlap)
    STRIDE = TILE_SIZE // 2

    # Representative Undersampling:
    # Keep all positive tiles, sample 20% of background-only tiles
    BACKGROUND_SAMPLE_RATE = 0.20

    NUM_WORKERS = 4

    # ==============================
    # Model Hyperparameters
    # ==============================
    MODEL_ARCH = "UnetPlusPlus"
    ENCODER_NAME = "resnet34"
    ENCODER_WEIGHTS = "imagenet"

    # 4 Channels: 3 RGB + 1 Anatomical Mask (Cortex vs Medulla/Bg)
    IN_CHANNELS = 4
    CLASSES = 1
    ACTIVATION = "sigmoid"

    # ==============================
    # Training Hyperparameters
    # ==============================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Batch size adjusted for 1024x1024 input on A100 (40GB)
    BATCH_SIZE = 8

    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-5

    EPOCHS = 50

    # Warmup Strategy: Disable early stopping for initial epochs
    WARMUP_EPOCHS = 15
    EARLY_STOPPING_PATIENCE = 10

    # Scheduler settings (CosineAnnealing)
    T_MAX = EPOCHS
    ETA_MIN = 1e-6

    # ==============================
    # Inference Hyperparameters
    # ==============================
    # Threshold for binary mask generation
    MASK_THRESHOLD = 0.5
    # Minimum pixel size for removing small artifacts (optional post-processing)
    MIN_OBJECT_SIZE = 0

    @staticmethod
    def setup_reproducibility(seed=42):
        """
        Sets random seeds for python, numpy, and torch to ensure reproducibility.
        """
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        torch.cuda.manual_seed(seed)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False
        os.environ["PYTHONHASHSEED"] = str(seed)


# Initialize reproducibility on import
Config.setup_reproducibility(Config.SEED)
