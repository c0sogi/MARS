import os
import torch


class Config:
    """
    Central configuration for the Dual-Stream Heterogeneous Multi-View Ensemble.
    Handles paths, model definitions, data processing parameters, and hyperparameters.
    """

    # ==========================================
    # Directories & Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for caching intermediate files (embeddings, models)
    # Using 'idea_10' as the specific iteration identifier
    WORK_DIR = "./working/idea_10"
    SUBMISSION_DIR = "./submission"

    # Ensure working and submission directories exist
    os.makedirs(WORK_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata Files (Generated by the provided metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Final Submission File
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Compute & Reproducibility
    # ==========================================
    SEED = 42

    # Device detection
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Compute settings
    # A100 GPU (40GB) allows for decent batch sizes even with Large models
    BATCH_SIZE = 32
    NUM_WORKERS = 4

    # ==========================================
    # Model Architectures & Weights
    # ==========================================
    # Stream A: Convolutional Neural Network (Local Texture Focus)
    MODEL_A_NAME = "convnext_large"
    # Using torchvision 'New Recipe' weights
    MODEL_A_WEIGHTS = "IMAGENET1K_V1"

    # Stream B: Vision Transformer (Global Context Focus)
    MODEL_B_NAME = "vit_l_16"
    # Using SWAG (Supervised Weakly from AGgregated hashtags) weights
    MODEL_B_WEIGHTS = "IMAGENET1K_SWAG_E2E_V1"

    # ==========================================
    # Data Views / Preprocessing
    # ==========================================
    # The target input size for all model forward passes
    INPUT_SIZE = 224

    # View 1: Global View
    # Strategy: Resize (Squish) entire image to target size
    GLOBAL_VIEW_SIZE = 224

    # View 2: Standard View
    # Strategy: Resize to slightly larger, then Center Crop
    STANDARD_RESIZE = 232
    STANDARD_CROP = 224

    # View 3: Robust Local View
    # Strategy: Resize to significantly larger, then FiveCrop (Corners + Center)
    ROBUST_RESIZE = 288
    ROBUST_CROP = 224

    # ==========================================
    # Caching Filenames
    # ==========================================
    # Standardized names for cached numpy arrays to ensure modular compatibility

    # Stream A (ConvNeXt) Embeddings
    CACHE_A_TRAIN_EMB = os.path.join(WORK_DIR, "stream_a_train_emb.npy")
    CACHE_A_VAL_EMB = os.path.join(WORK_DIR, "stream_a_val_emb.npy")
    CACHE_A_TEST_EMB = os.path.join(WORK_DIR, "stream_a_test_emb.npy")

    # Stream B (ViT) Embeddings
    CACHE_B_TRAIN_EMB = os.path.join(WORK_DIR, "stream_b_train_emb.npy")
    CACHE_B_VAL_EMB = os.path.join(WORK_DIR, "stream_b_val_emb.npy")
    CACHE_B_TEST_EMB = os.path.join(WORK_DIR, "stream_b_test_emb.npy")

    # Labels (Shared across streams)
    CACHE_TRAIN_LABELS = os.path.join(WORK_DIR, "train_labels.npy")
    CACHE_VAL_LABELS = os.path.join(WORK_DIR, "val_labels.npy")

    # IDs (For alignment verification)
    CACHE_TRAIN_IDS = os.path.join(WORK_DIR, "train_ids.npy")
    CACHE_VAL_IDS = os.path.join(WORK_DIR, "val_ids.npy")
    CACHE_TEST_IDS = os.path.join(WORK_DIR, "test_ids.npy")

    # Saved Models
    MODEL_A_HEAD_PATH = os.path.join(WORK_DIR, "model_a_head.joblib")
    MODEL_B_HEAD_PATH = os.path.join(WORK_DIR, "model_b_head.joblib")
    ENSEMBLE_WEIGHTS_PATH = os.path.join(WORK_DIR, "ensemble_weights.json")

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    # Logistic Regression CV settings
    CV_FOLDS = 5
    MAX_ITER = 2000
    # Number of C values to try in log-space
    CS_COUNT = 10

    # Debugging
    # Set to an integer (e.g., 100) to restrict dataset size for rapid testing
    # Set to None for full production run
    DEBUG_SAMPLE_SIZE = None
