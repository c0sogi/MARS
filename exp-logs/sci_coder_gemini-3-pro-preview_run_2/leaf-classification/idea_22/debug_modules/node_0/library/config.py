import os


class Config:
    """
    Global configuration for the Leaf Classification task.
    Centralizes file paths, model hyperparameters, and feature definitions.
    """

    # =========================================================================
    # GLOBAL SETTINGS
    # =========================================================================
    RANDOM_SEED = 42
    N_JOBS = 12  # Access to 12 vCPUs
    DEBUG = False  # Set to True to run on a subset of data for quick testing

    # =========================================================================
    # DIRECTORIES
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_22"
    SUBMISSION_DIR = "./submission"

    # Image directory (metadata contains relative paths like 'images/1.jpg')
    IMAGES_BASE_DIR = INPUT_DIR

    # =========================================================================
    # FILE PATHS
    # =========================================================================
    # Metadata files generated by the provided script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Sample submission
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Final Output
    SUBMISSION_FILE_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # CACHING PATHS (Parquet/Numpy)
    # =========================================================================
    # Stores the extracted morphometric features and processed datasets
    CACHE_TRAIN_PATH = os.path.join(WORKING_DIR, "train_processed.parquet")
    CACHE_VAL_PATH = os.path.join(WORKING_DIR, "val_processed.parquet")
    CACHE_TEST_PATH = os.path.join(WORKING_DIR, "test_processed.parquet")

    # =========================================================================
    # FEATURE DEFINITIONS
    # =========================================================================
    # Provided Feature Groups (64 dimensions each)
    MARGIN_COLS = [f"margin_{i+1}" for i in range(64)]
    SHAPE_COLS = [f"shape_{i+1}" for i in range(64)]
    TEXTURE_COLS = [f"texture_{i+1}" for i in range(64)]

    # Custom Morphometric Features (Source B)
    HU_MOMENTS_COLS = [f"hu_moment_{i}" for i in range(7)]
    GEOMETRIC_SCALARS_COLS = ["aspect_ratio", "solidity", "extent", "eccentricity"]

    # =========================================================================
    # MODEL HYPERPARAMETERS
    # =========================================================================
    # Precision setting: Critical for stability in generative models
    DTYPE = "float64"

    # Gaussianization
    POWER_TRANSFORMER_METHOD = "yeo-johnson"

    # Expert 1 & 2 & 3: Linear Discriminant Analysis
    # Using 'lsqr' with 'auto' shrinkage (Ledoit-Wolf) for high-dimensional stability
    LDA_PARAMS = {"solver": "lsqr", "shrinkage": "auto"}

    # Expert 4: Logistic Regression (Calibrated)
    # L2 regularization with lbfgs solver
    LOGREG_PARAMS = {
        "penalty": "l2",
        "solver": "lbfgs",
        "C": 10.0,  # Moderate regularization
        "max_iter": 5000,  # Ensure convergence
        "class_weight": "balanced",
        "n_jobs": N_JOBS,
    }

    # Ensemble Selection
    SELECTION_ITERATIONS = 20  # Number of steps for Greedy Forward Selection

    @classmethod
    def setup(cls):
        """Creates necessary working directories."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
