import os
import numpy as np


class Config:
    """
    Central configuration for the Discriminative-Manifold Generative Ensemble (DMGE).
    Defines global constants, file paths, and model hyperparameters.
    """

    # ==========================================
    # Global Reproducibility & Precision
    # ==========================================
    RANDOM_SEED = 42
    # Use double precision to minimize numerical noise at metric floor
    FLOAT_TYPE = np.float64

    # ==========================================
    # Directory Structure
    # ==========================================
    INPUT_DIR = "./input"
    IMAGES_DIR = os.path.join(INPUT_DIR, "images")
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Specific cache directory for Idea 47 (DMGE)
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_47")

    # Submission output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Data File Paths
    # ==========================================
    # Metadata files generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Sample submission for format reference
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # ==========================================
    # Data Processing Parameters
    # ==========================================
    # Image Polarity Correction
    # If mean intensity of corners > threshold, invert image (Leaf should be white, bg black)
    IMG_POLARITY_THRESHOLD = 0.5

    # Feature Dimensions
    N_PROVIDED_FEATURES = 192  # 64 Margin + 64 Shape + 64 Texture

    # ==========================================
    # Expert Topology Hyperparameters
    # ==========================================

    # General LDA Settings
    # 'lsqr' solver is required for shrinkage
    LDA_SOLVER = "lsqr"

    # Topology A: Marginal Statistical Anchors
    # Uses fixed shrinkage to stabilize covariance estimation
    TOPOLOGY_A_SHRINKAGE_CANDIDATES = [0.001, 0.01]

    # Topology B: Rotational Statistical Experts
    # PCA without whitening to preserve variance scale before PowerTransform
    TOPOLOGY_B_PCA_WHITEN = False

    # Topology C: Discriminative-Interaction Experts
    # Projects to discriminative subspace before polynomial expansion
    TOPOLOGY_C_LDA_COMPONENTS = 25
    TOPOLOGY_C_POLY_DEGREE = 2

    # Topology D: Polynomial Physical Experts
    # Polynomial expansion of morphometric features
    TOPOLOGY_D_POLY_DEGREE = 2

    # Topology E: Robust Distributional Experts
    # Quantile transformation parameters
    TOPOLOGY_E_N_QUANTILES = 50
    TOPOLOGY_E_OUTPUT_DIST = "normal"

    # ==========================================
    # Ensemble Selection Strategy
    # ==========================================
    # Greedy Forward Selection parameters
    SELECTION_MAX_ITER = 100  # Maximum number of experts to add to ensemble
    SELECTION_TOLERANCE = 1e-6  # Minimum improvement required to continue

    @classmethod
    def initialize(cls):
        """
        Initialize the environment by creating necessary directories.
        Must be called at the start of the pipeline.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        print(f"Directories initialized: {cls.CACHE_DIR}, {cls.SUBMISSION_DIR}")
