import os
import torch


class Config:
    """
    Central configuration class for the Missing Word Prediction task.
    Holds all hyperparameters, file paths, and hardware settings.
    """

    # --------------------------------------------------------------------------
    # General Settings
    # --------------------------------------------------------------------------
    SEED = 42
    PROJECT_NAME = "missing_word_prediction"

    # --------------------------------------------------------------------------
    # Paths
    # --------------------------------------------------------------------------
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_1"
    SUBMISSION_DIR = "./submission"

    # Data Files (Parquet format as generated by metadata script)
    TRAIN_DATA_PATH = os.path.join(METADATA_DIR, "train.parquet")
    VAL_DATA_PATH = os.path.join(METADATA_DIR, "val.parquet")
    TEST_DATA_PATH = os.path.join(METADATA_DIR, "test.parquet")

    # Output Artifacts
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model")
    TOKENIZER_SAVE_PATH = os.path.join(WORKING_DIR, "tokenizer")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Model Architecture
    # --------------------------------------------------------------------------
    MODEL_NAME = "distilroberta-base"
    MAX_SEQ_LEN = 128  # Sufficient for sentence-level tasks

    # --------------------------------------------------------------------------
    # Data Processing
    # --------------------------------------------------------------------------
    MLM_PROBABILITY = 0.15  # Standard masking probability for MLM

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    # A100 40GB allows for larger batch sizes
    TRAIN_BATCH_SIZE = 128
    VAL_BATCH_SIZE = 256

    # Optimization
    LEARNING_RATE = 5e-5
    WEIGHT_DECAY = 0.01
    ADAM_EPSILON = 1e-6
    MAX_GRAD_NORM = 1.0
    WARMUP_RATIO = 0.06

    # Duration
    # Given 24M training samples, 1 epoch is substantial.
    EPOCHS = 1
    # Optional: limit steps for debugging or faster iteration within time limit
    MAX_STEPS = -1

    # Logging & Saving
    LOGGING_STEPS = 1000
    EVAL_STEPS = 5000
    SAVE_STEPS = 5000
    SAVE_TOTAL_LIMIT = 2  # Keep only recent checkpoints to save space

    # --------------------------------------------------------------------------
    # Inference Hyperparameters
    # --------------------------------------------------------------------------
    INFERENCE_BATCH_SIZE = 128

    # --------------------------------------------------------------------------
    # Hardware & Performance
    # --------------------------------------------------------------------------
    USE_FP16 = True  # Enable Mixed Precision training
    NUM_WORKERS = 8  # 12 vCPUs available
    PIN_MEMORY = True

    @classmethod
    def setup(cls):
        """
        Ensures all necessary working and output directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

    @staticmethod
    def get_device():
        """
        Returns the appropriate torch device.
        """
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")


# Initialize directories on module import
Config.setup()
