import os
import random
import numpy as np
import torch


class Config:
    """
    Centralized configuration for the Densely Connected Hybrid Network (DCHN) pipeline.
    """

    # =========================================================================
    # Reproducibility
    # =========================================================================
    SEED = 42

    # =========================================================================
    # File System Paths
    # =========================================================================
    # Base Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_4"
    SUBMISSION_DIR = "./submission"

    # Raw Data Files
    TRAIN_JSON = os.path.join(INPUT_DIR, "train.json")
    TEST_JSON = os.path.join(INPUT_DIR, "test.json")

    # Metadata Files (Generated by previous steps)
    TRAIN_META = os.path.join(METADATA_DIR, "train.csv")
    VAL_META = os.path.join(METADATA_DIR, "val.csv")
    TEST_META = os.path.join(METADATA_DIR, "test.csv")

    # Output Files
    # Model checkpoint
    MODEL_PATH = os.path.join(WORKING_DIR, "sahcn_model.pth")
    # Cached processed data (numpy archive)
    PROCESSED_DATA_PATH = os.path.join(WORKING_DIR, "processed_data.npz")
    # Final submission file
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Parameters
    # =========================================================================
    IMG_HEIGHT = 75
    IMG_WIDTH = 75
    # Input channels: Band 1, Band 2, and Mean(Band 1, Band 2)
    IN_CHANNELS = 3
    NUM_CLASSES = 1

    # Imputation strategy for incidence angle
    INC_ANGLE_MISSING_VAL = 0.0  # Placeholder, will be replaced by median in processing

    # =========================================================================
    # Model Hyperparameters (Custom DenseNet)
    # =========================================================================
    # DenseNet Backbone
    GROWTH_RATE = 12
    # Number of layers in each dense block.
    # 3 blocks allows for 75 -> 37 -> 18 -> 9 spatial reduction before GAP.
    BLOCK_CONFIG = (6, 12, 16)
    # Compression factor (theta) for transition layers
    COMPRESSION = 0.5

    # Fusion Head
    DROPOUT_RATE = 0.2
    META_HIDDEN_DIM = 64

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 32
    LEARNING_RATE = 1e-3
    NUM_EPOCHS = 50

    # Early Stopping
    PATIENCE = 12

    # Learning Rate Scheduler (ReduceLROnPlateau)
    LR_FACTOR = 0.5
    LR_PATIENCE = 4
    MIN_LR = 1e-6

    # =========================================================================
    # Compute & Debugging
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 2

    # Debug flag to run on a small subset of data
    DEBUG = False
    DEBUG_SUBSET_SIZE = 100

    @classmethod
    def setup(cls):
        """
        Performs initial setup: creates directories and sets random seeds
        for reproducibility.
        """
        # Create directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set random seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)

        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.cuda.manual_seed_all(cls.SEED)
            # Ensure deterministic behavior
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

        print(f"Configuration loaded. Device: {cls.DEVICE}, Seed: {cls.SEED}")
        print(f"Working Directory: {cls.WORKING_DIR}")
