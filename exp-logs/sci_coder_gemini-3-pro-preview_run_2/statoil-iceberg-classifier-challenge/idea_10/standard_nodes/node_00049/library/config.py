import os
import torch


class Config:
    """
    Configuration for the Multi-Level Constrained-Width Network (MLCW-Net) solution.
    """

    # ==========================================
    # 1. FILE SYSTEM & PATHS
    # ==========================================
    # Base Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_10"

    # Create necessary writable directories
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    SUBMISSION_DIR = "./submission"

    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Input Data Paths
    TRAIN_JSON = os.path.join(INPUT_DIR, "train.json")
    TEST_JSON = os.path.join(INPUT_DIR, "test.json")

    # Metadata Paths (Generated by metadata script)
    TRAIN_META_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Output Paths
    PROCESSED_DATA_PATH = os.path.join(CACHE_DIR, "processed_data.npz")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # 2. DATA CONFIGURATION
    # ==========================================
    # Image Dimensions
    HEIGHT = 75
    WIDTH = 75
    CHANNELS = 3  # Band 1 (HH), Band 2 (HV), Average ((HH+HV)/2)

    # Preprocessing
    USE_AUGMENTATION = True
    ROTATION_ANGLES = [0, 90, 180, 270]  # Discrete rotations

    # ==========================================
    # 3. MODEL ARCHITECTURE (MLCW-Net)
    # ==========================================
    # Channel-Contracting Backbone: Bell Curve Strategy
    # Stage 1 -> Stage 2 -> Stage 3 -> Stage 4
    BACKBONE_FILTERS = [32, 48, 64, 32]

    # Feature Fusion
    # Level A: Extracted from Stage 3 (64 filters) -> Adaptive Pool
    # Level B: Extracted from Stage 4 (32 filters) -> Already Pooled
    FUSION_POOL_SIZE = 4  # Target spatial dim (4x4)

    # Classification Head
    DROPOUT_RATE = 0.2
    NUM_CLASSES = 1  # Binary (Sigmoid)

    # ==========================================
    # 4. TRAINING HYPERPARAMETERS
    # ==========================================
    SEED = 42
    NUM_FOLDS = 5

    # Optimization
    BATCH_SIZE = 32
    LEARNING_RATE = 2e-4
    NUM_EPOCHS = 100

    # Regularization & Callbacks
    PATIENCE = 15  # Early Stopping patience
    SCHEDULER_PATIENCE = 5  # ReduceLROnPlateau patience
    SCHEDULER_FACTOR = 0.5

    # Compute
    NUM_WORKERS = 2
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================
    # 5. DEBUGGING
    # ==========================================
    # Set to True to train on a small subset for rapid testing
    DEBUG = False
    DEBUG_SUBSET_SIZE = 100
