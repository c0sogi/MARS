import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration class for the SI-WBN (Spatially-Integrated Wide-Body Network) solution.
    Centralizes all file paths, model hyperparameters, and training settings.
    """

    # ==========================================
    # 1. FILE PATHS & DIRECTORIES
    # ==========================================
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_25"
    SUBMISSION_DIR = "./submission"

    # Raw Data Files
    TRAIN_JSON = os.path.join(INPUT_DIR, "train.json")
    TEST_JSON = os.path.join(INPUT_DIR, "test.json")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Files (Generated by metadata script)
    TRAIN_META = os.path.join(METADATA_DIR, "train.csv")
    VAL_META = os.path.join(METADATA_DIR, "val.csv")
    TEST_META = os.path.join(METADATA_DIR, "test.csv")

    # Output Files
    CACHE_PATH = os.path.join(WORKING_DIR, "processed_data.npz")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # 2. DATA SPECIFICATIONS
    # ==========================================
    IMAGE_SIZE = 75
    # Raw bands in JSON
    RAW_BANDS = 2  # HH, HV
    # Input channels to model (HH, HV, Avg)
    INPUT_CHANNELS = 3

    # ==========================================
    # 3. MODEL HYPERPARAMETERS (SI-WBN)
    # ==========================================
    # Sustained Width Strategy
    FILTERS = [64, 128, 128, 64]
    # Regularization
    DROPOUT = 0.5
    # Readout dimensions (Quadrant Max Pooling: 2x2 grid * 128 filters)
    FC_DIM = 512

    # ==========================================
    # 4. TRAINING HYPERPARAMETERS
    # ==========================================
    SEED = 42
    NUM_FOLDS = 5
    BATCH_SIZE = 32
    EPOCHS = 100
    # "Low and Slow" optimization
    LEARNING_RATE = 2e-4
    PATIENCE = 15

    # Debugging flags
    DEBUG = False
    DEBUG_SIZE = 100  # Number of samples to use if DEBUG is True

    # ==========================================
    # 5. HARDWARE
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Number of workers for DataLoader (conservative for shared envs)
    NUM_WORKERS = 2


def set_seed(seed=Config.SEED):
    """
    Sets the random seed for reproducibility across Python, NumPy, and PyTorch.

    Args:
        seed (int): The seed value to use. Defaults to Config.SEED.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)
        # Ensure deterministic behavior for cuDNN
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False


# Ensure necessary directories exist
os.makedirs(Config.WORKING_DIR, exist_ok=True)
os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
