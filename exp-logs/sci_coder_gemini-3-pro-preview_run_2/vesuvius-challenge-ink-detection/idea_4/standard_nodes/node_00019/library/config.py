import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration for the Vesuvius Ink Detection Task using Hybrid-Projection U-Net.
    Centralizes file paths, model hyperparameters, and data processing constants.
    """

    # =========================================================================
    # Directories and File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_4"

    # Ensure the working directory exists for caching and checkpoints
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Metadata Files (Generated by the provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output Files
    SUBMISSION_PATH = "./submission.csv"  # Required to be in the home directory
    CHECKPOINT_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # =========================================================================
    # Data Preprocessing & Hybrid-Projection Strategy
    # =========================================================================
    TILE_SIZE = 512
    STRIDE = 512

    # Z-Slice Ranges for 4-Channel Input
    # Python ranges are exclusive at the end, so range(22, 43) includes slices 22 through 42.

    # Channel 1: Global Anchor (Slices 22-42)
    # Provides robust, high-contrast signal to prevent dilution.
    Z_GLOBAL_RANGE = range(22, 43)

    # Channel 2: Top Slab (Slices 22-28)
    Z_SLAB1_RANGE = range(22, 29)

    # Channel 3: Middle Slab (Slices 29-35)
    Z_SLAB2_RANGE = range(29, 36)

    # Channel 4: Bottom Slab (Slices 36-42)
    Z_SLAB3_RANGE = range(36, 43)

    # =========================================================================
    # Model Architecture
    # =========================================================================
    ENCODER_NAME = "resnet34"
    ENCODER_WEIGHTS = "imagenet"
    IN_CHANNELS = 4  # Global + 3 Slabs
    CLASSES = 1
    ACTIVATION = None  # Use None to return logits (for BCEWithLogitsLoss)

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    SEED = 42
    BATCH_SIZE = 32  # A100 40GB can handle 32 with ResNet34
    EPOCHS = 15
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-5

    # Hardware settings
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 12  # Use all available vCPUs

    # Scheduler settings
    SCHEDULER_PATIENCE = 3
    SCHEDULER_FACTOR = 0.5

    # Inference settings
    THRESHOLD = 0.5

    # =========================================================================
    # Debugging and Development
    # =========================================================================
    # Set DEBUG to True to use a small subset of data for rapid testing
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 200  # Number of train/val samples to use in debug mode
    DEBUG_EPOCHS = 2  # Number of epochs in debug mode

    @staticmethod
    def set_seed(seed=42):
        """
        Sets fixed random seeds for reproducibility.
        """
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        torch.cuda.manual_seed(seed)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False
        os.environ["PYTHONHASHSEED"] = str(seed)
