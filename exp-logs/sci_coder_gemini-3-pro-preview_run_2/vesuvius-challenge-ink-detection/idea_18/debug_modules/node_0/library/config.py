import os
import torch


class Config:
    """
    Configuration module for Idea 18: Multi-View Robust SegFormer (MiT-B2).
    Defines global hyperparameters, constants, and data processing logic.
    """

    # =========================================================================
    # Reproducibility & Compute
    # =========================================================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Using 4 workers as a safe default for the available 12 vCPUs
    NUM_WORKERS = 4

    # =========================================================================
    # File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata CSVs generated by the provided metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VALID_METADATA_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Working directory for this specific experiment (Idea 18)
    # Used for caching processed data and saving model checkpoints
    WORKING_DIR = "./working/idea_18"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Output submission file
    SUBMISSION_PATH = "./submission.csv"

    # =========================================================================
    # Data Strategy: Multi-View & Z-Slicing
    # =========================================================================
    TILE_SIZE = 512

    # Input Interface: 3 Channels
    # Each channel is a projection of a "slab" of slices.
    IN_CHANNELS = 3

    # Slab Configuration: 12 slices thick, 50% overlap (stride 6)
    SLAB_THICKNESS = 12
    CHANNEL_STRIDE = 6

    # Discrete Multi-View Sampling
    # Defines the starting Z-index for the entire block for each view.
    # View A (High):   Starts at 16 (Covers 16-40)
    # View B (Center): Starts at 20 (Covers 20-44)
    # View C (Low):    Starts at 24 (Covers 24-48)
    VIEWS = {"A": 16, "B": 20, "C": 24}

    @staticmethod
    def get_channel_ranges(view_start_index):
        """
        Calculates the slice ranges for the 3 input channels based on the
        view's starting index.

        Args:
            view_start_index (int): The Z-index where the view begins.

        Returns:
            list of tuples: [(start, end), (start, end), (start, end)]
            Indices are suitable for python slicing (start inclusive, end exclusive).
        """
        ranges = []
        for i in range(Config.IN_CHANNELS):
            # Channel start shifts by the stride
            s = view_start_index + (i * Config.CHANNEL_STRIDE)
            # Channel end is start + thickness
            e = s + Config.SLAB_THICKNESS
            ranges.append((s, e))
        return ranges

    # =========================================================================
    # Model Architecture
    # =========================================================================
    # Architecture: SegFormer with MiT-B2 backbone and MLP Decoder
    MODEL_ARCH = "segformer"
    BACKBONE = "mit_b2"
    DECODER = "mlp"
    PRETRAINED = True
    NUM_CLASSES = 1

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    # Batch size set to 8 to maximize updates per epoch
    BATCH_SIZE = 8

    # Conservative learning rate for stability
    LEARNING_RATE = 6e-5

    # Default training duration
    NUM_EPOCHS = 15

    # Optimizer settings
    OPTIMIZER = "AdamW"
    WEIGHT_DECAY = 1e-2

    # Loss Function: Balanced BCE + Dice
    LOSS_FN = "BCE_Dice"

    # Early Stopping
    PATIENCE = 5

    # =========================================================================
    # Inference & Evaluation
    # =========================================================================
    # Binary threshold for final predictions
    THRESHOLD = 0.5

    # Metric parameter (F0.5 Score weights precision higher)
    METRIC_BETA = 0.5

    # =========================================================================
    # Debugging & Development
    # =========================================================================
    # Controls to limit dataset size for rapid debugging.
    # Set to an integer (e.g., 100) to only use that many samples.
    # Set to None to use the full dataset.
    MAX_TRAIN_SAMPLES = None
    MAX_VAL_SAMPLES = None
