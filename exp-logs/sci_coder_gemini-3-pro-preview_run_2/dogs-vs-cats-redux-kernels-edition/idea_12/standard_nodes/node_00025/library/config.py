import os
import torch


class Config:
    """
    Configuration class for Tri-Modal Heterogeneous Stacking Strategy with Model Soups.
    Centralizes all parameters for data, model, training, and inference.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    seed = 42
    debug = False  # Set to True to run on a small subset for debugging
    exp_name = "idea_12"

    # =========================================================================
    # Directories & Paths
    # =========================================================================
    # Input directories (Read-Only)
    input_dir = "./input"
    train_images_dir = os.path.join(input_dir, "train")
    test_images_dir = os.path.join(input_dir, "test")

    # Metadata (Generated by previous steps)
    metadata_dir = "./metadata"
    train_metadata_path = os.path.join(metadata_dir, "train.csv")
    val_metadata_path = os.path.join(metadata_dir, "val.csv")
    test_metadata_path = os.path.join(metadata_dir, "test.csv")

    # Working directories (Write access)
    working_dir = os.path.join("./working", exp_name)
    checkpoint_dir = os.path.join(working_dir, "checkpoints")
    oof_dir = os.path.join(working_dir, "oof")
    cache_dir = os.path.join(working_dir, "cache")

    # Submission
    submission_dir = "./submission"
    submission_path = os.path.join(submission_dir, "submission.csv")

    # =========================================================================
    # Data Parameters
    # =========================================================================
    img_size = 224
    num_classes = 2  # Dog (1) vs Cat (0)

    # Augmentation
    # RandomResizedCrop with min scale 0.8 as per strategy
    resize_crop_scale = (0.8, 1.0)
    # Mixup and CutMix parameters
    mixup_alpha = 0.2
    cutmix_alpha = 1.0
    mixup_prob = 0.5  # Probability of applying mixup/cutmix

    # Data Loading
    batch_size = 64  # A100 40GB can handle 64 for these "Small" models
    num_workers = 4  # 12 vCPUs available

    # =========================================================================
    # Model Architecture
    # =========================================================================
    # Tri-Modal Ensemble: ConvNeXt, Swin Transformer, EfficientNetV2 (MBConv)
    # Using timm compatible names
    models = [
        "convnext_small.fb_in22k",
        "swin_small_patch4_window7_224",
        "tf_efficientnetv2_s.in21k",
    ]

    # =========================================================================
    # Training Strategy
    # =========================================================================
    n_folds = 5
    epochs = 20
    # Model Soups: Average weights from these last N epochs
    soup_epochs = 3

    # Optimization
    optimizer_name = "AdamW"
    lr = 1e-4
    weight_decay = 0.05  # Standard for ViTs/ConvNeXt
    min_lr = 1e-6
    scheduler_name = "CosineAnnealingLR"

    # Meta-Learner
    meta_learner_params = {
        "C": 1.0,
        "penalty": "l2",
        "solver": "lbfgs",
        "max_iter": 1000,
    }

    # =========================================================================
    # Compute
    # =========================================================================
    device = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup_directories(cls):
        """Creates the necessary working directories."""
        os.makedirs(cls.working_dir, exist_ok=True)
        os.makedirs(cls.checkpoint_dir, exist_ok=True)
        os.makedirs(cls.oof_dir, exist_ok=True)
        os.makedirs(cls.cache_dir, exist_ok=True)
        os.makedirs(cls.submission_dir, exist_ok=True)
        print(f"Directories setup at {cls.working_dir}")
