import os
import torch


class Config:
    """
    Configuration class for the Asymmetric Grouped EfficientNet pipeline.
    """

    # --------------------------------------------------------------------------
    # Reproducibility
    # --------------------------------------------------------------------------
    SEED = 42

    # --------------------------------------------------------------------------
    # Compute Environment
    # --------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Using 4 workers as specified in the idea description for dynamic loading
    NUM_WORKERS = 4

    # --------------------------------------------------------------------------
    # File Paths & Directories
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the provided script
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Working directory for caching intermediate data and saving models
    # Idea 11 corresponds to the current architectural iteration
    WORKING_DIR = "./working/idea_11"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Model checkpoint path
    CHECKPOINT_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # Submission output
    SUBMISSION_DIR = "./submission"
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Data Preprocessing & ROI Selection
    # --------------------------------------------------------------------------
    # Image dimensions
    IMG_SIZE = 256

    # ROI Selection Logic
    # We use FLAIR to find the ROI.
    # We take the Anchor slice, and neighbors at +/- STRIDE.
    STRIDE = 5
    NUM_SLICES_PER_MODALITY = 3  # (Anchor-5, Anchor, Anchor+5)

    # Depth range to search for the tumor (15% to 85% of the Z-axis)
    ROI_SEARCH_MIN = 0.15
    ROI_SEARCH_MAX = 0.85

    # Smoothing window for intensity profile to avoid spikes
    SMOOTHING_WINDOW = 5

    # --------------------------------------------------------------------------
    # Model Architecture
    # --------------------------------------------------------------------------
    BACKBONE = "efficientnet_b0"

    # Input channels: 4 modalities * 3 slices = 12 channels
    IN_CHANNELS = 12

    # Grouped Convolutions: 1 group per modality (4 groups total)
    # This isolates FLAIR, T1w, T1wCE, T2w in the stem
    GROUPS = 4

    NUM_CLASSES = 1
    # Cite Lesson 00017: Explicit reconstruction of regularization.
    # Increased to 0.3 to combat overfitting observed in previous run.
    DROPOUT_RATE = 0.3

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    BATCH_SIZE = 32
    NUM_EPOCHS = 20

    # Optimization
    LEARNING_RATE = 1e-4
    # Aggressive weight decay as specified to prevent overfitting
    WEIGHT_DECAY = 1e-2

    # Early Stopping
    PATIENCE = 5

    # Augmentation
    # Rotation limited to +/- 15 degrees to preserve anatomical orientation
    ROTATION_DEGREES = 15

    # --------------------------------------------------------------------------
    # Debugging / Development
    # --------------------------------------------------------------------------
    # Set to True to train on a small subset for rapid iteration
    DEBUG = False
    DEBUG_SUBSET_SIZE = 50
