import os


class Config:
    """
    Global configuration for the Asymmetric Grouped EfficientNet-B0 pipeline.
    Implements the settings for Idea 37: Circuit-Breaked Fidelity Cache & Grouped Stem.
    """

    # --------------------------------------------------------------------------
    # Reproducibility
    # --------------------------------------------------------------------------
    SEED = 42

    # --------------------------------------------------------------------------
    # File System & Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory for Idea 37 (caching and checkpoints)
    WORKING_DIR = "./working/idea_37"

    # Metadata Paths (Generated by provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output Paths
    # Ensure submission directory exists or is created in setup
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    BEST_MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # Caching Paths (Parquet/NPY for fidelity cache)
    # Using .npy for dense tensor data to avoid pickle overhead/security issues
    CACHE_TRAIN_DATA = os.path.join(WORKING_DIR, "train_data.npy")
    CACHE_TRAIN_LABELS = os.path.join(WORKING_DIR, "train_labels.npy")
    CACHE_VAL_DATA = os.path.join(WORKING_DIR, "val_data.npy")
    CACHE_VAL_LABELS = os.path.join(WORKING_DIR, "val_labels.npy")
    CACHE_TEST_DATA = os.path.join(WORKING_DIR, "test_data.npy")

    # --------------------------------------------------------------------------
    # Data Pipeline Settings
    # --------------------------------------------------------------------------
    # Modalities: FLAIR is the geometric anchor
    MODALITIES = ["FLAIR", "T1w", "T1wCE", "T2w"]

    # ROI Selection
    ROI_DEPTH_MIN = 0.15  # 15% depth
    ROI_DEPTH_MAX = 0.85  # 85% depth
    ROI_METHOD = "sum_intensity_raw"  # Use raw sum of intensity

    # Stacking Logic
    NUM_SLICES_PER_MODALITY = 3  # Anchor-5, Anchor, Anchor+5
    STRIDE = 5

    # Input Dimensions
    IMG_SIZE = 224  # Standard for EfficientNet-B0
    # Total Channels = 4 modalities * 3 slices = 12
    IN_CHANNELS = len(MODALITIES) * NUM_SLICES_PER_MODALITY

    # Engineering Safety
    CIRCUIT_BREAKER_THRESHOLD = 0.01  # Fail if >1% of subjects are corrupt

    # --------------------------------------------------------------------------
    # Model Architecture
    # --------------------------------------------------------------------------
    MODEL_NAME = "efficientnet_b0"
    STEM_GROUPS = 4  # Grouped convolution in stem (1 per modality)
    DROPOUT_RATE = 0.5  # Regularized head

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    BATCH_SIZE = 32
    LEARNING_RATE = 1e-4  # Conservative LR
    WEIGHT_DECAY = 1e-2  # Aggressive decay
    NUM_EPOCHS = 20
    EARLY_STOPPING_PATIENCE = 5

    # Augmentation
    AUG_ROTATION_DEG = 15
    AUG_REFLECTION_PADDING = True

    # --------------------------------------------------------------------------
    # Inference / Debugging
    # --------------------------------------------------------------------------
    DEBUG_LIMIT = None  # Set to integer (e.g., 50) to limit dataset size for debugging
    TTA_ENABLED = True  # Test Time Augmentation (Flip H/V)

    @classmethod
    def setup(cls):
        """
        Create necessary directories for the pipeline.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
