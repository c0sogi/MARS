import os
import torch


class Config:
    # --------------------------------------------------------------------------
    # 1. General Setup & Reproducibility
    # --------------------------------------------------------------------------
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4

    # --------------------------------------------------------------------------
    # 2. File Paths & Directories
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    TRAIN_DIR = os.path.join(INPUT_DIR, "train")
    TEST_DIR = os.path.join(INPUT_DIR, "test")

    # Metadata generated by the provided script
    METADATA_DIR = "./metadata"
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Submission
    SUBMISSION_FILE = "./submission/submission.csv"
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Caching
    # We use a specific working directory for this idea to store cached ROIs/arrays
    WORKING_DIR = "./working/idea_32"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # Ensure working directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(os.path.dirname(SUBMISSION_FILE), exist_ok=True)

    # --------------------------------------------------------------------------
    # 3. Data Pipeline Hyperparameters
    # --------------------------------------------------------------------------
    # Image Dimensions
    IMG_SIZE = 224

    # Stacking Logic (Rule of 3)
    # We take 3 slices per modality: [Anchor - STRIDE, Anchor, Anchor + STRIDE]
    NUM_SLICES_PER_MODALITY = 3
    STRIDE = 5

    # Modalities
    MODALITIES = ["FLAIR", "T1w", "T1wCE", "T2w"]
    NUM_MODALITIES = len(MODALITIES)

    # Total Input Channels = Modalities * Slices per Modality
    # 4 * 3 = 12 channels
    IN_CHANNELS = NUM_MODALITIES * NUM_SLICES_PER_MODALITY

    # ROI Selection (Raw-Integral)
    ROI_MODALITY = "FLAIR"
    ROI_METHOD = "sum"  # Sum of pixel intensities
    ROI_DEPTH_RANGE = (0.15, 0.85)  # Exclude top/bottom 15% to avoid artifacts

    # Volumetric Anchor Jitter (Training Only)
    # Shifts the anchor index by a random offset to learn invariance
    ANCHOR_JITTER_RANGE = [-2, -1, 0, 1, 2]
    ANCHOR_JITTER_PROB = 1.0

    # Augmentation (Geometric)
    ROTATION_DEGREES = 15

    # --------------------------------------------------------------------------
    # 4. Model Hyperparameters
    # --------------------------------------------------------------------------
    MODEL_NAME = "efficientnet_b0"

    # Grouped Convolution Stem
    # We use groups=4 to isolate the 4 modalities (FLAIR, T1w, T1wCE, T2w)
    # Each group processes 3 channels (the 3 spatial slices of that modality)
    STEM_GROUPS = 4

    # Dropout for the classification head
    DROP_RATE = 0.5

    # --------------------------------------------------------------------------
    # 5. Training Hyperparameters
    # --------------------------------------------------------------------------
    BATCH_SIZE = 32
    EPOCHS = 10  # Default, can be overridden

    # Optimization
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2  # Aggressive weight decay

    # Early Stopping
    PATIENCE = 5

    # --------------------------------------------------------------------------
    # 6. Inference
    # --------------------------------------------------------------------------
    # Test-Time Augmentation
    USE_TTA = True  # Original + HFlip + VFlip
