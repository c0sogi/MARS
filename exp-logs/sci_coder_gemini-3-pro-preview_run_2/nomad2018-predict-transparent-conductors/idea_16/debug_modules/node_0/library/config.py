import os
import torch


class Config:
    """
    Configuration class for the Initial-Residual Crystal Graph Convolutional Network (IR-CGCNN) pipeline.
    Centralizes all hyperparameters, file paths, and constants.
    """

    # -------------------------------------------------------------------------
    # Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42

    # -------------------------------------------------------------------------
    # Directory Structure & Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the analysis script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Working directory for this specific experiment/idea
    WORKING_DIR = "./working/idea_16"

    # Cache directory for deterministic data processing (e.g., graph construction)
    # Stores .npz or .parquet files
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")

    # Directory for saving model checkpoints
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    BEST_MODEL_PATH = os.path.join(CHECKPOINT_DIR, "best_model.pth")

    # Directory for final submission
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure all writeable directories exist
    os.makedirs(CACHE_DIR, exist_ok=True)
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # -------------------------------------------------------------------------
    # Data Processing Hyperparameters
    # -------------------------------------------------------------------------
    # Graph Construction
    CUTOFF_RADIUS = 5.0  # Angstroms (Strictly set to 5.0 as per strategy)
    MAX_NEIGHBORS = (
        50  # Maximum number of neighbors per atom to maintain tensor regularity
    )

    # Targets to predict
    TARGET_COLS = ["formation_energy_ev_natom", "bandgap_energy_ev"]

    # Scaling
    # We will standardize targets. These paths store the scaler state.
    TARGET_SCALER_PATH = os.path.join(CACHE_DIR, "target_scaler.npz")

    # -------------------------------------------------------------------------
    # Model Architecture (IR-CGCNN)
    # -------------------------------------------------------------------------
    # Embedding dimensions
    ATOM_EMBEDDING_DIM = 128  # Width of node features
    EDGE_EMBEDDING_DIM = 128  # Width of edge features (projected from RBF)

    # RBF Expansion for distances
    RBF_BINS = 60  # Number of Gaussian basis functions
    RBF_MIN = 0.0  # Minimum distance
    RBF_MAX = 5.0  # Maximum distance (matches cutoff)

    # Network Depth
    NUM_LAYERS = 4  # Number of interaction blocks

    # Regularization within model
    DROPOUT = 0.1  # Dropout rate applied in interaction blocks

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 48  # Selected to introduce beneficial gradient noise
    LEARNING_RATE = 1e-3  # Standard starting LR
    WEIGHT_DECAY = 1e-4  # Decoupled weight decay for AdamW

    NUM_EPOCHS = 150  # Max training epochs
    PATIENCE = 15  # Early stopping patience (epochs without improvement)

    # Gradient clipping
    CLIP_GRAD_NORM = 1.0

    # -------------------------------------------------------------------------
    # Compute & Debugging
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Number of subprocesses for data loading

    # Set to an integer (e.g., 100) to train on a small subset for debugging.
    # Set to None for full training.
    DEBUG_SAMPLE_SIZE = None

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print("=" * 40)
        print(f"IR-CGCNN CONFIGURATION ({cls.DEVICE})")
        print("=" * 40)
        for attr in dir(cls):
            if not attr.startswith("__") and not callable(getattr(cls, attr)):
                print(f"{attr:<25} : {getattr(cls, attr)}")
        print("=" * 40)
