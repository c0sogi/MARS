import os
import torch


class Config:
    """
    Configuration class for the Smoothed Receiver-Aware Crystal Graph Network (SRA-CGN).
    Centralizes all hyperparameters, file paths, and execution settings.
    """

    # ==========================================
    # Directories and File Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for caching processed data and saving models
    # Using specific idea folder as requested
    WORKING_DIR = "./working/idea_31"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = "./submission"

    # Metadata files generated by the metadata script
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Sample submission file for formatting
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # ==========================================
    # Data Processing Parameters
    # ==========================================
    # Radius for neighbor search in the crystal lattice
    CUTOFF = 5.0  # Angstroms (Cite solution_lesson_node_00007)

    # Maximum number of neighbors to consider per atom (for memory efficiency)
    MAX_NEIGHBORS = 50

    # ==========================================
    # Model Architecture Hyperparameters
    # ==========================================
    # Dimension of atom embeddings (Cite solution_lesson_node_00039)
    ATOM_EMBEDDING_DIM = 128

    # Number of bins for Gaussian RBF edge expansion (Cite solution_lesson_node_00098)
    RBF_BINS = 32

    # Width of the Gaussian RBF filter (Cite solution_lesson_node_00098)
    RBF_SIGMA = 0.25

    # Number of Receiver-Aware Interaction Blocks
    NUM_INTERACTION_BLOCKS = 4

    # Dropout rate for regularization
    DROPOUT_RATE = 0.1

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    # Batch size (Cite solution_lesson_node_00005)
    BATCH_SIZE = 48

    # Initial learning rate
    LEARNING_RATE = 1e-3

    # Weight decay for AdamW optimizer (Cite solution_lesson_node_00003)
    WEIGHT_DECAY = 1e-4

    # Total number of training epochs
    NUM_EPOCHS = 150

    # Early stopping patience (epochs without improvement)
    EARLY_STOPPING_PATIENCE = 15

    # Learning rate scheduler parameters (ReduceLROnPlateau)
    SCHEDULER_FACTOR = 0.6
    SCHEDULER_PATIENCE = 5
    SCHEDULER_MIN_LR = 1e-6

    # ==========================================
    # System Settings
    # ==========================================
    # Random seed for reproducibility
    SEED = 42

    # Compute device
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Number of workers for data loading
    NUM_WORKERS = 4

    @classmethod
    def setup(cls):
        """
        Creates necessary directories for cache, checkpoints, and submissions.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        print(f"Configuration setup complete. Working directory: {cls.WORKING_DIR}")
        print(f"Device: {cls.DEVICE}")
