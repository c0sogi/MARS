import numpy as np
import pandas as pd
import torch
from torch.utils.data import TensorDataset, DataLoader
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import matthews_corrcoef
import os

from library.config import Config
from library.features import FeatureEngineer
from library.model import TD_SRN


class InferenceManager:
    """
    Handles post-training inference tasks:
    1. Refitting scalers on training data (to match training distribution).
    2. Optimizing the decision threshold on validation data.
    3. Generating predictions for the test set.
    """

    def __init__(self):
        self.device = torch.device(Config.DEVICE)
        self.feature_engineer = FeatureEngineer()
        self.scaler_kin = StandardScaler()
        self.scaler_vis = StandardScaler()
        self.model = None
        self.best_threshold = 0.5

    def _get_feature_columns(self):
        """
        Replicates the column ordering logic from the Trainer to ensure
        tensors are constructed identically.
        """
        # Base kinematic features from features.py
        base_features = [
            "x_position",
            "y_position",
            "speed",
            "acceleration",
            "sa",
            "direction_sin",
            "direction_cos",
            "orientation_sin",
            "orientation_cos",
        ]

        kin_cols = []
        # Loop through lags in the exact order generated by features.py
        for lag in range(-Config.WINDOW_HALF, Config.WINDOW_HALF + 1):
            suffix = f"_t{lag:+d}" if lag != 0 else ""

            # P1 features
            for feat in base_features:
                kin_cols.append(f"p1_{feat}{suffix}")

            # P2 features
            for feat in base_features:
                kin_cols.append(f"p2_{feat}{suffix}")

            # Distance feature
            kin_cols.append(f"dist{suffix}")

        # Visual features (not windowed)
        vis_cols = []
        vis_base = ["left", "top", "width", "height"]
        for feat in vis_base:
            vis_cols.append(f"p1_vis_{feat}")
        for feat in vis_base:
            vis_cols.append(f"p2_vis_{feat}")

        return kin_cols, vis_cols

    def _prepare_data(self, df, fit_scaler=False):
        """
        Extracts feature columns and applies scaling.
        """
        kin_cols, vis_cols = self._get_feature_columns()

        # Ensure float32
        X_kin = df[kin_cols].values.astype(np.float32)
        X_vis = df[vis_cols].values.astype(np.float32)

        if fit_scaler:
            X_kin = self.scaler_kin.fit_transform(X_kin)
            X_vis = self.scaler_vis.fit_transform(X_vis)
        else:
            X_kin = self.scaler_kin.transform(X_kin)
            X_vis = self.scaler_vis.transform(X_vis)

        return X_kin, X_vis

    def initialize_resources(self, debug_sample=None):
        """
        Loads the trained model and refits scalers using training data.
        """
        print("Initializing resources for inference...")

        # 1. Refit Scalers
        # We must load training data to establish the scaling parameters
        # used during training.
        print("Loading training features to fit scalers...")
        df_train = self.feature_engineer.generate_features(
            split="train", debug_sample=debug_sample
        )
        self._prepare_data(df_train, fit_scaler=True)

        # Free memory
        del df_train

        # 2. Load Model
        print(f"Loading model from {Config.MODEL_CHECKPOINT_PATH}...")
        self.model = TD_SRN().to(self.device)
        if os.path.exists(Config.MODEL_CHECKPOINT_PATH):
            state_dict = torch.load(
                Config.MODEL_CHECKPOINT_PATH, map_location=self.device
            )
            self.model.load_state_dict(state_dict)
        else:
            raise FileNotFoundError(
                f"Model checkpoint not found at {Config.MODEL_CHECKPOINT_PATH}"
            )

        self.model.eval()

    def find_best_threshold(self, debug_sample=None):
        """
        Predicts on validation set and performs grid search to maximize MCC.
        """
        print("Loading validation features for threshold optimization...")
        df_val = self.feature_engineer.generate_features(
            split="validation", debug_sample=debug_sample
        )

        X_kin, X_vis = self._prepare_data(df_val, fit_scaler=False)
        y_val = df_val["contact"].values.astype(np.float32)

        dataset = TensorDataset(torch.tensor(X_kin), torch.tensor(X_vis))
        loader = DataLoader(
            dataset,
            batch_size=Config.BATCH_SIZE,
            shuffle=False,
            num_workers=Config.NUM_WORKERS,
        )

        print("Running inference on validation set...")
        all_probs = []
        with torch.no_grad():
            for kin, vis in loader:
                kin = kin.to(self.device)
                vis = vis.to(self.device)
                logits = self.model(kin, vis)
                probs = torch.sigmoid(logits)
                all_probs.append(probs.cpu().numpy())

        all_probs = np.concatenate(all_probs).flatten()

        print("Optimizing threshold...")
        thresholds = np.arange(0.1, 0.9, 0.05)
        best_mcc = -1.0
        best_t = 0.5

        for t in thresholds:
            preds = (all_probs > t).astype(int)
            mcc = matthews_corrcoef(y_val, preds)
            if mcc > best_mcc:
                best_mcc = mcc
                best_t = t

        self.best_threshold = best_t
        print(f"Best Threshold: {best_t}")
        print(f"Validation MCC at Best Threshold: {best_mcc:.16f}")

    def generate_predictions(self):
        """
        Predicts on test set using the optimized threshold and saves submission.
        """
        print("Loading test features...")
        df_test = self.feature_engineer.generate_features(split="test")

        X_kin, X_vis = self._prepare_data(df_test, fit_scaler=False)

        dataset = TensorDataset(torch.tensor(X_kin), torch.tensor(X_vis))
        loader = DataLoader(
            dataset,
            batch_size=Config.BATCH_SIZE,
            shuffle=False,
            num_workers=Config.NUM_WORKERS,
        )

        print("Running inference on test set...")
        all_probs = []
        with torch.no_grad():
            for kin, vis in loader:
                kin = kin.to(self.device)
                vis = vis.to(self.device)
                logits = self.model(kin, vis)
                probs = torch.sigmoid(logits)
                all_probs.append(probs.cpu().numpy())

        all_probs = np.concatenate(all_probs).flatten()
        predictions = (all_probs > self.best_threshold).astype(int)

        # Create submission dataframe
        submission = pd.DataFrame(
            {"contact_id": df_test["contact_id"], "contact": predictions}
        )

        Config.setup_directories()
        submission.to_csv(Config.SUBMISSION_PATH, index=False)
        print(f"Submission saved to {Config.SUBMISSION_PATH}")
        print(f"Submission shape: {submission.shape}")
