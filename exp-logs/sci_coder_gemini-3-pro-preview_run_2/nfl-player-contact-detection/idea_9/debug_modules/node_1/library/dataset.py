import torch
from torch.utils.data import Dataset
import pandas as pd
import numpy as np
from library.config import Config


class NFLDataset(Dataset):
    """
    PyTorch Dataset for WIRK-Net.

    This dataset wrapper accepts the wide-format DataFrames generated by DataProcessor.
    It automatically separates continuous features from encoded categorical features
    (identified by the '_enc' suffix) to facilitate the hybrid input architecture
    of WIRK-Net (Embeddings + Dense Residuals).
    """

    def __init__(self, X, y=None):
        """
        Args:
            X (pd.DataFrame): Feature matrix containing both continuous and encoded categorical columns.
            y (pd.Series or np.ndarray, optional): Target labels.
        """
        # Identify categorical columns based on the naming convention from data_processing.py
        # Columns ending in '_enc' or containing '_enc_lag' are categorical indices.
        self.cat_feature_names = [c for c in X.columns if "_enc" in c]
        self.cont_feature_names = [
            c for c in X.columns if c not in self.cat_feature_names
        ]

        # Convert Categorical Features to LongTensor for Embedding Layers
        if self.cat_feature_names:
            # Ensure data is int64 for index lookups
            self.X_cat = torch.tensor(
                X[self.cat_feature_names].values, dtype=torch.long
            )
        else:
            # Create an empty tensor if no categorical features exist
            self.X_cat = torch.zeros((len(X), 0), dtype=torch.long)

        # Convert Continuous Features to FloatTensor
        # Ensure float32 for standard neural network weights
        self.X_cont = torch.tensor(
            X[self.cont_feature_names].values, dtype=torch.float32
        )

        # Process Targets
        if y is not None:
            if isinstance(y, pd.Series):
                y = y.values
            # Reshape to [N, 1] for BCEWithLogitsLoss / Focal Loss
            self.y = torch.tensor(y, dtype=torch.float32).unsqueeze(1)
        else:
            self.y = None

    def __len__(self):
        """Returns the total number of samples."""
        return len(self.X_cont)

    def __getitem__(self, idx):
        """
        Retrieves a sample at the given index.

        Returns:
            tuple: (x_cat, x_cont, y) if targets exist, otherwise (x_cat, x_cont)

            - x_cat (torch.Tensor): Categorical features [num_cat_features]
            - x_cont (torch.Tensor): Continuous features [num_cont_features]
            - y (torch.Tensor): Target label [1]
        """
        x_cat = self.X_cat[idx]
        x_cont = self.X_cont[idx]

        if self.y is not None:
            return x_cat, x_cont, self.y[idx]
        else:
            return x_cat, x_cont
