import os
import torch


class Config:
    """
    Global configuration for the Ego-Centric Deep Cross Network (EC-DCN) pipeline.
    Acts as the single source of truth for paths, hyperparameters, and feature definitions.
    """

    # ==========================================
    # 1. Paths & Directories
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_16"
    SUBMISSION_DIR = "./submission"

    # Ensure working and submission directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata Paths (Generated by previous steps)
    TRAIN_LABELS_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_LABELS_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Raw Data Paths
    TRAIN_TRACKING_PATH = os.path.join(INPUT_DIR, "train_player_tracking.csv")
    TEST_TRACKING_PATH = os.path.join(INPUT_DIR, "test_player_tracking.csv")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache/Artifact Paths (for intermediate storage)
    CACHE_TRAIN_FEATURES = os.path.join(WORKING_DIR, "train_features.parquet")
    CACHE_VAL_FEATURES = os.path.join(WORKING_DIR, "val_features.parquet")
    CACHE_TEST_FEATURES = os.path.join(WORKING_DIR, "test_features.parquet")

    SCALER_PATH = os.path.join(WORKING_DIR, "scaler.joblib")
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    THRESHOLD_PATH = os.path.join(WORKING_DIR, "best_threshold.npy")

    # ==========================================
    # 2. Reproducibility & Hardware
    # ==========================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Optimized for the available 12 vCPUs

    # ==========================================
    # 3. Data Processing & Feature Engineering
    # ==========================================
    # Temporal Window: t - WINDOW_SIZE ... t ... t + WINDOW_SIZE
    # Total frames = 2 * WINDOW_SIZE + 1
    WINDOW_SIZE = 5
    TOTAL_FRAMES = 2 * WINDOW_SIZE + 1

    # Columns to load from the raw tracking CSVs
    TRACKING_COLS = [
        "game_play",
        "step",
        "nfl_player_id",
        "x_position",
        "y_position",
        "speed",
        "acceleration",
        "orientation",
        "direction",
        "datetime",
    ]

    # Feature Names for the Model
    # These features are generated for each timestep in the window
    # and then flattened into a single vector.

    # 3.1 Ego-Centric Kinematics (Transformed to P1's Reference Frame)
    FEAT_EGO_DIST_LONG = "ego_dist_long"  # Longitudinal distance (Front/Back)
    FEAT_EGO_DIST_LAT = "ego_dist_lat"  # Lateral distance (Left/Right)
    FEAT_EGO_REL_VEL_LONG = "ego_rel_vel_long"  # Relative velocity Longitudinal
    FEAT_EGO_REL_VEL_LAT = "ego_rel_vel_lat"  # Relative velocity Lateral

    # 3.2 Geometric Invariants & High-Res Features
    FEAT_LOG_DIST = "log_distance"  # np.log1p(distance)
    FEAT_CLOSING_SPEED = "closing_speed"  # Rate of distance decrease

    # 3.3 Absolute Kinematics (Magnitudes only)
    # Retained to allow Cross Network to learn interactions between speed and impact
    FEAT_SPEED_1 = "speed_1"
    FEAT_ACCEL_1 = "acceleration_1"
    FEAT_SPEED_2 = "speed_2"
    FEAT_ACCEL_2 = "acceleration_2"

    # 3.4 Meta Features
    FEAT_IS_GROUND = "is_ground"

    # Ordered list of features per timestep
    STEP_FEATURES = [
        FEAT_EGO_DIST_LONG,
        FEAT_EGO_DIST_LAT,
        FEAT_EGO_REL_VEL_LONG,
        FEAT_EGO_REL_VEL_LAT,
        FEAT_LOG_DIST,
        FEAT_CLOSING_SPEED,
        FEAT_SPEED_1,
        FEAT_ACCEL_1,
        FEAT_SPEED_2,
        FEAT_ACCEL_2,
        FEAT_IS_GROUND,
    ]

    # Total Input Dimension = Features per step * Number of frames
    INPUT_DIM = len(STEP_FEATURES) * TOTAL_FRAMES

    # ==========================================
    # 4. Model Architecture (DCNv2)
    # ==========================================
    # Cross Branch
    NUM_CROSS_LAYERS = 3

    # Deep Branch
    DEEP_HIDDEN_LAYERS = [512, 256, 128]
    DROPOUT_RATE = 0.2

    # ==========================================
    # 5. Training Configuration
    # ==========================================
    BATCH_SIZE = 2048  # Large batch size for efficient tabular training
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    NUM_EPOCHS = 15
    EARLY_STOPPING_PATIENCE = 3

    # Focal Loss Parameters (for Class Imbalance)
    FOCAL_ALPHA = 0.25
    FOCAL_GAMMA = 2.0
