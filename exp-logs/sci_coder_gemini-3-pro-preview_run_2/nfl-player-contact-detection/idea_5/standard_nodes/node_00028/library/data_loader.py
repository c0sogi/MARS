import os
import numpy as np
import pandas as pd
import torch
import joblib
from torch.utils.data import Dataset
from sklearn.preprocessing import StandardScaler
from library.config import Config
from library.feature_engineering import process_data


class NFLDataset(Dataset):
    """
    PyTorch Dataset for NFL Player Contact Detection.
    Serves flattened wide feature vectors and binary targets.
    """

    def __init__(self, X, y=None):
        self.X = torch.FloatTensor(X)
        self.y = torch.FloatTensor(y) if y is not None else None

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        if self.y is not None:
            return self.X[idx], self.y[idx]
        return self.X[idx]


def get_feature_cols():
    """
    Generates the list of feature column names corresponding to the wide format.
    Matches the order generated by library.feature_engineering.create_wide_features.

    Format: {feature_name}_step{index}
    where index ranges from 0 to WINDOW_SIZE-1.
    """
    cols = []
    # create_wide_features iterates shifts from -half to +half
    # resulting in step indices from 0 to WINDOW_SIZE-1
    for i in range(Config.WINDOW_SIZE):
        for feat in Config.FEATURES_PER_STEP:
            cols.append(f"{feat}_step{i}")
    return cols


def prepare_data(split, load_cached_data=True):
    """
    Loads data, applies scaling, and returns a PyTorch Dataset.

    Args:
        split (str): 'train', 'validation', or 'test'.
        load_cached_data (bool): If True, attempts to load pre-processed numpy arrays and scaler.
                                 If False, regenerates data from source (via feature_engineering).

    Returns:
        NFLDataset: A dataset containing the scaled features and targets.
    """
    # Ensure working directory exists
    os.makedirs(Config.WORKING_DIR, exist_ok=True)

    # Paths for cached artifacts
    x_cache_path = os.path.join(Config.WORKING_DIR, f"X_{split}.npy")
    y_cache_path = os.path.join(Config.WORKING_DIR, f"y_{split}.npy")
    scaler_path = os.path.join(Config.WORKING_DIR, "scaler.joblib")

    # 1. Attempt to load from Numpy Cache
    if load_cached_data and os.path.exists(x_cache_path):
        # We assume if X exists, Y exists (unless it's test and we don't care, but we save it anyway)
        if os.path.exists(y_cache_path):
            print(f"Loading {split} data (X, y) from numpy cache...")
            X = np.load(x_cache_path)
            y = np.load(y_cache_path)
            return NFLDataset(X, y)
        elif split == "test":
            # Fallback for test if y wasn't saved (though logic below saves it)
            print(f"Loading {split} data (X) from numpy cache...")
            X = np.load(x_cache_path)
            return NFLDataset(X)

    # 2. Generate Data from Source (Parquet/CSV)
    print(f"Generating {split} data from source...")

    # process_data handles loading metadata/tracking, merging, feature engineering, and parquet caching
    df = process_data(split, load_cached_data=load_cached_data)

    # Select Feature Columns
    feature_cols = get_feature_cols()

    # Validate columns
    missing = [c for c in feature_cols if c not in df.columns]
    if missing:
        raise ValueError(
            f"Missing expected feature columns: {missing[:3]}... Check feature_engineering.py"
        )

    X = df[feature_cols].values.astype(np.float32)

    # Handle any remaining NaNs (e.g., from missing tracking data)
    X = np.nan_to_num(X, nan=0.0)

    # Extract Target
    y = None
    if "contact" in df.columns:
        y = df["contact"].values.astype(np.float32)

    # 3. Scaling
    if split == "train":
        print("Fitting StandardScaler on training data...")
        scaler = StandardScaler()
        X = scaler.fit_transform(X)
        print(f"Saving scaler to {scaler_path}...")
        joblib.dump(scaler, scaler_path)
    else:
        if not os.path.exists(scaler_path):
            raise FileNotFoundError(
                f"Scaler not found at {scaler_path}. You must run 'train' split first to fit the scaler."
            )
        print(f"Transforming {split} data using saved scaler...")
        scaler = joblib.load(scaler_path)
        X = scaler.transform(X)

    # 4. Save to Numpy Cache
    print(f"Saving {split} numpy arrays to cache...")
    np.save(x_cache_path, X)
    if y is not None:
        np.save(y_cache_path, y)

    return NFLDataset(X, y)
