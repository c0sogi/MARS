import os
import torch


class Config:
    """
    Configuration class for the Capacity-Scaled Transformer with Multi-Sample Dropout.
    Centralizes all hyperparameters, file paths, and model settings.
    """

    # --------------------------------------------------------------------------
    # General Configuration
    # --------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    NUM_WORKERS = 4
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # --------------------------------------------------------------------------
    # File Paths & Directories
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_5"

    # Ensure the working directory exists for caching and model saving
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Metadata Files (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VALID_METADATA_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Raw Text Sources (Used for lookups via 'id')
    TRAIN_TEXT_SOURCE = os.path.join(INPUT_DIR, "train.csv")
    TEST_TEXT_SOURCE = os.path.join(INPUT_DIR, "test.csv")

    # Submission
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure submission directory exists
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # --------------------------------------------------------------------------
    # Data Configuration
    # --------------------------------------------------------------------------
    ID_COL = "id"
    TEXT_COL = "comment_text"
    TARGET_COL = "target"
    SOURCE_FILE_COL = "source_file"

    # Identity attributes for Bias Metrics and Auxiliary Task
    IDENTITY_COLUMNS = [
        "male",
        "female",
        "homosexual_gay_or_lesbian",
        "christian",
        "jewish",
        "muslim",
        "black",
        "white",
        "psychiatric_or_mental_illness",
    ]

    # Auxiliary toxicity subtypes (available in train, not predicted for submission)
    AUX_COLUMNS = [
        "severe_toxicity",
        "obscene",
        "threat",
        "insult",
        "identity_attack",
        "sexual_explicit",
    ]

    # --------------------------------------------------------------------------
    # Model Architecture (RoBERTa-Large + Multi-Sample Dropout)
    # --------------------------------------------------------------------------
    MODEL_NAME = "roberta-large"
    HIDDEN_SIZE = 1024  # Hidden size for RoBERTa-Large
    NUM_LABELS = 1  # Primary task: Toxicity score
    NUM_AUX_LABELS = len(IDENTITY_COLUMNS)  # Auxiliary task: Identity detection

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    # Sequence Length: 320 is a good balance for Large models on A100
    # Device-side trimming will further optimize this.
    MAX_LEN = 320

    # Batch Sizes
    TRAIN_BATCH_SIZE = 16  # Adjusted for 40GB VRAM with Large model
    VALID_BATCH_SIZE = 32

    # Training Duration
    EPOCHS = 2  # Large models converge quickly; 2 epochs is usually sufficient

    # Optimization
    LEARNING_RATE = 1e-5
    WEIGHT_DECAY = 0.01
    MAX_GRAD_NORM = 1.0
    WARMUP_RATIO = 0.05

    # --------------------------------------------------------------------------
    # Advanced Strategy Parameters
    # --------------------------------------------------------------------------
    # Loss Balancing: L_total = L_toxicity + lambda * L_identity
    # lambda = 0.5 prevents identity task from dominating
    AUX_LOSS_WEIGHT = 0.5

    # Regularization
    DROPOUT = 0.2
    SPATIAL_DROPOUT = 0.1  # Applied to hidden states sequence
    MULTI_SAMPLE_DROPOUT_NUM = 5  # Number of dropout masks for the head

    # Layer-wise Learning Rate Decay (LLRD)
    # Decay rate for learning rates as we go from top (head) to bottom (embeddings)
    LLRD_DECAY = 0.95
