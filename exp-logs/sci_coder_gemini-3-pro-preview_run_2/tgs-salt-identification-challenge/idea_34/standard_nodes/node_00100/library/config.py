import os


class Config:
    """
    Global configuration for the Salt Segmentation Task.
    Implements the Marginalized-Distillation to Multi-Task Generalist strategy parameters.
    """

    # =========================================================================
    # File Paths & Directories
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for this specific idea/experiment
    WORKING_DIR = "./working/idea_34"

    # Sub-directories for organization
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    SUBMISSION_DIR = "./submission"

    # Specific file paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Metadata files (generated by the provided script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # =========================================================================
    # Data Configuration
    # =========================================================================
    ORIG_SIZE = 101  # Original image size
    IMG_SIZE = 128  # Padded size (divisible by 32 for ResNet)
    CHANNELS = 1  # Input channels (Grayscale seismic images)
    NUM_WORKERS = 2  # Number of data loading workers

    # =========================================================================
    # Model Configuration
    # =========================================================================
    BACKBONE = "resnet34"
    ENCODER_WEIGHTS = "imagenet"

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    SEED = 42
    BATCH_SIZE = 32
    LEARNING_RATE = 1e-4
    NUM_FOLDS = 5

    # Training Horizons
    EPOCHS_STAGE1 = 50  # Specialist Teacher (Supervised)
    EPOCHS_STAGE3 = 50  # Student (Distillation)
    EPOCHS = 50

    # Optimization
    EARLY_STOPPING_PATIENCE = 15
    WEIGHT_DECAY = 1e-2

    # =========================================================================
    # Augmentation Hyperparameters
    # =========================================================================
    # Non-Rigid (Elastic Transform) - Critical for performance
    AUG_ELASTIC_ALPHA = 120
    AUG_ELASTIC_SIGMA = 6
    AUG_ELASTIC_ALPHA_AFFINE = 6
    AUG_ELASTIC_P = 0.5

    # Rigid (Geometric)
    AUG_RIGID_P = 0.2  # Probability for ShiftScaleRotate

    # =========================================================================
    # Marginalization & Inference Strategy
    # =========================================================================
    # Standard deviations for scanning depth during pseudo-label generation.
    # Used to marginalize out depth uncertainty for the test set.
    DEPTH_SCAN_VALUES = [-1.5, -0.75, 0, 0.75, 1.5]

    # Test-Time Augmentation
    TTA_ENABLED = True  # Use Horizontal Flip TTA

    # =========================================================================
    # Debugging & Development
    # =========================================================================
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 100  # Number of samples to use when DEBUG is True

    @classmethod
    def setup(cls):
        """
        Initialize the working environment by creating necessary directories.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Automatically setup directories when config is imported
Config.setup()
