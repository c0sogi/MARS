class PseudoDataset(Dataset):
    """
    Dataset for the Unlabeled Student Training (Stage 3).
    Loads images and their corresponding soft pseudo-labels generated by the Teacher.
    """

    def __init__(self, df, pseudo_labels, transform=None):
        """
        Args:
            df (pd.DataFrame): Metadata for test images.
            pseudo_labels (dict): Dictionary mapping id -> soft mask (np.ndarray).
            transform (A.Compose): Albumentations transforms.
        """
        self.df = df
        self.pseudo_labels = pseudo_labels
        self.transform = transform
        self.ids = df["id"].values

        # Pre-load images to match SaltDataset behavior (speed vs memory trade-off)
        # Given the dataset size (1000 images), this fits easily in RAM.
        self.images = {}
        for idx, row in self.df.iterrows():
            img_path = os.path.join(Config.INPUT_DIR, row["image_path"])
            img = cv2.imread(img_path, cv2.IMREAD_GRAYSCALE)
            if img is not None:
                # Pad to match model input size (128x128)
                self.images[row["id"]] = pad_image(img)
            else:
                print(f"Warning: Image not found {img_path}")

    def __len__(self):
        return len(self.ids)

    def __getitem__(self, idx):
        img_id = self.ids[idx]

        # Load Image (H, W)
        image = self.images[img_id]

        # Load Soft Mask (H, W) - Already padded from model output in generation step
        mask = self.pseudo_labels[img_id]

        # Expand dims for transform (H, W, 1)
        image = np.expand_dims(image, axis=-1)

        # Apply Augmentations
        # Albumentations handles float masks correctly if passed as 'mask'
        if self.transform:
            augmented = self.transform(image=image, mask=mask)
            image = augmented["image"]
            mask = augmented["mask"]

        # Convert mask to tensor if not already done by transform
        if not isinstance(mask, torch.Tensor):
            mask = torch.from_numpy(mask)

        # Ensure mask has channel dim (1, H, W)
        if mask.ndim == 2:
            mask = mask.unsqueeze(0)

        mask = mask.float()

        # Dummy depth (not used for unsupervised loss, but required by collate/loop unpacking)
        depth = torch.tensor([0.0], dtype=torch.float32)

        return image, mask, depth, img_id


def generate_marginalized_pseudo_labels(
    teacher_model_paths, device, load_cached_data=True
):
    """
    Generates soft pseudo-labels for the test set using the Marginalized Depth-Scan strategy.
    Aggregates predictions from an ensemble of teachers across a range of latent depths.

    Args:
        teacher_model_paths (list): List of file paths to trained teacher model checkpoints.
        device (str): 'cuda' or 'cpu'.
        load_cached_data (bool): If True, attempts to load from disk.

    Returns:
        dict: Dictionary mapping image_id (str) -> soft_mask (np.ndarray).
    """

    cache_path = os.path.join(Config.WORKING_DIR, "pseudo_labels.npy")

    # 1. Check Cache
    if load_cached_data and os.path.exists(cache_path):
        print(f"Loading pseudo-labels from {cache_path}...")
        try:
            # Allow pickle is required for dictionary loading
            pseudo_labels = np.load(cache_path, allow_pickle=True).item()
            return pseudo_labels
        except Exception as e:
            print(f"Failed to load cache: {e}. Regenerating...")

    print("Generating marginalized pseudo-labels...")

    # 2. Setup Data
    test_df = pd.read_csv(Config.TEST_CSV)

    # Use SaltDataset for loading to ensure consistent preprocessing (padding/normalization)
    # 'test' mode returns (image, depth, id). We use the standard test transform (no aug).
    test_dataset = SaltDataset(
        df=test_df,
        mode="test",
        transform=get_transforms("test"),
        load_cached=True,  # Use dataset's internal cache if available
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=Config.BATCH_SIZE,
        shuffle=False,
        num_workers=Config.NUM_WORKERS,
        pin_memory=True,
    )

    # 3. Ensemble Prediction
    accumulated_results = {}  # id -> accumulated mask

    # Initialize dictionary with zeros
    for img_id in test_df["id"].values:
        accumulated_results[img_id] = np.zeros(
            (Config.IMG_SIZE, Config.IMG_SIZE), dtype=np.float32
        )

    num_models = len(teacher_model_paths)

    for model_path in teacher_model_paths:
        print(f"Processing with Teacher: {os.path.basename(model_path)}")

        # Load Model
        model = SaltNet(mode="teacher")
        state_dict = torch.load(model_path, map_location=device)
        model.load_state_dict(state_dict)
        model.to(device)
        model.eval()

        # Run Depth Scan
        # Returns dict: id -> soft_mask (H, W)
        # The engine handles the scanning over the depth range
        scan_results = Engine.predict_depth_scan(model, test_loader, device)

        # Accumulate
        for img_id, mask in scan_results.items():
            accumulated_results[img_id] += mask

    # 4. Average
    final_pseudo_labels = {}
    for img_id, mask_sum in accumulated_results.items():
        final_pseudo_labels[img_id] = mask_sum / num_models

    # 5. Save Cache
    os.makedirs(Config.WORKING_DIR, exist_ok=True)
    np.save(cache_path, final_pseudo_labels)
    print(f"Pseudo-labels saved to {cache_path}")

    return final_pseudo_labels
