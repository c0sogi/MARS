import os
import torch


class Config:
    """
    Configuration for the Corrected Wide-Context Dual-Path BiLSTM (CWCDP-BiLSTM)
    and the Segregated Physics-Fidelity Data Pipeline.
    """

    # ==========================
    # File Paths
    # ==========================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_19"
    SUBMISSION_DIR = "./submission"

    # Raw Data
    TRAIN_DATA_PATH = os.path.join(INPUT_DIR, "train.csv")
    TEST_DATA_PATH = os.path.join(INPUT_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata (Generated by separate script)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Outputs
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache Files (Parquet/Numpy)
    CACHE_TRAIN_PATH = os.path.join(WORKING_DIR, "train_processed.parquet")
    CACHE_VAL_PATH = os.path.join(WORKING_DIR, "val_processed.parquet")
    CACHE_TEST_PATH = os.path.join(WORKING_DIR, "test_processed.parquet")
    SCALER_PATH = os.path.join(WORKING_DIR, "scaler_params.npz")

    # Model Artifacts
    MODEL_CHECKPOINT_PATH = os.path.join(WORKING_DIR, "checkpoint.pth")
    BEST_MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # ==========================
    # Data Parameters
    # ==========================
    SEED = 42
    NUM_WORKERS = 4
    SEQ_LEN = 80  # Standard breath length

    # Feature Engineering Configuration
    # Continuous features: Apply RobustScaler (Median/IQR)
    CONT_FEATURES = [
        "time_step",
        "u_in",
        "R",
        "C",
        "u_in_cumsum",  # Time-weighted integration
        "R_u_in",  # Resistive pressure term
        "vol_div_C",  # Elastic pressure term
        # Past Lags (No future lags)
        "u_in_lag1",
        "u_in_lag2",
        "u_in_lag3",
        "u_in_lag4",
        # Finite Differences (1st Derivative)
        "u_in_diff1",
        "u_in_diff2",
        "u_in_diff3",
        "u_in_diff4",
        # Acceleration (2nd Derivative)
        "u_in_acc1",
        "u_in_acc2",
    ]

    # Binary features: Do NOT scale (preserve 0/1 logic)
    BINARY_FEATURES = ["u_out"]

    # Derived Input Dimension
    INPUT_DIM = len(CONT_FEATURES) + len(BINARY_FEATURES)

    # ==========================
    # Model Architecture
    # ==========================
    # Wide Deep Recurrent Backbone
    LSTM_HIDDEN_SIZE = 512
    LSTM_LAYERS = 4
    BIDIRECTIONAL = True

    # Wide Monolithic Context Extractor
    GLU_HIDDEN_SIZE = 256

    # Regularization
    DROPOUT = 0.1

    # ==========================
    # Training Hyperparameters
    # ==========================
    # Stretched-Horizon Protocol
    EPOCHS = 200
    BATCH_SIZE = 256  # A100 40GB allows large batches

    # Optimizer (AdamW)
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2

    # Scheduler (Cosine Annealing)
    # T_MAX matches EPOCHS to stretch the decay horizon
    T_MAX = 200
    ETA_MIN = 1e-6

    # Weighted Loss
    # Focus on inspiration, maintain stability during expiration
    LOSS_INSP_WEIGHT = 1.0
    LOSS_EXP_WEIGHT = 0.1

    # Hardware
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @staticmethod
    def setup_dirs():
        """Ensure necessary directories exist."""
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
