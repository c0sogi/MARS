import os
import torch


class Config:
    """
    Configuration class for the 2.5D Anatomically-Guided Attention Network.
    Centralizes all file paths, model hyperparameters, and training settings.
    """

    def __init__(self):
        # --- General Settings ---
        self.SEED = 42
        self.DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
        self.NUM_WORKERS = 12  # Utilizing available vCPUs

        # --- Debugging ---
        # Set to True to run on a small subset of data for quick testing
        self.DEBUG = False
        self.DEBUG_SAMPLE_SIZE = 16

        # --- Directories & Paths ---
        self.INPUT_DIR = "./input"
        self.METADATA_DIR = "./metadata"

        # Input Data Paths
        self.TRAIN_IMAGES_DIR = os.path.join(self.INPUT_DIR, "train_images")
        self.TEST_IMAGES_DIR = os.path.join(self.INPUT_DIR, "test_images")
        self.SEGMENTATION_DIR = os.path.join(self.INPUT_DIR, "segmentations")
        self.TRAIN_BOUNDING_BOXES = os.path.join(
            self.INPUT_DIR, "train_bounding_boxes.csv"
        )

        # Metadata Paths (Generated by previous steps)
        self.TRAIN_METADATA_PATH = os.path.join(self.METADATA_DIR, "train_metadata.csv")
        self.VAL_METADATA_PATH = os.path.join(self.METADATA_DIR, "val_metadata.csv")
        self.TEST_METADATA_PATH = os.path.join(self.METADATA_DIR, "test_metadata.csv")
        self.SAMPLE_SUBMISSION_PATH = os.path.join(
            self.INPUT_DIR, "sample_submission.csv"
        )

        # Working Directory (Output)
        self.WORKING_DIR = "./working/idea_5"
        self.CACHE_DIR = self.WORKING_DIR
        self.MODEL_SAVE_PATH = os.path.join(self.WORKING_DIR, "best_model.pth")
        self.SUBMISSION_PATH = os.path.join(self.WORKING_DIR, "submission.csv")

        # Cache Files for Deterministic Data Processing
        self.TRAIN_CACHE_PATH = os.path.join(self.CACHE_DIR, "train_cache.parquet")
        self.VAL_CACHE_PATH = os.path.join(self.CACHE_DIR, "val_cache.parquet")
        self.TEST_CACHE_PATH = os.path.join(self.CACHE_DIR, "test_cache.parquet")

        # Ensure working directory exists
        os.makedirs(self.WORKING_DIR, exist_ok=True)

        # --- Data Hyperparameters ---
        # 2.5D Stacking: (z-1, z, z+1) -> 3 channels
        self.IN_CHANNELS = 3
        # Image Dimensions: EfficientNet-B4 native is 380, using 384 for standard power of 2 alignment
        self.IMAGE_SIZE = (384, 384)
        # Sequence Length: Number of slices sampled per study
        self.SEQ_LENGTH = 128
        # Slice Selection Strategy: 'uniform' or 'consecutive'
        self.SAMPLING_STRATEGY = "uniform"

        # Augmentation
        self.USE_AUGMENTATION = True
        self.AUG_ROTATION = 15
        self.AUG_SHIFT = 0.1
        self.AUG_SCALE = 0.1

        # --- Model Hyperparameters ---
        # Backbone
        self.BACKBONE_NAME = "tf_efficientnet_b4_ns"
        self.BACKBONE_PRETRAINED = True
        self.DROP_RATE = 0.3
        self.DROP_PATH_RATE = 0.2

        # Sequence Model (LSTM)
        self.LSTM_HIDDEN_SIZE = 256
        self.LSTM_LAYERS = 2
        self.BIDIRECTIONAL = True

        # Heads
        # Main Task: 7 Vertebrae + 1 Patient Overall = 8 targets (but handled as independent heads)
        self.NUM_CLASSES = 8
        # Auxiliary Task: Background(0) + C1(1) to C7(7) = 8 classes
        self.AUX_NUM_CLASSES = 8

        # --- Training Hyperparameters ---
        self.EPOCHS = 10

        # Batch Size Optimization for A100 40GB
        # Sequence models with large backbones are memory intensive.
        # We use a small physical batch size and accumulate gradients.
        self.BATCH_SIZE = 1
        self.EFFECTIVE_BATCH_SIZE = 16
        self.GRAD_ACCUM_STEPS = self.EFFECTIVE_BATCH_SIZE // self.BATCH_SIZE

        # Optimizer
        self.LEARNING_RATE = 3e-4
        self.WEIGHT_DECAY = 1e-4
        self.MAX_GRAD_NORM = 10.0

        # Scheduler
        self.SCHEDULER_PATIENCE = 1
        self.SCHEDULER_FACTOR = 0.5
        self.MIN_LR = 1e-6

        # Early Stopping
        self.EARLY_STOPPING_PATIENCE = 3
        self.EARLY_STOPPING_MIN_DELTA = 0.0001

        # --- Loss Function Hyperparameters ---
        # Focal Loss for Fracture Classification
        self.FOCAL_ALPHA = 0.25
        self.FOCAL_GAMMA = 2.0

        # Auxiliary Loss (Anatomical Supervision)
        self.AUX_LOSS_WEIGHT = 0.5  # Weight of aux loss in total loss
        self.AUX_LOSS_IGNORE_INDEX = -1  # For slices without anatomical labels

    def display(self):
        """Prints the configuration."""
        print("=" * 30)
        print("CONFIG")
        print("=" * 30)
        for k, v in vars(self).items():
            print(f"{k}: {v}")
        print("=" * 30)
