import os
import torch


class Config:
    """
    Configuration class for the Robust Multi-Task XLM-RoBERTa Large Ensemble
    with Adversarial Training.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    # Random seeds for training separate models for the ensemble
    seeds = [42, 43, 44]

    # Debugging mode: If True, drastically reduces dataset size for fast pipeline verification
    debug = False
    debug_sample_size = 50  # Number of samples to use when debug=True

    # =========================================================================
    # Directory Paths
    # =========================================================================
    # Read-only input directories
    input_dir = "./input"
    metadata_dir = "./metadata"

    # Read-write working directory for caching features, checkpoints, and submissions
    working_dir = "./working/idea_8"

    # Metadata file paths (generated by the metadata script)
    train_path = os.path.join(metadata_dir, "train.csv")
    val_path = os.path.join(metadata_dir, "val.csv")
    test_path = os.path.join(metadata_dir, "test.csv")

    # Submission file path
    submission_path = os.path.join(working_dir, "submission.csv")

    # =========================================================================
    # Model Architecture
    # =========================================================================
    model_name = "xlm-roberta-large"

    # Weighted Layer Pooling: Number of last hidden layers to pool
    n_pool_layers = 4

    # =========================================================================
    # Data Processing (Tokenizer & Sliding Window)
    # =========================================================================
    max_len = 384
    doc_stride = 128

    # Negative Sampling: We retain ALL generated windows (no downsampling)
    # to maximize recall on long documents.
    downsample_negatives = False

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    epochs = 2

    # Batch Size Configuration
    # XLM-R Large is memory intensive. We use a small physical batch size
    # and accumulate gradients to achieve a stable effective batch size.
    train_batch_size = 4
    valid_batch_size = 16
    accumulate_grad_batches = 8  # Effective Batch Size = 4 * 8 = 32

    # Optimizer Settings (AdamW)
    learning_rate = 1.5e-5
    weight_decay = 0.01
    warmup_ratio = 0.1
    max_grad_norm = 1.0

    # Layer-wise Learning Rate Decay (LLRD)
    # Decays learning rate geometrically from top to bottom layers
    use_llrd = True
    llrd_decay = 0.9

    # Adversarial Training (Fast Gradient Method - FGM)
    use_fgm = True
    fgm_epsilon = 1.0

    # =========================================================================
    # Hardware & System
    # =========================================================================
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    num_workers = 4  # Optimized for 12 vCPUs

    def __init__(self):
        """Initialize configuration and ensure working directories exist."""
        os.makedirs(self.working_dir, exist_ok=True)
