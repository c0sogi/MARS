import os
import torch


class Config:
    """
    Centralized configuration for the Diabetic Retinopathy prediction task.
    """

    # ==========================
    # General Settings
    # ==========================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data
    DEBUG_SAMPLE_SIZE = 100  # Number of samples to use in debug mode

    # ==========================
    # Hardware & Compute
    # ==========================
    # Use CUDA if available, otherwise CPU
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # Number of workers for DataLoader (12 vCPUs available)
    NUM_WORKERS = 4

    # ==========================
    # Data Paths
    # ==========================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Sample submission file
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # ==========================
    # Output Paths
    # ==========================
    # Directory for intermediate files (checkpoints, cache)
    WORKING_DIR = "./working/idea_1"

    # Directory for final submission
    SUBMISSION_DIR = "./submission"

    # Specific output file paths
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "mobilenetv3_regression.pth")
    SUBMISSION_SAVE_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================
    # Model Hyperparameters
    # ==========================
    MODEL_NAME = "efficientnet_b3"
    IMG_SIZE = 300  # Increased resolution to match B3 capacity (Cite solution_lesson_node_00004)
    BATCH_SIZE = 32  # Adjusted for larger model/image
    LEARNING_RATE = 1e-4  # Adam optimizer learning rate
    NUM_EPOCHS = 20  # Extended for scheduler (Cite solution_lesson_node_00003)
    WEIGHT_DECAY = 1e-5  # Regularization

    # Regression specific
    NUM_CLASSES = 1  # Single neuron for regression output

    @classmethod
    def setup(cls):
        """
        Prepares the environment by creating necessary output directories.
        Should be called at the start of any script using this config.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Optional: Print config status
        print(f"Config setup complete. Device: {cls.DEVICE}")
        print(f"Working Dir: {cls.WORKING_DIR}")
