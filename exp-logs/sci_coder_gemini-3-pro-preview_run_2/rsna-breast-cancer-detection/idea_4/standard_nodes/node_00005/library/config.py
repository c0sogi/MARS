import os
import torch
import numpy as np
import random


class Config:
    """
    Configuration module for Idea 4: Multi-View Attention Network (MVAN).
    Centralizes all file paths, hyperparameters, and environment settings.
    """

    # ==========================================
    # Project & Experiment Settings
    # ==========================================
    PROJECT_NAME = "breast-cancer-mvan-idea4"
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data
    DEBUG_SAMPLE_SIZE = 200  # Number of samples to use when DEBUG is True

    # ==========================================
    # Directories & File Paths
    # ==========================================
    # Input Directories (Read-Only)
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Image Directories
    # Structure: [train/test]_images/[patient_id]/[image_id].dcm
    TRAIN_IMAGES_DIR = os.path.join(INPUT_DIR, "train_images")
    TEST_IMAGES_DIR = os.path.join(INPUT_DIR, "test_images")

    # Output Directories (Writeable)
    WORKING_DIR = "./working"
    OUTPUT_DIR = os.path.join(WORKING_DIR, "idea_4")

    # Submission
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Model Checkpoint
    MODEL_SAVE_PATH = os.path.join(OUTPUT_DIR, "mvan_model.pth")

    # ==========================================
    # Data Processing
    # ==========================================
    IMG_SIZE = (640, 640)  # High resolution to capture microcalcifications
    NUM_WORKERS = 4  # Number of dataloader workers (12 vCPUs available)
    PIN_MEMORY = True

    # ==========================================
    # Model Architecture
    # ==========================================
    BACKBONE = "efficientnet_b2"
    PRETRAINED = True  # Initialize with ImageNet weights
    FREEZE_BACKBONE = False  # False = End-to-End Fine-Tuning
    DROPOUT = 0.3
    ATTENTION_DIM = 128  # Dimension for the MIL Gated Attention mechanism
    NUM_CLASSES = 1  # Binary classification (Cancer vs Normal)

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    # Batch Size: Number of "Bags" (Patients/Breasts) per batch.
    # Each bag contains multiple views (avg ~4 images).
    # Batch Size 8 => ~32 images per forward pass.
    BATCH_SIZE = 8

    EPOCHS = 10
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2

    # Class Balancing (BCEWithLogitsLoss pos_weight)
    # The dataset is highly imbalanced (~2% positive).
    # A high pos_weight encourages the model to recall positive cases.
    POS_WEIGHT = 25.0

    # Optimization Strategy
    EARLY_STOPPING_PATIENCE = 3
    GRADIENT_ACCUMULATION_STEPS = 1

    # ==========================================
    # Hardware
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Initializes the environment:
        1. Creates necessary output directories.
        2. Sets fixed random seeds for reproducibility.
        """
        # Create directories
        os.makedirs(cls.OUTPUT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set seeds
        cls._set_seed()

    @classmethod
    def _set_seed(cls):
        """Sets fixed random seeds for random, numpy, and torch."""
        random.seed(cls.SEED)
        os.environ["PYTHONHASHSEED"] = str(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
