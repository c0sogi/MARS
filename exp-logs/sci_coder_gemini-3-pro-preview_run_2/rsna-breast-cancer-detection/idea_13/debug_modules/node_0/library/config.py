import os
import torch


class Config:
    """
    Centralized configuration for the Breast Cancer Detection task using the
    Tri-Spectral Hybrid Network (TS-HN) strategy.
    """

    # =========================================================================
    # Directories & File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory for caching processed data and model checkpoints (Idea 13)
    WORKING_DIR = "./working/idea_13"
    # Submission directory
    SUBMISSION_DIR = "./submission"

    # Metadata Files (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Raw Data
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Artifacts
    MODEL_CHECKPOINT_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_FILE_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Configuration
    # =========================================================================
    # Image resolution (Square)
    IMAGE_SIZE = 640

    # Number of input channels (Tri-Spectral: Linear, CLAHE, Gamma)
    NUM_CHANNELS = 3

    # Tri-Spectral Preprocessing Parameters
    GAMMA_VALUE = 2.0
    CLAHE_CLIP_LIMIT = 2.0
    CLAHE_TILE_GRID_SIZE = (8, 8)

    # =========================================================================
    # Model Architecture
    # =========================================================================
    # Backbone: EfficientNetV2-Small (timm implementation)
    BACKBONE = "tf_efficientnetv2_s.in1k"
    PRETRAINED = True

    # Regularization
    DROP_RATE = 0.2
    DROP_PATH_RATE = 0.1

    # Hybrid Fusion Head
    TABULAR_HIDDEN_DIM = 64
    FUSION_HIDDEN_DIM = 256

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    SEED = 42

    # Batch size (Fits in A100 40GB with 640x640 resolution)
    BATCH_SIZE = 16

    # Training duration
    EPOCHS = 10

    # Optimization
    LEARNING_RATE = 1e-4
    MAX_LR = 1e-3  # Peak learning rate for OneCycleLR
    WEIGHT_DECAY = 1e-2

    # Loss Function: Weighted BCEWithLogitsLoss
    # Aggressive weighting for ~1:50 class imbalance
    POS_WEIGHT = 20.0

    # =========================================================================
    # Hardware & Execution
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Number of data loading workers (12 vCPUs available)
    NUM_WORKERS = 12

    # Pin memory for faster host-to-device transfer
    PIN_MEMORY = True

    @classmethod
    def setup(cls):
        """
        Creates necessary working and submission directories.
        Should be called at the start of the pipeline.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print(f"\n{'='*20} CONFIGURATION {'='*20}")
        print(f"Device: {cls.DEVICE}")
        print(f"Backbone: {cls.BACKBONE}")
        print(f"Image Size: {cls.IMAGE_SIZE}x{cls.IMAGE_SIZE}")
        print(f"Batch Size: {cls.BATCH_SIZE}")
        print(f"Pos Weight: {cls.POS_WEIGHT}")
        print(f"Working Dir: {cls.WORKING_DIR}")
        print(f"{'='*55}\n")
