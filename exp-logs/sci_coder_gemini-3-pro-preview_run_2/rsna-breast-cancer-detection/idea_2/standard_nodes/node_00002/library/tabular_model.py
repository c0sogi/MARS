import os
import pickle
import numpy as np
import pandas as pd
import lightgbm as lgb
from sklearn.preprocessing import OrdinalEncoder
from library.config import (
    LGBM_PARAMS,
    WORKING_DIR,
    SUBMISSION_DIR,
    SEED,
    NUM_BOOST_ROUND,
    EARLY_STOPPING_ROUNDS,
    VERBOSE_EVAL,
)
from library.utils import probabilistic_f1


class CancerClassifier:
    """
    A wrapper class for the LightGBM classifier that handles tabular data preprocessing,
    training, and inference for breast cancer detection.
    """

    def __init__(self):
        # Define feature groups
        self.cat_features = ["site_id", "laterality", "view", "implant", "machine_id"]
        self.num_features = ["age"]
        # Embedding features generated by the backbone (emb_0 to emb_511)
        self.emb_features = [f"emb_{i}" for i in range(512)]

        self.all_features = self.cat_features + self.num_features + self.emb_features

        # Initialize encoder: handle unknown categories by setting them to -1
        self.encoder = OrdinalEncoder(
            handle_unknown="use_encoded_value", unknown_value=-1, dtype=int
        )

        self.model = None
        self.model_path = os.path.join(WORKING_DIR, "lgbm_model.txt")
        self.encoder_path = os.path.join(WORKING_DIR, "encoder.pkl")

    def _preprocess(self, df, is_train=True):
        """
        Preprocesses the dataframe: encodes categoricals and separates features/targets.
        """
        df = df.copy()

        # Ensure categorical columns are strings before encoding
        for col in self.cat_features:
            df[col] = df[col].astype(str)

        if is_train:
            # Fit encoder on training data
            df[self.cat_features] = self.encoder.fit_transform(df[self.cat_features])
        else:
            # Transform validation/test data using fitted encoder
            df[self.cat_features] = self.encoder.transform(df[self.cat_features])

        # Select features
        X = df[self.all_features]

        # Extract target if present
        y = None
        if "cancer" in df.columns:
            y = df["cancer"].values

        return X, y

    def fit(self, train_df, val_df):
        """
        Trains the LightGBM model using the provided training and validation dataframes.
        """
        print("Preprocessing data for LightGBM...")
        X_train, y_train = self._preprocess(train_df, is_train=True)
        X_val, y_val = self._preprocess(val_df, is_train=False)

        # Create LightGBM Datasets
        # Note: We explicitly tell LightGBM which features are categorical
        train_data = lgb.Dataset(
            X_train, label=y_train, categorical_feature=self.cat_features
        )
        val_data = lgb.Dataset(
            X_val,
            label=y_val,
            reference=train_data,
            categorical_feature=self.cat_features,
        )

        print(f"Training LightGBM model (Max Rounds: {NUM_BOOST_ROUND})...")

        callbacks = [
            lgb.early_stopping(stopping_rounds=EARLY_STOPPING_ROUNDS),
            lgb.log_evaluation(period=VERBOSE_EVAL),
        ]

        self.model = lgb.train(
            params=LGBM_PARAMS,
            train_set=train_data,
            valid_sets=[train_data, val_data],
            valid_names=["train", "valid"],
            num_boost_round=NUM_BOOST_ROUND,
            callbacks=callbacks,
        )

        # Save model and encoder
        print(f"Saving model artifacts to {WORKING_DIR}...")
        self.model.save_model(self.model_path)
        with open(self.encoder_path, "wb") as f:
            pickle.dump(self.encoder, f)

        # Validation Evaluation (pF1)
        print("Evaluating on Validation Set...")
        val_preds = self.model.predict(X_val, num_iteration=self.model.best_iteration)
        score = probabilistic_f1(y_val, val_preds)
        print(f"Validation pF1 Score: {score}")

    def predict_and_submit(self, test_df):
        """
        Generates predictions for the test set, aggregates them by prediction_id,
        and saves the submission file.
        """
        print("Loading model artifacts for inference...")
        if self.model is None:
            if os.path.exists(self.model_path):
                self.model = lgb.Booster(model_file=self.model_path)
            else:
                raise FileNotFoundError("Model file not found. Run fit() first.")

        if os.path.exists(self.encoder_path):
            with open(self.encoder_path, "rb") as f:
                self.encoder = pickle.load(f)
        else:
            raise FileNotFoundError("Encoder file not found. Run fit() first.")

        print("Preprocessing test data...")
        X_test, _ = self._preprocess(test_df, is_train=False)

        print("Generating predictions...")
        # Predict cancer probability
        preds = self.model.predict(X_test, num_iteration=self.model.best_iteration)

        # Add predictions to dataframe for aggregation
        results_df = test_df[["prediction_id"]].copy()
        results_df["cancer"] = preds

        # Aggregate by prediction_id
        # Strategy: Take the MAX probability across all views for a specific breast
        # This is because if any view shows cancer, the breast is cancerous.
        submission_df = (
            results_df.groupby("prediction_id")["cancer"].max().reset_index()
        )

        # Save submission
        os.makedirs(SUBMISSION_DIR, exist_ok=True)
        submission_path = os.path.join(SUBMISSION_DIR, "submission.csv")
        submission_df.to_csv(submission_path, index=False)

        print(f"Submission saved to {submission_path}")
        print(f"Submission shape: {submission_df.shape}")
        print("Head of submission:")
        print(submission_df.head())

        return submission_df
