import os
import torch


class Config:
    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging

    # =========================================================================
    # File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_3"
    SUBMISSION_DIR = "./submission"

    # Input Metadata (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output Paths
    MODEL_PATH = os.path.join(WORKING_DIR, "hybrid_efficientnet_b2.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Configuration
    # =========================================================================
    # Image Configuration
    IMG_SIZE = (640, 640)  # High resolution for microcalcification detection
    IN_CHANNELS = 3

    # Tabular Feature Configuration
    # Features used in the MLP branch
    NUMERICAL_FEATURES = ["age"]
    CATEGORICAL_FEATURES = ["site_id", "laterality", "view", "implant", "machine_id"]

    # =========================================================================
    # Model Hyperparameters
    # =========================================================================
    BACKBONE = "efficientnet_b2"  # timm model name
    PRETRAINED = True
    NUM_CLASSES = 1

    # Dimension of the embedding produced by the tabular MLP before fusion
    TABULAR_EMBED_DIM = 64

    # Dropout Rates
    DROP_RATE = 0.3  # Classifier dropout
    DROP_PATH_RATE = 0.2  # Stochastic depth for backbone

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 16  # Fits 640x640 on A100 40GB
    NUM_EPOCHS = 10  # Max epochs (using Early Stopping)

    # Optimization
    LR = 3e-4  # Initial learning rate
    WEIGHT_DECAY = 1e-4

    # Loss Function Weights
    # Imbalance is approx 1:47. We use a weight to penalize missing positive cases.
    POS_WEIGHT = 20.0

    # Scheduler
    WARMUP_EPOCHS = 1

    # Early Stopping
    PATIENCE = 3

    # =========================================================================
    # Hardware & System
    # =========================================================================
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 12  # Utilizing available vCPUs
    PIN_MEMORY = True

    @staticmethod
    def create_dirs():
        """Ensures that necessary working directories exist."""
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)


# Initialize directories upon import
Config.create_dirs()
