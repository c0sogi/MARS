import os
import torch
from library.utils import seed_everything


class Config:
    # -------------------------------------------------------------------------
    # General Configuration
    # -------------------------------------------------------------------------
    PROJECT_NAME = "BirdSpeciesClassification"
    IDEA_NAME = "idea_14"
    SEED = 42

    # Debugging flags
    DEBUG = False  # Set to True to run on a small subset of data
    DEBUG_SAMPLES = 20  # Number of samples to use when DEBUG is True

    # Compute
    NUM_WORKERS = 4  # Adjust based on available vCPUs
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # -------------------------------------------------------------------------
    # File Paths & Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Output directory for checkpoints and submissions
    WORKING_DIR = os.path.join("./working", IDEA_NAME)

    # Metadata CSVs (Generated by the metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Image Source: Using Filtered Spectrograms as per idea description
    # Note: Metadata CSVs contain relative paths. Dataset class should handle joining
    # or replacing the directory if needed. Here we define the absolute root.
    FILTERED_SPEC_DIR = os.path.join(
        INPUT_DIR, "supplemental_data", "filtered_spectrograms"
    )

    # -------------------------------------------------------------------------
    # Data Parameters
    # -------------------------------------------------------------------------
    NUM_CLASSES = 19
    IN_CHANNELS = 3  # Pseudo-RGB (Channel Replication)

    # Multi-Resolution Strategy
    # Format: (Height/Frequency, Width/Time)
    # ResNet18/EfficientNet: 224x448 to preserve temporal fidelity
    # DenseNet121: 160x320 for architectural regularization
    RESOLUTIONS = {
        "resnet18": (224, 448),
        "efficientnet_b0": (224, 448),
        "densenet121": (160, 320),
    }

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 16
    EPOCHS = 60
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Augmentation
    MIXUP_ALPHA = 0.4

    # -------------------------------------------------------------------------
    # Model Selection
    # -------------------------------------------------------------------------
    MODELS_TO_RUN = ["resnet18", "densenet121"]

    @classmethod
    def get_resolution(cls, model_name):
        """
        Retrieves the specific input resolution (height, width) for a given model architecture.
        Defaults to (224, 448) if model is not explicitly mapped.
        """
        return cls.RESOLUTIONS.get(model_name, (224, 448))

    @classmethod
    def setup(cls):
        """
        Performs initial setup:
        1. Sets random seeds for reproducibility.
        2. Creates the working directory.
        """
        seed_everything(cls.SEED)
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
