import os


class Config:
    """
    Central configuration for the Bird Species Classification experiment.
    Implements the 'Tri-Backbone Heterogeneous Ensemble with SAM' strategy.
    """

    # ==========================================
    # General Settings
    # ==========================================
    SEED = 42
    NUM_CLASSES = 19
    NUM_FOLDS = 5

    # Debugging / Development flags
    DEBUG = False
    DEBUG_SAMPLES = 50  # Number of samples to use when DEBUG is True

    # ==========================================
    # File Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the metadata script
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Source Data
    # Using Filtered Spectrograms as per strategy (denoised signal)
    SPECTROGRAM_DIR = os.path.join(
        INPUT_DIR, "supplemental_data", "filtered_spectrograms"
    )

    # Working Directory for checkpoints and cache
    WORK_DIR = "./working/idea_25"

    # ==========================================
    # Data Configuration
    # ==========================================
    # Input dimensions: 224 (Frequency) x 448 (Time)
    # 1:2 aspect ratio preserves temporal fidelity of bird calls
    IMG_HEIGHT = 224
    IMG_WIDTH = 448
    IMG_SIZE = (IMG_HEIGHT, IMG_WIDTH)

    # Channels: 3 (Pseudo-RGB via channel replication for ImageNet weights)
    CHANNELS = 3

    # ==========================================
    # Model Architecture
    # ==========================================
    # Heterogeneous Ensemble Backbones
    BACKBONES = [
        "resnet18",  # Residual Bias (Stability)
        "efficientnet_b0",  # Inverted Residual Bias (Fine-grained features)
        "densenet121",  # Dense Bias (Feature reuse)
    ]

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 16

    # Optimization
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Schedule
    # Fixed number of update steps per fold (dataset size agnostic)
    MAX_STEPS = 1000

    # ==========================================
    # Augmentation & Regularization
    # ==========================================
    # Mixup
    MIXUP_ALPHA = 0.4

    # Test Time Augmentation (TTA)
    # 4 variants: Original, Roll 25%, Roll 50%, Roll 75%
    TTA_STEPS = 4


# Ensure the working directory exists immediately upon import
os.makedirs(Config.WORK_DIR, exist_ok=True)
