import os
import cv2
import torch
import numpy as np
import pandas as pd
import albumentations as A
from albumentations.pytorch import ToTensorV2
from torch.utils.data import Dataset

from library.config import Config


def get_transforms(data="train"):
    """
    Returns the Albumentations transformation pipeline.

    Args:
        data (str): 'train' for augmentation, 'valid' or 'test' for deterministic transforms.
    """
    if data == "train":
        return A.Compose(
            [
                A.Resize(Config.IMG_HEIGHT, Config.IMG_WIDTH),
                # SpecAugment approximation using CoarseDropout
                # This masks random rectangular regions, simulating time/frequency masking
                A.CoarseDropout(
                    max_holes=8,
                    max_height=int(Config.IMG_HEIGHT * 0.2),  # Approx frequency masking
                    max_width=int(Config.IMG_WIDTH * 0.2),  # Approx time masking
                    min_holes=1,
                    min_height=8,
                    min_width=8,
                    fill_value=0,
                    p=0.5,
                ),
                A.Normalize(
                    mean=[0.485, 0.456, 0.406],
                    std=[0.229, 0.224, 0.225],
                ),
                ToTensorV2(),
            ]
        )
    else:
        # Validation / Test transforms
        return A.Compose(
            [
                A.Resize(Config.IMG_HEIGHT, Config.IMG_WIDTH),
                A.Normalize(
                    mean=[0.485, 0.456, 0.406],
                    std=[0.229, 0.224, 0.225],
                ),
                ToTensorV2(),
            ]
        )


class BirdDataset(Dataset):
    def __init__(self, df, transforms=None):
        """
        Args:
            df (pd.DataFrame): DataFrame containing metadata.
            transforms (albumentations.Compose): Transforms to apply.
        """
        self.df = df
        self.transforms = transforms

        # Pre-compute file paths and labels
        self.file_paths = []

        # Extract labels: columns species_0 to species_18
        label_cols = [f"species_{i}" for i in range(Config.NUM_CLASSES)]
        self.labels = self.df[label_cols].values.astype(np.float32)

        for _, row in self.df.iterrows():
            # Metadata points to 'spectrograms', but we want 'filtered_spectrograms'
            # Extract filename from the metadata path
            orig_path = row["file_path_spec"]
            filename = os.path.basename(orig_path)

            # Construct full path to the filtered spectrogram
            full_path = os.path.join(Config.IMAGE_DIR, filename)
            self.file_paths.append(full_path)

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        file_path = self.file_paths[idx]
        labels = self.labels[idx]

        # Load image (BMP)
        # Load as grayscale first
        image = cv2.imread(file_path, cv2.IMREAD_GRAYSCALE)

        # Handle cases where image loading might fail (though paths should be valid)
        if image is None:
            image = np.zeros((Config.IMG_HEIGHT, Config.IMG_WIDTH), dtype=np.uint8)

        # Convert to RGB (3 channels) for pretrained backbone compatibility
        image = cv2.cvtColor(image, cv2.COLOR_GRAY2RGB)

        # Apply transforms
        if self.transforms:
            augmented = self.transforms(image=image)
            image = augmented["image"]

        return image, torch.tensor(labels)


def load_data():
    """
    Loads dataframes from metadata CSVs.
    Merges train and validation sets to allow for K-Fold Cross Validation.

    Returns:
        tuple: (df_full_train, df_test)
    """
    # Load the CSVs generated by the metadata script
    df_train_part = pd.read_csv(Config.TRAIN_CSV_PATH)
    df_val_part = pd.read_csv(Config.VAL_CSV_PATH)
    df_test = pd.read_csv(Config.TEST_CSV_PATH)

    # Merge train and val splits into a single development set
    # This allows the training script to handle K-Fold splitting
    df_full_train = pd.concat([df_train_part, df_val_part], axis=0).reset_index(
        drop=True
    )

    return df_full_train, df_test
