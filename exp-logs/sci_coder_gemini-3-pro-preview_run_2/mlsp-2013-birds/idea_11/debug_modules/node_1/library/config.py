import os
import torch


class Config:
    """
    Configuration for Idea 11: Corrected Tri-Architecture Heterogeneous Ensemble
    with Aggressive Domain Adaptation.
    """

    # ==========================================
    # Execution Control
    # ==========================================
    # Flags to control debugging and dataset size
    DEBUG = False
    DEBUG_SUBSET_SIZE = 20  # Number of samples to use when DEBUG is True

    # ==========================================
    # Paths & Directories
    # ==========================================
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Image Source: Filtered Spectrograms (Denoised)
    # The metadata points to 'spectrograms', but we will map this to 'filtered_spectrograms'
    # in the dataset loader to use the denoised versions.
    FILTERED_SPECTROGRAM_DIR = os.path.join(
        INPUT_ROOT, "supplemental_data", "filtered_spectrograms"
    )

    # Output Directories
    WORKING_DIR = "./working"
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_11")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Data Specifications
    # ==========================================
    # Rectangular Resolution: (Height/Frequency, Width/Time)
    # Preserves 1:2 aspect ratio to maintain temporal fidelity of bird calls.
    IMAGE_SIZE = (224, 448)

    # Input Channels: 3 (Pseudo-RGB via replication)
    CHANNELS = 3

    # Target Classes
    NUM_CLASSES = 19

    # ==========================================
    # Cross Validation
    # ==========================================
    # Iterative Stratified K-Fold
    N_FOLDS = 5
    SEED = 42

    # ==========================================
    # Model Architecture
    # ==========================================
    # Heterogeneous Ensemble: Combining Residual, Dense, and Inverted Residual biases
    BACKBONES = ["resnet18", "densenet121", "efficientnet_b0"]
    PRETRAINED = True

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    # Batch Size: Adjusted for 12 vCPUs + A100
    BATCH_SIZE = 32
    NUM_WORKERS = 2

    # Optimization: Aggressive Domain Adaptation
    # High LR to adapt ImageNet weights to Audio Spectrograms quickly
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Scheduler
    # Constant LR is requested to prevent premature convergence in micro-data regime
    SCHEDULER_TYPE = "constant"

    # Training Duration
    # Defined by Total Update Steps per fold to ensure convergence regardless of epoch size
    MAX_STEPS_PER_FOLD = 1000

    # Regularization
    # Mild Mixup to provide regularization without destructive ambiguity
    USE_MIXUP = True
    MIXUP_ALPHA = 0.4

    # Loss Function
    # BCE with Logits (pos_weight to be handled in trainer)
    LOSS_FUNCTION = "BCEWithLogitsLoss"

    # ==========================================
    # Hardware
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Creates necessary writable directories for caching and submissions.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
