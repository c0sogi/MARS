import os
import torch
import random
import numpy as np


def set_seed(seed=42):
    """
    Sets the random seed for reproducibility across Python, NumPy, and PyTorch.
    """
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False
    os.environ["PYTHONHASHSEED"] = str(seed)


class Config:
    # --- General Configuration ---
    SEED = 42
    DEBUG = False  # Set to True to run on a subset of data for debugging

    # --- Directories & Paths ---
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata CSVs (Generated by the metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Input Data Source
    # We use 'filtered_spectrograms' as they are denoised
    FILTERED_SPECTROGRAM_DIR = os.path.join(
        INPUT_ROOT, "supplemental_data", "filtered_spectrograms"
    )

    # Output Directory for this specific idea (Cache, Models, Submissions)
    WORKING_DIR = "./working/idea_8"

    # --- Data Processing ---
    # Rectangular Resolution: 224 (Frequency/Height) x 896 (Time/Width)
    # This preserves temporal resolution for the 10s clips (Cite Lesson 34)
    IMAGE_SIZE = (224, 896)
    NUM_CLASSES = 19
    NUM_FOLDS = 5

    # --- Training Hyperparameters ---
    # Batch size: 16 is chosen to allow more gradient updates per epoch on the small dataset
    BATCH_SIZE = 16

    # Epochs: High count (80) to ensure convergence (~1000 steps total per fold)
    NUM_EPOCHS = 80

    # Optimizer settings
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4  # Conservative decay to prevent underfitting

    # Regularization
    MIXUP_ALPHA = 0.4  # Mild mixup

    # Loss Configuration
    USE_POS_WEIGHT = True  # Explicitly handle class imbalance

    # --- Model Architecture ---
    # Heterogeneous Ensemble: Training both architectures
    MODEL_ARCHS = ["resnet18", "densenet121"]

    # --- System ---
    NUM_WORKERS = 2
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Ensures the working directory exists.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)

    @classmethod
    def get_spectrogram_path(cls, filename_or_path):
        """
        Resolves the absolute path to the filtered spectrogram file.

        Args:
            filename_or_path (str): The filename or relative path from metadata.
                                    e.g., 'supplemental_data/spectrograms/PC10...bmp'
                                    or just 'PC10...bmp'

        Returns:
            str: Absolute path to the file in the filtered_spectrograms directory.
        """
        basename = os.path.basename(filename_or_path)
        return os.path.join(cls.FILTERED_SPECTROGRAM_DIR, basename)
