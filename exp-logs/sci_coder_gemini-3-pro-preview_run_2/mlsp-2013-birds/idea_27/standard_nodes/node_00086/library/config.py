import os
import torch


class Config:
    """
    Configuration class for the Bird Species Classification Task.
    Implements settings for the Heterogeneous 'Born-Again' Ensemble with
    Iterative Weighted Self-Distillation.
    """

    # -------------------------------------------------------------------------
    # System & Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Specific Cache Directory for this experiment (Idea 27)
    IDEA_ID = "idea_27"
    CACHE_DIR = os.path.join(WORKING_DIR, IDEA_ID)

    # Metadata CSVs (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Image Source: Filtered Spectrograms (Denoised)
    SPECTROGRAM_DIR = os.path.join(
        INPUT_DIR, "supplemental_data", "filtered_spectrograms"
    )

    # Submission Output
    SUBMISSION_PATH = os.path.join(WORKING_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Processing & Input Topology
    # -------------------------------------------------------------------------
    # Rectangular Resolution: 224 (Frequency) x 448 (Time)
    # Aspect ratio 1:2 preserves temporal fidelity of bird calls.
    IMG_HEIGHT = 224
    IMG_WIDTH = 448

    # Pseudo-RGB: 3 channels (replicated) to align with ImageNet weights
    CHANNELS = 3

    NUM_CLASSES = 19

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    NUM_FOLDS = 5
    BATCH_SIZE = 32
    EPOCHS = 30

    # Optimization
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Augmentation
    MIXUP_ALPHA = 0.4

    # -------------------------------------------------------------------------
    # Strategy Specifics: Distillation & Loss
    # -------------------------------------------------------------------------
    # Weight for the distillation loss term (Soft Targets)
    DISTILLATION_LAMBDA = 1.0

    # Factor to scale the calculated positive class weights
    # Used in BCEWithLogitsLoss to handle class imbalance
    POS_WEIGHT_FACTOR = 1.0

    # Ensemble Components
    MODELS = ["resnet18", "efficientnet_b0", "densenet121"]

    # -------------------------------------------------------------------------
    # Debugging & Development
    # -------------------------------------------------------------------------
    # Set DEBUG to True to run on a small subset of data
    DEBUG = False

    # If set to an integer, limits the number of training samples (for debugging)
    MAX_SAMPLES = None

    @classmethod
    def setup(cls):
        """
        Performs necessary setup operations, such as creating the cache directory.
        Should be called at the start of execution.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)

        # Set seeds for reproducibility
        import random
        import numpy as np

        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(cls.SEED)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
