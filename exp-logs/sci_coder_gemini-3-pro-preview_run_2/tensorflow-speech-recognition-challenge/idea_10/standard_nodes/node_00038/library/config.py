import os
import random
import numpy as np
import torch


class Config:
    # ==========================================
    # 1. General Configuration
    # ==========================================
    PROJECT_NAME = "audio_command_recognition"
    IDEA_NAME = "idea_10"
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data for debugging

    # Compute
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================
    # 2. File Paths
    # ==========================================
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Background noise directory (for specific noise injection logic)
    BACKGROUND_NOISE_DIR = os.path.join(
        INPUT_ROOT, "train", "audio", "_background_noise_"
    )

    # Output directories
    WORKING_DIR = os.path.join("./working", IDEA_NAME)
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Model Checkpoints
    BEST_MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    LAST_MODEL_PATH = os.path.join(WORKING_DIR, "last_checkpoint.pth")

    # ==========================================
    # 3. Audio Processing (Spectral Oversampling)
    # ==========================================
    SAMPLE_RATE = 16000
    DURATION = 1.0  # seconds
    NUM_SAMPLES = int(SAMPLE_RATE * DURATION)

    # STFT / Mel Spectrogram parameters
    # Using N_FFT=1024 with Window=400 provides spectral oversampling
    N_FFT = 1024
    WIN_LENGTH = 400  # 25ms
    HOP_LENGTH = 160  # 10ms
    N_MELS = 128  # Number of Mel bands
    F_MIN = 0
    F_MAX = None  # Nyquist frequency

    # ==========================================
    # 4. Data Augmentation
    # ==========================================
    # Waveform Domain
    NOISE_INJECTION_PROB = 0.5
    NOISE_MIN_SNR_DB = 10.0
    NOISE_MAX_SNR_DB = 30.0

    # Spectrogram Domain (SpecAugment)
    SPEC_AUG_PROB = 0.5
    SPEC_AUG_TIME_MASK_PARAM = 20  # Max time steps to mask (conservative <20%)
    SPEC_AUG_FREQ_MASK_PARAM = 20  # Max freq bands to mask (conservative <20%)

    # ==========================================
    # 5. Model Architecture
    # ==========================================
    # EfficientNetV2-B0 (Fused-MBConv)
    MODEL_NAME = "tf_efficientnetv2_b0"
    NUM_CLASSES = 12
    IN_CHANNELS = 1

    # Exponential Moving Average (EMA)
    USE_EMA = True
    EMA_DECAY = 0.999

    # ==========================================
    # 6. Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 32
    NUM_EPOCHS = 30

    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2
    LABEL_SMOOTHING = 0.1

    # Scheduler (Cosine Annealing)
    T_MAX = NUM_EPOCHS
    MIN_LR = 1e-6

    # Early Stopping
    PATIENCE = 6

    @staticmethod
    def initialize():
        """
        Initialize the environment:
        1. Create working and submission directories.
        2. Set random seeds for reproducibility.
        """
        # Create directories
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)

        # Set seeds
        random.seed(Config.SEED)
        np.random.seed(Config.SEED)
        torch.manual_seed(Config.SEED)

        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(Config.SEED)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False


# Execute initialization upon module import
Config.initialize()
