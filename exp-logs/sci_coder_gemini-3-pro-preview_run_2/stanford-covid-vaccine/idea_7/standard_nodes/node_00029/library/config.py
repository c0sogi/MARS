import os


class Config:
    """
    Configuration for the Latent Structure-Refined Hybrid Network.
    Includes file paths, data processing parameters, model hyperparameters,
    and training settings.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    # Flag to control dataset size for debugging purposes
    DEBUG = False
    DEBUG_SUBSET_SIZE = 100

    # =========================================================================
    # File Paths
    # =========================================================================
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory for caching processed data and saving model checkpoints
    WORKING_DIR = "./working/idea_7"

    # Metadata Input files (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Raw Input files
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output files
    SUBMISSION_PATH = os.path.join(WORKING_DIR, "submission.csv")
    MODEL_CHECKPOINT = os.path.join(WORKING_DIR, "best_model.pth")

    # Cache files (used to store processed tensors for speed)
    TRAIN_CACHE = os.path.join(WORKING_DIR, "train_cache.npz")
    VAL_CACHE = os.path.join(WORKING_DIR, "val_cache.npz")
    TEST_CACHE = os.path.join(WORKING_DIR, "test_cache.npz")

    # =========================================================================
    # Data Parameters
    # =========================================================================
    SEQ_LENGTH = 107
    SEQ_SCORED = 68

    # Vocabulary mappings for One-Hot Encoding
    TOKEN_TO_INDEX_SEQ = {"A": 0, "G": 1, "C": 2, "U": 3}
    TOKEN_TO_INDEX_STRUCT = {".": 0, "(": 1, ")": 2}
    TOKEN_TO_INDEX_LOOP = {"S": 0, "M": 1, "I": 2, "B": 3, "H": 4, "E": 5, "X": 6}

    # Input Dimensions Calculation:
    # 1. Sequence One-Hot: 4 channels
    # 2. Structure One-Hot: 3 channels
    # 3. Loop Type One-Hot: 7 channels
    # 4. Partner Base Identity One-Hot: 4 channels
    # Total Input Channels = 4 + 3 + 7 + 4 = 18
    INPUT_CHANNELS = 18

    # Target Columns
    # All 5 provided in training data
    TARGET_COLS = ["reactivity", "deg_Mg_pH10", "deg_pH10", "deg_Mg_50C", "deg_50C"]
    # Only these 3 are scored in the competition metric (Masked Optimization)
    SCORED_COLS = ["reactivity", "deg_Mg_pH10", "deg_Mg_50C"]
    NUM_TARGETS = 5

    # =========================================================================
    # Model Hyperparameters (Latent Structure-Refined Hybrid Network)
    # =========================================================================
    # Backbone: Multi-Scale Dilated TCN
    # Reduced filters to 64 to prevent over-parameterization (Cite solution_lesson_node_00017)
    NUM_FILTERS = 64
    KERNEL_SIZE = 3
    # Dilations for capturing multi-scale context
    # Added dilation 32 to ensure Receptive Field > Sequence Length (Cite solution_lesson_node_00011)
    DILATION_RATES = [1, 2, 4, 8, 16, 32]
    DROPOUT = 0.3

    # Global Aggregation: BiGRU
    # Hidden size set to half of fusion dimension (Filters * Dilations)
    # This ensures BiGRU output dim matches input dim (Cite solution_lesson_node_00004)
    RNN_HIDDEN_DIM = (NUM_FILTERS * len(DILATION_RATES)) // 2
    RNN_LAYERS = 1
    RNN_BIDIRECTIONAL = True

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 64
    LEARNING_RATE = 1e-3
    EPOCHS = 50

    # Optimization
    EARLY_STOPPING_PATIENCE = 10
    WEIGHT_DECAY = 1e-4

    # Scheduler (ReduceLROnPlateau)
    SCHEDULER_FACTOR = 0.5
    SCHEDULER_PATIENCE = 3

    # Hardware
    NUM_WORKERS = 4

    @classmethod
    def setup(cls):
        """Ensures that the necessary working directories exist."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)


# Initialize directories upon import
Config.setup()
