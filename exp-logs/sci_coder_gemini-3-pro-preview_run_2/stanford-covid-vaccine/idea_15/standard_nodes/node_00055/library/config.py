import os
import torch


class Config:
    """
    Configuration for the Dense-Stacking Hybrid Network (Idea 15).
    Centralizes file paths, model hyperparameters, and training settings.
    """

    # =========================================================================
    # Directories & Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_15"
    CACHE_DIR = WORKING_DIR  # Storing cache directly in the working dir for simplicity

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # =========================================================================
    # Data Generation & Caching
    # =========================================================================
    SEQ_LEN = 107
    PRED_LEN = 68

    # Cache Keys
    # We use specific versioning 'dense_stacking_v1' to ensure the data loader
    # generates the required Partner Identity features and Neighbor Indices.
    TRAIN_CACHE_KEY = "train_data_dense_stacking_v1.npz"
    VAL_CACHE_KEY = "val_data_dense_stacking_v1.npz"
    TEST_CACHE_KEY = "test_data_dense_stacking_v1.npz"

    # =========================================================================
    # Model Hyperparameters
    # =========================================================================
    # Input Dimension Calculation:
    #   Sequence: 4 (A, G, C, U)
    #   Structure: 3 (., (, ))
    #   Loop Type: 7 (S, M, I, B, H, E, X)
    #   Partner Identity: 5 (A, G, C, U, None)
    #   Total: 4 + 3 + 7 + 5 = 19
    INPUT_DIM = 19

    # Backbone Config (Dense Dilated TCN)
    HIDDEN_DIM = 64  # "Growth Rate" / Channel Width
    KERNEL_SIZE = 3
    DROPOUT = 0.1
    # Exponential dilation schedule for global receptive field
    DILATIONS = [1, 2, 4, 8, 16, 32]

    # Latent Stacking Config
    # Number of neighbors to gather: Partner(j), 5' Neighbor(j-1), 3' Neighbor(j+1)
    STACKING_NEIGHBORS = 3

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 32
    LEARNING_RATE = 1e-3
    EPOCHS = 50
    NUM_WORKERS = 4
    SEED = 42

    # =========================================================================
    # Targets & Metrics
    # =========================================================================
    # All available ground truth columns
    TARGET_COLS = ["reactivity", "deg_Mg_pH10", "deg_pH10", "deg_Mg_50C", "deg_50C"]

    # Columns specifically used for the competition metric (MCRMSE)
    # We mask optimization to these columns to prevent negative transfer.
    SCORED_COLS = ["reactivity", "deg_Mg_pH10", "deg_Mg_50C"]

    # =========================================================================
    # System
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """Creates necessary working directories."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        # Cache dir is same as working dir in this config, but good practice to ensure
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
