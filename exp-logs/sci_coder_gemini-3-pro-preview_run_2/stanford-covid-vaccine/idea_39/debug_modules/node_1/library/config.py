import os
import torch


class Config:
    """
    Configuration class for the Graph-Smoothed Recurrent Dense Network (GS-RDN).
    Handles paths, hyperparameters, and runtime settings.
    """

    def __init__(self, debug: bool = False):
        # ---------------------------------------------------------------------
        # Directory and File Paths
        # ---------------------------------------------------------------------
        self.input_dir = "./input"
        self.metadata_dir = "./metadata"
        self.working_dir = "./working/idea_39"
        self.submission_dir = "./submission"

        # Ensure writable directories exist
        os.makedirs(self.working_dir, exist_ok=True)
        os.makedirs(self.submission_dir, exist_ok=True)

        # Metadata paths (generated by the metadata script)
        self.train_metadata_path = os.path.join(self.metadata_dir, "train.csv")
        self.val_metadata_path = os.path.join(self.metadata_dir, "val.csv")
        self.test_metadata_path = os.path.join(self.metadata_dir, "test.csv")
        self.sample_submission_path = os.path.join(
            self.input_dir, "sample_submission.csv"
        )

        # Cache paths for processed tensors (using .npz for efficiency)
        self.train_cache_path = os.path.join(
            self.working_dir, "train_data_gs_rdn_v1.npz"
        )
        self.val_cache_path = os.path.join(self.working_dir, "val_data_gs_rdn_v1.npz")
        self.test_cache_path = os.path.join(self.working_dir, "test_data_gs_rdn_v1.npz")

        # Final submission output path
        self.submission_path = os.path.join(self.submission_dir, "submission.csv")

        # Model checkpoint path
        self.model_save_path = os.path.join(self.working_dir, "best_model.pth")

        # ---------------------------------------------------------------------
        # Data Specifications
        # ---------------------------------------------------------------------
        self.seq_len = 107
        self.pred_len = 68

        # All available ground truth columns
        self.target_cols = [
            "reactivity",
            "deg_Mg_pH10",
            "deg_pH10",
            "deg_Mg_50C",
            "deg_50C",
        ]

        # Columns used for loss calculation and evaluation metric
        self.scored_cols = ["reactivity", "deg_Mg_pH10", "deg_Mg_50C"]

        # ---------------------------------------------------------------------
        # Model Architecture Hyperparameters
        # ---------------------------------------------------------------------
        # Input Channels Calculation:
        # Sequence (One-Hot A,G,C,U) -> 4
        # Structure (One-Hot (, ), .) -> 3
        # Loop Type (One-Hot S,M,I,B,H,E,X) -> 7
        # Partner Identity (One-Hot A,G,C,U) -> 4
        self.input_channels = 4 + 3 + 7 + 4  # Total: 18

        self.hidden_dim = 64  # Backbone capacity / Latent dimension
        self.feedback_dim = 32  # Dimension for the graph-smoothed feedback features
        self.dropout = 0.1
        self.kernel_size = 3

        # Dilated TCN Backbone settings
        self.dilations = [1, 2, 4, 8, 16, 32]

        # Aggregation RNN settings
        self.rnn_layers = 1
        self.bidirectional = True

        # ---------------------------------------------------------------------
        # Training Hyperparameters
        # ---------------------------------------------------------------------
        self.seed = 42
        self.device = "cuda" if torch.cuda.is_available() else "cpu"
        self.num_workers = 2

        self.lr = 1e-3
        self.weight_decay = 1e-4
        self.patience = 5  # Early stopping patience

        # Loss weighting for Iterative Refinement
        # L = MCRMSE(Pass2) + 0.5 * MCRMSE(Pass1)
        self.loss_w_pass2 = 1.0
        self.loss_w_pass1 = 0.5

        # ---------------------------------------------------------------------
        # Runtime Control (Debug vs Production)
        # ---------------------------------------------------------------------
        if debug:
            self.batch_size = 4
            self.epochs = 2
            self.sample_size = 50  # Process only 50 samples for debugging
        else:
            self.batch_size = 32
            self.epochs = 25
            self.sample_size = None  # Use full dataset
