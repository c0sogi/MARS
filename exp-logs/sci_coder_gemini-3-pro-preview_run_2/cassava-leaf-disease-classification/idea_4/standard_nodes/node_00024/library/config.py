import os
import torch


class Config:
    def __init__(self):
        """
        Initializes the configuration and ensures the working directory exists.
        """
        os.makedirs(self.working_dir, exist_ok=True)

    # ==========================================
    # General Settings
    # ==========================================
    seed = 42
    debug = False  # Set to True to train on a small subset for debugging
    debug_sample_size = 500  # Number of samples if debug is True
    num_workers = 4  # Optimized for 12 vCPUs
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # ==========================================
    # Directories & Paths
    # ==========================================
    # Input Paths
    input_dir = "./input"
    metadata_dir = "./metadata"

    # Metadata Files (Generated by previous steps)
    train_metadata_path = os.path.join(metadata_dir, "train.csv")
    val_metadata_path = os.path.join(metadata_dir, "val.csv")
    test_metadata_path = os.path.join(metadata_dir, "test.csv")

    # Image Directory
    # Note: Metadata contains relative paths (e.g., 'train_images/123.jpg')
    # Joining input_dir with these relative paths locates the files correctly.
    base_image_path = input_dir

    # Output Paths
    working_dir = "./working/idea_4"
    best_model_path = os.path.join(working_dir, "best_model.pth")
    submission_path = os.path.join(working_dir, "submission.csv")

    # ==========================================
    # Model Hyperparameters
    # ==========================================
    # Using ConvNeXt Small for higher capacity, trained longer to ensure convergence
    # Cite solution_lesson_node_00022 (Convergence over CV)
    # Cite solution_lesson_node_00023 (Regularization scaling)
    model_name = "convnext_small"
    pretrained = True
    num_classes = 5

    # Stochastic Depth (Drop Path) rate for regularization
    drop_path_rate = 0.2

    # ==========================================
    # Data Hyperparameters
    # ==========================================
    image_size = 224
    batch_size = 32

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    epochs = 10
    learning_rate = 1e-4
    weight_decay = 0.05  # Standard for AdamW
    min_lr = 1e-6

    # Early Stopping
    patience = 3

    # ==========================================
    # Augmentation & Regularization
    # ==========================================
    # MixUp and CutMix parameters
    mixup_alpha = 0.8
    cutmix_alpha = 1.0
    mixup_prob = 0.5  # Probability of applying MixUp/CutMix to a batch

    # Label Smoothing to handle noisy labels
    label_smoothing = 0.1

    # Test Time Augmentation
    tta_flips = True  # Enable horizontal flip TTA during inference
