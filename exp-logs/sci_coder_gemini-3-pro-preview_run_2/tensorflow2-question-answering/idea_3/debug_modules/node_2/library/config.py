import os


class Config:
    """
    Configuration class for the Siamese Gated Convolutional Ranker project.
    """

    # -------------------------------------------------------------------------
    # Directory Structure
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_3"
    SUBMISSION_DIR = "./submission"

    # -------------------------------------------------------------------------
    # Input File Paths
    # -------------------------------------------------------------------------
    # Raw Data
    TRAIN_DATA_PATH = os.path.join(INPUT_DIR, "simplified-nq-train.jsonl")
    TEST_DATA_PATH = os.path.join(INPUT_DIR, "simplified-nq-test.jsonl")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "validation_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # -------------------------------------------------------------------------
    # Cache File Paths (for deterministic data processing)
    # -------------------------------------------------------------------------
    # Vocabulary and Embeddings
    VOCAB_PATH = os.path.join(WORKING_DIR, "vocab.npy")
    EMBEDDING_MATRIX_PATH = os.path.join(WORKING_DIR, "embedding_matrix.npy")

    # Processed Features (if caching features)
    TRAIN_FEATURES_PATH = os.path.join(WORKING_DIR, "train_features.parquet")
    VAL_FEATURES_PATH = os.path.join(WORKING_DIR, "val_features.parquet")
    TEST_FEATURES_PATH = os.path.join(WORKING_DIR, "test_features.parquet")

    # Model Checkpoint
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "siamese_cnn_ranker.pt")

    # Submission Output
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Model Hyperparameters
    # -------------------------------------------------------------------------
    EMBEDDING_DIM = 100  # Dimension of word embeddings (e.g., GloVe 100d)
    MAX_Q_LEN = 30  # Maximum sequence length for questions
    MAX_C_LEN = 300  # Maximum sequence length for long answer candidates
    KERNEL_SIZES = [2, 3, 4]  # Kernel sizes for 1D Convolutions
    NUM_FILTERS = 128  # Number of filters per kernel size
    DROPOUT = 0.2  # Dropout rate for regularization
    HIDDEN_DIM = 256  # Dimension for any dense layers if added

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 64
    LEARNING_RATE = 0.001
    NUM_EPOCHS = 5
    NEG_SAMPLES = 4  # Number of negative candidates per positive sample
    PATIENCE = 2  # Early stopping patience (epochs)

    # -------------------------------------------------------------------------
    # Inference / Post-processing Thresholds
    # -------------------------------------------------------------------------
    LONG_CONFIDENCE_THRESHOLD = 0.5  # Min probability to predict a long answer
    SHORT_OVERLAP_THRESHOLD = 2  # Min n-gram overlap count to predict short answer

    # -------------------------------------------------------------------------
    # System & Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4  # Number of dataloader workers

    # -------------------------------------------------------------------------
    # Debugging
    # -------------------------------------------------------------------------
    DEBUG = False  # Set to True to run on a small subset
    DEBUG_SIZE = 5000  # Number of samples to use when DEBUG is True

    @classmethod
    def setup(cls):
        """
        Ensures that necessary working and submission directories exist.
        Should be called at the start of the pipeline.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories when module is imported
Config.setup()
