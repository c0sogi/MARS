import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration class for the Catheter and Line Position Detection task.
    Implements the settings for 'Idea 2': ConvNeXt-Tiny with high-resolution input (768x768).
    """

    # --- General Settings ---
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data for debugging
    DEBUG_SAMPLE_SIZE = 100  # Number of samples to use in debug mode

    # --- Directory Paths ---
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory specific to this idea/experiment
    WORKING_DIR = "./working/idea_2"

    # Metadata files generated by the provided script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output paths
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = "./submission/submission.csv"

    # --- Data Configuration ---
    # High resolution for ConvNeXt to resolve thin lines
    IMAGE_SIZE = 768
    NUM_WORKERS = 12  # Matches available vCPUs

    # Target Columns (11 classes)
    TARGET_COLS = [
        "ETT - Abnormal",
        "ETT - Borderline",
        "ETT - Normal",
        "NGT - Abnormal",
        "NGT - Borderline",
        "NGT - Incompletely Imaged",
        "NGT - Normal",
        "CVC - Abnormal",
        "CVC - Borderline",
        "CVC - Normal",
        "Swan Ganz Catheter Present",
    ]
    NUM_CLASSES = len(TARGET_COLS)

    # --- Model Architecture ---
    # Using ConvNeXt-Tiny as per the strategy (LayerNorm handles batch size flexibility better)
    MODEL_NAME = "convnext_tiny"
    PRETRAINED = True

    # --- Training Hyperparameters ---
    # Batch size 16 fits 768x768 on 40GB A100 (conservative estimate)
    # Reduced to 4 to prevent OOM on smaller GPUs (approx 16GB VRAM)
    BATCH_SIZE = 4
    EPOCHS = 10

    # Mixed Precision Training
    USE_AMP = True

    # Optimizer & Scheduler
    LEARNING_RATE = 2e-4  # Slightly higher for OneCycle
    WEIGHT_DECAY = 1e-2
    MAX_GRAD_NORM = 10.0

    # OneCycleLR settings
    PCT_START = 0.1
    DIV_FACTOR = 25.0
    FINAL_DIV_FACTOR = 1000.0

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 3
    EARLY_STOPPING_MODE = "max"  # We want to maximize AUC

    # --- Compute ---
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Initializes the environment:
        1. Creates necessary directories.
        2. Sets random seeds for reproducibility.
        """
        # Create directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(os.path.dirname(cls.SUBMISSION_PATH), exist_ok=True)

        # Set seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.cuda.manual_seed_all(cls.SEED)
            # Ensure deterministic behavior for CuDNN
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

        print(
            f"Configuration setup complete. Working dir: {cls.WORKING_DIR}, Device: {cls.DEVICE}"
        )
