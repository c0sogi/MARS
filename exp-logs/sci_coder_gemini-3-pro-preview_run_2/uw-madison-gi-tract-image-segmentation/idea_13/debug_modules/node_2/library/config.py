import os
import torch


class Config:
    """
    Configuration for Idea 13: 2.5D U-Net++ with Patch-Based Learning.
    This module defines all file paths, model hyperparameters, and training settings.
    """

    # ====================================================
    # General Settings
    # ====================================================
    SEED = 42
    DEBUG = False  # Set to True to use a small subset of data for debugging
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4  # Number of workers for data loading

    # ====================================================
    # Directories & Paths
    # ====================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_13"
    SUBMISSION_DIR = "./submission"

    # Metadata Paths (generated by metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Paths
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Ensure necessary directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ====================================================
    # Data Configuration
    # ====================================================
    # 2.5D Input: Slice i-1, Slice i, Slice i+1
    IN_CHANNELS = 3

    # Segmentation Classes
    CLASSES = ["large_bowel", "small_bowel", "stomach"]
    NUM_CLASSES = len(CLASSES)

    # Patch-Based Learning Strategy
    # Training: Extract random patches of this size from native resolution images
    PATCH_SIZE = (320, 320)

    # Inference: Sliding Window parameters
    # We do not resize test images; we slide a window with overlap
    WINDOW_SIZE = (320, 320)
    STRIDE = 160  # 50% overlap to ensure smooth boundary blending

    # Physical Slice Depth (for 3D Hausdorff calculation context)
    SLICE_DEPTH_MM = 3.0

    # ====================================================
    # Model Configuration
    # ====================================================
    ARCH = "UnetPlusPlus"
    BACKBONE = "efficientnet-b4"
    ENCODER_WEIGHTS = "imagenet"
    DEEP_SUPERVISION = True  # Enable deep supervision for U-Net++

    # ====================================================
    # Training Hyperparameters
    # ====================================================
    EPOCHS = 15
    BATCH_SIZE = 32  # Tuned for A100 40GB with 320x320 patches

    # Optimizer
    LEARNING_RATE = 2e-4
    WEIGHT_DECAY = 1e-5

    # Scheduler (Cosine Annealing)
    T_MAX = EPOCHS
    MIN_LR = 1e-6

    # Loss Function (Combined BCE + Tversky)
    BCE_WEIGHT = 0.5
    TVERSKY_WEIGHT = 0.5

    # Tversky Loss Parameters
    # Beta > Alpha emphasizes Recall (penalizing False Negatives more)
    TVERSKY_ALPHA = 0.3
    TVERSKY_BETA = 0.7
    TVERSKY_SMOOTH = 1.0

    # ====================================================
    # Metric Weights (for Competition Scoring)
    # ====================================================
    DICE_WEIGHT = 0.4
    HAUSDORFF_WEIGHT = 0.6
