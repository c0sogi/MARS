import os
import torch
import random
import numpy as np


class Config:
    """
    Central configuration for the stomach and intestine segmentation pipeline.
    Contains hyperparameters, file paths, and system settings.
    """

    # ==========================
    # System Settings
    # ==========================
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 12  # Optimized for the available 12 vCPUs

    # ==========================
    # Debugging / Development
    # ==========================
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 500  # Number of samples to use when DEBUG is True

    # ==========================
    # File Paths
    # ==========================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the previous step
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Working directory for caching processed data and models
    WORKING_DIR = "./working"
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_1")
    MODEL_SAVE_PATH = os.path.join(CACHE_DIR, "best_model.pth")

    # Submission output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================
    # Data Parameters
    # ==========================
    IMAGE_SIZE = (256, 256)  # Input resolution (Height, Width)
    IN_CHANNELS = 3  # 2.5D Input: [slice-1, slice, slice+1]
    NUM_CLASSES = 3  # Classes: large_bowel, small_bowel, stomach
    CLASS_LABELS = ["large_bowel", "small_bowel", "stomach"]

    # Physical properties
    SLICE_DEPTH_MM = 3.0  # Thickness in superior-inferior direction

    # ==========================
    # Model Architecture
    # ==========================
    BACKBONE = "mobilenet_v2"
    PRETRAINED = True
    ENCODER_WEIGHTS = "imagenet"

    # ==========================
    # Training Hyperparameters
    # ==========================
    BATCH_SIZE = 32
    EPOCHS = 15
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Learning Rate Scheduler (Cosine Annealing)
    SCHEDULER_T_MAX = EPOCHS
    SCHEDULER_MIN_LR = 1e-6

    # Loss Function Weights
    BCE_WEIGHT = 0.5
    DICE_WEIGHT = 0.5

    # ==========================
    # Inference & Post-processing
    # ==========================
    PRED_THRESHOLD = 0.5  # Probability threshold for binary mask
    MIN_MASK_AREA = 0  # Minimum pixel area to retain a mask (noise filtering)


def set_seed(seed=42):
    """
    Sets the random seed for reproducibility across Python, NumPy, and PyTorch.

    Args:
        seed (int): The seed value to use.
    """
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False
    os.environ["PYTHONHASHSEED"] = str(seed)


def setup_system(seed=None):
    """
    Initializes the system environment.
    1. Sets random seeds.
    2. Creates necessary directories for caching and submission.

    Args:
        seed (int, optional): Specific seed to use. If None, uses Config.SEED.
    """
    if seed is None:
        seed = Config.SEED

    set_seed(seed)

    # Create directories
    os.makedirs(Config.CACHE_DIR, exist_ok=True)
    os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)
