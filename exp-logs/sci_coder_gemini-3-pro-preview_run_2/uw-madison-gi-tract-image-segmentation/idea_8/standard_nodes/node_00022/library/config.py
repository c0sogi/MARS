import os
import torch


class Config:
    """
    Configuration for Idea 8: 2.5D Attention U-Net.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 500  # Number of samples to use if DEBUG is True

    # =========================================================================
    # Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the provided script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output directories
    WORKING_DIR = "./working/idea_8"
    CACHE_DIR = WORKING_DIR  # Directory to store processed/cached data
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Parameters
    # =========================================================================
    IMG_SIZE = 256  # Resizing input to 256x256
    IN_CHANNELS = 3  # 2.5D Input: Slice i-1, Slice i, Slice i+1
    NUM_CLASSES = 3  # Large Bowel, Small Bowel, Stomach

    # Preprocessing - Contrast Limited Adaptive Histogram Equalization
    USE_CLAHE = True
    CLAHE_CLIP_LIMIT = 2.0
    CLAHE_TILE_GRID_SIZE = (8, 8)

    # =========================================================================
    # Model Architecture
    # =========================================================================
    ENCODER_NAME = "efficientnet_b0"
    ENCODER_WEIGHTS = "imagenet"
    USE_ATTENTION_GATES = True  # Enable Attention Gates in U-Net decoder

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 32
    NUM_EPOCHS = 15
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2

    # Tversky Loss Parameters
    # Alpha penalizes False Positives, Beta penalizes False Negatives
    # Beta > Alpha emphasizes Recall (useful for small objects)
    TVERSKY_ALPHA = 0.3
    TVERSKY_BETA = 0.7
    TVERSKY_SMOOTH = 1.0

    # Scheduler (Cosine Annealing)
    T_MAX = NUM_EPOCHS
    ETA_MIN = 1e-6

    # =========================================================================
    # Compute
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4

    # =========================================================================
    # Post-Processing / Inference
    # =========================================================================
    THRESHOLD = 0.5
    # 3D Connected Component Analysis
    KEEP_LARGEST_COMPONENT = True

    @classmethod
    def setup(cls):
        """
        Ensures necessary working directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories upon import
Config.setup()
