import os
import torch


class Config:
    """
    Configuration class for the EEG Harmful Brain Activity Detection pipeline.
    Centralizes all file paths, hyperparameters, and constants.
    """

    # -------------------------------------------------------------------------
    # Directory & File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_1"
    OUTPUT_DIR = "./submission"

    # Ensure working and output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    # Data Paths
    TRAIN_EEGS_DIR = os.path.join(INPUT_DIR, "train_eegs")
    TEST_EEGS_DIR = os.path.join(INPUT_DIR, "test_eegs")

    # Metadata Paths (Generated by the provided metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Submission Path
    SUBMISSION_FILE = os.path.join(OUTPUT_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data & Signal Processing Parameters
    # -------------------------------------------------------------------------
    SAMPLING_RATE = 200  # Hz
    DURATION = 50  # Seconds
    EEG_LENGTH = SAMPLING_RATE * DURATION  # 10,000 samples

    # Spectrogram Generation
    N_MELS = 128  # Number of Mel bands
    N_FFT = 1024  # FFT window size
    HOP_LENGTH = 512  # Hop length for STFT
    FMIN = 0  # Min frequency
    FMAX = SAMPLING_RATE // 2  # Max frequency (Nyquist)

    # Input Image Dimensions for the Model (Height, Width)
    # The pipeline will resize the generated spectrograms to this size.
    IMG_SIZE = (512, 512)

    # -------------------------------------------------------------------------
    # Model Architecture Parameters
    # -------------------------------------------------------------------------
    MODEL_NAME = "tf_efficientnet_b1_ns"  # Pre-trained backbone from timm
    NUM_CLASSES = 6
    IN_CHANNELS = 3  # EfficientNet expects 3 channels (we will replicate mono spec)
    PRETRAINED = True

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    SEED = 42
    BATCH_SIZE = 32  # Adjust based on GPU VRAM (A100 can handle larger, but 32 is safe)
    EPOCHS = 10  # Max epochs (Early Stopping will likely cut this short)
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2
    MAX_GRAD_NORM = 10.0  # Gradient clipping
    PATIENCE = 3  # Early stopping patience
    NUM_WORKERS = 4  # For DataLoader

    # Hardware
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # -------------------------------------------------------------------------
    # Labels & Targets
    # -------------------------------------------------------------------------
    # The raw vote count columns in the original metadata
    VOTE_COLS = [
        "seizure_vote",
        "lpd_vote",
        "gpd_vote",
        "lrda_vote",
        "grda_vote",
        "other_vote",
    ]

    # The normalized probability columns created in the metadata step (Targets)
    TARGET_COLS = [
        "seizure_prob",
        "lpd_prob",
        "gpd_prob",
        "lrda_prob",
        "grda_prob",
        "other_prob",
    ]

    # -------------------------------------------------------------------------
    # Montage Configuration (Longitudinal Bipolar / "Double Banana")
    # -------------------------------------------------------------------------
    # This defines the specific electrode subtractions to create the 4 chains.
    # LL: Left Lateral, RL: Right Lateral, LP: Left Parasagittal, RP: Right Parasagittal
    MONTAGE_PAIRS = {
        "LL": [("Fp1", "F7"), ("F7", "T3"), ("T3", "T5"), ("T5", "O1")],
        "RL": [("Fp2", "F8"), ("F8", "T4"), ("T4", "T6"), ("T6", "O2")],
        "LP": [("Fp1", "F3"), ("F3", "C3"), ("C3", "P3"), ("P3", "O1")],
        "RP": [("Fp2", "F4"), ("F4", "C4"), ("C4", "P4"), ("P4", "O2")],
    }

    # Ordered list of all electrodes present in the raw parquet files
    # (Excluding EKG which is usually the last column)
    ELECTRODES = [
        "Fp1",
        "F3",
        "C3",
        "P3",
        "F7",
        "T3",
        "T5",
        "O1",
        "Fz",
        "Cz",
        "Pz",
        "Fp2",
        "F4",
        "C4",
        "P4",
        "F8",
        "T4",
        "T6",
        "O2",
        "EKG",
    ]

    # -------------------------------------------------------------------------
    # Debugging
    # -------------------------------------------------------------------------
    DEBUG = False  # Set to True to run on a small subset of data
    DEBUG_SAMPLE_SIZE = 100  # Number of samples to use if DEBUG is True
