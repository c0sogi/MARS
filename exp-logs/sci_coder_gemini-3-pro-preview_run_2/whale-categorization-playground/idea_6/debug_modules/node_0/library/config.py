import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration class for Whale Species Prediction.
    Centralizes all hyperparameters, file paths, and system settings.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging

    # =========================================================================
    # File System Paths
    # =========================================================================
    INPUT_DIR = "./input"
    TRAIN_IMG_DIR = os.path.join(INPUT_DIR, "train")
    TEST_IMG_DIR = os.path.join(INPUT_DIR, "test")

    # Metadata generated by the provided script
    METADATA_DIR = "./metadata"
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Working directory for caching and model checkpoints
    WORKING_DIR = "./working/idea_6"
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Submission directory
    SUBMISSION_DIR = "./submission"
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Model Checkpoint Path
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # =========================================================================
    # Model Hyperparameters
    # =========================================================================
    BACKBONE = "efficientnet_b4"
    EMBEDDING_SIZE = 512
    USE_GRADIENT_CHECKPOINTING = True  # Critical for fitting B4 with larger batches

    # ArcFace Head Parameters
    ARC_S = 30.0
    ARC_M = 0.50

    # Placeholder for Number of Classes (updated dynamically by data loader)
    NUM_CLASSES = 0

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 32
    NUM_EPOCHS = 20

    # Optimizer (AdamW)
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4

    # Scheduler (Cosine Annealing)
    SCHEDULER_MIN_LR = 1e-6

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 5

    # =========================================================================
    # Progressive Resolution Strategy
    # =========================================================================
    # Phase 1: Warm-up on smaller images for faster convergence
    IMG_SIZE_START = 256
    PHASE_1_EPOCHS = 12  # Run first 12 epochs at 256x256

    # Phase 2: Fine-tuning on larger images for detail resolution
    IMG_SIZE_FINAL = 384

    # =========================================================================
    # Inference Hyperparameters
    # =========================================================================
    # Threshold for open-set rejection (predicting 'new_whale')
    # If distance to nearest neighbor > threshold, predict new_whale
    CONFIDENCE_THRESHOLD = 0.6  # Calibrate based on validation
    TOP_K = 5

    # =========================================================================
    # System Settings
    # =========================================================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Adjust num_workers based on CPU core availability (12 vCPUs available)
    NUM_WORKERS = 4

    @staticmethod
    def get_cache_path(subset_name, resolution):
        """
        Generates a consistent cache filename based on subset and resolution.
        Example: ./working/idea_6/train_images_384.npy
        """
        filename = f"{subset_name}_images_{resolution}.npy"
        return os.path.join(Config.WORKING_DIR, filename)

    @staticmethod
    def set_seed(seed=42):
        """
        Sets the random seed for reproducibility across Python, NumPy, and PyTorch.
        """
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            # Ensure deterministic behavior
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
        os.environ["PYTHONHASHSEED"] = str(seed)
