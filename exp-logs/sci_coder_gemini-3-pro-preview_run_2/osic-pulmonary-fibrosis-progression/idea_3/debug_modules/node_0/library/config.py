import os
import torch


class Config:
    """
    Configuration for the Attention-Enhanced Neural Varying-Coefficient Network.
    Defines global constants, file paths, and hyperparameters.
    """

    # ==========================================
    # Reproducibility
    # ==========================================
    SEED = 42

    # ==========================================
    # Directories
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_3"
    SUBMISSION_DIR = "./submission"

    # ==========================================
    # Input Data Paths
    # ==========================================
    # Metadata files generated by the metadata script
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Raw DICOM directories
    TRAIN_DICOM_DIR = os.path.join(INPUT_DIR, "train")
    TEST_DICOM_DIR = os.path.join(INPUT_DIR, "test")

    # Sample submission for formatting reference
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # ==========================================
    # Output Paths
    # ==========================================
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Feature Caching (Frozen Embeddings)
    # ==========================================
    # Paths to store pre-computed features to speed up training
    # These are saved in the working directory
    TRAIN_FEATURES_PATH = os.path.join(WORKING_DIR, "train_features.npy")
    TRAIN_TABULAR_PATH = os.path.join(WORKING_DIR, "train_tabular.npy")
    TRAIN_TARGETS_PATH = os.path.join(WORKING_DIR, "train_targets.npy")

    VAL_FEATURES_PATH = os.path.join(WORKING_DIR, "val_features.npy")
    VAL_TABULAR_PATH = os.path.join(WORKING_DIR, "val_tabular.npy")
    VAL_TARGETS_PATH = os.path.join(WORKING_DIR, "val_targets.npy")

    TEST_FEATURES_PATH = os.path.join(WORKING_DIR, "test_features.npy")
    TEST_TABULAR_PATH = os.path.join(WORKING_DIR, "test_tabular.npy")
    TEST_IDS_PATH = os.path.join(WORKING_DIR, "test_ids.npy")

    # ==========================================
    # Data Hyperparameters
    # ==========================================
    NUM_SLICES = 12  # Number of slices to sample per patient (Structural Innovation)
    IMG_SIZE = 224  # Input resolution for EfficientNet
    BATCH_SIZE = 32  # Batch size for training
    NUM_WORKERS = 2  # DataLoader workers

    # Debugging: Set to True to use a small subset of data for rapid testing
    DEBUG = False
    DEBUG_SIZE = 50

    # ==========================================
    # Model Architecture Hyperparameters
    # ==========================================
    # Backbone
    MODEL_NAME = "efficientnet_b0"
    EMBED_DIM = 1280  # Output dimension of EfficientNet-B0

    # Tabular Features
    CONTINUOUS_COLS = ["Age", "Baseline_FVC", "Baseline_Percent"]
    CATEGORICAL_COLS = ["Sex", "SmokingStatus"]

    # MLP Heads
    HIDDEN_DIM = 512  # Hidden layer size for the varying-coefficient MLP
    DROPOUT = 0.2  # Dropout probability

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    EPOCHS = 100
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-5
    PATIENCE = 15  # Early stopping patience

    # Metric Constants
    MAX_ERROR = 1000  # Delta clipping
    MIN_CONFIDENCE = 70  # Sigma clipping

    # ==========================================
    # Hardware
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Ensures that the necessary working and submission directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
