import os
import numpy as np
import pandas as pd
import joblib
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.decomposition import TruncatedSVD
from sklearn.metrics.pairwise import cosine_similarity
from joblib import Parallel, delayed
from library.config import Config
from library.utils import save_joblib, load_joblib, set_seed


class DualViewFeaturePipeline:
    """
    Implements the Decoupled Dual-View Neighborhood Aggregation pipeline.
    Manages TF-IDF and SVD models, and extracts features based on
    Lexical and Latent similarities between Markdown and Code cells.
    """

    def __init__(self):
        self.config = Config
        self.tfidf_path = self.config.CACHE_TFIDF_MODEL
        self.svd_path = self.config.CACHE_SVD_MODEL

        # Initialize models with placeholders or load if they exist (handled in fit/transform)
        self.tfidf = None
        self.svd = None

        set_seed(self.config.SEED)

    def fit(self, df_train):
        """
        Fits the TF-IDF and SVD models on the training markdown cells.
        Saves the models to disk.
        """
        print("Fitting Vectorizers on Training Data...")

        # Filter for markdown cells only for vocabulary learning
        md_cells = (
            df_train[df_train["cell_type"] == "markdown"]["source"]
            .astype(str)
            .fillna("")
        )

        # 1. Fit TF-IDF
        print(f"Fitting TF-IDF with params: {self.config.TFIDF_PARAMS}")
        self.tfidf = TfidfVectorizer(**self.config.TFIDF_PARAMS)
        self.tfidf.fit(md_cells)
        save_joblib(self.tfidf, self.tfidf_path)

        # 2. Fit SVD
        # Transform a subset or all to fit SVD.
        # For stability, we use the sparse matrix generated by TF-IDF
        print(f"Transforming text for SVD fitting...")
        tfidf_matrix = self.tfidf.transform(md_cells)

        print(f"Fitting TruncatedSVD with n_components={self.config.SVD_N_COMPONENTS}")
        self.svd = TruncatedSVD(
            n_components=self.config.SVD_N_COMPONENTS,
            random_state=self.config.SVD_RANDOM_STATE,
        )
        self.svd.fit(tfidf_matrix)
        save_joblib(self.svd, self.svd_path)

        print("Vectorizers fitted and saved.")

    def _load_models(self):
        """Helper to load models if they are not in memory."""
        if self.tfidf is None:
            if os.path.exists(self.tfidf_path):
                self.tfidf = load_joblib(self.tfidf_path)
            else:
                raise FileNotFoundError("TF-IDF model not found. Run fit() first.")

        if self.svd is None:
            if os.path.exists(self.svd_path):
                self.svd = load_joblib(self.svd_path)
            else:
                raise FileNotFoundError("SVD model not found. Run fit() first.")

    def extract_features(self, df, mode="train", load_cached_data=True):
        """
        Main method to extract features. Handles caching.

        Args:
            df: DataFrame containing notebook cells.
            mode: 'train', 'val', or 'test'. Used for cache naming.
            load_cached_data: Boolean to enable/disable loading from cache.

        Returns:
            df_features: DataFrame with extracted features and targets.
        """
        # Determine cache path based on mode
        if mode == "train":
            cache_path = self.config.CACHE_TRAIN_FEATURES
        elif mode == "val":
            cache_path = self.config.CACHE_VAL_FEATURES
        elif mode == "test":
            cache_path = self.config.CACHE_TEST_FEATURES
        else:
            raise ValueError(f"Unknown mode: {mode}")

        # 1. Try Load Cache
        if load_cached_data and os.path.exists(cache_path):
            print(f"[{mode}] Loading extracted features from {cache_path}...")
            return pd.read_parquet(cache_path)

        # 2. Compute Features
        print(f"[{mode}] Extracting features from scratch...")
        self._load_models()

        # Ensure working directory exists
        os.makedirs(os.path.dirname(cache_path), exist_ok=True)

        # Transform all text to vectors (Global Scope)
        print(f"[{mode}] Vectorizing text data...")
        all_text = df["source"].astype(str).fillna("")
        tfidf_matrix = self.tfidf.transform(all_text)
        svd_matrix = self.svd.transform(tfidf_matrix)

        # Prepare for parallel processing
        # We need to group by notebook ID
        # To avoid passing the huge matrices around, we pass indices.

        # Create a mapping of global index to notebook structure
        # We assume df index is reset and continuous 0..N-1
        df = df.reset_index(drop=True)
        groups = df.groupby("id")

        # Define the worker function for Parallel execution
        # We use a closure or static method, but here we define a helper function
        # that takes indices and slices the pre-computed matrices.

        # Pre-compute necessary columns to avoid overhead inside loop
        cell_types = df["cell_type"].values
        pct_ranks = df["pct_rank"].values

        # List of (notebook_id, indices)
        tasks = []
        for nb_id, group_indices in groups.indices.items():
            tasks.append((nb_id, group_indices))

        print(f"[{mode}] Processing {len(tasks)} notebooks with Parallel(n_jobs=-1)...")

        # Use threading backend to share memory of tfidf_matrix/svd_matrix
        results = Parallel(n_jobs=-1, backend="threading")(
            delayed(self._process_notebook)(
                nb_id, indices, cell_types, pct_ranks, tfidf_matrix, svd_matrix
            )
            for nb_id, indices in tasks
        )

        # Flatten results
        # results is a list of lists of dicts (one dict per markdown cell)
        flat_results = [item for sublist in results for item in sublist]

        if not flat_results:
            # Handle empty case (e.g. no markdown cells in dataset)
            print("Warning: No features extracted. Returning empty DataFrame.")
            return pd.DataFrame()

        df_features = pd.DataFrame(flat_results)

        # Optimize types
        float_cols = [
            c for c in df_features.columns if c not in ["id", "cell_id", "ancestor_id"]
        ]
        for c in float_cols:
            df_features[c] = df_features[c].astype(np.float32)

        # 3. Save Cache
        print(f"[{mode}] Saving features to {cache_path}...")
        df_features.to_parquet(cache_path, index=False)

        return df_features

    def _process_notebook(
        self, nb_id, indices, all_cell_types, all_pct_ranks, tfidf_matrix, svd_matrix
    ):
        """
        Process a single notebook to extract features for its markdown cells.

        Args:
            nb_id: Notebook ID
            indices: Indices of rows in the global dataframe belonging to this notebook
            all_cell_types: Global array of cell types
            all_pct_ranks: Global array of percent ranks
            tfidf_matrix: Global sparse TF-IDF matrix
            svd_matrix: Global dense SVD matrix

        Returns:
            List of dictionaries (one per markdown cell)
        """
        # Identify Code and Markdown indices within this notebook
        nb_cell_types = all_cell_types[indices]

        # Boolean masks relative to the 'indices' array
        is_code = nb_cell_types == "code"
        is_md = nb_cell_types == "markdown"

        code_indices = indices[is_code]
        md_indices = indices[is_md]

        # If no markdown cells, nothing to predict
        if len(md_indices) == 0:
            return []

        # If no code cells, we cannot compute neighbors.
        # Return defaults (should be rare/impossible in valid data)
        if len(code_indices) == 0:
            return self._create_empty_features(nb_id, md_indices, all_pct_ranks)

        # Get Code Cell Ranks (The anchors)
        # In the dataframe, 'pct_rank' for code cells is their normalized position [0, 1]
        code_ranks = all_pct_ranks[code_indices]

        # Slice matrices
        # Code vectors (Candidates)
        code_tfidf = tfidf_matrix[code_indices]
        code_svd = svd_matrix[code_indices]

        # Markdown vectors (Queries)
        md_tfidf = tfidf_matrix[md_indices]
        md_svd = svd_matrix[md_indices]

        # --- Lexical View (TF-IDF) ---
        # Compute Cosine Similarity (Sparse x Sparse -> Dense)
        # Result shape: (n_md, n_code)
        lex_sim_matrix = cosine_similarity(md_tfidf, code_tfidf)

        # --- Latent View (SVD) ---
        # Compute Cosine Similarity (Dense x Dense -> Dense)
        lat_sim_matrix = cosine_similarity(md_svd, code_svd)

        features_list = []

        K = self.config.NEIGHBOR_TOP_K

        # Iterate over each markdown cell in this notebook
        for i, global_md_idx in enumerate(md_indices):

            # --- Process Lexical View ---
            lex_sims = lex_sim_matrix[i]
            # Get indices of Top-K highest similarity
            # argsort is ascending, so take last K and reverse
            if len(lex_sims) > K:
                top_k_idx = np.argpartition(lex_sims, -K)[-K:]
                # Sort these K to get exact order for NN1
                top_k_idx = top_k_idx[np.argsort(lex_sims[top_k_idx])[::-1]]
            else:
                top_k_idx = np.argsort(lex_sims)[::-1]

            lex_top_sims = lex_sims[top_k_idx]
            lex_top_ranks = code_ranks[top_k_idx]

            # Features
            lex_nn1_sim = lex_top_sims[0]
            lex_nn1_rank = lex_top_ranks[0]

            # Weighted Mean Rank
            # Add epsilon to avoid division by zero if all sims are 0
            sum_sim = np.sum(lex_top_sims) + 1e-9
            lex_wmean_rank = np.sum(lex_top_ranks * lex_top_sims) / sum_sim
            lex_mean_sim = np.mean(lex_top_sims)
            lex_std_rank = np.std(lex_top_ranks)

            # --- Process Latent View ---
            lat_sims = lat_sim_matrix[i]
            if len(lat_sims) > K:
                top_k_idx_lat = np.argpartition(lat_sims, -K)[-K:]
                top_k_idx_lat = top_k_idx_lat[np.argsort(lat_sims[top_k_idx_lat])[::-1]]
            else:
                top_k_idx_lat = np.argsort(lat_sims)[::-1]

            lat_top_sims = lat_sims[top_k_idx_lat]
            lat_top_ranks = code_ranks[top_k_idx_lat]

            lat_nn1_sim = lat_top_sims[0]
            lat_nn1_rank = lat_top_ranks[0]

            sum_sim_lat = np.sum(lat_top_sims) + 1e-9
            lat_wmean_rank = np.sum(lat_top_ranks * lat_top_sims) / sum_sim_lat
            lat_mean_sim = np.mean(lat_top_sims)
            lat_std_rank = np.std(lat_top_ranks)

            # --- Interaction Features ---
            delta_rank_nn1 = abs(lex_nn1_rank - lat_nn1_rank)
            delta_rank_wmean = abs(lex_wmean_rank - lat_wmean_rank)

            # --- Metadata ---
            # We can't easily get char length here without accessing the source string again
            # but we can pass it if needed. For now, we rely on the embedding signals.
            # We add notebook length (number of code cells)
            nb_len = len(code_indices)

            # Construct row
            row = {
                "id": nb_id,
                "cell_id": "unknown",  # We don't track cell_id in indices, but usually not needed for X
                # Targets
                "pct_rank": all_pct_ranks[global_md_idx],
                # Lexical
                "lex_nn1_sim": lex_nn1_sim,
                "lex_nn1_rank": lex_nn1_rank,
                "lex_mean_sim": lex_mean_sim,
                "lex_wmean_rank": lex_wmean_rank,
                "lex_std_rank": lex_std_rank,
                # Latent
                "lat_nn1_sim": lat_nn1_sim,
                "lat_nn1_rank": lat_nn1_rank,
                "lat_mean_sim": lat_mean_sim,
                "lat_wmean_rank": lat_wmean_rank,
                "lat_std_rank": lat_std_rank,
                # Interaction
                "delta_rank_nn1": delta_rank_nn1,
                "delta_rank_wmean": delta_rank_wmean,
                # Meta
                "nb_len": nb_len,
            }
            features_list.append(row)

        return features_list

    def _create_empty_features(self, nb_id, md_indices, all_pct_ranks):
        """Fallback for notebooks with no code cells."""
        rows = []
        for idx in md_indices:
            rows.append(
                {
                    "id": nb_id,
                    "pct_rank": all_pct_ranks[idx],
                    "lex_nn1_sim": 0.0,
                    "lex_nn1_rank": 0.5,
                    "lex_mean_sim": 0.0,
                    "lex_wmean_rank": 0.5,
                    "lex_std_rank": 0.0,
                    "lat_nn1_sim": 0.0,
                    "lat_nn1_rank": 0.5,
                    "lat_mean_sim": 0.0,
                    "lat_wmean_rank": 0.5,
                    "lat_std_rank": 0.0,
                    "delta_rank_nn1": 0.0,
                    "delta_rank_wmean": 0.0,
                    "nb_len": 0,
                }
            )
        return rows
