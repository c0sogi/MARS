import os
import torch


class Config:
    """
    Central configuration for the iNaturalist species prediction task.
    Includes file paths, model hyperparameters, and training settings.
    """

    # --- System Configuration ---
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # We have 12 vCPUs, so 4-8 workers is a safe bet.
    NUM_WORKERS = 8

    # --- File Paths ---
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory for checkpoints and cached data
    WORKING_DIR = "./working/idea_1"
    SUBMISSION_DIR = "./submission"

    # Metadata files generated by the provided script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Final submission output
    SUBMISSION_FILE_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --- Data Configuration ---
    NUM_CLASSES = 1010
    INPUT_SIZE = 224  # Standard input size for MobileNetV3

    # Normalization constants (ImageNet defaults)
    MEAN = [0.485, 0.456, 0.406]
    STD = [0.229, 0.224, 0.225]

    # --- Model Configuration ---
    MODEL_NAME = "mobilenet_v3_large"
    PRETRAINED = True
    DROPOUT_RATE = 0.2

    # --- Training Hyperparameters ---
    BATCH_SIZE = 128
    NUM_EPOCHS = 15
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2

    # Scheduler settings (Cosine Annealing)
    T_MAX = NUM_EPOCHS  # For CosineAnnealingLR
    ETA_MIN = 1e-6

    # Optimization
    EARLY_STOPPING_PATIENCE = 3

    # Debugging / Development
    # Set to a small integer (e.g., 1000) to train on a subset for quick testing.
    # Set to None for full training.
    DEBUG_SAMPLE_SIZE = None

    @classmethod
    def setup(cls):
        """
        Ensures necessary directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories when module is imported
Config.setup()
