import os
import torch


class Config:
    """
    Configuration class for the Hierarchical Multi-Task Hybrid EfficientNet-B2 model.
    Centralizes all hyperparameters, file paths, and runtime settings.
    """

    def __init__(self, debug: bool = False, epochs: int = 15):
        """
        Initialize configuration with optional overrides for debugging and training duration.

        Args:
            debug (bool): If True, enables debug mode (smaller dataset, fewer epochs).
            epochs (int): Number of training epochs.
        """
        # =========================================================================
        # General Settings
        # =========================================================================
        self.seed = 42
        self.debug = debug
        # If debug is True, limit dataset to this many samples
        self.debug_sample_size = 1000
        self.num_workers = 12

        # =========================================================================
        # Directories and Paths
        # =========================================================================
        self.input_root = "./input"
        self.meta_dir = "./metadata"

        # Metadata files (generated by previous steps)
        self.train_csv = os.path.join(self.meta_dir, "train.csv")
        self.val_csv = os.path.join(self.meta_dir, "val.csv")
        self.test_csv = os.path.join(self.meta_dir, "test.csv")

        # Sample submission for format reference
        self.sample_submission_path = os.path.join(
            self.input_root, "sample_submission.csv"
        )

        # Working directory for this specific idea/experiment
        self.working_dir = "./working/idea_5"
        os.makedirs(self.working_dir, exist_ok=True)

        # Directory to save model checkpoints
        self.checkpoint_dir = os.path.join(self.working_dir, "checkpoints")
        os.makedirs(self.checkpoint_dir, exist_ok=True)

        # Final submission output path
        self.submission_path = "./submission/submission.csv"
        os.makedirs(os.path.dirname(self.submission_path), exist_ok=True)

        # =========================================================================
        # Model Hyperparameters
        # =========================================================================
        # Backbone: EfficientNet-B2 (better capacity/efficiency trade-off than B1)
        self.model_name = "tf_efficientnet_b2_ns"
        self.image_size = 384

        # Number of output classes for the primary head (Malignancy: 0 or 1)
        self.num_classes = 1

        # =========================================================================
        # Training Hyperparameters
        # =========================================================================
        self.epochs = 2 if self.debug else epochs
        # Batch size adjusted for A100 GPU (40GB) and 384x384 resolution
        self.batch_size = 32

        # Optimizer settings (AdamW)
        self.learning_rate = 1e-4
        self.weight_decay = 1e-5

        # Scheduler settings (Cosine Annealing with Warmup)
        self.min_lr = 1e-6
        self.warmup_epochs = 1

        # Loss Function Weights
        # Positive weight for BCEWithLogitsLoss to handle class imbalance (~1:55)
        self.pos_weight = 55.0
        # Weight for the auxiliary diagnosis loss
        self.aux_loss_weight = 0.1

        # Checkpoint Strategy
        # Number of top epochs to average for the final model
        self.avg_checkpoints = 3

        # =========================================================================
        # Inference Hyperparameters
        # =========================================================================
        # Test Time Augmentation steps: Original, HFlip, VFlip, HVFlip
        self.tta_steps = 4

        # =========================================================================
        # Hardware
        # =========================================================================
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    def __str__(self):
        """String representation for logging configuration."""
        config_str = "\n" + "=" * 40 + "\n"
        config_str += "CONFIGURATION\n"
        config_str += "=" * 40 + "\n"
        for k, v in self.__dict__.items():
            config_str += f"{k:<25}: {v}\n"
        config_str += "=" * 40 + "\n"
        return config_str
