import os


class Config:
    """
    Global configuration for the Sky-Contextualized Sequence-to-Point CNN.
    """

    # --------------------------------------------------------------------------
    # Directory Setup
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_12"
    SUBMISSION_DIR = "./submission"

    # Ensure working and submission directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    # Metadata files generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "validation_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Cache Paths for processed data (Parquet format for efficiency)
    TRAIN_CACHE_PATH = os.path.join(WORKING_DIR, "train_data.parquet")
    VAL_CACHE_PATH = os.path.join(WORKING_DIR, "val_data.parquet")
    TEST_CACHE_PATH = os.path.join(WORKING_DIR, "test_data.parquet")

    # Artifacts
    SCALER_PATH = os.path.join(WORKING_DIR, "scaler.json")
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # --------------------------------------------------------------------------
    # Hyperparameters
    # --------------------------------------------------------------------------
    RANDOM_STATE = 42

    # Data Processing
    WINDOW_SIZE = 15  # Size of the sliding window (N epochs)

    # Training
    BATCH_SIZE = 256
    LEARNING_RATE = 1e-3
    NUM_EPOCHS = 50
    EARLY_STOPPING_PATIENCE = 8
    NUM_WORKERS = 4

    # Model Architecture
    TRAJECTORY_CHANNELS = 8  # Number of input channels for the 1D CNN
    CONTEXT_INPUT_DIM = 7  # Number of input features for the Context MLP
    CNN_HIDDEN_DIM = 64
    MLP_HIDDEN_DIM = 128
    DROPOUT_RATE = 0.2

    # --------------------------------------------------------------------------
    # Feature Definitions
    # --------------------------------------------------------------------------
    # Raw columns to load from GNSS files for aggregation
    GNSS_RAW_COLS = [
        "utcTimeMillis",
        "WlsPositionXEcefMeters",
        "WlsPositionYEcefMeters",
        "WlsPositionZEcefMeters",
        "Cn0DbHz",
        "RawPseudorangeUncertaintyMeters",
        "SvElevationDegrees",
        "SvAzimuthDegrees",
    ]

    # Features used in the Trajectory Stream (1D CNN)
    # Calculated relative to the window center timestamp
    TRAJECTORY_FEATURES = [
        "rel_lat_m",  # Relative Latitude in meters
        "rel_lon_m",  # Relative Longitude in meters
        "rel_alt_m",  # Relative Altitude in meters
        "vel_lat_m",  # Delta Latitude (Velocity proxy)
        "vel_lon_m",  # Delta Longitude (Velocity proxy)
        "vel_alt_m",  # Delta Altitude (Velocity proxy)
        "mean_cn0",  # Mean Carrier-to-Noise density
        "mean_uncertainty",  # Mean Raw Pseudorange Uncertainty
    ]

    # Features used in the Sky Context Stream (MLP)
    # Aggregated statistics over the satellites visible in the window
    CONTEXT_FEATURES = [
        "sky_mean_elev",  # Mean Satellite Elevation
        "sky_std_elev",  # Standard Deviation of Elevation
        "sky_mean_azimuth",  # Mean Azimuth
        "sky_std_azimuth",  # Spread of Azimuth (Geometry proxy)
        "sky_mean_cn0",  # Mean Signal Strength across sky
        "sky_std_cn0",  # Variance of Signal Strength
        "sat_count",  # Number of satellites
    ]

    # Regression Targets (Residuals in meters from WLS baseline)
    TARGET_COLS = ["d_east", "d_north"]
