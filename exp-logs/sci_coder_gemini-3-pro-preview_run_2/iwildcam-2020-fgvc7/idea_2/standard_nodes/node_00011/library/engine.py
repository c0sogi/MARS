import torch
import torch.nn as nn
import torch.nn.functional as F
from typing import Dict, Tuple, Optional


class SoftTargetCrossEntropy(nn.Module):
    """
    Cross Entropy Loss for soft targets (probabilities) generated by Mixup/CutMix.
    Formula: - sum(p * log(q))
    """

    def __init__(self):
        super(SoftTargetCrossEntropy, self).__init__()

    def forward(self, x: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
        # x: logits [batch_size, num_classes]
        # target: soft targets [batch_size, num_classes]
        loss = torch.sum(-target * F.log_softmax(x, dim=-1), dim=-1)
        return loss.mean()


def train_one_epoch(
    model: nn.Module,
    dataloader: torch.utils.data.DataLoader,
    optimizer: torch.optim.Optimizer,
    device: torch.device,
    scaler: torch.cuda.amp.GradScaler,
    epoch: int,
) -> Dict[str, float]:
    """
    Executes one epoch of training using AMP and Label Smoothing Cross Entropy.
    """
    model.train()
    criterion = nn.CrossEntropyLoss(label_smoothing=0.1)

    total_loss = 0.0
    correct = 0
    total = 0

    for i, (images, targets, _) in enumerate(dataloader):
        images = images.to(device, non_blocking=True)
        targets = targets.to(device, non_blocking=True)

        optimizer.zero_grad()

        # Mixed Precision Context
        with torch.cuda.amp.autocast(enabled=True):
            outputs = model(images)
            loss = criterion(outputs, targets)

        # Scaled Backward Pass
        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()

        # Metric Accumulation
        batch_size = images.size(0)
        total_loss += loss.item() * batch_size

        # Calculate accuracy
        _, predicted = torch.max(outputs, 1)
        total += batch_size
        correct += (predicted == targets).sum().item()

    avg_loss = total_loss / total
    accuracy = correct / total

    print(f"Epoch {epoch} Training - Loss: {avg_loss}, Accuracy: {accuracy}")

    return {"loss": avg_loss, "accuracy": accuracy}


def validate(
    model: nn.Module, dataloader: torch.utils.data.DataLoader, device: torch.device
) -> Dict[str, float]:
    """
    Evaluates the model on the validation set using standard Cross Entropy.
    """
    model.eval()
    criterion = nn.CrossEntropyLoss()

    total_loss = 0.0
    correct = 0
    total = 0

    with torch.no_grad():
        for images, targets, _ in dataloader:
            images = images.to(device, non_blocking=True)
            targets = targets.to(device, non_blocking=True)

            outputs = model(images)
            loss = criterion(outputs, targets)

            batch_size = images.size(0)
            total_loss += loss.item() * batch_size

            _, predicted = torch.max(outputs, 1)
            total += batch_size
            correct += (predicted == targets).sum().item()

    avg_loss = total_loss / total
    accuracy = correct / total

    print(f"Validation - Loss: {avg_loss}, Accuracy: {accuracy}")

    return {"loss": avg_loss, "accuracy": accuracy}
