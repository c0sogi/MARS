import os
import torch


class Config:
    """
    Global configuration for the Curriculum-Enriched Residual Hybrid Cascade text normalization pipeline.
    This configuration manages the Strict-Priority Cascade (HFBB + Transformer) and the
    Curriculum-Enriched data construction strategy.
    """

    # ==========================================
    # 1. PATHS & DIRECTORIES
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_7"
    SUBMISSION_DIR = "./submission"

    # Input Metadata Files (Generated by metadata script)
    # These contain the split data with sentence_id grouping
    TRAIN_META = os.path.join(METADATA_DIR, "train.csv")
    VAL_META = os.path.join(METADATA_DIR, "val.csv")
    TEST_META = os.path.join(METADATA_DIR, "test.csv")

    # Output/Cache Files
    # HFBB Cache: Stores the hierarchical frequency maps
    HFBB_CACHE_DIR = os.path.join(WORKING_DIR, "hfbb_cache")

    # Data Processing Caches
    # Stores the raw residuals (failures of HFBB on train via Jackknifing)
    RESIDUAL_TRAIN_PATH = os.path.join(WORKING_DIR, "residual_train.parquet")
    # Stores the final curriculum-enriched dataset (residuals + anchors)
    ENRICHED_TRAIN_PATH = os.path.join(WORKING_DIR, "enriched_train.parquet")
    ENRICHED_VAL_PATH = os.path.join(WORKING_DIR, "enriched_val.parquet")

    # Tokenizer Models
    # BPE model for the target (normalized) text
    BPE_MODEL_PREFIX = os.path.join(WORKING_DIR, "bpe_ru_target")

    # Model Checkpoints
    BEST_MODEL_PATH = os.path.join(WORKING_DIR, "transformer_best.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # 2. REPRODUCIBILITY & HARDWARE
    # ==========================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Using 12 vCPUs, so 4 workers is a safe balance
    NUM_WORKERS = 4

    # ==========================================
    # 3. TIER 1: HFBB (MEMORY ENGINE) CONFIG
    # ==========================================
    # Hierarchy: Trigram -> Bigram(Prev) -> Bigram(Next) -> Unigram
    HFBB_NGRAM_ORDER = 3

    # ==========================================
    # 4. TIER 2: TRANSFORMER CONFIG
    # ==========================================
    # Architecture: Char-Encoder -> Subword-Decoder
    # Designed to handle 'semiotic' tokens (digits, symbols)

    # Data Dimensions
    MAX_INPUT_LEN = 128  # Max characters in input context (Prev + Token + Next)
    MAX_OUTPUT_LEN = 64  # Max subwords in output
    TARGET_VOCAB_SIZE = 4000  # Small BPE vocab size for normalized text

    # Transformer Hyperparameters
    D_MODEL = 512
    NHEAD = 8
    NUM_ENCODER_LAYERS = 6
    NUM_DECODER_LAYERS = 6
    DIM_FEEDFORWARD = 2048
    DROPOUT = 0.1

    # ==========================================
    # 5. TRAINING CONFIG
    # ==========================================
    BATCH_SIZE = 256  # A100 40GB can handle large batches
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-4
    EPOCHS = 20
    WARMUP_STEPS = 2000
    PATIENCE = 3  # Early stopping patience
    GRAD_CLIP = 1.0
    LABEL_SMOOTHING = 0.1

    # ==========================================
    # 6. CURRICULUM STRATEGY CONFIG
    # ==========================================
    # Number of folds for Jackknifing to generate residuals
    # High folds = better approximation of inference-time residuals
    N_FOLDS = 5

    # Ratio of 'easy' anchors (successful HFBB lookups) to mix back into training
    # to preserve grammatical structure.
    # 0.2 means we add anchors equal to 20% of the residual dataset size.
    ANCHOR_RATIO = 0.2

    # Regex patterns for the "Gate" logic
    # If token matches these, it is routed to Transformer if HFBB fails
    REGEX_DIGIT = r"\d"
    REGEX_LATIN = r"[a-zA-Z]"

    @classmethod
    def setup(cls):
        """
        Creates necessary directories for the pipeline.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.HFBB_CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        print(f"Directories setup at {cls.WORKING_DIR}")
