import os
import torch
import random
import numpy as np


class Config:
    # ==========================================
    # 1. PATHS & DIRECTORIES
    # ==========================================
    # Base directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_11"

    # Sub-directories for caching and artifacts
    HFBB_CACHE_DIR = os.path.join(WORKING_DIR, "hfbb_cache")
    TRANSFORMER_CACHE_DIR = os.path.join(WORKING_DIR, "transformer_cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    TOKENIZER_DIR = os.path.join(WORKING_DIR, "tokenizers")
    SUBMISSION_DIR = "./submission"

    # Input Data Files (Generated by Metadata Script)
    TRAIN_DATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_DATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_DATA_PATH = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "ru_sample_submission_2.csv")

    # Cache Files - HFBB (Tier 1)
    HFBB_UNIGRAM_PATH = os.path.join(HFBB_CACHE_DIR, "unigram.parquet")
    HFBB_BIGRAM_PREV_PATH = os.path.join(HFBB_CACHE_DIR, "bigram_prev.parquet")
    HFBB_BIGRAM_NEXT_PATH = os.path.join(HFBB_CACHE_DIR, "bigram_next.parquet")
    HFBB_TRIGRAM_PATH = os.path.join(HFBB_CACHE_DIR, "trigram.parquet")

    # Cache Files - Transformer Data (Tier 2)
    TRANSFORMER_TRAIN_PATH = os.path.join(
        TRANSFORMER_CACHE_DIR, "processed_train.parquet"
    )
    TRANSFORMER_VAL_PATH = os.path.join(TRANSFORMER_CACHE_DIR, "processed_val.parquet")

    # Tokenizer Paths
    CHAR_VOCAB_PATH = os.path.join(TOKENIZER_DIR, "char_vocab.json")
    BPE_MODEL_PREFIX = os.path.join(TOKENIZER_DIR, "bpe_ru_target")

    # Model Checkpoint
    BEST_MODEL_PATH = os.path.join(CHECKPOINT_DIR, "transformer_best.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # 2. HYPERPARAMETERS - DATA & PROCESSING
    # ==========================================
    SEED = 42

    # Tier 1: HFBB Logic
    CONFIDENCE_THRESHOLD = 0.99  # Threshold for Unigram confidence gating

    # Tier 2: Transformer Context
    CONTEXT_WINDOW = 2  # +/- 2 words: Prev_2, Prev_1, Target, Next_1, Next_2

    # Filtering / Sampling
    # We keep all tokens containing digits or latin chars for the transformer
    SEMIOTIC_REGEX = r"[\d]|[a-zA-Z]"

    # Tokenization
    BPE_VOCAB_SIZE = 4000  # Target vocabulary size for output BPE
    MAX_SRC_LEN = 128  # Max length for input sequence (chars + context tokens)
    MAX_TGT_LEN = 128  # Max length for output sequence (BPE tokens)

    # ==========================================
    # 3. HYPERPARAMETERS - MODEL ARCHITECTURE
    # ==========================================
    # Custom Transformer parameters
    D_MODEL = 512
    NHEAD = 8
    NUM_ENCODER_LAYERS = 6
    NUM_DECODER_LAYERS = 6
    DIM_FEEDFORWARD = 2048
    DROPOUT = 0.1

    # ==========================================
    # 4. HYPERPARAMETERS - TRAINING
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    BATCH_SIZE = 32  # Reduced to fit in VRAM (Cite debug_lesson_7)
    GRAD_ACCUM_STEPS = 8  # Maintain effective batch size of 256 (Cite debug_lesson_8)
    USE_AMP = True  # Enable Automatic Mixed Precision (Cite debug_lesson_8)
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-5
    LABEL_SMOOTHING = 0.1

    NUM_EPOCHS = 10
    EARLY_STOPPING_PATIENCE = 3
    WARMUP_STEPS = 1000

    # Debugging / Development
    DEBUG_SUBSET_SIZE = 0  # Set to > 0 (e.g., 10000) to train on a subset for quick testing. 0 = Full Data.

    @classmethod
    def setup(cls):
        """
        Initialize the environment: create directories and set random seeds.
        """
        # Create directories
        dirs = [
            cls.WORKING_DIR,
            cls.HFBB_CACHE_DIR,
            cls.TRANSFORMER_CACHE_DIR,
            cls.CHECKPOINT_DIR,
            cls.TOKENIZER_DIR,
            cls.SUBMISSION_DIR,
        ]
        for d in dirs:
            os.makedirs(d, exist_ok=True)

        # Set seeds for reproducibility
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        torch.cuda.manual_seed_all(cls.SEED)

        # Ensure deterministic behavior in CuDNN if needed (may slow down slightly)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False

        print(f"Configuration initialized. Working directory: {cls.WORKING_DIR}")
        print(f"Device: {cls.DEVICE}")
