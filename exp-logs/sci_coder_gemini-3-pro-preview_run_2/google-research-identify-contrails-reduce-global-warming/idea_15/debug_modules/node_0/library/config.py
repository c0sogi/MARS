import os
import torch


class CFG:
    """
    Configuration module for the Lightweight Pyramid-Fusion ConvNeXt U-Net pipeline.
    """

    # ====================================================
    # General
    # ====================================================
    seed = 42
    debug = False  # Set to True to limit dataset size for debugging
    debug_sample_size = 500  # Number of samples to use if debug=True
    num_workers = 4
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # ====================================================
    # Data
    # ====================================================
    image_size = 256
    in_channels = 6  # 3 Ash bands + 3 Temporal difference bands
    out_channels = 1

    # Directories
    input_dir = "./input"
    metadata_dir = "./metadata"

    # Metadata Paths (generated by the provided script)
    train_metadata_path = os.path.join(metadata_dir, "train_metadata.csv")
    valid_metadata_path = os.path.join(metadata_dir, "validation_metadata.csv")
    test_metadata_path = os.path.join(metadata_dir, "test_metadata.csv")

    # Sample Submission
    sample_submission_path = os.path.join(input_dir, "sample_submission.csv")

    # ====================================================
    # Model
    # ====================================================
    backbone = "convnext_tiny"
    pretrained = True
    drop_path_rate = 0.1

    # ====================================================
    # Training
    # ====================================================
    epochs = 30
    batch_size = 32  # Critical for stability with Lightweight Fusion

    # Optimization
    learning_rate = 2e-4
    min_lr = 1e-6
    weight_decay = 0.01
    scheduler = "CosineAnnealingLR"

    # Loss Weights
    bce_weight = 0.5
    dice_weight = 0.5

    # ====================================================
    # Inference & Post-processing
    # ====================================================
    threshold = 0.5
    tta = True  # Enable Test-Time Augmentation (Flip/Rotate)

    # ====================================================
    # Output
    # ====================================================
    working_dir = "./working/idea_15"
    output_dir = working_dir

    submission_dir = "./submission"
    submission_path = os.path.join(submission_dir, "submission.csv")

    best_model_path = os.path.join(working_dir, "best_model.pth")

    @classmethod
    def setup(cls, debug=None):
        """
        Initialize directories and optional overrides.
        """
        if debug is not None:
            cls.debug = debug

        # Ensure output directories exist
        os.makedirs(cls.working_dir, exist_ok=True)
        os.makedirs(cls.submission_dir, exist_ok=True)

        if cls.debug:
            print(
                f"[Config] Debug mode active. Dataset limited to {cls.debug_sample_size} samples."
            )


# Initialize directories on import
CFG.setup()
