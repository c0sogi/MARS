import os
import torch


class Config:
    """
    Global configuration for the Supervised Projected-Context Residual Network (SPCR-Net).
    """

    # -------------------------------------------------------------------------
    # General Setup
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a subset for debugging

    # -------------------------------------------------------------------------
    # Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for this specific idea/architecture
    WORKING_DIR = "./working/spcr_net"

    # Input Metadata Files (Generated by metadata script)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Directories
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = os.path.join(WORKING_DIR, "submission")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    BEST_MODEL_PATH = os.path.join(CHECKPOINT_DIR, "best_model.pth")

    # -------------------------------------------------------------------------
    # Data Preprocessing
    # -------------------------------------------------------------------------
    # Radiological Windowing (Lung Window)
    LUNG_WINDOW_LEVEL = -600
    LUNG_WINDOW_WIDTH = 1500

    # Image Dimensions (EfficientNet-B2 native is ~260)
    IMG_SIZE = 260

    # Slice Selection
    # We select 3 slices: Anchor (Max Area) and 2 boundaries
    NUM_SLICES = 3

    # Target Normalization (Derived from EDA)
    # Mean: 2654.6528, Std: 801.7017
    TARGET_MEAN = 2654.6528
    TARGET_STD = 801.7017

    # Input Normalization
    # Relative time scaling factor (Weeks * 0.01)
    TIME_SCALE = 0.01

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    BACKBONE_NAME = "efficientnet_b2"
    # Dimension to project high-dim visual features down to
    PROJECTION_DIM = 64
    # Hidden dimension for MLPs
    HIDDEN_DIM = 128

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    # Batch size must be >= 32 per requirements
    BATCH_SIZE = 32

    # Training duration
    EPOCHS = 50

    # Differential Learning Rates
    LR_BACKBONE = 1e-4
    LR_HEAD = 1e-3

    # Optimizer settings
    WEIGHT_DECAY = 0.01

    # Loss Weights
    # Total Loss = L_main + AUX_LOSS_WEIGHT * L_aux
    AUX_LOSS_WEIGHT = 0.5

    # -------------------------------------------------------------------------
    # Evaluation & Metrics
    # -------------------------------------------------------------------------
    # Metric calculation constants
    SIGMA_CLIP = 70.0
    MAX_ERROR = 1000.0

    # -------------------------------------------------------------------------
    # Hardware
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # Number of data loading workers
    NUM_WORKERS = 4

    @classmethod
    def setup(cls):
        """
        Creates necessary working directories for cache, checkpoints, and submission.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
