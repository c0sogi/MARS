import os
import torch


class Config:
    """
    Configuration for the Unregularized Dual-Stream Residual Network (UDSR-Net).
    Centralizes all file paths, hyperparameters, and experiment settings.
    """

    # =========================================================================
    # Random Seed & Hardware
    # =========================================================================
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 12  # Utilizing available vCPUs

    # =========================================================================
    # File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Input Metadata (Generated by metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Working Directories (Specific to Idea 35)
    WORKING_DIR = "./working/idea_35"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = os.path.join(WORKING_DIR, "submission")

    # Artifact Paths
    BEST_MODEL_PATH = os.path.join(CHECKPOINT_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Preprocessing & Augmentation
    # =========================================================================
    # Image Specifics (EfficientNet-B2 native resolution)
    IMG_SIZE = 260

    # Lung Window Settings (HU)
    WINDOW_LEVEL = -600
    WINDOW_WIDTH = 1500

    # Slice Selection
    SLICES_PER_PATIENT = 3  # Anchor + 2 boundary slices

    # Feature Scaling
    TIME_SCALE = 0.01  # Scale relative weeks

    # =========================================================================
    # Model Hyperparameters
    # =========================================================================
    BACKBONE_NAME = "efficientnet_b2"
    PRETRAINED = True

    # Stream B: Visual Residual Stream
    # Explicitly NO dropout for the visual stream to preserve weak signal
    VISUAL_DROPOUT = 0.0

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    EPOCHS = 50
    BATCH_SIZE = 32  # Strictly >= 32 for BN stability

    # Differential Learning Rates
    LR_BACKBONE = 1e-4
    LR_HEAD = 1e-3

    WEIGHT_DECAY = 1e-2

    # Scheduler
    T_MAX = EPOCHS  # Cosine Annealing horizon

    # =========================================================================
    # Metric / Loss Constants
    # =========================================================================
    CONFIDENCE_CLIP = 70
    MAX_ERROR = 1000

    # =========================================================================
    # Utilities
    # =========================================================================
    @classmethod
    def setup(cls):
        """Creates necessary working directories."""
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        print(f"Directories created at {cls.WORKING_DIR}")

    @classmethod
    def set_debug_mode(cls, debug=True):
        """Adjusts configuration for rapid debugging."""
        if debug:
            print("WARNING: Debug mode enabled. Reducing epochs and batch size.")
            cls.EPOCHS = 2
            cls.BATCH_SIZE = 8
            cls.NUM_WORKERS = 2
