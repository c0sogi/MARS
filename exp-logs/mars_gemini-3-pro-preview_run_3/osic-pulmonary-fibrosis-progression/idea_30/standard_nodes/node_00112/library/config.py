import os
import torch


class Config:
    """
    Configuration class for MAZR-DS (Metric-Aligned Zero-Residual Dual-Stream Network).
    Holds all constants, hyperparameters, and file paths.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data for debugging
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # =========================================================================
    # File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the previous step
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Directory containing DICOM images (relative paths in metadata point here)
    DICOM_ROOT = INPUT_DIR

    # Working directory for artifacts
    WORKING_DIR = "./working/idea_31"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINTS_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = os.path.join(WORKING_DIR, "submission")

    # =========================================================================
    # Image Preprocessing (Radiological & 2.5D)
    # =========================================================================
    # Backbone selection
    BACKBONE_NAME = "efficientnet_b2"

    # Input resolution (260x260 for B2)
    IMG_SIZE = 260

    # Lung Window Settings (HU)
    WINDOW_LEVEL = -600
    WINDOW_WIDTH = 1500

    # Slice Selection
    # We use 3 slices: Anchor (Max Area) + 2 Boundary slices
    NUM_SLICES = 3

    # =========================================================================
    # Model Architecture
    # =========================================================================
    # Dimension of the projection from the image backbone
    IMG_PROJ_DIM = 64

    # Dimension of the hidden layers in the MLP streams
    MLP_HIDDEN_DIM = 128

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    EPOCHS = 50
    BATCH_SIZE = 32

    # Differential Learning Rates
    LR_BACKBONE = 1e-4  # Slower learning for the pretrained feature extractor
    LR_HEAD = 1e-3  # Faster learning for the MLP streams

    # Optimizer & Scheduler
    WEIGHT_DECAY = 1e-2

    # =========================================================================
    # Feature Engineering
    # =========================================================================
    # Scale factor for relative weeks (t_rel)
    # t_rel = (Weeks - Baseline_Weeks) * TIME_SCALE
    TIME_SCALE = 0.01

    # =========================================================================
    # Methods
    # =========================================================================
    @classmethod
    def setup(cls):
        """
        Creates the necessary working directories if they do not exist.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINTS_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        print(f"Directories initialized at {cls.WORKING_DIR}")

    @classmethod
    def get_dataset_config(cls):
        """
        Returns a dictionary of dataset configuration for logging.
        """
        return {
            "img_size": cls.IMG_SIZE,
            "window_level": cls.WINDOW_LEVEL,
            "window_width": cls.WINDOW_WIDTH,
            "num_slices": cls.NUM_SLICES,
            "time_scale": cls.TIME_SCALE,
        }
