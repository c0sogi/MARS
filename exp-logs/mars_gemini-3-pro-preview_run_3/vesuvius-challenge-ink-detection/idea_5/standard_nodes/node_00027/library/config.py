import os
import torch


class Config:
    """
    Configuration for the Deep Sequential Dilated Network with Group Normalization (DSDN-GN).
    This module defines all hyperparameters, file paths, and structural constants
    required for the ink detection pipeline.
    """

    # -------------------------------------------------------------------------
    # System & Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 12  # Utilizing all available vCPUs for data loading

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (generated by the provided metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Working directory for this specific experiment (Idea 5)
    # Used for caching processed tensors and saving model checkpoints
    WORKING_DIR = "./working/idea_5"
    CACHE_DIR = WORKING_DIR

    # Model checkpoint path
    CHECKPOINT_PATH = os.path.join(WORKING_DIR, "best_model.pth")

    # Final submission file output path (root directory as per instructions)
    SUBMISSION_PATH = "submission.csv"

    # -------------------------------------------------------------------------
    # Data Parameters
    # -------------------------------------------------------------------------
    Z_DIM = 65  # Depth of the 3D X-ray volume
    PATCH_SIZE = 256  # Large patch size to preserve spatial context

    # -------------------------------------------------------------------------
    # Model Architecture (DSDN-GN)
    # -------------------------------------------------------------------------
    # The model uses a learnable 2.5D projection followed by a deep 2D backbone.

    NUM_CHANNELS = 32  # Lean channel width to balance parameter count with depth
    NUM_BLOCKS = 18  # Deep backbone to resolve complex textures

    # Sequential Dilation Pattern: 1, 2, 4, 8, 16, 1, 2...
    # This hierarchy builds receptive fields from edges to shapes.
    DILATION_CYCLE = [1, 2, 4, 8, 16]

    # Group Normalization Settings
    # Used to ensure stability with small batch sizes.
    # 32 channels / 8 groups = 4 channels per group.
    GN_NUM_GROUPS = 8

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    # Batch size is kept small to fit the deep model and large patches into GPU memory.
    # Group Norm makes the model invariant to this small batch size.
    BATCH_SIZE = 8

    # Optimization
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2

    # Training Loop
    EPOCHS = 25
    PATIENCE = 5  # Strict early stopping to prevent overfitting

    # Loss Function (Balanced BCE + Dice)
    BCE_WEIGHT = 0.5
    DICE_WEIGHT = 0.5

    # -------------------------------------------------------------------------
    # Inference & Validation
    # -------------------------------------------------------------------------
    # Tiled inference parameters
    INFERENCE_STRIDE = 128  # 50% overlap (PATCH_SIZE // 2)

    # Test-Time Augmentation (TTA)
    # Averages predictions across 4 rotations and 2 flips
    TTA_ENABLED = True

    # Dynamic Threshold Tuning
    # Range to search for the optimal F0.5 threshold on the validation set
    THRESHOLD_SEARCH_START = 0.20
    THRESHOLD_SEARCH_END = 0.80
    THRESHOLD_SEARCH_STEP = 0.05

    @classmethod
    def get_dilation_rates(cls):
        """
        Generates the full list of dilation rates for the sequential backbone
        based on NUM_BLOCKS and DILATION_CYCLE.
        """
        rates = []
        cycle_len = len(cls.DILATION_CYCLE)
        for i in range(cls.NUM_BLOCKS):
            rates.append(cls.DILATION_CYCLE[i % cycle_len])
        return rates

    @staticmethod
    def setup_directories():
        """
        Ensures the working and cache directories exist.
        Should be called at the start of the pipeline.
        """
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
