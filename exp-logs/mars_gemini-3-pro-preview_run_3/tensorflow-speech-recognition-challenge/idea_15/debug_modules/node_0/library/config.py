import os
import torch


class Config:
    """
    Configuration class for the Frequency-Attentive Multi-Resolution ResNeSt-CRNN pipeline.
    """

    # ==========================================
    # Project & Paths
    # ==========================================
    PROJECT_NAME = "idea_15"
    INPUT_ROOT = "./input"
    OUTPUT_DIR = os.path.join("./working", PROJECT_NAME)
    CACHE_DIR = os.path.join(OUTPUT_DIR, "cache")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Input Data Paths
    TRAIN_AUDIO_DIR = os.path.join(INPUT_ROOT, "train", "audio")
    TEST_AUDIO_DIR = os.path.join(INPUT_ROOT, "test", "audio")
    NOISE_DIR = os.path.join(TRAIN_AUDIO_DIR, "_background_noise_")

    # Metadata Paths (Generated by previous steps)
    METADATA_DIR = "./metadata"
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # ==========================================
    # Audio Processing Parameters
    # ==========================================
    SAMPLE_RATE = 16000
    DURATION = 1.0  # Seconds
    N_MELS = 224  # Scaled to match ResNeSt spatial resolution

    # Multi-Resolution Window Sizes (ms)
    WIN_LENGTH_SHORT_MS = 20
    WIN_LENGTH_MEDIUM_MS = 40
    WIN_LENGTH_LONG_MS = 60

    # Converted to Samples
    WIN_LENGTH_SHORT = int(SAMPLE_RATE * WIN_LENGTH_SHORT_MS / 1000)
    WIN_LENGTH_MEDIUM = int(SAMPLE_RATE * WIN_LENGTH_MEDIUM_MS / 1000)
    WIN_LENGTH_LONG = int(SAMPLE_RATE * WIN_LENGTH_LONG_MS / 1000)

    # FFT Sizes (Next power of 2 for efficiency)
    N_FFT_SHORT = 512
    N_FFT_MEDIUM = 1024
    N_FFT_LONG = 2048

    # Hop Length & Image Size
    # Standard 10ms hop
    HOP_LENGTH = 160
    # Target size for the model input (Freq, Time) -> (224, 224)
    # The dataset loader will resize/pad to this dimension.
    TARGET_IMAGE_SIZE = (224, 224)

    # ==========================================
    # Labels & Classes
    # ==========================================
    LABELS = [
        "yes",
        "no",
        "up",
        "down",
        "left",
        "right",
        "on",
        "off",
        "stop",
        "go",
        "silence",
        "unknown",
    ]
    NUM_CLASSES = len(LABELS)
    LABEL2ID = {label: i for i, label in enumerate(LABELS)}
    ID2LABEL = {i: label for i, label in enumerate(LABELS)}

    # ==========================================
    # Model Architecture
    # ==========================================
    MODEL_NAME = "resnest50d"  # ResNeSt-50 backbone
    PRETRAINED = True

    # RNN Head
    RNN_HIDDEN_SIZE = 256
    RNN_LAYERS = 2
    DROPOUT = 0.3

    # Attention
    ATTENTION_HEADS = 4

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    SEED = 42
    BATCH_SIZE = 128  # Optimized for A100 40GB
    EPOCHS = 25
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    NUM_WORKERS = 8  # Utilizing available vCPUs

    # Scheduler (Cosine Annealing)
    T_MAX = EPOCHS
    MIN_LR = 1e-6

    # ==========================================
    # Augmentation (GPU-Native)
    # ==========================================
    PITCH_SHIFT_STEPS = 2.0
    TIME_STRETCH_RATE = 1.2
    NOISE_PROB = 0.6

    # SpecAugment
    MASK_TIME_PROB = 0.5
    MASK_FREQ_PROB = 0.5
    MASK_TIME_LIMIT = 30
    MASK_FREQ_LIMIT = 30

    # ==========================================
    # Runtime Configuration
    # ==========================================
    DEBUG = False
    MAX_SAMPLES = None  # Use None for full dataset

    @classmethod
    def setup(cls):
        """
        Creates necessary output directories.
        Should be called at the start of execution.
        """
        os.makedirs(cls.OUTPUT_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

    def __init__(self, debug=False, max_samples=None, epochs=None):
        """
        Initialize config with optional overrides for flexibility.

        Args:
            debug (bool): If True, enables debug mode (fewer epochs, small dataset).
            max_samples (int, optional): Limit the number of samples for debugging.
            epochs (int, optional): Override the number of training epochs.
        """
        if debug:
            self.DEBUG = True
            self.EPOCHS = 2 if epochs is None else epochs
            self.MAX_SAMPLES = 1000 if max_samples is None else max_samples

        if epochs is not None:
            self.EPOCHS = epochs
            self.T_MAX = epochs

        if max_samples is not None:
            self.MAX_SAMPLES = max_samples

    def display(self):
        """Prints the current configuration."""
        print("=" * 30)
        print(f"Configuration: {self.PROJECT_NAME}")
        print("=" * 30)
        print(
            f"Device: {torch.cuda.get_device_name(0) if torch.cuda.is_available() else 'CPU'}"
        )
        print(f"Batch Size: {self.BATCH_SIZE}")
        print(f"Epochs: {self.EPOCHS}")
        print(f"Learning Rate: {self.LEARNING_RATE}")
        print(f"Debug Mode: {self.DEBUG}")
        print(f"Max Samples: {self.MAX_SAMPLES}")
        print(f"Input Resolution: {self.TARGET_IMAGE_SIZE} (Mels: {self.N_MELS})")
        print("=" * 30)
