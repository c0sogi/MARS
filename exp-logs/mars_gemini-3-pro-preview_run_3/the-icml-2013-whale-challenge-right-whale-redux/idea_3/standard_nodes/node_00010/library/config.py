import os
import torch


class Config:
    """
    Configuration class for Right Whale Detection (Idea 3: EfficientNet-B0 + GeM).
    Acts as a single source of truth for all hyperparameters and paths.
    """

    # --------------------------------------------------------------------------
    # General Settings
    # --------------------------------------------------------------------------
    PROJECT_NAME = "RightWhaleDetection_Idea3"
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SUBSET_SIZE = 500  # Number of samples to use when DEBUG is True

    # --------------------------------------------------------------------------
    # Directory & File Paths
    # --------------------------------------------------------------------------
    # Base directories
    INPUT_DIR = "./input"
    WORKING_DIR = "./working"
    IDEA_DIR = os.path.join(WORKING_DIR, "idea_3")
    METADATA_DIR = "./metadata"
    SUBMISSION_DIR = "./submission"

    # Ensure writable directories exist
    os.makedirs(IDEA_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata files (Generated by the provided metadata script)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Output paths
    BEST_MODEL_PATH = os.path.join(IDEA_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache paths for pre-processed spectrograms (using .npz for storage)
    # Updated for B2 model with 224 Mels
    TRAIN_CACHE = os.path.join(IDEA_DIR, "train_b2_224.npz")
    VAL_CACHE = os.path.join(IDEA_DIR, "val_b2_224.npz")
    TEST_CACHE = os.path.join(IDEA_DIR, "test_b2_224.npz")

    # --------------------------------------------------------------------------
    # Audio Processing Parameters
    # --------------------------------------------------------------------------
    # Based on data analysis: SR=2000Hz, Duration=2s
    SR = 2000  # Sampling Rate (Hz)
    DURATION = 2.0  # Clip duration (seconds)

    # Spectrogram generation (High Resolution)
    N_FFT = 512  # Window size (approx 256ms)
    HOP_LENGTH = 20  # Hop length (samples). 20 samples @ 2kHz = 10ms
    N_MELS = 224  # Number of Mel bands (Increased for EfficientNet-B2)
    FMIN = 10  # Min frequency (Hz)
    FMAX = 1000  # Max frequency (Hz) - Nyquist limit
    POWER = 2.0  # Power for Mel spectrogram

    # --------------------------------------------------------------------------
    # Model Hyperparameters
    # --------------------------------------------------------------------------
    MODEL_NAME = "efficientnet_b2"  # Upgraded backbone
    PRETRAINED = True  # Use ImageNet pretrained weights
    IN_CHANNELS = 1  # Input channels (Spectrogram is 1 channel)
    NUM_CLASSES = 1  # Binary classification

    # Generalized Mean (GeM) Pooling settings
    POOLING_TYPE = "gem"
    GEM_P = 3.0  # Initial p value (p=1 is AvgPool, p->inf is MaxPool)
    GEM_TRAINABLE = True  # Learn p during training

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Number of DataLoader workers (12 vCPUs available)

    EPOCHS = 30  # Total training epochs
    BATCH_SIZE = 64  # Batch size (Reduced for larger model/input)

    # Optimizer (AdamW)
    LR = 1e-3  # Initial learning rate
    WEIGHT_DECAY = 1e-2  # Weight decay

    # Scheduler (Cosine Annealing)
    T_MAX = EPOCHS  # Cycle length
    MIN_LR = 1e-6  # Minimum learning rate

    # Loss Function (BCE with Inverse Class Frequency Weighting)
    # Class imbalance is approx 1:9 (Pos:Neg).
    # Pos_weight should be Neg_Count / Pos_Count ~= 9.0
    POS_WEIGHT = 9.0

    # --------------------------------------------------------------------------
    # Regularization & Augmentation
    # --------------------------------------------------------------------------
    # Mixup
    USE_MIXUP = True
    MIXUP_ALPHA = 0.4  # Beta distribution parameter

    # SpecAugment
    USE_SPECAUG = True
    FREQ_MASK_PARAM = 20  # Max frequency bands to mask
    TIME_MASK_PARAM = 30  # Max time steps to mask

    # Stochastic Depth (DropPath)
    DROP_PATH_RATE = 0.2  # Probability of dropping residual paths

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 7

    @classmethod
    def print_config(cls):
        """Prints the current configuration."""
        print("=" * 40)
        print(f"Configuration: {cls.PROJECT_NAME}")
        print("=" * 40)
        for key, val in cls.__dict__.items():
            if not key.startswith("__") and not callable(val):
                print(f"{key}: {val}")
        print("=" * 40)
