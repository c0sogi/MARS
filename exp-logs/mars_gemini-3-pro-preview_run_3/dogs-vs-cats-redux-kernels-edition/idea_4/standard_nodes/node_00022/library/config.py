import os
import torch


class Config:
    """
    Configuration for the Dog vs Cat Classification Task.
    Implements settings for Stratified K-Fold Heterogeneous Ensemble with Scaled Backbones.
    """

    # --- Reproducibility ---
    SEED = 42

    # --- System & Directories ---
    # Input data is read-only
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for checkpoints and cached data
    WORKING_DIR = "./working/idea_4"

    # Submission directory
    SUBMISSION_DIR = "./submission"

    # Ensure mutable directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # --- File Paths ---
    # Metadata CSVs generated by the provided script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Final submission output path
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --- Data Configuration ---
    IMAGE_SIZE = 256
    NUM_CLASSES = 1  # Binary classification (Dog vs Cat)

    # --- Model Architecture ---
    # Heterogeneous ensemble: ResNet-101 and ConvNeXt-Small
    # These names correspond to timm model registry names
    MODEL_BACKBONES = ["resnet101", "convnext_small"]
    PRETRAINED = True

    # --- Training Hyperparameters ---
    N_FOLDS = 5
    EPOCHS = 6
    BATCH_SIZE = 64

    # Optimization
    LEARNING_RATE = 1e-4
    WEIGHT_DECAY = 1e-2

    # Scheduler (Cosine Annealing)
    SCHEDULER_T_MAX = EPOCHS
    SCHEDULER_MIN_LR = 1e-6

    # --- Hardware & Performance ---
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 8  # Utilizing available vCPUs efficiently

    # --- Inference ---
    USE_TTA = True  # Enable Test Time Augmentation (Horizontal Flip)

    # --- Debugging ---
    # If True, runs on a small subset of data for pipeline verification
    DEBUG = False
