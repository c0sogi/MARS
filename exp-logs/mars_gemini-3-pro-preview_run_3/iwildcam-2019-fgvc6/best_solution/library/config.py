import os
import torch


class Config:
    """
    Configuration class for the Animal Classification Task.
    Implements parameters for Swin Transformer V2, GeM Pooling, and training strategy.
    """

    # --------------------
    # General Setup
    # --------------------
    SEED = 42
    DEBUG = False  # Set to True to use a subset of data for debugging
    DEBUG_SAMPLE_SIZE = 2000  # Number of samples to use in debug mode
    NUM_WORKERS = 12  # Use available vCPUs

    # --------------------
    # Compute
    # --------------------
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # --------------------
    # Paths
    # --------------------
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (generated by the metadata script)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Output directories
    WORKING_DIR = "./working/idea_3"
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------
    # Model Configuration
    # --------------------
    # EfficientNetV2-S (Cite solution_lesson_node_00011)
    MODEL_NAME = "tf_efficientnetv2_s.in21k_ft_in1k"
    NUM_CLASSES = 23  # Classes 0-22
    USE_GEM_POOLING = (
        True  # Use Generalized Mean Pooling instead of Global Average Pooling
    )
    PRETRAINED = True

    # --------------------
    # Data Configuration
    # --------------------
    IMG_SIZE = 256

    # --------------------
    # Training Configuration
    # --------------------
    NUM_EPOCHS = 12
    BATCH_SIZE = 64  # Fits in A100 40GB with Swin Tiny

    # Optimizer (AdamW)
    WEIGHT_DECAY = 0.05

    # Scheduler (OneCycleLR)
    MAX_LR = 1e-3
    PCT_START = 0.1  # Percentage of training to increase LR
    DIV_FACTOR = 25.0
    FINAL_DIV_FACTOR = 1000.0

    # Loss
    LABEL_SMOOTHING = 0.0  # Disabled as per strategy for imbalanced data

    # Regularization
    DROP_PATH_RATE = 0.1  # Stochastic Depth
    DROPOUT_RATE = 0.0  # Head Dropout

    # --------------------
    # Augmentation Configuration
    # --------------------
    # Geometric
    AUG_SHIFT_LIMIT = 0.1
    AUG_SCALE_LIMIT = 0.1
    AUG_ROTATE_LIMIT = 15

    # Color/Intensity
    AUG_BRIGHTNESS_LIMIT = 0.2
    AUG_CONTRAST_LIMIT = 0.2

    # CoarseDropout (Distributed occlusion)
    AUG_MIN_HOLES = 4
    AUG_MAX_HOLES = 12
    AUG_HOLE_HEIGHT = 16
    AUG_HOLE_WIDTH = 16
    AUG_DROPOUT_PROB = 0.5

    # --------------------
    # Inference
    # --------------------
    TTA_FLIP = True  # Use Horizontal Flip Test-Time Augmentation

    @classmethod
    def setup(cls):
        """Creates necessary output directories."""
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Initialize directories
Config.setup()
