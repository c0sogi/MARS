import os
import random
import numpy as np
import torch


class Config:
    """
    Centralized configuration for the Multi-Task DINO model with Swin-L backbone.
    Handles hyperparameters, file paths, and system setup.
    """

    # ==========================
    # General Settings
    # ==========================
    PROJECT_NAME = "idea_11_dino_swin"
    SEED = 42

    # Debugging: Set to True to train on a small subset of data
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 100

    # ==========================
    # Directories & Paths
    # ==========================
    # Base directories
    ROOT_DIR = "."
    INPUT_DIR = os.path.join(ROOT_DIR, "input")
    METADATA_DIR = os.path.join(ROOT_DIR, "metadata")
    WORKING_DIR = os.path.join(ROOT_DIR, "working", "idea_11")

    # Metadata files (Generated by the provided script)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Submission output
    SUBMISSION_DIR = os.path.join(ROOT_DIR, "submission")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================
    # Data Configuration
    # ==========================
    # Image resizing strategy: Letterbox resizing to preserve aspect ratio
    IMG_SIZE = 1024

    # Class Definitions
    # Object Detection: Single class 'opacity'
    NUM_CLASSES = 1

    # Study Classification: 4 mutually exclusive labels (mostly)
    STUDY_LABELS = [
        "Negative for Pneumonia",
        "Typical Appearance",
        "Indeterminate Appearance",
        "Atypical Appearance",
    ]
    NUM_STUDY_CLASSES = len(STUDY_LABELS)

    # ==========================
    # Model Architecture
    # ==========================
    # Backbone: Swin Transformer Large
    # Using 'swin_large_patch4_window12_384_in22k' as a strong baseline
    BACKBONE_NAME = "swin_large_patch4_window12_384_in22k"

    # DINO / Transformer Head Config
    NUM_QUERIES = 300  # Number of object queries for DINO
    ENC_LAYERS = 6  # Number of encoder layers
    DEC_LAYERS = 6  # Number of decoder layers
    DIM_FEEDFORWARD = 2048  # Transformer FFN dimension
    HIDDEN_DIM = 256  # Model hidden dimension
    DROPOUT = 0.1

    # ==========================
    # Training Hyperparameters
    # ==========================
    # Batch size: Conservative due to Swin-L memory footprint on 1024px images
    BATCH_SIZE = 2

    # Epochs
    EPOCHS = 15

    # Optimization
    LR = 1e-4  # Learning rate for Transformer
    LR_BACKBONE = 1e-5  # Lower learning rate for Backbone
    WEIGHT_DECAY = 1e-4
    CLIP_MAX_NORM = 0.1  # Gradient clipping

    # Scheduler
    LR_DROP = 12  # Epoch to drop learning rate

    # System
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Initialize the environment:
        1. Create necessary directories.
        2. Set random seeds for reproducibility.
        """
        # 1. Create Directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # 2. Set Random Seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)

        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.cuda.manual_seed_all(cls.SEED)

            # Ensure deterministic behavior for cuDNN
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

        print(f"[Config] Setup complete.")
        print(f"         Device: {cls.DEVICE}")
        print(f"         Working Dir: {cls.WORKING_DIR}")
        print(f"         Image Size: {cls.IMG_SIZE}")
        print(f"         Backbone: {cls.BACKBONE_NAME}")
