import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration for Idea 12: Multi-Task DINO with Dual-Stream Geometric-Semantic Reasoning.
    Includes settings for model architecture, data pipeline, training loop, and file paths.
    """

    # =========================================================================
    # General Setup
    # =========================================================================
    PROJECT_NAME = "idea_12_multitask_dino"
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data for debugging
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # =========================================================================
    # Directories & File Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (generated by the provided script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Working directory for this experiment
    WORKING_DIR = "./working/idea_12"

    # Cache directory for processed data (e.g., resized images, cached dataframes)
    CACHE_DIR = WORKING_DIR

    # Output directory for model checkpoints
    OUTPUT_DIR = WORKING_DIR

    # Submission file path
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Configuration
    # =========================================================================
    # Image Preprocessing
    IMG_SIZE = 1024  # Target size for the longest dimension (Letterbox resizing)

    # Class Definitions
    NUM_DETECTION_CLASSES = 1  # 'opacity'
    NUM_STUDY_CLASSES = 4  # Study-level labels

    STUDY_LABELS = [
        "Negative for Pneumonia",
        "Typical Appearance",
        "Indeterminate Appearance",
        "Atypical Appearance",
    ]

    # =========================================================================
    # Model Hyperparameters (Multi-Task DINO + Swin-L)
    # =========================================================================
    # Backbone
    BACKBONE_NAME = "swin_large_patch4_window12_384"
    PRETRAINED_BACKBONE = True

    # DINO Transformer Parameters
    HIDDEN_DIM = 256
    ENC_LAYERS = 6
    DEC_LAYERS = 6
    NHEADS = 8
    DIM_FEEDFORWARD = 2048
    DROPOUT = 0.0
    NUM_QUERIES = 300  # Number of object queries/proposals

    # Dual-Stream Reasoning Head Parameters
    REASONING_HIDDEN_DIM = 256
    REASONING_DROPOUT = 0.1

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    # Batch Size & Gradient Accumulation
    # Swin-L is memory intensive; using small batch size with accumulation
    BATCH_SIZE = 2
    ACCUMULATE_GRAD_BATCHES = 8  # Effective batch size = 16

    # Epochs & Early Stopping
    EPOCHS = 12
    EARLY_STOPPING_PATIENCE = 3
    EARLY_STOPPING_MIN_DELTA = 1e-4

    # Optimization
    LR = 1e-4  # Learning rate for Transformer and Heads
    BACKBONE_LR = 1e-5  # Lower learning rate for the backbone
    WEIGHT_DECAY = 1e-4
    CLIP_MAX_NORM = 0.1  # Gradient clipping

    # Learning Rate Scheduler
    LR_DROP_EPOCH = 10  # Epoch to decay learning rate

    # Loss Weights
    # Detection Losses (Standard DINO weights)
    COST_CLASS = 2.0  # Focal loss weight
    COST_BBOX = 5.0  # L1 box loss weight
    COST_GIOU = 2.0  # Generalized IoU loss weight

    # Multi-Task Balancing
    LOSS_DETECTION_WEIGHT = 1.0
    LOSS_STUDY_WEIGHT = 2.0  # Higher weight for study classification accuracy

    # =========================================================================
    # Augmentation (Large Scale Jittering)
    # =========================================================================
    AUG_MIN_SCALE = 0.1
    AUG_MAX_SCALE = 2.0
    AUG_HFLIP_PROB = 0.5
    # Note: Mosaic augmentation is explicitly disabled to preserve anatomical structure

    # =========================================================================
    # Utility Methods
    # =========================================================================
    @classmethod
    def setup(cls):
        """
        Initializes the environment by creating necessary directories and setting seeds.
        """
        # Create working and submission directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set random seeds for reproducibility
        cls.set_seed(cls.SEED)

    @staticmethod
    def set_seed(seed):
        """
        Sets random seeds for Python, NumPy, and PyTorch to ensure reproducible results.
        """
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
