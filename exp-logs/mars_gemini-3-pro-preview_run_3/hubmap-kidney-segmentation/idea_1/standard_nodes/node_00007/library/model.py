import torch
import torch.nn as nn
import torch.nn.functional as F
from torchvision import models
from library.config import Config


class FPNResNet(nn.Module):
    """
    Tissue-Aware FPN with ResNet-18 Encoder.

    This architecture uses a ResNet-18 backbone to extract features at multiple scales
    (strides 4, 8, 16, 32). A Feature Pyramid Network (FPN) decoder aggregates these
    features using lateral connections and a top-down pathway. The final segmentation
    mask is generated by merging the pyramid features at 1/4 resolution.
    """

    def __init__(self):
        super(FPNResNet, self).__init__()

        # ==========================
        # 1. Encoder (ResNet-18)
        # ==========================
        # Load pre-trained weights safely across different torchvision versions
        try:
            from torchvision.models import ResNet18_Weights

            weights = ResNet18_Weights.IMAGENET1K_V1
            self.encoder = models.resnet18(weights=weights)
        except (ImportError, AttributeError):
            self.encoder = models.resnet18(pretrained=True)

        # Handle input channels if different from RGB (3)
        if Config.IN_CHANNELS != 3:
            self.encoder.conv1 = nn.Conv2d(
                Config.IN_CHANNELS, 64, kernel_size=7, stride=2, padding=3, bias=False
            )

        # ==========================
        # 2. FPN Decoder Components
        # ==========================
        self.fpn_dim = 256

        # Lateral connections (1x1 convolutions)
        # ResNet18 channel sizes: layer1=64, layer2=128, layer3=256, layer4=512
        self.lat_layer1 = nn.Conv2d(64, self.fpn_dim, kernel_size=1)
        self.lat_layer2 = nn.Conv2d(128, self.fpn_dim, kernel_size=1)
        self.lat_layer3 = nn.Conv2d(256, self.fpn_dim, kernel_size=1)
        self.lat_layer4 = nn.Conv2d(512, self.fpn_dim, kernel_size=1)

        # Smoothing convolutions (3x3) to reduce aliasing after upsampling/addition
        self.smooth1 = nn.Conv2d(self.fpn_dim, self.fpn_dim, kernel_size=3, padding=1)
        self.smooth2 = nn.Conv2d(self.fpn_dim, self.fpn_dim, kernel_size=3, padding=1)
        self.smooth3 = nn.Conv2d(self.fpn_dim, self.fpn_dim, kernel_size=3, padding=1)
        self.smooth4 = nn.Conv2d(self.fpn_dim, self.fpn_dim, kernel_size=3, padding=1)

        # ==========================
        # 3. Segmentation Head
        # ==========================
        # Processes the merged feature map (at stride 4)
        self.seg_head = nn.Sequential(
            nn.Conv2d(self.fpn_dim, 128, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(128),
            nn.ReLU(inplace=True),
            nn.Conv2d(128, Config.CLASSES, kernel_size=1),
        )

    def forward(self, x):
        """
        Forward pass of the network.

        Args:
            x (torch.Tensor): Input image tensor of shape (B, C, H, W).

        Returns:
            torch.Tensor: Output logits of shape (B, Classes, H, W).
        """
        # --- Encoder Path ---
        # Initial stem (Stride 4 total: conv1 stride 2 -> maxpool stride 2)
        x_stem = self.encoder.conv1(x)
        x_stem = self.encoder.bn1(x_stem)
        x_stem = self.encoder.relu(x_stem)
        x_stem = self.encoder.maxpool(x_stem)

        # ResNet Layers
        c1 = self.encoder.layer1(x_stem)  # Stride 4, 64 ch
        c2 = self.encoder.layer2(c1)  # Stride 8, 128 ch
        c3 = self.encoder.layer3(c2)  # Stride 16, 256 ch
        c4 = self.encoder.layer4(c3)  # Stride 32, 512 ch

        # --- FPN Top-Down Path ---
        # P4
        p4 = self.lat_layer4(c4)

        # P3: Upsample P4 + Lateral C3
        p3_in = self.lat_layer3(c3)
        p3_up = F.interpolate(p4, size=p3_in.shape[2:], mode="nearest")
        p3 = p3_in + p3_up

        # P2: Upsample P3 + Lateral C2
        p2_in = self.lat_layer2(c2)
        p2_up = F.interpolate(p3, size=p2_in.shape[2:], mode="nearest")
        p2 = p2_in + p2_up

        # P1: Upsample P2 + Lateral C1
        p1_in = self.lat_layer1(c1)
        p1_up = F.interpolate(p2, size=p1_in.shape[2:], mode="nearest")
        p1 = p1_in + p1_up

        # Smooth features
        p4 = self.smooth4(p4)
        p3 = self.smooth3(p3)
        p2 = self.smooth2(p2)
        p1 = self.smooth1(p1)

        # --- Merge & Predict ---
        # Upsample all pyramid levels to the resolution of P1 (Stride 4)
        target_size = p1.shape[2:]

        m4 = F.interpolate(p4, size=target_size, mode="bilinear", align_corners=False)
        m3 = F.interpolate(p3, size=target_size, mode="bilinear", align_corners=False)
        m2 = F.interpolate(p2, size=target_size, mode="bilinear", align_corners=False)
        m1 = p1

        # Element-wise Sum
        merged_features = m1 + m2 + m3 + m4

        # Generate Logits (B, Classes, H/4, W/4)
        logits = self.seg_head(merged_features)

        # Upsample to original input resolution (4x upsample)
        out = F.interpolate(
            logits, scale_factor=4, mode="bilinear", align_corners=False
        )

        return out
