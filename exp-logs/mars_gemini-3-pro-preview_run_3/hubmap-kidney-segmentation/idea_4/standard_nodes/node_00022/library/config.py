import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration for the Stain-Deconvolved U-Net++ with ConvNeXt-Tiny pipeline.
    Centralizes all hyperparameters, file paths, and setup logic.
    """

    # -------------------------------------------------------------------------
    # General & Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data
    DEBUG_SAMPLE_SIZE = 64  # Number of tiles to use if DEBUG is True

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (generated by metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output directories
    WORKING_DIR = "./working/idea_4"
    SUBMISSION_DIR = "./submission"

    # Artifact paths
    MODEL_SAVE_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Cache directory for processed tiles/masks
    CACHE_DIR = WORKING_DIR

    # -------------------------------------------------------------------------
    # Data Configuration
    # -------------------------------------------------------------------------
    TILE_SIZE = 768
    # Input Channels: 5 (Red, Green, Blue, Hematoxylin, Eosin)
    INPUT_CHANNELS = 5
    NUM_CLASSES = 1  # Binary segmentation (FTU)

    # -------------------------------------------------------------------------
    # Model Configuration
    # -------------------------------------------------------------------------
    BACKBONE = "convnext_tiny"
    PRETRAINED = True

    # Deep Supervision: Weighted loss from multiple decoder levels
    # Weights for outputs [Final, Skip1, Skip2, Skip3]
    DEEP_SUPERVISION = True
    DEEP_SUPERVISION_WEIGHTS = [1.0, 0.5, 0.25, 0.125]

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    # Batch size tailored for A100 (40GB) with 768x768x5 inputs
    BATCH_SIZE = 8

    # Training duration
    EPOCHS = 20

    # Optimization
    LEARNING_RATE = 2e-4
    WEIGHT_DECAY = 1e-2

    # Scheduler (Cosine Annealing)
    T_MAX = EPOCHS
    MIN_LR = 1e-6

    # Early Stopping
    PATIENCE = 6

    # -------------------------------------------------------------------------
    # Inference Configuration
    # -------------------------------------------------------------------------
    THRESHOLD = 0.5
    MIN_OBJECT_SIZE = 0  # Optional post-processing filter

    # -------------------------------------------------------------------------
    # Hardware & System
    # -------------------------------------------------------------------------
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Initialize directories and set random seeds for reproducibility.
        """
        # Create directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(cls.SEED)
            # Deterministic mode for full reproducibility
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
