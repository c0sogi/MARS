import os
import torch


class Config:
    """
    Configuration module for the Whale Identification Task.
    Implements settings for Dual-Backbone Ensemble (EfficientNet-B2 & B3) with ArcFace.
    """

    # -------------------------------------------------------------------------
    # General & Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 100  # Number of samples to use when DEBUG is True

    # -------------------------------------------------------------------------
    # Directories & File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_7"

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Submission Output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Configuration
    # -------------------------------------------------------------------------
    IMAGE_SIZE = 512  # Target resolution (512x512) for anisotropic resizing
    NUM_WORKERS = 4  # Optimized for 12 vCPUs
    PIN_MEMORY = True

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    # Single Strong Backbone Strategy (Cite solution_lesson_node_00042)
    MODEL_BACKBONES = ["efficientnet_b3"]
    EMBEDDING_DIM = 512  # Dimension of the embedding vector
    PRETRAINED = True

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 16  # Small batch size as per strategy
    LEARNING_RATE = 3e-4  # Aggressive learning rate
    WEIGHT_DECAY = 1e-2  # Standard weight decay for AdamW
    EPOCHS = 20  # Training duration

    # Early Stopping
    PATIENCE = 5  # Epochs to wait before early stopping

    # ArcFace Loss Parameters
    ARCFACE_S = 30.0  # Scale
    ARCFACE_M = 0.5  # Margin

    # -------------------------------------------------------------------------
    # Inference & Post-Processing
    # -------------------------------------------------------------------------
    TTA_ENABLED = True  # Enable Test-Time Augmentation (Horizontal Flip)
    KNN_K = 50  # Neighbors for Query Expansion/Re-ranking

    # -------------------------------------------------------------------------
    # Hardware Configuration
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @classmethod
    def setup(cls):
        """
        Initializes the working environment by creating necessary directories.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set deterministic behavior for reproducibility
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(cls.SEED)
