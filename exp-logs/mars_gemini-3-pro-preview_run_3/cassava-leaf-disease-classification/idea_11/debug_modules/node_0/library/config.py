import os
import torch


class Config:
    """
    Central configuration for the Cassava Leaf Disease Classification pipeline.
    Implements the settings for a 5-Fold Cross-Validated Heterogeneous Stacking strategy.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for testing
    DEBUG_SAMPLE_SIZE = 100  # Number of samples to use in debug mode

    # =========================================================================
    # Compute
    # =========================================================================
    # Use CUDA if available, otherwise CPU
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    # Number of workers for data loading (adjust based on vCPUs)
    NUM_WORKERS = 8

    # =========================================================================
    # File Paths
    # =========================================================================
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the provided script
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(
        METADATA_DIR, "val.csv"
    )  # Note: We use 5-fold on TRAIN_METADATA, but this exists
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Output directories
    # idea_11 is the designated working directory for this experiment
    OUTPUT_DIR = "./working/idea_11"
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Data Configuration
    # =========================================================================
    IMG_SIZE = 384
    NUM_CLASSES = 5

    # =========================================================================
    # Model Architecture
    # =========================================================================
    # Heterogeneous backbones for Level 0 Stacking
    MODEL_ARCHS = [
        "vit_base_patch16_384",
        "beit_base_patch16_384",
        "convnext_base_384_in22ft1k",
    ]

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    N_FOLDS = 5
    EPOCHS = 12
    BATCH_SIZE = 24  # Tuned for A100 40GB with 384x384 images

    # Optimization
    LR = 2e-4
    MIN_LR = 1e-6
    WEIGHT_DECAY = 0.05  # Standard for Transformers/ConvNeXt
    MAX_GRAD_NORM = 1.0

    # Regularization
    LABEL_SMOOTHING = 0.1
    DROP_PATH_RATE = 0.1  # Stochastic Depth

    # Augmentation (MixUp / CutMix)
    MIXUP_ALPHA = 0.8
    CUTMIX_ALPHA = 1.0
    MIXUP_PROB = 1.0  # Probability of applying mixing

    @classmethod
    def setup(cls):
        """
        Creates necessary output directories.
        """
        os.makedirs(cls.OUTPUT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

    @classmethod
    def print_config(cls):
        """
        Prints the current configuration.
        """
        print("=" * 30)
        print("CONFIG")
        print("=" * 30)
        for k, v in cls.__dict__.items():
            if not k.startswith("__") and not callable(v):
                print(f"{k}: {v}")
        print("=" * 30)
