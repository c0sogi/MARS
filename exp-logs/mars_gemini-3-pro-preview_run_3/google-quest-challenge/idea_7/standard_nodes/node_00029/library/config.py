import os


class Config:
    """
    Global configuration for the StackExchange Question-Answer Labeling task.
    Implements the 'Domain-Adapted DeBERTa-v3 with Topology-Aware Stacking' strategy.
    """

    # --------------------------------------------------------------------------
    # Directory Setup
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_7"
    SUBMISSION_DIR = "./submission"

    # Ensure necessary writeable directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    # Metadata files generated by the metadata script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Original input files
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output file
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Model Configuration
    # --------------------------------------------------------------------------
    # Pre-trained backbones
    MODEL_DEBERTA = "microsoft/deberta-v3-large"
    MODEL_MPNET = "sentence-transformers/all-mpnet-base-v2"

    # Path to save/load the Domain-Adapted model
    DAPT_MODEL_OUTPUT_PATH = os.path.join(WORKING_DIR, "dapt_deberta_v3_large")

    # --------------------------------------------------------------------------
    # Hyperparameters
    # --------------------------------------------------------------------------
    SEED = 42
    MAX_LEN = 512

    # Domain Adaptation (DAPT) Hyperparameters
    DAPT_EPOCHS = 3
    DAPT_BATCH_SIZE = 1
    DAPT_GRAD_ACCUM_STEPS = 4
    DAPT_LR = 2e-5
    DAPT_MLM_PROB = 0.15

    # Supervised Fine-Tuning Hyperparameters
    TRAIN_BATCH_SIZE = 1  # Optimized for A100 (40GB) with Large model
    VALID_BATCH_SIZE = 8
    GRAD_ACCUM_STEPS = 4
    LEARNING_RATE = 1e-5
    WEIGHT_DECAY = 0.01
    EPOCHS = 4  # Early stopping should be implemented in training loop
    WARMUP_RATIO = 0.1

    # Stacking / Cross-Validation
    N_FOLDS = 4

    # --------------------------------------------------------------------------
    # Target Definitions
    # --------------------------------------------------------------------------
    # Full list of 30 target columns
    TARGET_COLS = [
        "question_asker_intent_understanding",
        "question_body_critical",
        "question_conversational",
        "question_expect_short_answer",
        "question_fact_seeking",
        "question_has_commonly_accepted_answer",
        "question_interestingness_others",
        "question_interestingness_self",
        "question_multi_intent",
        "question_not_really_a_question",
        "question_opinion_seeking",
        "question_type_choice",
        "question_type_compare",
        "question_type_consequence",
        "question_type_definition",
        "question_type_entity",
        "question_type_instructions",
        "question_type_procedure",
        "question_type_reason_explanation",
        "question_type_spelling",
        "question_well_written",
        "answer_helpful",
        "answer_level_of_information",
        "answer_plausible",
        "answer_relevance",
        "answer_satisfaction",
        "answer_type_instructions",
        "answer_type_procedure",
        "answer_type_reason_explanation",
        "answer_well_written",
    ]

    @classmethod
    def get_question_targets(cls):
        """
        Returns the list of 21 targets related to the Question.
        Used for the Q-Solver topology.
        """
        return [c for c in cls.TARGET_COLS if c.startswith("question_")]

    @classmethod
    def get_answer_targets(cls):
        """
        Returns the list of 9 targets related to the Answer.
        Used for the A-Solver topology.
        """
        return [c for c in cls.TARGET_COLS if c.startswith("answer_")]
