import os
import torch


class Config:
    """
    Configuration class for the Essay Scoring pipeline.
    Defines parameters for data paths, model architecture, training loops,
    feature extraction, and the gradient boosting head.
    """

    # --------------------------------------------------------------------------
    # General Configuration
    # --------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset of data for debugging
    DEBUG_SAMPLES = 100  # Number of samples to use when DEBUG is True
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    NUM_WORKERS = 4  # Number of dataloader workers

    # --------------------------------------------------------------------------
    # Directory Setup
    # --------------------------------------------------------------------------
    # Base directories
    INPUT_DIR = "./metadata"
    WORKING_DIR = "./working/idea_2"
    OUTPUT_DIR = "./submission"

    # Ensure working and output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    # --------------------------------------------------------------------------
    # Data Paths
    # --------------------------------------------------------------------------
    # Input Metadata CSVs (Generated by previous steps)
    TRAIN_DATA_PATH = os.path.join(INPUT_DIR, "train_metadata.csv")
    VAL_DATA_PATH = os.path.join(INPUT_DIR, "val_metadata.csv")
    TEST_DATA_PATH = os.path.join(INPUT_DIR, "test_metadata.csv")

    # Final Submission File
    SUBMISSION_PATH = os.path.join(OUTPUT_DIR, "submission.csv")

    # --------------------------------------------------------------------------
    # Stage 1: Backbone Model (DeBERTa-v3-base) & Fine-Tuning
    # --------------------------------------------------------------------------
    MODEL_NAME = "microsoft/deberta-v3-base"

    # Tokenizer & Input settings
    MAX_LENGTH = 512  # Max tokens for standard training

    # Training Hyperparameters
    TRAIN_BATCH_SIZE = 8
    GRADIENT_ACCUMULATION_STEPS = 2
    VALID_BATCH_SIZE = 16
    EPOCHS = 3
    LEARNING_RATE = 2e-5
    WEIGHT_DECAY = 0.01
    WARMUP_RATIO = 0.1
    MAX_GRAD_NORM = 1.0

    # Model Checkpointing
    MODEL_CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    BEST_MODEL_PATH = os.path.join(MODEL_CHECKPOINT_DIR, "deberta_best.pth")
    os.makedirs(MODEL_CHECKPOINT_DIR, exist_ok=True)

    # --------------------------------------------------------------------------
    # Feature Extraction (Sliding Window Strategy)
    # --------------------------------------------------------------------------
    # Settings for handling long essays during inference/embedding generation
    WINDOW_SIZE = 512
    STRIDE = 256  # 50% overlap to capture context at boundaries

    # Cache Paths for Embeddings (Stage 1 Output)
    # Used to store the dense vector representations of essays
    TRAIN_EMBEDDINGS_PATH = os.path.join(WORKING_DIR, "train_embeddings.npy")
    VAL_EMBEDDINGS_PATH = os.path.join(WORKING_DIR, "val_embeddings.npy")
    TEST_EMBEDDINGS_PATH = os.path.join(WORKING_DIR, "test_embeddings.npy")

    # Cache Paths for Meta-Features
    # Used to store structural features (word counts, etc.)
    TRAIN_META_FEATS_PATH = os.path.join(WORKING_DIR, "train_meta_features.parquet")
    VAL_META_FEATS_PATH = os.path.join(WORKING_DIR, "val_meta_features.parquet")
    TEST_META_FEATS_PATH = os.path.join(WORKING_DIR, "test_meta_features.parquet")

    # --------------------------------------------------------------------------
    # Stage 2: LightGBM Head
    # --------------------------------------------------------------------------
    # Hyperparameters for the Gradient Boosting Regressor
    LGBM_PARAMS = {
        "objective": "regression",
        "metric": "rmse",
        "verbosity": -1,
        "boosting_type": "gbdt",
        "learning_rate": 0.02,
        "num_leaves": 31,
        "feature_fraction": 0.8,  # Subsample features to encourage usage of both embeddings and meta-feats
        "bagging_fraction": 0.8,
        "bagging_freq": 5,
        "n_estimators": 2000,
        "early_stopping_rounds": 100,
        "random_state": SEED,
        "n_jobs": -1,
    }
