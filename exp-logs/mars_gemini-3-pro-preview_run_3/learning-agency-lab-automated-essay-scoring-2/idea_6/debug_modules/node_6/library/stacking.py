import os
import numpy as np
import pandas as pd
import lightgbm as lgb
import joblib
from sklearn.model_selection import StratifiedKFold
from library.config import CFG
from library.utils import compute_qwk, get_logger

# Initialize logger
logger = get_logger(os.path.join(CFG.output_dir, "stacking.log"))


def load_meta_features(is_train=True, load_cached_data=True):
    """
    Loads the meta-features from the parquet files generated by library.data.

    Args:
        is_train (bool): Whether to load train or test meta-features.
        load_cached_data (bool): Flag to verify cache existence (logic handled by data.py mostly,
                                 but here we check file existence).

    Returns:
        tuple: (meta_features_array, dataframe)
    """
    cache_name = "train_processed" if is_train else "test_processed"
    cache_file = os.path.join(CFG.cache_dir, f"{cache_name}.parquet")

    if load_cached_data and os.path.exists(cache_file):
        # logger.info(f"Loading meta-features from {cache_file}")
        df = pd.read_parquet(cache_file)
        # Select specific scalar features calculated in data.py
        meta_cols = ["char_count", "word_count", "sentence_count", "unique_word_ratio"]
        return df[meta_cols].values.astype(np.float32), df
    else:
        # If the file doesn't exist, we cannot proceed as this module depends on data.py
        raise FileNotFoundError(
            f"Cache file {cache_file} not found. Ensure data processing is complete."
        )


def create_stacking_dataset(
    embeddings, meta_features, cache_name, load_cached_data=True
):
    """
    Combines neural embeddings and meta-features into a single feature matrix.
    Implements caching using .npy files.

    Args:
        embeddings (np.array): Neural embeddings (N, D).
        meta_features (np.array): Scalar features (N, 4).
        cache_name (str): Identifier for the cache file.
        load_cached_data (bool): Whether to attempt loading from cache.

    Returns:
        np.array: Combined feature matrix.
    """
    os.makedirs(CFG.cache_dir, exist_ok=True)
    cache_path = os.path.join(CFG.cache_dir, f"{cache_name}_features.npy")

    if load_cached_data and os.path.exists(cache_path):
        logger.info(f"Loading stacking features from {cache_path}")
        features = np.load(cache_path)
    else:
        logger.info(f"Creating stacking features for {cache_name}...")
        # Concatenate: (N, hidden_size) + (N, 4) -> (N, hidden_size + 4)
        features = np.concatenate([embeddings, meta_features], axis=1)

        # Save to cache
        np.save(cache_path, features)
        logger.info(f"Saved stacking features to {cache_path}")

    return features


def train_lgbm_and_predict(
    oof_embeddings, train_labels, test_embeddings, load_cached_data=True
):
    """
    Trains LightGBM on OOF embeddings + meta-features and predicts on the test set.

    Args:
        oof_embeddings (np.array): Embeddings for the training set (from backbone OOF).
        train_labels (np.array): Ground truth scores for training set.
        test_embeddings (np.array): Embeddings for the test set (averaged backbone preds).
        load_cached_data (bool): Whether to use cached feature matrices.

    Returns:
        float: The QWK score on the OOF data.
    """
    logger.info("Starting LightGBM Stacking...")

    # 1. Load Meta Features and Dataframes (for IDs)
    train_meta, train_df = load_meta_features(
        is_train=True, load_cached_data=load_cached_data
    )
    test_meta, test_df = load_meta_features(
        is_train=False, load_cached_data=load_cached_data
    )

    # 2. Create Combined Feature Matrices
    # We use specific cache names to distinguish between runs if needed, or just standard names
    X = create_stacking_dataset(
        oof_embeddings, train_meta, "train_stacking", load_cached_data
    )
    y = train_labels
    X_test = create_stacking_dataset(
        test_embeddings, test_meta, "test_stacking", load_cached_data
    )

    # 3. Stratified K-Fold for Stacking
    # We re-split the data for the meta-learner to ensure robust evaluation
    skf = StratifiedKFold(n_splits=CFG.n_folds, shuffle=True, random_state=CFG.seed)

    oof_preds = np.zeros(X.shape[0])
    test_preds = np.zeros(X_test.shape[0])

    models = []

    for fold, (train_idx, val_idx) in enumerate(skf.split(X, y.astype(int))):
        logger.info(f"LightGBM Fold {fold+1}/{CFG.n_folds}")

        X_train, y_train = X[train_idx], y[train_idx]
        X_val, y_val = X[val_idx], y[val_idx]

        # Create LightGBM Datasets
        lgb_train = lgb.Dataset(X_train, y_train)
        lgb_val = lgb.Dataset(X_val, y_val, reference=lgb_train)

        # Callbacks for logging and early stopping
        callbacks = [
            lgb.log_evaluation(period=CFG.print_freq),
            lgb.early_stopping(stopping_rounds=CFG.lgb_params["early_stopping_round"]),
        ]

        # Train
        model = lgb.train(
            CFG.lgb_params,
            lgb_train,
            valid_sets=[lgb_train, lgb_val],
            num_boost_round=CFG.lgb_params["n_estimators"],
            callbacks=callbacks,
        )

        # Predict Validation (OOF)
        val_pred = model.predict(X_val, num_iteration=model.best_iteration)
        oof_preds[val_idx] = val_pred

        # Predict Test
        test_pred = model.predict(X_test, num_iteration=model.best_iteration)
        test_preds += test_pred / CFG.n_folds

        models.append(model)

        # Save Model
        model_path = os.path.join(CFG.checkpoint_dir, f"lgbm_fold_{fold}.pkl")
        joblib.dump(model, model_path)

    # 4. Evaluate OOF Performance
    # Clip predictions to valid range [1, 6] and round to nearest integer
    oof_preds_int = np.rint(np.clip(oof_preds, 1, 6)).astype(int)
    y_int = y.astype(int)

    qwk_score = compute_qwk(y_int, oof_preds_int)
    logger.info(f"LightGBM Stacking OOF QWK: {qwk_score}")

    # 5. Process Test Predictions and Save Submission
    final_preds = np.rint(np.clip(test_preds, 1, 6)).astype(int)

    submission = pd.DataFrame({"essay_id": test_df["essay_id"], "score": final_preds})

    # Ensure submission directory exists
    os.makedirs(CFG.submission_dir, exist_ok=True)
    submission_path = os.path.join(CFG.submission_dir, "submission.csv")
    submission.to_csv(submission_path, index=False)

    logger.info(f"Submission saved to {submission_path}")

    return qwk_score
