import os
import torch


class CFG:
    """
    Configuration class for Essay Scoring with DeBERTa-v3-Large and LightGBM Stacking.
    Implements parameters for Idea 6: Full-Scale K-Fold Ensemble with Adversarial Robustness.
    """

    # ====================================================
    # General Settings
    # ====================================================
    seed = 42
    num_workers = 4
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # Debugging: Set to True to run on a small subset for testing pipeline logic
    debug = False
    debug_subset_size = 100
    print_freq = 100

    # ====================================================
    # Directories
    # ====================================================
    # Working directory for Idea 6
    base_dir = "./working/idea_6"
    output_dir = os.path.join(base_dir, "output")
    checkpoint_dir = os.path.join(base_dir, "checkpoints")
    cache_dir = os.path.join(base_dir, "cache")
    submission_dir = "./submission"

    # Ensure directories exist
    for d in [base_dir, output_dir, checkpoint_dir, cache_dir, submission_dir]:
        os.makedirs(d, exist_ok=True)

    # ====================================================
    # Data Paths
    # ====================================================
    # Primary data sources
    train_path = "./input/train.csv"
    test_path = "./input/test.csv"
    sample_submission_path = "./input/sample_submission.csv"

    # Metadata paths (generated by previous steps)
    meta_train_path = "./metadata/train_metadata.csv"
    meta_val_path = "./metadata/val_metadata.csv"
    meta_test_path = "./metadata/test_metadata.csv"

    # ====================================================
    # Model Architecture
    # ====================================================
    model_name = "microsoft/deberta-v3-large"
    gradient_checkpointing = True
    target_size = 1  # Regression output

    # Dropout settings (often set to 0 for regression transformers)
    hidden_dropout_prob = 0.0
    attention_probs_dropout_prob = 0.0

    # Pooling Strategy
    pooling_type = "attention"  # Attention pooling on the final hidden layer

    # ====================================================
    # Tokenization & Sliding Window
    # ====================================================
    # DeBERTa max length is 512. We use a sliding window approach.
    max_len = 512  # Window size
    stride = 128  # Overlap stride

    # ====================================================
    # Training Hyperparameters
    # ====================================================
    n_folds = 5  # 5-Fold Stratified CV
    epochs = 3  # Sufficient for fine-tuning within 24h limit
    batch_size = 4  # Fits A100 40GB with DeBERTa-Large
    accum_iter = 4  # Gradient accumulation steps (Effective BS = 16)
    max_grad_norm = 10.0  # Gradient clipping threshold

    # Optimization
    encoder_lr = 1e-5  # Learning rate for backbone
    head_lr = 1e-4  # Learning rate for regression head
    weight_decay = 0.01
    warmup_ratio = 0.1
    scheduler = "cosine"  # Cosine annealing schedule

    # Layer-wise Learning Rate Decay (LLRD)
    llrd_decay = 0.9  # Decay rate for deeper layers

    # Adversarial Weight Perturbation (AWP)
    use_awp = True
    awp_lr = 1e-4
    awp_eps = 1e-4
    awp_start_epoch = 1  # Enable AWP after the first epoch

    # ====================================================
    # Stacking / Meta-Model (LightGBM)
    # ====================================================
    # Parameters for the LightGBM Regressor Head
    lgb_params = {
        "objective": "regression",
        "metric": "rmse",
        "boosting_type": "gbdt",
        "verbosity": -1,
        "feature_fraction": 0.7,  # Subsample features to force usage of embeddings
        "learning_rate": 0.01,
        "num_leaves": 31,
        "bagging_fraction": 0.8,
        "bagging_freq": 1,
        "n_estimators": 2000,
        "early_stopping_round": 100,
        "n_jobs": -1,
        "random_state": 42,
    }
