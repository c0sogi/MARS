import os
import torch


class Config:
    """
    Configuration class for the Essay Scoring pipeline.
    Centralizes all hyperparameters, paths, and model settings.
    """

    # =========================================================================
    # General Settings
    # =========================================================================
    seed = 42
    debug = False  # Set to True to run on a small subset for debugging
    num_workers = 4
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # =========================================================================
    # File Paths & Directories
    # =========================================================================
    # Input Directories
    input_dir = "./input"
    metadata_dir = "./metadata"

    # Metadata Files (Generated by previous steps)
    train_metadata_path = os.path.join(metadata_dir, "train_metadata.csv")
    val_metadata_path = os.path.join(metadata_dir, "val_metadata.csv")
    test_metadata_path = os.path.join(metadata_dir, "test_metadata.csv")

    # Working Directories (Idea 4)
    working_dir = "./working/idea_4"
    cache_dir = os.path.join(working_dir, "cache")
    checkpoint_dir = os.path.join(working_dir, "checkpoints")
    output_dir = os.path.join(working_dir, "output")

    # Submission
    submission_dir = "./submission"
    submission_path = os.path.join(submission_dir, "submission.csv")

    # =========================================================================
    # Model Architecture (Backbone)
    # =========================================================================
    model_name = "microsoft/deberta-v3-large"
    max_length = 1024  # Handling long essays
    gradient_checkpointing = True  # Essential for A100 40GB with Large model

    # Pooling Strategy
    # Options: 'mean', 'max', 'attention', 'cls'
    pooling_type = "attention"

    # =========================================================================
    # Training Hyperparameters (Stage 1: Backbone)
    # =========================================================================
    n_folds = 5
    epochs = 4

    # Batch Size Configuration
    # Effective batch size = batch_size * accum_iter
    batch_size = 4
    accum_iter = 4

    # Optimizer & Scheduler
    lr = 1e-5
    weight_decay = 0.01
    eps = 1e-6
    scheduler = "cosine"
    warmup_ratio = 0.1
    clip_grad_norm = 1.0

    # Mixed Precision
    use_amp = True
    dtype = torch.float16

    # =========================================================================
    # Advanced Training Techniques
    # =========================================================================
    # Layer-wise Learning Rate Decay (LLRD)
    use_llrd = True
    llrd_rate = 0.9

    # Adversarial Weight Perturbation (AWP)
    use_awp = True
    awp_lr = 1e-4
    awp_eps = 1e-2
    awp_start_epoch = 1.0  # Start AWP after the first epoch

    # =========================================================================
    # Stacking Head (Stage 2: LightGBM)
    # =========================================================================
    use_meta_features = True
    meta_features = [
        "char_count",
        "word_count",
        "sentence_count",
        "unique_word_ratio",
        "paragraph_count",
    ]

    # LightGBM Hyperparameters
    lgbm_params = {
        "objective": "regression",
        "metric": "rmse",
        "boosting_type": "gbdt",
        "learning_rate": 0.005,
        "num_leaves": 31,
        "feature_fraction": 0.7,  # Subsample features to force usage of embeddings
        "bagging_fraction": 0.8,
        "bagging_freq": 5,
        "verbosity": -1,
        "n_estimators": 5000,
        "early_stopping_rounds": 100,
        "random_state": 42,
        "n_jobs": -1,
    }

    @classmethod
    def create_directories(cls):
        """
        Creates necessary directories for the experiment.
        """
        for d in [
            cls.working_dir,
            cls.cache_dir,
            cls.checkpoint_dir,
            cls.output_dir,
            cls.submission_dir,
        ]:
            os.makedirs(d, exist_ok=True)

    @classmethod
    def get_lgbm_params(cls):
        """
        Returns LightGBM parameters, potentially modifying them based on debug mode.
        """
        params = cls.lgbm_params.copy()
        if cls.debug:
            params["n_estimators"] = 100
        return params
