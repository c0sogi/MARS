import os
import random
import numpy as np
import torch


class Config:
    """
    Configuration for the Anchor-Variant Parallel Funnel Ensemble (AV-PFE) strategy.
    Defines project-wide constants, file paths, model architecture, and training hyperparameters.
    """

    # =========================================================================
    # File Paths & Directories
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_22"
    SUBMISSION_DIR = "./submission"

    # Input Files (Generated by metadata script)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Output Files
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Caching Directory (for Parquet/NPY files)
    CACHE_DIR = WORKING_DIR

    # =========================================================================
    # Global Settings
    # =========================================================================
    SEED = 42
    DEBUG = False  # Set to True to run on a subset of data for testing
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # =========================================================================
    # Data Processing Parameters
    # =========================================================================
    # Feature Engineering
    N_F27_CHARS = 10  # Number of characters to split f_27 into
    DISCRETE_FEATURES = ["f_29", "f_30"]

    # =========================================================================
    # Model Architecture: Anchor-Variant Parallel Funnel Ensemble (AV-PFE)
    # =========================================================================
    EMBED_DIM = 16  # Fixed embedding dimension for all categorical streams

    # Stream Definitions
    # Each dictionary defines the architecture for one independent stream in the ensemble.
    # Anchors provide stability; Variants explore capacity and regularization boundaries.
    STREAM_CONFIGS = [
        # Stream 1: Anchor (Standard Funnel, Moderate Reg)
        {"layers": [512, 256, 128], "dropout": 0.20},
        # Stream 2: Anchor (Standard Funnel, Moderate Reg)
        {"layers": [512, 256, 128], "dropout": 0.20},
        # Stream 3: Capacity Variant (Wide Funnel, Higher Reg)
        {"layers": [1024, 512, 256], "dropout": 0.25},
        # Stream 4: Aggressive Variant (Standard Funnel, Low Reg)
        {"layers": [512, 256, 128], "dropout": 0.10},
        # Stream 5: Conservative Variant (Standard Funnel, High Reg)
        {"layers": [512, 256, 128], "dropout": 0.30},
    ]

    # =========================================================================
    # Training Hyperparameters
    # =========================================================================
    BATCH_SIZE = 1024
    EPOCHS = 20  # Sufficient for One-Cycle convergence

    # Optimizer & Scheduler
    MAX_LR = 1e-2  # Restored high learning rate for Super-Convergence
    WEIGHT_DECAY = 1e-4  # Calibrated for AdamW

    @classmethod
    def setup(cls):
        """
        Initialize the environment:
        1. Create necessary working and submission directories.
        2. Set random seeds for reproducibility.
        """
        # Create directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)

        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(cls.SEED)
            # Ensure deterministic behavior where possible
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False

        print(f"Configuration Setup Complete. Working Directory: {cls.WORKING_DIR}")
