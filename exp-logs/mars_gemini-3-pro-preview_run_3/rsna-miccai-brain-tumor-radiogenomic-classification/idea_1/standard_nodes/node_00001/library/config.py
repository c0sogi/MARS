import os
import torch


class Config:
    """
    Central configuration for the Multi-Modal 2.5D Stacked CNN pipeline.
    """

    # -------------------------------------------------------------------------
    # Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42

    # -------------------------------------------------------------------------
    # Directories & Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_1"
    SUBMISSION_DIR = "./submission"

    # Metadata files generated by the analysis step
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.parquet")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.parquet")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.parquet")

    # Output paths
    MODEL_PATH = os.path.join(WORKING_DIR, "best_model.pth")
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Preprocessing & Model Architecture
    # -------------------------------------------------------------------------
    # Modalities to use
    MODALITIES = ["FLAIR", "T1w", "T1wCE", "T2w"]

    # Image dimensions
    IMAGE_SIZE = 256

    # Slice extraction strategy
    NUM_SLICES = 3  # Number of slices to extract per modality (e.g., middle 3)

    # Input channels = Modalities * Slices per modality
    # For 4 modalities and 3 slices, input channels = 12
    IN_CHANNELS = len(MODALITIES) * NUM_SLICES

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    BATCH_SIZE = 32
    NUM_EPOCHS = 20
    LEARNING_RATE = 1e-4

    # Early Stopping
    EARLY_STOPPING_PATIENCE = 5

    # Debugging / Development
    # Set DEBUG to True to run on a small subset of data for quick testing
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 32

    # -------------------------------------------------------------------------
    # Hardware & Compute
    # -------------------------------------------------------------------------
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    @staticmethod
    def initialize():
        """
        Creates necessary output directories if they do not exist.
        Should be called at the start of the pipeline.
        """
        os.makedirs(Config.WORKING_DIR, exist_ok=True)
        os.makedirs(Config.SUBMISSION_DIR, exist_ok=True)


# Automatically setup directories when config is imported
Config.initialize()
