import os

# Ensure working and submission directories exist upon import
os.makedirs("./working/idea_8", exist_ok=True)
os.makedirs("./submission", exist_ok=True)


class Config:
    """
    Central configuration for the Early-Fusion Dual-Stream GBDT solution.
    Handles paths, hyperparameters, and feature whitelists for Stream A (Player-Player)
    and Stream B (Player-Ground).
    """

    # =========================================================================
    # Directories and Paths
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_8"
    SUBMISSION_DIR = "./submission"

    # Metadata Paths (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Raw Data Paths
    TRAIN_TRACKING_PATH = os.path.join(INPUT_DIR, "train_player_tracking.csv")
    TEST_TRACKING_PATH = os.path.join(INPUT_DIR, "test_player_tracking.csv")
    TRAIN_HELMETS_PATH = os.path.join(INPUT_DIR, "train_baseline_helmets.csv")
    TEST_HELMETS_PATH = os.path.join(INPUT_DIR, "test_baseline_helmets.csv")

    # Output Paths
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    CACHE_PATH_PREFIX = os.path.join(WORKING_DIR, "cache_")

    # =========================================================================
    # Global Settings
    # =========================================================================
    SEED = 42
    N_JOBS = 12
    EXP_NAME = "idea_8_dual_stream_gbdt"

    # =========================================================================
    # Data Preprocessing Config
    # =========================================================================
    # Window sizes for rolling statistics
    WINDOW_SIZE_MICRO = 4  # +/- 4 frames (approx 0.4s window)
    WINDOW_SIZE_MACRO = 15  # +/- 15 frames (approx 1.5s window)

    # Undersampling ratio for training (Negative : Positive)
    NEGATIVE_RATIO = 10.0

    # =========================================================================
    # Model Hyperparameters (XGBoost)
    # =========================================================================
    # Stream A: Player-Player Interaction
    # Deeper trees to capture complex conditional logic between tracking and video
    XGB_PARAMS_A = {
        "n_estimators": 5000,
        "learning_rate": 0.015,
        "max_depth": 8,
        "subsample": 0.8,
        "colsample_bytree": 0.8,
        "min_child_weight": 5,
        "gamma": 0.5,
        "tree_method": "gpu_hist",  # Utilizing A100
        "objective": "binary:logistic",
        "eval_metric": "logloss",
        "random_state": SEED,
        "n_jobs": N_JOBS,
    }

    # Stream B: Player-Ground Interaction
    # Shallower trees, focusing on threshold-based physics (impact detection)
    XGB_PARAMS_B = {
        "n_estimators": 5000,
        "learning_rate": 0.015,
        "max_depth": 6,
        "subsample": 0.8,
        "colsample_bytree": 0.9,
        "min_child_weight": 3,
        "gamma": 0.1,
        "tree_method": "gpu_hist",  # Utilizing A100
        "objective": "binary:logistic",
        "eval_metric": "logloss",
        "random_state": SEED,
        "n_jobs": N_JOBS,
    }

    # =========================================================================
    # Feature Whitelists
    # =========================================================================

    # Stream A: Interaction Model (Player vs Player)
    # Combines relative kinematics with view-specific geometry (IoU)
    FEATURES_STREAM_A = [
        # --- Micro Kinematics (Instantaneous) ---
        "p1_speed",
        "p1_acceleration",
        "p1_distance",
        "p2_speed",
        "p2_acceleration",
        "p2_distance",
        # Cyclical Orientation/Direction
        "p1_direction_sin",
        "p1_direction_cos",
        "p1_orientation_sin",
        "p1_orientation_cos",
        "p2_direction_sin",
        "p2_direction_cos",
        "p2_orientation_sin",
        "p2_orientation_cos",
        # --- Relative Kinematics ---
        "distance_p1_p2",  # Euclidean distance
        "speed_diff",  # Absolute difference in speed
        "x_diff",
        "y_diff",  # Positional offsets
        "rel_speed",  # Closing speed
        # --- Macro Kinematics (Rolling Stats) ---
        "p1_roll_mean_speed",
        "p1_roll_max_speed",
        "p1_roll_std_speed",
        "p2_roll_mean_speed",
        "p2_roll_max_speed",
        "p2_roll_std_speed",
        # --- Visual Geometry (Sideline View) ---
        "sideline_iou",  # Intersection over Union
        "sideline_dist_pixel",  # Centroid distance in pixels
        "sideline_p1_area",
        "sideline_p2_area",
        # --- Visual Geometry (Endzone View) ---
        "endzone_iou",
        "endzone_dist_pixel",
        "endzone_p1_area",
        "endzone_p2_area",
    ]

    # Stream B: Impact Model (Player vs Ground)
    # Combines physics (Signed Acceleration) with visual dynamics (Drop Velocity)
    FEATURES_STREAM_B = [
        # --- Micro Kinematics ---
        "speed",
        "acceleration",
        "sa",  # Signed Acceleration (crucial for stops)
        "distance",
        "direction_sin",
        "direction_cos",
        "orientation_sin",
        "orientation_cos",
        # --- Macro Kinematics ---
        "roll_mean_speed",
        "roll_std_speed",
        "roll_mean_accel",
        "roll_std_accel",
        "roll_min_sa",  # Minimum signed acceleration (sudden stop)
        # --- Visual Dynamics (Sideline) ---
        "sideline_helmet_drop_velocity",  # d(top)/dt
        "sideline_visual_compression",  # height / width ratio
        "sideline_bbox_area",
        # --- Visual Dynamics (Endzone) ---
        "endzone_helmet_drop_velocity",
        "endzone_visual_compression",
        "endzone_bbox_area",
    ]
