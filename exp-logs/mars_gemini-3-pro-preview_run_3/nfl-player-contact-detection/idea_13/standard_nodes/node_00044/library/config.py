# ==============================================================================
# 3. TEMPORAL PYRAMID CONFIGURATION
# ==============================================================================
# Exponentially spaced offsets (deltas) from current time t.
# Includes both past (+) and future (-) context relative to the event.

# Tracking Deltas: Micro (1,2) + Macro (4,8,15) context
TRACKING_DELTAS = [0, -1, 1, -2, 2, -4, 4, -8, 8, -15, 15]

# Visual Deltas: Sparse Macro context only (to capture looming/trajectory)
VISUAL_DELTAS = [0, -4, 4, -8, 8, -15, 15]

# ==============================================================================
# 4. BASE FEATURE DEFINITIONS
# ==============================================================================
# Raw tracking columns to utilize
TRACKING_BASE_COLS = [
    "x_position",
    "y_position",
    "speed",
    "direction",
    "orientation",
    "acceleration",
    "sa",
]

# Visual metrics derived from Sideline/Endzone views
VISUAL_BASE_COLS = ["sideline_iou", "sideline_dist", "endzone_iou", "endzone_dist"]

# Interaction metrics (computed between P1 and P2)
INTERACTION_COLS = ["distance", "speed_diff", "direction_diff"]

# Kinematic derivatives for Stream B (Player-Ground)
KINEMATIC_DERIVATIVES = ["jerk", "pose_motion_alignment"]


# ==============================================================================
# 5. FEATURE LIST GENERATION
# ==============================================================================
def generate_feature_names(stream_type):
    """
    Generates the exhaustive list of flattened feature names for a given stream
    based on the configured lags and base columns.
    """
    features = []

    if stream_type == "A":
        # --- STREAM A: Player-Player Interaction ---
        # 1. P1 Tracking Features (Current + Lags)
        for delta in TRACKING_DELTAS:
            suffix = f"_lag{delta}" if delta != 0 else ""
            for col in TRACKING_BASE_COLS:
                features.append(f"p1_{col}{suffix}")

        # 2. P2 Tracking Features (Current + Lags)
        for delta in TRACKING_DELTAS:
            suffix = f"_lag{delta}" if delta != 0 else ""
            for col in TRACKING_BASE_COLS:
                features.append(f"p2_{col}{suffix}")

        # 3. Interaction Features (Current + Lags)
        for delta in TRACKING_DELTAS:
            suffix = f"_lag{delta}" if delta != 0 else ""
            for col in INTERACTION_COLS:
                features.append(f"{col}{suffix}")

        # 4. Visual Features (Current + Visual Lags)
        for delta in VISUAL_DELTAS:
            suffix = f"_lag{delta}" if delta != 0 else ""
            for col in VISUAL_BASE_COLS:
                features.append(f"{col}{suffix}")

    elif stream_type == "B":
        # --- STREAM B: Player-Ground Impact ---
        # 1. P1 Tracking Features (Current + Lags)
        for delta in TRACKING_DELTAS:
            suffix = f"_lag{delta}" if delta != 0 else ""
            for col in TRACKING_BASE_COLS:
                features.append(f"p1_{col}{suffix}")

        # 2. Kinematic Derivatives (Current + Lags)
        for delta in TRACKING_DELTAS:
            suffix = f"_lag{delta}" if delta != 0 else ""
            for col in KINEMATIC_DERIVATIVES:
                features.append(f"p1_{col}{suffix}")

        # NOTE: Explicitly excluding P2 features and Visual features for Stream B
        # to prevent noise injection and overfitting.

    return features


# Pre-generate the static feature lists for import by other modules
STREAM_A_FEATURES = generate_feature_names("A")
STREAM_B_FEATURES = generate_feature_names("B")
