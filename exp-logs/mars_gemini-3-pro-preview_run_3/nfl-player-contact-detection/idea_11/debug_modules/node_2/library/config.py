import os


class Config:
    """
    Central configuration for the Contact Detection Pipeline.
    Defines paths, hyperparameters, feature specifications, and model settings.
    """

    # =========================================================================
    # DIRECTORIES AND PATHS
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_11"
    SUBMISSION_DIR = "./submission"

    # Ensure necessary writeable directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Metadata Paths (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Raw Data Paths
    TRAIN_TRACKING_PATH = os.path.join(INPUT_DIR, "train_player_tracking.csv")
    TEST_TRACKING_PATH = os.path.join(INPUT_DIR, "test_player_tracking.csv")

    TRAIN_HELMETS_PATH = os.path.join(INPUT_DIR, "train_baseline_helmets.csv")
    TEST_HELMETS_PATH = os.path.join(INPUT_DIR, "test_baseline_helmets.csv")

    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")
    FINAL_SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # GLOBAL SETTINGS
    # =========================================================================
    SEED = 42
    NUM_WORKERS = 12  # Matches vCPU count

    # Sentinel value for missing data (e.g., missing visual detection)
    # XGBoost handles this natively if configured correctly, but explicit value helps debugging
    SENTINEL_VALUE = -999.0

    # =========================================================================
    # FEATURE ENGINEERING CONFIGURATION
    # =========================================================================
    # Window sizes for time-series flattening
    # Micro: Instantaneous mechanics (approx +/- 0.4s)
    WINDOW_MICRO = 4
    # Macro: Trajectory context (approx +/- 1.5s)
    WINDOW_MACRO = 15

    # Base Tracking Columns available in raw data
    RAW_TRACKING_COLS = [
        "x_position",
        "y_position",
        "speed",
        "direction",
        "orientation",
        "acceleration",
        "sa",
    ]

    # --- Stream A: Interaction Model (Player-Player) ---
    # Features: Tracking (P1 & P2) + Conditional Visuals
    STREAM_A_FEATURES = {
        "raw_tracking": RAW_TRACKING_COLS,
        "derived_tracking": [
            "distance",  # Euclidean distance between P1 and P2
            "speed_diff",  # Absolute difference in speed
            "orientation_diff",  # Difference in body orientation
            "direction_diff",  # Difference in movement direction
        ],
        "visual": [
            "Sideline_IoU",  # Intersection over Union (Sideline view)
            "Sideline_Dist",  # Centroid pixel distance (Sideline view)
            "Endzone_IoU",  # Intersection over Union (Endzone view)
            "Endzone_Dist",  # Centroid pixel distance (Endzone view)
        ],
    }

    # --- Stream B: Impact Model (Player-Ground) ---
    # Features: Tracking (P1 Only) + Physics Derivatives. NO Visuals. NO P2.
    STREAM_B_FEATURES = {
        "raw_tracking": RAW_TRACKING_COLS,
        "derived_physics": [
            "jerk",  # Derivative of acceleration
            "pose_motion_alignment",  # Dot product of orientation and velocity vectors
            "kinetic_energy",  # 0.5 * mass (assumed 1) * speed^2
        ],
    }

    # =========================================================================
    # TRAINING HYPERPARAMETERS
    # =========================================================================
    # Undersampling ratio for majority class (No Contact)
    # Keep 1 positive : N negatives
    NEG_POS_RATIO = 10.0

    # XGBoost Hyperparameters
    # Optimized for Flattened Windows on GPU
    XGB_PARAMS = {
        "objective": "binary:logistic",
        "eval_metric": "logloss",
        "tree_method": "hist",  # Efficient histogram-based algorithm
        "device": "cuda",  # Use NVIDIA A100
        "learning_rate": 0.02,
        "max_depth": 8,  # Slightly deeper for interaction complexity
        "subsample": 0.8,
        "colsample_bytree": 0.8,
        "min_child_weight": 5,
        "n_estimators": 5000,  # High cap, controlled by early stopping
        "early_stopping_rounds": 100,
        "n_jobs": NUM_WORKERS,
        "random_state": SEED,
        "missing": SENTINEL_VALUE,  # Explicitly tell XGB how to handle sentinels
    }

    # Inference Threshold Search Space
    # Range of probabilities to scan for maximizing MCC
    THRESHOLD_SEARCH_START = 0.1
    THRESHOLD_SEARCH_END = 0.6
    THRESHOLD_SEARCH_STEP = 0.01

    @staticmethod
    def get_feature_cache_path(stream_name, split_name):
        """
        Generates a standardized path for cached feature files.
        Args:
            stream_name (str): 'streamA' or 'streamB'
            split_name (str): 'train', 'val', or 'test'
        """
        filename = f"features_{split_name}_{stream_name}.parquet"
        return os.path.join(Config.WORKING_DIR, filename)
