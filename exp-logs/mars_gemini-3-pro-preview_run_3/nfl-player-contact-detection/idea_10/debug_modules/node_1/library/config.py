import os


class Config:
    # =========================================================================
    # Directories
    # =========================================================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_10"
    SUBMISSION_DIR = "./submission"

    # Ensure output directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # =========================================================================
    # File Paths
    # =========================================================================
    # Metadata generated by the previous step
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "validation.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Raw Data
    TRAIN_TRACKING_PATH = os.path.join(INPUT_DIR, "train_player_tracking.csv")
    TEST_TRACKING_PATH = os.path.join(INPUT_DIR, "test_player_tracking.csv")

    TRAIN_HELMETS_PATH = os.path.join(INPUT_DIR, "train_baseline_helmets.csv")
    TEST_HELMETS_PATH = os.path.join(INPUT_DIR, "test_baseline_helmets.csv")

    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")
    SUBMISSION_FILE_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # =========================================================================
    # Global Settings
    # =========================================================================
    SEED = 42
    N_JOBS = 12  # Available vCPUs

    # =========================================================================
    # Data Processing Configuration
    # =========================================================================
    # Temporal Windowing: Micro (t +/- 4) and Macro (t +/- 15)
    # 4 steps = 0.4 seconds, 15 steps = 1.5 seconds
    WINDOW_SIZES = [4, 15]

    # Imputation for missing visual data (Stream A)
    VISUAL_SENTINEL_VALUE = -1.0

    # Class Balancing
    # Keep 10 negative samples for every 1 positive sample
    UNDERSAMPLE_RATIO = 10.0

    # =========================================================================
    # Feature Configuration
    # =========================================================================
    # Raw tracking columns to be used for feature generation
    TRACKING_COLS = [
        "x_position",
        "y_position",
        "speed",
        "direction",
        "orientation",
        "acceleration",
        "sa",
    ]

    # =========================================================================
    # Model Hyperparameters
    # =========================================================================
    # Common XGBoost arguments
    _XGB_COMMON = {
        "objective": "binary:logistic",
        "eval_metric": "logloss",
        "tree_method": "hist",
        "device": "cuda",  # Use A100 GPU
        "n_jobs": N_JOBS,
        "random_state": SEED,
        "n_estimators": 10000,  # High cap, controlled by early stopping
        "early_stopping_rounds": 100,
    }

    # Stream A: Interaction Model (Player-Player)
    # Needs to handle sparse visual data and complex interactions
    XGB_PARAMS_STREAM_A = _XGB_COMMON.copy()
    XGB_PARAMS_STREAM_A.update(
        {
            "learning_rate": 0.02,
            "max_depth": 8,
            "subsample": 0.8,
            "colsample_bytree": 0.8,
            "min_child_weight": 5,
        }
    )

    # Stream B: Impact Model (Player-Ground)
    # Relies on kinematics and physics derivatives (Jerk, etc.)
    # Visuals are explicitly blocked in this stream
    XGB_PARAMS_STREAM_B = _XGB_COMMON.copy()
    XGB_PARAMS_STREAM_B.update(
        {
            "learning_rate": 0.02,
            "max_depth": 6,  # Slightly shallower to prevent overfitting on noise
            "subsample": 0.8,
            "colsample_bytree": 0.8,
            "min_child_weight": 3,
        }
    )
