import pandas as pd
import numpy as np
import os
import gc
from library.config import Config
from library.utils import reduce_mem_usage, setup_logger
from library.data_loader import DataLoader


class TrackingFeatureEngineer:
    """
    Implements the kinematic feature generation pipeline (Stream A).
    Generates Micro and Macro temporal features from player tracking data
    and merges them with contact labels.
    """

    def __init__(self):
        self.config = Config
        self.logger = setup_logger("TrackingFE")
        self.data_loader = DataLoader()

    def preprocess_tracking(self, tracking_df):
        """
        Applies feature engineering to the raw tracking dataframe.
        Includes angular decomposition, micro-window shifts, and macro-window rolling stats.
        """
        # Ensure data is sorted for temporal operations
        tracking_df = tracking_df.sort_values(
            by=["game_play", "nfl_player_id", "step"]
        ).reset_index(drop=True)

        # 1. Angular Decomposition
        # Orientation and Direction are in degrees (0-360)
        for col in ["orientation", "direction"]:
            if col in tracking_df.columns:
                rads = np.deg2rad(tracking_df[col].fillna(0))
                tracking_df[f"{col}_sin"] = np.sin(rads)
                tracking_df[f"{col}_cos"] = np.cos(rads)
                # Drop original degree columns to save space if needed, but keeping them is fine

        # Define feature groups
        base_features = [
            "x_position",
            "y_position",
            "speed",
            "acceleration",
            "sa",
            "orientation_sin",
            "orientation_cos",
            "direction_sin",
            "direction_cos",
        ]
        # Filter to available columns
        base_features = [c for c in base_features if c in tracking_df.columns]

        # Group object for efficient application
        # We use transform to keep the index aligned
        grouper = tracking_df.groupby(["game_play", "nfl_player_id"])

        # 2. Micro-Window Features (Lags/Leads)
        # Config.MICRO_WINDOW_SIZE = 4. We take a few key offsets.
        shifts = [-4, -2, -1, 1, 2, 4]

        for feature in base_features:
            for s in shifts:
                # shift(positive) takes previous value (lag), shift(negative) takes future (lead)
                # But pandas shift(1) gives value from index i-1 at index i.
                # To get t-k, we use shift(k). To get t+k, we use shift(-k).
                col_name = f"{feature}_shift_{s}"
                tracking_df[col_name] = grouper[feature].shift(s)

        # 3. Macro-Window Features (Rolling Stats)
        # Config.MACRO_WINDOW_SIZE = 15.
        window_size = self.config.MACRO_WINDOW_SIZE

        # We only apply rolling stats to motion magnitude features
        macro_targets = ["speed", "acceleration"]
        macro_targets = [c for c in macro_targets if c in tracking_df.columns]

        for feature in macro_targets:
            # Centered rolling window
            rolling_obj = grouper[feature].rolling(
                window=window_size, center=True, min_periods=1
            )
            tracking_df[f"{feature}_roll_mean_{window_size}"] = (
                rolling_obj.mean().reset_index(drop=True)
            )
            tracking_df[f"{feature}_roll_std_{window_size}"] = (
                rolling_obj.std().reset_index(drop=True)
            )

        # Fill NaNs generated by shifts/rolling with 0 or appropriate method
        # Forward fill then backward fill within group is often safer for tracking, but 0 is safe for missing lags at edges
        tracking_df = tracking_df.fillna(0)

        return reduce_mem_usage(tracking_df)

    def create_features(
        self, metadata_df, tracking_df=None, mode="train", load_cached_data=True
    ):
        """
        Main pipeline execution method.

        Args:
            metadata_df (pd.DataFrame): The labels/metadata containing contact_id, game_play, step, players.
            tracking_df (pd.DataFrame, optional): Raw tracking data. If None, loads from DataLoader.
            mode (str): 'train', 'validation', or 'test'. Used for caching and data selection.
            load_cached_data (bool): Whether to attempt loading from cache.

        Returns:
            pd.DataFrame: The merged feature set ready for training/inference.
        """
        cache_path = os.path.join(
            self.config.WORKING_DIR, f"{mode}_tracking_features.parquet"
        )

        # 1. Check Cache
        if load_cached_data and os.path.exists(cache_path):
            self.logger.info(f"Loading cached tracking features from {cache_path}")
            return pd.read_parquet(cache_path)

        self.logger.info(f"Generating tracking features for {mode} set...")

        # 2. Load Tracking Data if not provided
        if tracking_df is None:
            train_track, test_track = self.data_loader.load_tracking_data(
                load_cached_data=load_cached_data
            )
            if mode == "test":
                tracking_df = test_track
            else:
                tracking_df = train_track

            # Clean up unused dataframe to save memory
            if mode == "test":
                del train_track
            else:
                del test_track
            gc.collect()

        # 3. Filter Tracking Data
        # Only keep game_plays present in metadata to reduce processing time
        relevant_plays = metadata_df["game_play"].unique()
        tracking_df = tracking_df[tracking_df["game_play"].isin(relevant_plays)].copy()

        if tracking_df.empty:
            raise ValueError(
                f"No tracking data found for the games in {mode} metadata."
            )

        # 4. Preprocess Tracking Data (Feature Engineering)
        self.logger.info("Preprocessing tracking data (Micro/Macro windows)...")
        tracking_df = self.preprocess_tracking(tracking_df)

        # 5. Merge Features
        self.logger.info("Merging tracking features with labels...")

        # Ensure join keys are consistent types
        metadata_df["step"] = metadata_df["step"].astype(int)
        tracking_df["step"] = tracking_df["step"].astype(int)
        metadata_df["nfl_player_id_1"] = metadata_df["nfl_player_id_1"].astype(str)
        metadata_df["nfl_player_id_2"] = metadata_df["nfl_player_id_2"].astype(str)
        tracking_df["nfl_player_id"] = tracking_df["nfl_player_id"].astype(str)

        # Merge Player 1
        # Rename tracking columns to _p1 suffix
        track_p1 = tracking_df.add_suffix("_p1")
        # Restore join keys in tracking df (add_suffix changed them)
        track_p1 = track_p1.rename(
            columns={
                "game_play_p1": "game_play",
                "step_p1": "step",
                "nfl_player_id_p1": "nfl_player_id_1",
            }
        )

        merged_df = pd.merge(
            metadata_df,
            track_p1,
            on=["game_play", "step", "nfl_player_id_1"],
            how="left",
        )

        # Merge Player 2
        # Rename tracking columns to _p2 suffix
        track_p2 = tracking_df.add_suffix("_p2")
        track_p2 = track_p2.rename(
            columns={
                "game_play_p2": "game_play",
                "step_p2": "step",
                "nfl_player_id_p2": "nfl_player_id_2",
            }
        )

        merged_df = pd.merge(
            merged_df, track_p2, on=["game_play", "step", "nfl_player_id_2"], how="left"
        )

        # 6. Post-Merge Interaction Features
        self.logger.info("Calculating interaction features...")

        # Handle Ground (G) or missing tracking data
        # Create flag for ground contact
        merged_df["is_ground"] = (merged_df["nfl_player_id_2"] == "G").astype(int)

        # Fill NaNs for P2 (which occur for Ground or missing tracking) with 0
        # Identify P2 columns (those ending in _p2)
        p2_cols = [c for c in merged_df.columns if c.endswith("_p2")]
        # Only fill numeric columns to avoid corrupting string columns (e.g. datetime) with int 0
        p2_numeric = merged_df[p2_cols].select_dtypes(include=[np.number]).columns
        merged_df[p2_numeric] = merged_df[p2_numeric].fillna(0)

        # Also fill P1 NaNs if any (should be rare)
        p1_cols = [c for c in merged_df.columns if c.endswith("_p1")]
        p1_numeric = merged_df[p1_cols].select_dtypes(include=[np.number]).columns
        merged_df[p1_numeric] = merged_df[p1_numeric].fillna(0)

        # Distance
        # If is_ground, distance is technically 0 (contact with floor), but geometrically undefined.
        # We calculate Euclidean distance based on filled values (0,0 for ground).
        # However, distance between player at (50, 25) and ground (0,0) is misleading.
        # We will enforce distance = 0 for ground contacts to signal proximity.

        dx = merged_df["x_position_p1"] - merged_df["x_position_p2"]
        dy = merged_df["y_position_p1"] - merged_df["y_position_p2"]
        dist = np.sqrt(dx**2 + dy**2)

        # Overwrite distance for ground contacts to -1 or 0.
        # 0 is ambiguous with actual contact. -1 clearly separates it.
        # But tree models handle continuous splits well. Let's use -1 for ground distance.
        merged_df["distance"] = np.where(merged_df["is_ground"] == 1, -1.0, dist)

        # Relative Speed
        s_diff = merged_df["speed_p1"] - merged_df["speed_p2"]
        merged_df["speed_diff"] = np.where(
            merged_df["is_ground"] == 1, merged_df["speed_p1"], s_diff
        )

        # 7. Save and Return
        self.logger.info(f"Saving features to {cache_path}...")
        merged_df = reduce_mem_usage(merged_df)
        merged_df.to_parquet(cache_path, index=False)

        return merged_df
