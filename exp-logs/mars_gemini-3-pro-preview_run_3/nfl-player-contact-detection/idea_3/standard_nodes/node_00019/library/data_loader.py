import os
import glob
import json
import hashlib
import pandas as pd
import numpy as np
from library.config import Config
from library.utils import get_logger
from library.feature_engineering import FeatureEngineer

logger = get_logger("data_loader")


class CacheHandler:
    """
    Manages cache invalidation based on configuration changes.

    Since the provided FeatureEngineer uses fixed filenames for caching,
    this handler computes a hash of the current data configuration.
    If the configuration changes, it invalidates (deletes) the existing
    cache files to force regeneration.
    """

    def __init__(self):
        self.cache_dir = Config.WORKING_DIR
        self.hash_file = os.path.join(self.cache_dir, "data_config_hash.json")
        os.makedirs(self.cache_dir, exist_ok=True)

    def _compute_hash(self):
        """
        Computes a deterministic hash based on configuration parameters
        that affect data generation.
        """
        config_dict = {
            "window_size": Config.WINDOW_SIZE,
            "undersample_ratio": Config.UNDERSAMPLE_RATIO,
            "features": Config.PER_STEP_FEATURES,
            "seed": Config.SEED,
        }
        # Serialize to JSON string with sort_keys for determinism
        config_str = json.dumps(config_dict, sort_keys=True)
        return hashlib.md5(config_str.encode("utf-8")).hexdigest()

    def check_and_invalidate(self):
        """
        Checks if the current configuration matches the cached one.
        If not, deletes cached data files to force regeneration.
        """
        current_hash = self._compute_hash()
        stored_hash = ""

        if os.path.exists(self.hash_file):
            try:
                with open(self.hash_file, "r") as f:
                    data = json.load(f)
                    stored_hash = data.get("hash", "")
            except Exception as e:
                logger.warning(f"Could not read hash file: {e}")

        if current_hash != stored_hash:
            logger.info("Configuration changed or hash missing. Invalidating cache...")
            # Patterns of files generated by FeatureEngineer
            patterns = ["*_X.parquet", "*_y.npy", "*_ids.npy"]
            deleted_count = 0
            for pattern in patterns:
                files = glob.glob(os.path.join(self.cache_dir, pattern))
                for file_path in files:
                    try:
                        os.remove(file_path)
                        deleted_count += 1
                    except OSError as e:
                        logger.error(f"Error deleting cached file {file_path}: {e}")

            if deleted_count > 0:
                logger.info(f"Deleted {deleted_count} cached files.")

            # Update the hash file
            try:
                with open(self.hash_file, "w") as f:
                    json.dump({"hash": current_hash}, f)
            except Exception as e:
                logger.error(f"Error writing hash file: {e}")
        else:
            logger.info("Configuration hash matches. Cache is valid.")


class DatasetManager:
    """
    Orchestrates data loading, preprocessing, and caching.

    Acts as a wrapper around FeatureEngineer to ensure configuration
    consistency and provide a clean interface for the training pipeline.
    """

    def __init__(self, load_cached_data=True):
        """
        Args:
            load_cached_data (bool): If True, attempts to load from cache.
                                     If False, forces regeneration.
        """
        self.load_cached_data = load_cached_data

        # If we intend to load cached data, we must first ensure the cache
        # is valid relative to the current configuration.
        if self.load_cached_data:
            cache_handler = CacheHandler()
            cache_handler.check_and_invalidate()

        # Initialize the provided FeatureEngineer which handles the heavy lifting
        # (loading, lagging, flattening, undersampling, and saving to disk)
        self.fe = FeatureEngineer(load_cached_data=self.load_cached_data)

    def get_train_data(self):
        """
        Retrieves training data.
        Note: The underlying FeatureEngineer handles undersampling for the train split.

        Returns:
            X (pd.DataFrame): Feature matrix
            y (np.ndarray): Target vector
            ids (np.ndarray): Contact IDs
        """
        logger.info("Retrieving training data...")
        return self.fe.process_data("train")

    def get_validation_data(self):
        """
        Retrieves validation data.

        Returns:
            X (pd.DataFrame): Feature matrix
            y (np.ndarray): Target vector
            ids (np.ndarray): Contact IDs
        """
        logger.info("Retrieving validation data...")
        return self.fe.process_data("validation")

    def get_test_data(self):
        """
        Retrieves test data for inference.

        Returns:
            X (pd.DataFrame): Feature matrix
            y (np.ndarray): Target vector (placeholder/zeros)
            ids (np.ndarray): Contact IDs
        """
        logger.info("Retrieving test data...")
        return self.fe.process_data("test")
