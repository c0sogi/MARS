import os
import torch


class Config:
    """
    Configuration class for Domain-Adapted RoBERTa-Large Ensemble.
    Stores hyperparameters, file paths, and training settings.
    """

    # ==========================================
    # General Settings
    # ==========================================
    project_name = "insult-detection-roberta-dapt"
    debug = False  # Set to True for quick debugging on small subsets
    num_workers = 4
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # ==========================================
    # File Paths
    # ==========================================
    # Input Metadata (Generated by previous steps)
    input_dir = "./metadata"
    train_path = os.path.join(input_dir, "train.csv")
    val_path = os.path.join(input_dir, "val.csv")
    test_path = os.path.join(input_dir, "test.csv")

    # Output Directories
    working_dir = "./working/idea_5"
    submission_dir = "./submission"
    submission_path = os.path.join(submission_dir, "submission.csv")

    # Ensure directories exist
    os.makedirs(working_dir, exist_ok=True)
    os.makedirs(submission_dir, exist_ok=True)

    # ==========================================
    # Model Architecture
    # ==========================================
    model_name = "roberta-large"
    tokenizer_name = "roberta-large"

    # Sequence Length: 160 to capture longer rant-style comments
    max_length = 160

    # Dropout: 0.2 for stronger regularization
    dropout = 0.2

    # Output classes (Binary classification)
    num_classes = 1

    # ==========================================
    # Regularization & Freezing
    # ==========================================
    # Freeze embeddings and bottom N layers to preserve general linguistic features
    freeze_embeddings = True
    freeze_encoder_layers = 6

    # ==========================================
    # Stage 1: Domain-Adaptive Pre-training (DAPT)
    # ==========================================
    # Masked Language Modeling on Train + Val + Test
    dapt_epochs = 3
    dapt_batch_size = 8  # Smaller batch size for MLM due to memory intensity
    dapt_learning_rate = 5e-5
    mlm_probability = 0.15
    dapt_model_output_dir = os.path.join(working_dir, "dapt_roberta_large")

    # ==========================================
    # Stage 2: Supervised Fine-Tuning (SFT)
    # ==========================================
    # Training on concatenated Train + Val
    sft_epochs = 4
    train_batch_size = 16
    valid_batch_size = 32

    # Learning Rate: Conservative for Large model
    learning_rate = 1.5e-5

    # Optimizer & Scheduler
    weight_decay = 0.01
    warmup_ratio = 0.1
    max_grad_norm = 1.0
    gradient_accumulation_steps = 1

    # ==========================================
    # Ensemble Strategy
    # ==========================================
    # Seed Averaging: Train 3 independent models on full data
    seeds = [42, 123, 2024]

    # ==========================================
    # Caching
    # ==========================================
    # Directory to store cached processed datasets (parquet/npy)
    cache_dir = working_dir
