import os
import torch


class Config:
    # -------------------------------------------------------------------------
    # Directories and Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory for caching processed data and model checkpoints for Idea 8
    WORKING_DIR = "./working/idea_8"
    SUBMISSION_DIR = "./submission"

    # Input Files
    TRAIN_JSON = os.path.join(INPUT_DIR, "train.json")
    TEST_JSON = os.path.join(INPUT_DIR, "test.json")

    # Metadata Files (Generated by previous steps)
    TRAIN_META = os.path.join(METADATA_DIR, "train.csv")
    VAL_META = os.path.join(METADATA_DIR, "val.csv")
    TEST_META = os.path.join(METADATA_DIR, "test.csv")

    # Output Files
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Hyperparameters
    # -------------------------------------------------------------------------
    IMG_HEIGHT = 75
    IMG_WIDTH = 75
    # Input channels: HH, HV, and (HH+HV)/2
    IN_CHANNELS = 3

    # Imputation value for missing incidence angles (approximate median from analysis)
    INC_ANGLE_IMPUTE_VAL = 39.23

    # -------------------------------------------------------------------------
    # Model Architecture Hyperparameters (AC-ResNet)
    # -------------------------------------------------------------------------
    # Channel dimensions for the residual stages: 64 -> 64 -> 128
    CHANNEL_WIDTHS = [64, 64, 128]

    # Dense layer dimension after Global Max Pooling
    FC_DIM = 512

    # Dropout rate applied after activation in the classification head
    DROPOUT_RATE = 0.5

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    SEED = 42
    N_FOLDS = 5

    # Batch size (suitable for 1600 samples and generalization)
    BATCH_SIZE = 32

    # Optimization
    LEARNING_RATE = 1e-3
    # L2 Regularization (Weight Decay) to prevent overfitting
    WEIGHT_DECAY = 1e-4

    # Training Loop
    NUM_EPOCHS = 100
    # Early stopping patience
    PATIENCE = 15

    # Debugging / Development
    # Set to a small integer (e.g., 100) to limit dataset size for quick testing
    # Set to None for full training
    MAX_SAMPLES = None

    # -------------------------------------------------------------------------
    # Compute
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 2

    @classmethod
    def setup(cls):
        """
        Ensures that necessary working and submission directories exist.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Create fold-specific directories within working dir
        for fold in range(cls.N_FOLDS):
            os.makedirs(os.path.join(cls.WORKING_DIR, f"fold_{fold}"), exist_ok=True)


# Initialize directories on import
Config.setup()
