import os
import random
import numpy as np
import torch


class Config:
    # -------------------------------------------------------------------------
    # General Configuration
    # -------------------------------------------------------------------------
    SEED = 42
    DEBUG = False  # Set to True to use a subset of data for debugging
    DEBUG_SAMPLES = 100  # Number of samples to use in debug mode

    # -------------------------------------------------------------------------
    # Data Configuration
    # -------------------------------------------------------------------------
    # Input Dimensions
    IMG_HEIGHT = 75
    IMG_WIDTH = 75
    # Channels: 3 (Band 1 HH, Band 2 HV, Band 3 Avg)
    IN_CHANNELS = 3

    # Dataset Paths
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Raw Data
    TRAIN_JSON = os.path.join(INPUT_DIR, "train.json")
    TEST_JSON = os.path.join(INPUT_DIR, "test.json")

    # Metadata (Generated by the provided script)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test.csv")

    # -------------------------------------------------------------------------
    # Working Directory & Caching
    # -------------------------------------------------------------------------
    # All intermediate files and model checkpoints go here
    WORK_DIR = "./working/idea_3"

    # Cached Numpy Arrays (for deterministic data processing)
    # We define specific paths to ensure consistency across modules
    CACHE_X_TRAIN = os.path.join(WORK_DIR, "X_train_v3.npy")
    CACHE_Y_TRAIN = os.path.join(WORK_DIR, "y_train_v3.npy")
    CACHE_ANGLE_TRAIN = os.path.join(WORK_DIR, "angle_train_v3.npy")

    CACHE_X_TEST = os.path.join(WORK_DIR, "X_test_v3.npy")
    CACHE_ANGLE_TEST = os.path.join(WORK_DIR, "angle_test_v3.npy")
    CACHE_TEST_IDS = os.path.join(WORK_DIR, "test_ids_v3.npy")

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    NUM_FOLDS = 5
    NUM_EPOCHS = 30
    BATCH_SIZE = 32
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-4
    PATIENCE = 8  # Early stopping patience

    # Model Architecture Specifics
    FC_DIM = 512
    DROP_RATE = 0.2

    # -------------------------------------------------------------------------
    # Submission
    # -------------------------------------------------------------------------
    SUBMISSION_DIR = "./submission"
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Hardware
    # -------------------------------------------------------------------------
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4

    @classmethod
    def setup(cls):
        """
        Sets up the environment:
        1. Creates necessary working and submission directories.
        2. Sets random seeds for reproducibility.
        """
        # Create directories
        os.makedirs(cls.WORK_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)

        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.cuda.manual_seed_all(cls.SEED)
            # Ensure deterministic behavior
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
