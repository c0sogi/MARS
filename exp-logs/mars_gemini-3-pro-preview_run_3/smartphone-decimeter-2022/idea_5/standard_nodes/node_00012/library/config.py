import os


class Config:
    """
    Centralized configuration for the GNSS positioning correction pipeline.
    """

    # -------------------------------------------------------------------------
    # Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    TRAIN_DIR = os.path.join(INPUT_DIR, "train")
    TEST_DIR = os.path.join(INPUT_DIR, "test")
    METADATA_DIR = "./metadata"

    # Working directory for caching intermediate files and models
    WORKING_DIR = "./working/idea_5"
    SUBMISSION_DIR = "./submission"

    # Ensure working directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    # Metadata files generated by the analysis script
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Sample submission
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Cached Feature Paths (Parquet format)
    TRAIN_FEATURES_PATH = os.path.join(WORKING_DIR, "train_features.parquet")
    VAL_FEATURES_PATH = os.path.join(WORKING_DIR, "val_features.parquet")
    TEST_FEATURES_PATH = os.path.join(WORKING_DIR, "test_features.parquet")

    # Model Checkpoint Path
    MODEL_PATH = os.path.join(
        WORKING_DIR, "lgbm_model.txt"
    )  # LightGBM saves to text or binary

    # -------------------------------------------------------------------------
    # Global Settings
    # -------------------------------------------------------------------------
    SEED = 42

    # -------------------------------------------------------------------------
    # WGS84 Ellipsoid Constants (for ECEF <-> Geodetic conversions)
    # -------------------------------------------------------------------------
    WGS84_A = 6378137.0  # Semi-major axis (meters)
    WGS84_F_INV = 298.257223563  # Inverse flattening
    WGS84_F = 1.0 / WGS84_F_INV  # Flattening
    WGS84_B = WGS84_A * (1 - WGS84_F)  # Semi-minor axis (meters)
    WGS84_E2 = 1 - (WGS84_B**2 / WGS84_A**2)  # First eccentricity squared

    # -------------------------------------------------------------------------
    # Model Hyperparameters (LightGBM)
    # -------------------------------------------------------------------------
    LGBM_PARAMS = {
        "objective": "mae",  # Mean Absolute Error (L1 loss)
        "boosting_type": "gbdt",
        "n_estimators": 2000,
        "learning_rate": 0.05,
        "num_leaves": 128,
        "max_depth": -1,
        "min_child_samples": 20,
        "colsample_bytree": 0.8,  # Feature subsampling
        "subsample": 0.8,  # Row subsampling
        "subsample_freq": 1,
        "reg_alpha": 0.1,  # L1 regularization
        "reg_lambda": 0.1,  # L2 regularization
        "random_state": SEED,
        "n_jobs": -1,
        "verbose": -1,
    }

    # Training control
    EARLY_STOPPING_ROUNDS = 100
    VERBOSE_EVAL = 100

    # -------------------------------------------------------------------------
    # Feature Definitions
    # -------------------------------------------------------------------------
    # Features to be generated by the feature engineering pipeline
    FEATURES = [
        # Signal Quality Statistics
        "Cn0DbHz_mean",
        "Cn0DbHz_max",
        "Cn0DbHz_std",
        # Frequency specific features (L5 is cleaner)
        "Cn0DbHz_L1_mean",
        "Cn0DbHz_L5_mean",
        # Satellite Geometry
        "sv_count",
        "SvElevationDegrees_mean",
        # IMU Dynamics (Proxy for movement/static state)
        "accel_mag_mean",
        "accel_mag_std",
    ]

    # -------------------------------------------------------------------------
    # Target Definitions
    # -------------------------------------------------------------------------
    # Targets are residuals in the East-North-Up (ENU) frame (meters)
    # We predict East and North errors. Up is usually ignored for 2D location.
    TARGET_EAST = "delta_east"
    TARGET_NORTH = "delta_north"
    TARGETS = [TARGET_EAST, TARGET_NORTH]
