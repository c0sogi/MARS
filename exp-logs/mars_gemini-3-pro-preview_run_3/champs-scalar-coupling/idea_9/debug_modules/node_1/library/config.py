import os
import torch


class Config:
    # ==========================================
    # General Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 5000  # Number of molecules to use in debug mode

    # ==========================================
    # Directories
    # ==========================================
    INPUT_DIR = "./input"
    META_DIR = "./metadata"
    WORK_DIR = "./working/idea_9"
    SUBMISSION_DIR = "./submission"

    # Ensure working and submission directories exist
    os.makedirs(WORK_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================================
    # Raw Data Paths
    # ==========================================
    # Metadata files (generated by previous steps)
    TRAIN_META_PATH = os.path.join(META_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(META_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(META_DIR, "test_metadata.csv")

    # Raw input files
    STRUCTURES_PATH = os.path.join(INPUT_DIR, "structures.csv")
    DIPOLE_MOMENTS_PATH = os.path.join(INPUT_DIR, "dipole_moments.csv")
    MAGNETIC_SHIELDING_PATH = os.path.join(INPUT_DIR, "magnetic_shielding_tensors.csv")
    MULLIKEN_CHARGES_PATH = os.path.join(INPUT_DIR, "mulliken_charges.csv")
    POTENTIAL_ENERGY_PATH = os.path.join(INPUT_DIR, "potential_energy.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # ==========================================
    # Processed Data / Cache Paths
    # ==========================================
    # Directory for flattened numpy arrays
    PROCESSED_DATA_DIR = os.path.join(WORK_DIR, "processed_data")
    os.makedirs(PROCESSED_DATA_DIR, exist_ok=True)

    # Paths for specific cached artifacts
    # We use dictionary-based paths for flexibility
    CACHE_PATHS = {
        "train": os.path.join(PROCESSED_DATA_DIR, "train_data"),
        "val": os.path.join(PROCESSED_DATA_DIR, "val_data"),
        "test": os.path.join(PROCESSED_DATA_DIR, "test_data"),
        "stats": os.path.join(PROCESSED_DATA_DIR, "stats.npy"),
        "node_map": os.path.join(PROCESSED_DATA_DIR, "node_map.pkl"),
    }

    # ==========================================
    # Model Hyperparameters
    # ==========================================
    # Architecture dimensions
    HIDDEN_DIM = 256
    NUM_INTERACTIONS = 4  # Depth of the Directional Message Passing

    # Geometric features
    CUTOFF = 5.0  # Radius in Angstroms for graph construction
    NUM_RBF = 64  # Number of RBF kernels for distance expansion
    NUM_ANGLE_RBF = 32  # Number of RBF kernels for angular expansion (cos theta)

    # Readout
    NUM_HEADS = 8  # One head per coupling type

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    BATCH_SIZE = 96  # Number of molecules per batch
    LEARNING_RATE = 5e-4
    WEIGHT_DECAY = 1e-6
    MAX_EPOCHS = 40

    # Scheduler
    SCHEDULER_PATIENCE = 3
    SCHEDULER_FACTOR = 0.5
    MIN_LR = 1e-6

    # Loss weights
    # Total Loss = L_coupling + AUX_WEIGHT * (L_shielding + L_charge)
    AUX_LOSS_WEIGHT = 0.1

    # ==========================================
    # Hardware & Performance
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Data loader workers
    PIN_MEMORY = True

    # ==========================================
    # Domain Constants
    # ==========================================
    # Coupling types ordered alphabetically or by dataset convention
    COUPLING_TYPES = ["1JHC", "1JHN", "2JHC", "2JHH", "2JHN", "3JHC", "3JHH", "3JHN"]

    # Atom types mapping
    ATOM_MAP = {"H": 0, "C": 1, "N": 2, "O": 3, "F": 4}
    NUM_ATOM_TYPES = 5

    @staticmethod
    def print_config():
        """Prints the current configuration."""
        print("=" * 30)
        print("CONFIG")
        print("=" * 30)
        for key, val in Config.__dict__.items():
            if not key.startswith("__") and not callable(val):
                print(f"{key}: {val}")
        print("=" * 30)
