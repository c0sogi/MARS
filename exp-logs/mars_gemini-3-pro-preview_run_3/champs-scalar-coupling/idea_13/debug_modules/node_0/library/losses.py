import torch
import torch.nn as nn
import numpy as np
import os
from library.config import Config


class LossComputer(nn.Module):
    """
    Computes the training objective and validation metrics for the Scalar Coupling task.

    Handles:
    1. Standardization of primary targets (Coupling Constant) using pre-computed statistics.
    2. Computation of L1 Loss for the primary task.
    3. Computation of L1 Loss for auxiliary tasks (Charge, Shielding).
    4. Weighted combination of losses.
    5. Calculation of the competition metric (Log Mean Absolute Error).
    """

    def __init__(self):
        super().__init__()
        self.config = Config
        self.l1_loss = nn.L1Loss()

        # Load pre-computed statistics for target standardization
        # These are generated by DataProcessor and saved to stats.npy
        stats_path = self.config.STATS_FILE

        if os.path.exists(stats_path):
            stats = np.load(stats_path, allow_pickle=True).item()
        else:
            # Fallback defaults (Mean=0, Std=1) if stats file is missing
            # This allows instantiation before data processing is complete
            print(
                f"Warning: Stats file not found at {stats_path}. Using default normalization."
            )
            stats = {
                i: {"mean": 0.0, "std": 1.0}
                for i in range(self.config.NUM_COUPLING_TYPES)
            }

        # Create lookup tensors for efficient GPU usage
        # We use register_buffer so these move to device with the module
        num_types = self.config.NUM_COUPLING_TYPES
        means = torch.zeros(num_types, dtype=torch.float32)
        stds = torch.ones(num_types, dtype=torch.float32)

        for t_idx, s in stats.items():
            idx = int(t_idx)
            if idx < num_types:
                means[idx] = s["mean"]
                stds[idx] = s["std"]

        self.register_buffer("means", means)
        self.register_buffer("stds", stds)

    def standardize(self, values, types):
        """
        Standardizes values: z = (y - mu) / sigma
        """
        batch_means = self.means[types]
        batch_stds = self.stds[types]
        return (values - batch_means) / batch_stds

    def unstandardize(self, values, types):
        """
        Restores values: y = z * sigma + mu
        """
        batch_means = self.means[types]
        batch_stds = self.stds[types]
        return values * batch_stds + batch_means

    def standardized_l1_loss(self, pred, target, types):
        """
        Computes L1 loss between predictions and standardized targets.
        """
        target_std = self.standardize(target, types)
        return self.l1_loss(pred, target_std)

    def auxiliary_loss(
        self, pred_charge, target_charge, pred_shielding, target_shielding
    ):
        """
        Computes L1 losses for auxiliary tasks.
        """
        loss_charge = self.l1_loss(pred_charge, target_charge)
        loss_shielding = self.l1_loss(pred_shielding, target_shielding)
        return loss_charge, loss_shielding

    def forward(self, predictions, batch):
        """
        Computes the total weighted loss.

        Args:
            predictions (dict): Output from DMPNN ('coupling', 'charge', 'shielding').
            batch (dict): Batch data from SoACollator.

        Returns:
            tuple: (total_loss, dict_of_components)
        """
        # 1. Primary Task: Scalar Coupling
        pred_coupling = predictions["coupling"]
        target_coupling = batch["coupling_value"]
        coupling_type = batch["coupling_type"]

        loss_coupling = self.standardized_l1_loss(
            pred_coupling, target_coupling, coupling_type
        )

        # 2. Auxiliary Tasks
        pred_charge = predictions["charge"]
        target_charge = batch["aux_charge"]

        pred_shielding = predictions["shielding"]
        target_shielding = batch["aux_shielding"]

        loss_charge, loss_shielding = self.auxiliary_loss(
            pred_charge, target_charge, pred_shielding, target_shielding
        )

        # 3. Weighted Sum
        # L_total = L_coupling + lambda * (L_charge + L_shielding)
        total_loss = loss_coupling + self.config.LAMBDA_AUX * (
            loss_charge + loss_shielding
        )

        return total_loss, {
            "loss_coupling": loss_coupling.item(),
            "loss_charge": loss_charge.item(),
            "loss_shielding": loss_shielding.item(),
        }

    def compute_metric(self, predictions, batch):
        """
        Computes the competition metric: Log of the Mean Absolute Error,
        calculated for each scalar coupling type, and then averaged across types.
        """
        pred_coupling = predictions["coupling"]
        target_coupling = batch["coupling_value"]
        coupling_type = batch["coupling_type"]

        # Unstandardize predictions to physical scale (raw values)
        pred_coupling_phys = self.unstandardize(pred_coupling, coupling_type)

        # Absolute Error
        abs_err = torch.abs(pred_coupling_phys - target_coupling)

        # Group by type and compute log(MAE)
        log_maes = []

        # Iterate through all possible types
        for t_idx in range(self.config.NUM_COUPLING_TYPES):
            mask = coupling_type == t_idx
            if mask.sum() > 0:
                mae = abs_err[mask].mean()
                # Metric is log(MAE). Add epsilon for numerical stability.
                log_mae = torch.log(mae + 1e-9)
                log_maes.append(log_mae)

        if len(log_maes) == 0:
            return 0.0

        # Average across types
        final_metric = torch.stack(log_maes).mean()
        return final_metric.item()
