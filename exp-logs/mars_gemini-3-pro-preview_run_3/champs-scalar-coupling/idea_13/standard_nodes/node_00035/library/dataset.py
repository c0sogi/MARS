import os
import torch
import numpy as np
from torch.utils.data import Dataset
from library.config import Config


class SoADataset(Dataset):
    """
    Structure-of-Arrays (SoA) Dataset.

    This dataset manages the loading and indexing of flattened, monolithic numpy arrays
    generated by the DataProcessor. It avoids object overhead by storing data in
    continuous memory blocks and slicing them on-the-fly during collation.

    It handles:
    1. Loading global structural data (Nodes, Edges, Triplets).
    2. Loading split-specific coupling data (Targets).
    3. Mapping molecule IDs to their respective slices in the arrays.
    """

    def __init__(self, split="train", load_cached_data=True):
        """
        Args:
            split (str): 'train', 'val', or 'test'.
            load_cached_data (bool): If True, expects data to exist in PROCESSED_DIR.
                                     (Note: This module assumes DataProcessor has run).
        """
        self.split = split
        self.config = Config

        # Ensure processed directory exists
        if not os.path.exists(self.config.PROCESSED_DIR):
            raise FileNotFoundError(
                f"Processed data directory not found: {self.config.PROCESSED_DIR}"
            )

        # ==========================================
        # 1. Load Global Structural Data
        # ==========================================
        # The DataProcessor saves nodes/edges/triplets with the 'train' prefix
        # as a master copy for all molecules.
        print(f"[{split.upper()}] Loading global structural data...")
        try:
            # We use mmap_mode='r' to avoid loading 10GB+ into RAM immediately.
            # The OS handles paging efficiently.
            self.pos = np.load(
                self.config.get_processed_file_path("train", "pos"), mmap_mode="r"
            )
            self.node_type = np.load(
                self.config.get_processed_file_path("train", "node_type"), mmap_mode="r"
            )
            self.mol_id = np.load(
                self.config.get_processed_file_path("train", "mol_id"), mmap_mode="r"
            )

            self.edge_index = np.load(
                self.config.get_processed_file_path("train", "edge_index"),
                mmap_mode="r",
            )
            self.edge_vec = np.load(
                self.config.get_processed_file_path("train", "edge_vec"), mmap_mode="r"
            )
            self.edge_dist = np.load(
                self.config.get_processed_file_path("train", "edge_dist"), mmap_mode="r"
            )

            self.triplet_index = np.load(
                self.config.get_processed_file_path("train", "triplet_index"),
                mmap_mode="r",
            )

            self.aux_charge = np.load(
                self.config.get_processed_file_path("train", "aux_charge"),
                mmap_mode="r",
            )
            self.aux_shielding = np.load(
                self.config.get_processed_file_path("train", "aux_shielding"),
                mmap_mode="r",
            )
        except FileNotFoundError:
            raise RuntimeError(
                f"Processed data files missing in {self.config.PROCESSED_DIR}. Please run DataProcessor."
            )

        # ==========================================
        # 2. Load Split-Specific Coupling Data
        # ==========================================
        print(f"[{split.upper()}] Loading coupling targets...")
        self.coupling_atom_index = np.load(
            self.config.get_processed_file_path(split, "coupling_atom_index"),
            mmap_mode="r",
        )
        self.coupling_type = np.load(
            self.config.get_processed_file_path(split, "coupling_type"), mmap_mode="r"
        )
        self.coupling_id = np.load(
            self.config.get_processed_file_path(split, "coupling_id"), mmap_mode="r"
        )
        self.coupling_value = np.load(
            self.config.get_processed_file_path(split, "coupling_value"), mmap_mode="r"
        )

        # ==========================================
        # 3. Build Indexing Maps (Ranges per Molecule)
        # ==========================================
        # We need to know which slice of the arrays belongs to which molecule.
        print(f"[{split.upper()}] Building index maps...")

        # A. Identify molecules in this split
        # We look at the coupling data to see which molecules are included.
        # coupling_atom_index refers to global node indices.
        # We use the first atom of the pair to look up the molecule ID.
        coupling_nodes = self.coupling_atom_index[0]
        coupling_mol_ids = self.mol_id[coupling_nodes]

        # The unique molecules we will iterate over
        self.unique_mol_ids = np.unique(coupling_mol_ids)

        # B. Sort Coupling Data by Molecule
        # To allow efficient slicing, the coupling data must be grouped by molecule.
        # The raw metadata might be shuffled, so we enforce sorting here.
        print(f"[{split.upper()}] Sorting coupling data by molecule...")
        sort_idx = np.argsort(coupling_mol_ids)

        # Apply sort to split-specific arrays (loading into memory if not already)
        self.coupling_atom_index = np.array(self.coupling_atom_index[:, sort_idx])
        self.coupling_type = np.array(self.coupling_type[sort_idx])
        self.coupling_id = np.array(self.coupling_id[sort_idx])
        self.coupling_value = np.array(self.coupling_value[sort_idx])

        # Update the owner array to match sorted data
        sorted_coupling_owners = coupling_mol_ids[sort_idx]

        # C. Compute Ranges (Start, Count) for all arrays
        # We use bincount/cumsum to find the slice [start, start+count] for each molecule ID.
        # Note: We compute this for ALL molecules in the global set to allow direct indexing by mol_id.

        max_mol_id = self.mol_id[-1]  # Assuming sorted mol_id in global nodes

        # --- Node Ranges ---
        # Global nodes are sorted by mol_id
        mol_counts = np.bincount(self.mol_id, minlength=max_mol_id + 1)
        mol_starts = np.zeros_like(mol_counts)
        mol_starts[1:] = np.cumsum(mol_counts)[:-1]
        self.node_ranges = np.column_stack((mol_starts, mol_counts))

        # --- Edge Ranges ---
        # Edges are typically sorted by molecule because they are generated from sorted nodes.
        # We verify ownership using the source node.
        edge_owners = self.mol_id[self.edge_index[0]]
        edge_counts = np.bincount(edge_owners, minlength=max_mol_id + 1)
        edge_starts = np.zeros_like(edge_counts)
        edge_starts[1:] = np.cumsum(edge_counts)[:-1]
        self.edge_ranges = np.column_stack((edge_starts, edge_counts))

        # --- Triplet Ranges ---
        # Triplets index edges. triplet_index[0] is the incoming edge index.
        # We map edge index -> molecule ID to find triplet ownership.
        triplet_edge_idx = self.triplet_index[0]
        triplet_owners = edge_owners[triplet_edge_idx]
        triplet_counts = np.bincount(triplet_owners, minlength=max_mol_id + 1)
        triplet_starts = np.zeros_like(triplet_counts)
        triplet_starts[1:] = np.cumsum(triplet_counts)[:-1]
        self.triplet_ranges = np.column_stack((triplet_starts, triplet_counts))

        # --- Coupling Ranges ---
        # Computed from the sorted coupling data
        c_counts = np.bincount(sorted_coupling_owners, minlength=max_mol_id + 1)
        c_starts = np.zeros_like(c_counts)
        c_starts[1:] = np.cumsum(c_counts)[:-1]
        self.coupling_ranges = np.column_stack((c_starts, c_counts))

        print(f"[{split.upper()}] Dataset ready. {len(self.unique_mol_ids)} molecules.")

    def __len__(self):
        return len(self.unique_mol_ids)

    def __getitem__(self, idx):
        # We return the molecule ID. The Collator will handle the heavy lifting (slicing).
        return self.unique_mol_ids[idx]


class SoACollator:
    """
    Collator for Structure-of-Arrays.

    Receives a list of molecule IDs, slices the monolithic arrays, and
    re-indexes the connectivity (edges, triplets) to form a valid batch.
    """

    def __init__(self, dataset):
        self.dataset = dataset
        # Cache references for speed
        self.pos = dataset.pos
        self.node_type = dataset.node_type
        self.edge_index = dataset.edge_index
        self.edge_vec = dataset.edge_vec
        self.edge_dist = dataset.edge_dist
        self.triplet_index = dataset.triplet_index
        self.aux_charge = dataset.aux_charge
        self.aux_shielding = dataset.aux_shielding

        self.coupling_atom_index = dataset.coupling_atom_index
        self.coupling_type = dataset.coupling_type
        self.coupling_value = dataset.coupling_value
        self.coupling_id = dataset.coupling_id

        self.node_ranges = dataset.node_ranges
        self.edge_ranges = dataset.edge_ranges
        self.triplet_ranges = dataset.triplet_ranges
        self.coupling_ranges = dataset.coupling_ranges

    def __call__(self, mol_ids):
        """
        Args:
            mol_ids (list[int]): List of global molecule IDs.
        Returns:
            dict: Batched tensors.
        """
        mol_ids_np = np.array(mol_ids)

        # 1. Retrieve Ranges for Batch
        n_ranges = self.node_ranges[mol_ids_np]
        e_ranges = self.edge_ranges[mol_ids_np]
        t_ranges = self.triplet_ranges[mol_ids_np]
        c_ranges = self.coupling_ranges[mol_ids_np]

        # 2. Calculate Total Sizes
        num_nodes = np.sum(n_ranges[:, 1])
        num_edges = np.sum(e_ranges[:, 1])
        num_triplets = np.sum(t_ranges[:, 1])
        num_couplings = np.sum(c_ranges[:, 1])

        # 3. Allocate Output Tensors
        batch = {
            "pos": torch.empty((num_nodes, 3), dtype=torch.float32),
            "node_type": torch.empty((num_nodes,), dtype=torch.long),
            "batch": torch.empty((num_nodes,), dtype=torch.long),
            "edge_index": torch.empty((2, num_edges), dtype=torch.long),
            "edge_vec": torch.empty((num_edges, 3), dtype=torch.float32),
            "edge_dist": torch.empty((num_edges,), dtype=torch.float32),
            "triplet_index": torch.empty((3, num_triplets), dtype=torch.long),
            "aux_charge": torch.empty((num_nodes,), dtype=torch.float32),
            "aux_shielding": torch.empty((num_nodes, 9), dtype=torch.float32),
            "coupling_atom_index": torch.empty((2, num_couplings), dtype=torch.long),
            "coupling_type": torch.empty((num_couplings,), dtype=torch.long),
            "coupling_value": torch.empty((num_couplings,), dtype=torch.float32),
            "coupling_id": torch.empty((num_couplings,), dtype=torch.long),
            "coupling_batch": torch.empty((num_couplings,), dtype=torch.long),
            "num_graphs": len(mol_ids),
        }

        # 4. Fill and Re-index
        # We track current offsets in the output tensors
        curr = {"node": 0, "edge": 0, "triplet": 0, "coupling": 0}

        for i, mol_id in enumerate(mol_ids):
            # --- Nodes ---
            ns, nc = n_ranges[i]
            batch["pos"][curr["node"] : curr["node"] + nc] = torch.from_numpy(
                self.pos[ns : ns + nc].copy()
            )
            batch["node_type"][curr["node"] : curr["node"] + nc] = torch.from_numpy(
                self.node_type[ns : ns + nc].copy()
            )
            batch["aux_charge"][curr["node"] : curr["node"] + nc] = torch.from_numpy(
                self.aux_charge[ns : ns + nc].copy()
            )
            batch["aux_shielding"][curr["node"] : curr["node"] + nc] = torch.from_numpy(
                self.aux_shielding[ns : ns + nc].copy()
            )
            batch["batch"][curr["node"] : curr["node"] + nc] = i

            # --- Edges ---
            es, ec = e_ranges[i]
            if ec > 0:
                # Slice
                e_idx = torch.from_numpy(
                    self.edge_index[:, es : es + ec].astype(np.int64)
                )
                # Re-index: Convert global node index to batch node index
                # new_idx = old_idx - start_node_global + start_node_batch
                e_idx = e_idx - ns + curr["node"]

                batch["edge_index"][:, curr["edge"] : curr["edge"] + ec] = e_idx
                batch["edge_vec"][curr["edge"] : curr["edge"] + ec] = torch.from_numpy(
                    self.edge_vec[es : es + ec].copy()
                )
                batch["edge_dist"][curr["edge"] : curr["edge"] + ec] = torch.from_numpy(
                    self.edge_dist[es : es + ec].copy()
                )

            # --- Triplets ---
            ts, tc = t_ranges[i]
            if tc > 0:
                t_idx = torch.from_numpy(
                    self.triplet_index[:, ts : ts + tc].astype(np.int64)
                )
                # Re-index Edges: new_edge_idx = old_edge_idx - start_edge_global + start_edge_batch
                t_idx[0] = t_idx[0] - es + curr["edge"]
                t_idx[1] = t_idx[1] - es + curr["edge"]
                # Re-index Center Node: new_node_idx = old_node_idx - start_node_global + start_node_batch
                t_idx[2] = t_idx[2] - ns + curr["node"]

                batch["triplet_index"][
                    :, curr["triplet"] : curr["triplet"] + tc
                ] = t_idx

            # --- Couplings ---
            cs, cc = c_ranges[i]
            if cc > 0:
                c_atom = torch.from_numpy(
                    self.coupling_atom_index[:, cs : cs + cc].astype(np.int64)
                )
                # Re-index Nodes
                c_atom = c_atom - ns + curr["node"]

                batch["coupling_atom_index"][
                    :, curr["coupling"] : curr["coupling"] + cc
                ] = c_atom
                batch["coupling_type"][curr["coupling"] : curr["coupling"] + cc] = (
                    torch.from_numpy(self.coupling_type[cs : cs + cc].copy())
                )
                batch["coupling_value"][curr["coupling"] : curr["coupling"] + cc] = (
                    torch.from_numpy(self.coupling_value[cs : cs + cc].copy())
                )
                batch["coupling_id"][curr["coupling"] : curr["coupling"] + cc] = (
                    torch.from_numpy(self.coupling_id[cs : cs + cc].copy())
                )
                batch["coupling_batch"][curr["coupling"] : curr["coupling"] + cc] = i

            # Update cursors
            curr["node"] += nc
            curr["edge"] += ec
            curr["triplet"] += tc
            curr["coupling"] += cc

        return batch
