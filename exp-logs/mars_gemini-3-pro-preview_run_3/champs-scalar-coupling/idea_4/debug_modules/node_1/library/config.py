import os
import torch


class Config:
    """
    Configuration class for the Scalar Coupling Prediction Task.
    Defines file paths, model hyperparameters, training settings, and data processing constants.
    """

    # --------------------------------------------------------------------------
    # General Configuration
    # --------------------------------------------------------------------------
    SEED = 42
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    # Number of workers for DataLoader.
    # vCPUs = 12, so 4-6 is usually a good balance to avoid overhead.
    NUM_WORKERS = 4

    # --------------------------------------------------------------------------
    # File Paths
    # --------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_4"
    SUBMISSION_DIR = "./submission"

    # Ensure working and submission directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # Raw Data Files
    STRUCTURES_CSV = os.path.join(INPUT_DIR, "structures.csv")
    DIPOLE_MOMENTS_CSV = os.path.join(INPUT_DIR, "dipole_moments.csv")
    MAGNETIC_SHIELDING_CSV = os.path.join(INPUT_DIR, "magnetic_shielding_tensors.csv")
    MULLIKEN_CHARGES_CSV = os.path.join(INPUT_DIR, "mulliken_charges.csv")
    POTENTIAL_ENERGY_CSV = os.path.join(INPUT_DIR, "potential_energy.csv")
    SAMPLE_SUBMISSION_CSV = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Splits (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Cache Directory (for processed graphs)
    CACHE_DIR = WORKING_DIR

    # --------------------------------------------------------------------------
    # Data Processing & Graph Construction
    # --------------------------------------------------------------------------
    # Radius cutoff for constructing the Atom Graph (edges between atoms)
    RADIUS_CUTOFF = 5.0  # Angstroms

    # Maximum number of neighbors per atom to consider (for computational efficiency)
    MAX_NEIGHBORS = 32

    # Debugging / Development
    # If True, runs on a small subset of the data
    DEBUG = False
    DEBUG_SAMPLE_SIZE = 2000  # Number of molecules to use in debug mode

    # --------------------------------------------------------------------------
    # Model Architecture: Dual-Graph Interaction Network
    # --------------------------------------------------------------------------
    # Dimension of node and edge embeddings
    HIDDEN_DIM = 128

    # Number of interaction blocks (Line Graph Conv <-> Atom Graph Conv)
    NUM_INTERACTION_LAYERS = 4

    # Radial Basis Function (RBF) Parameters for feature lifting
    NUM_RBF_DISTANCE = 64  # Number of basis functions for distance (Atom Graph edges)
    RBF_DISTANCE_MIN = 0.0
    RBF_DISTANCE_MAX = 5.0  # Should match RADIUS_CUTOFF

    NUM_RBF_ANGLE = 32  # Number of basis functions for bond angles (Line Graph edges)
    # Angles are represented as cos(theta) in [-1, 1]

    # Dropout rate for regularization
    DROPOUT = 0.1

    # Coupling Types (Targets)
    # The model will have specific heads for each coupling type
    COUPLING_TYPES = ["1JHC", "1JHN", "2JHC", "2JHH", "2JHN", "3JHC", "3JHH", "3JHN"]
    NUM_COUPLING_TYPES = len(COUPLING_TYPES)

    # --------------------------------------------------------------------------
    # Training Hyperparameters
    # --------------------------------------------------------------------------
    # Batch size (Adjust based on GPU VRAM, A100 40GB allows larger batches)
    BATCH_SIZE = 96

    # Optimization
    LEARNING_RATE = 5e-4
    WEIGHT_DECAY = 1e-5

    # Training Duration
    EPOCHS = 25
    EARLY_STOPPING_PATIENCE = 5

    # Scheduler: Cosine Annealing Warm Restarts
    SCHEDULER_T0 = 10
    SCHEDULER_T_MULT = 2
    SCHEDULER_ETA_MIN = 1e-6

    # Auxiliary Loss Weights (Physics-Aware Regularization)
    # Total Loss = L_coupling + lambda1 * L_shielding + lambda2 * L_charge
    LAMBDA_SHIELDING = 0.15
    LAMBDA_CHARGE = 0.10

    # Target Normalization
    # If True, targets are standardized (z-score) per coupling type
    NORMALIZE_TARGETS = True
