import torch
import torch.nn as nn
import torch.optim as optim
import numpy as np
import pandas as pd
import os
import time
from collections import defaultdict
from library.config import Config
from library.model import DualGraphGNN
from library.utils import TargetScaler, AuxScaler


class Trainer:
    """
    Handles training, validation, and inference for the DualGraphGNN model.
    """

    def __init__(self):
        self.device = Config.get_device()

        # Initialize Model
        self.model = DualGraphGNN().to(self.device)

        # Initialize Target Scaler (loads stats from cache if available)
        self.scaler = TargetScaler()
        # We assume stats are generated by the data loader initialization step,
        # but we try to load them here to be safe.
        self.scaler.fit(None, load_cached_data=True)

        # Initialize Aux Scaler
        self.aux_scaler = AuxScaler()

        # Optimizer & Scheduler
        self.optimizer = optim.AdamW(
            self.model.parameters(),
            lr=Config.LEARNING_RATE,
            weight_decay=Config.WEIGHT_DECAY,
        )

        # Cosine Annealing with Warm Restarts
        # T_0 is the number of epochs for the first restart
        self.scheduler = optim.lr_scheduler.CosineAnnealingWarmRestarts(
            self.optimizer, T_0=Config.WARMUP_EPOCHS + 5, T_mult=2, eta_min=1e-6
        )

        # Loss Functions
        self.criterion_coupling = nn.L1Loss()  # MAE for standardized targets
        self.criterion_aux = nn.MSELoss()  # MSE for physical aux targets

    def train_epoch(self, loader):
        """
        Performs one epoch of training.
        """
        self.model.train()
        total_loss = 0.0
        total_coupling_loss = 0.0
        total_aux_loss = 0.0
        num_batches = 0

        for batch in loader:
            batch = batch.to(self.device)
            self.optimizer.zero_grad()

            # 1. Forward Pass
            pred_coupling, pred_shielding, pred_charge = self.model(batch)

            # 2. Prepare Targets
            # Standardize coupling targets for training stability
            y_coupling_std = self.scaler.transform(
                batch.y_coupling, batch.type_coupling
            )

            # 3. Compute Losses
            loss_c = self.criterion_coupling(pred_coupling, y_coupling_std)

            # Auxiliary losses (Shielding + Charge)
            # Standardize targets to prevent task dominance (Cite solution_lesson_node_00009)
            y_shield_std, y_charge_std = self.aux_scaler.transform(
                batch.y_shielding, batch.y_charge
            )

            loss_s = self.criterion_aux(pred_shielding, y_shield_std)
            loss_q = self.criterion_aux(pred_charge, y_charge_std)

            loss_aux = loss_s + loss_q

            # Total Loss
            loss = loss_c + Config.LAMBDA_PHYS * loss_aux

            # 4. Backward
            loss.backward()
            self.optimizer.step()

            # 5. Logging
            total_loss += loss.item()
            total_coupling_loss += loss_c.item()
            total_aux_loss += loss_aux.item()
            num_batches += 1

        avg_loss = total_loss / num_batches
        avg_c_loss = total_coupling_loss / num_batches
        avg_aux_loss = total_aux_loss / num_batches

        return avg_loss, avg_c_loss, avg_aux_loss

    def evaluate(self, loader):
        """
        Evaluates the model on the validation set using the competition metric (LogMAE).
        """
        self.model.eval()

        # Store predictions and targets per type to calculate metric correctly
        preds_all = []
        targets_all = []
        types_all = []

        with torch.no_grad():
            for batch in loader:
                batch = batch.to(self.device)

                # Forward
                pred_coupling_std, _, _ = self.model(batch)

                # Inverse Transform to get physical values
                pred_coupling_phys = self.scaler.inverse_transform(
                    pred_coupling_std, batch.type_coupling
                )

                preds_all.append(pred_coupling_phys.cpu().numpy())
                targets_all.append(batch.y_coupling.cpu().numpy())
                types_all.append(batch.type_coupling.cpu().numpy())

        # Concatenate
        preds_all = np.concatenate(preds_all)
        targets_all = np.concatenate(targets_all)
        types_all = np.concatenate(types_all)

        # Calculate LogMAE per type
        metrics = {}
        log_maes = []

        unique_types = np.unique(types_all)

        for t_idx in unique_types:
            # Map index back to string name for logging
            t_name = Config.COUPLING_TYPES[t_idx]

            mask = types_all == t_idx
            diff = np.abs(preds_all[mask] - targets_all[mask])
            mae = np.mean(diff)
            log_mae = np.log(mae)

            metrics[t_name] = log_mae
            log_maes.append(log_mae)

        # Final Metric: Average of LogMAEs
        avg_log_mae = np.mean(log_maes)

        return avg_log_mae, metrics

    def fit(self, train_loader, val_loader):
        """
        Main training loop with Early Stopping.
        """
        print(f"Starting training on device: {self.device}")

        # Fit Aux Scaler on training data
        self.aux_scaler.fit(train_loader)

        best_val_metric = float("inf")
        patience_counter = 0

        for epoch in range(1, Config.MAX_EPOCHS + 1):
            start_time = time.time()

            # Train
            train_loss, train_c_loss, train_aux_loss = self.train_epoch(train_loader)

            # Validate
            val_metric, val_type_metrics = self.evaluate(val_loader)

            # Scheduler Step
            self.scheduler.step()

            elapsed = time.time() - start_time

            # Print Status
            print(f"Epoch {epoch}/{Config.MAX_EPOCHS} | Time: {elapsed:.1f}s")
            print(
                f"  Train Loss: {train_loss:.6f} (C: {train_c_loss:.6f}, Aux: {train_aux_loss:.6f})"
            )
            print(f"  Val LogMAE: {val_metric:.9f}")  # Full precision

            # Early Stopping Check
            if val_metric < best_val_metric:
                best_val_metric = val_metric
                patience_counter = 0
                print(f"  New best model! Saving to {Config.MODEL_SAVE_PATH}")
                torch.save(self.model.state_dict(), Config.MODEL_SAVE_PATH)
            else:
                patience_counter += 1
                print(
                    f"  No improvement. Patience: {patience_counter}/{Config.PATIENCE}"
                )

            if patience_counter >= Config.PATIENCE:
                print("Early stopping triggered.")
                break

    def predict(self, test_loader):
        """
        Generates predictions for the test set and saves submission file.
        """
        print("Starting inference on test set...")

        # Load best model
        if os.path.exists(Config.MODEL_SAVE_PATH):
            print(f"Loading best model from {Config.MODEL_SAVE_PATH}")
            self.model.load_state_dict(
                torch.load(Config.MODEL_SAVE_PATH, map_location=self.device)
            )
        else:
            print("Warning: No saved model found. Using current model state.")

        self.model.eval()

        ids_all = []
        preds_all = []

        with torch.no_grad():
            for batch in test_loader:
                batch = batch.to(self.device)

                # Forward
                pred_coupling_std, _, _ = self.model(batch)

                # Inverse Transform
                pred_coupling_phys = self.scaler.inverse_transform(
                    pred_coupling_std, batch.type_coupling
                )

                ids_all.append(batch.id.cpu().numpy())
                preds_all.append(pred_coupling_phys.cpu().numpy())

        # Concatenate
        ids = np.concatenate(ids_all)
        preds = np.concatenate(preds_all)

        # Create Submission DataFrame
        df_sub = pd.DataFrame({"id": ids, "scalar_coupling_constant": preds})

        # Sort by ID to ensure correct order (though not strictly required by format, good practice)
        df_sub.sort_values("id", inplace=True)

        # Save
        save_path = Config.SUBMISSION_PATH
        os.makedirs(os.path.dirname(save_path), exist_ok=True)
        df_sub.to_csv(save_path, index=False)
        print(f"Submission saved to {save_path}")
        print(f"Submission shape: {df_sub.shape}")
