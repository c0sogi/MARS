import os
import torch
import numpy as np
import random


class Config:
    """
    Configuration for Molecule-Parallel Deep Continuous Filter Network (MP-DCFN).
    Centralizes all file paths, model hyperparameters, and training settings.
    """

    # ==========================================
    # 1. File Paths & Directories
    # ==========================================
    # Base Directories
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working/idea_17"
    SUBMISSION_DIR = "./submission"

    # Input Files
    STRUCTURES_CSV = os.path.join(INPUT_DIR, "structures.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Metadata Files (Generated by previous steps)
    TRAIN_META_PATH = os.path.join(METADATA_DIR, "train_metadata.csv")
    VAL_META_PATH = os.path.join(METADATA_DIR, "val_metadata.csv")
    TEST_META_PATH = os.path.join(METADATA_DIR, "test_metadata.csv")

    # Output Files
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Checkpoints & Cache
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    BEST_MODEL_PATH = os.path.join(CHECKPOINT_DIR, "best_model.pth")
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")

    # Create necessary writable directories
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)
    os.makedirs(CACHE_DIR, exist_ok=True)

    # ==========================================
    # 2. Data Configuration
    # ==========================================
    # Atom types mapping (QM9 subset)
    ATOM_TYPES = ["H", "C", "N", "O", "F"]
    ATOM_TO_IDX = {atom: i for i, atom in enumerate(ATOM_TYPES)}
    NUM_ATOM_TYPES = len(ATOM_TYPES)

    # Coupling types mapping
    COUPLING_TYPES = ["1JHC", "2JHC", "3JHC", "1JHN", "2JHN", "3JHN", "2JHH", "3JHH"]
    TYPE_TO_IDX = {t: i for i, t in enumerate(COUPLING_TYPES)}
    NUM_COUPLING_TYPES = len(COUPLING_TYPES)

    # Target Normalization placeholders (populated during data loading)
    # Stores mean and std for each coupling type index to perform per-type scaling
    COUPLING_TYPE_MEAN = {}
    COUPLING_TYPE_STD = {}

    # ==========================================
    # 3. Model Architecture (MP-DCFN)
    # ==========================================
    # Node Embedding
    N_ATOM_BASIS = 128  # Dimension of atom embeddings (h_i)

    # Continuous Filter Convolution
    N_FILTERS = 128  # Dimension of continuous filters
    N_INTERACTIONS = 6  # Number of interaction blocks (Depth)

    # RBF Expansion
    N_RBF = 25  # Number of Gaussian Radial Basis Functions
    CUTOFF = (
        10.0  # Interaction cutoff in Angstroms (Large to approximate fully connected)
    )

    # Readout Head
    # Layers for the shared conditional head
    READOUT_HIDDEN_DIMS = [128, 64]

    # ==========================================
    # 4. Training Hyperparameters
    # ==========================================
    # General
    SEED = 42
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    NUM_WORKERS = 4  # Data loader workers

    # Optimization
    BATCH_SIZE = 64  # Number of MOLECULES per batch (Effective pairs is much higher)
    LEARNING_RATE = 5e-4  # Initial learning rate
    WEIGHT_DECAY = 1e-5  # Weight decay for AdamW

    # Scheduler (Cosine Annealing Warm Restarts)
    MAX_EPOCHS = 25  # Total training epochs
    SCHEDULER_T_0 = 10  # Number of epochs for the first restart
    SCHEDULER_T_MULT = 2  # Factor to increase T_i after a restart

    # Early Stopping
    PATIENCE = 5  # Epochs to wait before stopping if val loss doesn't improve

    # Debugging
    # Set to integer (e.g., 2000) to limit dataset size for fast debugging. Set to None for full run.
    DEBUG_SAMPLE_SIZE = None

    @staticmethod
    def set_seed(seed=42):
        """
        Sets the random seed for reproducibility across Python, NumPy, and PyTorch.
        """
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
            # Deterministic operations for reproducibility
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
