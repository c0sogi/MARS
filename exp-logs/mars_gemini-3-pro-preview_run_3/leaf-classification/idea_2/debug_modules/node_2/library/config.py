import os
import numpy as np


class Config:
    # ==========================================
    # Global Configuration
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SAMPLE_SIZE = 50  # Number of samples to use when DEBUG is True

    # ==========================================
    # Directory Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    WORKING_DIR = "./working"

    # Specific cache directory for this idea (Idea 2: Hybrid Deep-Linear)
    CACHE_DIR = os.path.join(WORKING_DIR, "idea_2")

    SUBMISSION_DIR = "./submission"
    IMAGES_DIR = os.path.join(INPUT_DIR, "images")

    # ==========================================
    # File Paths
    # ==========================================
    # Metadata generated by the previous step
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Sample submission for format reference
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Final output path
    SUBMISSION_FILE_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Cache File Names (for .npy storage)
    # ==========================================
    # We use .npy as requested to avoid pickle for data
    CACHE_TRAIN_IMG_FEATS = "train_img_features.npy"
    CACHE_VAL_IMG_FEATS = "val_img_features.npy"
    CACHE_TEST_IMG_FEATS = "test_img_features.npy"

    # PCA artifacts (saved as numpy arrays to avoid pickle)
    CACHE_PCA_COMPONENTS = "pca_components.npy"
    CACHE_PCA_MEAN = "pca_mean.npy"

    # ==========================================
    # Image Processing Parameters
    # ==========================================
    # ResNet50 expects 224x224
    IMG_HEIGHT = 224
    IMG_WIDTH = 224
    IMG_SIZE = (IMG_HEIGHT, IMG_WIDTH)

    # Batch size for feature extraction
    BATCH_SIZE = 32
    NUM_WORKERS = 2

    # ImageNet Normalization Constants
    IMAGENET_MEAN = [0.485, 0.456, 0.406]
    IMAGENET_STD = [0.229, 0.224, 0.225]

    # ==========================================
    # Feature Engineering Parameters
    # ==========================================
    # Variance to retain in PCA
    PCA_VARIANCE_THRESHOLD = 0.95

    # ==========================================
    # Model Hyperparameters
    # ==========================================
    # Logistic Regression
    # Grid search range for Inverse Regularization Strength (C)
    # Log-spaced values from 0.0001 to 10000
    LOG_REG_C_GRID = np.logspace(-4, 4, 20).tolist()
    LOG_REG_MAX_ITER = 2000
    LOG_REG_SOLVER = "lbfgs"

    # Linear Discriminant Analysis (LDA)
    LDA_SOLVER = "lsqr"
    LDA_SHRINKAGE = "auto"  # Ledoit-Wolf shrinkage

    @classmethod
    def setup(cls):
        """
        Creates the necessary working directories for cache and submission.
        """
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
