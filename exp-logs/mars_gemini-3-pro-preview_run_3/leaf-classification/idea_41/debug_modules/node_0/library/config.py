import os
import random
import numpy as np
import torch


class Config:
    """
    Configuration for Stratified Selective-Topology Orthogonal Manifold-Densified LDA
    with Global Variance Alignment.
    """

    # ==========================================
    # Reproducibility & Global Settings
    # ==========================================
    SEED = 42
    N_FOLDS = 10

    # ==========================================
    # Directories
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    IMAGES_DIR = os.path.join(INPUT_DIR, "images")

    # Working directory for Idea 41
    WORKING_DIR = "./working/idea_41"
    SUBMISSION_DIR = "./submission"
    MODELS_DIR = os.path.join(WORKING_DIR, "models")

    # Metadata Paths (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # ==========================================
    # Feature Extraction (Dual-Stream)
    # ==========================================
    # Global Geometry Stream
    MODEL_DINO = "vit_large_patch14_dinov2"
    # Local Texture Stream
    MODEL_CONVNEXT = "convnext_large"

    IMG_SIZE = 224
    BATCH_SIZE = 32

    # ==========================================
    # Manifold Densification (Orthogonal Views)
    # ==========================================
    # 12 Equidistant Rotations
    ROTATION_ANGLES = [0, 30, 60, 90, 120, 150, 180, 210, 240, 270, 300, 330]

    # Orthogonal Centroids: Mutually exclusive sets of 4 orthogonal views
    # Indices correspond to positions in ROTATION_ANGLES
    CENTROID_INDICES = {
        "A": [0, 3, 6, 9],  # Angles: 0, 90, 180, 270
        "B": [1, 4, 7, 10],  # Angles: 30, 120, 210, 300
        "C": [2, 5, 8, 11],  # Angles: 60, 150, 240, 330
    }

    # ==========================================
    # Pipeline Hyperparameters
    # ==========================================
    # Independent Subspace Reduction
    PCA_VARIANCE = 0.99

    # Classifier (LDA with Ledoit-Wolf Shrinkage)
    LDA_SOLVER = "lsqr"
    LDA_SHRINKAGE = "auto"

    # Tabular Features
    TABULAR_COLS_PREFIXES = ["margin", "shape", "texture"]

    # ==========================================
    # Caching Paths
    # ==========================================
    # Extracted Features (Shape: [N, 12, Feature_Dim])
    CACHE_TRAIN_DINO = os.path.join(WORKING_DIR, "train_dino_12views.npy")
    CACHE_TRAIN_CONVNEXT = os.path.join(WORKING_DIR, "train_convnext_12views.npy")
    CACHE_TEST_DINO = os.path.join(WORKING_DIR, "test_dino_12views.npy")
    CACHE_TEST_CONVNEXT = os.path.join(WORKING_DIR, "test_convnext_12views.npy")

    # Tabular and Metadata Arrays
    CACHE_TRAIN_IDS = os.path.join(WORKING_DIR, "train_ids.npy")
    CACHE_TRAIN_LABELS = os.path.join(WORKING_DIR, "train_labels.npy")
    CACHE_TRAIN_TABULAR = os.path.join(WORKING_DIR, "train_tabular.npy")

    CACHE_TEST_IDS = os.path.join(WORKING_DIR, "test_ids.npy")
    CACHE_TEST_TABULAR = os.path.join(WORKING_DIR, "test_tabular.npy")

    @classmethod
    def setup(cls):
        """
        Initializes the environment:
        1. Creates necessary directories.
        2. Sets random seeds for reproducibility.
        """
        # Create directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        os.makedirs(cls.MODELS_DIR, exist_ok=True)

        # Set seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        os.environ["PYTHONHASHSEED"] = str(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
