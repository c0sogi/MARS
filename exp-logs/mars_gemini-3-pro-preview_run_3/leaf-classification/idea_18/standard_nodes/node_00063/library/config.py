import os
import torch


class Config:
    """
    Configuration class for Hyper-Densified Independent-Component LDA.
    Defines all global constants, paths, and hyperparameters.
    """

    # ==========================================
    # 1. Global & Environment Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for testing
    DEBUG_SAMPLE_SIZE = 50  # Number of samples to use when DEBUG is True

    # Compute resources
    # Use all available CPUs for data loading, or default to 4
    NUM_WORKERS = os.cpu_count() if os.cpu_count() is not None else 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # ==========================================
    # 2. File Paths & Directories
    # ==========================================
    INPUT_DIR = "./input"
    IMAGES_DIR = os.path.join(INPUT_DIR, "images")

    # Metadata generated by the previous step
    METADATA_DIR = "./metadata"
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Submission paths
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Caching Directory for Idea 18 (Hyper-Densification)
    # This is where extracted features and densified arrays will be stored
    WORKING_DIR = "./working/idea_18"
    CACHE_DIR = WORKING_DIR

    # Ensure directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # ==========================================
    # 3. Model Architectures (Dual-Stream)
    # ==========================================
    # Stream 1: Global Geometry (Self-Supervised ViT)
    MODEL_DINO = "facebook/dinov2-large"

    # Stream 2: Local Texture/Margin (Supervised ConvNet)
    MODEL_CONVNEXT = "facebook/convnext-large-224-22k-1k"

    # Image Input Specifications
    IMAGE_SIZE = 224
    BATCH_SIZE = 32  # Batch size for feature extraction inference

    # ==========================================
    # 4. Hyper-Densification Strategy
    # ==========================================
    # Rotation parameters for Multi-View Extraction
    ROTATION_START = 0
    ROTATION_END = 360
    ROTATION_STEP = 10

    # Total number of views per image (36 views: 0, 10, ..., 350)
    NUM_VIEWS = (ROTATION_END - ROTATION_START) // ROTATION_STEP

    # Orthogonal Centroid Logic
    # We average 4 orthogonal views (separated by 90 degrees) to form a centroid
    VIEWS_PER_CENTROID = 4

    # Number of centroids generated per image in the training set
    # 36 views / 4 views per centroid = 9 distinct training samples per original image
    NUM_TRAIN_CENTROIDS = NUM_VIEWS // VIEWS_PER_CENTROID

    # ==========================================
    # 5. Modeling & Pipeline Hyperparameters
    # ==========================================
    # Independent Subspace Reduction
    # Variance threshold for PCA on each visual stream
    PCA_VARIANCE = 0.99

    # Cross-Validation Strategy
    N_FOLDS = 5

    # Data Dimensions
    # 64 margin + 64 shape + 64 texture
    NUM_TABULAR_FEATURES = 192
