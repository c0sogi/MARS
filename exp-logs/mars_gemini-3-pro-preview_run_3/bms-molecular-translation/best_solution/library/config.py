import os
import torch


class Config:
    """
    Configuration class for the Image-to-InChI prediction pipeline.
    Holds all hyperparameters, file paths, and model settings.
    """

    # -------------------------------------------------------------------------
    # General Setup
    # -------------------------------------------------------------------------
    seed = 42
    debug = False  # Set to True to run on a small subset of data
    debug_sample_size = 5000  # Number of samples to use in debug mode
    num_workers = 12  # Utilizing available vCPUs
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # -------------------------------------------------------------------------
    # Data Paths
    # -------------------------------------------------------------------------
    input_root = "./input"

    # Metadata files generated by the analysis script
    train_metadata_path = "./metadata/train_metadata.csv"
    val_metadata_path = "./metadata/val_metadata.csv"
    test_metadata_path = "./metadata/test_metadata.csv"

    # Output directories
    working_dir = "./working/idea_8"
    checkpoint_dir = os.path.join(working_dir, "checkpoints")
    submission_dir = "./submission"
    submission_path = os.path.join(submission_dir, "submission.csv")

    # Cache files
    vocab_path = os.path.join(working_dir, "vocab.json")

    # Ensure necessary directories exist
    os.makedirs(working_dir, exist_ok=True)
    os.makedirs(checkpoint_dir, exist_ok=True)
    os.makedirs(submission_dir, exist_ok=True)

    # -------------------------------------------------------------------------
    # Data Processing
    # -------------------------------------------------------------------------
    image_size = 256
    patch_size = 16
    in_channels = 1  # Grayscale images based on EDA

    # Text / Tokenization
    max_text_length = 400  # Covers >99% of InChI strings based on EDA
    sos_token = "<sos>"
    eos_token = "<eos>"
    pad_token = "<pad>"
    unk_token = "<unk>"

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    # MLP-Mixer Encoder
    # Number of patches = (image_size // patch_size) ** 2 = (256 // 16)^2 = 256
    encoder_dim = 512  # Embedding dimension for patches
    encoder_depth = 8  # Number of Mixer layers
    token_mixing_dim = 256  # Hidden dim for token-mixing MLP
    channel_mixing_dim = 2048  # Hidden dim for channel-mixing MLP

    # GRU Decoder
    decoder_dim = (
        512  # Hidden state dimension (matches encoder_dim for dot-product attention)
    )
    embedding_dim = 512  # Embedding dimension for characters
    decoder_layers = 1
    decoder_dropout = 0.1
    attention_dim = 256  # Dimension for attention projection

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    epochs = 15
    batch_size = 128  # Optimized for A100 40GB
    learning_rate = 1e-4
    weight_decay = 1e-2  # AdamW weight decay
    clip_grad_norm = 1.0  # Gradient clipping value

    # Scheduling
    scheduler_patience = 2
    scheduler_factor = 0.5
    min_lr = 1e-6

    # Early Stopping
    early_stopping_patience = 4

    # Strategy
    teacher_forcing_ratio = 1.0  # Constant teacher forcing for baseline

    # -------------------------------------------------------------------------
    # Inference
    # -------------------------------------------------------------------------
    print_freq = 100  # Frequency of logging during training
