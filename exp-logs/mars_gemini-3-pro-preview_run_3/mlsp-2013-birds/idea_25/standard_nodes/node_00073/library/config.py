import os
import torch


class Config:
    """
    Configuration class for the Bird Species Classification Task.
    Implements the 'Heterogeneous Ensemble with LLRD and Safe-Zone Augmentation' strategy.
    """

    # -------------------------------------------------------------------------
    # Paths & Directories
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Working directory for this specific strategy iteration
    WORKING_DIR = "./working/idea_25"

    # Ensure necessary directories exist
    os.makedirs(WORKING_DIR, exist_ok=True)

    # Input Data Paths
    # Strictly using standard spectrograms as per strategy
    SPECTROGRAM_DIR = os.path.join(INPUT_DIR, "supplemental_data", "spectrograms")

    # Metadata Paths (Generated by previous steps)
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION_PATH = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output Paths
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # Create output directories
    os.makedirs(CHECKPOINT_DIR, exist_ok=True)
    os.makedirs(SUBMISSION_DIR, exist_ok=True)

    # -------------------------------------------------------------------------
    # Data & Preprocessing
    # -------------------------------------------------------------------------
    NUM_CLASSES = 19
    IMG_SIZE = (224, 224)  # Resize to 224x224
    IN_CHANNELS = 3  # Replicated 3 times for RGB backbones

    # Augmentation Constraints ("Safe-Zone")
    SHIFT_LIMIT = 0.1  # Limit time-shift to 10% to prevent signal loss
    ENABLE_MIXUP = True
    MIXUP_ALPHA = 0.4  # Reduced alpha to prevent underfitting
    HORIZONTAL_FLIP = False  # Strictly disabled

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    # Heterogeneous Ensemble Backbones
    MODEL_BACKBONES = ["resnet18", "efficientnet_b0", "densenet121"]

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    N_FOLDS = 5  # Iterative Stratified K-Fold
    BATCH_SIZE = 32  # Physical batch size for stable BN
    EPOCHS = 50  # Upper bound, controlled by Early Stopping
    LEARNING_RATE = 1e-3  # Base Learning Rate
    WEIGHT_DECAY = 1e-2  # High regularization
    PATIENCE = 15  # Aggressive early stopping

    # Layer-Wise Learning Rate Decay (LLRD)
    LLRD_DECAY_RATE = 0.9

    # Optimization
    OPTIMIZER = "AdamW"
    USE_LOOKAHEAD = True  # Wrap optimizer with Lookahead

    # Scheduler
    SCHEDULER = "CosineAnnealingLR"
    MIN_LR = 1e-6

    # -------------------------------------------------------------------------
    # Evaluation & Inference
    # -------------------------------------------------------------------------
    TOP_K_CHECKPOINTS = 3  # Snapshot Ensemble: Average top 3 checkpoints per fold
    TTA_STEPS = 3  # Test Time Augmentation: [Original, Left Shift, Right Shift]

    # -------------------------------------------------------------------------
    # System / Misc
    # -------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

    # Debugging / Development Flags
    DEBUG = False  # Set to True to run on a small subset
    DEBUG_SUBSET_SIZE = 50  # Number of samples to use in debug mode
