import os
import torch


class Config:
    """
    Global configuration for the Bird Species Classification task.
    Implements the 'Optimized Strategy' settings including Heterogeneous Ensemble,
    SAM optimization parameters, and rigid data constraints.
    """

    # -------------------------------------------------------------------------
    # Reproducibility
    # -------------------------------------------------------------------------
    SEED = 42

    # -------------------------------------------------------------------------
    # File Paths
    # -------------------------------------------------------------------------
    # Root directories
    INPUT_ROOT = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files (generated by the metadata script)
    # These contain the splits and labels
    TRAIN_METADATA_PATH = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA_PATH = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA_PATH = os.path.join(METADATA_DIR, "test.csv")

    # Source Data
    # Using provided standard spectrograms (BMP format)
    SPECTROGRAM_DIR = os.path.join(INPUT_ROOT, "supplemental_data", "spectrograms")

    # Output Directories
    WORKING_DIR = "./working/idea_19"
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Data Configuration
    # -------------------------------------------------------------------------
    # Rigid spatial adherence as per strategy
    IMAGE_SIZE = 224

    # 3-Channel Rule: Replicate mono spectrogram to pseudo-RGB
    NUM_CHANNELS = 3

    # Dataset specifics
    NUM_CLASSES = 19

    # -------------------------------------------------------------------------
    # Model Configuration
    # -------------------------------------------------------------------------
    # Heterogeneous Ensemble components
    MODELS = ["resnet18", "efficientnet_b0", "densenet121"]

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    # Optimization
    BATCH_SIZE = 32
    EPOCHS = 75
    LEARNING_RATE = 1e-3
    WEIGHT_DECAY = 1e-2  # High weight decay for regularization

    # Sharpness-Aware Minimization (SAM)
    SAM_RHO = 0.05

    # Cross-Validation
    NUM_FOLDS = 5

    # -------------------------------------------------------------------------
    # Runtime & Debugging
    # -------------------------------------------------------------------------
    # Device configuration
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # Debugging: Set to an integer (e.g., 50) to limit dataset size during development
    # Set to None for full training
    DEBUG_MAX_SAMPLES = None

    @classmethod
    def initialize(cls):
        """
        Sets up the environment by creating necessary directories.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)


# Automatically initialize directories when config is imported
Config.initialize()
