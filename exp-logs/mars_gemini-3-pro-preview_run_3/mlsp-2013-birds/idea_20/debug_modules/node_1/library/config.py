import os


class Config:
    """
    Global configuration for the Bird Species Classification Task.
    Implements the strategy defined in Idea 20: Heterogeneous Ensemble with SAM and Shift-TTA.
    """

    # -------------------------------------------------------------------------
    # Directory and File Paths
    # -------------------------------------------------------------------------
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Source Data
    # Using the provided standard spectrograms (BMP format)
    SPECTROGRAM_DIR = os.path.join(INPUT_DIR, "supplemental_data", "spectrograms")

    # Metadata Files (Generated by the metadata script)
    TRAIN_METADATA = os.path.join(METADATA_DIR, "train.csv")
    VAL_METADATA = os.path.join(METADATA_DIR, "val.csv")
    TEST_METADATA = os.path.join(METADATA_DIR, "test.csv")

    # Working Directory (Idea 20)
    WORKING_DIR = "./working/idea_20"
    CACHE_DIR = os.path.join(WORKING_DIR, "cache")
    CHECKPOINT_DIR = os.path.join(WORKING_DIR, "checkpoints")
    SUBMISSION_DIR = os.path.join(WORKING_DIR, "submission")
    SUBMISSION_FILE = os.path.join(SUBMISSION_DIR, "submission.csv")

    # -------------------------------------------------------------------------
    # Global Configuration
    # -------------------------------------------------------------------------
    SEED = 42
    NUM_WORKERS = 4  # Optimized for 12 vCPUs

    # -------------------------------------------------------------------------
    # Data Parameters
    # -------------------------------------------------------------------------
    IMG_SIZE = 224  # Resize spectrograms to 224x224
    NUM_CHANNELS = 3  # Replicate single-channel spectrogram to 3 channels (RGB)
    NUM_CLASSES = 19  # 19 Bird Species

    # -------------------------------------------------------------------------
    # Training Hyperparameters
    # -------------------------------------------------------------------------
    NUM_FOLDS = 5  # Iterative Stratification
    BATCH_SIZE = 32  # Physical batch size (no gradient accumulation)
    EPOCHS = 50  # Max epochs (relying on Early Stopping)
    PATIENCE = 15  # Aggressive Early Stopping

    # Optimizer & Scheduler
    OPTIMIZER_NAME = "SAM"  # Sharpness-Aware Minimization
    LEARNING_RATE = 1e-3  # Initial Learning Rate
    MIN_LEARNING_RATE = 1e-6  # Minimum Learning Rate for Cosine Annealing
    WEIGHT_DECAY = 1e-2  # High Weight Decay for regularization
    SAM_RHO = 0.05  # Neighborhood size for SAM

    # -------------------------------------------------------------------------
    # Model Architecture
    # -------------------------------------------------------------------------
    # Heterogeneous Ensemble of 3 distinct architectures
    MODEL_ARCHITECTURES = ["resnet18", "efficientnet_b0", "densenet121"]

    # -------------------------------------------------------------------------
    # Augmentation Pipeline
    # -------------------------------------------------------------------------
    # Photometric
    BRIGHTNESS_LIMIT = 0.2
    CONTRAST_LIMIT = 0.2

    # Geometric
    SHIFT_LIMIT = 0.1  # 10% Time-shifting
    USE_HORIZONTAL_FLIP = False  # Strictly Disabled per strategy

    # Regularization
    USE_MIXUP = True
    MIXUP_ALPHA = 0.4

    # -------------------------------------------------------------------------
    # Inference (Test-Time Augmentation)
    # -------------------------------------------------------------------------
    USE_TTA = True
    # TTA Strategy: Original + Left Shift + Right Shift

    @classmethod
    def setup(cls):
        """
        Initialize the working directory structure.
        Must be called at the start of the pipeline.
        """
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.CACHE_DIR, exist_ok=True)
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)
        print(f"Configuration initialized. Working directory: {cls.WORKING_DIR}")
