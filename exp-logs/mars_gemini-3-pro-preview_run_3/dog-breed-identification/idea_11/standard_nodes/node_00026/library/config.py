import os
import torch


class Config:
    """
    Central configuration for the Dog Breed Classification task.
    Implements the Hierarchical Stratified Ensemble strategy (Model Soup + Bagging).
    """

    # ==========================================
    # General Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a subset of data for debugging
    DEBUG_SAMPLE_SIZE = 100  # Number of samples to use if DEBUG is True

    # ==========================================
    # Compute Environment
    # ==========================================
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    # A100 has 40GB VRAM, 12 vCPUs available
    NUM_WORKERS = 4
    PIN_MEMORY = True

    # ==========================================
    # Data Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"

    # Metadata files generated by the provided script
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # Output directory for this specific experiment (Idea 11)
    OUTPUT_DIR = "./working/idea_11"
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    # ==========================================
    # Model Hyperparameters
    # ==========================================
    # ConvNeXt-Small pre-trained on ImageNet-21k and fine-tuned on 1k
    # This architecture provides the capacity sweet spot for this dataset
    MODEL_NAME = "convnext_small.fb_in22k_ft_in1k"

    # Image resolution fixed at 224x224 to allow larger batch sizes and stability
    IMAGE_SIZE = 224
    NUM_CLASSES = 120

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    N_FOLDS = 5
    EPOCHS = 30
    BATCH_SIZE = 64

    # Optimization
    # Two-phase training strategy
    LR_WARMUP = 1e-3  # Learning rate for the head during warm-up (1 epoch)
    LR_FINE_TUNE = 1e-5  # Conservative LR for full backbone fine-tuning
    WEIGHT_DECAY = 1e-4

    # Scheduler
    SCHEDULER_T_MAX = 30  # Cosine Annealing T_max matches total epochs

    # ==========================================
    # Ensemble Strategy (Model Soup)
    # ==========================================
    # We average weights from the final few epochs to flatten loss landscape
    # Indices are 0-based. If EPOCHS=30, indices are 0..29.
    # Averaging last 5 epochs: 25, 26, 27, 28, 29.
    SOUP_EPOCH_START = 25

    # ==========================================
    # Inference
    # ==========================================
    # Test-Time Augmentation: Average predictions of original and horizontally flipped images
    TTA_FLIP = True
