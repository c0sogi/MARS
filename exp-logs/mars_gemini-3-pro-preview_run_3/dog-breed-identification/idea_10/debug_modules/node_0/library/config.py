import os
import torch
import random
import numpy as np


class Config:
    """
    Configuration class for the Dog Breed Classification Task.
    Implements settings for a Fully Converged Homogeneous Stratified Ensemble
    using ConvNeXt-Small.
    """

    # ==========================================
    # General Settings
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a small subset for debugging
    DEBUG_SUBSET_SIZE = 500  # Number of samples to use when DEBUG is True

    # ==========================================
    # Hardware
    # ==========================================
    # Use CUDA if available, otherwise CPU
    DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    # 12 vCPUs available, setting workers accordingly
    NUM_WORKERS = 12

    # ==========================================
    # Directories & Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    # Working directory for the current idea iteration
    WORKING_DIR = "./working/idea_10"

    # Metadata files generated by the provided script
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")

    # Submission output
    SUBMISSION_DIR = "./submission"
    SUBMISSION_PATH = os.path.join(SUBMISSION_DIR, "submission.csv")

    # ==========================================
    # Model Architecture
    # ==========================================
    # ConvNeXt-Small pre-trained on IN-22k and fine-tuned on IN-1k
    # This architecture was identified as the capacity sweet spot.
    MODEL_NAME = "convnext_small.fb_in22k_ft_in1k"
    NUM_CLASSES = 120

    # ==========================================
    # Data Preprocessing
    # ==========================================
    IMG_SIZE = 224  # Fixed resolution to avoid overfitting/instability
    MEAN = [0.485, 0.456, 0.406]  # ImageNet standard
    STD = [0.229, 0.224, 0.225]  # ImageNet standard

    # ==========================================
    # Training Hyperparameters
    # ==========================================
    N_FOLDS = 5
    BATCH_SIZE = 64  # Optimized for A100-40GB

    # Two-Phase Learning Strategy
    WARMUP_EPOCHS = 1  # Freeze backbone, train head
    FINE_TUNE_EPOCHS = 30  # Unfreeze all, train full network

    # Optimization
    LEARNING_RATE = 1e-5  # Conservative LR for fine-tuning
    WEIGHT_DECAY = 1e-4  # Standard for AdamW

    # Scheduler (Cosine Annealing)
    T_MAX = 30  # Matches fine-tune epochs
    MIN_LR = 1e-7

    @classmethod
    def setup(cls):
        """
        Initializes the environment:
        1. Creates necessary directories.
        2. Sets fixed random seeds for reproducibility.
        """
        # Create directories
        os.makedirs(cls.WORKING_DIR, exist_ok=True)
        os.makedirs(cls.SUBMISSION_DIR, exist_ok=True)

        # Set seeds
        random.seed(cls.SEED)
        np.random.seed(cls.SEED)
        torch.manual_seed(cls.SEED)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(cls.SEED)
            torch.cuda.manual_seed_all(cls.SEED)
            # Ensure deterministic behavior
            torch.backends.cudnn.deterministic = True
            torch.backends.cudnn.benchmark = False
