import os
import random
import numpy as np
import torch


class Config:
    """
    Configuration class for the Dog Breed Classification Task.
    Implements the Hierarchical Stratified Ensemble strategy settings.
    """

    # ==========================================
    # General Configuration
    # ==========================================
    SEED = 42
    DEBUG = False  # Set to True to run on a subset of data for debugging
    NUM_WORKERS = 12  # Utilizing all 12 vCPUs

    # ==========================================
    # Directories & Paths
    # ==========================================
    INPUT_DIR = "./input"
    METADATA_DIR = "./metadata"
    OUTPUT_DIR = "./working/idea_15"

    # Metadata Files (Generated by previous steps)
    TRAIN_CSV = os.path.join(METADATA_DIR, "train.csv")
    VAL_CSV = os.path.join(METADATA_DIR, "val.csv")
    TEST_CSV = os.path.join(METADATA_DIR, "test.csv")
    SAMPLE_SUBMISSION = os.path.join(INPUT_DIR, "sample_submission.csv")

    # ==========================================
    # Model Architecture
    # ==========================================
    # Using ConvNeXt-Small initialized with ImageNet-21k weights
    MODEL_NAME = "convnext_small_in22k"
    NUM_CLASSES = 120

    # ==========================================
    # Data Preprocessing
    # ==========================================
    IMG_SIZE = 224  # Fixed resolution to avoid resizing artifacts
    BATCH_SIZE = 64  # Optimized for A100-40GB

    # ==========================================
    # Training Strategy
    # ==========================================
    N_FOLDS = 5

    # Phase 1: Head Warmup (Freeze backbone, high LR)
    EPOCHS_WARMUP = 1
    LR_WARMUP = 1e-3

    # Phase 2: Fine-Tuning (Unfreeze all, conservative LR, Cosine Annealing)
    EPOCHS_FINE_TUNE = 30
    LR_FINE_TUNE = 1e-5
    MIN_LR = 1e-7
    WEIGHT_DECAY = 1e-4

    # ==========================================
    # Ensemble Strategy
    # ==========================================
    # Number of top epochs to average for Manual Soup per fold
    SOUP_TOP_K = 3

    @staticmethod
    def setup(seed=None):
        """
        Initializes the environment by creating directories and setting random seeds.

        Args:
            seed (int, optional): Random seed to enforce. Defaults to Config.SEED.
        """
        if seed is None:
            seed = Config.SEED
        else:
            Config.SEED = seed

        # 1. Create Output Directory
        os.makedirs(Config.OUTPUT_DIR, exist_ok=True)

        # 2. Set Random Seeds for Reproducibility
        random.seed(seed)
        os.environ["PYTHONHASHSEED"] = str(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        torch.cuda.manual_seed(seed)

        # Ensure deterministic behavior
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False

        print(f"Environment Setup Complete.")
        print(f"  - Output Directory: {Config.OUTPUT_DIR}")
        print(f"  - Random Seed: {seed}")
        print(f"  - Device: {'cuda' if torch.cuda.is_available() else 'cpu'}")
